using System;

namespace HealerACR.Common;

/// <summary>
/// **调试窗开关** —— **全进程一份**（AppDomain 数据槽），
/// 而"每次加载都从关开始"由 `独立设置窗.尝试挂载()` **复位一次**保证。
///
/// ══════════════════════════════════════════════════════════════════════
///  [!] 用户的两条要求（都写在原话里，缺一不可）：
///      ① 「把逻辑改成**每次启动加载的时候**调试窗开关改成**默认关**」
///      ② 「调试窗**关不掉**了」  ← 2026-10-03 实测
///
///  [!] 为什么**不能**用普通静态字段（前两版就是这么写的，两次都翻车）：
///      本项目里 `HealerACR.Common.*` 的静态字段是**每个程序集副本各一份** ——
///      重载 ACR / 重启 AE **不会卸载旧程序集**，进程里同时活着好几份。
///      于是"窗口那一份"和"入口那一份"各说各话：
///        · 用户点 X  ⇒ 窗口副本把自己那份写成 false
///        · 入口副本读自己那份 ⇒ 还是 true ⇒ **照旧每帧画** ⇒ 表现为"关不掉"
///      诊断文件里的直接证据（同一次点击前后）：
///          [01:58:54] 画(启用=False) 被调用 屏=2560x1440
///          [01:58:58] 画(启用=True)  被调用 屏=2560x1440
///      两行相隔 4 秒、值相反 —— 不同副本各报自己的值。
///
///  [!] ✅ 所以这里放在 **AppDomain 数据槽**：一个进程只有一格，
///      所有副本读写的是同一个值 ⇒ 点 X 立刻全进程生效，一定关得掉；
///      设置里勾选也一样，所有副本同时看到"开"。
///
///  [!] 那"默认关"怎么办？—— 交给 `独立设置窗.尝试挂载()`：
///      每个副本**加载时复位一次**（且只复位一次）⇒ 每次加载都是关。
///      ⚠️ 千万别改成"每次调用都复位"：`尝试挂载()` 在一份副本里会被调多次
///         （5 个入口的 Build + QT 面板的"设置"按钮），那样用户开着窗口
///         点一下别的东西窗口就自己关了。
///
///  [!] ⚠️ 也别改成落盘文件（0.6.0.0 及更早）：下次启动游戏窗口会自己冒出来。
///      历史与取舍见 `交接文档-调试窗开关问题.md` 的"开关的作用域"一节。
/// ══════════════════════════════════════════════════════════════════════
public static class 调试窗全局开关
{
    /// <summary>AppDomain 数据槽的键（全进程唯一）。</summary>
    private const string 键 = "BlueWhale.AutoHealerACR.调试窗开关";

    /// <summary>
    /// 调试窗是否启用 —— **全进程一份**；每次加载由 `独立设置窗` 复位为 false。
    ///
    /// [!] 读不到（还没人写过）⇒ false（= 关）—— 这正是"默认关"。
    /// </summary>
    public static bool 启用
    {
        get
        {
            try { if (AppDomain.CurrentDomain.GetData(键) is bool 值) return 值; } catch { }
            return false;
        }
        set
        {
            try { AppDomain.CurrentDomain.SetData(键, value); } catch { }
        }
    }
}
