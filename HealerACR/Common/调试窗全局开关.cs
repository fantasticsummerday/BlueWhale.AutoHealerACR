using System;

namespace HealerACR.Common;

/// <summary>
/// **调试窗开关** —— **只活在当前这次加载里**：默认关，不读盘、不落盘。
///
/// ══════════════════════════════════════════════════════════════════
///  [!] 用户要求（2026-10-03 原话）：
///      「把调试窗开关改成**默认关**、**不保存状态**」
///
///  [!] 所以本类现在**没有文件读写**：
///        · 每次 ACR 加载（以及每次完全重启游戏）⇒ 一律是 `false`（关）
///        · 用户在设置里勾上 ⇒ **只对本次会话有效**
///        · 关掉游戏 ⇒ 状态自然消失，下次还是关
///
///  [!] 为什么这样更对（这次改动之前的历史，值得记着）：
///      以前它落盘到 `设置目录\调试窗开关.json`，于是"上次勾了"会被带到下一次
///      ⇒ 用户一启动游戏，调试窗就**自己冒出来**（他反复报过这个现象：
///        「我一加载 ae 他就跳出来了调试窗」）。
///      对一个**排查工具**来说，"每次都要我主动去开"才是对的行为 ——
///      默认出现的调试窗既是打扰，也让人分不清"这是我要的还是要来的"。
///      ⚠️ 那个 json 文件现在已经**没人读也没人写**了（残留文件可以删）。
///
///  [!] 为什么仍然保留成一个类（而不是直接塞个 bool 到别处）：
///        · 读它的地方有几处（设置页 Checkbox / `调试窗.开` / `HealerEntryBase`）
///        · 而且 `HealerACR.Common.*` 的静态字段在本进程里**可能有两份**
///          （`BlueWhale.dll` 编译了 HealerACR 的源码）
///          ⇒ 必须保证**写的人和读的人是同一份**：设置页和调试窗都在
///            BlueWhale.dll 里跑 ⇒ 它们读写的都是这一份（同程序集同一份 static）。
///
///  [!] ⚠️ 别再给它加"落盘"—— 除非用户明确要求能跨会话记住。
///      真要加，也必须先读一遍 `交接文档-调试窗开关问题.md`：
///      "开关关不掉 / 自己冒出来 / 点 X 又回来"这一整条坑都和"状态被记住"有关。
/// ══════════════════════════════════════════════════════════════════
public static class 调试窗全局开关
{
    /// <summary>
    /// 调试窗是否启用 —— **默认 false**（每次加载 ACR 都从"关"开始）。
    ///
    /// [!] 设置页的 Checkbox 直接绑它；勾上就立刻生效（同一份 static）。
    /// [!] 不落盘：进程结束即消失，这是**有意的**（见类注释）。
    /// </summary>
    public static bool 启用 { get; set; }
}
