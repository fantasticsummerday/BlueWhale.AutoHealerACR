using System;

namespace HealerACR.Common;

/// <summary>
/// **调试窗开关** —— 作用域是**这一次游戏进程**：启动时默认关，进程内一直记得。
///
/// ══════════════════════════════════════════════════════════════════
///  [!] 用户要求（2026-10-03，分两次说清，**两条都要满足**）：
///      ① 「每次启动加载的时候把调试窗开关改成默认关」
///         —— 目的：**一加载 AE 不要自己冒出调试窗**（他反复报过这个）
///      ② 「第一遍加载调试窗有内容，切换别的 acr 再切回来、或者重载 AE 就没了」
///         —— 目的：**同一次游戏里，我勾上的状态别自己丢掉**
///
///  [!] 为什么不能用普通静态字段（上一版就是这么翻车的）：
///      `HealerACR.Common.*` 的静态字段**每加载一份程序集副本就重置一次**
///      （切 ACR / 重载 AE 都会产生新副本，而旧副本不会卸载）
///      ⇒ 勾上之后一切 ACR，新副本里的静态又是 false ⇒ **窗口自己没了**。
///
///  [!] 为什么不能用文件（更早那版的问题）：
///      文件会**跨游戏进程**记住 ⇒ 下次启动游戏窗口自己冒出来
///      （就是用户最初报的「我一加载 ae 他就跳出来了调试窗」）。
///
///  [!] ✅ 所以用 **AppDomain 的数据槽**：
///        · 一个进程只有一个 AppDomain ⇒ **所有程序集副本读到的都是同一份**
///        · 进程退出就没了 ⇒ **下次启动游戏一定是"关"**
///      正好是"进程内记得、跨进程不记得"。
///
///  [!] ⚠️ 以后要换存储机制，先用这两条验收，缺一不可：
///        「游戏启动时是关的吗？」→ 必须是
///        「同一次游戏里切 ACR / 重载 AE 之后会丢吗？」→ 必须不丢
///      本项目在这两点上**各翻车过一次**（先落盘太黏、后静态太健忘）。
/// ══════════════════════════════════════════════════════════════════
public static class 调试窗全局开关
{
    /// <summary>AppDomain 数据槽的键（带插件名前缀，避免和别的插件撞）。</summary>
    private const string 键 = "BlueWhale.AutoHealerACR.调试窗开关";

    /// <summary>
    /// AppDomain 不可用时的兜底值 —— 退化成"每次加载都重置"（= 上一版的行为）。
    /// [!] 只是兜底，正常情况下永远读不到它。
    /// </summary>
    private static bool _兜底;

    /// <summary>
    /// 调试窗是否启用。
    ///
    /// [!] **默认 false**：新进程里没有任何数据 ⇒ 游戏启动时一定是关的。
    /// [!] **进程内持久**：切 ACR / 重载 AE 之后，新副本读到的还是你上次勾的值。
    /// [!] **不落盘**：没有文件、不读文件、不写文件（`调试窗开关.json` 已删）。
    /// </summary>
    public static bool 启用
    {
        get
        {
            try
            {
                if (AppDomain.CurrentDomain.GetData(键) is bool 值) return 值;
            }
            catch { }
            return _兜底;
        }
        set
        {
            _兜底 = value;
            try { AppDomain.CurrentDomain.SetData(键, value); } catch { }
        }
    }
}
