using System;

namespace HealerACR.Common;

/// <summary>
/// **调试窗开关** —— **每次加载都从"关"开始**（用户明确要求，反复确认过两次）。
///
/// ══════════════════════════════════════════════════════════════════
///  [!] 用户原话（2026-10-03）：
///      ① 「把逻辑改成**每次启动加载的时候**调试窗开关改成**默认关**」
///      ② 「再次启用 ae，发现并没有按前面我的要求那样**默认关闭**设置和调试窗，
///          进设置看调试窗开关是开启的」
///
///  [!] 所以本类就是**一个普通静态字段**：
///        · 每加载一份程序集副本 ⇒ 重新从 `false` 开始
///          （AE 启动 / 关闭 AE 再启用 / 重载 ACR 都是新的加载）
///        · 用户在设置里勾上 ⇒ 只对**这一份副本**有效
///        · 不落盘、不跨副本、不跨进程
///
///  [!] ⚠️ 别再给它加任何"记住"机制 —— 这里已经翻车过**两次**：
///        · 落盘文件（0.6.0.0 及更早）⇒ 下次启动游戏窗口自己冒出来
///        · AppDomain 数据槽（0.6.0.5）⇒ 用户关了 AE 再开，开关还是开的，
///          而他明确要的是"默认关"
///      真要改，先读 `交接文档-调试窗开关问题.md` 里"开关的作用域"那一节。
///
///  [!] 为什么仍然保留成一个类（而不是直接塞个 bool 到别处）：
///        · 读它的地方有几处（设置页 Checkbox / `调试窗.开` / `HealerEntryBase`）
///        · 而且 `HealerACR.Common.*` 的静态字段在本进程里**可能有两份**
///          （`BlueWhale.dll` 编译了 HealerACR 的源码）
///          ⇒ 必须保证**写的人和读的人是同一份**：设置页和调试窗都在
///            BlueWhale.dll 里跑 ⇒ 它们读写的都是这一份（同程序集同一份 static）。
/// ══════════════════════════════════════════════════════════════════
public static class 调试窗全局开关
{
    /// <summary>
    /// 调试窗是否启用 —— **每次加载都是 false**。
    ///
    /// [!] 设置页的 Checkbox 直接绑它；勾上就立刻生效（同一份 static）。
    /// [!] 不落盘、不跨加载保存：这是**有意的**（见类注释）。
    /// </summary>
    public static bool 启用 { get; set; }
}
