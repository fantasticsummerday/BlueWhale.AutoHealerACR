using AEAssist;
using AEAssist.Helper;
using AEAssist.MemoryApi;
using HealerACR.Timeline;

namespace HealerACR.Common;

/// <summary>
/// **进本识别** —— 判定"刚进了一个副本"，然后通知外部输出识别结果。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么需要它（时序问题）★
///
///  ── 日志实证 ──
///      22:34  离开了休息区
///      22:34  换本 -> 已重置倾向 / 建议队列 / 阈值平滑      ← 这时还在房区
///      22:34  究极神兵破坏作战任务开始                      ← 副本这时才开始
///
///  ── 两个后果 ──
///    ① `换本` 是在 `OnTerritoryChanged` 触发的，那一刻人**刚离开休息区**、
///       还没进本 —— 读到的仍是房区（实测显示成 `区域#979`）。
///    ② `换本` **只清状态、不重新初始化**，所以真正进本之后
///       **不会再有第二次输出** —— 副本名和同步后的等级一直看不到。
///
///  ── 修法 ──
///    每帧看一次"现在在副本里吗"，**状态从"不在"变成"在"** 时通知一次。
///    这时副本信息、等级同步都**已经生效**：
///      · 副本名 → 真名（不是 `区域#...`）
///      · 等级   → `Data.PlayerCurrentLevel` 拿到的**就是同步后的等级**
///        （房区里是 Lv100，进本同步后是 Lv50/60 ——
///         这才是技能可用性的依据，也是要显示的那个数）
///
///  ── 为什么判定在本地层、输出在外面 ──
///    判定只用 `地名`（在 HealerACR 里），不依赖 BlueWhale；
///    输出要 `屏幕提示` + AI 层的日志写法，所以做成回调。
///    没挂回调时（原版 HealerACR）本类只是空转 —— 零副作用。
///
///  ⚠️ 边沿判断（`_上次在副本`）必须有 —— 不然每帧都会输出一条。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 进本识别
{
    /// <summary>
    /// 刚进副本时调用（由外部挂）。
    /// 没挂 = 什么都不做（原版 HealerACR 就是这样）。
    /// </summary>
    public static Action? 进入副本;

    /// <summary>
    /// 上次检查时的地图 ID（边沿判据）。
    ///
    /// ⚠️ 原来这里存的是 `bool _上次在副本` —— 那个判据**会漏**：
    ///     · 副本 A 直接切副本 B（中间没有"不在副本"的状态）→ `true→true` → 漏
    ///     · 优雷卡各岛之间来回（都是副本）→ 同样漏
    ///     · 经过中转地图（房区→中转→副本）时边沿可能配不上 → 漏
    ///     改成盯"地图 ID 变没变"就没有这些缺口了。
    /// </summary>
    private static uint _上次地图;

    /// <summary>本次地图变化是什么时候观察到的（稳定计时起点）</summary>
    private static long _变化时刻;

    /// <summary>这一轮是否已经通知过（防止稳定期内反复通知）</summary>
    private static bool _本轮已通知;

    /// <summary>
    /// 地图要稳定这么久（毫秒）才认为"落地了"。
    ///
    /// ⚠️ 为什么需要它（实测）：
    ///     切地图过程中 `GetCurrTerrId()` 会**先返回旧值**再返回新值 ——
    ///     日志里 `地图变化 1048 -> 979` 报的其实是**上一个地图**（房区），
    ///     那一刻游戏还在黑屏读条，场上没有敌人、没有队友。
    ///     AI 在那种状态下初始化，第一印象就是"空场、单人、无战斗"，
    ///     而它**不会自己纠正** —— 那份报告会一直用到下一次重建。
    ///
    /// ⚠️ 1500ms 的依据：切图黑屏通常 1~3 秒，
    ///     加上下面的 `IsBetweenAreas` 双保险，宁晚勿早。
    /// </summary>
    private const int 稳定毫秒 = 1500;

    /// <summary>
    /// 每帧调用一次 —— **地图 ID 一变就通知**（比原来的"在不在副本"判据更宽）。
    ///
    /// ⚠️ 调用点必须在**每帧都跑**的地方，不能挂在 `OnBattleUpdate`。
    ///
    ///    实测踩的坑：原来挂在 `OnBattleUpdate`，而框架 IL 证明
    ///    `IRotationEventHandler.OnBattleUpdate` 只在 `BattleData.Update` 里被调，
    ///    那条路**只有战斗循环会走**（`AILoop_Normal/PVP/Simulate`）。
    ///
    ///    结果：**进本那一刻是非战斗状态 → 这个方法从不执行** →
    ///      · 时间轴没装 → 开怪时报「本场战斗没有加载时间轴」
    ///      · AI 上下文没重建 → AI 以为还在上一个地图
    ///
    ///    现在它挂在 `SetUpdateAction`（每帧无条件）+ 仍在 `OnBattleUpdate`（战斗内），
    ///    两边都会推它，所以什么状态都盖得住。
    /// </summary>
    public static void 每帧检查()
    {
        try
        {
            var 地图 = TimelineManager.实时副本Id();
            if (地图 == 0) return;               // 读不到 → 不当成"换图"

            // ★ 判据：**地图 ID 变了**（不是"在不在副本"）★
            if (地图 != _上次地图)
            {
                var 旧地图0 = _上次地图;
                _上次地图 = 地图;
                _变化时刻 = TimeHelper.Now();
                _本轮已通知 = false;

                LogHelper.Info($"[HealerACR] 地图变化 {旧地图0} -> {地图}" +
                               $"（等落地稳定 {稳定毫秒}ms 后再重建上下文）");

                // ⚠️ 这里**先不通知** —— 等下面的稳定闸门放行。
                //    切图过程中这一刻的场景是"黑屏 + 空场"，
                //    拿它去初始化 AI 会让第一印象完全错。
                return;
            }

            // ★ 稳定闸门 ★
            if (_本轮已通知) return;
            if (地图 == 0) return;

            // ① 游戏自己说"不在切图状态"
            try
            {
                if (Core.Resolve<MemApiCondition>().IsBetweenAreas()) return;
            }
            catch { }

            // ② 地图 ID 稳定够久
            if (TimeHelper.Now() - _变化时刻 < 稳定毫秒) return;

            _本轮已通知 = true;

            // ★ 进副本 → 标记"本局要重召宠物"（只对副本置位）★
            //
            //  ⚠️ 放在稳定闸门**之后** —— 前面已经排除掉
            //     "还在切图"和"IsBetweenAreas"的情况，这时置位才有效。
            try
            {
                if (地名.是副本(地图)) _本局要重召 = true;
            }
            catch { }
            var 旧地图 = _变化时刻 > 0 ? _上次地图 : 0;

            // 不在副本表里的地图（房区 / 野外）也重建上下文 ——
            // 至少要让它知道"现在在哪"，而不是继续用上一个地图的局面。
            var 是副本 = 地名.是副本(地图);

            // ★ 第一步：**把时间轴装上**（不等开怪）★
            //
            //   ⚠️ 这一步必须在通知之前 —— 通知那条路会重建 AI 上下文，
            //      而上下文里的「副本与机制时间轴」段读的就是 Runner 的状态。
            //      如果时间轴还没装，AI 收到的仍是"没有匹配到时间轴"。
            //
            //   原来 `确保当前时间轴()` 只在战斗中才被调用（`更新` 的第一句
            //   就把非战斗挡掉了），所以开怪前 Runner 永远是空的。
            TimelineManager.现在加载();

            // ★ 第二步：输出"本地看到了什么"（日志兜底，不依赖 AI 层）★
            var 前缀 = $"落地完成 {地图}";

            LogHelper.Info($"[HealerACR] {前缀}：TerritoryType {地图}" +
                           $"（{地名.解析(地图, 是副本: 是副本)}）" +
                           $" | 是副本：{(是副本 ? "是" : "否")}" +
                           $" | 时间轴：{TimelineManager.状态摘要()}");

            // ★ 第三步：通知外层（重建 AI 上下文 + 打横幅）★
            进入副本?.Invoke();
        }
        catch { }
    }

    /// <summary>
    /// **现在是不是在副本里**（给别的模块用）。
    ///
    /// ⚠️ 和 `地名.是副本()` 的分工：
    ///    · `地名.是副本(地图)` —— 问"**这个 id** 是不是副本"，纯查表
    ///    · 本方法             —— 问"**我现在**在不在副本里"，
    ///      自己用已缓存的地图 id，调用方不用重复取
    ///
    /// ⚠️ 用**缓存**的 `_上次地图` 而不是每次重新 `GetCurrTerrId()`：
    ///    切图过程中那个接口会短暂返回旧值，而缓存值已经过稳定窗口过滤。
    ///    而且这个方法会被每帧调用，省一次解析。
    ///
    /// ⚠️ 拿不到地图（`_上次地图 == 0`，比如刚加载还没跑过每帧检查）
    ///    返回 **false** —— 保守方向是"当作不在副本"，
    ///    免得在房区 / 野外误判成副本。
    /// </summary>
    public static bool 在副本里()
    {
        try
        {
            return _上次地图 != 0 && 地名.是副本(_上次地图);
        }
        catch
        {
            return false;
        }
    }

    /// <summary>当前地图 id（0 = 还没读到）</summary>
    public static uint 当前地图 => _上次地图;

    /// <summary>
    /// **本局是否需要重新召唤宠物** —— 进副本时置位，被取走一次就清掉。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  ★ 为什么需要它 ★
    ///
    ///    小仙女是**跟着玩家走**的 —— 从房区进副本它还在，
    ///    所以 `HasPet` 一直是 true，"不在场才召"这个判据**永远不会触发**。
    ///
    ///    但用户要的是"**每次进本都重新召一次**"。两个理由：
    ///      · 进本后宠物位置/状态可能不对（还停在传送前的位置）
    ///      · 视觉上确认"这只小仙女是这一局的"（心里有底）
    ///
    ///  ⚠️ 用**取走即清**（`取走 = true` 只返回一次 true）而不是一直返回 true：
    ///     否则每一帧都会重召，把 GCD 全浪费在召唤上。
    ///
    ///  ⚠️ 时机：在地图**落地稳定之后**才置位（`每帧检查` 的稳定闸门之后），
    ///     不是地图 id 一变就置 —— 切图过程中置的话，
    ///     召唤会在黑屏里被尝试，白白浪费一次。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static bool _本局要重召;

    /// <summary>
    /// **只看**有没有"本局要重召"标记（不移除）。
    ///
    /// ⚠️ 为什么要有"只读"版本：
    ///     调用方（`Res_SummonPet.Check`）在标记之后还有一串校验
    ///     （移动中、CD、转化中…），任何一条不过都会返回负值。
    ///     如果在那里就把标记**取走**了，标记会被白白丢掉 ——
    ///     而 `Check` 每帧会被调很多次，丢掉就等于**本局再也不重召**。
    ///
    ///     ⇒ 所以 `Check` 用这个只读版本判，真正取走放到 `Build`
    ///       （那时技能确实要放出去了）。
    /// </summary>
    public static bool 有重召标记 => _本局要重召;

    /// <summary>取走"本局要重召"标记（只会返回一次 true）</summary>
    public static bool 取走重召标记()
    {
        if (!_本局要重召) return false;
        _本局要重召 = false;
        return true;
    }

    /// <summary>重置边沿状态（换职业 / 重载时用）</summary>
    public static void 重置()
    {
        _上次地图 = 0;
        _变化时刻 = 0;
        _本轮已通知 = false;
        _本局要重召 = false;
    }
}
