using System;

namespace HealerACR.Common;

/// <summary>
/// **调试窗的"请求"数据** —— 入口侧写、窗口侧读的**唯一通道**。
///
/// ══════════════════════════════════════════════════════════════════════════
///  [!] 为什么要有这个类（2026-10-06 的架构级修法，替换掉"反射 + 委托缓存"）
///
///      旧架构：入口侧反射找 `BlueWhale.AutoHealerACR.调试窗.画(bool,bool)`，
///              **把委托缓存进静态字段**，每帧调用它。
///
///      真因：缓存的那个委托**指向"上一次加载的程序集"里的那个类型** ——
///            ACR 重载时旧程序集不会被卸载，而 `GetAssemblies()` 的顺序
///            不保证第一个带这个名字的类型就是"当前这一份"。
///            旧类型的方法体不再执行 ⇒ 委托照常**返回**、**零效果、零报错**。
///            实测：入口侧记了 6807 次"即将调用"，窗口侧**一行诊断都没有**，
///            而且 catch 里一条"调用抛异常"都没有。
///
///  [!] ✅ 所以改成：**跨程序集只传"纯数据"** ——
///        · 入口侧（`HealerEntryBase.发布调试窗请求()`）写本类的两个 bool；
///        · 窗口侧（`BlueWhale.AutoHealerACR.调试窗驱动.每帧画()`）读本类，
///          然后**在同一个程序集内部直接调** `调试窗.画(启用, ACR在用)`。
///      ==> 没有任何 `Type` / `MethodInfo` / `Delegate` 跨程序集流动，
///          也就不存在"指向旧程序集"这件事。
///
///  [!] ⚠️ 关键前提（本类成立的原因，**不要想当然**）：
///        部署目录 `D:\FF14\ACR\BlueWhale\` 里**只有 BlueWhale.dll**
///        （`HealerACR.dll` 从来没部署过 —— 见 `BlueWhale.AutoHealerACR.csproj`
///          里那段"两份静态状态呢？"的注释，那段结论是实测过的）。
///        而 BlueWhale.dll **编译了 HealerACR 的源码**
///        ⇒ 本类（入口侧）与 `调试窗驱动`（窗口侧）**在同一个程序集里**
///        ⇒ 两边读写的 `调试窗请求` 是**同一份 static**。
///
///        ⇒ 所以：**本类的字段只允许在同一程序集内部读写**
///          （入口侧写、窗口侧读，或窗口侧写、设置页读）。
///          绝对不要用它承载"两个程序集要共享"的状态 ——
///          如果哪天 HealerACR.dll 真被部署了，那才会有两份。
///
///  [!] 为什么诊断计数也放在这里（而不是各自留一份）：
///        设置页自检那一行要同时显示"入口侧发了多少次请求 / 窗口侧接了多少次
///        / 真正画了多少次"。如果这三个数来自不同的 static 副本，
///        就会出现本次事故里那种**自相矛盾的数字**
///        （`调用=6807` 而 `入绘制=1` —— 逻辑上不可能）。
///        ==> 放进同一份数据里，三个数**必然自洽**。
/// ══════════════════════════════════════════════════════════════════════════
/// </summary>
public static class 调试窗请求
{
    // ══════════════════════════════════════════════════════════════════════
    //  ① 请求本体（入口侧写，窗口侧读）
    // ══════════════════════════════════════════════════════════════════════

    /// <summary>
    /// **用户在设置里勾的开关** —— 入口侧读好写在这里（与设置页 Checkbox 同一份）。
    ///
    /// [!] 窗口侧**不要**自己去读 `调试窗全局开关.启用`：那样一旦有两份状态，
    ///     就会出现"勾选框改了没用 / 窗口提前出现"这类现象
    ///     （用户实测踩过：「这个开关关不掉」）。
    /// </summary>
    public static bool 启用;

    /// <summary>
    /// **"我们这套 ACR 正在被框架使用"** —— 入口侧判好（`我们在被使用()`）写在这里。
    ///
    /// [!] 语义见 `调试窗.画(bool,bool)` 的 `<param name="ACR在用">`：
    ///     它只负责"**自动**显示/隐藏"，**不否决**用户开关。
    /// </summary>
    public static bool ACR在用;

    // ══════════════════════════════════════════════════════════════════════
    //  ② 诊断（同侧读写，设置页自检直接读，不走反射）
    // ══════════════════════════════════════════════════════════════════════

    /// <summary>入口侧发布了多少次请求。</summary>
    public static int 请求次数;

    /// <summary>最后一次发布请求的时刻（`Environment.TickCount64`）。</summary>
    public static long 最后请求毫秒;

    /// <summary>窗口侧驱动被调了多少次（≈ 这个窗口被请求画了多少帧）。</summary>
    public static int 驱动次数;

    /// <summary>最后一次驱动调用的时刻。</summary>
    public static long 最后驱动毫秒;

    /// <summary>窗口侧 `绘制()` 真正进去了多少次（由窗口侧自己写）。</summary>
    public static int 入绘制次数;

    /// <summary>窗口侧连续失败了几次（由驱动写；成功一次即清零）。</summary>
    public static int 连续失败次数;

    /// <summary>窗口侧是否处于"连续失败后的冷却"中（由驱动写）。</summary>
    public static bool 冷却中;

    // ══════════════════════════════════════════════════════════════════════
    //  ③ 写法（都只碰本类字段，不做任何跨程序集动作）
    // ══════════════════════════════════════════════════════════════════════

    /// <summary>
    /// **发布一次请求**（入口侧每帧调）。
    /// </summary>
    /// <returns>
    /// **两个值里有没有变化** —— 调用方据此决定要不要写诊断。
    /// （每帧都写盘是禁止的：高频路径不能做文件 I/O，见工程约定 ★5。）
    /// </returns>
    public static bool 写(bool 启用, bool ACR在用)
    {
        var 变了 = 调试窗请求.启用 != 启用 || 调试窗请求.ACR在用 != ACR在用;
        调试窗请求.启用 = 启用;
        调试窗请求.ACR在用 = ACR在用;

        请求次数++;
        try { 最后请求毫秒 = Environment.TickCount64; } catch { }

        return 变了;
    }

    /// <summary>记一次驱动调用（窗口侧每帧调）。</summary>
    public static void 记驱动()
    {
        驱动次数++;
        try { 最后驱动毫秒 = Environment.TickCount64; } catch { }
    }

    /// <summary>记一次"真的进了 `绘制()`"（窗口侧调）。</summary>
    public static void 记入绘制()
    {
        入绘制次数++;
    }

    /// <summary>记一次失败（窗口侧驱动在 catch 里调）。</summary>
    public static void 记失败(int 连续次数, bool 冷却)
    {
        连续失败次数 = 连续次数;
        冷却中 = 冷却;
    }

    /// <summary>
    /// **复位诊断计数** —— 用户在设置里**重新勾上开关**时调。
    ///
    /// [!] 为什么需要：连续失败会进 30 秒冷却，而"重新勾选复选框"是用户
    ///     最自然的"我再来一次"操作，不该让他等 30 秒。
    /// </summary>
    public static void 复位诊断()
    {
        连续失败次数 = 0;
        冷却中 = false;
    }
}
