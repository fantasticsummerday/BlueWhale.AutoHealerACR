    /// <summary>已经报过"找不到"的名字，避免每帧刷屏</summary>
    private static readonly HashSet<string> 已报告 = new(StringComparer.Ordinal);

    /// <summary>
    /// 取技能 ID。参数是"中文名"（对照游戏客户端）。
    /// 第二位参数保留兼容，现在不用了。
    /// </summary>
    public static uint 取(string 中文名, string _ = "")
    {
        if (表.TryGetValue(中文名, out var id) && id != 0) return id;

        // 设置里手工补的（内置表没有的技能）
        try
        {
            if (HealSettings.Instance.技能Id覆盖.TryGetValue(中文名, out var 手工) && 手工 != 0)
            {
                return 手工;
            }
        }
        catch
        {
        }

        // 只报一次：这个函数每帧都会被调用，报多了日志直接刷爆
        if (已报告.Add(中文名))
        {
            LogHelper.Error($"[HealerACR] 不在内置技能表里：{中文名}" +
                            "（用 SeeSpell 查到 ID 后填进设置里的「技能Id覆盖」）");
        }

        return 0;
    }

    /// <summary>内置表里有没有这个技能（不报错）</summary>
    public static bool 有(string 中文名) => 表.ContainsKey(中文名);

    /// <summary>
    /// **内置表里的全部技能名** —— 给"AI 幻觉校验"用。
    ///
    /// [!] 为什么要它：要判断"AI 回复里提到的中文词是不是技能名"，
    ///     就得有"全部技能名"这个集合做白名单。
    ///     否则"治疗""坦克""输出"这些词全会被当成技能名误报。
    ///
    /// [!] 返回的是**副本** —— 调用方可能排序/遍历，不能让它改到内部表。
    /// </summary>
    public static IReadOnlyList<string> 全部技能名()
    {
        try
        {
            return 表.Keys.ToArray();
        }
        catch
        {
            return Array.Empty<string>();
        }
    }

    /// <summary>
    /// 反查：ID → 中文名。给 AI 描述"这个技能 ID 是什么"用。
    /// 找不到返回空字符串（AI 那边就会把它当无效 ID）。
    /// </summary>
    public static string 反查(uint id)
    {
        if (id == 0) return "";

        try
        {
            if (_反向 == null)
            {
                _反向 = new Dictionary<uint, string>();
                foreach (var kv in 表)
                {
                    if (!_反向.ContainsKey(kv.Value)) _反向[kv.Value] = kv.Key;
                }
            }

            return _反向.TryGetValue(id, out var 名) ? 名 : "";
        }
        catch
        {
            return "";
        }
    }

    private static Dictionary<uint, string>? _反向;
