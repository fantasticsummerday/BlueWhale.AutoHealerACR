    /// <summary>查这个技能的 MP 消耗。**查不到返回 0**（0 的语义是"不知道"，不是"不耗蓝"）。</summary>
    public static int 取(uint 技能Id)
    {
        if (技能Id == 0) return 0;
        return _表.TryGetValue(技能Id, out var mp) ? mp : 0;
    }

    // ══════════════════════════════════════════════════════════════════
    //  ★ **按技能分档的 MP 门** ★
    //
    //  [!] 参考实现**没有全局停手线**，只有"每个技能各自的 MP 门"：
    //        闪灼 / 再生        400
    //        医治 / 愈疗        700
    //        医养                800
    //        **走位即刻重力**   1000   ← 比它自己的 400 成本高得多
    //        失衡 / 群盾 / 单盾 / 预后  1000
    //        救疗               1400
    //
    //  [!] 注意两个"门"和"成本"不是一回事：
    //      走位即刻重力本身只要 400 蓝，但它是**一次性瞬发资源**换来的输出，
    //      参考要求手里有 1000 蓝才肯用它 ——
    //      因为这一发之后还得留蓝治疗。
    //
    //  [!] 本表**只登记与成本不同的那几档**（成本相同的没必要列），
    //      查不到就退回 `取()` 的成本值。
    // ══════════════════════════════════════════════════════════════════
    private static readonly Dictionary<uint, int> _门 = new()
    {
        [3615] = 1000,    // 重力（走位即刻那一发）
        [25872] = 1000,   // 中重力（走位即刻那一发）
    };

    /// <summary>
    /// 放这个技能**至少要留多少蓝**。
    ///
    /// [!] 有分档门就用门，没有就用它自己的 MP 成本；
    ///     两样都查不到返回 0（= 不管）。
    /// </summary>
    public static int 门(uint 技能Id)
    {
        if (技能Id == 0) return 0;
        if (_门.TryGetValue(技能Id, out var g)) return g;
        return 取(技能Id);
    }

    /// <summary>现在够不够放这个技能（按分档门判）</summary>
    public static bool 蓝够(uint 技能Id)
    {
        var g = 门(技能Id);
        if (g <= 0) return true;   // 不知道要多少 ⇒ 放行（保守方向取"别卡住输出"）

        try { return 蓝量.当前蓝量 >= (uint)g; }
        catch { return true; }
    }

    /// <summary>表里有几条（诊断用）</summary>
    public static int 条数 => _表.Count;
}
