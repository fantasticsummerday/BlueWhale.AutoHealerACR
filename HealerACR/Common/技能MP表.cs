namespace HealerACR.Common;

/// <summary>
/// **填充技 MP 消耗表**（技能Id -> MP）。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么需要它（用户实测）★
///
///    "本地一直在打破阵法，ai建议毁灭 这是对的，因为毁灭少用100蓝"
///
///    `选填充技()` 原来按**纯威力**排序：
///        破阵法 150 × 命中数  vs  毁灭 150
///    ⇒ 单目标时两者**威力持平**，而破阵法是**瞬发**的 ⇒ 必然被选中。
///      但 **毁灭只要 300 蓝、破阵法要 400** —— 白花 100 蓝。
///
///  [!] 用户规则（已实现为字典序比较，见 `Res_Damage.选填充技`）：
///      输出：GCD 内最高输出优先，**相同**的情况下选蓝耗少的
///      治疗：优先能力技，然后 GCD 治疗量优先，其次蓝量
///
///  ★ 数据来源 ★
///
///    **huijiwiki**（`X/职业技能` 页面渲染后的 HTML）：
///        `技能:<ID> <名> <等级>级 魔力：<MP>`
///
///    [!] `Action` 表**查不到玩家技能的 MP** ——
///        全表导出 45490 条，只有 11 行有消耗值，而且全是 Boss 技能。
///        所以只能从 wiki 取。
///    [!] wikitext 里也没有（是小部件渲染的）——
///        必须用 `action=parse&prop=text` 取渲染后的 HTML。
///
///    [!] 抓取脚本：`tools/JobSkillMP/抓技能MP.py`
///        输出 `build/job_skill_mp.tsv`，本文件由它生成。
///        **游戏版本更新后重跑即可**，不用手改。
///
///  [!] 为什么用**共享表**而不是各职业各写一份：
///      MP 是按**技能 ID** 定的，与职业无关；
///      四个职业各写一份会让数据慢慢分叉（本项目栽过）。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 技能MP表
{
