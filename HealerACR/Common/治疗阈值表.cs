    /// <summary>
    /// **缓存**：上一次算出来的摘要 + 它的输入。
    ///
    /// ⚠️ 为什么要缓存：本方法**每帧**会被 `AiSituation` 调一次
    ///    （局面报告每个决策周期重建），而它内部要遍历 44 条 + 分组 + 拼字符串。
    ///    输入（两个大类阈值 + 表内容）不变时结果必然一样 ==> 缓存掉。
    ///
    /// ⚠️ 缓存键**包含表内容本身**（用一个版本号）—— 否则运行时加了新条目不会刷新。
    /// </summary>
    private static string _摘要缓存 = "";
    private static float _摘要缓存群 = float.NaN;
    private static float _摘要缓存单 = float.NaN;
    private static int _摘要缓存版本 = -1;
    private static int _表版本;

    /// <summary>表内容变过几次（`设()` 每次 ++，用来给缓存失效）。</summary>
    private static void 版本前进() { unchecked { _表版本++; } }

    /// <summary>
    /// **给 AI 看的一行摘要**：本职业里哪些技能的阈值**和大类阈值不同**，
    /// 按数值分组（同值的合并）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么按数值分组、而不是逐个列：
    ///      提示词预算很紧（本项目 `PromptBudget` 会算），
    ///      而 AI 需要的是"**哪几个和默认不一样**"，不是 44 个数。
    ///      实测：本方法输出 **学者/白魔 78 字符、占星 64、贤者 51**
    ///      （逐个列要 300+）。**改这里的措辞要重新量一遍长度**。
    ///
    ///  [!] 为什么只列"和传入的大类阈值不同"的：
    ///      大部分技能的独立值**就是**它所属大类的值（或者没登记 -> 回落），
    ///      列出来是纯噪声、还占预算。只列**有独立值**的才有信息量。
    ///
    ///  [!] 传入两个大类阈值是为了过滤 —— 由调用方传"本地生效值"即可
    ///      （±0.10 的 AI 偏移不影响"要不要显示"这个判断）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static string 本职业阈值摘要(float 群疗阈值, float 单疗阈值)
    {
        try
        {
            // ── 缓存命中 ──
            if (_摘要缓存版本 == _表版本
                && _摘要缓存群 == 群疗阈值
                && _摘要缓存单 == 单疗阈值)
                return _摘要缓存;

            var 结果 = 算摘要(群疗阈值, 单疗阈值);

            _摘要缓存版本 = _表版本;
            _摘要缓存群 = 群疗阈值;
            _摘要缓存单 = 单疗阈值;
            _摘要缓存 = 结果;
            return 结果;
        }
        catch { return ""; }
    }

    private static string 算摘要(float 群疗阈值, float 单疗阈值)
    {
        try
        {
            if (_表.Count == 0) return "";

            // 按"数值"分组：同值的技能名合并
            var 分组 = new SortedDictionary<int, List<string>>();
            foreach (var kv in _表)
            {
                var 值 = kv.Value;
                // 与大类阈值相同的跳过（信息量为 0）
                if (MathF.Abs(值 - 群疗阈值) < 0.005f) continue;
                if (MathF.Abs(值 - 单疗阈值) < 0.005f) continue;

                var 百分 = (int)MathF.Round(值 * 100f);
                if (!分组.TryGetValue(百分, out var 列表))
                {
                    列表 = new List<string>();
                    分组[百分] = 列表;
                }
                列表.Add(名字(kv.Key));
            }

            if (分组.Count == 0) return "";

            var sb = new System.Text.StringBuilder();
            foreach (var kv in 分组)
            {
                if (sb.Length > 0) sb.Append("｜");
                // 一行里名字不超过 5 个，多了用 +N
                var 名s = kv.Value;
                sb.Append(string.Join("/", 名s.Take(5)));
                if (名s.Count > 5) sb.Append($"+{名s.Count - 5}");
                sb.Append(' ').Append(kv.Key).Append('%');
            }

            // ⚠️ 硬上限：提示词预算有限，超了就截断（宁可少给，不能让整段被挤掉）。
            //    实测正常值 51~78 字符，这个上限是**保险丝**，正常不会碰到。
            var s = sb.ToString();
            return s.Length <= 200 ? s : s[..200] + "…";
        }
        catch { return ""; }
    }

