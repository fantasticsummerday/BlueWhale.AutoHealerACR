using System.Collections.Generic;
using System.Linq;   // `本职业阈值摘要` 里的 `Take` 要用

namespace HealerACR.Common;

/// <summary>
/// **治疗阈值表** —— 参考实现的阈值是**每个技能一个**，而我们原来只有"一个大阈值"。
///
/// ══════════════════════════════════════════════════════════════════════
///  ★ **结构现状**：本表是「可选覆盖」，不是「唯一来源」 ★
///
///  [!] 调用方一律写成 `治疗阈值表.取(技能id, 大类阈值)` —— 两层：
///        ① **表里有这个技能** -> 用表里的（并叠加 AI 的三种偏移）
///        ② **表里没有**       -> 用调用方传进来的大类阈值（`HealSettings.单体治疗阈值` 等）
///      ==> 所以"某个技能还没登记"**不会改变行为**，只是它还在吃大类阈值。
///
///  [!] 这意味着**迁移是渐进的、可以停在任何一步**：
///      登记一个技能 = 它从"跟大类走"变成"有自己的值 + 能单独被 AI 调"。
///      没登记的不受影响 —— 这是刻意的（见开发约定：不要一次改一半还留着旧的入口）。
///
///  [!] **当前登记了哪些（44 条）** 见下面各 `载入Xxx()`；
///      `_按类别` 决定每条吃哪个类别偏移；`_名字` 给它一个显示名（AI 要用）。
///
///  ⚠️ **加一条时要同时想三件事**（漏一件就会静默出问题）：
///        ① `设(...)` 登记数值        —— 否则查不到，回落大类（**不影响行为，但白写**）
///        ② `_按类别` 给类别          —— 否则只吃通用偏移，**AI 按类别调它不生效**
///        ③ `_名字` 给显示名          —— 否则 AI **说不出这个名字**（`技能:xxx` 会被丢弃）
///      自检：`verify_categories.py` 会报"登记了但没归类"的；名字缺失只有 AI 会感觉到。
///
///  [!] 已核对的对照关系（不要把"没登记"误当成"漏了"）：
///        · `Res_HealAoEGcd`（GCD 群疗）**按槽位技能查表**，不是按最终选中的技能 ——
///          因为它是"先数人再挑技能"，数人时还不知道会挑中哪个（结构约束，见该方法注释）
///        · `Res_HealShield`（单盾）用 `_t.单体盾` 当 key
///        · `Res_GroupShield`（群盾）用 `_t.群体盾` 当 key
///        · 几个"减伤"类（野战治疗阵 / 中间学派 / 太阳星座）走的是**读条判据**，
///          血线只在少数分支用 —— 它们登记的值用于那些分支
/// ══════════════════════════════════════════════════════════════════════
/// ══════════════════════════════════════════════════════════════════════
///  [!] 为什么需要它（复刻的核心差异，IL 实证）
///
///      我们原来的结构：
///        `HealSettings.单体治疗阈值`（0.52）—— 所有单奶共用一个
///        `HealSettings.群体治疗阈值`（0.62）—— 所有群奶共用一个
///        `JobSpellTable.瞬发单奶血线`  —— 职业级一个裸 const
///
///      参考实现（两套都是）：
///        **每个技能一个独立阈值**。以学者为例（IL 实证）：
///          shiyuvi：Adloquium 0.4 / Lustrate 0.45 / Indomitability 0.7 /
///                   WhisperingDawn 0.7 / FeyBlessing 0.6 / Succor 0.65 /
///                   SummonSeraph 0.55 / Seraphism 0.4 / EmergencyTactics 0.35 /
///                   GCDShield 0.8 / GCDAOEHeal 0.5 / Aetherpact 0.6
///          youshu ：单盾 45 / 群盾 55 / 绿帽 60 / 活性法 45 / 回生法 35 /
///                   低语 70 / 不屈 70 / 祥光 70 / 慰藉 55 / 变身 40 /
///                   野战治疗阵 35 / 应急战术 35 / GCD群奶 50 / GCD单奶 45
///
///  [!] 为什么不能继续"一个大阈值 + 例外"
///      参考实现的差异是**结构性的**，不是"调一下数"：
///        · 同一个技能在两套实现里差 5~15 个点（不屈 70 vs 65）
///        · 组内差异很大（单盾 0.4 而罩子 0.35、GCD群盾 0.8）
///        · 一个大阈值下**没法表达"这个技能宁可早点交、那个宁可晚点"**
///      ==> 复刻这一层，就必须有"每技能一个数"的落点。
///
///  [!] 不硬编码在 resolver 里，而是集中成表 —— 三个理由：
///      ① 参考实现的这些数**在设置里可调**（有 UI 滑条），我们也该可调
///      ② AI 的"阈值调参"要能逐个改（用户明确要的特色）
///      ③ 一处能看全 → 对照参考实现时不用满仓库找
///
///  [!] 缺省行为：**表里没有该技能 → 回落到原来的统一阈值**。
///      这样逐职业铺开时，没改到的技能行为不变（可以一个一个来）。
/// ══════════════════════════════════════════════════════════════════════
/// </summary>
public static class 治疗阈值表
{
    /// <summary>
    /// 每个技能自己的血线。key = 技能 id。
    ///
    /// ⚠️ 数值来源**逐个标注**在该技能的注释里（IL 行号或"两套实现的取值"）。
    ///    没标注来源的数**不许进来** —— 这是本项目的铁律（数值必须有依据）。
    /// </summary>
    private static readonly Dictionary<uint, float> _表 = new();

    /// <summary>
    /// **每个技能属于哪个大类** —— 决定它吃 AI 的哪一个偏移。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要分类（而不是给 AI 加 44 个参数）★
    ///
    ///  [!] 问题：AI 原来只有 8 个大类参数（`单体治疗阈值` / `群体治疗阈值` /
    ///      `紧急单奶阈值` / `预铺血线` / `妖精契约血线` / `大招血线` /
    ///      两个保留数）。而本表有 44 条**每技能**阈值。
    ///      ==> 一旦某技能在表里有值，调用方就不读大类阈值了，
    ///          **AI 的偏移对它失效**。
    ///
    ///  [!] 两条路：
    ///        ① 给每个技能各加一个 AI 参数 ==> 提示词里多 44 行，
    ///           而 AI 本来也管不过来（它一次只该调几个数）
    ///        ② **按大类桥接**：给每条标一个类别，类别对应一个已有的 AI 参数
    ///      ==> 选 ②。理由：这 44 条**本来就分属那几个大类**
    ///          （低语/祥光/不屈/慰藉 = 群疗；活性法/绿帽/回生法 = 单疗；
    ///            炽天附体/炽天召唤 = 大招），
    ///          所以"AI 调群体治疗阈值时，群疗类技能一起动"**正是它期望的语义**。
    ///      ==> 提示词**一个字都不用加**，AI 的能力却从 8 个数变成 44 个数的覆盖。
    ///
    ///  [!] 没登记的条目按 `其他` 处理（只吃通用偏移）——
    ///      这样"新加一条忘了标类别"不会静默失效，只是少一层桥接。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public enum 类别
    {
        /// <summary>没有特化（只吃通用偏移）</summary>
        其他 = 0,
        /// <summary>单体治疗 —— 吃「单体治疗阈值」的偏移</summary>
        单疗,
        /// <summary>群体治疗 —— 吃「群体治疗阈值」的偏移</summary>
        群疗,
        /// <summary>大招 / 长 CD 群疗 —— 吃「大招血线」的偏移</summary>
        大招,
        /// <summary>预铺 / 盾 —— 吃「预铺血线」的偏移</summary>
        预铺,
    }

    /// <summary>技能 id -> 类别</summary>
    private static readonly Dictionary<uint, 类别> _类别 = new();

    /// <summary>
    /// **各大类的 AI 偏移** —— 由 `BlueWhale` 侧每帧写入。
    ///
    /// key = 类别名（和 `Ai策略参数` 的参数名一致），value = 偏移量。
    /// 单装 `HealerACR` 时字典为空 ⇒ 偏移恒为 0 ⇒ 行为 = 本地基线。
    /// </summary>
    private static readonly Dictionary<类别, float> _类别偏移 = new();

    /// <summary>
    /// 静态构造 —— **保证表一定被载入**。
    /// （不依赖任何调用方记得先调 `载入默认()`；"必须记得初始化"的设计在本项目踩过坑。）
    /// </summary>
    static 治疗阈值表() { try { 载入默认(); } catch { } }

    /// <summary>表里的条目数（诊断用）</summary>
    public static int 条目数 { get { try { return _表.Count; } catch { return 0; } } }

    /// <summary>
    /// 查这个技能自己的血线。
    /// **查不到返回 -1**（调用方据此回落到统一阈值）——
    /// 不用 0 当"没有"，因为 0 是合法血线（"永不因血线触发"）。
    /// </summary>
    public static float 查(uint 技能Id)
    {
        if (技能Id == 0) return -1f;
        try { return _表.TryGetValue(技能Id, out var v) ? v : -1f; }
        catch { return -1f; }
    }

    /// <summary>
    /// 取"这个技能该用的血线"：表里有就用表里的，没有就用传入的统一阈值。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ **AI 的偏移在这里生效**（这是"保留 AI 调参特色"的关键接缝）★
    ///
    ///  [!] 为什么必须有这一段：
    ///      AI 原来只能调 `单体治疗阈值` / `群体治疗阈值` 这**几个大类**。
    ///      而参考实现的阈值是**每技能一个**，所以本表登记了 44 条。
    ///      ==>
    ///      一旦某个技能在本表里有值，**调用方就不再读那些大类阈值了**
    ///      ==> `AiThresholdAdapter` 的偏移**对它失效** ——
    ///          AI 说"这轮保守一点"，这个技能却纹丝不动。
    ///
    ///  [!] 所以：**表里的值也要过一遍 AI 的偏移**。
    ///      传 `AI偏移` 进来（由调用方从 `AiThresholdAdapter` 拿），
    ///      没传就按 0 算（单装 HealerACR 时 AI 层不存在，行为不变）。
    ///
    ///  [!] 为什么偏移**不缓存**：
    ///      `AiThresholdAdapter` 自己做了平滑（`平滑速率 0.7`），
    ///      每次调用拿到的是当前值 —— 缓存反而会让平滑失效。
    ///
    ///  [!] 上下界：夹在 `[0.05, 0.99]` ——
    ///        下界 0.05：不能因为偏移把阈值压到 0（那等于"永不触发"）
    ///        上界 0.99：不能压过 1.0（那等于"永远触发"）
    /// ══════════════════════════════════════════════════════════════════
    ///
    /// 调用方写法：
    ///     var 血线 = 治疗阈值表.取(技能id, HealSettings.Instance.单体治疗阈值);
    /// </summary>
    public static float 取(uint 技能Id, float 统一阈值)
    {
        var v = 查(技能Id);
        var 基 = v >= 0f ? v : 统一阈值;
        return 夹(基 + AI偏移 + 类别偏移(技能Id) + 取单技能偏移(技能Id));
    }

    /// <summary>
    /// 这个技能所属类别对应的 AI 偏移（没登记类别/没设偏移 -> 0）。
    /// </summary>
    private static float 类别偏移(uint 技能Id)
    {
        try
        {
            if (_类别偏移.Count == 0) return 0f;
            if (!_类别.TryGetValue(技能Id, out var 类)) return 0f;
            return _类别偏移.TryGetValue(类, out var v) ? v : 0f;
        }
        catch { return 0f; }
    }

    /// <summary>
    /// **大类偏移** —— 由 `BlueWhale` 侧每帧写入（本地不反向依赖 AI）。
    ///
    /// 传 0 或传不存在的类别名都等于"不偏移"。
    /// 单装 `HealerACR` 时没人写它，字典恒空 ⇒ 行为 = 本地基线
    /// （开发约定 G：AI 是增强层，本地逻辑不该依赖 AI 存活）。
    /// </summary>
    public static void 设类别偏移(类别 类, float 偏移)
    {
        try
        {
            if (偏移 == 0f) _类别偏移.Remove(类);
            else _类别偏移[类] = 偏移;
        }
        catch { }
    }

    /// <summary>清掉所有大类偏移（AI 关掉 / 换本时调）。</summary>
    public static void 清类别偏移()
    {
        try { _类别偏移.Clear(); } catch { }
    }

    /// <summary>取某个技能的类别（诊断 / 提示词用）。</summary>
    public static 类别 取类别(uint 技能Id)
    {
        try { return _类别.TryGetValue(技能Id, out var c) ? c : 类别.其他; }
        catch { return 类别.其他; }
    }

    /// <summary>把技能登记进某个类别（载入时调）。</summary>
    private static void 归类(uint 技能Id, 类别 类)
    {
        try { if (技能Id != 0) _类别[技能Id] = 类; } catch { }
    }

    /// <summary>
    /// **AI 的阈值偏移** —— 由 `BlueWhale` 侧每帧写入（本地不反向依赖 AI）。
    ///
    /// ⚠️ 单装 `HealerACR`（没有 BlueWhale）时它恒为 0，一切按表里的原值走。
    ///    这是开发约定 G（AI 是增强层，本地逻辑不该依赖 AI 存活）的落点。
    /// </summary>
    public static float AI偏移 { get; set; }

    /// <summary>把血线夹在合法区间 `[0.05, 0.99]`。</summary>
    private static float 夹(float v)
    {
        try { return Math.Clamp(v, 0.05f, 0.99f); }
        catch { return v; }
    }

