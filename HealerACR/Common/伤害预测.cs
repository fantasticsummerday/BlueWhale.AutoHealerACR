    /// <summary>
    /// **预计这次机制落地时，队伍里最危险的那个人会掉多少血**（最大血比例）。
    ///
    /// 返回 0 表示"近期没有机制"或"还没学到这个机制"。
    /// </summary>
    public static float 预计机制伤害(float 秒 = 4f)
    {
        try
        {
            var 最 = 0f;
            foreach (var r in HealTargetHelper.可治疗队友(50f))
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (r == null || !r.对象有效()) continue;
                var 上限 = r.MaxHp;
                if (上限 <= 0) continue;
                var 比例 = 预计掉血(r, 秒) / 上限;
                if (比例 > 最) 最 = 比例;
            }
            return 最;
        }
        catch
        {
            return 0f;
        }
    }

    /// <summary>
    /// **如果给某人加上这个减伤，预计掉血会变成多少**（最大血比例）。
    ///
    /// ⚠️ 用它和 <see cref="预计机制伤害"/> 对比，就知道"值不值得交"。
    ///
    /// ⚠️ 只算**减伤类** buff；护盾类（`减伤状态表.护盾`）不在乘数里，
    ///    盾是"先扣盾再扣血"，要按有效血量单独处理。
    /// </summary>
    public static float 加减伤后的预计(IBattleChara? 目标, uint 减伤Buff, float 秒 = 4f)
    {
                // ★ **非战斗不预测**（用户实测的"幻觉"根因之一）：
                //   未战斗时预测掉血本身没有意义，而且会被 `要预铺()` 用来乱铺盾。
                //   脱战样本已由 `每帧更新()` 清掉，这里再加一道门更稳。
                if (!CharacterExt.我在战斗()) return 0f;
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            if (目标 == null) return 0f;

            var 上限 = 目标.MaxHp;
            if (上限 <= 0) return 0f;

            var 原乘数 = 减伤乘数.取(目标);
            var 新乘数 = 减伤乘数.加上(目标, 减伤Buff);
            if (原乘数 <= 0.001f) return 0f;

            // 机制部分按新乘数缩放（平A 部分不变）
            var 平A = 平A速率(目标) * 秒;
            var 机制 = 机制伤害(秒, 目标);
            // 把机制部分从"原乘数"换成"新乘数"
            var 机制新 = 机制 * (新乘数 / MathF.Max(0.05f, 原乘数));

            return MathF.Max(0f, 平A + 机制新);
        }
        catch
        {
            return 0f;
        }
    }

    /// <summary>
    /// **减伤收益**（百分点）—— 交了这个减伤能少掉多少（最大血比例）。
    ///
    /// ⚠️ 返回的是**百分点差**，比如 0.08 表示"少掉 8% 最大血"。
    ///    调用方自己决定"这个收益值不值得花一个 CD"。
    /// </summary>
    public static float 减伤收益(IBattleChara? 目标, uint 减伤Buff, float 秒 = 4f)
    {
                // ★ **非战斗不预测**（用户实测的"幻觉"根因之一）：
                //   未战斗时预测掉血本身没有意义，而且会被 `要预铺()` 用来乱铺盾。
                //   脱战样本已由 `每帧更新()` 清掉，这里再加一道门更稳。
                if (!CharacterExt.我在战斗()) return 0f;
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            if (目标 == null) return 0f;
            var 上限 = 目标.MaxHp;
            if (上限 <= 0) return 0f;

            var 不加 = 预计掉血(目标, 秒) / 上限;
            var 加了 = 加减伤后的预计(目标, 减伤Buff, 秒) / 上限;
            return MathF.Max(0f, 不加 - 加了);
        }
        catch
        {
            return 0f;
        }
    }

