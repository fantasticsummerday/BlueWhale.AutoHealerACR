    /// <summary>给 AI 看的一段描述（没有预测数据时返回空串）</summary>
    public static string 状态描述()
    {
        try
        {
            // ══════════════════════════════════════════════════════════════
            //  ★ **非战斗时不给预测，但要明确说明**（用户实测的"幻觉"根因）★
            //
            //  [!] 症状（用户截图）：
            //        基础局面「战斗：未战斗」+ 伤害预测「平A 速率 3.0%…预计 6 秒内 1 人会掉 10% 以上」
            //      ==> AI 会读成「用户正在被平A」 —— **幻觉**。
            //
            //  [!] 为什么不能直接返回空字符串：
            //        空 = AI 不知道发生了什么（可能理解成"没有危险"）。
            //        必须**明确告诉它"未战斗，不做预测"**，它才不会臆测。
            //      （这和 `取主线程缓存()` 的降级文本是同一个设计原则：
            //        「读不到」必须写清楚，不能静默变成「没有」。）
            // ══════════════════════════════════════════════════════════════
            if (!CharacterExt.我在战斗())
                return "【伤害预测】未战斗 —— 不做预测（脱战后样本已清零，等进战斗重新观察）\n";

            var 样本数 = _机制样本.Count;
            var 有观察 = _历史.Count > 0;

            if (!有观察 && 样本数 == 0 && !TimelineManager.未来有减伤(8.0))
                return "";

            var sb = new System.Text.StringBuilder();
            sb.AppendLine("【伤害预测（本地推算，不是猜测结果）】");

// 平A 速率分对象报告（这段会被脚本原样插入 伤害预测.cs）
            // ══════════════════════════════════════════════════════════════
            //  ★ 平A 速率**必须分对象报**（用户实测报的问题）★
            //
            //  ── 原来错在哪 ──
            //      `平A = 平A速率(Core.Me)` —— 报的是**奶妈自己**的掉血。
            //      而奶妈站在远处**不吃平A** ==> `掉 <= 0` ==> 恒 0.0%。
            //      提示词那句「平A 速率：约 0.0%」没有主语，
            //      AI 会读成「整体没有平A伤害」 ==> 判断全错。
            //
            //  ── 用户要求（原话）──
            //      「应该把 T 的和队伍其他成员的分开测算预测」
            //
            //  ── 改法 ──
            //      ① 全队逐个算，报**最高**的那个（谁在被平A，一眼看出）
            //      ② **坦克单独再报一行** —— 它是承伤主体，
            //         而且「T 在裸抗」这类结论要看的就是它
            //      ③ 带上名字，避免再出现「不知道说的是谁」这种歧义
            // ══════════════════════════════════════════════════════════════
            var 全队平A = new List<(string 名, float 速率, bool 实测)>();
            try
            {
                foreach (var r in HealTargetHelper.可治疗队友(50f))
                {
                    try
                    {
                        var 速 = 平A速率(r);
            // ★ 记录这个数是**实测**还是**兜底估计** —— 见下面描述的写法。
            //   区分它们很重要：兜底值只是"附近有怪"的保守假设，**不是观测到的掉血**。
            //   不区分就会让 AI 读成"正在被平A"（用户实测截图确认过这个幻觉）。
            var 是实测 = false;
            try
            {
                if (r.对象有效() && _历史.TryGetValue(r.GameObjectId, out var 表X) && 表X.Count >= 3)
                {
                    var 秒X = (表X[^1].时刻 - 表X[0].时刻) / 1000f;
                    是实测 = 秒X >= 0.5f;
                }
            }
            catch { }
                        if (速 <= 0f) continue;
                        var 名 = "";
                        try { 名 = r.Name.TextValue ?? ""; } catch { }
                        if (string.IsNullOrEmpty(名)) 名 = "id" + r.GameObjectId;
                        全队平A.Add((名, 速, 是实测));
                    }
                    catch { }
                }
            }
            catch { }

            // ① 全队最高（谁在被平A）
            if (全队平A.Count > 0)
            {
                var 最高 = 全队平A.OrderByDescending(x => x.速率).First();
                // ★ **区分"实测"和"兜底估计"**（用户实测发现的幻觉源头）：
                //   原来不管数据从哪来都写"从最近 N 秒掉血外推"，
                //   而实际可能只是"附近有怪"的保守假设（`兜底速率()`）。
                //   ==> AI 读成"用户正在被平A" ==> 幻觉。
                if (最高.实测)
                    sb.AppendLine($"  平A 速率（最高）：{最高.名} {最高.速率 * 100f:F1}% 最大血/秒" +
                                  $"（**实测**：从最近 {(int)采样窗口秒} 秒的掉血外推；" +
                                  $"全队 {全队平A.Count} 人）");
                else
                    sb.AppendLine($"  平A 速率（最高）：{最高.名} {最高.速率 * 100f:F1}% 最大血/秒" +
                                  "（★ **这是兜底估计，不是观测到的掉血** —— " +
                                  "按「附近敌人数 × 每敌每秒」的保守假设得出，仅供备战参考）");
            }
            else
            {
                // [!] 兜底**不能写 0.0%** —— 那是在告诉 AI「没有平A伤害」，
                //     而真实情况是「没观察到有人掉血」。两者完全不同。
                sb.AppendLine($"  平A 速率：约 {兜底速率() * 100f:F1}% 最大血/秒" +
                              "（**没观察到有人实际掉血**；这是按敌人数量估的上限，不是测量值）");
            }

            // ② 坦克单独一行 —— 「T 在裸抗」这类判断看的就是它
            try
            {
                var 坦克 = HealTargetHelper.队伍里的坦克();
                if (坦克 != null)
                {
                    var 坦速 = 平A速率(坦克);
                    sb.AppendLine($"  坦克平A 速率：约 {坦速 * 100f:F1}% 最大血/秒" +
                                  (坦速 <= 0f ? "（**观察不到掉血**：没接怪 / 被盾挡住 / 刚被奶满）" : ""));
                }
            }
            catch { }

            if (样本数 > 0)
                sb.AppendLine($"  已记录 {样本数} 次机制命中，平均 {机制样本均值() * 100f:F0}% 最大血");
            else
                sb.AppendLine("  还没记录到机制（接怪太短或本场没吃过大伤害）");

            var 人 = 预计掉血人数(6f);
            if (人 > 0) sb.AppendLine($"  预计 6 秒内 {人} 人会掉 10% 以上");

            var 危险 = 最危险(6f, 0.5f);
            if (危险 != null)
                sb.AppendLine($"  6 秒后最危险：{危险.Name.ToString()} 预计 {预计血量比例(危险, 6f) * 100f:F0}%");

            // ══════════════════════════════════════════════════════════
            //  ★ 减伤维度（用户需求：让 AI 能判断"要不要交减伤"）★
            //
            //  [!] 只说"预计掉 42%"不够 —— AI 需要知道**当前减伤是多少**，
            //      以及"交了会不会好一点"，否则它无从判断值不值得花一个 CD。
            // ══════════════════════════════════════════════════════════
            var 要我 = 减伤乘数.取自己();
            if (要我 < 0.999f)
                sb.AppendLine($"  我的减伤乘数 x{要我:F2}（已计入上面的预测）");

            if (要预铺(6f))
            {
                var 机制伤害 = 预计机制伤害(4f);
                if (机制伤害 > 0.01f)
                    sb.AppendLine($"  即将落地的机制：预计最危险的人掉 {机制伤害 * 100f:F0}% 最大血");
                sb.AppendLine("  -> 短时间内有需要预铺的伤害");
            }

            // [!] 反解诊断**不进提示词** —— 它是开发期用来核对
            //     "原始威力学得准不准"的，已经通过 `日志诊断` 打进了日志。
            //     提示词预算本来就紧，不放只给开发者看的东西。

            return sb.ToString();
        }
        catch
        {
            return "";
        }
    }
