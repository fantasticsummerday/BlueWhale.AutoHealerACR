using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;
using HealerACR.Timeline;

namespace HealerACR.Common;

/// <summary>
/// **伤害预测** —— 本地、每帧、不依赖 AI。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么必须本地 ★
///
///    AI 分析一轮要几百毫秒，而建议还要缓存几秒 ——
///    **等它想好，局面早就变了**（用户原话："思考好了已经过时了"）。
///    治疗决策要在**几十毫秒**内做出，只能靠本地预测。
///
///  ★ 两个数据来源 ★
///
///    ① **观察法**（主要）——
///       每帧记录全队血量，从"过去几秒掉了多少"外推"未来几秒会掉多少"。
///
///       ⚠️ 为什么不能直接读伤害数值：
///          游戏**不暴露**"敌人下一次攻击打多少"。只能观察结果（掉血）。
///          ⇒ 有滞后：战斗刚开始的几秒估不准。
///          这是**已知限制**，不是 bug —— 有预测总比没有强。
///
///    ② **机制记录**（补充）——
///       检测"突然大幅掉血"（>阈值）记成一次机制命中，
///       同时关联时间轴上的机制名。
///       ⇒ 第二次遇到同名机制就能预判"这一下大概打多少"。
///
///  ★ 平A vs 机制怎么区分 ★
///    机制 = 短时间内（<0.5 秒）掉血超过 `机制判定比例`（默认 15% 最大血）
///    平A = 其余的所有掉血（细水长流）
///    两者的外推方式不同：
///      · 平A 是**持续**的 → 按速率外推
///      · 机制是**脉冲**的 → 按"下次什么时候来 + 大概多少"外推
/// ══════════════════════════════════════════════════════════════════
public static class 伤害预测
{
    // ══════════════════════════════════════════════════════════════
    //  参数
    // ══════════════════════════════════════════════════════════════

    /// <summary>血量采样保留多久（秒）</summary>
    private const float 采样窗口秒 = 12f;

    /// <summary>采样间隔（毫秒）—— 每帧采样太密，10 帧一次足够</summary>
    private const int 采样间隔毫秒 = 160;

    /// <summary>
    /// 一次掉血超过**最大血的这个比例**，判定为「机制命中」而不是平A。
    ///
    /// ⚠️ 15% 的依据：平A 通常每次 3~8% 最大血，机制 AOE 通常 25~60%。
    ///    取 15% 做分界，两边都不会误判得太离谱。
    /// </summary>
    private const float 机制判定比例 = 0.15f;

    /// <summary>机制判定的时间窗（秒）—— 在这段时间内的掉血算"一次"</summary>
    private const float 机制聚合秒 = 0.5f;

    /// <summary>
    /// **平A 兜底速率**（每秒掉最大血的百分之多少 / 每个敌人）。
    ///
    /// ⚠️ 只在"还没观察到任何掉血"时用（接怪的头几秒）。
    ///    取 3% 是个保守值：4 人本单 Boss 大约 2~5%/秒。
    ///    宁可高估（多奶一口）也不要低估（人死了没法救）。
    /// </summary>
    private const float 平A兜底每敌每秒 = 0.03f;

    /// <summary>
    /// **机制兜底伤害**（最大血的比例）—— 没观察过任何机制时用。
    ///
    /// ⚠️ 时间轴说"马上有机制"但我们没记录过它时，按这个估。
    ///    40% 是常见 AOE 的量级。
    /// </summary>
    private const float 机制兜底比例 = 0.40f;

    // ══════════════════════════════════════════════════════════════
    //  采样状态
    // ══════════════════════════════════════════════════════════════

    private sealed class 采样
    {
        public long 时刻;
        public float 有效比例;    // 含盾
        public float 血量比例;    // 不含盾（算真实掉血）
    }

    private static readonly Dictionary<ulong, List<采样>> _历史 = new();

    /// <summary>
    /// 上一帧在不在战斗 —— 用来在**脱战那一刻**清掉样本。
    ///
    /// [!] 为什么要清：不清的话 `_历史` 里会留着**上一场战斗**的样本，
    ///     而 `平A速率()` 会拿它外推 ==> 非战斗时也"预测掉血"。
    ///     用户实测截图确认过这个幻觉。
    /// </summary>
    private static bool _上次战斗中;
    private static long _上次采样;

    /// <summary>记录到的机制命中：最大血比例</summary>
    private static readonly List<(long 时刻, float 比例)> _机制样本 = new();

    /// <summary>时间轴机制名 → 观察到的伤害比例（**含当时减伤**，原始观察值）</summary>
    private static readonly Dictionary<string, float> _机制伤害 = new();

    // ══════════════════════════════════════════════════════════════
    //  ★ 减伤维度（用户需求）★
    //
    //  [!] 为什么要**分离**"原始威力"和"减伤乘数"：
    //      观察到的伤害 = 原始威力 x 当时的减伤乘数
    //      只存观察值的话，"当时有减伤"和"当时没减伤"会混在一起，
    //      预测时**无法回答"如果现在交减伤会怎样"**。
    //
    //    => 反解出原始威力（= 观察值 / 当时乘数），预测时再乘当前乘数。
    // ══════════════════════════════════════════════════════════════

    /// <summary>机制名 -> **反解出的原始威力**（最大血比例，未计减伤）</summary>
    private static readonly Dictionary<string, float> _机制原始威力 = new();

    /// <summary>上次采样时每个成员的减伤乘数（反解要用**命中前那一刻**的）</summary>
    private static readonly Dictionary<ulong, float> _上次减伤 = new();

    /// <summary>最近一次反解的诊断信息（给日志用）</summary>
    public static string 最近诊断 { get; private set; } = "";

    private static long _上次诊断日志;

    /// <summary>反解诊断打日志（最多每 3 秒一条，避免刷屏）</summary>
    private static void 日志诊断(string 说明)
    {
        try
        {
            var 现在 = TimeHelper.Now();
            if (现在 - _上次诊断日志 < 3000) return;
            _上次诊断日志 = 现在;
            LogHelper.Info("[伤害预测] " + 说明);
        }
        catch { }
    }

    // ══════════════════════════════════════════════════════════════
    //  每帧更新（挂到 OnBattleUpdate）
    // ══════════════════════════════════════════════════════════════

    /// <summary>每帧调一次 —— 采样全队血量。</summary>
    public static void 每帧更新()
    {
        try
        {
            var 现在 = TimeHelper.Now();
            if (现在 - _上次采样 < 采样间隔毫秒) return;
            _上次采样 = 现在;

            // ══════════════════════════════════════════════════════════════
            //  ★ **非战斗不采样** —— 用户实测发现的"幻觉"源头之一 ★
            //
            //  [!] 症状（用户截图）：
            //        基础局面「战斗：未战斗」
            //        伤害预测「平A 速率（最高）：月时计 3.0% 最大血/秒
            //                  （从最近 12 秒掉血外推）」+「预计 6 秒内 1 人会掉 10% 以上」
            //      ==> **未战斗却在预测掉血。**
            //
            //  [!] 为什么：`每帧更新()` 原来**不分战斗与否**都采样，
            //      于是 `_历史` 里混着"上次战斗的旧样本"，被 `平A速率()` 外推。
            //
            //  [!] 代价（不只是显示问题）：
            //      预测会被 `要预铺()` 用 ==> **非战斗时乱铺盾 / 乱交资源**。
            // ══════════════════════════════════════════════════════════════
            if (!CharacterExt.我在战斗())
            {
                // 脱战后清掉样本 —— 下次战斗从零开始观察，
                // 避免"上一场的数据"影响这一场的预测。
                // ⚠️ 只在"刚脱战"那一刻清一次（`_战斗中` 记状态），否则每帧都清。
                if (_上次战斗中)
                {
                    _上次战斗中 = false;
                    try { _历史.Clear(); _机制样本.Clear(); } catch { }
                }
                return;
            }
            _上次战斗中 = true;

            var 队伍 = HealTargetHelper.可治疗队友(50f);
            var 见过的 = new HashSet<ulong>();

            foreach (var r in 队伍)
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (r == null || !r.对象有效()) continue;

                var id = r.GameObjectId;
                见过的.Add(id);

                if (!_历史.TryGetValue(id, out var 表))
                {
                    表 = new List<采样>();
                    _历史[id] = 表;
                }

                var 本次 = new 采样
                {
                    时刻 = 现在,
                    有效比例 = r.有效血量比例(),
                    血量比例 = r.血量比例(),
                };

                // ★ 记下"这一刻的减伤乘数"——下一次机制命中要用它反解 ★
                //   [!] 位置在机制检测**之前**是故意的：
                //       检测时读到的就是"命中前一刻"的乘数。
                _上次减伤[id] = 减伤乘数.取(r);

                // ── 机制检测：和上一条采样比，掉血是否超过阈值 ──
                if (表.Count > 0)
                {
                    var 上条 = 表[^1];
                    var 掉 = 上条.血量比例 - 本次.血量比例;
                    if (掉 >= 机制判定比例)
                    {
                        _机制样本.Add((现在, 掉));
                        if (_机制样本.Count > 40) _机制样本.RemoveAt(0);

                        // 关联时间轴上的机制名（如果有）
                        //
                        // ⚠️ 用 `下一条机制()` 而不是 `当前机制()`：
                        //    后者返回 `List<...>`（同一时刻可能多个），
                        //    前者返回"接下来那一个" —— 刚吃到伤害时，
                        //    时间轴的下一条通常就是刚打过来的这个。
                        // ══════════════════════════════════════════════════
                        //  ★ 反解原始威力 = 观察到的掉血 / 命中那一刻的减伤乘数 ★
                        //
                        //  [!] 用**上一次采样的乘数**（`_上次减伤`）而不是现在的 ——
                        //      这次采样时血已经掉了，减伤可能刚好在这一帧过期，
                        //      用错会让原始威力偏高或偏低。
                        //
                        //  [!] 乘数低于 0.15 时**跳过**：那种情况反解会放大 6 倍以上，
                        //      一次异常读数就能把缓存带偏，等正常样本更稳。
                        // ══════════════════════════════════════════════════
                        var 当时减伤 = _上次减伤.TryGetValue(id, out var mm) ? mm : 1f;

                        try
                        {
                            var 机制 = TimelineManager.下一条机制();
                            if (机制 != null && !string.IsNullOrEmpty(机制.Value.名称))
                            {
                                var 名 = 机制.Value.名称;

                                // 观察值（含当时减伤）—— 保留，做兜底
                                _机制伤害[名] = _机制伤害.TryGetValue(名, out var 旧)
                                    ? (旧 + 掉) * 0.5f
                                    : 掉;

                                // 原始威力（反解）
                                if (当时减伤 > 0.15f)
                                {
                                    var 原始 = 掉 / 当时减伤;
                                    _机制原始威力[名] = _机制原始威力.TryGetValue(名, out var 旧原)
                                        ? (旧原 + 原始) * 0.5f
                                        : 原始;

                                    最近诊断 = $"{名}：观察 {掉 * 100:F1}% / 当时减伤 x{当时减伤:F2}" +
                                               $" => 原始威力 {原始 * 100:F1}%";
                                    日志诊断(最近诊断);

                                    // 记下"当时的减伤"，用来修正旧观察值
                                    _机制减伤样本.Add(当时减伤);
                                    if (_机制减伤样本.Count > 40) _机制减伤样本.RemoveAt(0);
                                }
                            }
                        }
                        catch { }
                    }
                }

                表.Add(本次);

                // ── 裁掉过期采样 ──
                var 最早 = 现在 - (long)(采样窗口秒 * 1000);
                var 删到 = 0;
                while (删到 < 表.Count && 表[删到].时刻 < 最早) 删到++;
                if (删到 > 0) 表.RemoveRange(0, 删到);
            }

            // ── 清理离队/死亡的人 ──
            if (_历史.Count > 见过的.Count + 4)
            {
                foreach (var k in _历史.Keys.Where(k => !见过的.Contains(k)).ToList())
                    _历史.Remove(k);
            }
        }
        catch { }
    }

    /// <summary>战斗重置 —— 换本 / 重新开怪时清空（旧数据会误导预测）</summary>
    public static void 重置()
    {
        try
        {
            _历史.Clear();
            _机制样本.Clear();
            _机制伤害.Clear();
            _机制原始威力.Clear();
            _上次减伤.Clear();
            _机制减伤样本.Clear();
            最近诊断 = "";
            _上次采样 = 0;
        }
        catch { }
    }

    // ══════════════════════════════════════════════════════════════
    //  预测
    // ══════════════════════════════════════════════════════════════

    /// <summary>
    /// **预计未来 <paramref name="秒"/> 秒会掉多少血**（绝对值，不是比例）。
    ///
    /// = 平A 外推 + 机制预测
    /// </summary>
    public static float 预计掉血(IBattleChara 目标, float 秒)
    {
                // ★ **非战斗不预测**（用户实测的"幻觉"根因之一）：
                //   未战斗时预测掉血本身没有意义，而且会被 `要预铺()` 用来乱铺盾。
                //   脱战样本已由 `每帧更新()` 清掉，这里再加一道门更稳。
                if (!CharacterExt.我在战斗()) return 0f;
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            if (目标 == null || 秒 <= 0f) return 0f;

            var 上限 = 目标.MaxHp;
            if (上限 <= 0) return 0f;

            // ★ 机制部分按**该目标当前的减伤**折算 ★
            //   （平A 不折 —— 平A 本来就很少有减伤覆盖，而且它是观察外推值）
            var 比例 = 平A速率(目标) * 秒 + 机制伤害(秒, 目标);
            return 上限 * MathF.Max(0f, 比例);
        }
        catch
        {
            return 0f;
        }
    }

    /// <summary>
    /// **预计 <paramref name="秒"/> 秒后这个人的血量比例**（0~1，含盾）。
    ///
    /// ⚠️ 会**扣除**期间的预测治疗吗？**不会** ——
    ///    这是"什么都不做会怎样"，治疗决策正是要用它来判断"需不需要做"。
    /// </summary>
    public static float 预计血量比例(IBattleChara 目标, float 秒)
    {
                // ★ **非战斗不预测**（用户实测的"幻觉"根因之一）：
                //   未战斗时预测掉血本身没有意义，而且会被 `要预铺()` 用来乱铺盾。
                //   脱战样本已由 `每帧更新()` 清掉，这里再加一道门更稳。
                if (!CharacterExt.我在战斗()) return 1f;
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            if (目标 == null) return 1f;

            var 上限 = 目标.MaxHp;
            if (上限 <= 0) return 1f;

            var 当前 = 目标.有效血量比例() * 上限;
            var 之后 = 当前 - 预计掉血(目标, 秒);
            return MathF.Max(0f, 之后 / 上限);
        }
        catch
        {
            return 1f;
        }
    }

    /// <summary>
    /// **未来 <paramref name="秒"/> 秒内最危险的那个人**（预计血量比例最低）。
    ///
    /// 没人低于 <paramref name="低于比例"/> 时返回 null。
    /// </summary>
    public static IBattleChara? 最危险( float 秒, float 低于比例 = 1f)
    {
        try
        {
            IBattleChara? 最 = null;
            var 最低 = float.MaxValue;

            foreach (var r in HealTargetHelper.可治疗队友(50f))
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (r == null || !r.对象有效()) continue;
                var p = 预计血量比例(r, 秒);
                if (p < 最低) { 最低 = p; 最 = r; }
            }

            return 最低 <= 低于比例 ? 最 : null;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>
    /// **未来 <paramref name="秒"/> 秒内预计会掉血的人数**（掉超过 <paramref name="掉血比例"/>）。
    ///
    /// 用途：判断"群奶值不值得交" —— 比只看当前血量更早。
    /// </summary>
    public static int 预计掉血人数(float 秒, float 掉血比例 = 0.10f)
    {
                // ★ **非战斗不预测**（用户实测的"幻觉"根因之一）：
                //   未战斗时预测掉血本身没有意义，而且会被 `要预铺()` 用来乱铺盾。
                //   脱战样本已由 `每帧更新()` 清掉，这里再加一道门更稳。
                if (!CharacterExt.我在战斗()) return 0;
        try
        {
            var 数 = 0;
            foreach (var r in HealTargetHelper.可治疗队友(50f))
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (r == null || !r.对象有效()) continue;

                var 上限 = r.MaxHp;
                if (上限 <= 0) continue;

                if (预计掉血(r, 秒) / 上限 >= 掉血比例) 数++;
            }
            return 数;
        }
        catch
        {
            return 0;
        }
    }

    /// <summary>
    /// **未来 <paramref name="秒"/> 秒内会不会有"大到需要预铺"的伤害**。
    ///
    /// 两个来源任一成立即真：
    ///   ① 时间轴预报（`TimelineManager.未来有减伤`）
    ///   ② 观察到的机制样本很大（超过 <paramref name="比例"/>）
    /// </summary>
    public static bool 要预铺(float 秒 = 4f, float 比例 = 0.20f)
    {
                // ★ **非战斗不预测**（用户实测的"幻觉"根因之一）：
                //   未战斗时预测掉血本身没有意义，而且会被 `要预铺()` 用来乱铺盾。
                //   脱战样本已由 `每帧更新()` 清掉，这里再加一道门更稳。
                if (!CharacterExt.我在战斗()) return false;
        try
        {
            if (TimelineManager.未来有减伤(秒)) return true;
            if (减伤Helper.即将来大伤害()) return true;

            // 观察到的机制量级够大 → 即使时间轴没报也要预铺
            return 机制伤害(秒) >= 比例;
        }
        catch
        {
            return false;
        }
    }

