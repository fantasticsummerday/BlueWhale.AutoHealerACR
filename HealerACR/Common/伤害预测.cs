    /// <summary>
    /// **平A 速率**（每秒掉最大血的百分之多少）—— 从最近几秒的观察外推。
    ///
    /// ⚠️ 用**血量比例**（不含盾）而不是有效比例 ——
    ///    盾抵消掉的伤害**没有真的打到人身上**，算进"掉血速率"会高估。
    /// </summary>
    private static float 平A速率(IBattleChara 目标)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            if (!_历史.TryGetValue(目标.GameObjectId, out var 表) || 表.Count < 3)
                return 兜底速率();

            var 首 = 表[0];
            var 末 = 表[^1];
            var 秒 = (末.时刻 - 首.时刻) / 1000f;
            if (秒 < 0.5f) return 兜底速率();

            // ══════════════════════════════════════════════════════════════
            //  ★★ 用「累计掉血」而不是「净变化」—— 修的是"被自己治疗抹平" ★★
            //
            //  [!] 用户实测「T 的血量预测完全没生效」的第二个根因在这里。
            //
            //  [!] 原来写的是
            //        var 掉 = 首.血量比例 - 末.血量比例;   // **净变化**
            //        if (掉 <= 0f) return 0f;              // 没在掉血（或者被奶回来了）
            //      而注释自己都写了"或者被奶回来了" ——
            //      **我们一直在奶坦克** ==> 净变化经常 <= 0 ==> **恒 0**。
            //      ==> T 越是被照顾好，这个预测越是 0，**方向完全是反的**。
            //
            //  [!] 改成**累计掉血**：把窗口内每一对相邻采样里"下降的部分"加起来。
            //      这样"掉了 8% 又被奶回 8%"会算成掉了 8%（真相），而不是 0（假象）。
            //      **治疗不再抹平它。**
            //
            //  [!] 参考实现的立场（IL 实证）：它们**根本不看血量趋势** ——
            //      youshu 和 shiyuvi 的预判都只读 BOSS 读条。
            //      ==> 这条路**本来就不该是主力**，主力是上面那个"读条门"。
            //          这里改好只是让"没有读条可读"时也有个像样的退路。
            //
            //  [!] 观测不到任何掉血时退回 `兜底速率()` 而**不是 0**：
            //      0 会被上层读成"这个目标不会受伤"（于是不做准备），
            //      而真相多半是"被盾挡住了 / 刚被奶满 / 我们没采到"。
            //      兜底值是保守的正数。
            //      ==> 0 = 不做准备，兜底 = 做准备；漏了准备的代价远大于多做一次。
            // ══════════════════════════════════════════════════════════════
            var 累计掉 = 0f;
            for (var i = 1; i < 表.Count; i++)
            {
                var d = 表[i - 1].血量比例 - 表[i].血量比例;
                if (d > 0f) 累计掉 += d;
            }
            if (累计掉 <= 0f) return 兜底速率();   // 观测不到掉血 -> 保守兜底，不是 0

            // ⚠️ 把「机制造成的那部分」扣掉 —— 否则遇到一次大机制，
            //    之后的平A 速率会被拉得虚高，导致过度治疗。
            //
            // [!] **必须是窗口内的机制总量**，不能拿采样点数去凑 ——
            //     原来写成「机制样本均值() * (表.Count / 3f)」会算出 375% 最大血，
            //     把所有人的平A速率抹成 0（详见「窗口内机制掉血」的说明）。
            var 机制占 = 窗口内机制掉血(首.时刻, 末.时刻);
            var 平A掉 = MathF.Max(0f, 累计掉 - 机制占);

            return 平A掉 / 秒;
        }
        catch
        {
            return 兜底速率();
        }
    }

    /// <summary>没有观察数据时的兜底：按敌人数量估</summary>
    private static float 兜底速率()
    {
        try
        {
            var 敌 = Math.Clamp(HealTargetHelper.附近敌人总数(30f), 1, 8);
            return 平A兜底每敌每秒 * 敌;
        }
        catch
        {
            return 平A兜底每敌每秒;
        }
    }

    /// <summary>
    /// **机制伤害预测**（未来 <paramref name="秒"/> 秒内，最大血的比例）。
    ///
    /// ⚠️ 简化模型：不做"下次机制什么时候来"的精确推算 ——
    ///    因为 `TimelineManager` 已经给了时机（`未来有减伤`），
    ///    这里只负责**量级**。时间轴说有机制 → 按观察到的量级估。
    /// </summary>
    private static float 机制伤害(float 秒, IBattleChara? 目标 = null)
    {
        try
        {
            // ══════════════════════════════════════════════════════════════
            //  ★★ 修的是一个真 bug：**读条那条路被时间轴门挡死了** ★★
            //
            //  [!] 用户实测「T 的血量预测完全没生效」的根因就在这里。
            //
            //  [!] 原来的顺序：
            //        L472  if (!时间轴有减伤(秒) && !即将来大伤害()) return 0f;   ← 门
            //        L504  var 在读 = 机制读条.最强(秒);                        ← 读条在后面
            //      ==> **时间轴没匹配到、当前也没有危险读条时，直接返回 0**
            //          而"有读条"这件事**要走到 L504 才知道**
            //      ==> 注释自己写着「时间轴只有 45% 的副本有」
            //          ==> **另外 55% 的副本里，机制预测恒 0**，
            //              哪怕 Boss 正在读一个大伤害。
            //
            //  [!] 参考实现怎么做的（两套完全一致，IL 实证）：
            //        youshu  `HasBossCastingAoeWithin(ms)` / `HasBossCastingTankbusterWithin(ms)`
            //                → `IsBoss` → `IsTargetCastingActionSoon` → `IsAoeAction`
            //        shiyuvi `CheckAllNearbyEnemiesSkills(30f, 8000)` → `targetCastingIsBossAOE`
            //      ==> **它们不看时间轴**，只看"Boss 现在在读什么、还剩多久"。
            //          理由是那条路**不依赖副本数据**，任何副本都成立。
            //
            //  [!] 所以门改成"三选一"，而且**读条优先**：
            //        ① Boss 身上有危险读条（我们在用参考实现同款的
            //           `TargetHelper.targetCastingIsBossAOE` / `targetCastingIsDeathSentenceWithTime`）
            //        ② 时间轴说未来有减伤（原来是唯一的门）
            //        ③ 减伤Helper 说即将来大伤害
            //      ==> 没有时间轴的副本也能预测了。
            // ══════════════════════════════════════════════════════════════
            var 有危险读条 = false;
            try { 有危险读条 = 减伤Helper.即将来大伤害(); } catch { }

            var 时间轴说有 = false;
            try { 时间轴说有 = TimelineManager.未来有减伤(秒); } catch { }

            if (!有危险读条 && !时间轴说有)
                return 0f;

            // ── 当前减伤乘数（该目标的）──
            var 当前减伤 = 1f;
            if (目标 != null) 当前减伤 = 减伤乘数.取(目标);

            // ══════════════════════════════════════════════════════════
            //  ★ 优先用"原始威力 x 当前减伤" ★
            //
            //  [!] 这就是"能不能回答'交了盾会掉多少'"的关键：
            //      原始威力是**去掉了当时减伤**的值，乘上当前减伤，
            //      就等于"如果现在这个减伤状态下吃这一下，会掉多少"。
            //
            //  [!] 用不了原始威力时才退回观察值 ——
            //      观察值里含**当时**的减伤，拿它当"现在的"会偏。
            //      但比"返回 0（当作没伤害）"安全得多。
            // ══════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════
            //  ★ 第一优先：**读条实测**（三方对照里最可靠的一路）★
            //
            //  [!] 为什么它比时间轴优先：
            //      时间轴给的是"下一条机制是谁"—— 那是**猜**，而且
            //        · 只有 45% 的副本有
            //        · 对齐会漂（灭团重来 / 跳阶段）
            //        · 同时跑两条时会张冠李戴
            //      而读条是 **Boss 正在施放**这件事本身 —— 实测，不会猜错。
            //
            //  [!] 只有读条技才走得到这里。瞬发机制仍然退回时间轴（下面）。
            // ══════════════════════════════════════════════════════════
            try
            {
                var 在读 = 机制读条.最强(秒);
                if (在读 != null && !string.IsNullOrEmpty(在读.名))
                {
                    var 名 = 在读.名;

                    if (_机制原始威力.TryGetValue(名, out var 原始2) && 原始2 > 0f)
                        return 原始2 * 当前减伤;

                    if (_机制伤害.TryGetValue(名, out var 观察2) && 观察2 > 0f)
                    {
                        var 当时2 = 机制样本减伤均值();
                        if (当时2 > 0.15f) return 观察2 / 当时2 * 当前减伤;
                        return 观察2;
                    }

                    // 读条确认了身份，但**还没有它的量级样本**（第一次见）。
                    //   此时**不能返回 0**（= 当作没伤害）——
                    //   那是"知道要挨打却当没事"，比估高危险得多。
                    //   退回全局均值兜底（下面的逻辑会做，这里只记一笔）。
                    LogHelper.Info($"[伤害预测] 读条确认机制「{名}」但还没有量级样本，用全局均值兜底");
                }
            }
            catch { }

            try
            {
                var 机制 = TimelineManager.下一条机制();
                if (机制 != null && !string.IsNullOrEmpty(机制.Value.名称))
                {
                    var 名 = 机制.Value.名称;

                    if (_机制原始威力.TryGetValue(名, out var 原始) && 原始 > 0f)
                        return 原始 * 当前减伤;

                    if (_机制伤害.TryGetValue(名, out var 观察) && 观察 > 0f)
                    {
                        // 观察值含当时减伤 —— 尽力修正：除以"当时"的均值乘数
                        var 当时 = 机制样本减伤均值();
                        if (当时 > 0.15f) return 观察 / 当时 * 当前减伤;
                        return 观察;
                    }
                }
            }
            catch { }

            var 均值 = 机制样本均值();
            var 基础 = 均值 > 0f ? 均值 : 机制兜底比例;

            // 兜底值也不知道当时减伤 —— 按当前减伤折算（近似）
            return 基础 * 当前减伤;
        }
        catch
        {
            return 0f;
        }
    }

    /// <summary>机制命中时观察到的减伤乘数均值（用于修正旧观察值）</summary>
    private static readonly List<float> _机制减伤样本 = new();

    private static float 机制样本减伤均值()
    {
        if (_机制减伤样本.Count == 0) return 1f;
        var 和 = 0f;
        foreach (var v in _机制减伤样本) 和 += v;
        return 和 / _机制减伤样本.Count;
    }

    /// <summary>
    /// **在这段时间窗内，机制一共打掉了多少比例的血**。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  [!] 修的是一个**量纲错误**（用户实测：平A速率恒 0.0%）
    ///
    ///      原来写的是：
    ///          var 机制占 = 机制样本均值() * (表.Count / 3f);
    ///      `_机制样本` 存的是**单次机制的掉血比例**（每条 ≥ 0.15），
    ///      而 `表.Count` 是**该成员的采样点数**（160ms × 12s ≈ 75）。
    ///      ==> 机制占 ≥ 0.15 × (75/3) = **3.75**（= 375% 最大血），
    ///          而 `掉 = 首.血量比例 - 末.血量比例` **最多 1.0**
    ///      ==> `平A掉 = max(0, 掉 − 3.75) = 0`
    ///      ==> **一旦记过任何一次机制，所有人的平A速率恒为 0**
    ///          （包括坦克的 `预计掉血`，它的平A项也被抹掉了）。
    ///
    ///  [!] 正确的量纲：
    ///          机制占 = 单次机制伤害 × **窗口内发生了几次机制**
    ///      而发生几次只能靠**时刻**数出来 ——
    ///      所以 `_机制样本` 必须带时刻（这次一并改了）。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static float 窗口内机制掉血(long 从, long 到)
    {
        try
        {
            var 和 = 0f;
            foreach (var s in _机制样本)
            {
                if (s.时刻 < 从 || s.时刻 > 到) continue;
                和 += s.比例;
            }
            return 和;
        }
        catch { return 0f; }
    }
    
    private static float 机制样本均值()
    {
        if (_机制样本.Count == 0) return 0f;

        var 和 = 0f;
        foreach (var s in _机制样本) 和 += s.比例;
        return 和 / _机制样本.Count;
    }

