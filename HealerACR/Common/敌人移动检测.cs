using System.Numerics;
using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;

namespace HealerACR.Common;

/// <summary>
/// 敌人移动检测 —— 参考同类 ACR 的 `ScholarEnemyCheck.HasEnemyMovedLessThan`。
///
/// **要解决的问题**：地面放置技能（罩子 / 地星 / 庇护所 / 礼仪之铃）
/// 放下去之后敌人一走，技能就废了。所以选位置要挑"站位稳定"的敌人。
///
/// ══════════════════════════════════════════════════════════════════
///  ⚠️ 关键修正：「没动」不等于「站得稳」
///
///  第一版逻辑是"最近没移动 -> 判定站得稳"。
///  但**小怪刚出现时往往站着不动**（还在待机 / 没被拉 / 在远处），
///  这时候会被误判成"稳定"，罩子扔过去，它马上冲进来 —— 白放。
///
///  所以真正的判据不是"现在没动"，而是 **"已经稳定了足够久"**：
///    ① 必须**观察满最短时间**（默认 3 秒）才给判断，之前一律 false
///    ② 采样点要够多（至少 4 个），避免"刚好两帧没动"
///    ③ **还在持续靠近我的敌人直接排除**（它在移动，只是采样间隔没抓到）
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 敌人移动检测
{
    /// <summary>采样间隔（毫秒）—— 太短会被抖动干扰，太长反应慢</summary>
    private const int 采样间隔 = 400;

    /// <summary>
    /// 最短观察时间。**这是防误判的核心** ——
    /// 小怪刚出现的头几秒一律不给"稳定"判定。
    /// </summary>
    private const int 最短观察 = 3000;

    /// <summary>最少要采到几个点（配合最短观察，双重保险）</summary>
    private const int 最少采样数 = 4;

    /// <summary>记录多久没出现就清掉</summary>
    private const int 记录过期 = 15000;

    /// <summary>判定阈值：平均移动速度超过这个值（米/秒）就不算稳定</summary>
    private const float 默认阈值 = 2.5f;

    private sealed class 采样
    {
        public Vector3 位置;
        public long 时间;
        public float 累计移动;
        public int 采样数;
        public long 首次观察;
    }

    private static readonly Dictionary<ulong, 采样> _记录 = new();

    /// <summary>
    /// 先记账再说 —— 不管最后判不判得了，采样都要继续。
    /// 返回"当前这次是否需要继续累加"。
    /// </summary>
    private static void 累加采样(采样 s, Vector3 当前位置, long 现在)
    {
        if (现在 - s.时间 < 采样间隔) return;

        s.累计移动 += Vector3.Distance(当前位置, s.位置);
        s.位置 = 当前位置;
        s.时间 = 现在;
        s.采样数++;
    }

    // ══════════════════════════════════════════════════════════════
    //  ★ 复刻参考实现的 `IsTargetMoving`（逐帧位移法）★
    // ══════════════════════════════════════════════════════════════

    /// <summary>上一次位置（逐帧位移用）—— key 用 EntityId，和参考实现一致</summary>
    private static readonly Dictionary<ulong, Vector3> _上次位置 = new();

    /// <summary>
    /// **这个目标"这一帧"动了没有** —— 复刻参考实现的 `IsTargetMoving`。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 和上面 `移动很少()` 的区别（两套判据，用途不同）★
    ///
    ///    | | 移动很少()（我们的） | 本方法（参考实现的） |
    ///    |---|---|---|
    ///    | 判据 | 3 秒内**平均速度** < 2.5 米/秒 | **逐帧位移** > 0.0001 |
    ///    | 观察期 | 要 3000ms + 4 个采样点 | **没有** |
    ///    | 数据不足 | 一律 false | **首次返回 false，之后立刻生效** |
    ///    | 用途 | "这个怪稳不稳"（长时间判断）| "它现在动没动"（当下判断）|
    ///
    ///  ⚠️ **名字反过来看会晕**：`移动很少` 名字像"判当下"，
    ///     其实是**长时间平均**；本方法才是真正的"当下有没有动"。
    ///
    ///  ⚠️ 首次见到这个目标返回 **false**（"没在动"）——
    ///     参考实现就是这么写的（`IL_0035-0043`：建档后直接 `Ldc_i4_0; Ret`）。
    ///     不这么写的话，第一帧必然返回 true，会白白挡住一次施放。
    ///
    ///  ⚠️ key 用 `EntityId`（参考实现也是）——
    ///     `GameObjectId` 和它在我们这个版本里是同一个值的两种暴露，
    ///     但用 `EntityId` 更明确（对象身份而非"游戏对象 id"）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    [Obsolete("截至 3.19.33 全仓库零调用点。" +
              "它判的是「逐帧位移 > 1 厘米」，和本文件真正在用的 `移动很少()`" +
              "（累计移动/观察秒 < 2.5 米每秒）**不是一回事** —— 别混用。")]
    public static bool 正在移动(IBattleChara? 目标)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return false;
        if (目标 == null) return false;

        try
        {
            var id = 目标.EntityId;
            if (id == 0) return false;

            var 位置 = 目标.Position;

            if (!_上次位置.TryGetValue(id, out var 上次))
            {
                _上次位置[id] = 位置;
                return false;              // 首次 → 当作"没动"（与对照实现一致）
            }

            _上次位置[id] = 位置;

            // ⚠️ 0.0001 是参考实现的阈值（`Ldc_r4 0.0001` + `Cgt`）——
            //    这是**平方距离**的比较，0.0001 = 0.01 米 = 1 厘米。
            //    非常灵敏：站着不动的目标偶尔也会有 1 厘米抖动，
            //    但那种抖动是**单帧**的，不会持续，所以不会误判成"一直在动"。
            var dx = 位置.X - 上次.X;
            var dy = 位置.Y - 上次.Y;
            var dz = 位置.Z - 上次.Z;
            return dx * dx + dy * dy + dz * dz > 0.0001f;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>清掉逐帧位移记录（换本时用）</summary>
    public static void 清位移记录() => _上次位置.Clear();


    /// <summary>
    /// 这个敌人是不是**已经稳定了足够久**（可以放心往它脚下放地面技能）。
    ///
    /// **数据不足时一律返回 false** —— 宁可退回"放自己脚下"，
    /// 也不要因为误判把技能扔到马上要跑的目标身上。
    /// </summary>
    public static bool 移动很少(IBattleChara? 敌人, float 阈值 = 默认阈值)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (敌人 == null || !敌人.对象有效()) return false;
        if (敌人 == null) return false;

        try
        {
            var id = 敌人.GameObjectId;
            var 现在 = TimeHelper.Now();
            var 当前位置 = 敌人.Position;

            // 第一次见 → 建档，什么都不判
            if (!_记录.TryGetValue(id, out var s))
            {
                _记录[id] = new 采样
                {
                    位置 = 当前位置,
                    时间 = 现在,
                    累计移动 = 0,
                    采样数 = 0,
                    首次观察 = 现在,
                };
                return false;
            }

            var 观察毫秒 = 现在 - s.首次观察;

            // ── ③ 还在持续靠近我的敌人直接排除 ──
            //     （先判这个：它明确在移动，不用等观察期）
            try
            {
                if (s.位置 != Vector3.Zero)
                {
                    var 上次距我 = Vector3.Distance(s.位置, CharacterExt.我的位置());
                    var 现在距我 = Vector3.Distance(当前位置, CharacterExt.我的位置());
                    if (现在距我 < 上次距我 - 0.5f)
                    {
                        累加采样(s, 当前位置, 现在);
                        return false;
                    }
                }
            }
            catch { }

            // 继续采样
            累加采样(s, 当前位置, 现在);

            // ── ① 观察时间不够 → 不判 ──
            if (观察毫秒 < 最短观察) return false;

            // ── ② 采样点不够 → 不判 ──
            if (s.采样数 < 最少采样数) return false;

            // ── ④ 平均移动速度够小 → 判定稳定 ──
            var 观察秒 = Math.Max(1f, 观察毫秒 / 1000f);
            return s.累计移动 / 观察秒 < 阈值;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// 给**地面放置技能**挑一个落点（罩子 / 地星 / 庇护所 / 礼仪之铃）。
    ///
    /// **选位优先级**：
    ///   ① 优选敌人（一般是 Boss）**已经稳定足够久** → 放它脚下（覆盖最大）
    ///   ② 它在动 / 数据不足 / 没敌人 → **放自己脚下**（最保险）
    ///
    /// 因为 ① 有"观察满 3 秒"的门槛，所以**小怪刚出现那几秒会自动退回自己脚下**，
    /// 不会出现"扔在待机小怪脚下、它马上冲进来"的浪费。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 表 #40：**按参考实现的三分支选落点** ★
    ///
    ///  [!] 参考的 `GroundCastPosition(优先场中, 挂模式, 优先目标位置, 当前目标)`
    ///      是一个**三分支**函数（IL 直证）：
    ///
    ///        ① **场中**（`地星优先场中` 设置开着）
    ///           → `MapCenter(自己位置)`；
    ///             若地图中心**离自己 ≥30 米**（`DistanceSquared >= 900`）
    ///             说明中心不在这一场的活动范围内 ⇒ **退回自己脚下**
    ///        ② **目标位置**（`地星优先目标位置` 开着，且目标有效
    ///           且 `HitboxRadius < 15`，即**不是巨型 Boss**）
    ///           → 目标脚下
    ///        ③ 兜底 → **自己脚下**
    ///
    ///  [!] 我们原来**只有 ②③ 两支**（"敌人站得稳就放它脚下，否则放自己脚下"）：
    ///      · 缺 ① 场中分支 ⇒ 用户说的"落点永远在脚下"就是这一支缺失 ✗
    ///      · 也缺 ② 的 `HitboxRadius < 15` 过滤 ⇒
    ///        对**巨型 Boss**（判定圈很大）会把落点放在它脚下，
    ///        而它的脚下往往离队伍很远 ⇒ 铺了个没人的位置 ✗
    ///
    ///  [!] 关于 ① 的 `MapCenter`：参考读的是 `TerritoryType.Map` 的
    ///      `OffsetX/OffsetY` 取负（= 地图坐标原点在世界里的位置）。
    ///      我们**不引 Lumina 表**，改成用**战场上敌人（没有则队友）的质心**
    ///      作为"场中" —— 语义一致（"大家围着打的那个地方"），
    ///      而且不依赖任何外部数据源。
    ///      同样保留参考的"太远就退回自己脚下"（≥30 米）那条守卫。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static Vector3 地面技能位置(IBattleChara? 优选敌人 = null)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        // ⚠️ 这个函数的语义是【优选敌人为空时回退到当前目标】——
        //    在入口 `return` 会把整条回退链砍掉（下面 241-242 行的兜底永远跑不到）。
        //    ==> 守卫必须放在**真正读到对象之后**，不能放入口。
        //    （脚本按返回类型机械插入，这里要人工纠正 —— 这是它第 3 次插错了。）
        if (优选敌人 != null && !优选敌人.对象有效()) 优选敌人 = null;
        try
        {
            // ── ① 场中分支 ──
            if (HealSettings.Instance.地星优先场中)
            {
                var 场中 = 战场质心();
                if (场中.HasValue)
                {
                    var 我 = CharacterExt.我的位置();
                    // 参考的守卫：中心离自己 ≥30 米 ⇒ 中心不在这一场里 ⇒ 退回自己脚下
                    if (Vector3.DistanceSquared(我, 场中.Value) < 900f) return 场中.Value;
                }
            }

            var 敌人 = 优选敌人;

            if (敌人 == null) 敌人 = HealTargetHelper.当前目标();
            if (敌人 == null) 敌人 = HealTargetHelper.当前目标()?.GetCurrTarget();

            // ★ 守卫放在**回退链之后**（回退链本身可能给出已释放的对象）
            if (敌人 == null || !敌人.对象有效()) return CharacterExt.我的位置();

            // ── ② 目标脚下分支 ──
            //   [!] 参考要求 `HitboxRadius < 15` —— **巨型 Boss 不给它脚下**
            //       （它判定圈太大，脚下常常离队伍很远）
            if (HealSettings.Instance.地星优先目标位置
                && 敌人.CurrentHp > 0
                && 敌人.HitboxRadius < 15f
                && 移动很少(敌人))
            {
                return 敌人.Position;
            }
        }
        catch { }

        // ── ③ 兜底：自己脚下 ──
        return CharacterExt.我的位置();
    }

    /// <summary>
    /// **战场质心** —— 敌人（没有则队友）位置的平均值，当"场中"用（表 #40）。
    ///
    /// [!] 为什么不用地图几何中心：那要读 `TerritoryType.Map` 的 OffsetX/OffsetY
    ///     （参考用的 `MapCenter`），而我们**不引 Lumina 表**。
    ///     质心在语义上更贴"大家围着打的那个地方"，而且不依赖外部数据。
    ///
    /// [!] 没有任何可比位置时返回 **null** —— 由调用方退回自己脚下。
    /// </summary>
    private static Vector3? 战场质心()
    {
        try
        {
            var 累加 = Vector3.Zero;
            var 数量 = 0;

            foreach (var 敌 in Data.AllHostileTargets)
            {
                if (敌 == null || !敌.对象有效()) continue;
                if (敌.CurrentHp <= 0) continue;

                累加 += 敌.Position;
                数量++;
            }

            if (数量 == 0)
            {
                // 没敌人（纯治疗窗口）⇒ 用队友的质心
                foreach (var 友 in PartyHelper.CastableAlliesWithin30)
                {
                    if (友 == null || !友.对象有效() || !友.活着()) continue;

                    累加 += 友.Position;
                    数量++;
                }
            }

            return 数量 > 0 ? 累加 / 数量 : null;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>
    /// **任意目标（含玩家）是不是站得稳** —— 和 `移动很少()` 同一套判据，
    /// 但**不排除"靠近我的人"**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要单独一个方法
    ///
    ///    `移动很少()` 里有一条「还在持续靠近我的敌人直接排除」——
    ///    那是为**敌人**写的（怪冲过来时采样间隔可能抓不到，得提前排除）。
    ///    但**队友**（尤其坦克）在道中就是会朝我走过来 ——
    ///    用那条会把"T 正常往前拉怪"误判成不稳定，反而永远铺不出罩子。
    ///
    ///  [!] 用于什么问题
    ///    用户实测：「小怪阶段 T 在路上停了一下 -> 误判放了罩子」。
    ///    判据不能只看"我自己在不在移动"，必须**T 也停了**才算站定。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static bool 玩家站得稳(IBattleChara? 目标, float 阈值 = 默认阈值)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return false;
        if (目标 == null) return false;

        try
        {
            var id = 目标.GameObjectId;
            var 现在 = TimeHelper.Now();
            var 当前位置 = 目标.Position;

            if (!_记录.TryGetValue(id, out var s))
            {
                _记录[id] = new 采样
                {
                    位置 = 当前位置,
                    时间 = 现在,
                    累计移动 = 0,
                    采样数 = 0,
                    首次观察 = 现在,
                };
                return false;      // [!] 数据不足一律 false —— 宁可多等，不要误铺
            }

            累加采样(s, 当前位置, 现在);

            var 观察毫秒 = 现在 - s.首次观察;
            if (观察毫秒 < 最短观察) return false;
            if (s.采样数 < 最少采样数) return false;

            var 观察秒 = Math.Max(1f, 观察毫秒 / 1000f);
            return s.累计移动 / 观察秒 < 阈值;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>这个敌人现在的采样状态（调试面板用）</summary>
    public static string 状态描述(IBattleChara? 敌人)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (敌人 == null || !敌人.对象有效()) return "";
        if (敌人 == null) return "无目标";

        try
        {
            if (!_记录.TryGetValue(敌人.GameObjectId, out var s)) return "无数据";

            var 观察秒 = (TimeHelper.Now() - s.首次观察) / 1000f;
            var 就绪 = 观察秒 * 1000 >= 最短观察 && s.采样数 >= 最少采样数;

            return $"{观察秒:F1}s / 采样{s.采样数} / 移动{s.累计移动:F1}m / {(就绪 ? "已就绪" : "观察中")}";
        }
        catch
        {
            return "读取失败";
        }
    }

    /// <summary>清理过期记录（每帧调一下，很轻）</summary>
    public static void 清理()
    {
        try
        {
            // 位移记录也要清过期 —— 不清会随敌人数无限增长
            if (_上次位置.Count > 64) _上次位置.Clear();

            if (_记录.Count == 0) return;

            var 现在 = TimeHelper.Now();
            var 要删 = new List<ulong>();

            foreach (var kv in _记录)
            {
                if (现在 - kv.Value.时间 > 记录过期) 要删.Add(kv.Key);
            }

            foreach (var id in 要删) _记录.Remove(id);
        }
        catch { }
    }

    /// <summary>
    /// **地面技能（罩子 / 庇护所 / 地星 这类）现在铺下去稳不稳？**
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么要有这一个"合起来的判据"（开发约定 F③）
    ///    本地 `Res_Mitigation.Check` 里是**三道分开的守卫**（返回 -6 / -7 / -8，
    ///    为的是排查时能一眼看出是"我在动"还是"T 在动"还是"落点在动"）；
    ///    而**学者组合链**与 **AI 建议侧**只需要一个"能不能铺"的布尔值。
    ///    于是把**同一批评据**收在这里：守卫 / 组合链 / AI 侧**三处同源** ——
    ///    而不是各写一份（"改一处漏一处"正是本项目栽过的坑）。
    ///
    ///  [!] 判据（与 `Res_Mitigation.cs:758` / `:787-804` 逐条一致）
    ///    ① 我能不能读条（含跳跃 —— `不能读条()` 与 `移动中可用()` 同源）
    ///    ② T 站得稳不稳（`玩家站得稳`：观察满 3 秒 + 采样 ≥4 + 平均速度 &lt; 2.5 米/秒）
    ///    ③ 落点目标（当前目标）动得少不少
    ///
    ///  [!] 读不到 ⇒ **返回 false（不稳）**：罩子持续 15 秒以上，
    ///      **宁可多等一秒，不要误铺**（与 `Res_Mitigation.cs:778` 对"数据不足"的口径一致）。
    ///
    ///  [!] ⚠️ 本地守卫里"**时间轴要求 / 读条要求**可以越过这三条"那一支**不在这里** ——
    ///      那是"明确的即将来伤害"，只有本地 Check 在**触发阶段**才拿得到这两个判据。
    ///      调用方若要保留那个例外，请自己判断强触发后**跳过本判据**
    ///      （AI 侧正是这么处理的：它拿不到判据 ⇒ 一律要求稳定，把强触发交回本地放）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static bool 地面站得稳()
    {
        try
        {
            // ① 我在移动 / 跳跃 —— 地面技放不出去
            if (SpellUtil.不能读条()) return false;

            // ② T 站得稳不稳（只看"我自己停没停"拦不住："T 在路上停一下"是常态）
            var 主坦 = HealTargetHelper.队伍里的坦克();
            if (主坦 != null && !玩家站得稳(主坦)) return false;

            // ③ 落点目标动得少不少（不稳定时落点会退回自己脚下 = 铺在我站的地方）
            var 落点目标 = HealTargetHelper.当前目标();
            if (落点目标 != null && 落点目标.CurrentHp > 0 && !移动很少(落点目标)) return false;

            return true;
        }
        catch
        {
            return false;   // 读不到 ⇒ 不稳（宁可多等一秒，不要误铺）
        }
    }

    /// <summary>换本 / 战斗重置时清空</summary>
    public static void 重置()
    {
        _记录.Clear();
        _上次位置.Clear();
    }
