using System;

namespace HealerACR.Common;

/// <summary>
/// **全进程共享的绘制频率门** —— 防止"同一帧被画几十次"。
///
/// ══════════════════════════════════════════════════════════════════
///  [!] 为什么需要（用户实测）
///      「进本后一开始绘制页面有闪烁」+ 日志里 `[面板] 路标` 的累计次数
///      在 30 秒内到了 **20,722 次**（约 680 次/秒）。
///      而 ImGui 一帧最多画 60 次 ⇒ **同一帧被画了 10 次以上**。
///      · 闪烁：同一个窗口一帧内被 Begin/End 多次 ⇒ 视觉上就是闪
///      · 卡顿：每次绘制都跑 13 个 ImGui 子段 + 6 个反射委托
///
///  [!] 为什么**不能用**原来的 8ms 门（两个原因）
///      ① 它用 `AEAssist.Helper.TimeHelper.Now()`，而那个东西的语义**无法确认**
///         （不是 Stopwatch、不是 TickCount64，也没有文档）。
///         实测：门设成 8ms，面板仍被画 680~8800 次/秒
///         ==> 它**不是可靠的"实时毫秒"**。
///         ⚠️ 工程里有 **149 处**都在用它做节流 —— 那些节流的可靠性全部存疑，
///            这里先把这个门换成可信的计时器，别的以后单独审。
///      ② 门是"每个入口各一份静态字段"—— 本项目有 **10 个职业入口**
///         （HealerACR 5 个 + BlueWhale 5 个），框架对每个都调一次绘制
///         ==> 125 次/秒 × 10 = **1250 次/秒**。
///         ==> 所以门必须**全进程共享**，不能放在各自的入口类里。
///
///  [!] 为什么用 `Environment.TickCount64`
///      · 它是 **struct**（`long`）—— 无装箱、无分配
///      · 它**确定是毫秒**（文档明确）
///      · 它**单调递增**（不受系统时间调整影响）
///      · 它**跨程序集共享同一份系统计时器**（不是 per-assembly 的）
///      ==> 这三点正好是节流需要的全部性质。
/// ══════════════════════════════════════════════════════════════════
public static class 绘制节流
{
    /// <summary>设置面板的最小绘制间隔（毫秒）。8ms ≈ 125 FPS 上限。</summary>
    private const int 面板最小间隔毫秒 = 8;

    private static long _面板上次;

    /// <summary>
    /// **这一帧该不该画设置面板**。
    ///
    /// 返回 false = **跳过本次绘制**（省掉 13 个 ImGui 子段 + 6 个反射调用）。
    /// 8ms 意味着"最多 125 次/秒"，远超显示刷新率 —— **画面完全看不出区别**，
    /// 而同一帧画多次只会闪烁 + 卡顿。
    ///
    /// ⚠️ 用 `Environment.TickCount64` 而不是 `TimeHelper.Now()` —— 见类说明。
    /// </summary>
    public static bool 该画面板()
    {
        try
        {
            var 现在 = Environment.TickCount64;
            if (现在 - _面板上次 < 面板最小间隔毫秒) return false;
            _面板上次 = 现在;
            return true;
        }
        catch
        {
            return true;   // 出错就画（宁可多画，也不要"面板不显示"）
        }
    }

    /// <summary>诊断用：当前距上次绘制过了多久（毫秒）。</summary>
    public static long 距上次面板毫秒()
    {
        try { return Environment.TickCount64 - _面板上次; }
        catch { return 0; }
    }
}
