using System;

namespace HealerACR.Common;

/// <summary>
/// **全进程共享的绘制频率门** —— 防止"同一帧被画几十次"。
///
/// ══════════════════════════════════════════════════════════════════
///  [!] 为什么需要（用户实测）
///      「进本后一开始绘制页面有闪烁」+ 日志里 `[面板] 路标` 的累计次数
///      在 30 秒内到了 **20,722 次**（约 680 次/秒）。
///      而 ImGui 一帧最多画 60 次 ⇒ **同一帧被画了 10 次以上**。
///      · 闪烁：同一个窗口一帧内被 Begin/End 多次 ⇒ 视觉上就是闪
///      · 卡顿：每次绘制都跑 13 个 ImGui 子段 + 6 个反射委托
///
///  [!] 为什么**不能用**原来的 8ms 门（两个原因）
///      ① 它用 `AEAssist.Helper.TimeHelper.Now()`，而那个东西的语义**无法确认**
///         （不是 Stopwatch、不是 TickCount64，也没有文档）。
///         实测：门设成 8ms，面板仍被画 680~8800 次/秒
///         ==> 它**不是可靠的"实时毫秒"**。
///         ⚠️ 工程里有 **149 处**都在用它做节流 —— 那些节流的可靠性全部存疑，
///            这里先把这个门换成可信的计时器，别的以后单独审。
///      ② 门是"每个入口各一份静态字段"—— 本项目有 **10 个职业入口**
///         （HealerACR 5 个 + BlueWhale 5 个），框架对每个都调一次绘制
///         ==> 125 次/秒 × 10 = **1250 次/秒**。
///         ==> 所以门必须**全进程共享**，不能放在各自的入口类里。
///
///  [!] 为什么用 `Environment.TickCount64`
///      · 它是 **struct**（`long`）—— 无装箱、无分配
///      · 它**确定是毫秒**（文档明确）
///      · 它**单调递增**（不受系统时间调整影响）
///      · 它**跨程序集共享同一份系统计时器**（不是 per-assembly 的）
///      ==> 这三点正好是节流需要的全部性质。
/// ══════════════════════════════════════════════════════════════════
public static class 绘制节流
{
    /// <summary>
    /// 设置面板的最小绘制间隔（毫秒）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么是 **16ms**（≈60 次/秒）—— 由实测数字定出来
    ///
    ///      实测（连续 20 个采样点，每秒差分，来自用户日志）：
    ///          `OnDrawSetting()` = **749 次/秒**
    ///          （744 / 732 / 756 / 768 / 732 / 768 …）
    ///      而显示帧率是 60 ⇒ **同一帧里这一页被画了约 12.5 次**。
    ///
    ///  [!] 为什么是 12.5 次而不是 1 次：
    ///        AEAssist 对**每一个已加载的 ACR 入口**每帧调一次 `OnDrawSetting`。
    ///        实测日志显示加载了 **10 个入口**（小鲸鱼 5 个 + 其它 ACR）
    ///        ⇒ 10 × 60 ≈ 600~750 次/秒。
    ///
    ///  [!] 后果（与用户实测「设置面板双重曝光 / 一直在闪」完全吻合）：
    ///        那 13 个 ImGui 段（输入框 / 滑条 / 复选框 / 子页）
    ///        在**同一帧内被反复重建** ⇒
    ///          · 控件位置每遍微调 ⇒ 视觉抖动
    ///          · 同一位置画了两套不同内容 ⇒ **双重曝光**
    ///
    ///  [!] 为什么必须用**全进程共享**的静态字段（本类存在的理由）：
    ///        10 个入口各有各的 `HealerEntryBase` 静态字段是**不行**的
    ///        （每个入口各自 60 次/秒 = 600 次/秒，等于没限）。
    ///        放在这个独立静态类里 ⇒ 全进程只有一份 ⇒ **真正的每帧一次**。
    ///
    ///  [!] 为什么不用 `ImGui.GetFrameCount()`（更精确的那个）：
    ///        它**只在绘制阶段有效**；`OnDrawSetting` 的调用时机不保证落在
    ///        那个区间里，取不到就会抛 ⇒ 退回"每帧都画"。
    ///        `Environment.TickCount64` 任何时候都能读，且是**文档明确的毫秒**。
    ///        16ms 对应约 60 次/秒，与帧率同量级。
    ///
    ///  [!] ⚠️ **不要删掉这个门**：
    ///        我一度以为"门会吃掉某些帧 ⇒ 窗口消失 ⇒ 闪"，于是把它删了 ——
    ///        **那是错的**：`OnDrawSetting` 是**每帧被调十几次**的，
    ///        限到"每帧一次"才是它该有的样子。
    ///        （必须每帧提交的是**悬浮窗**，不是这个面板回调。）
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private const int 面板最小间隔毫秒 = 16;

    private static long _面板上次;

    /// <summary>
    /// **这一帧该不该画设置面板**（全进程共享，见上面那段说明）。
    ///
    /// 返回 false = **跳过本次绘制**（省掉 13 个 ImGui 子段 + 数个反射调用）。
    /// </summary>
    public static bool 该画面板()
    {
        try
        {
            var 现在 = Environment.TickCount64;
            if (现在 - _面板上次 < 面板最小间隔毫秒) return false;
            _面板上次 = 现在;
            return true;
        }
        catch
        {
            return true;   // 出错就画（宁可多画，也不要"面板不显示"）
        }
    }

    /// <summary>诊断用：当前距上次绘制过了多久（毫秒）。</summary>
    public static long 距上次面板毫秒()
    {
        try { return Environment.TickCount64 - _面板上次; }
        catch { return 0; }
    }
}
