using System;

namespace HealerACR.Common;

/// <summary>
/// **"这个 ACR 现在正在被使用"的心跳**。
///
/// ══════════════════════════════════════════════════════════════════════════
///  [!] 为什么需要它（用户明确要求 + 一次失败的设计）
///
///      用户原话：「我要的是**只有 BlueWhale 被加载使用的时候**
///                 才出现这个调试窗口」
///
///      我第一版的做法是：在 `调试窗`（BlueWhale 侧）放一个静态标志
///      `_ACR已加载`，由入口侧反射调 `标记已加载()` 置 true。
///      **它失败了**，而且失败得毫无声息 —— 日志里一条线索都没有。
///
///  [!] 为什么失败：**`HealerACR.Common.*` 的静态字段在这个进程里有【两份】**
///      （`BlueWhale.csproj` 编译了 HealerACR 的源码）。
///      而"置标志"和"读标志"如果**跨了程序集**，就是各改各的那一份 ——
///      看起来完全正确，实际互不相干。这个坑本项目已犯过 **三次**：
///        · `绘制节流`      ⇒ 全进程绘制门被穿过
///        · `调试窗全局开关` ⇒ 设置里取消勾选无效
///        · 本类取代的那个 `_ACR已加载` ⇒ 调试窗永远不画（本次）
///
///  [!] ✅ 正确做法：**不要跨程序集传"状态"，只传"结论"。**
///      · 本类只做一件小事：入口侧在**真的画调试窗的那一刻**打一个时间戳
///      · 读时间戳的是**同一个程序集里**的代码（同一个 static 实例）
///      · 窗口侧不做任何跨程序集判断，结论由调用方作为**参数**传进去
///
///  [!] 为什么用"心跳（时间戳）"而不是"布尔标志"：
///      布尔标志一旦被置 true 就**永远是 true**（没有谁负责复位），
///      ACR 卸载后窗口还会一直画。
///      心跳会**自己过期** —— 只要入口侧不再打戳，窗口在 2.5 秒内自动消失。
///      这同时满足了卸载与"切到别的 ACR"两种情况，**不需要卸载钩子**。
/// ══════════════════════════════════════════════════════════════════════════
/// </summary>
public static class 调试窗心跳
{
    /// <summary>心跳超过这么久没更新 ⇒ 认为"这个 ACR 已经不在用了"。</summary>
    private const long 有效毫秒 = 2500;

    [ThreadStatic] private static long _上次打戳;

    /// <summary>
    /// **打一次心跳**（入口侧在真的画调试窗的那一刻调）。
    ///
    /// [!] 为什么是 `[ThreadStatic]`：绘制回调固定在渲染线程上跑，
    ///      而"ACR 是否在用"是**那个线程**的事。用线程静态可以避免
    ///      其他线程偶然打戳造成"看起来还在用"。
    /// </summary>
    public static void 打戳()
    {
        try { _上次打戳 = Environment.TickCount64; } catch { }
    }

    /// <summary>
    /// **这个 ACR 现在在用吗**（最近 2.5 秒内打过戳）。
    ///
    /// [!] 只能由**打戳的同一侧**调用（否则又是两份静态）。
    ///      当前调用方：`HealerEntryBase.画调试窗()`（与 `打戳()` 同程序集一份）。
    /// </summary>
    public static bool 在用
    {
        get
        {
            try
            {
                var 上次 = _上次打戳;
                if (上次 == 0) return false;
                return Environment.TickCount64 - 上次 <= 有效毫秒;
            }
            catch { return false; }
        }
    }

    /// <summary>当前心跳的原始毫秒戳（诊断用；0 = 从没打过）。</summary>
    public static long 上次毫秒 => _上次打戳;
}
