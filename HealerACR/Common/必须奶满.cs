namespace HealerACR.Common;

/// <summary>
/// 「必须奶满」类副本机制 —— **不奶满就会死**。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 这是什么机制 ★
///
///    某些副本会给队友挂一个 **必须把血奶到满** 才解除的 debuff，
///    效果结束前没奶满 → 直接变僵尸 / 石化 / 无法战斗。
///
///    这跟"血少了要奶"完全不是一个东西：
///      · 普通掉血：**血量低**才需要奶
///      · 这类机制：**血量可能还很健康**，但必须**奶到满**才解除
///    如果只按血线判断，AI 会觉得"这人 80% 血没事" → 时间到 → 人没了。
///
///    所以必须**单独识别**，并且给 AI 一份明确的说明。
///
///  ★ 数据来源（不是凭印象）★
///
///    `Status.csv` 的 **Description** 直接写明了机制，例如：
///      · 370  塞壬的歌声：「在效果结束之前**如果体力没有恢复到最大值**便会变成僵尸」
///      · 1628 渐渐石化：  「不断石化，**体力完全恢复时**效果解除」
///    这两条是"必须奶满"的教科书式定义，直接采用。
///
///  ⚠️ **明确排除**的几个（曾经差点被误收）：
///      · 811 死而不僵 / 3255 出死入生 / 2303 纯正死而不僵
///        —— **版本更新后不再需要奶满**（同类 ACR 的表里也没有它们）。
///        硬把 811 当"必须奶满"会把坦克的正常减伤循环搅乱。
///      · 210 / 1769 死亡宣告 —— 描述只说"倒计时为 0 时无法战斗"，
///        **解除条件是驱散，不是奶满**。走 `Res_Esuna` 那条路。
///
///  ══════════════════════════════════════════════════════════════════
///  ★★ 保守策略：**ID + 名字 双保险** ★★
///
///    只认 ID 有个风险：游戏里 **ID 复用很常见**，同一个 ID
///    在不同副本/版本里可能是完全不相干的东西。
///    一旦撞上，我们就会"对着一个无关 buff 猛灌治疗"。
///
///    所以这里多加一道**名字核对**：读出目标身上那个 aura 的**实际名字**，
///    必须和我们记录的名字（或别名）一致，才认为它真是这个机制。
///
///    为什么不按地图限定（同类 ACR 的做法）：
///      要按地图限定就得知道"这机制出在哪张图"，而这需要一个小型
///      副本名→ZoneId 对照表。我们的 `dump_territory.tsv` 里只有
///      「区域名 + 地名」，**没有可靠的副本名** —— 硬填就是猜。
///      而**猜错地图 ID 的后果是机制彻底失效**（人直接死），
///      比名字核对的漏判严重得多。所以选了名字核对这条更可靠的路。
///
///    **名字核对不通过 → 当作不是这个机制，按普通治疗走。**
///    （漏判的代价是"回到改动前的行为"，误判的代价是"治疗被一个无关 buff 骗走"。）
///
///  ══════════════════════════════════════════════════════════════════
///  ★★ 本地优先：这个判断**不依赖 AI** ★★
///
///    识别（本类）和处理（`Res_HealSingleGcd` 的优先级 30）**全在 HealerACR 本地层**。
///    AI 那侧（`AiSituation`）只是把结果**读出来转述**给模型，不参与判断。
///
///    已验证：`HealerACR` 对 BlueWhale 的编译期引用是 **0 处**
///    （`记忆钩子.cs` 里那一处是注释），且该工程**能单独编译通过**。
///
///    所以下面这些情况，机制照样生效：
///      · 没填 API Key / AI 未配置
///      · 断网 / 请求超时 / 三层熔断降级
///      · DeepSeek 返回了胡说八道（白名单会丢，但本地判断不受影响）
///    **AI 是增强层，不是必需品** —— 这是本项目的既定原则，新功能都要守住。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 必须奶满
{
    /// <summary>
    /// 必须奶满的状态表。
    ///
    /// <c>别名</c> 用于容忍中英文 / 版本差异 —— **任意一个名字对上就算命中**。
    /// 留空表示"只要 ID 对上就行"（不确定名字时才这么用）。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  这份清单是**把整个 Status 表按描述关键词扫了一遍**得到的，
    ///  不是零散抄来的。扫描判据：「体力完全恢复 / 恢复到最大 /
    ///  得到足够 / 同等恢复量」——
    ///  **全表 5251 条里只有 5 条命中**，其中 2 条是坦克的（已排除）。
    ///
    ///  ⚠️ 排除记录（别再手贱加回来）：
    ///    · 811 死而不僵 —— 虽命中关键词，但它是**坦克无敌**，
    ///      且版本更新后**不再需要奶满**
    ///    · 2303 纯正死而不僵 —— 同上，多变迷宫版
    ///    · 1605 混沌之土 —— 解除条件是"受到使体力为 0 的伤害"，
    ///      **不是奶满**（而且它让治疗完全失效，奶也奶不动）
    ///    · 全部「死亡宣告」变体（1769 / 210 / 910 / …18 个）——
    ///      在**当前版本**的 Status 表里它们的描述只有
    ///      「倒计时为 0 时会陷入无法战斗状态」，**没有"体力完全恢复"那句**。
    ///      所以它们是**驱散型**，走 `Res_Esuna`。
    ///      （旧版本曾把 1769 写成奶满型，已核对当前表推翻。）
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static readonly (uint Id, string 主名, string[] 别名)[] 表 =
    {
        // 塞壬的歌声：效果结束前没奶满 → 变僵尸
        (370u, "塞壬的歌声", new[] { "Siren's Song", "Sirensong", "塞壬之歌" }),

        // 渐渐石化：不断石化，体力完全恢复时解除
        (1628u, "渐渐石化", new[] { "Gradual Petrification", "Petrification", "石化" }),

        // 混沌之泥土：所有体力恢复效果降低（治疗量减半），体力完全恢复时解除
        //   ⚠️ 这条最难：治疗量被砍一半，要留出更多 GCD
        (1604u, "混沌之泥土", new[] { "Chaotic Mud", "混沌之泥" }),
    };

    /// <summary>
    /// 这个状态下，要不要按"必须奶满"处理。
    ///
    /// ⚠️ <paramref name="目标"/> 为空时**只按 ID 判断**（无法核对名字）。
    ///    调用方应该尽量传目标 —— 传了才会走双保险。
    /// </summary>
    public static bool 是必须奶满状态(uint 状态Id, IBattleChara? 目标 = null)
    {
        if (状态Id == 0) return false;

        try
        {
            foreach (var 项 in 表)
            {
                if (项.Id != 状态Id) continue;

                // 没有目标 → 没法核对名字，只能信 ID（保守起见仍放行，
                // 因为漏判的代价是人死；但调用方都会传目标）
                if (目标 == null) return true;

                return 名字对得上(目标, 状态Id, 项.主名, 项.别名);
            }
        }
        catch { }

        return false;
    }

    /// <summary>
    /// 保守核对：目标身上这个 aura 的**实际名字**必须和记录的一致。
    ///
    /// 拿不到名字时返回 false（= 不认）—— **这是有意的**：
    /// 保守策略宁可漏判（退回普通治疗，人还有机会被血量判断救到），
    /// 也不要误判（把所有治疗都砸在一个无关 buff 上，真正掉血的人没人管）。
    /// </summary>
    private static bool 名字对得上(IBattleChara 目标, uint 状态Id, string 主名, string[] 别名)
    {
        var 实际 = 取状态名(目标, 状态Id);
        if (string.IsNullOrWhiteSpace(实际)) return false;   // 拿不到名字 → 不认

        if (!string.IsNullOrWhiteSpace(主名) && 实际.Contains(主名)) return true;

        if (别名 != null)
        {
            foreach (var a in 别名)
            {
                if (string.IsNullOrWhiteSpace(a)) continue;
                if (实际.Contains(a)) return true;
            }
        }

        return false;
    }

    /// <summary>
    /// 从目标身上取出指定 aura 的**显示名**。
    ///
    /// 走 Dalamud 的 StatusList（AEAssist 也是这么读的），
    /// 拿不到返回空串。
    /// </summary>
    private static string 取状态名(IBattleChara 目标, uint 状态Id)
    {
        // ══════════════════════════════════════════════════════════════════
        //  ★★ **读 `StatusList` 之前必须先验对象有效性 —— try 挡不住崩溃** ★★
        //
        //  [!] 本项目为这个模式**崩过三次**（`0xc0000005`）：
        //      读已释放对象的 `StatusList` 会踩在坏内存上，
        //      而那是**原生访问违例**，**穿透 C# 的 catch** —— 加 try 从原理上无效。
        //
        //  [!] 尤其要挡的是 Dalamud 的**释放哨兵地址 `0x12345679`**：
        //      它**不是 0**，所以 `!= IntPtr.Zero` 之类的判据会**放行**它。
        //      `对象有效()` 里已经按**范围**筛（见 `CharacterExt` 的长注释）。
        //
        //  [!] 这里原来只有 `try` + `列表 == null` —— 两者都挡不住上面那种情况。
        //      `StatusList` 是**唯一一个会真的读到游戏内存**的属性（`CurrentHp` 那些
        //      读的是结构体字段，不遍历），所以这个守卫是必须的。
        // ══════════════════════════════════════════════════════════════════
        if (!目标.对象有效()) return "";

        try
        {
            var 列表 = 目标.StatusList;
            if (列表 == null) return "";

            foreach (var s in 列表)
            {
                if (s == null) continue;
                if (s.StatusId != 状态Id) continue;

                // ⚠️ Status.GameData 是 RowRef<Status>（struct），**不能用 ?.**
                //    取不到就抛异常，靠外层 catch 兜住
                var 名 = s.GameData.Value.Name.ToString();
                return string.IsNullOrWhiteSpace(名) ? "" : 名;
            }
        }
        catch { }

        return "";
    }

    /// <summary>这个队友身上有没有"必须奶满"的状态；返回命中的状态 ID（0 = 没有）</summary>
    public static uint 命中状态(IBattleChara? 目标)
    {
        if (目标 == null) return 0;

        try
        {
            foreach (var 项 in 表)
            {
                if (项.Id == 0) continue;
                // ★ 读 buff 前判有效性：HasAura 走 StatusList，原生违例会穿透 catch
                if (目标 == null || !目标.对象有效()) continue;
                if (!目标.HasAura(项.Id)) continue;      // 没有这个 aura，跳过
                if (是必须奶满状态(项.Id, 目标)) return 项.Id;
            }
        }
        catch { }

        return 0;
    }

    /// <summary>有没有人正处在"必须奶满"状态</summary>
    public static bool 有人需要奶满() => 找目标() != null;

    /// <summary>
    /// 找出**最该被奶满**的队友。
    ///
    /// 选择规则：谁的这个 debuff **剩余时间最短**谁最急
    /// （时间一到就死，所以按紧迫度排，而不是按血量排）。
    /// 拿不到剩余时间时退回"血量最低的那个"。
    /// </summary>
    public static IBattleChara? 找目标()
    {
        using var _深度 = HealerACR.Common.调用深度.进("必须奶满.找目标");
        try
        {
            IBattleChara? 最优 = null;
            var 最优剩余 = float.MaxValue;

            // 自己也可能中这个机制
            foreach (var 队员 in 候选())
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (队员 == null || !队员.对象有效()) continue;

                var 状态 = 命中状态(队员);
                if (状态 == 0) continue;

                // ══════════════════════════════════════════════════════
                //  ★ 必须用 `fromMe: false` 读剩余时间（审计发现的 bug）★
                //
                //  ── 原来是 `我的Buff剩余秒(状态)`，它内部是
                //     `GetAuraTimeleft(target, id, fromMe: true)` —— **只看我挂的**。
                //
                //     而这些 debuff（370 塞壬的歌声 / 1628 渐渐石化 /
                //     1604 混沌之泥土）**都是敌人挂的** →
                //     fromMe 那条路永远匹配不上 → **一律返回 0**。
                //
                //  ── 后果 ──
                //     所有人并列 0 → `剩余 < 最优剩余` 只在**第一个人**身上成立
                //     → 实际是"候选列表里第一个"（自己优先、再按队伍顺序），
                //     **不是最急的那个**。两个队友同时中招时可能先救错人 ——
                //     而这个机制的判据就是"时间到就死"，救错等于放弃一个。
                //
                //    顺带：`if (剩余 < 0f)` 也是死代码（该 API 查不到返回 0，不是负数）。
                //
                //  ⚠️ 所以这里改成**按状态列表直接找**那条 debuff 的剩余时间，
                //     不看是谁挂的。`所有状态剩余` 已经在用同样的读法。
                // ══════════════════════════════════════════════════════
                var 剩余 = float.MaxValue;
                try
                {
                    foreach (var st in HealerACR.Common.CharacterExt.所有状态剩余(队员))
                    {
                        if (st.Id != 状态) continue;
                        剩余 = st.剩余秒;
                        break;
                    }
                }
                catch { }

                if (剩余 < 最优剩余)
                {
                    最优剩余 = 剩余;
                    最优 = 队员;
                }
            }

            return 最优;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>候选：所有可治疗的队友 + 自己</summary>
    private static List<IBattleChara> 候选()
    {
        var 结果 = new List<IBattleChara>(8);

        try
        {
            if (CharacterExt.我还活着()) 结果.Add(Core.Me);

            var 队友 = PartyHelper.CastableAlliesWithin30;
            if (队友 != null)
            {
                foreach (var r in 队友)
                {
                    // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                    if (r == null || !r.对象有效()) continue;
                    if (r.GameObjectId == CharacterExt.我的ObjectId()) continue;   // 自己已经加过
                    if (!r.可以治()) continue;
                    结果.Add(r);
                }
            }
        }
        catch { }

        return 结果;
    }

    /// <summary>
    /// 「必须奶满」时该用的**能力技** —— 只挑"一次到满"那类。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么不能直接用 `JobSpellTable.紧急单奶` ★
    ///
    ///    那张表里有些技能**在目标血高时是无效的**：
    ///      · 学者 `深谋远虑之策(7434)` —— 挂个 buff，**血量降到阈值才触发**。
    ///        中 Doom 的人血量还很高 → 它根本不触发 → 等于没治。
    ///      · 占星 `先天禀赋(3614)` —— 治疗量**随目标血量降低而提高**。
    ///        血越高奶得越少 → 血高时救不了命。
    ///
    ///    而「体力完全恢复」型（370/1604/1628）要求**某一刻真的到满血**，
    ///    所以必须挑**与当前血量无关**的技能。白魔的 `天赐祝福(140)`
    ///    正是这类（直接把 HP 设为 100%），这也是同类 ACR 把它排在
    ///    奶满序列第一位的原因。
    ///
    ///    ⚠️ 拿不到"一次到满"的技能时返回 0 —— 由调用方回退到
    ///      GCD 治疗链（那条路一定有效，只是慢）。
    ///      宁可慢，也不要交一个**注定不触发**的技能。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static uint 最该用的能力技(JobSpellTable 表)
    {
        if (表 == null) return 0;

        try
        {
            switch (表.Job)
            {
                // 白魔：天赐祝福 = 直接把目标 HP 设为 100%（一次到满）
                case Jobs.WhiteMage:
                    return SpellUtil.已解锁(SpellIds.取("天赐祝福")) ? SpellIds.取("天赐祝福") : 0u;

                // 学者：生命活性法(189) 是即时大治疗；
                //       深谋远虑之策(7434) **不算** —— 它要血降到阈值才触发
                case Jobs.Scholar:
                    return SpellUtil.已解锁(SpellIds.取("生命活性法")) ? SpellIds.取("生命活性法") : 0u;

                // 贤者：白牛清汁(24303) 即时单体大治疗
                case Jobs.Sage:
                    return SpellUtil.已解锁(SpellIds.取("白牛清汁")) ? SpellIds.取("白牛清汁") : 0u;

                // 占星：先天禀赋随血量降低而增强，**血高时救不了**
                //       → 没有"一次到满"的能力技，返回 0 让调用方走 GCD 治疗链
                case Jobs.Astrologian:
                default:
                    return 0;
            }
        }
        catch
        {
            return 0;
        }
    }

    /// <summary>
    /// 「必须奶满」序列里**第 2 发**的候选（按顺序；越靠前越先放）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 语义照抄参考 IL ★
    ///    `ACR.Scholar.Resolvers.Strategy.学者奶满策略` 的
    ///    `QueueEmergencyActions(Slot)`（IL 直证）：
    ///      · 停手门槛：`BattleData.HighPrioritySlots_OffGCD.Count >= 2` ⇒ 直接 `ret`；
    ///      · 顺序：先 `秘策(16542)`（QT「秘策」开 **且** `IsReady(16542,1)`）
    ///              → 再 `应急战术(3586)`（`IsReady(3586,1)`）；
    ///      · **两发都 `Slot::Add` 进同一个 slot**（不是每帧只挑一个）。
    ///
    ///  [!] `秘策` 在本工程已由 `Res_AllExtra` / `ScholarACR` **单独负责**
    ///      （见那里的 `每技能注册(16542)`）—— 这里再排一次会**双排**，
    ///      所以本序列只提供**第 2 发**（学者 = 应急战术）。
    ///
    ///  [!] 其余职业（白魔 / 贤者 / 占星）的"第 2 发"**未做** ⇒ 返回空表，
    ///      调用方退化成"只放第 1 发"（= 改动前的行为，不会变差）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static List<uint> 助手能力技序列(JobSpellTable 表)
    {
        var 结果 = new List<uint>(1);
        if (表 == null) return 结果;

        try
        {
            if (表.Job != Jobs.Scholar) return 结果;

            var 技 = SpellIds.取("应急战术");
            if (技 != 0 && SpellUtil.已解锁(技)) 结果.Add(技);
        }
        catch { }

        return 结果;
    }

    /// <summary>
    /// 给 AI 看的一段描述。
    ///
    /// ⚠️ **必须明确写出"这不是按血线判断"** ——
    ///    否则 AI 会按常识回一句"目标血量健康，不需要治疗"，
    ///    而这正是这个机制最危险的地方。
    /// </summary>
    public static string 状态描述()
    {
        try
        {
            var 目标 = 找目标();
            if (目标 == null) return "";

            var 状态 = 命中状态(目标);
            var 名 = SpellIds.反查(状态);
            if (string.IsNullOrEmpty(名)) 名 = "状态 " + 状态;

            // ══════════════════════════════════════════════════════════════
            //  [!] **不能用 `我的Buff剩余秒`** —— 那是 `fromMe: true`（只看我挂的），
            //      而"必须奶满"这三种 debuff 都是**敌人挂的** => 永远匹配不上
            //      => 返回 -1 => 下面 `剩余 >= 0f` 为假 => **"剩余 X 秒"整段消失**。
            //
            //      实测后果：AI 看得到"有人中了致死状态"，但**完全不知道还剩多久** ——
            //      而这是个"到点就死"的机制，剩余时间是它唯一的紧迫度依据。
            //
            //  [!] `找目标()` 已经为此改过（用 `所有状态剩余`），
            //      但这里没跟着改 —— 修一处忘一处。
            //      现在两处读法统一。
            // ══════════════════════════════════════════════════════════════
            var 剩余 = -1f;
            try
            {
                foreach (var st in HealerACR.Common.CharacterExt.所有状态剩余(目标))
                {
                    if (st.Id == 状态) { 剩余 = st.剩余秒; break; }
                }
            }
            catch { }

            var 血 = 目标.血量比例() * 100f;

            var sb = new System.Text.StringBuilder();
            sb.AppendLine(" 【必须奶满机制】有人中了会致死的状态，**必须把血奶到 100% 才能解除**");
            sb.AppendLine($"   目标：{目标.Name}  当前血量 {血:F0}%  状态：{名}（{状态}）"
                          + (剩余 >= 0f ? $"  剩余 {剩余:F1} 秒" : ""));
            sb.AppendLine("    判断依据**不是血量**：就算这个人血量看着健康，只要这个状态还在，"
                          + "效果结束时会直接无法战斗 / 变僵尸。");
            sb.AppendLine("   正确处理：**优先对他使用治疗量最大的单体治疗**，直到状态消失。");
            sb.AppendLine("    不要因为\"他血还挺多\"而把治疗给别人 —— 这是这个机制唯一的解。");

            return sb.ToString();
        }
        catch (Exception e)
        {
            return "（必须奶满状态读取失败：" + e.Message + "）" + Environment.NewLine;
        }
    }
}
