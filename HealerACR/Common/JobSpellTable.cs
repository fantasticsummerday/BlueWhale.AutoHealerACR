using AEAssist.CombatRoutine;

namespace HealerACR.Common;

/// <summary>
/// 职业技能表：把"四个奶妈的差异"全部收敛到这一个抽象里。
/// 技能 ID 全部走 <see cref="SpellIds.取"/>（内置表，中文名，已用 Lumina dump 核对）。
/// </summary>
public abstract class JobSpellTable
{
    public abstract Jobs Job { get; }
    public abstract string 职业名 { get; }

    // ---------------- 输出 ----------------

    public abstract uint 基础输出 { get; }
    public abstract uint 群体输出 { get; }

    /// <summary>DoT 技能（写当前可用的最高级，用 取已解锁 链）</summary>
    public abstract uint Dot技能 { get; }

    /// <summary>DoT 的 buff id（满级那个）</summary>
    public abstract uint DotBuff { get; }

    /// <summary>
    /// **所有等级段**的 DoT buff id。
    ///
    /// ⚠️ 踩过的坑：DoT 升级会换 buff id
    ///    （占星 烧灼838 → 炽灼843 → 焚灼1881，学者 毒菌179 → 猛毒菌189 → 蛊毒法1895）。
    ///    只检查一个的话，满级用的是最高级 DoT，buff 对不上 → 永远认为"没上 DoT" → 无限补。
    ///    所以这里把所有等级段都列出来，只要身上有其中任意一个就算"已上 DoT"。
    /// </summary>
    public virtual uint[] 所有DotBuff => DotBuff != 0 ? new[] { DotBuff } : Array.Empty<uint>();

    /// <summary>要卡 CD 打的输出能力技（学者的能量吸收这种），空数组表示没有</summary>
    public virtual uint[] 输出能力技 => Array.Empty<uint>();

    /// <summary>
    /// 现在是不是处于"基础输出被游戏替换掉"的状态。
    /// 典型例子：白魔神速咏唱期间闪灼被替换成闪飒，硬放闪灼会直接失败。
    /// </summary>
    public virtual bool 有特殊输出形态 => false;

    // ---------------- 治疗 ----------------

    public abstract uint 单体治疗GCD { get; }
    public abstract uint 群体治疗GCD { get; }
    public abstract uint 紧急单奶 { get; }
    public abstract uint 群体治疗能力技 { get; }

    /// <summary>
    /// **单体持续治疗（HoT）** —— 再生（白魔 137）/ 吉星相位（占星 3595）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么要开这一栏 ★
    ///
    ///  现象："最后移动中掉血的情况完全可以上再生，
    ///            而不是等不动了硬读 gcd 奶"
    ///
    ///  ── 两个问题叠在一起 ──
    ///    ① **AI 看不到再生** —— `采可选技能` 没列这一栏，
    ///       所以它移动中一直说"无瞬发技能可用，等站定"，
    ///       而再生**就是瞬发的**（放了 53 次，但全是本地层放的）。
    ///    ② **本地层移动中也不放** —— `Res_SingleHoT` 里
    ///       "有人 <35% 就让路给直疗"那条，在移动中是错的：
    ///       直疗要读条、移动中根本放不出 → 两个都不放，一直等站定。
    ///
    ///  ⇒ 开这一栏有两个作用：
    ///     · 喂给 AI（它才知道移动中能挂 HoT）
    ///     · 让"是不是 HoT"这件事有个**唯一来源**，不必在别处硬编码
    ///
    ///  ⚠️ 这一栏和 `瞬发单奶能力技` 的区别：
    ///     这个是 **GCD** 的 HoT（占一个 GCD，但瞬发），
    ///     那个是**能力技**（不占 GCD）。两者移动中都可用，
    ///     但代价完全不同 —— 所以不能合并成一栏。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual uint 单体HoT { get; } = 0;

    /// <summary>
    /// **药尾声用的瞬发填充技**（0 = 这个职业没有）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 参考实现 A 四职业统一的"药尾声补刀"（对照分析发现的缺口）★
    ///
    ///  ── 它们怎么做的（IL 直证）──
    ///    白魔 `即刻闪灼` / 学者 `即刻极炎法` /
    ///    贤者 `即刻注药` / 占星 `即刻落陷凶星`
    ///    启用条件都是 `HasAura(49 强化药) && BuffTimeLessThan(49, 3000)`，
    ///    命中后放「即刻咏唱 + 下面的瞬发填充」，权重 15。
    ///
    ///  ── 为什么值得做 ──
    ///    爆发药是整个爆发窗口的时钟。药快过期时用即刻把**最后一发**塞进去，
    ///    等于白赚一个 GCD 的增伤。我们原来磕完药就当没这回事。
    ///
    ///  ⚠️ 和 `移动填充技` 的区别：
    ///    那个是"移动中**原生**瞬发"的填充（四奶里只有学者的毁坏符合）；
    ///    这个是"靠**即刻咏唱**临时变瞬发"的填充，各职业都取自己的主力输出技。
    ///    两者可以指向同一个技能（学者：毁坏），也可以不同（白魔：闪灼）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual uint 药尾声填充技 => 0;

    /// <summary>
    /// **预铺类**单体能力技 —— 伤害/掉血**之前**给才有价值的那一类。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么要单独开一栏 ★
    ///
    ///    现象："治疗应该优先能力技（不用读条的），
    ///             比如学者可以给 T 上绿帽而不是狂读单盾"
    ///
    ///    日志实证（他的那一场）：
    ///        鼓舞激励之策（单盾，读条）  61 次
    ///        生命活性法（能力技）         6 次
    ///        **深谋远虑之策（绿帽）       0 次**
    ///
    ///  ── 根因 ──
    ///    绿帽原来被塞在 `紧急单奶` 这一栏里：
    ///        `紧急单奶 => 取已解锁(深谋远虑之策, 生命活性法)`
    ///    而"紧急单奶"的判据是 `紧急单奶阈值 = 0.30`（血 < 30% 才交）。
    ///    日志里坦克一直在 **80%** —— 于是**永远不触发**。
    ///
    ///    **但绿帽的设计用途恰恰是"提前给"**：
    ///      45 秒 CD，给目标挂上，等它掉到阈值以下**自动触发**治疗。
    ///      它的价值在"预铺"，不是在"急救"。
    ///      放进急救栏 = 用错分类，等于这个技能不存在。
    ///
    ///  ⚠️ 为什么不能简单"把紧急单奶阈值调高"：
    ///      那会让**所有**急救技能都在 80% 就交掉（天赐祝福、先天禀赋…），
    ///      是更严重的浪费。分类错了就得改分类，不是改阈值。
    ///
    ///  ⚠️ 这一栏给的是"**目标**"技能；实际交不交由 `Res_ProactiveAbility`
    ///      按"伤害要来 / 坦克在掉血"判断。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual uint 预铺单奶能力技 { get; } = 0;

    /// <summary>
    /// **瞬发**单体治疗能力技（不读条、能移动中用的）。
    ///
    /// 用途：移动中/需要快速补一口时优先用它，而不是硬读 GCD 治疗。
    /// 和 <see cref="紧急单奶"/> 的区别：这个不要求"濒死"，
    /// 只要"有人掉血且我需要一个不读条的治疗"就可能交。
    /// </summary>
    public virtual uint 瞬发单奶能力技 { get; } = 0;

    /// <summary>
    /// 瞬发单奶的触发血线（默认 0.75）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么要有这个、而且默认 0.75（参考实现 IL 直读）★
    ///
    ///  参考实现的白魔把"常规瞬发补血"和"保命急救"**分成两个独立 resolver、
    ///  两个独立阈值**：
    ///      神名（60 秒 CD、**有充能**）→ 阈值 **75%**  ← 常规补血
    ///      天赐祝福（180 秒 CD、一次到满）→ 阈值 **20%**  ← 救命
    ///
    ///  它**不用"二选一"** —— 所以不会出现"谁等级高就永远是它"。
    ///
    ///  ⚠️ 我们这里踩过**第三次**同类坑：
    ///      `瞬发单奶能力技 => 取已解锁(神名, 天赐祝福)`
    ///      60 级以后两个都解锁 → `取已解锁` 永远返回**神名** →
    ///      天赐变成死代码；而且常规补血会去花 180 秒 CD 的保命大。
    ///      （前两次：`紧急单奶` 写反、`单体治疗GCD` 把群疗「愈疗」当单体。）
    ///
    ///  ⇒ 正确结构：**两个槽位、两条血线**。
    ///     瞬发槽（75%）用便宜的充能技；急救槽（`紧急单奶阈值`）用保命大。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual float 瞬发单奶血线 => 0.75f;

    /// <summary>群体治疗能力技是不是"输出型"（白魔法令）—— 这种卡 CD 打，不等掉血</summary>
    public virtual bool 群体治疗能力技是输出型 => false;

    public virtual uint 单体盾 { get; } = 0;
    public virtual uint 群体盾 { get; } = 0;
    public virtual uint 护盾前置 { get; } = 0;

    // ---------------- 减伤 ----------------

    public virtual uint 团队减伤 { get; } = 0;
    public virtual uint 个人减伤 { get; } = 0;

    // ---------------- 通用 ----------------

    public abstract uint 复活 { get; }
    public abstract uint 驱散 { get; }
    public abstract uint 醒梦 { get; }

    /// <summary>
    /// 放 AOE 至少要有几个敌人。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ⚠️ 从 3 降到 2（对照同类 ACR 的实测值）
    ///
    ///    原来写死 3，四个职业全部继承、没人覆写。问题是**日随一波小怪
    ///    常常只有 2 只** —— 按 3 判就一直在打单体，AOE 永远不触发。
    ///
    ///    对照值（从同类 ACR 的 IL 直读）：
    ///      · 白魔/占星系 = 82 级前 2，82 级后 3    ///      · 学者/贤者系 = 54 级前 1，54 级后 2
    ///      · 占星系      = 2
    ///    共同点是**低等级更宽松**（低等级 AOE 威力占比更高、怪也更容易成堆）。
    ///    这里取 2 作为统一值 —— 比"按等级分档"简单，且对日随足够。
    ///
    ///    代价：只有 2 个敌人时用 AOE，纯单体收益可能略低一点点。
    ///    但"两只怪还在打单体"是更常见、更明显的损失。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual int AOE最少敌人数 => 2;

    /// <summary>
    /// **AOE 门槛（按等级）** —— 方法名和属性 `AOE最少敌人数` 区分开
    /// （C# 不允许属性与方法同名：`error CS0102`）。 —— 恰好 N 只怪时群体技是否真的更优。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要按等级（算术核实）★
    ///
    ///    `AOE最少敌人数` 写死 **2**，但恰好 2 只怪时
    ///    **群体技在某些等级段是负收益**：
    ///
    ///      白魔 72-82：神圣 140×2=280  <  闪耀 290        -> 负 3.4%
    ///      白魔 82-94：豪圣 150×2=300  <  闪灼 310        -> 负 3.2%
    ///      白魔 94+  ：豪圣 150×2=300  <  闪灼 350        -> 负 14.3%
    ///      贤者 94+  ：失衡II 170×2=340 < 注药III 380     -> 负 10.5%
    ///      学者 82+  ：裂阵法 180×2=360 >  极炎法 295/320 -> 正，保持 2
    ///      占星 82+  ：中重力 140×2=280 >  落陷凶星 250/270 -> 正，保持 2
    ///
    ///  [!] 而且**门槛就是唯一判据** —— 项目已证"仲裁只看行号"，
    ///      `Res_AoEDamage` 恒排在 `Res_BaseDamage` 之前 ⇒
    ///      `选填充技` 里那个更精确的"威力 × 命中数"比较**没机会纠偏**。
    ///
    ///  [!] 默认返回 `AOE最少敌人数`（2）—— 不改任何职业的现有行为，
    ///      只有明确算出负收益的职业才覆写。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★★ **这里故意和参考实现不同 —— 不要"照抄参考"把它改坏** ★★
    ///
    ///  [!] 参考实现（youshu IL 实证）四个职业**全是** `等级 >= 82 ? 3 : 2`：
    ///        裂阵法(学者) / 中重力(占星) / 豪圣(白魔) / 失衡(贤者)
    ///
    ///  [!] **判据必须写成"两边在同一个敌人数下比"**（这里早期写错过一次）：
    ///      要问的是：**如果跟参考（门槛 3），那 2 只怪时它打什么？**
    ///        · 门槛 3 ==> 2 只怪时它打**单体**
    ///        · 学者：单体 极炎法 295/320   vs   我们的 AOE 裂阵法 180×2 = **360**
    ///        · 占星：单体 落陷凶星 250/270 vs   我们的 AOE 中重力 140×2 = **280**
    ///      ==> 2 只怪就该打 AOE ==> **参考的门槛 3 偏高**，保持 2 是对的。
    ///      ⚠️ 早期这里只列了"AOE 的值"（360 / 280）就下结论，
    ///         没有列"参考那时在打什么" —— **结论对，论证不成立**。
    ///         错误的论证会被下一个人当成依据，所以判据要写全。
    ///
    ///  [!] 而且我们**已经**为"真的是负收益"的那两个职业覆写了：
    ///        白魔 `等级 >= 72 ? 3 : 2`   （2 只怪：神圣 140×2=280 < 崩石系 290）
    ///        贤者 `等级 >= 94 ? 3 : 2`   （2 只怪：失衡II 170×2=340 < 注药III 380）
    ///      ==> 那两个的档位是**自己算出来的**，比参考的 82 更贴实际。
    ///
    ///  [!] 反向确认（门槛 2 的那两个职业）：1 只怪时
    ///        学者 单体 295/320  vs  AOE 180   ==> 单体高 ==> 门槛 2 正确
    ///        占星 单体 250/270  vs  AOE 140   ==> 单体高 ==> 门槛 2 正确
    ///
    ///  [!] 所以：**学者和占星不覆写（保持 2）是有意的。**
    ///      要动它，先按当前版本的威力表**重新算一遍**，别拿参考的数字当依据 ——
    ///      这正是开发约定 ⑧ 说的「错误归因的注释比没有注释更危险」的反面用法：
    ///      **正确的"为什么不跟参考"也要写下来，否则下一个人会照着参考改回去。**
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual int AOE门槛(int 等级) => AOE最少敌人数;

    /// <summary>
    /// AOE 技能的**伤害范围**（米）。各职业不一样：
    ///   白魔 神圣/豪圣 = 8、学者 破阵法/裂阵法 = 5、占星 重力/中重力 = 5、贤者 失衡 = 5
    /// 对照官方文档的 CheckNeedUseAOE 第二个参数。
    /// </summary>
    public virtual int AOE伤害范围 => 5;

    // ---------------- 资源管理 ----------------

    /// <summary>现在手上的治疗资源够不够交"能力技群奶"</summary>
    public virtual bool 治疗资源充足 => true;

    /// <summary>脱战时要提前准备的战斗资源（技能 ID），空数组 = 不需要</summary>
    public virtual uint[] 脱战准备技能 => Array.Empty<uint>();

    /// <summary>
    /// **召唤宠物**（0 = 这个职业没有宠物）。
    ///
    /// ⚠️ 为什么不塞进 <see cref="脱战准备技能"/>：
    ///    那个只在**脱战**时用（`if (Core.Me.InCombat()) return -1;`）。
    ///    而宠物在战斗中也会没 —— 被「转化」主动牺牲掉、或者被打死。
    ///    那时候不补，小仙女给的免费治疗就全没了，学者的治疗量会明显下降。
    ///
    ///     所以召唤要**独立一栏**：脱战补（进本第一件事）+ 战中没了也补。
    /// </summary>
    public virtual uint 召唤宠物 => 0;

    /// <summary>
    /// 移动中用的**瞬发填充技**，0 表示这个职业没有（那就干脆不放，别硬读条）。
    /// 四奶里只有学者的"毁坏"是纯瞬发填充。
    /// </summary>
    public virtual uint 移动填充技 => 0;

    /// <summary>
    /// **站定填充技** —— 站定时威力更高的那个填充技（默认 0 = 不用）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要（用户实测："远处应该打毁灭，而不是毁坏，少10威力"）★
    ///
    ///    `基础输出` 是 `取已解锁(...)` 链条 —— 取到的是**当前等级下
    ///    进阶最高的那个**。但那条链里 `毁坏(38)` 排在 `毁灭(1)` 前面，
    ///    所以 50 级取到的是 **毁坏（140，瞬发）**。
    ///
    ///    而 `毁坏` 是**瞬发技** —— 瞬发的代价就是威力低。
    ///    站定时该用 `毁灭（150，1.5s 读条）`，**每发多 10 威力**。
    ///
    ///    问题在于：**`毁灭` 从来不是候选**（候选只加 基础输出/群体输出/Dot），
    ///    所以 AI 看不到它，只能一直建议它唯一看得到的那个填充技。
    ///
    ///  ⇒ 加这个槽位：候选集在**站定**时把它一并列出，
    ///     AI 按威力自己挑（配合铁律 22b"读条但威力更高的更好"）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual uint 站定填充技 => 0;

    // ---------------- 近战位单体填充（"走近了打这个更疼"）----------------

    /// <summary>
    /// **贴近目标时威力更高的单体填充技**，0 = 这个职业没有。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么单独开一栏 ★
    ///
    ///  ── 现象 ──
    ///     50 级学者站在 Boss 脚下，**一直在打「毁坏」而不是「破阵法」**。
    ///
    ///  ── 为什么 ──
    ///     `破阵法`（Art of War，16539）是**以自己为中心的近战范围技**：
    ///       威力 600、半径 5 米、**瞬发**；而 `毁坏`（Ruin II）威力 500。
    ///     ⇒ 站在 3 米内时 `破阵法` **高 100 威力**（+20%），还瞬发。
    ///
    ///     但它在表里只登记成 `群体输出`，走 `Res_AoEDamage` ——
    ///     那条路要求 `AOE最少敌人数`（2 个）才用。
    ///     **单体 Boss 时永远不满足 → 永远打「毁坏」。**
    ///
    ///  ── 为什么做成"栏位"而不是写死技能 ID ──
    ///     写死会让 `Res_BaseDamage` 认识学者的具体技能，破坏分层。
    ///     做成栏位：
    ///       · 学者填 `破阵法`（82 级后 `裂阵法`）
    ///       · 别的职业留 0（白魔 `神圣` 是读条 AOE，不是这个场景）
    ///
    ///  ⚠️ **只在目标足够近时用**（见 <see cref="近战填充距离"/>）——
    ///     远了打不到，硬放等于空转一个 GCD。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual uint 近战填充技 => 0;

    /// <summary>
    /// **自身 AOE 技的候选列表**（按强弱降序，`当前形态` 会取第一个已解锁的）。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  ★ 什么是"自身 AOE 技" ★
    ///
    ///    游戏数据里 `CastType = 2` 且 `Range = 0` 且 `EffectRange > 0` ——
    ///    **以玩家自己为中心**的圆形范围攻击。实测（`tools\CastProbe`）：
    ///
    ///        学者  破阵法 16539  咏唱0.0  范围5   150/165
    ///              裂阵法 25866  咏唱0.0  范围5   180
    ///        白魔  神圣   139    咏唱1.5  范围8   140
    ///              豪圣   25860  咏唱1.5  范围8   150
    ///        贤者  失衡   24297  咏唱0.0  范围5   160
    ///              失衡II 24315  咏唱0.0  范围5   170
    ///
    ///  ⚠️ 为什么不复用 `群体输出`：
    ///    那个栏位喂给 `Res_AoEDamage`，走"**敌人数 ≥ AOE最少敌人数**"的门槛，
    ///    而且它是**以目标为中心**数的（奶妈站远程位才数得到）。
    ///    而这里要的是"以**自己**为中心数"——两者语义相反，不能混用。
    ///
    ///  ⚠️ 占星**没有**这类技能（重力/中重力都是读条 1.5~2.5 秒），
    ///    所以它留空 —— 列表里加了也会被"移动中可用"挡掉。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    public virtual uint[] 自身AOE候选 => Array.Empty<uint>();

    /// <summary>
    /// 「近战填充技」够得着的距离（米）—— 兼容旧栏位，新代码用
    /// <see cref="自身AOE半径"/> 按技能查。
    /// </summary>
    public virtual float 近战填充距离 => 3f;

    /// <summary>
    /// **某个技能是不是"自身 AOE"**，以及它的作用半径（米）。
    ///
    /// ⚠️ 半径**必须按技能查**，不能用统一值：
    ///    学者的破阵法/裂阵法是 **5** 米，白魔的神圣/豪圣是 **8** 米 ——
    ///    用统一值会算错"能打到几个敌人"，进而选错技能。
    ///
    /// ⚠️ 判据来自**游戏数据**（`CastType=2, Range=0, EffectRange`），
    ///    不是靠技能名猜 —— 名字里没有"阵"字的 AOE 照样要认得。
    ///
    /// 返回 `(是不是, 半径)`。
    /// </summary>
    public virtual (bool 是, float 半径) 自身AOE半径(uint 技能Id) => (false, 0f);

    /// <summary>
    /// **威力档位表** —— `(提升等级, 威力)` 的降序列表，用来算"当前等级下这个技能多少威力"。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  ★ 数据来源（权威）★
    ///
    ///    `游戏数据宏`（`tools\HealPotency` 的 `raw` 模式解出），逐字：
    ///        破阵法 16539:  if(学者, if(等级>=54, 165, 150), 150)
    ///        毁坏   17870:  等级>=82→220，>=72→200，>=64→180，>=54→160，否则 140
    ///        裂阵法 25866:  180（无档位）
    ///
    ///  ⚠️ 为什么必须记录**等级**而不只是威力数字：
    ///     威力档位是**交叉**的 —— 同一个技能在不同等级有不同威力，
    ///     而两个技能的相对高低会**随等级翻转**。
    ///
    ///     学者实例（这就是为什么"固定用某一个"是错的）：
    ///         46~53  破阵法 150 > 毁坏 140   ← 贴身该用破阵法
    ///         54~63  破阵法 165 > 毁坏 160   ← 还是破阵法
    ///         64~71  毁坏   180 > 破阵法 165 ← **翻转了**，该用毁坏
    ///         72~81  毁坏   200 > 破阵法 165
    ///         82+    毁坏   220 > 裂阵法 180
    ///
    ///  ⚠️ 空表 = 不做威力比较（退回"贴身就用"的旧行为）。
    ///     没填的职业不受影响。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    public virtual (int 等级, int 威力)[] 威力档位 => Array.Empty<(int, int)>();

    /// <summary>
    /// **当前等级下这个技能的威力**（查 <see cref="威力档位"/>）。
    ///
    /// ⚠️ 表里没填、或者查不到 → 返回 **0**（表示"不知道"），
    ///    调用方应当**不做比较**而不是当成 0 威力。
    /// </summary>
    public int 当前威力(uint 技能Id, int 等级)
    {
        try
        {
            var 档 = 威力表(技能Id);
            if (档 == null || 档.Length == 0) return 0;

            // 档位按**提升等级降序**排 —— 取第一个"等级够"的
            foreach (var (提升等级, 威力) in 档)
                if (等级 >= 提升等级) return 威力;

            return 0;   // 一个都不满足 → 不知道（不该发生，最后一档应为 0 级）
        }
        catch
        {
            return 0;
        }
    }
    
    /// <summary>
    /// **群攻能打中几个** —— 按技能类型**选对圆心**（治本的那个判据）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么必须有它（用户**第三次**报同一个症状）：
    ///      「50级神兵又在打 aoe」
    ///
    ///      50 级学者「破阵法」是 **自身中心 5 米** AOE（Range=0 / EffectRange=5），
    ///      但判"能打几个"原来用的是 `HealTargetHelper.周围敌人数量()` ——
    ///      那个**以当前目标为中心**数（它自己的注释写明"奶妈站远程位，
    ///      以自己为中心数不到"，那是**为目标中心 AOE 写的**）。
    ///
    ///      ==> **圆心错了**：数的是"目标周围 5 米有几个"，
    ///          而破阵法打的是"**我**周围 5 米"。
    ///          怪群在目标周围、离我 15 米 ==> 敌数数成 2 ==> 门槛放行
    ///          ==> 放出去只打中我周围 5 米内的（可能 1 个）==> **白白少打**。
    ///
    ///  [!] `HealerACR.Common.HealTargetHelper.自身周围敌人数量(半径)`
    ///      **本来就是为这个加的**（它的注释逐字写着破阵法/裂阵法的数据）。
    ///      问题只是**该用它的时候没用**。
    ///
    ///  [!] 所以集中到这一个方法里，候选集 / 终审 / 提示词 全都调它 ——
    ///      开发约定 F③：同一个决策不论从哪条路进来，判断必须一致。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public int 群攻命中数(uint 技能Id, IBattleChara? 目标 = null)
    {
        try
        {
            if (技能Id == 0) return 0;
    
            // ① 自身中心 AOE（破阵法 / 裂阵法这类）-> **以我为中心**数
            try
            {
                var (是自身, 半径) = 自身AOE半径(技能Id);
                if (是自身 && 半径 > 0f)
                    return HealTargetHelper.自身周围敌人数量(半径);
            }
            catch { }
    
            // ② 其余（目标中心 / 地面）-> 以目标为中心数，施法距离用**技能真实射程**
            var 射程 = 技能数据.取有效射程(技能Id);
            if (射程 <= 0) 射程 = 25;
            return HealTargetHelper.周围敌人数量(Math.Max(1f, AOE伤害范围), 射程);
        }
        catch
        {
            return 0;
        }
    }

    /// <summary>
    /// **这张表是不是当前职业的**。
    ///
    /// ⚠️ 为什么需要（踩过的坑）：
    ///     六个职业表都是静态的，找"当前这个"如果没有权威判据，
    ///     就会拿到**最后加载的那个**（现象：玩学者却收到幻术师的技能清单）。
    ///
    /// 判据：表的 <see cref="Job"/> 和 `Core.Me.ClassJob` 一致。
    /// 白魔/学者/占星/贤者都有对应的**基础职业**（幻术/秘术…），
    /// 所以再比一次转职前的职业 —— 低等级时 `ClassJob` 是基础职业。
    /// </summary>
    public virtual bool 是当前职业
    {
        get
        {
            try
            {
                // ⚠️ `Core.Me.ClassJob` 是 `RowRef<ClassJob>`，要取 `.RowId`
                //    （直接和 uint 比会编译不过 —— 见 `取当前职业技能表` 同款写法）
                var 我 = AEAssist.Core.Me.ClassJob.RowId;
                if (我 == (uint)Job) return true;

                // 基础职业 → 特职的映射（低等级时读到的是基础职业）
                return Job switch
                {
                    Jobs.WhiteMage => 我 == 6,      // 幻术
                    Jobs.Scholar => 我 == 26,       // 秘术
                    _ => false,
                };
            }
            catch
            {
                return false;
            }
        }
    }

    /// <summary>
    /// **公开的威力查询**（给 AI 清单用）。
    ///
    /// ⚠️ `威力表` 是 protected 的（子类填），这里转发一个 public 版本，
    ///    不暴露内部结构。查不到返回 0（调用方**不要写占位符**）。
    /// </summary>
    public int 查威力(uint 技能Id, int 等级)
    {
        try
        {
            return 当前威力(技能Id, 等级);
        }
        catch
        {
            return 0;
        }
    }

    /// <summary>
    /// **这个技能是不是治疗类**（威力含义是"恢复力"而不是"伤害"）。
    ///
    /// ⚠️ 为什么需要区分：治疗候选集里同时有伤害技（贤者注药）和
    ///    治疗技（诊断），显示时要说清楚数字是什么含义。
    /// </summary>
    public bool 是治疗技能(uint 技能Id)
    {
        try
        {
            foreach (var h in 治疗候选.全部)
                if (h.Id == 技能Id) return true;
        }
        catch { }
        return false;
    }

    /// <summary>
    /// **这个技能的数值是多少**（治疗=恢复力，输出=威力）—— **统一入口**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要它（审查发现的缺口）★
    ///
    ///    项目里有**两套**数值来源，而调用方各自只知道一套：
    ///      · `查威力()` → `威力表()`  —— **四职业的威力表里没有任何治疗技能**
    ///      · `治疗候选` → `恢复力`      —— 完整，但只有治疗决策在读
    ///
    ///    ⇒ 结果：提示词里明确写着「力N ... 治疗类=恢复力」，
    ///      而治疗技能的 `力N` **恒为空**（`查威力` 返回 0）。
    ///      AI 判"缺口 3000 该用医术还是鼓舞"**没有任何数字可依**。
    ///
    ///  [!] 治疗**优先**查治疗候选 —— 那里的恢复力是人工核对过的完整数据
    ///      （含等级档位），比威力表可靠。
    ///
    ///  [!] 放在这里而不是各调用点自己处理：调用点有两个
    ///      （散文清单 + 候选集），各自处理必然分叉。
    ///      开发约定 F③："同一个决策不论从哪条路进来，判断必须一致"。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public int 查数值(uint 技能Id, int 等级)
    {
        if (技能Id == 0) return 0;

        // ① 治疗候选里查恢复力（完整数据）
        try
        {
            foreach (var h in 治疗候选.全部)
                if (h.Id == 技能Id) return h.恢复力;
        }
        catch { }

        // ② 退回威力表（输出技）
        try { return 当前威力(技能Id, 等级); }
        catch { return 0; }
    }

    /// <summary>子类重写：给出某个技能的威力档位（按提升等级降序）</summary>
    protected virtual (int 等级, int 威力)[]? 威力表(uint 技能Id) => null;

    /// <summary>
    /// **子类可选：这个技能的 MP 消耗**（0 = 不知道/不消耗）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要它（用户实测）★
    ///
    ///    "本地一直在打破阵法，ai建议毁灭 这是对的，因为毁灭少用100蓝"
    ///    （用户确认：破阵法 500 蓝 / 毁灭 400 蓝）
    ///
    ///    `选填充技()` 原来按**纯威力**排序：
    ///        破阵法150 × 命中数  vs  毁灭150
    ///    ⇒ 单目标时两者**威力持平**，而破阵法是**瞬发**的 ⇒ 必然被选中。
    ///      可它多花 100 蓝 —— 长时间下来蓝耗差很多。
    ///
    ///  [!] **为什么 MP 不折进 `威力表`**：
    ///      威力表是"这一发打多少"，MP 是"花多少代价"，两个维度。
    ///      混在一起会让 `查威力()` 的数字含义失真（它还被别的判断在用）。
    ///
    ///  [!] 数据来源：**游戏内技能说明**（Action 表的 `PrimaryCostValue`
    ///      对玩家技能是空的，实测导出 45490 条只有 11 行有值，
    ///      而且全是 Boss 技能 —— 所以只能人工填）。
    ///      查不到就返回 0（= 不参与 MP 折算，退回纯威力排序）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual int 查MP(uint 技能Id)
    {
        // ══════════════════════════════════════════════════════════════
        //  [!] 默认直接查**共享表** —— 四个治疗职业都用同一份数据
        //      （MP 是按技能 ID 定的，与职业无关）。
        //
        //      子类**不需要**覆写。早先我给学者单独写了一份，
        //      那是"四份数据会分叉"的开端 —— 已改成共享。
        //
        //  [!] 查不到返回 **0**，语义是"**不知道**"，不是"不耗蓝"。
        //      比较时两边都已知才比；让"未知"无理由胜出是错的。
        //
        //  数据来源与生成方式见 `技能MP表` 的类注释。
        // ══════════════════════════════════════════════════════════════
        return 技能MP表.取(技能Id);
    }

    /// <summary>
    /// **咏唱时间表**（技能Id → 秒）。0 或查不到表示瞬发。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  ★ 它在"选最优技能"里起什么作用 ★
    ///
    ///    实测（`tools\CastProbe` 读游戏数据）：
    ///        读条技：Cast 1.5s + 复唱 2.5s
    ///        瞬发技：Cast 0.0s + 复唱 2.5s
    ///
    ///    因为**复唱时间都是 2.5 秒**、且 Cast < Recast，
    ///    两者都只占**一个 GCD** ⇒
    ///        单位时间收益 = 威力 ÷ 2.5s
    ///    ⇒ **咏唱时间在威力排序里约掉了**，比威力即可。
    ///
    ///  ⚠️ 那为什么还要存：
    ///    ① **移动中能不能放**取决于它 —— 不过那个由
    ///       `SpellUtil.移动中可用`（走游戏数据）判，这里存着是给
    ///       AI 描述 / 人类核对用；
    ///    ② 万一以后出现 `Cast > Recast` 的技能（会真正拖慢循环），
    ///       可以改用 `每秒威力` 排序 —— 那时这个表就必需了。
    ///
    ///  ⚠️ 空表 = 都当瞬发处理（不影响移动判定，那个不依赖本表）。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **治疗候选集** —— 综合判定（`治疗决策`）的输入。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么不是"槽位"★
    ///
    ///    槽位（`单体治疗GCD` / `群体治疗GCD` / `瞬发单奶能力技`…）只能表达
    ///    "这一类用哪一个"，**不能在同类里按情况挑**。
    ///
    ///    但实际需要按情况挑 —— 白魔有两个单体 GCD 治疗：
    ///        治疗 120  500/450  MP 400
    ///        救疗 135  800/700  MP 1000
    ///      缺口小 → 用治疗（省 600 MP）
    ///      缺口大 → 用救疗（省一个 GCD，GCD 更稀缺）
    ///
    ///  ⇒ 候选集 + `治疗决策` 打分才能表达这个。
    ///
    ///  ⚠️ 旧的槽位**保留**（`Res_HealShield` 等还在用），
    ///    两边不冲突：候选集是"更好的选择"，槽位是"兜底"。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public virtual 治疗候选集 治疗候选 { get; } = new();

    public virtual IReadOnlyDictionary<uint, float> 咏唱时间表 { get; }
        = new Dictionary<uint, float>();

    /// <summary>这个技能的咏唱时间（秒）；查不到按瞬发（0）算</summary>
    public float 咏唱时间(uint 技能Id)
    {
        try
        {
            return 咏唱时间表.TryGetValue(技能Id, out var v) ? v : 0f;
        }
        catch
        {
            return 0f;
        }
    }





