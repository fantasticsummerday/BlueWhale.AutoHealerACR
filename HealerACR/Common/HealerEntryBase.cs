using AEAssist.CombatRoutine;
using AEAssist.CombatRoutine.Module;
using AEAssist.CombatRoutine.View.JobView;
using HealerACR.Opener;
using HealerACR.Timeline;
using Dalamud.Bindings.ImGui;

namespace HealerACR.Common;

/// <summary>
/// 四个职业入口类的公共部分。
///
/// AEAssist 3.0 的 IRotationEntry 只有 4 个成员：
///   string AuthorName { get; set; }
///   Rotation Build(string settingFolder)
///   IRotationUI GetRotationUI()
///   void OnDrawSetting()
/// 再加上 IDisposable。等级 / 职业 / 描述是通过 Build 里构造的 Rotation 设置的。
/// </summary>
public abstract class HealerEntryBase : IRotationEntry
{
    // ==================== 身份信息 ====================

    public string AuthorName { get; set; } = "小鲸鱼";

    /// <summary>日随从 1 级开始，一路到 100 级</summary>
    public int MinLevel { get; set; } = 1;
    public int MaxLevel { get; set; } = 100;

    public abstract Jobs TargetJob { get; }

    /// <summary>QT 面板标题</summary>
    public abstract string OverlayTitle { get; }

    public abstract string Description { get; }

    /// <summary>职业技能表：本职业所有技能 ID 的唯一来源</summary>
    public abstract JobSpellTable Spells { get; }

    /// <summary>
    /// ACR 类型 —— 决定在 AEAssist 的 ACR 列表里怎么归类。
    ///
    /// **本项目定位是日随**（四人本为主、随机副本、省心优先），
    /// 所以默认 `Normal`（只显示"日常"），不是 `Both`。
    ///
    /// 改成 `Both` 会让它在"高难"分类里也出现 ——
    /// 但我们没有针对高难做优化（没有精细的减伤轴编排、
    /// 没有 Trigger 条件体系），挂个"高难"标签容易误导。
    ///
    /// 子类可以覆盖（比如以后真做了高难特化版）。
    /// </summary>
    public AcrType AcrType { get; set; } = AcrType.Normal;

    // ==================== UI ====================

    /// <summary>QT 窗口。所有 resolver 通过 HealerACR.Common.HealQt 读开关。</summary>
    public JobViewWindow? 视图窗口 { get; protected set; }


    // ==================== 时间轴目录输入框的缓冲 ====================

    /// <summary>
    /// 时间轴目录输入框的缓冲。
    ///
    /// ⚠️ ImGui 的 InputText 需要一个**稳定**的 string 引用 ——
    ///    每帧新建字符串会让**光标每帧跳到末尾**（根本没法编辑）。
    ///
    /// ⚠️ 但**用户打字时不能刷新**（那会把刚敲的字冲掉）：
    ///    所以打字时要同步 `时间轴目录来源`（见调用处）。
    /// </summary>
    private static string _时间轴目录缓冲 = "";
    private static string 时间轴目录来源 = "";

    private static string 时间轴目录缓冲(string 当前值)
    {
        if (当前值 != 时间轴目录来源)
        {
            _时间轴目录缓冲 = 当前值;
            时间轴目录来源 = 当前值;
        }

        return _时间轴目录缓冲;
    }

    // ==================== 核心 ====================

    /// <summary>
    /// 各职业提供**自己的**决策队列（不含基类的统一拦截）。
    ///
    /// ⚠️ 名称带 `_职业专属` 是为了和下面的 <see cref="构建决策队列"/> 区分开 ——
    ///    子类**只该重写这一个**，不要再直接重写 <see cref="构建决策队列"/>：
    ///    那会把记录模式的"停手"逻辑绕过去（见下）。
    /// </summary>
    protected abstract List<SlotResolverData> 构建决策队列_职业专属();

    /// <summary>
    /// **最终**决策队列 —— 基类在这里做统一拦截，子类不要重写。
    ///
    /// ★ 为什么要有这一层（设计要点，别拆掉）★
    ///
    ///   「记录模式」要求 **ACR 一个技能都不放**（见 记录模式.cs 的说明：
    ///   只有完全停手，记录到的每一条才必然是玩家手动按的，归属才干净）。
    ///
    ///   而"停手"最干净的实现就是**返回空队列** —— 没有任何 resolver，
    ///   ACR 自然什么都不会做（连心跳都没有，AI 也不会跑）。
    ///
    ///   ⚠️ 但这个判断**只能写在一处**：决策队列是在**每个职业入口**里
    ///      各自构建的（5 个重写），如果把判断下发到那 5 处，
    ///      就是"改一处漏四处"的经典隐患 ——
    ///      漏掉的那个职业会**在记录模式下照常出手**，
    ///      污染数据而且很难发现（它看起来只是"另一个职业"）。
    ///
    ///   所以：子类实现 `构建决策队列_职业专属()`，
    ///        基类在这里统一决定"到底给不给队列"。
    /// </summary>
    protected virtual List<SlotResolverData> 构建决策队列()
    {
        // ── 记录模式：ACR 完全停手 ──
        if (记录模式.开启 && !记录模式.保留保命兜底)
        {
            return new List<SlotResolverData>();
        }

        return Res_低蓝闸门.套上(构建决策队列_职业专属());
    }

    public virtual Rotation Build(string settingFolder)
    {
        // 1. 读设置（每个职业一份 json）
        HealSettings.Build(settingFolder, TargetJob.ToString());

        // 2. 扫一遍 cactbot 时间轴目录
        TimelineManager.初始化();

        // 3. 构建 QT 面板
        // 2.5 ★ **锁定"主线程 id"给 AI 层用** ★
        //
        //  [!] 为什么必须在这里做（而不是让 AI 层自己判）：
        //      `AiSituation.采集()` 会调 **84 处以上游戏 API**
        //      （PartyHelper / TargetHelper / MemApi / Data.AllHostileTargets），
        //      而它的**唯一**调用点在 AI 层的 `单次尝试()` 里 —— 那是
        //      `async Task`，**跑在后台线程**。主线程同一时刻也在调同样的 API
        //      ==> 两个线程同调非线程安全的进程内 API ==> 在它们内部崩
        //      ==> 无转储 / 无托管异常 / 全局异常钩子不触发。
        //
        //  [!] 为什么不能"让 AI 层第一次调时自己记下来"：
        //      那样变成"谁先调谁就是主线程" —— 而第一次恰恰是**后台线程**调的
        //      ==> 守卫完全失效（0.4.1.6 就是这么失败的，用户实测仍崩）。
        //      ==> **必须在确定是主线程的地方写**，而 `Build()` 就是那个地方。
        //
        //  [!] 反射必须包 try —— BlueWhale 没加载时不能让本地层崩
        //      （开发约定 G：AI 是增强层，本地逻辑不该依赖它存活）。
        标记AI层主线程();
        
        构建QT();

        // 4. 组装 Rotation
        var rotation = new Rotation(构建决策队列())
        {
            TargetJob = TargetJob,
            AcrType = AcrType,
            MinLevel = MinLevel,
            MaxLevel = MaxLevel,
            Description = Description,
        };

        // ══════════════════════════════════════════════════════════════
        //  ★ 记下本入口的旋转对象 —— 每帧回调靠它确认"我还是当前 ACR 吗" ★
        //
        //  [!] 为什么必须记（实测 bug）：
        //      框架把回调存进 `JobViewWindow.UpdateAction`，**每帧无条件调**。
        //      小鲸鱼有 5 个入口，只用"是不是小鲸鱼"判断的话，
        //      **5 个回调会互相抢帧**（每个都以为自己是当前的那个）。
        //      用引用比对才能唯一确定"这个回调属于被选中的那个入口"。
        //
        //  [!] 赋值位置在 rotation 构造之后、回调注册之前 ——
        //      `构建QT()`（回调在那里注册）跑在 `base.Build()` 里，
        //      比这里**早**，所以回调第一次执行时字段已经赋值了。
        // ══════════════════════════════════════════════════════════════
        _本入口旋转 = rotation;

        var rot = rotation
            .SetRotationEventHandler(new HealRotationEventHandler())
            // 日随用的"起手"其实只会做开怪倒计时预铺，序列是空的
            .AddOpener(level => new 预铺起手(Spells))
            // ── Trigger Action（参考同类 ACR 用的 AddTriggerAction）──
            //   让"铺减伤 / 攒资源"能从 AEAssist 的时间轴编辑器里直接触发。
            //   两者并存：轮询还在跑，Trigger 是额外的触发源。
            .AddTriggerAction(new AEAssist.CombatRoutine.Trigger.ITriggerAction[]
            {
                new 减伤触发器(),
                new 攒资源触发器(),
            })
            // ── Trigger Condition（参考同类 ACR 用的 AddTriggerCondition）──
            //   时间轴编辑器里可选的"条件"，配合 Action 用。
            .AddTriggerCondition(new AEAssist.CombatRoutine.Trigger.ITriggerCond[]
            {
                new 血量低于条件(),
                new 死亡人数条件(),
                new 资源条件(),
            });

        // ── 爆发轴（参考同类 ACR 用的 AddSlotSequences）──
        //   爆发期按固定套路走，不被优先级逻辑打断。
        //   **默认关闭** —— 爆发轴会占 GCD，日随里不一定划算。
        try
        {
            var 轴 = 构建爆发轴();
            if (轴 != null && 轴.Length > 0) rot.AddSlotSequences(轴);
        }
        catch { }

        return rot;
    }

    /// <summary>
    /// 子类返回自己的爆发轴（返回空数组 = 不用）。
    ///
    /// 爆发轴的意义：爆发期有固定套路，不该被优先级逻辑打断 ——
    /// 比如连环计刚放完，优先级队列可能因为"有人掉血"就转头去治疗。
    /// </summary>
    protected virtual AEAssist.CombatRoutine.Module.ISlotSequence[] 构建爆发轴()
        => Array.Empty<AEAssist.CombatRoutine.Module.ISlotSequence>();

    /// <summary>把开关暴露到 QT 面板。子类可以 override 之后往里面加职业专属开关。</summary>
    protected virtual void 构建QT()
    {
        // 把技能表注入给事件处理类 —— 它是独立类，拿不到入口类的 Spells 属性。
        // AfterSpell 里做单插控制要用到（判断"复活"用掉了即刻）。
        // ⚠️ **这里原来还有一行 `HealRotationEventHandler.当前技能表 = Spells;`** ——
        //    已**删除**：那是个单一静态字段，而 AEAssist 加载时会依次 Build 每个 ACR
        //    ==> **最后一个 Build 的职业赢**，于是玩学者时 AI 拿到白魔的技能清单。
        //    用户实测：候选里出现 `7432 神祝祷` / `天赐祝福` / `庇护所` / `法令`（全是白魔）。
        //    ==> 只保留下面那行**按职业**的登记（字典），读取方一律走 `取当前职业技能表()`。
        //    留着那个字段就一定会有人再读到 —— 这个 bug 已经犯过两次。
        // ★ 同时按职业登记 ★ —— 否则 5 个入口会互相覆盖，
        //   最后加载的那个（幻术师）赢，导致 AI 看到错误的技能清单。
        HealRotationEventHandler.登记技能表((uint)TargetJob, Spells);

        // 尝试挂 ActionEffect hook（默认关闭；挂不上会降级，不影响其他功能）
        效果确认.尝试挂载();
        var s = HealSettings.Instance;

        // ══════════════════════════════════════════════════════════════
        //  ★ QT 精简：把"不需要经常动"的开关默认隐藏起来 ★
        //
        //    原来面板上有 24 个开关，日随根本用不上这么多 ——
        //    开关太多反而让人不知道该看哪个。
        //
        //    做法用 AEAssist 自带的机制：`JobViewSave.QtUnVisibleList`。
        //    隐藏的开关**依然生效**（保持默认值），只是不出现在主面板上；
        //    真想调的时候，在 QT 控制台里能看到全部。
        //
        //    保留可见的 9 个 = 日随里最可能想动的：
        //      奶人 / 输出 / 减伤 / 时间轴     ← 大方向
        //      复活 / 驱散 / 群盾              ← 关键功能的开关
        //      一键爆发                        ← 新功能，值得先暴露
        //      解除熔断                        ← 要绑快捷键，必须可见
        //
        //    其余全部隐藏（默认值都是合理的，不需要用户操心）。
        // ══════════════════════════════════════════════════════════════
        应用QT精简(s);

        视图窗口 = new JobViewWindow(s.职业视图保存, s.保存回调, OverlayTitle);

        // ── 加一个「优先级」页签（参考同类 ACR 的 JobPriorityUI）──
        //   决定血线接近时先救谁。用 JobViewWindow.AddTab 挂进去。
        try
        {
            视图窗口.AddTab("优先级", _ => 职业优先级.画());
        }
        catch { }

        void 加开关(string 名称, bool 默认)
        {
            视图窗口.AddQt(名称, 默认);
            HealQt.注册默认值(名称, 默认);
        }

        加开关("奶人", s.奶人);
        加开关("单奶", s.单体治疗);
        加开关("群奶", s.群体治疗);
        加开关("复活", s.复活);
        加开关("驱散", s.驱散);
        加开关("醒梦", s.醒梦);
        加开关("输出", s.输出);
        加开关("AOE", s.AOE);
        加开关("DOT", s.挂Dot);
        加开关("减伤", true);
        加开关("群盾", false);
        加开关("时间轴", true);
        加开关("能量吸收", true);    // 允许卸豆换输出
        // ⚠️ 「小怪卸豆」开关**已删除**（1.29.0）：
        //    豆子规则改成"默认留，只在爆发 / 以太超流快转好时卸"，
        //    不再区分小怪和 Boss，所以这个开关没有任何读取点了。
        //    留着一个不起作用的开关只会造成困惑（和「自动召唤」同一个问题）。
        加开关("强制以太", false);   // 手动强制补，默认关
        // ---- 小仙女系统（参考实现的开关命名）----
        // ⚠️ 「自动召唤」和「小仙女」是**两件事**，别合并：
        //    · 「自动召唤」—— 宠物不在场时**召不召唤**（本开关）
        //    · 「小仙女」  —— 召唤出来之后**用不用它的技能**（在 ScholarACR 注册）
        //    合并的话，想"只召唤不用技能"或者反过来都做不到。
        //
        // ⚠️ 这个开关 1.29.0 前后被删过一次，理由是"注册了但没人读"。
        //    现在 `Res_SummonPet` 读它了，所以恢复。
        //    （教训：开关和读取点必须**同时**存在或同时不存在。）
        加开关("自动召唤", true);    // 宠物不在场就召唤（学者的朝日召唤）
        // ⚠️ 默认关：即刻咏唱是 60 秒 CD 的宝贵资源（一般留给复活/紧急治疗），
        //    拿它换"落地立刻召出小仙女"是**用大资源换小便利** ——
        //    只有用户明确想要那种即时性时才开。
        加开关("召唤用即刻", false);  // 召不出来时用即刻咏唱强制瞬发
        加开关("自动转化", false);   // 牺牲小仙女换 3 颗以太（默认关，有代价）
        加开关("脚下放罩", false);   // 地面减伤放自己脚下（不勾则放目标处）

        // ══════════════════════════════════════════════════════════════
        //  ★★ 完全采信 AI —— **高风险开关** ★★
        //
        //  语义：启用后完全限制本地策略，完全采信 AI 策略
        //
        //  ── 打开后会发生什么 ──
        //    AI 的建议**不再过本地策略判断**，直接执行：
        //      · 不再拦"DoT 还没到该补的时候"（AI 说补就补）
        //      · 不再拦"有人在等治疗，输出让路"（AI 说打输出就打输出）
        //      · 判不出该给谁的技能**一律不放**（原来会猜"血最少的队友"，
        //        那个兜底已删 —— 候选自带目标，判不出说明不是候选层来的，
        //        猜一个比不放更糟：占掉 GCD 还可能治错人）
        //
        //  ── 仍然保留的三道闸（**不是策略，是"放不放得出去"**）──
        //    · 技能没解锁 / CD 中      → 放了也是失败
        //    · 没有合法的敌人/队友目标  → 放了也是空放
        //    · 视线被挡 / 超出射程      → 放了也是失败
        //    这些**不是本地策略**，去掉它们不会让 AI 更自由，
        //    只会让日志多几条"技能放不出去"。
        //
        //  ── 为什么默认关、为什么标高风险 ──
        //    本地策略里有几条是**保命的**（"有人在等治疗就让路"就是）。
        //    关掉它意味着 AI 判断失误时**没有任何东西兜底** ——
        //    而 AI 会超时、会幻觉、会建议错时机。
        //    这个开关是给"我知道我在干什么、我要拿 AI 做实验"的人用的。
        // ══════════════════════════════════════════════════════════════
        加开关("完全采信AI", false);

        // ══════════════════════════════════════════════════════════════
        //  ⚠️ 下面这些是"被 resolver 读取了、但一直没注册"的开关。
        //
        //    没注册的后果：GetQt 查不到 → 落到**调用方的兜底参数** →
        //      ① 用户在面板上看不到它，改不了
        //      ② 如果兜底是 false，**功能直接静默失效**
        //
        //    最严重的是「应急」—— 它读取时写的兜底是 false，
        //    意味着**紧急治疗从来没触发过**。
        //
        //    教训：新增任何 GetQt("XXX") 调用，都必须在这里补一行注册。
        //          （这个坑我是靠"交叉检查读取 vs 注册"扫出来的，
        //           肉眼绝对看不出来 —— 因为代码不报错，只是什么也不做。）
        // ══════════════════════════════════════════════════════════════
        加开关("HoT", true);         // 再生 / 吉星相位 这类单体 HoT
        加开关("应急", true);        // ★ 紧急治疗 —— 之前默认 false 导致从未生效
        加开关("脱战准备", true);    // 脱战期提前攒资源
        加开关("极限技", true);      // 治疗极限技（LB3）
        加开关("自动疾跑", true);    // 脱战自动疾跑
        加开关("自动以太", true);    // 学者：以太不够时自动补
        // ★ 「一键爆发」★ —— 合并了原来的「爆发轴」和「木桩爆发」
        //   勾上 = 战斗或木桩，只要条件满足就走爆发轴
        //   默认关（爆发轴会占 GCD，日随里不一定划算）
        加开关("一键爆发", false);
        // ★ 记录模式 ★ —— 只观察玩家手动操作，ACR 完全停手
        //   ⚠️ 默认关。开启后 **ACR 不会替你奶**，全程要自己操作 ——
        //      详细说明和数据用途见 记录模式.cs
        加开关("记录模式", false);
        // ★ 解除熔断 ★ —— HealQt 只提供 bool 开关，
        //   但 AEAssist 的 QT 控制台支持给开关绑快捷键 ——
        //   所以在 QT 面板里给这个开关设个键，就等于有了"解除熔断"快捷键。
        //   勾上即解除，下一帧自动弹回（见 HealQt.每帧更新）。
        加开关("解除熔断", false);

        // ★ 强制熔断 ★ —— 和「解除熔断」**方向相反**的一对。
        //
        //   勾上 = 立刻停掉所有 AI 请求，全程走原有逻辑；
        //   取消 = 恢复正常。
        //
        //   ⚠️ 和「解除熔断」的三个区别（别混）：
        //      · 解除熔断：**一次性按钮**，勾上执行、下一帧自动弹回
        //      · 强制熔断：**状态开关**，开就是开、关就是关
        //      · 自动熔断：连续失败太多次**系统自己**触发的，到期自动恢复
        //
        //   ── 用途 ──
        //     ① 想省 token（打熟悉的本、不需要 AI 判断时）
        //     ② AI 建议明显不对，想临时关掉它、又不想卸载插件
        //     ③ 网络/额度出问题，不想让它反复重试
        //
        //   ⚠️ 默认**关** —— 强制熔断开着等于没有 AI，
        //      默认开会让新用户以为"这插件没效果"。
        加开关("强制熔断", false);

        // ★ 爆发药 ★ —— 默认关。
        //   药水 ID 不在这里填 —— 用 AEAssist 自带的「爆发药设置」，
        //   所以只判断"有没有配 + 够不够 + CD 好没好"。
        //   实际消耗点见 爆发轴.cs 的 使用爆发药()（挂在爆发轴第一步）。
        加开关("爆发药", false);

        // 每个职业自己的页（参考同类 ACR 的 XXXOverlay / XXXSettingView 做法）
        视图窗口.AddTab("职业", w => 职业面板.画(TargetJob, w));
        // 通用页：阈值 + 时间轴
        视图窗口.AddTab("阈值", 画阈值设置);

        HealQt.绑定(视图窗口);

        // ══════════════════════════════════════════════════════════════
        //  ★ 把"和战斗无关的每帧任务"挂到框架窗口的 Update 上 ★
        //
        //  ── 为什么不能挂在 `OnBattleUpdate`（实测踩的坑）──
        //     框架 IL 直证：`IRotationEventHandler.OnBattleUpdate` 是在
        //     `BattleData.Update` 里调的，而 `BattleData.Update`
        //     只由 `AILoop_Normal/PVP/Simulate.Update` 调用 ——
        //     **只有战斗中才跑**。
        //
        //     现象：在木桩（非战斗）点了「哼一段」，
        //     日志有 `[彩蛋] 手动触发，共 6 句`，**但一句都没唱出来** ——
        //     因为推进队列的那行代码在 `OnBattleUpdate` 里，压根没执行。
        //
        //  ── 为什么这个能行（框架 IL 直证）──
        //     `JobViewWindow.SetUpdateAction(action)` 把回调存进
        //     `UpdateAction` 字段；而 `UpdateAction` **全框架只有一处被读** ——
        //     `JobViewWindow.OnDrawUI()` 的**第 3 条语句**：
        //         IL_001c: ldfld  JobViewWindow::UpdateAction
        //         IL_0022: dup / brtrue → callvirt Invoke
        //     位置在 `MainControlView` 之后、**一切早退之前**
        //     ⇒ 只要窗口在画，它每帧都跑，**和战斗状态无关**。
        //
        //     ⚠️ 注意**不是** `JobViewWindow.Update()` —— 那个方法
        //        （由 `OverlayManager.Update` → `IRotationUI.Update` 调）
        //        只跑两个快捷键（`HotkeyWindow.RunHotkey` +
        //        `QtWindow.RunHotkey`），**不碰 `UpdateAction`**。
        //        差点按那个理解去写注释（写错了会误导后面的人）。
        //
        //  ⚠️ 这里只放**确实需要"任何时候都跑"**的东西。
        //     依赖战斗状态的那些（时间轴推进、移动检测采样…）
        //     继续留在 `OnBattleUpdate` —— 它们本来就只该在战斗中跑。
        // ══════════════════════════════════════════════════════════════
        // ══════════════════════════════════════════════════════════════
        //  ★ 记下本次 Build 的旋转对象 —— 给每帧回调做"我还是当前 ACR 吗"的判据 ★
        //
        //  [!] 为什么必须记（实测 bug）：
        //      框架把回调存进 `JobViewWindow.UpdateAction`，**每帧无条件调**。
        //      重载 ACR / 切到别的 ACR 时若不清掉，**旧回调会继续跑** ——
        //      现象是"已经切到别的 ACR 了，左下角还在刷小鲸鱼的日志"。
        //      （静态类不依赖实例，所以照样执行、照样打日志。）
        // ══════════════════════════════════════════════════════════════

        try
        {
            // [!] 回调存进字段（不是就地写 lambda）—— `Dispose` 要按引用清掉它
            _每帧回调 = () =>
            {
                // ══════════════════════════════════════════════════════
                //  ★ 守卫：确认"我还是当前 ACR" ★
                //
                //  [!] 两条判据都查（不是二选一）：
                //      ① 代次     —— 挡住"重载 ACR / 切职业"
                //      ② 职业比对 —— 挡住"代次恰好相同但 ACR 换了"
                //
                //  [!] 任一不满足就**直接返回**，且**不打日志** ——
                //      打日志同样会刷屏，那正是用户看到的现象。
                // ══════════════════════════════════════════════════════
                // ══════════════════════════════════════════════════════
                //  ★ 守卫：这个回调还属于本入口吗 ★
                //
                //  [!] 这里比"挂载门"更严格 —— 必须排除**兄弟入口**：
                //      小鲸鱼有 5 个入口（白魔/学者/占星/贤者/幻术师），
                //      如果只用"是不是小鲸鱼"，5 个回调会**互相抢帧**
                //      （每个都以为自己是当前的那个）。
                //      => 用 `ReferenceEquals` 比对本入口的旋转对象。
                //
                //  [!] 判据：`Data.currRotation` 是不是**本入口 Build 出来的那个**
                //      `_本入口旋转` 在 `Build()` 里赋值（那时 rotation 已构造完）。
                //      只有被选中的那个入口的旋转会成为 `currRotation`。
                //
                //  [!] 读不到就返回（宁可少跑，不抢别人的帧），且**不打日志**。
                // ══════════════════════════════════════════════════════
                try
                {
                    var 当前 = AEAssist.CombatRoutine.Data.currRotation;
                    if (当前 == null) return;
                    if (!ReferenceEquals(当前, _本入口旋转)) return;
                }
                catch { return; }

            // ★ 进本识别：必须在这里，不能只在 OnBattleUpdate ★
                //
                //  `OnBattleUpdate` **只有战斗中才跑**（框架 IL 直证：
                //  它由 `BattleData.Update` 调，而那条路只有 `AILoop_*` 走）。
                //  而"进本"那一刻是**非战斗**状态 ——
                //  挂在那边就永远不会执行：
                //    · 时间轴装不上 → 开怪时报「本场战斗没有加载时间轴」
                //    · AI 上下文不重建 → AI 以为还在上一个地图
                //  （实测日志：`进入新地图` 之后没有任何「进本识别」行。）
                try { 伤害预测.每帧更新(); } catch { }   // 血量采样（给预测用）
                try { 进本识别.每帧检查(); } catch { }

                // ══════════════════════════════════════════════════════
                //  ★ 坦克压力采样**必须在这里**（用户实测「血量波动数据不足、
                //     最高100% 最低100%」的根因）★
                //
                //  [!] 它原来**只有一个调用点**：`BlueWhaleEntries.cs` 的 AI 心跳里。
                //      而心跳在**记录模式**下根本不进队列
                //      （`if (记录模式.开启 && !保留保命兜底) return 队列;`），
                //      AI 层没挂上时同理 ==>
                //      `坦克压力.每帧更新()` **永不执行** ==> 采样恒 0 条
                //      ==> `最高血量/最低血量` 停在初值 1f/1f
                //      ==> 显示成「数据不足（刚开始采样）｜最高=100% 最低=100%」。
                //
                //  [!] 这违反项目自己的「开发约定 G：AI 是增强层，本地逻辑不该依赖 AI 存活」——
                //      同一个隐患之前已经在 `HealQt.每帧更新()` / `以太管理.每帧更新()`
                //      上修过一次（它们也曾经只在心跳里），坦克压力是**漏掉的那个**。
                //      （心跳里那次调用**保留**：两份都调不会重复采样，
                //        因为 `每帧更新` 内部有 250ms 节流闸门。）
                // ══════════════════════════════════════════════════════
                try { 坦克压力钩子.每帧更新(); } catch { }

                // ★ 空中检测：采样 Y 判断"跳起来了没" ★
                //   [!] 必须每帧采（跳跃很短），而且必须在这条回调里 ——
                //      它是**唯一确定的每帧路径**（见上面 OnBattleUpdate 的说明）。
                try { 空中检测.每帧更新(); } catch { }

                // ★ 彩蛋：同理，木桩/城里也要能唱 ★
                try { 彩蛋.每帧更新(); } catch { }

                // ══════════════════════════════════════════════════════
                //  ★ 兜底：确保 AI 层一定有机会被挂上 ★
                //
                //  [!] 为什么需要第三道（前两道都可能失效，都已有实证）：
                //      · `Build()` —— 每次都会跑，但 ACR 发现阶段
                //        `Data.currRotation` 可能还是 null
                //      · `OnEnterRotation()` —— 真被选中时会跑，
                //        但**重载时日志实证它没被调**
                //
                //  [!] 为什么多这一道是安全的：
                //      `尝试挂载AI层()` 自带"只挂一次"开关 ——
                //      重复调无害，只是每帧一次反射查找；挂上后立即短路。
                //
                //  [!] 为什么值得：
                //      **"AI 永远不初始化"比"不该初始化时初始化了"更糟** ——
                //      前者是功能完全失效（副本里毫无反应，还不知道为什么），
                //      后者只是白花一次请求。
                // ══════════════════════════════════════════════════════
                尝试挂载AI层反射();
            };

            视图窗口.SetUpdateAction(_每帧回调);
        }
        catch (Exception e)
        {
            LogHelper.Info("[HealerACR] 挂每帧回调失败（彩蛋只能在战斗中唱）：" + e.Message);
        }
    }

