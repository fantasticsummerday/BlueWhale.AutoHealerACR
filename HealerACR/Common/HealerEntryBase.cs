    /// <summary>
    /// 当前职业的技能表，由入口类在 Build 时注入。
    /// 这个事件处理类是独立类，拿不到入口类的属性，所以用静态字段传。
    /// </summary>
    // ⚠️ **`public static JobSpellTable? 当前技能表;` 已删除** ——
    //    它是单一静态字段，而 AEAssist 会依次 Build 每个 ACR，
    //    ==> 最后 Build 的职业覆写它 ==> 别的职业读到错表。
    //    正确做法：用 `登记技能表(职业Id, 表)` + `取当前职业技能表()`（按职业查）。

    /// <summary>
    /// **按职业存的技能表** —— 解决"最后加载的职业覆盖前面的"问题。
    ///
    /// ⚠️ 这是个真 bug：
    ///    BlueWhale 有 5 个入口（白魔/学者/占星/贤者/幻术师），
    ///    AEAssist 加载时会**依次调用每个的 Build**，
    ///    而每个 Build 都写同一个静态字段 `当前技能表` ——
    ///    **最后一个（幻术师）赢了**。
    ///
    ///    后果：玩学者时，AI 收到的"可选技能清单"是**幻术师的技能**，
    ///    于是它建议 `132 烈风` / `127 坚石` —— 学者根本没有这两个技能。
    ///
    ///    修法：**按职业 ID 存表**，取的时候用当前职业去查。
    /// </summary>
    private static readonly Dictionary<uint, JobSpellTable> _各职业技能表 = new();

    /// <summary>入口类 Build 时调：登记本职业的技能表</summary>
    public static void 登记技能表(uint 职业Id, JobSpellTable 表)
    {
        try
        {
            _各职业技能表[职业Id] = 表;
        }
        catch { }
    }

    /// <summary>
    /// 取**当前实际职业**的技能表。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ⚠️⚠️ 这里原来有个**很隐蔽的真 bug** ⚠️⚠️
    ///
    ///  旧实现：
    ///      var 职业 = Core.Me.ClassJob.RowId;
    ///      if (_各职业技能表.TryGetValue(职业, out var 表)) return 表;
    ///      return 当前技能表;                    // ← 兜底 = **别的职业的表**
    ///
    ///  后果：**玩学者，AI 却拿到幻术师的技能清单。**
    ///  日志实证（AI 原始回复）：
    ///      "job says 学者 (Scholar) but skills list has 坚石/烈风/救疗/医济/复活
    ///        — these are Conjurer/White Mage?"
    ///  AI 自己都发现不对劲了，但它只能从清单里选 —— 于是**给的全是错的技能**。
    ///  这解释了一大半现象：不是 AI 判断错，是**喂给它的数据是错的**。
    ///
    ///  ── 为什么会走到兜底 ──
    ///    `Core.Me.ClassJob.RowId` 在**职业数据还没就绪时返回 0**（加载期/切职业瞬间），
    ///    查不到 → 落到 `当前技能表` —— 那是"最后一个被注入的表"。
    ///    而我们的加载顺序让**幻术师最后注入**，于是就串成幻术师了。
    ///
    ///  ── 修法原则：**宁可不给，也不给错的** ──
    ///    · 先按职业 ID 直接查（正常路径）
    ///    · 再按"基础职业 → 特职"映射查（幻术师→白魔、秘术师→学者）
    ///      —— 这条是安全的，因为那些**本来就是同一个技能体系**
    ///    · 都查不到就 **返回 null**，让上层明确报"拿不到技能表"
    ///      （`采可选技能` 会提示 AI 输出 `0|数据不足`，比给错 ID 强得多）
    ///    · **绝不**退回"别的职业的表"
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static JobSpellTable? 取当前职业技能表()
    {
        try
        {
            var 职业 = CharacterExt.我的职业Id();

            // ① 正常路径：按职业 ID 直接查
            if (职业 != 0 && _各职业技能表.TryGetValue(职业, out var 表) && 表 != null)
                return 表;

            // ② 基础职业 → 特职：**同一技能体系**，可以安全借用
            //
            //    幻术师(6) 是白魔的前置职业，技能同源；
            //    秘术师(26) 是学者的前置职业，1-30 级共用。
            //    低等级本（用户测的 15 级）走的就是这条路。
            var 替代 = 职业 switch
            {
                职业表.幻术师 => 职业表.白魔,
                26 => 职业表.学者,        // 秘术师 → 学者
                _ => 0u,
            };

            if (替代 != 0 && _各职业技能表.TryGetValue(替代, out var 表2) && 表2 != null)
                return 表2;

            // ③ 查不到就**不给** —— 宁可让上层报"数据不足"，也不串职业
            return null;
        }
        catch
        {
            return null;
        }
    }

