    public void AfterSpell(Slot slot, Spell spell)
    {
        // ── 本地施放记录（对付服务器状态滞后）──
        //   官方文档 L129：buff 是技能成功的 0.x 秒后才在内存里出现。
        //   先记本地一笔，判断时优先问它，能盖住那段空窗期，
        //   避免"刚放完盾，因为还没看到 buff 又放一次"。
        try
        {
            本地施放记录.记(spell?.Id ?? 0);
        }
        catch { }

            // ★ 综合效果指标：记放了一次治疗（**本地和 AI 共用的出口**，所以两条路都覆盖）
            //   [!] 恢复力在 HealerACR 这侧查（技能表在这里），查不到就静默跳过。
            try { 指标钩子.记治疗(spell?.Id ?? 0); } catch { }

        // ★ 记忆采集（通过钩子转出去，本类不知道采集器是谁）★
        //   原版 HealerACR 没挂这个钩子 → 什么也不发生。
        try
        {
            记忆钩子.通知决策(spell?.Id ?? 0, SpellIds.反查(spell?.Id ?? 0));
        }
        catch { }

        // 单插控制（官方文档）：
        //   每次 GCD 技能成功后会重置 BattleData.CurrGcdAbilityCount，
        //   紧接着触发这个回调 —— 在这里改它，就能控制"本 GCD 内还能插几个能力技"。
        //
        // 场景：复活用掉即刻之后，这个 GCD 不该再塞能力技（窗口留给随后的治疗）。
        try
        {
            // [!] 必须用**按职业**的表（不能用那个被覆写的静态字段）——
            //     AfterSpell 是全局回调，读错职业的表会让 `表.复活` 比对失效。
            var 表 = 取当前职业技能表();
            var 数据 = AI.Instance?.BattleData;
            if (表 == null || 数据 == null) return;

            // ⚠️ 官方错题集警告：在 AfterSpell 里把 CurrGcdAbilityCount 设成 0/1，
            //    会让这个 GCD 内的**能力技全部作废**（"能力技返回 0 但就是不打出去"）。
            //    所以这里必须卡死条件：
            //      - 技能表里确实配了复活（否则 表.复活 是 0，spell.Id == 0 会误命中）
            //      - 而且就是刚放出去的那个技能
            if (表.复活 != 0 && spell != null && spell.Id == 表.复活)
            {
                数据.CurrGcdAbilityCount = 0;   // 复活后本 GCD 不再插能力技
            }
        }
        catch
        {
            // 拿不到战斗数据就算了，不影响正常循环
        }    }

    public void OnBattleUpdate(int currTimeInMs)
    {
        TimelineManager.更新(currTimeInMs);

        // 死亡追踪：记录"谁躺下了、躺了多久"（复活时判断该不该等）
        死亡追踪.每帧更新();

        // 本地施放记录：清理过期条目
        本地施放记录.每帧更新();

        // ══════════════════════════════════════════════════════════════
        //  ★ 一次性开关 / 状态开关的每帧处理（**本地层**）★
        //
        //  ⚠️ 原来这个只在 BlueWhale 的 `AiHeartbeat` 里调用 —— 那是个隐患：
        //     `AiHeartbeat` 是插在**决策队列**里的 resolver，
        //     一旦队列里没有它（记录模式停手、或者 AI 层出问题被摘掉），
        //     这些开关就**永远不会被处理**：
        //       · 「解除熔断」勾了没反应
        //       · 「记录模式」勾了**启动不了**（而且是死锁：
        //          勾上 → 想停手 → 心跳被移除 → 再没人读这个开关 → 永远开不起来）
        //
        //     移到本地层就与队列内容无关了 —— 这也符合 开发约定.md G 节
        //     （AI 是增强层，这些开关不该依赖 AI 存活）。
        // ══════════════════════════════════════════════════════════════
        HealQt.每帧更新();

        // ══════════════════════════════════════════════════════════════
        //  ★ 以太管理：**同一个隐患的第二处**（2026-09 补）★
        //
        //  ⚠️ 它原来只被 `BlueWhaleEntries` 调（AI 层）。
        //     而 `以太管理` 是**本地逻辑**（学者的以太保留/抑制），
        //     按开发约定 G「AI 是增强层，本地逻辑不该依赖它」——
        //     卸载 BlueWhale 之后这个更新就停了：
        //       · `抑制中` 永远是 false（抑制窗口形同虚设）
        //       · 保留策略不生效
        //
        //    和上面 `HealQt.每帧更新()` 是**完全同一类问题**，
        //    所以放在一起 —— 以后新增"每帧维护的本地状态"也放这里。
        // ══════════════════════════════════════════════════════════════
        以太管理.每帧更新();

        // ★ DoT 自适应黑名单：把"待确认"的项拿出来看 buff 上去没有 ★
        //   ⚠️ 这个每帧更新原来**不存在** —— 导致 `记补失败`/记补成功`
        //     永远不被调用，自适应拉黑是死代码。
        Dot黑名单.每帧更新();

        // ★ 敌人移动检测：清理过期记录 ★
        //   ⚠️ 它自己的注释写着"（每帧调一下，很轻）"，
        //     但**原来一个调用点都没有** —— 记录只能靠换本时的 `重置()` 清。
        //     一场长副本里敌人 GameObjectId 会一直累积（每只怪一条 Vector3）。
        敌人移动检测.清理();

        // ★ 记录模式：观察玩家手动操作 ★
        //   非记录模式下这个方法第一行就 return，零开销。
        记录模式.每帧更新();

        // ★ OffGcd 闸门诊断：观测队列深度到底会不会变成非 0 ★
        //   ⚠️ 这是**只读诊断**，不改变任何行为。
        //     为什么必须看：如果队列恒为 0，`可以排()` 就恒真 ——
        //     闸门形同虚设（"读了但永远是同一个值"，比"注册了没人读"更隐蔽）。
        //     日志里看到"历史最大 >= 1"才说明闸门真的会关上。
        OffGcd闸门.每帧更新();

        // ══════════════════════════════════════════════════════════════
        //  ★ 进本监视：进副本时通知一次（本地层负责判定，AI 层负责输出）★
        //
        //  ── 为什么判定放本地层 ──
        //    ① **它不依赖 AI**：识别"进没进副本、进的是哪个本"是本地能力。
        //       按开发约定 G，本地逻辑不该依赖 AI 层存活。
        //    ② **AI 层有一条路径跑不到**：记录模式下 `AiHeartbeat`
        //       会被移出决策队列（`BlueWhaleEntries` 的守卫直接 return），
        //       而记录模式恰恰是"每一局都要知道在打什么本"的场景。
        //
        //  ── 为什么不能靠 `状态重置钩子`（换本）──
        //    那个钩子在 `OnTerritoryChanged` 触发，而那时人**刚离开休息区**、
        //    还没进本 —— 读到的仍是房区。真正进本要再过一两秒，
        //    所以必须"每帧看一次、状态变了才通知"。
        //
        //  ⚠️ 输出（打横幅 / 写日志）由 AI 层挂的回调做 ——
        //     "副本名/地名的解析表"在 BlueWhale 那边（`地名` 在 Common，
        //     但调用方要 `屏幕提示` + `Ai调试` 的组合，那是 AI 层的写法）。
        //     没挂回调时（原版 HealerACR）本方法只是空转，不影响任何东西。
        // ══════════════════════════════════════════════════════════════
        //  ⚠️ 这里保留一份是**双保险**（战斗内也推）——
        //     主驱动在 `视图窗口.SetUpdateAction`（每帧无条件），
        //     因为"进本"那一刻是非战斗状态，这里根本不会被执行。
        进本识别.每帧检查();

        // ⚠️ 彩蛋的每帧驱动**不在这里** ——
        //    这里是 `OnBattleUpdate`（**只有战斗中才跑**），
        //    而彩蛋在木桩/城里点按钮也得能唱。
        //    它挂在 `视图窗口.SetUpdateAction`（每帧都跑），
        //    见 `构建QT()` 里的说明。
    }

    public void OnEnterRotation()
    {
        // ══════════════════════════════════════════════════════════════
        //  ★ 进入本职业的循环 = 切换到了这个职业 / 重新加载了本 ACR ★
        //
        //    这时候所有"有状态"的东西都要清一遍，而且**理由比换本更强**：
        //    换本只是换了地图，切职业是**换了一整套技能表和判断逻辑** ——
        //    上一个职业攒下的状态套到新职业上，全都是错的。
        //
        //    尤其是 AI 层：它的"倾向 / 阈值偏移 / 预取队列"
        //    是按上一个职业的局面得出的。所以除了清状态，
        //    **还要重新初始化**（否则开场有一段"哑"的窗口）。
        //    这些由 BlueWhale 挂的 `记忆钩子.进入循环` 负责 ——
        //    本类不认识 AI 类，只负责"通知"（和 状态重置钩子 同一个套路）。
        // ══════════════════════════════════════════════════════════════

        // ① 本地层的状态：和换本一样全清
        try { 以太管理.重置(); } catch { }
        try { 本地施放记录.重置(); } catch { }
        try { 死亡追踪.重置(); } catch { }
        try { 敌人移动检测.重置(); } catch { }
        try { Dot黑名单.重置自适应(); } catch { }
        try { 技能熔断.重置(); } catch { }
        try { 效果确认.重置(); } catch { }
        try { 技能诊断.重置(); } catch { }
        try { 屏幕提示.重置(); } catch { }      // 换职业后同 key 的提示应该能再弹一次
        try { Dot补判.重置(); } catch { }
        try { 记录模式.重置();

        OffGcd闸门.重置(); } catch { }        // DoT 保险丝（换职业后重新开始计时）

        // ② 队伍规模要重新判定（切职业常常伴随换队伍 / 换本）
        try { HealTargetHelper.刷新队伍规模(); } catch { }

        // ══════════════════════════════════════════════════════════════
        //  ★ ③ 通知 AI 层 —— **只在"我确实是当前 ACR"时才通知** ★
        //
        //  [!] 这是实测 bug 的根因（第二次修）：
        //      ACR 重载时框架会对**所有已加载的 ACR** 调 `OnEnterRotation`。
        //      原来这里无条件通知 ⇒ 没被选中的小鲸鱼也被拉起来初始化，
        //      现象是"界面明明默认是别的 ACR，小鲸鱼却完成了初始化"，
        //      而且**白花 API 请求**（初始化是完整的一轮请求）。
        //
        //  [!] 为什么本地层重置（①②）**不**加守卫：
        //      它们幂等、代价极小，而且是"万一真被选中"该做的准备。
        //      只有**发 API 请求 / 打日志**的部分必须挡住。
        // ══════════════════════════════════════════════════════════════
        if (ACR身份.是当前())
        {
            try { 记忆钩子.通知进入循环(); } catch { }
            LogHelper.Info("[HealerACR] 进入职业循环（当前 ACR）-> 已清理本地状态并通知 AI 层");
        }
        else
        {
            LogHelper.Info("[HealerACR] 进入职业循环（非当前 ACR）-> 只清本地状态，不惊动 AI 层");
        }

        // ══════════════════════════════════════════════════════════════
        //  ★ 补一次"挂载 AI 层"的机会 ★
        //
        //  [!] 为什么需要：`Build()` 跑在 ACR **发现阶段**，
        //      那时 `Data.currRotation` 可能还是 null
        //      => `Build()` 里的身份守卫会把"真正被选中"那次也挡掉。
        //      这里再试一次，两条路都不会漏。
        //
        //  [!] `尝试挂载AI层()` 自带"只挂一次"开关 —— 重复调无害。
        //
        //  [!] 用全限定名而不是 using：
        //      `BlueWhale` 命名空间只在 BlueWhale 那个 dll 里存在，
        //      单独编译 HealerACR 时没有那个类 —— 所以放在 try 里，
        //      编译期**不要**直接引用（否则独立编译会失败）。
        //      这里用反射调用，两边都能编译。
        // ══════════════════════════════════════════════════════════════
        HealerEntryBase.尝试挂载AI层反射();
    }

