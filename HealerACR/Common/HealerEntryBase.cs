    public void OnTerritoryChanged()
    {
        // ★ 进本先重新判定队伍规模（四人本 / 八人本）★
        //   复活策略依赖它，所以换本时必须刷新。
        try
        {
            HealTargetHelper.刷新队伍规模();
            LogHelper.Info($"[HealerACR] 进入新地图 -> 队伍规模：{(HealTargetHelper.是八人本() ? "八人本（双奶）" : "四人本（单奶）")}");
        }
        catch { }

        // 换副本了，让时间轴重新匹配
        TimelineManager.战斗重置();

        // ── 换本时把所有带状态的模块也清一遍 ──
        //   理由和 OnResetBattle 一样：旧地图的状态在新地图里全是错的。
        //   尤其是：
        //     · 敌人移动检测 —— 位置数据是上一个副本的敌人
        //     · DoT 黑名单     —— 上个别本的怪种类
        //     · 死亡追踪       —— 上场的尸体记录
        try { 以太管理.重置(); } catch { }
        try { 本地施放记录.重置(); } catch { }
        try { 死亡追踪.重置(); } catch { }
        try { 敌人移动检测.重置(); } catch { }
        try { Dot黑名单.重置自适应(); } catch { }
        try { 技能熔断.重置(); } catch { }
        try { 效果确认.重置(); } catch { }   // 同上：换本也要清
        try { 技能诊断.重置(); } catch { }
        try { Dot补判.重置(); } catch { }
        try { 记录模式.重置();

        OffGcd闸门.重置(); } catch { }    // DoT 保险丝

        // ★ 通知 AI 层：局面完全变了 ★
        //   不通知的话，AI 的"倾向"和阈值偏移会从上个副本带过来 ——
        //   比如上个本一直在打小怪（激进），进 Boss 本还保持激进。
        try { 状态重置钩子.通知(); } catch { }

        // ★ 换本时重置"进本识别"的边沿状态 ★
        //
        //  ⚠️ 不重置的话会漏掉一种情况：**副本 A 直接切到副本 B**
        //     （中途没有"不在副本"的状态，比如连续排本 / 副本内换区域）。
        //     `_上次在副本` 一直是 true → 边沿判据认为"没变化" → 不输出。
        //     清了之后，下一个副本会被当成"新的一次进入"，正常输出。
        try { 进本识别.重置(); } catch { }
        try { 彩蛋.重置(); } catch { }        // 换本别把没唱完的句子带过去

        // ★ 空中检测也要清 ★
        //   [!] 不清的话，跨地图时"上一个地图的 Y"会成为起点，
        //      地形高度差被算成"跳起了" -> 一直报空中 -> 读条技能全被挡。
        //
        //   [!] **这里才是对的位置** —— 我第一次插在了 `_每帧回调` 里，
        //      结果每帧先重置再采样，永远停在"首次采样"，功能等于没写。
        //      （编译通过、看着正常 —— 正是本项目反复栽的那种错。）
        try { 空中检测.重置(); } catch { }

        // ★ 幻觉校验的统计也要清（换本 = 新的等级/副本环境）★
        //   [!] 不清的话，50 级本里抓到的"越级建议"会一直留在数字里，
        //      看起来像"进了满级本还在越级"。
        try
        {
            foreach (var 程序集 in AppDomain.CurrentDomain.GetAssemblies())
            {
                var 类型 = 程序集.GetType("BlueWhale.AutoHealerACR.幻觉校验", false);
                if (类型 == null) continue;
                类型.GetMethod("重置",
                    System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)
                    ?.Invoke(null, null);
                break;
            }
        }
        catch { }

        // ★ 清掉输出目标选择器的粘滞 ★
        //   不清的话，上个副本那只怪的 ID 会一直"粘"着，
        //   新副本第一帧找不到它 → 白等一次重挑。
        try { 输出目标.重置(); } catch { }
    }


