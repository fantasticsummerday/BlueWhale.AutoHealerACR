        // [!] 自禁用：连抛 N 次就关掉它 ——
        //     绘制函数每帧都跑，一个持续异常会**每帧抛一次**，
        //     在 ImGui 里很容易把窗口栈搞乱（那是闪退级的问题）。
        //     宁可少一个调试窗，也不能让它在战斗里反复抛。
        if (_调试窗失败次数 >= 调试窗失败上限) { 写诊断($"跳过：失败次数={_调试窗失败次数} 已达上限"); return; }

        try
        {
            if (_画调试窗 == null)
            {
                foreach (var 程序集 in AppDomain.CurrentDomain.GetAssemblies())
                {
                    Type? 类型 = null;
                    try { 类型 = 程序集.GetType("BlueWhale.AutoHealerACR.调试窗", false); }
                    catch { }
                    if (类型 == null) continue;

                    // [!] **必须显式指定参数签名** —— `调试窗` 有 `画(bool)` 与 `画()` 两个重载，
                    //     `GetMethod("画", flags)` 在有重载时可能抛 AmbiguousMatchException
                    //     或返回不确定的那个 ⇒ 用 `GetMethod(name, Type[])` 明确要 `画(bool)`。
                    var 方法 = 类型.GetMethod(
                        "画",
                        System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static,
                        null,
                        new[] { typeof(bool) },
                        null);

                    if (方法 == null) continue;
                    _画调试窗 = (Action<bool>?)Delegate.CreateDelegate(typeof(Action<bool>), 方法, false);
                    写诊断($"反射成功：方法={方法.DeclaringType?.FullName}.{方法.Name} 参数数={方法.GetParameters().Length} 返回={方法.ReturnType.Name}");
                    break;
                }
            }

            if (_画调试窗 == null) { 写诊断("反射失败：找不到 调试窗.画"); return; }
            调用次数++;
            写诊断($"即将调用第{调用次数}次（委托={_画调试窗.Method.DeclaringType?.FullName}.{_画调试窗.Method.Name}）");
            try
            {
                // [!] **把本程序集读到的开关值传进去** —— 两个 DLL 的 HealSettings.Instance 是两份，
                //     不传的话画() 读的是它自己那份，可能永远是 false（这就是那个 bug）。
                var 开关 = HealSettings.Instance?.启用调试窗 ?? false;
                _画调试窗(开关);
                写诊断($"调用返回正常（第{调用次数}次）");
            }
            catch (Exception 内层)
            {
                写诊断($"调用抛异常（第{调用次数}次）：{内层.GetType().Name} {内层.Message}");
                throw;
            }

            _调试窗失败次数 = 0;   // 成功一次就清零（偶发失败不算）
        }
        catch (Exception e)
        {
        写诊断("画() 抛异常：" + e.GetType().Name + " " + e.Message);
            _调试窗失败次数++;

            if (_调试窗失败次数 == 1)
            {
                try
                {
                    LogHelper.Error("[HealerACR] 调试窗绘制异常：" + e.Message + "\n" + e.StackTrace);
                }
                catch { }
            }

            if (_调试窗失败次数 >= 调试窗失败上限)
            {
                // 自动关掉开关 —— 否则每帧抛，而且用户看不出为什么
                try
                {
                    if (HealSettings.Instance != null)
                    {
                        HealSettings.Instance.启用调试窗 = false;
                        HealSettings.Instance.Save();
                    }
                    LogHelper.Error($"[HealerACR] 调试窗连续失败 {调试窗失败上限} 次，" +
                                    "已**自动关闭**它（避免每帧抛异常影响战斗）");
                }
                catch { }
            }
        }
    }

    /// <summary>
    /// **反射调用 AI 层的 `AiSituation.标记主线程()`** —— 把"当前线程是主线程"告诉 AI 层。
    ///
    /// ⚠️ 为什么走反射：HealerACR **编译期看不到** `BlueWhale.AutoHealerACR`
    ///    （两个程序集，本地层不能依赖 AI 层 —— 开发约定 G）。
    /// ⚠️ 为什么包 try：AI 层没加载时不能让本地层崩。
    /// ⚠️ 只**首次**调用有效（AI 层内部只写一次）—— 所以放 `Build()` 最稳。
    ///
    /// [!] 找不到就静默返回 —— 那是**正常情况**（用户没装 AI 层）。
    ///
    /// [!] 背景（连续 16 次崩溃的真正根因）：
    ///    AI 层的 `采集()` 会调 84 处以上游戏 API，而它在 `async Task` 里
    ///    （**后台线程**），与主线程每帧的同类调用**竞争非线程安全的进程内 API**。
    ///    修法是"采集只在主线程跑，后台线程读缓存"——
    ///    而**主线程 id 必须在确定是主线程的地方写**（就是这里）。
    /// </summary>
    private static void 标记AI层主线程()
    {
        try
        {
            foreach (var 程序集 in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type? 类型 = null;
                try { 类型 = 程序集.GetType("BlueWhale.AutoHealerACR.AiSituation", false); }
                catch { }
                if (类型 == null) continue;
    
                var 方法 = 类型.GetMethod(
                    "标记主线程",
                    System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static,
                    null, Type.EmptyTypes, null);
                if (方法 == null) continue;
    
                方法.Invoke(null, null);
                return;   // 找到并调用了，收工
            }
        }
        catch { }
    }
    
    internal static void 尝试挂载AI层反射()
    {
        // [!] **故意不缓存"找过"** ——
        //     这个方法的用途正是**兜底**：只要哪一帧发现自己是当前 ACR 就该挂上。
        //     如果缓存"找过"，那么第一帧（BlueWhale 可能还没加载完）找不到之后，
        //     用户再切到小鲸鱼时也会被缓存挡掉 —— **兜底彻底失效**。
        //
        //     性能不是问题：挂上之后 `尝试挂载AI层()` 里 `_已挂载` 立即短路，
        //     所以这段反射只在**没挂上**时每帧跑 —— 那本来就是异常状态。
        try
        {
            foreach (var 程序集 in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type? 类型 = null;
                try { 类型 = 程序集.GetType("BlueWhale.AutoHealerACR.Ai层挂载", false); }
                catch { }
                if (类型 == null) continue;

                var 方法 = 类型.GetMethod("尝试挂载AI层",
                    System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static);
                方法?.Invoke(null, null);
                return;
            }
        }
        catch { }
    }

    public virtual void Dispose()
    {
        // ══════════════════════════════════════════════════════════════
        //  ★ 卸载时把每帧回调摘掉 ★
        //
        //  [!] 实测 bug：不清的话，重载 ACR / 切到别的 ACR 之后，
        //      小鲸鱼的回调**还在每帧跑** —— 现象是
        //      "已经切到别的 ACR 了，左下角还在刷小鲸鱼的日志"。
        //
        //  [!] 三重保护，不把正确性押在任何一条上：
        //      ① `Dispose` 里把代次作废（下面这行）
        //      ② 回调内部的代次守卫
        //      ③ 回调内部的旋转对象守卫
        //      本项目栽过"以为框架会调某方法、结果它没调"的坑
        //      （`OnBattleUpdate` 只在战斗里跑就是最典型的一次），
        //      所以 ②③ 必须在，`Dispose` 只是主动一点。
        // ══════════════════════════════════════════════════════════════
        _每帧回调 = null;

        // ══════════════════════════════════════════════════════════════
        //  ★ AI 层也要一起卸载 ★
        //
        //  [!] 为什么必须（用户实测）：重载 ACR 之后如果只摘回调、
        //      不卸 AI 层，那么 AI 的钩子（记忆钩子 / 状态重置钩子 /
        //      记录模式的事件订阅）**还挂着** ——
        //      于是切到别的 ACR 后：
        //        · 仍在发 API 请求（白花 Key 的钱）
        //        · 仍往聊天框打日志
        //        · 记录模式的事件订阅还在（往没人管的采集器塞数据）
        //
        //  [!] 走**钩子**而不是直接引用 BlueWhale：
        //      `HealerACR.csproj` 只编译自己目录，两个 dll 里各有一份
        //      HealerACR 的类，直接加 ProjectReference 会**循环依赖**。
        //      => 和既有的 `记忆钩子` / `状态重置钩子` 同一个模式。
        //
        //  [!] 只做"卸载"，**不做"重置"** ——
        //      重置清的是阈值平滑这类战斗状态，那是"换本"该做的事。
        // ══════════════════════════════════════════════════════════════
        // ══════════════════════════════════════════════════════════════
        //  ★ 通知 AI 层卸载 —— **先摘钩子，再通知，且只通知一次** ★
        //
        //  [!] 为什么顺序不能反（3.19.4 引入的闪退根因）：
        //      `卸载钩子.卸载` 指向 `Ai层挂载.卸载`，而后者又会去动这个钩子。
        //      先通知的话，一旦链路里再触发一次 `Dispose`，就成环：
        //          Dispose -> 通知 -> Ai层挂载.卸载 -> … -> Dispose
        //      => `StackOverflowException` => `0xc0000005` => **游戏闪退**
        //      （栈溢出绕过所有 try/catch，所以这里 try 也救不了）
        //
        //  [!] 先摘再通知：钩子已摘 => 中途再被通知也没人接 => 断环。
        //  [!] 一次性标记：ACR 重载时框架可能对同一入口多次调 Dispose。
        // ══════════════════════════════════════════════════════════════
        if (!_已通知卸载)
        {
            _已通知卸载 = true;
            try { 卸载钩子.卸载 = null; } catch { }   // ★ 先断环 ★
            try { 卸载钩子.通知(); } catch { }
        }
    }
}

