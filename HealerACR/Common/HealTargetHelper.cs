public static class HealTargetHelper
{
    /// <summary>
    /// 按血量比例升序的、可以被治疗的队友。
    ///
    /// ⚠️ 默认半径 30 米（单体治疗够用），但**群疗判断必须传技能真实半径** ——
    ///    见 <see cref="低于阈值人数(float, float)"/> 的说明。
    /// </summary>
    /// <summary>
    /// 最近一次「可治疗队友」**返回空表的原因** —— 给调试窗 / AI 诊断用。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要它（2026-10-03 用户实测）：
    ///      调试窗里只写 `治疗=0（没有可治疗队友）`，而"空表"有 **7 种完全不同的成因**：
    ///        在切图 / 地图 id=0 / 队伍服务返回 null / 物化失败 /
    ///        第 N 个对象无效 / 预检抛异常 / 外层异常
    ///      —— 只看到"没有队友"就**分不清是哪一种**，只能猜（这次就卡在这里）。
    ///      ⇒ 每个空返回都写明原因，窗口直接显示出来。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static string 最近空原因 = "还没调用过";

    /// <summary>统一的"空表返回" —— 顺手把原因记进 `最近空原因`。</summary>
    private static List<IBattleChara> 空(string 原因)
    {
        最近空原因 = 原因;
        return new List<IBattleChara>();
    }

    /// <summary>
    /// **可治疗队友**（对外入口）—— 里面那层是 `可治疗队友_内部`。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么要包一层（2026-10-03 用户实测）：
    ///      内部有**多条**返回空表的出口（7 个 `空(...)` + 排序后返回 + 主循环筛完为空）。
    ///      漏掉任何一条，`最近空原因` 就会停在初始值 **"还没调用过"** ——
    ///      窗口上看起来像"根本没跑过"，其实跑过、只是结果为空
    ///      （用户两次截图里都是这一句，害我们多查了一轮）。
    ///      ⇒ 包一层：**每次调用先清空原因**，返回空还没写原因就补一句通用的，
    ///        这样"空表"永远带得出解释。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static List<IBattleChara> 可治疗队友(float 半径 = 30f)
    {
        最近空原因 = "";
        var 结果 = 可治疗队友_内部(半径);
        if (结果.Count == 0 && 最近空原因.Length == 0)
            最近空原因 = "内部返回了空表但没写明原因（说明是「全部被筛选掉」或「排序后为空」这类出口）";
        return 结果;
    }

    private static List<IBattleChara> 可治疗队友_内部(float 半径 = 30f)
    {
        using var _深度 = HealerACR.Common.调用深度.进("可治疗队友");
        // ══════════════════════════════════════════════════════════════
        //  ★ 这是**所有治疗目标的唯一入口**，所以韧性放在这里 ★
        //
        //  [!] 崩溃签名（Windows 事件 1026，进程 ffxiv_dx11.exe 被杀）：
        //        Dalamud...BattleChara.get_StatusList()
        //        AEAssist...MemApiBuff.HasAnyAura(...)
        //        HealerACR...HealTargetHelper.<可治疗队友>b__0_1   <- 就是下面那个 lambda
        //
        //  [!] **为什么原来那个 `catch` 不够** ——
        //      这类崩溃是**访问违例**（`0xc0000005`）级别，会**穿透 C# 的 catch**。
        //      ==> 不能指望"外面包了 try 就安全"。
        //      ==> 真正有效的是**两步都做**：
        //           ① 进 lambda 之前先筛掉无效对象（下面 `对象有效()`）
        //           ② 触到游戏对象的每一步各自包 try（Linq 的延迟求值会把异常
        //              拖到 `ToList()` 那一刻，报错位置和真实位置不一致）
        //
        //  [!] 拿不到就返回**空列表**，方向很重要：
        //      空列表 => 治疗以为"没人需要治" => **什么都不做**，
        //      而不是去读一个可能失效的对象。宁可少治一次，不要崩游戏。
        // ══════════════════════════════════════════════════════════════
        try
        {
            // ══════════════════════════════════════════════════════════════
            //  ★ 第 0 道：**场景可信吗** —— 不可信就整批不读 ★
            //
            //  [!] 崩溃转储（`dalamud_appcrash_*_154349_357_12772.log`）显示：
            //        地址: **12345679**（Dalamud 的"已释放对象"哨兵）
            //        BattleChara.get_StatusList()
            //        MemApiBuff.HasAnyAura
            //        HealerACR.<可治疗队友>b__0_1   <- 本方法的 lambda
            //        伤害预测.预计掉血人数 -> 调试窗.画预测 -> 绘制
            //      而第 3 次崩溃时加的"整体预检"（下面那道）**没能挡住** ——
            //      因为"判完有效"到"读 buff"之间那**极窄的窗口**依然存在：
            //      换区 / 队友掉线 / 对象池回收，都能在这一瞬间把对象释放掉。
            //
            //  [!] **访问违例（0xc0000005）会穿透 C# 的 `catch`** ——
            //      所以这里**不能**靠 try，只能在**读之前**判定"不能读"。
            //
            //  [!] 判据（和 `调试窗.cs` 那三条同源，别自造）：
            //        ① 游戏自己说在切图 -> 整批对象都不可信
            //        ② 地图 id 为 0（不在任何场景）-> 同上
            //      代价是"换区那一两帧治不了人" —— 本来也治不了（人都不在场景里）。
            //
            //  [!] 注意：这个判据**只挡"明显不可信"**，不挡单点失效 ——
            //      单点的由下面两道 + `可以治()` 里"读之前再判一次"负责。
            // ══════════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★★ **原子路标：这一行才是真正的函数入口** ★★
            //
            //  [!] 外部审查的关键纠正：原来那个 `3500` 路标**不是第一行** ——
            //      它前面还有 `IsBetweenAreas()` / `实时副本Id()` / 队伍列表 getter。
            //      ==> **"日志里没有 3500" 不能证明"没进入本函数"** ——
            //          可能死在前面那三个 native 调用的任意一个里。
            //      ==> 所以必须把探针放到**方法体的第一条语句**。
            //
            //  [!] 同时记录审查者要的"身份信息"：
            //      · 线程 id        —— 确认 AI 层到底在哪个线程调
            //      · 程序集名/位置  —— 确认是 HealerACR.dll 还是 BlueWhale.dll 那份拷贝
            //      · ALC 名字       —— 确认是否在独立 AssemblyLoadContext（dev plugin reload 相关）
            //      这三项能把"猜测型排查"变成"定位型排查"。
            // ══════════════════════════════════════════════════════════════
            本地路标.记详(3490, $"可治疗 方法体第一行｜线程={Environment.CurrentManagedThreadId}" +
                                 $"｜程序集={typeof(HealTargetHelper).Assembly.GetName().Name}" +
                                 $"｜ALC={System.Runtime.Loader.AssemblyLoadContext.GetLoadContext(typeof(HealTargetHelper).Assembly)?.Name ?? "(默认)"}" +
                                 $"｜半径={半径}");

            try
            {
                本地路标.记详(3491, "即将 IsBetweenAreas");
                var 在切图 = Core.Resolve<AEAssist.MemoryApi.MemApiCondition>().IsBetweenAreas();
                本地路标.记详(3492, $"IsBetweenAreas 返回 {在切图}");
                if (在切图)
                    return 空("游戏说在切图（IsBetweenAreas）");
            }
            catch (Exception e) { LogHelper.Info("[HealerACR.路标] 3491 抛异常：" + e.GetType().Name); }

            try
            {
                本地路标.记详(3493, "即将 实时副本Id");
                var 副本 = HealerACR.Timeline.TimelineManager.实时副本Id();
                本地路标.记详(3494, $"实时副本Id 返回 {副本}");
                if (副本 == 0)
                    return 空("地图 id 读到 0（AEAssist 与 Dalamud 两路都没有）");
            }
            catch (Exception e) { LogHelper.Info("[HealerACR.路标] 3493 抛异常：" + e.GetType().Name); }

            // ══════════════════════════════════════════════════════════════
            //  ★ 第一道：**先整体确认这个队伍可不可信，不可信就直接空手退出 ★**
            //
            //  [!] 这是第 3 次闪退之后加的。前两次失败的原因现在清楚了：
            //      转储里 `异常信息 #0 地址: **12345679**` ——
            //      那是 Dalamud 的"已释放对象"哨兵地址，
            //      而当时的 `对象有效()` 只检查 `Address != 0`
            //      ==> **哨兵地址通过了检查** ==> 随后读 `StatusList` 踩空 ==> 进程被杀。
            //      （`对象有效()` 本身已修好，这里是**第二道**。）
            //
            //  [!] 为什么还要这道：`对象有效()` 修好之后，
            //      "检查通过"到"真正读 buff"之间仍有极短的窗口。
            //      而 `PartyHelper.CastableAlliesWithin30` 在换区时会**整批**
            //      变成失效对象 —— 只要发现**任何一个**失效，
            //      就说明这一帧整个队伍不可信，**这一次调用直接放弃**。
            //
            //  [!] 代价是"换区那一两帧治不了人" —— 本来也治不了（人都不在场景里）。
            // ══════════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★ **只取一次 getter** —— 外部审查 P0-2（我核实确认为真）★
            //
            //  [!] 原来的写法是**两次取**：
            //        L130  var 待检 = PartyHelper.CastableAlliesWithin30;   // 预检
            //        L177  var 原始 = PartyHelper.CastableAlliesWithin30;   // 真正物化
            //      ==> 同一个 getter 被调两次，而两次之间：
            //            · 换区 / 队友离开 / 对象重建都可能发生
            //      ==> **预检验的那批**和**真正用的那批可能不是同一批**
            //      ==> 预检就失去意义（它证明的不是即将使用的那批）
            //
            //  [!] 正确做法：**取一次 -> 立刻 `ToArray()` 物化 -> 之后只用数组**。
            //      物化把原生集合的引用一次性拷进托管数组，
            //      预检和正式遍历**用的是同一批引用**，中间没有时间窗口。
            // ══════════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★ 物化后的数组 —— **在 try 之外声明**，因为下面两段都要用它 ★
            //    （P0-2 修复：整个方法只取一次 getter，物化一次，之后都用它）
            // ══════════════════════════════════════════════════════════════
            IBattleChara[] 快照;

            try
            {
                本地路标.记详(3495, "即将取 PartyHelper.CastableAlliesWithin30");
                var 原始 = PartyHelper.CastableAlliesWithin30;
                本地路标.记详(3496, $"队伍列表已取，{(原始 == null ? "null" : 原始.Count + " 个")}");
                if (原始 == null) return 空("AEAssist 的队伍列表为 null");

                // ① 立刻物化 —— 之后**绝不再碰那个 getter**
                try { 快照 = 原始.ToArray(); }
                catch { return 空("队伍列表物化失败（ToArray 抛异常）"); }
                本地路标.记详(3504, $"已物化 {快照.Length} 个");

                // ② 预检：在**同一批**上验有效性
                //
                // ══════════════════════════════════════════════════════════
                //  [!] ⚠️ 2026-10-03 改：**不再"一个坏就丢整队"**（用户实测）
                //
                //  现象（调试窗印出来的原因）：
                //    治疗=0（没有可治疗队友（**队伍第 1 / 1 个对象无效**））
                //    而"队伍"只有 1 个对象 = **玩家自己**（单人局）
                //    ⇒ 整队被判无效 ⇒ 治疗候选永远是 0 ⇒ AI 永远没有治疗候选。
                //
                //  为什么原来写"全丢"：换区那一瞬间整批对象确实会一起失效，
                //  全丢是最保守的做法。但代价是**误伤**：
                //  · `对象有效()` 旧实现第一句是原生读 `GameObjectId`，
                //    抛一次异常就把**活着的对象**判成无效（见 `CharacterExt` 的说明）；
                //  · 只要**任何一个**队友那一下读失败，整队就没了。
                //
                //  为什么现在敢放宽：
                //  ① 下面那个主循环**本来就是逐个 `continue` 跳过**坏对象的
                //     （判 + 读在同一瞬间完成，见下面 3505 那段），
                //     ⇒ 预检"全丢"是**多余且更严**的一层，去掉不会让坏对象被使用；
                //  ② `对象有效()` 已改成**地址优先**（纯托管判据先做），
                //     不会再对活对象误判，也不会在判据里踩原生内存；
                //  ③ 真正的区域门是上面 ①②（在切图 / 地图 id），那两道仍在前头。
                //
                //  ⇒ 现在的语义：**全部**都无效才返回空（并写明原因），
                //     只要有一个可用就继续 —— 坏的那些由主循环跳过。
                // ══════════════════════════════════════════════════════════
                var 有效数 = 0;
                var 首坏原因 = "";
                for (var i = 0; i < 快照.Length; i++)
                {
                    本地路标.记详(3497, $"正在验第 {i} 个");
                    var rr = 快照[i];
                    if (rr == null)
                    {
                        if (首坏原因.Length == 0) 首坏原因 = $"第 {i + 1}/{快照.Length} 个为 null";
                        continue;
                    }
                    if (rr.对象有效(out var 坏原因)) { 有效数++; continue; }
                    if (首坏原因.Length == 0) 首坏原因 = $"第 {i + 1}/{快照.Length} 个：{坏原因}";
                }

                if (有效数 == 0)
                    return 空($"队里 {快照.Length} 个对象全部无效（{首坏原因}）");

                if (首坏原因.Length > 0)
                    本地路标.记详(3498, $"预检：{有效数}/{快照.Length} 个有效 —— 坏的会被主循环跳过（{首坏原因}）");
                else
                    本地路标.记详(3498, $"全部 {快照.Length} 个都有效");
            }
            catch { return 空("预检队伍时抛异常"); }

            // ══════════════════════════════════════════════════════════════
            //  ★★★ **一个都没给时：把自己用 Dalamud 补进来** ★★★（2026-10-03 用户实测）
            //
            //  [!] 现场证据（调试窗那行诊断）：
            //        治疗=0（没有可治疗队友（**还没调用过**））
            //      "还没调用过"是 `最近空原因` 的初始值 ⇒ 说明空表**不是**从任何一个
            //      `空(...)` 出口出去的 ⇒ 是"队伍列表本来就是 0 个"：
            //      `PartyHelper.CastableAlliesWithin30` 给的是**队友**，**单人局返回 0 个**
            //      （**不含你自己**）⇒ 下面的主循环一次都不跑 ⇒ 直接返回空表。
            //      ⇒ 后果：单人打木人时，「给自己加血 / 给自己上盾」这类候选永远是 0，
            //        AI 拿到的候选集也永远是空 ⇒ 只能退回技能 ID 模式。
            //
            //  [!] ✅ 兜底用 **Dalamud 的 `LocalPlayer`**（宿主，不会被重载搞坏，
            //      也不依赖 AEAssist 的队友服务 —— 同一晚已经因为它踩过好几次）。
            //      单人局补上"自己"；有多人队伍时 AEAssist 那份非空，这里不会进来。
            //
            //  [!] 只补"自己"这一份：Dalamud 的 `IPartyMember` 在本版本里
            //      不派生 `IGameObject`（写死了编译不过），队伍成员那份仍走 AEAssist。
            // ══════════════════════════════════════════════════════════════
            if (快照.Length == 0)
            {
                try
                {
                    var 自己 = ECommons.DalamudServices.Svc.Objects.LocalPlayer;
                    if (自己 == null)
                        return 空("AEAssist 队伍列表为 0 个，且 Dalamud 也读不到自己");

                    if (!自己.对象有效(out var 自己原因))
                        return 空($"AEAssist 队伍列表为 0 个，Dalamud 的自己无效（{自己原因}）");

                    if (自己 is not IBattleChara 自己角色)
                        return 空("AEAssist 队伍列表为 0 个，且 Dalamud 的自己不是可治疗角色类型");

                    快照 = new[] { 自己角色 };
                    本地路标.记详(3504, "队伍列表为 0 个（单人局）⇒ 已用 Dalamud 把自己补进来");
                }
                catch (Exception e)
                {
                    return 空("AEAssist 队伍列表为 0 个，取 Dalamud 自己时抛异常：" + e.GetType().Name);
                }
            }

            // ══════════════════════════════════════════════════════════════
            //  ★★ **一次性物化 + 立即标量化 + 纯托管排序** ★★
            //
            //  [!] 为什么必须推倒重写（外部审查指出的、我之前没意识到的关键点）：
            //
            //      原来的写法是**惰性链**：
            //          var 源 = PartyHelper.CastableAlliesWithin30.Where(...);   // 不执行
            //          return 源.Where(r => r.对象有效() && r.可以治())           // 不执行
            //                    .OrderBy(r => r.有效血量比例())                    // 不执行
            //                    .ToList();                                        // ★ 真正执行在这里
            //
            //      ==> **"预检"和"真正读取"之间隔着整条延迟链**，中间可能过了很久。
            //      ==> `对象有效()` 只能证明**检查那一瞬间**有效，
            //          **不能保证本次操作期间一直有效**。
            //      ==> 这就是"修了 43 处元素级守卫仍然崩"的原因 —— **守卫在时间上太早了**。
            //
            //  [!] 另外两个问题：
            //      · `PartyHelper.CastableAlliesWithin30` 被读了 **3 次**（预检 / 两分支）
            //        —— 它可能是**每次访问都重建的原生集合**，而 `源` 直接持有它。
            //      · `OrderBy` 会**物化并重新枚举**，`r.Position` / `有效血量比例()` 会被读多次。
            //
            //  [!] 修法（三步，彻底消除延迟求值）：
            //      ① **一次读取**集合，**立即 `ToArray()`** 物化成托管数组
            //      ② **一次遍历**，每读到一个对象就**立刻**做完所有 native 判定，
            //         并通过 `一次读完()` **在同一瞬间**把标量取出来
            //      ③ **纯托管排序** —— 用取好的 `float` 排序，排序时**不再碰游戏对象**
            //
            //  [!] 这样"判"和"读"之间没有时间窗口，`PartyHelper` 只读一次，
            //      排序阶段完全在托管内存里。**native 对象只存在于循环体那几行。**
            // ══════════════════════════════════════════════════════════════
            本地路标.记详(3503, "可治疗：即将一次性读取队伍集合");

            // ★ 集合已经在上面【取一次 + 物化 + 同批预检】过了（P0-2 修复）
            //   这里直接用那份 `快照`，**不再访问 getter**。
            //   ⚠️ 注意：这里**不能再声明** `原始` 或 `快照` —— 会与上面的重名。

            var 我 = CharacterExt.我的位置();
            var 结果 = new List<IBattleChara>(快照.Length);
            var 分数 = new List<float>(快照.Length);

            // ② 一次遍历：判 + 读 全在同一瞬间完成
            for (var i = 0; i < 快照.Length; i++)
            {
                本地路标.记详(3505, $"可治疗：处理第 {i} 个");
                var r = 快照[i];
                if (r == null) continue;

                // ★ 一次读完所有需要的 native 值（判 + 读在同一瞬间，无延迟链）
                var 有效 = false;
                var 可治 = false;
                var 血比 = 999f;
                var 距离够 = true;
                try
                {
                    有效 = r.对象有效();
                    if (!有效) continue;
                    可治 = r.可以治();
                    if (!可治) continue;
                    if (半径 < 30f)
                        距离够 = Vector3.Distance(我, r.Position) <= 半径;
                    if (!距离够) continue;
                    血比 = r.有效血量比例();
                }
                catch { continue; }

                结果.Add(r);
                分数.Add(血比);
            }
            本地路标.记详(3506, $"可治疗：过滤后 {结果.Count} 个，即将纯托管排序");

            // ③ 纯托管排序 —— 只比较取好的 float，**不再触碰任何游戏对象**
            try
            {
                var 序 = new int[结果.Count];
                for (var i = 0; i < 序.Length; i++) 序[i] = i;
                Array.Sort(序, (a, b) => 分数[a].CompareTo(分数[b]));
                var 排好 = new List<IBattleChara>(结果.Count);
                foreach (var i in 序) 排好.Add(结果[i]);
                本地路标.记详(3507, "可治疗：排序完成");
                return 排好;
            }
            catch
            {
                return 结果;   // 排序失败就返回未排序的（不影响正确性，只是优先级差一点）
            }
        }
        catch
        {
            return 空("外层异常（可治疗队友整体 try 的 catch）");
        }
    }

