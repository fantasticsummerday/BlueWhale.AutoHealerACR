                if (敌人状态.攻击无效(敌人)) continue;
                // ★ 2026-10-04 补：**招架(680)** 也是"打上去没伤害"的一类 ——
                //   参考实现的 DoT 候选枚举把 680 和两个魔法攻击无效化一起排除 ✓
                if (敌人状态.招架中(敌人)) continue;
                // ★ **不可选中**的怪别上毒 ——
                //   转场 / 无敌演出期间 `IsTargetable` 会短暂为 false，
                //   这时候按下去技能放不出来，还白占一个 GCD。
                try { if (!敌人.IsTargetable) continue; } catch { }

                try
                {
                    if (敌人.CurrentHp <= 0) continue;
                    if (当前 != null && 敌人.GameObjectId == 当前.GameObjectId) continue;
                    // ★ 2026-10-04：改用**稳定**仇恨（原来用瞬时的 `有仇恨`，它把「正在打我自己」也算合格 ✗）
                      //   无坦克时退回瞬时判据（单人场景没有「拉稳」可言 ✓）
                      if (!(有坦克时() ? 稳定仇恨(敌人) : 有仇恨(敌人))) continue;

                      // ★ 2026-10-04 用户实测：「他一直给仇恨没拉稳的怪上 DoT」
                      //   `有仇恨()` 只看"这怪在打我方任何人（含我自己）" ⇒ 正在打奶妈的怪照样合格 ✗
                      //   参考精神：输出目标跟坦克锁定的目标 ✓ ⇒ 有坦克时，跳过"正在打我"的怪 ✓
                      //   ⚠️ 单人/无坦克时不改行为（那时怪我本来就是对的 ✓）
                      try
                      {
                          var 坦克0 = 主坦();
                          if (坦克0 != null && 坦克0.对象有效())
                          {
                              var 我的Id0 = Core.Me?.GameObjectId ?? 0;
                              if (我的Id0 != 0 && 敌人.TargetObjectId == 我的Id0) continue;
                          }
                      }
                      catch { }              // ★ 本次修的核心
                    if (有我的Dot(敌人)) continue;

                    var 距离 = Vector3.Distance(我, 敌人.Position);
                    if (距离 > 半径) continue;

                    结果.Add(敌人);
                }
                catch { }
            }

            // 排序：近的优先（少走位、少切目标的时间）
            结果 = 结果.OrderBy(x =>
            {
                try { return Vector3.Distance(我, x.Position); }
                catch { return 999f; }
            }).Take(最多几个).ToList();
        }
        catch { }

        return 结果;
    }

