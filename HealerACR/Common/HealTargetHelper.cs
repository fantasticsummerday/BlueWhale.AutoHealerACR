    ///          而"没人拉"的代价是灭团。**宁可重复，不能没人。**
    ///
    ///    防重复交给 复活等待 buff（已经有人挂了复活就不重复拉）。
    /// </summary>
    public static bool 该我复活()
    {
        // 四人本（单奶）：只有我能拉，无条件自己上。
        // 八人本（双奶）：也不搞单方面谦让 —— 对方如果是别的 ACR，
        //   它不知道我在等它，结果两个都不拉（这就是 T 死了没人复活的根因）。
        //   防重复交给「复活等待」buff，那个机制本来就够用。
        return true;
    }

    /// <summary>
    /// 躺在地上、还没被挂复活 buff 的队友（含多奶妈协调）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 复活优先级：**坦克 &gt; 奶妈 &gt; 赤魔 &gt; 其他 DPS** ★
    ///
    ///  [!] 用户 2026-10-04 拍板：按参考实现（youshu）的顺序。
    ///      我们原来是自己定的「奶妈 &gt; 坦克 &gt; 其他」（理由是"奶妈躺了治疗断档"），
    ///      但**参考的顺序更有道理**：
    ///        · **坦克先拉** —— 没坦克怪会转向所有人，全队立刻崩；
    ///        · 然后才是奶妈 —— 治疗断档是"慢慢疼"，拉不住怪是"当场死"；
    ///        · **赤魔（Red Mage）第三** —— 他有「复活」能起来再拉别人，
    ///          拉他等于多一个复活源（这是"谁都没想到"的那一层）；
    ///        · 最后才是其他 DPS。
    ///
    ///  [!] 过滤两类，**含义完全不同，别搞混**：
    ///     · 复活等待(148)  —— 别人已经在拉了 → 防"两个奶妈抢同一个尸体"
    ///     · 限制复活(5 个) —— 这个尸体**根本拉不起来** → 防"白交即刻和 GCD"
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static IBattleChara? 待复活队友()
    {
        // 多奶妈协调：不是"我负责"就返回空，让另一个奶妈去拉
        if (!该我复活()) return null;

        var 躺着的 = PartyHelper.DeadAllies
            .Where(r => r != null && !r.被禁止复活())
            .ToList();

        if (躺着的.Count == 0) return null;

        // ── ① 坦克 ──
        var 坦克 = 躺着的.FirstOrDefault(r => 职业表.是坦克(r));
        if (坦克 != null) return 坦克;

        // ── ② 奶妈 ──
        var 奶妈 = 躺着的.FirstOrDefault(r => 职业表.是奶妈(r));
        if (奶妈 != null) return 奶妈;

        // ── ③ 赤魔（24）—— 他能起来再拉别人，等于多一个复活源 ──
        var 赤魔 = 躺着的.FirstOrDefault(r => 职业表.是赤魔(r));
        if (赤魔 != null) return 赤魔;

        // ── ④ 其他 DPS ──
        return 躺着的[0];
    }

    /// <summary>
    /// 周围敌人数量（AOE 判断用）。
    ///
    /// ⚠️ 必须**以当前目标为中心**数，不能以自己为中心 ——
    /// 奶妈站远程位，以自己为中心 5 米内经常一个敌人都没有，
    /// 结果就是 AOE 永远不触发。
    /// </summary>
    /// <param name="伤害范围">技能命中后的伤害范围（米）</param>
    /// <param name="施法范围">技能施法距离（米）</param>
    public static int 周围敌人数量(float 伤害范围 = 5f, float 施法范围 = 25f)
    {
        // 对照官方文档的 CheckNeedUseAOE：施法范围和伤害范围要**分别传**。
        // 之前我把两个都写死成 5 米，等于把"能不能打到"和"能打几个"混为一谈了。
        //
        // ══════════════════════════════════════════════════════════════════
        //  ★★ **传给 AEAssist 的对象必须先验有效性** ★★
        //
        //  [!] `TargetHelper.GetNearbyEnemyCount` 是 **AEAssist 自己的代码**，
        //      它**不知道我们的哨兵约定**（已释放对象的地址是 `0x12345679`，
        //      **不是 null**）。把这种对象交给它 ==> 它在内部直接读内存
        //      ==> **原生访问违例发生在它的函数体里**
        //      ==> 我们的 `try/catch` 和**全局异常钩子都在它外面**，
        //          所以连续 12 轮排查里钩子**一次都没触发过**。
        //
        //  [!] 这是本项目最隐蔽的一类崩溃：**防线一交出去就断了**。
        //      铁律：**绝不能把"未验证有效"的游戏对象传给外部库**。
        //      （`当前目标()` 现在自带 `对象有效()`；这里再判一次是**刻意重复** ——
        //        将来若有人改 `当前目标()`，这里不能跟着破防。）
        // ══════════════════════════════════════════════════════════════════
        var t = 当前目标();
        if (t != null && t.对象有效())
            return TargetHelper.GetNearbyEnemyCount(t, (int)施法范围, (int)伤害范围);

        // ⚠️ 没有**可信**目标时，改走**我们自己**的安全实现（`自身周围敌人数量`
        //    逐对象判 `对象有效()`），而不是 `TargetHelper.GetNearbyEnemyCount(int)`
        //    —— 后者同样来自外部库，且连"以谁为中心"都不需要，行为更难预期。
        //    数值上两者都是"以我为中心、按伤害范围数"，语义一致。
        return 自身周围敌人数量(伤害范围);
    }

    /// <summary>
    /// **以玩家自己为中心**数敌人（用来判断"对自身周围"的 AOE 能打到几个）。
    ///
    /// ⚠️ 和 <see cref="周围敌人数量"/> 的关键区别：
    ///    那个是**以当前目标为中心**数（奶妈站远程位时要靠它才数得到），
    ///    这个**以自己为中心** —— 因为「破阵法 / 裂阵法」是
    ///    `CastType=2 射程=0 效果范围=5` 的**自身圆形 AOE**，
    ///    判定就是"我周围 5 米内有几个敌人"。
    ///
    /// ⚠️ 用法上必须按技能的 `EffectRange` 传半径 ——
    ///    传错半径会得出错的命中数，进而选错技能。
    ///
    /// ⚠️ 用 `敌人.HitboxRadius` 放宽：Boss 的目标圈有大有小，
    ///    严格按中心距会在"贴着大 Boss"时少数。
    /// </summary>
    public static int 自身周围敌人数量(float 半径 = 5f)
    {
        var 数 = 0;
        try
        {
            var 我 = CharacterExt.我的位置();

            foreach (var 敌人 in Data.AllHostileTargets)
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (敌人 == null || !敌人.对象有效()) continue;
                if (敌人.CurrentHp <= 0) continue;
                // ★ 2026-10-04：**攻击无效的怪不计入 AOE 命中数** ✓
                //   （对照实现的 AOE 计数同样查攻击无效状态；漏了它会把「打不动的怪」算成命中 ⇒ 白放 AOE）
