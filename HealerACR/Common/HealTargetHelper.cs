    ///
    ///  ⚠️ 只返回**有仇恨**的（用 `有仇恨()`）—— 这是本次修的核心。
    ///  ⚠️ 排除当前目标（那个归 `Res_Dot` 管，避免重复建议）。
    /// ══════════════════════════════════════════════════════════════════
