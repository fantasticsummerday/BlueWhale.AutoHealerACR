    /// <summary>当前选中的敌人（挂 DoT / 打输出用）</summary>
    public static IBattleChara? 当前目标()
    {
        var t = CharacterExt.我的目标();
        if (t == null) return null;

        // ══════════════════════════════════════════════════════════════════
        //  ★★ **必须判 `对象有效()` —— 原来只判 `CurrentHp > 0`** ★★
        //
        //  [!] 为什么这是**致命**的（连续 12+ 次崩溃的真正根因）：
        //      本函数返回的对象会被交给 **AEAssist 自己的 API**，例如
        //          `TargetHelper.GetNearbyEnemyCount(t, 施法范围, 伤害范围)`
        //      而 **AEAssist 的代码不知道我们的哨兵约定** ——
        //      它会直接读 `t` 的内存。对象在换图/切区时已被释放
        //      （地址是哨兵 `0x12345679`，**但不是 null**），
        //      ==> **原生访问违例发生在 AEAssist 内部**，
        //          我们的 `try/catch` 和全局异常钩子**全都在它外面**，
        //          所以 12 轮排查里钩子一次都没触发过。
        //
        //  [!] 崩溃路径（实测日志 `Log-0308847.log` 的路标）：
