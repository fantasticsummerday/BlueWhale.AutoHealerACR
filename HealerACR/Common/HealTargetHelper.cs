        catch
        {
            return 基础保留;
        }
    }

    /// <summary>
    /// 复活时该不该由我负责。
    ///
    /// ⚠️ **修正（现象：90 级本 T 死了没人复活，而且即刻是好的）**
    ///
    ///    原来这里实现的是"两个奶妈时，只让对象 ID 最小的那个拉人"，
    ///    本意是避免重复。但实际会死锁：
    ///      · 如果对方奶妈是别的 ACR（比如其他 ACR），它很可能也有自己的协调逻辑
    ///      · 两边互相谦让 → **两个都不拉**
    ///      · 更糟的是这个判断在"有没有即刻"之前就 return 了，
    ///        所以表现成"明明即刻是好的，就是不拉人"
    ///
