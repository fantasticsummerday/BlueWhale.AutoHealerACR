using AEAssist;
using AEAssist.Helper;

namespace HealerACR.Common;

/// <summary>
/// 记录模式 —— **只观察，不动手**。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 这是什么 ★
///
///    用户要的一个模式：开了之后 **ACR 完全不参与输出和治疗**，
///    只把**玩家自己手动**放的每一个技能连同当时的局面记录下来。
///    副本结束后由 AI 提炼成"记忆库"，下次初始化时喂回给 AI。
///
///    目的是拿到**人类高手打法的参考答案** ——
///    这是记忆库唯一的可信来源（见下面"为什么必须停手"）。
///
///  ★ 为什么必须"完全停手"（用户选择的最严格档）★
///
///    记忆库最大的风险是**回音壁**：
///      ACR 做决策 → 存库 → 检索到 → 照做 → 又存库
///    越用越确信自己的习惯是对的，**错误被固化**。
///
///    所以记录模式里必须让 ACR 一个技能都不放 ——
///    这样"记录到的每一条"都必然是玩家手动按的，**归属天然干净**，
///    不需要任何启发式去猜"这条是谁放的"。
///
///    ⚠️ 代价：这期间 **ACR 不会替你奶**，全程得自己操作。
///       这是有意的取舍 —— 数据纯度优先。
///
///  ★ 为什么放在 HealerACR 这边（而不是 BlueWhale）★
///
///    "停手"是**战斗行为的开关**，必须由本地层执行 ——
///    否则就违反了 开发约定.md G 节（AI 是增强层，不能成为必需品）。
///    存盘和提炼那一半需要 AI，放在 BlueWhale 用钩子接
///    （和 记忆钩子 / 状态重置钩子 同一个套路）。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 记录模式
{
    // ==================== 开关 ====================

    /// <summary>
    /// 是否处于记录模式。
    ///
    /// ⚠️ 这个标志**同时被两处读取**，改它必须两处都生效：
    ///   · `HealerEntryBase.构建决策队列()` —— 返回空队列 = ACR 停手
    ///   · <see cref="每帧更新"/> —— 只有开启时才观察玩家操作
    /// </summary>
    public static bool 开启 { get; private set; }

    /// <summary>
    /// 记录模式下是否**保留保命兜底**。
    ///
    /// 用户选了"只记录，完全不动" → 默认 **false**（最纯净）。
    /// 留这个开关是因为日随里全程手动奶确实累，
    /// 万一以后想放松一点，改这里就行。
    ///
    /// ⚠️ 一旦打开，记录里就会出现 ACR 自己的操作 ——
    ///    那些条目的归属就不干净了。启用时会在日志里**明确警告**。
    /// </summary>
    public static bool 保留保命兜底 = false;

    /// <summary>切换记录模式（带日志提示）</summary>
    public static void 设置(bool 开)
    {
        if (开启 == 开) return;
        开启 = 开;

        try
        {
            if (开)
            {
                LogHelper.Info("[记录模式] 已开启 —— ACR 停止输出与治疗，只记录你的手动操作");
                LogHelper.Info(保留保命兜底
                    ? "[记录模式] ⚠️ 保命兜底开启：记录里会混入 ACR 自己的操作，归属不再纯净"
                    : "[记录模式] 保命兜底关闭：全程需要你手动操作（记录最纯净）");
            }
            else
            {
                LogHelper.Info("[记录模式] 已关闭 —— ACR 恢复正常运行");
            }
        }
        catch { }

        // 通知外面（BlueWhale 用它决定要不要采集/提炼）
        try { 进入记录模式?.Invoke(开); } catch { }
    }

    /// <summary>切换通知（参数 = 是否开启）。HealerACR 不挂 → 什么也不发生。</summary>
    public static Action<bool>? 进入记录模式;

    // ==================== 手动施法观察 ====================

    /// <summary>
    /// 玩家放了一个技能 —— 参数：(技能ID, 技能名)。
    /// 由 BlueWhale 挂上；没挂就什么也不发生（原版 HealerACR 不带记录功能）。
    /// </summary>
    public static Action<uint, string>? 记录一次;

    /// <summary>
    /// 上一次观察到的施法（用来判断"新的一次"）。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  ⚠️ **这里的能力边界，务必如实告知使用者** ⚠️
    ///
    ///    检测手段是**轮询游戏客户端的读条状态**：
    ///      `IBattleChara.IsCasting` + `IBattleChara.CastActionId`
    ///    （⚠️ 属性名是 `CastActionId`，不是 `CurrentAction` —— 后者在
    ///     `IBattleChara` 上不存在，编译期就会报错）
    ///
    ///    这能可靠抓到：
    ///      ✅ 所有**读条技能**（大部分治疗、复活、群奶、输出魔法…）
    ///      ✅ 读条开始时记录，拿得到准确的技能 ID
    ///
    ///    抓不到：
    ///      ❌ **瞬发技能**（再生、天辉这类 2.5 秒读条的 GCD 有读条会抓到，
    ///         但**能力技**如天赐祝福、神速咏唱、醒梦完全没有读条）——
    ///         它们不会让 `IsCasting` 变 true，**必然漏记**
    ///
    ///    所以：**需要读条的技能记录可靠，瞬发能力技记录不到。**
    ///
    ///  ★ 这个局限意味着什么（很重要，别过度解读数据）★
    ///
    ///    记录**不能**用来还原"完整的操作序列"——能力技会缺一大块。
    ///    但它**足够回答时机类问题**，因为奶妈的主体操作是 GCD：
    ///      · "队友掉到多少血他才开始奶" → GCD 治疗，抓得到
    ///      · "DoT 还剩多久他才补"      → GCD 的 DoT，抓得到
    ///      · "什么时候开始输出"        → GCD 输出，抓得到
    ///    而**时机**恰恰是记忆库真正要学的东西（不是"有没有用某个能力技"）。
    ///
    ///    ⚠️ 提炼时**必须把这条局限写进提示词**，
    ///       否则 AI 会据"能力技很少出现"得出错误结论
    ///       （比如"他从不开减伤"——其实只是没记录到）。
    ///
    ///    后续要提高精度，可行方向是读动作包（`Data.LastPacketDownAction`），
    ///    但那必须**在游戏里实测验证**，不能凭推测写代码。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static uint _上次技能Id;

    /// <summary>上一次是否在读条 —— 用来抓"开始读条"这个**上升沿**</summary>
    private static bool _上次在读条;

    /// <summary>
    /// 每帧调用（挂在心跳里）。**非记录模式下直接返回**，零开销。
    /// </summary>
    public static void 每帧更新()
    {
        if (!开启) return;

        try
        {
            var me = Core.Me;
            if (me == null) return;

            var 在读条 = me.IsCasting;

            // ⚠️ 只记**上升沿**（开始读条那一刻）。
            //    不是每帧都记 —— 否则一个 2.5 秒的读条会被记上百次。
            var 刚开始 = 在读条 && !_上次在读条;
            _上次在读条 = 在读条;

            if (!刚开始) return;

            var 技能 = me.CastActionId;
            if (技能 == 0) return;

            // 同一个技能连续两次读条之间，客户端会先结束上一次 ——
            // 上升沿已经保证了"每次读条只记一次"，这里不用再去重。
            _上次技能Id = 技能;

            try { 记录一次?.Invoke(技能, SpellIds.反查(技能)); }
            catch { }
        }
        catch
        {
            // 观察绝不能影响战斗 —— 任何异常都吞掉
        }
    }

    /// <summary>战斗重置 / 换本 / 切职业时清（避免跨场次串味）</summary>
    public static void 重置()
    {
        _上次技能Id = 0;
        _上次在读条 = false;
    }
}
