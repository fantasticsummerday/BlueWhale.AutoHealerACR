public static class SpellUtil
{
    /// <summary>
    /// **最近一次"取不到技能实体"的原因** —— 给调试窗 / 日志用（2026-10-03 新增）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么必须有（用户实测「重载 AE 之后完全没有输出」）：
    ///      调试窗里那一轮是 **候选=0，而诊断写着"治疗：列表里有对象但全被筛掉"、
    ///      "输出：目标读到了但一个候选都没加"** —— 也就是**每个技能都被判成不可用**。
    ///
    ///      原因就在下面这个 `catch`：`id.GetSpell()` 一旦抛异常
    ///      （典型场景：**重载 AE 之后我们这份副本读不到 AEAssist 的技能服务**），
    ///      老写法**静默返回 null** ⇒ `可用()` 判 false ⇒ 所有技能被筛掉
    ///      ⇒ 没有候选、没有 AI 请求、也没有任何线索 —— 只能靠猜。
    ///
    ///  [!] ✅ 现在：记一次原因（5 秒节流）+ 打一行日志 + 调试窗显示。
    ///      看到它就意味着"这次加载的 AEAssist 技能服务是坏的"，
    ///      重启游戏可以让它恢复正常（重载救不回来 —— 换的是另一份副本的状态）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static string 最近取技能失败 = "";

    private static long _上次记取技能失败;

    /// <summary>取技能实体。所有 xxx.GetSpell() 最终都走这里。</summary>
    public static Spell? Get(uint id)
    {
        if (id == 0) return null;
        try
        {
            return id.GetSpell();
        }
        catch (Exception e)
        {
            // ★ 不再静默：这是"所有技能都不可用"的唯一真凶候选，必须留痕（5 秒最多一条）
            try
            {
                var 现在 = Environment.TickCount64;
                if (现在 - _上次记取技能失败 >= 5000)
                {
                    _上次记取技能失败 = 现在;
                    最近取技能失败 = $"{e.GetType().Name} {e.Message}";
                    LogHelper.Info($"[HealerACR] 取技能失败（技能 id={id}）—— " +
                                   "这会让**所有技能都判成不可用**（候选全空 / 没有 AI 请求）：" +
                                   最近取技能失败);
                    报一次服务不可用();
                }
            }
            catch { }
            return null;
        }
    }

    /// <summary>是否已经上屏报过"AEAssist 服务不可用"（只报一次，别刷屏）。</summary>
    private static bool _已报服务不可用;

    /// <summary>
    /// **上屏报一次"AEAssist 技能服务不可用"** —— 2026-10-03 用户实测。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么要在游戏里直接说（而不是只写日志/窗口）：
    ///      重载 AE 之后我们这份副本绑定到的那份 AEAssist **已经被 Dispose**，
    ///      `Spell` 内部 16 处 `Core.Resolve<MemApiSpell>()` 全部抛异常
    ///      ⇒ 每个技能都判成"不可用" ⇒ **本 ACR 完全不出手、AI 也不发请求**，
    ///      而现象只是"没反应" —— 用户会以为是我们写坏了。
    ///
    ///  [!] 这个状态**重载救不回来**（换任何一份副本，绑的还是那份死的 AEAssist）
    ///      ⇒ 只能**重启游戏**。所以要明确告诉用户做什么。
    ///
    ///  [!] 只报一次：`_已报服务不可用` 是静态的（每份副本各一次），
    ///      不刷屏、也不影响其他功能（本函数只发一条聊天栏提示）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 报一次服务不可用()
    {
        if (_已报服务不可用) return;
        _已报服务不可用 = true;
        try
        {
            屏幕提示.错误("AEAssist 技能服务已失效（本 ACR 读不到技能状态、将不出手）—— " +
                          "这是「重载 AE / 重载 ACR」之后常见的状态，重启游戏即可恢复");
        }
        catch { }
    }

    /// <summary>这个技能当前等级学会了吗</summary>
    public static bool 已解锁(uint id)
    {
        if (id == 0) return false;
        try
        {
            var sp = id.GetSpell();
            if (sp == null) return false;
            if (!sp.IsUnlock()) return false;

            // ══════════════════════════════════════════════════════════════
            //  ★★ **等级同步门** —— 用户日志实证的崩溃/卡顿根因 ★★
            //
            //  [!] 症状（日志原文）：
            //        决策构建Slot Spell 17215 朝日召唤     ← ⚠️ 这是 **Lv4** 技能（我一度误写成 100 级）
            //        技能开始使用. 17215 朝日召唤
            //        技能触发Event 17215 CancelCast
            //        SelfCastCancel Id: 17215              ← 服务器回弹
            //        [WRN] 17215 读条技能 取消了读条/服务器回弹 使用失败
            //      场景：`究极神兵破坏作战` 是 **50 级副本**（等级同步）。
            //
            //  [!] 为什么 `IsUnlock()` 挡不住：
            //        它只判"技能有没有被**学会**" ——
            //        满级角色进了 50 级同步本，**所有 100 级技能都"已学会"**
            //        ==> 决策层会选它们 ==> 放不出去 ==> 回弹/取消 ==> 卡顿。
            //
            //  [!] 正确的判据：
            //        `Spell.LevelRequirement`（技能需要多少级）
            //        对比 `Data.PlayerCurrentLevel`（**副本内生效的等级**）
            //        —— 后者在等级同步时返回**同步后的等级**。
            //
            //  [!] 读不到 `LevelRequirement` 时**保守放行**：
            //        宁可漏挡一个技能，也不要因为读不到属性就把全部技能禁掉
            //        （那会让整个 ACR 罢工，比漏挡严重得多）。
            // ══════════════════════════════════════════════════════════════
            var 现在等级 = 0;
            try { 现在等级 = Data.PlayerCurrentLevel; } catch { }
            if (现在等级 > 0)
            {
                // 技能需要的等级 —— 走游戏数据表。
                // ⚠️ **不要用 `Spell.LevelRequirement`** —— 那个属性在 AEAssist 的
                //    `Spell` 上**不存在**（我一度以为有，编译不过）。
                var 需要 = 技能数据.取需要等级(id);
                if (需要 > 0 && 现在等级 < 需要) return false;
            }

            return true;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// **等级同步诊断** —— 给调试窗用：当前生效等级、以及某技能差多少级。
    ///
    /// [!] 为什么单独开一个：`已解锁()` 只会静默返回 false，
    ///     而"为什么这个技能用不了"必须能一眼看出来（`技能诊断.cs` 已经在做，
    ///     但它只报"未解锁（等级/职业任务不够）"，**不区分是同步还是没学**）。
    /// </summary>
    public static string 等级同步说明(uint id)
    {
        try
        {
            if (id == 0) return "";
            var sp = Get(id);
            if (sp == null) return "读不到技能";
            var 需要 = 技能数据.取需要等级(id);
            var 现在 = 0;
            try { 现在 = Data.PlayerCurrentLevel; } catch { }
            if (需要 <= 0 || 现在 <= 0) return "";
            if (现在 >= 需要) return "";
            return $"★ 等级同步：现在只按 {现在} 级算，这个技能要 {需要} 级";
        }
        catch { return ""; }
    }

    /// <summary>现在能用吗（含施法条件检查）</summary>
    public static bool 可用(uint id)
    {
        if (id == 0) return false;

        var s = Get(id);
        if (s == null) return false;

        // ==================== 这一段改动前请先读完 ====================
        //
        // 官方文档原文（完整版，注意【】里的限定词）：
        //
        //     技能是否可用 IsReady
        //
        //     注意，考虑到 Buff 延迟，【部分有 Buff 才亮的技能】，可能需要你自行
        //     比对本地有没有释放获取 Buff 的技能。【此时】你可以通过 IsUnlock
        //     检查是否学习/等级够不够，接着使用 xxx.GetSpell().Cooldown 来检测
        //     技能 CD，再检测本地有没有释放过获取对应 Buff 的技能
        //
        // → **主判断始终是 IsReady**。「IsUnlock + Cooldown」是【只在 Buff 延迟
        //    导致技能不亮时】才用的**补充手段**，不是通用替代方案。
        //
        // 我在这一点上翻车两次，别再犯：
        //   0.6.7  换成 s.Cooldown > TimeSpan.Zero —— 语义没验证，恒真
        //          → 所有技能不可用
        //   0.7.3  加 !s.IsUnlock()               —— 对召唤技/爆发技返回 false
        //          → 小仙女不召唤、爆发不打
        //
        // 实测证据：0.5.5 的实机日志里有 "CastSpell success: 17215 朝日召唤"，
        // 那一版用的就是这个判断。**实测优先于文档的一般性建议。**
        //
        // 真要做"Buff 延迟"的补充判断，应该**针对具体技能**在它自己的 resolver 里做，
        // 而不是在这个通用入口上一刀切。
        // =============================================================

        // ⚠️ **这里故意不做移动判定** —— 移动守卫由各 resolver 显式调用
        //    `移动中能放()` 完成（错误码也更具体，方便调试）。
        //
        //    为什么不在这个公共出口一刀切：
        //      ① 有些调用点判的是**能力技**（紧急单奶 / 群体治疗能力技），
        //         它们本来就是瞬发，在这里判是多余的；
        //      ② 更要紧的是**可预测性** —— 在这里静默否决，
        //         会让"为什么这个技能突然不放了"变得很难查
        //         （我已经在"通用入口一刀切"上翻车过两次，见上面那段注释）。
        return s.IsReadyWithCanCast();
    }

    /// <summary>
    /// **即将可用** —— 现在不能放，但在 <paramref name="展望秒"/> 内会好。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要它（结构性矛盾）★
    ///
    ///    候选集是**备货**：生成的候选给接下来 **2~3 个 GCD** 用
    ///    （`每次请求步数 = 3`、`目标长度 = 3`）。
    ///    而生成器用的是 `可用()` = `IsReadyWithCanCast()` = **此刻**能不能放。
    ///
    ///    ⇒ 一个"还有 1.2 秒 CD"的技能被砍掉 —— 可它到你真要用时早好了。
    ///    ⇒ 这是"候选偏少"的结构性原因
    ///      （调试窗实证：`治疗候选：解锁 5 个，其中现在可用 0 个`）。
    ///
    ///  [!] **绝不在 `可用()` 里放宽** —— 那个语义是"此刻能不能放"，
    ///      被 resolver（执行层）共用。放宽它会让执行层去放一个真放不出来的技能。
    ///      **放宽只属于"生成候选"这一步。**
    ///
    ///  [!] 「正在读条」也算即将可用：读条中 GCD 被占，
    ///      但候选是给**读完之后**用的 —— 那正是最需要备货的时刻。
    ///      （`可用()` 在读条中会对 GCD 技能返回 false，这是候选全空的主因之一。）
    ///
    ///  [!] 判据刻意保守：只放宽"时间"这个维度 ——
    ///      **等级/职业任务没到（`已解锁` 假）仍然不放行**。
    ///      一个 50 级放不了的技能，"即将可用"也不该成立。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static bool 即将可用(uint id, float 展望秒 = 2.5f)
    {
        try
        {
            if (id == 0) return false;

            // ① 已经能用 -> 当然算
            if (可用(id)) return true;

            // ② 等级/职业任务没到 -> 永远不算（不放宽这一维）
            if (!已解锁(id)) return false;

            // ③ 正在读条 -> 读完之后就能用（GCD 被这一发占着）
            try
            {
                var (在读条, 已读秒, 总秒) = 读条进度();
                if (在读条 && 总秒 - 已读秒 <= 展望秒) return true;
            }
            catch { }

            // ④ 冷却剩余 <= 展望 -> 等你轮到它就好了
            try
            {
                var s = Get(id);
                if (s == null) return false;

                var cd = s.Cooldown;
                if (cd > TimeSpan.Zero && cd.TotalSeconds <= 展望秒) return true;
            }
            catch { }

            return false;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// **建议视野（秒）** —— AI 一次给"接下来 3 个 GCD"的建议，
    /// 所以第 3 个建议的落地时间约等于 **3 个 GCD 的时长**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要它（`即将可用` 的门槛原来定得太短）★
    ///
    ///  [!] `即将可用` 的默认展望是 **2.5 秒**。对**本地** resolver 是对的
    ///      （它只关心"这一帧能不能放"），但**候选集是给 AI 备货的** ——
    ///      AI 建议的是**未来 3 个 GCD**。
    ///
    ///  [!] 后果：一个 CD 还剩 **5 秒**的技能**进不了候选**，
    ///      但它 5 秒后就好了，而 AI 的第 2~3 个建议正是那个时候
    ///      ==> **AI 无法建议它** —— 不是模型不行，是它**看不到**。
    ///      表现为"AI 建议总是那几个廉价技能，大招/长 CD 技从不出现"。
    ///
    ///  [!] 所以候选集那 4 个调用点改用本值：
    ///        `3 × GCD时长`（1000 = 2.5 秒的 GCD -> 7.5 秒）
    ///      **下限 2.5 秒**：GCD 时长读不到/异常时不比原来更严。
    ///      **上限 9 秒**：避免极慢 GCD（或读到大值）把窗口拉得过宽 ——
    ///        太宽的话候选里会塞一堆"还早得很"的技能，稀释本地分排序。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static float 建议视野秒()
    {
        try
        {
            var gcd毫秒 = HealerACR.Common.CharacterExt.GCD时长;
            var 秒 = gcd毫秒 * 3 / 1000f;
            return Math.Clamp(秒, 2.5f, 9f);
        }
        catch { return 2.5f; }
    }

    /// <summary>
    /// 移动守卫的便捷包装：**移动中不要放读条技能**（瞬发和正在读条的除外）。
    ///
    /// 各 resolver 在"确定要用哪个技能之后、返回之前"调用它，
    /// 详见 <see cref="移动中能放"/> 的说明。
    /// </summary>
    public static bool 移动中可用(uint id) => 移动中能放(id);

    // ==================== 移动状态描述（给 AI 看）====================

    /// <summary>
    /// **我现在在移动吗**。读不到返回 false（保守：当作没在移动）。
    /// </summary>
    public static bool 在移动()
    {
        try { return MoveHelper.IsMoving(); }
        catch { return false; }
    }

    // ══════════════════════════════════════════════════════════════════
    //  ★ 移动时长 / 移动延迟 ★
    //
    //  [!] 为什么要"移动了多久"这个量：
    //      刚起步的几帧**还没离开原位**，这一拍读条其实读得完；
    //      而且"蹭一下就走"（躲个 AOE 再回来）也不该被当成走位。
    //      ⇒ 移动**满一段时间**之后，才认为"这一拍确实读不完"，
    //        才允许动用即刻这类一次性资源。
    //
    //  [!] 状态是静态的，所以必须进 `OnResetBattle` / `OnTerritoryChanged`
    //      的清理清单（见 `HealerEntryBase`，开发约定 F①）。
    // ══════════════════════════════════════════════════════════════════

    private static long _位移开始时刻;
    private static bool _上一帧在动;

    /// <summary>移动延迟（毫秒）—— 连续移动超过这么久才算"真在走位"</summary>
    public const int 移动延迟毫秒 = 300;

    /// <summary>移动已经持续了多少毫秒（没在移动返回 0）</summary>
    public static long 移动时长毫秒()
    {
        刷新移动状态();
        return _上一帧在动 ? Math.Max(0, Environment.TickCount64 - _位移开始时刻) : 0;
    }

    /// <summary>
    /// **这一拍是不是"真的在走位"** —— 连续移动超过 <see cref="移动延迟毫秒"/>。
    ///
    /// [!] 用途：一次性资源（即刻 / 光速）和 DoT 让路都该用它，
    ///     而不是裸的 `在移动()` —— 后者会被"起步第一帧"和"蹭一步"触发。
    /// </summary>
    public static bool 真在走位() => 移动时长毫秒() >= 移动延迟毫秒;

    /// <summary>每帧调一次（幂等）：维护"连续移动了多久"</summary>
    public static void 刷新移动状态()
    {
        var 现在在动 = 在移动();

        if (现在在动 && !_上一帧在动) _位移开始时刻 = Environment.TickCount64;
        if (!现在在动) _位移开始时刻 = 0;

        _上一帧在动 = 现在在动;
    }

    /// <summary>战斗重置 / 换本时清</summary>
    public static void 重置移动状态()
    {
        _位移开始时刻 = 0;
        _上一帧在动 = false;
    }

    /// <summary>
    /// **现在能不能开始读条**（不能 = 移动中 或 在空中）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 这个入口是为了**统一一个判据**（用户明确要求过「原地跳跃也是移动状态」）★
    ///
    ///  [!] 两个状态的区别（`空中检测.cs` 的类注释写得很清楚，这里复述关键）：
    ///        `在移动()`  = 语义上**在走位** —— 用于给 AI 的**措辞**
    ///                       （说"移动中"会让人以为在走位，所以跳跃不能并进去）
    ///        `本方法`    = **能不能读条** —— 用于**实际决策**
    ///                       （跳跃是"站在原地跳"，但同样放不出读条技能）
    ///
    ///  [!] 为什么必须单独有它（**原来漏了**）：
    ///      `空中检测` 只修了 `移动状态描述()` —— 让 AI 别建议读条技。
    ///      但**本地那条路**（`治疗决策.选最优` 的 `移动中` 参数）
    ///      读的还是 `在移动()` ==>
    ///      **跳起来的时候，本地会选一个读条技，然后放不出来。**
    ///      （`空中检测.cs` L28-32 自己预言了这个后果：
    ///        "跳跃时 `在移动()` 返回 false -> AI 建议读条技能 -> **放不出来**"，
    ///        但它只修了 AI 那条路。）
    ///
    ///  [!] 判据与 `移动中能放()` 保持一致 —— 那里用的就是
    ///      `!MoveHelper.IsMoving() && !空中检测.在空中`。
    ///      两处必须同源（开发约定 F③），否则又会出现
    ///      "这个 resolver 说能放、那个说不能放"。
    ///
    ///  [!] 读不到时返回 **false**（保守：当作"能读条"）——
    ///      这与 `在移动()` 的保守方向一致（都往"放行"偏），
    ///      避免因为接口抽风把治疗整体卡死。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static bool 不能读条()
    {
        try { return 在移动() || 空中检测.在空中; }
        catch { return false; }
    }

    /// <summary>
    /// **大技能的冷却剩余秒数**（0 = 已就绪 / 读不到）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么必须有它（用户目标：「**资源最大化利用**」）：
    ///
    ///      AI 能看到职业资源**计数**（以太/百合/蛇胆/手牌…），
    ///      但**看不到大技能还剩多久转好** —— 而"该省还是该花"完全取决于后者：
    ///        · 「深谋远虑之策 还剩 3 秒」-> 再撑一下就有大招，别交便宜技能
    ///        · 「天赐祝福 还剩 200 秒」  -> 指望不上，该用 GCD 就用
    ///        · 「以太超流 还剩 2 秒」    -> 手里豆子马上溢出，赶紧卸
    ///      ==> 缺了 CD，AI 的"资源规划"只能瞎猜。
    ///
    ///  [!] 为什么用 `Cooldown` 属性：
    ///      这是本文件 `即将可用()` 已经在用的同一个 API（见那里的 ④），
    ///      语义已验证。**不要**改用 `IsReady` 反推 —— 那个不含充能信息。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static float 冷却剩余秒(uint 技能Id)
    {
        try
        {
            var s = Get(技能Id);

            // ★ 2026-10-15 修：**"读不到"必须与"已就绪"区分开** —— 原来两者都返回 `0f`，
            //   而 `战斗指标` 把 `剩余 == 0` 当作"技能空着/空转" ⇒ **读不到被算成空转**，
            //   指标整体虚增（本项目 `CharacterExt.冷却剩余秒` 的同款函数读不到时返回 `-1`，
            //   这里与它同源）。
            //   [!] 兼容性：调用方普遍写 `<= 0f`（"就绪就放"）⇒ `-1f` 与 `0f` 在那里的含义一致 ✓；
            //       只有按 `== 0` 严格判"空着"的地方会因此不再把"读不到"算进去 —— 那正是修正目标。
            if (s == null) return -1f;

            var cd = s.Cooldown;
            return cd > TimeSpan.Zero ? (float)cd.TotalSeconds : 0f;
        }
        catch
        {
            return -1f;
        }
    }

    /// <summary>
    /// 当前读条进度 —— (是否在读条, 已读秒, 总读条秒)。没读条返回 (false, 0, 0)。
    /// </summary>
    public static (bool 在读条, float 已读秒, float 总秒) 读条进度()
    {
        try
        {
            var me = Core.Me;
            if (me == null || !me.IsCasting) return (false, 0f, 0f);

            var 总 = me.TotalCastTime;
            var 已 = me.CurrentCastTime;

            // TotalCastTime <= 0 说明不是真读条（瞬发也会让 IsCasting 短暂为真）
            if (总 <= 0f) return (false, 0f, 0f);

            return (true, 已, 总);
        }
        catch { return (false, 0f, 0f); }
    }

    /// <summary>
    /// 一句话描述移动 / 读条状态 —— **给 AI 判断"能不能建议读条技能"用**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么要给 AI 这个 ★
    ///
    ///    "本地逻辑已经会在移动时挡掉读条技能，但 **AI 还在建议读条技能**"
    ///
    ///    根因：**AI 根本不知道玩家在移动** ——
    ///    `移动中能放()` 是本地层的事，AI 拿到的局面里没有这个信息。
    ///    于是它按"站着不动"的前提给建议，那些建议全被本地拦掉，
    ///    表现为"AI 一直在说用闪灼，但一个都没打出去"。
    ///
    ///    所以必须把移动状态**作为事实喂给它**，让它自己改成建议瞬发技能。
    ///
    ///  ── 输出形态（举例）──
    ///      `移动中（读条会中断）—— 阶段B只能建议瞬发技能`
    ///      `站定 —— 可以建议读条技能`
    ///      `正在读条（已 1.2s / 共 2.5s）—— 读条期间不能移动`
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static string 移动状态描述()
    {
        var (在读条, 已读, 总) = 读条进度();

        if (在读条)
            return $"正在读条（已 {已读:F1}s / 共 {总:F1}s）—— 读条期间不能移动";

        if (在移动())
            return "移动中（读条会被中断）—— 阶段B只能建议瞬发技能";

        // ★ 空中（跳跃中）也要说清楚 ★
        //   [!] 这里**不能**并进 `在移动()` —— 那会让 AI 以为在走位。
        //      跳跃是"站在原地跳"，但它同样**放不出读条技能**（会失败/被打断）。
        //      所以单独一句，把真实原因说明白。
        //
        //   [!] 起因是用户反馈"原地跳跃应该也是移动状态" —— 核实后发现
        //      框架的 `IsMoving` 只看 `AgentMap.IsPlayerMoving`，跳跃不改变它。
        if (空中检测.在空中)
            return "空中（跳跃中，读条放不出来）—— 只能建议瞬发技能";

        return "站定 —— 可以建议读条技能";
    }

    /// <summary>
    /// 这个技能**能不能在移动中放**（给 AI 看的一句话）。
    /// 用于告诉 AI"你建议的这个技能现在放不放得出来"。
    /// </summary>
    public static string 技能移动适用性(uint id)
    {
        if (id == 0) return "未知";

        try
        {
            var s = Get(id);
            if (s == null) return "未知";

            var 读条 = s.CastTime.TotalSeconds;
            if (读条 <= 0.05) return "瞬发（移动中也能放）";

            return $"读条 {读条:F1}s（移动中放不出）";
        }
        catch { return "未知"; }
    }

    /// <summary>
    /// 等级变换：把"最初形态"的技能换成当前等级该用的那个。
    /// 白魔 Stone(1) → StoneII → Glare → GlareIII，学者 Ruin → Broil IV …
    ///
    /// ⚠️ **返回值可能是 null，调用方必须判空**（现有调用方都判了）。
    ///
    /// ⚠️ 这里做了**双重保险**，因为"闪飒放不出来"这类 bug 的嫌疑点就在这：
    ///    `CheckActionChange(id)` 对**没有形态变化**的技能会返回 0
    ///    （而不是原样返回 id）—— 这时 `0.GetSpell()` 拿到的是 null，
    ///    技能就**静默不放**了。
    ///    所以：结果 id 为 0 → 退回原 id；换出来的 Spell 也是 null → 再退一次。
    ///    这样"没有形态变化"的技能永远走 `Get(id)`，不会因为多包一层而失效。
    /// </summary>
    public static Spell? 当前形态(uint id)
    {
        if (id == 0) return null;

        uint 形态Id = 0;
        try
        {
            形态Id = Core.Resolve<MemApiSpell>().CheckActionChange(id);
        }
        catch
        {
            // 这个 AEAssist 版本没有 CheckActionChange → 直接用原 id
            return Get(id);
        }

        // 没有形态变化（返回 0）→ 按原 id 处理，别让它变成"放不出来"
        if (形态Id == 0) return Get(id);

        return Get(形态Id) ?? Get(id);
    }

    /// <summary>从高到低挑第一个已解锁的技能（等级降级用），都没解锁返回 0</summary>
    public static uint 取已解锁(params uint[] ids)
    {
        foreach (var id in ids)
        {
            if (已解锁(id)) return id;
        }

        return 0;
    }

