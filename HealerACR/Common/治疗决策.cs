using AEAssist;
using AEAssist.Helper;
using HealerACR.Common;

namespace HealerACR.Common;

/// <summary>
/// **治疗综合判定** —— 把"恢复力 / 效率 / 瞬发 / MP / 冷却 / 资源"一起算分。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么必须综合，不能单看恢复力 ★
///
///    单看恢复力会选出**又贵又慢又过量**的技能。看白魔的实际情况：
///
///      治疗 120  恢复力 500/450   MP 400   ← 便宜够用
///      救疗 135  恢复力 800/700   MP 1000  ← 恢复力 +60%，MP **+150%**
///
///    掉 1500 血时：
///      · 救疗 ×2 = 2 个 GCD，2000 MP
///      · 治疗 ×4 = 4 个 GCD，1600 MP   ← GCD 更贵
///    ⇒ 缺口大用大治疗（省 GCD）；缺口小用小治疗（省 MP）。
///
///  ★ 五个维度 ★
///
///    ① **有效性** —— 这一口能补上多少真实缺口（不是恢复力数字）
///       过量治疗是纯浪费，要把超出缺口的 70% 折价。
///    ② **救急能力** —— 目标命悬一线时必须"一次补满"，
///       差一点就是人没了 ⇒ 用指数放大"补不满"的惩罚。
///    ③ **效率** —— MP / 真实治疗量。蓝量见底时这一项权重加大。
///    ④ **可用性** —— 移动中读条**必然被打断**（日志实证），
///       所以移动中只认瞬发；冷却没好 / 资源不够的直接剔除。
///    ⑤ **GCD 成本** —— GCD 是最稀缺的资源。GCD 技占一个，
///       能力技不占 ⇒ 同等条件下能力技优先。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 治疗决策
{
    /// <summary>
    /// 从候选里挑**最该用的那一个**（挑不出返回 null）。
    /// </summary>
    /// <param name="候选">候选集</param>
    /// <param name="缺口">目标**还差多少血**（已按目标上限截断）</param>
    /// <param name="命悬一线">目标是不是"下一击就会死"</param>
    /// <param name="移动中">自己是不是在移动</param>
    /// <param name="只群体">只考虑群体技</param>
    /// <param name="只瞬发">只考虑瞬发技</param>
    /// <param name="只要GCD">
    /// 只考虑**占 GCD** 的技能（排除 oGCD 能力技）。
    ///
    /// [!] 为什么要这个参数：`Res_HealAoEGcd` 是**走 GCD 槽**的，
    ///     而 `只群体` 只判 `群体`，不过滤能力技 ==>
    ///     会把 oGCD 群体能力技（礼仪之铃 180s / 法令 40s / 大赦 …）
    ///     当 GCD 技能用完，白占一个 GCD。见 `治疗技能.是能力技`。
    /// </param>
    /// <summary>
    /// **给某个目标算一条技能的本地分** —— 和 `选最优` 内部用**完全相同**的判据。
    ///
    /// [!] 存在的意义（H2，审计确认）：
    ///      `候选集` 给 AI 看的 `本地分` 是**另一个公式**
    ///      （`覆盖*2 - 过量*1.5`），而 `选最优` 真正用的是 `打分()` ——
    ///      它有 AI 完全看不到的维度：**GCD数** / 效率罚 / 盾吸收 / 低蓝 ×2.5。
    ///      ==> AI 只能自己猜算术。
    ///      例：缺口 2500 时本地选救疗（800 -> 4 个 GCD）而不是治疗（500 -> 5 个），
    ///      **而 AI 的数据里没有「要几个 GCD」这个概念**。
    ///
    /// [!] 缺口口径**必须和 `给目标选最优` 同一条**（开发约定 F③）——
    ///      所以这里直接复用同一个 `未来缺口(目标)`（默认 2.5 秒预测），
    ///      「命悬一线」也按同一条（`有效血量比例() <= 0.30f`），**不另造判据**。
    /// </summary>
    public static float 对目标打分(治疗技能 技, IBattleChara 目标)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            if (技 == null || 目标 == null) return float.NegativeInfinity;

            // 和 `给目标选最优` 逐字同一条：未来缺口（含预测掉血）
            var 缺口 = 未来缺口(目标);
            if (缺口 <= 0f) return float.NegativeInfinity;

            // 和 `选最优` 逐字同一条：低蓝时把"效率"权重抬高
            var 蓝量比 = 蓝量比例();
            var 效率权重 = 蓝量比 < 0.30f ? 2.5f : 1.0f;

            // 和 `给目标选最优` 逐字同一条：命悬一线
            var 命悬 = false;
            try { 命悬 = 目标.有效血量比例() <= 0.30f; } catch { }

            return 打分(技, 缺口, 命悬, 效率权重, SpellUtil.不能读条());
        // ⚠️ 用 `不能读条()`（含跳跃）而不是 `在移动()` ——
        //    这里判的是能不能放读条技，跳跃同样放不出。
        }
        catch { return float.NegativeInfinity; }
    }
    
    public static 治疗技能? 选最优(
        治疗候选集 候选,
        float 缺口,
        bool 命悬一线,
        bool 移动中,
        bool 只群体 = false,
        bool 只瞬发 = false,
        bool 只要GCD = false)
    {
        try
        {
            if (候选 == null || 缺口 <= 0f) return null;

            // ── 蓝量水位：低蓝时把"效率"权重抬高 ──
            var 蓝量比 = 蓝量比例();
            var 效率权重 = 蓝量比 < 0.30f ? 2.5f : 1.0f;

            治疗技能? 最好 = null;
            var 最高分 = float.NegativeInfinity;

            // ★ 记录本次的打分过程（诊断用）★
            //   [!] 只在真有多个候选时才拼串 —— 单候选是绝大多数情况，
            //      每次都拼字符串会给每帧加 GC 压力（这层是热路径）。
            var 明细 = new System.Text.StringBuilder();

            foreach (var 技 in 候选.已解锁())
            {
                if (只群体 && !技.群体) continue;
                if (只要GCD && 技.是能力技_实际) continue;   // GCD 槽不能塞能力技
                if (技.仅自己) continue;

                // ④ 可用性：冷却 / 资源 / 移动
                if (!可用(技, 移动中, 只瞬发)) continue;

                var 分 = 打分(技, 缺口, 命悬一线, 效率权重, 移动中);

                if (明细.Length < 200)
                    明细.Append(技.名).Append('=').Append(分.ToString("F2")).Append(' ');

                if (分 > 最高分) { 最高分 = 分; 最好 = 技; }
            }

            // ★ 记下"选了谁 + 候选明细" ★
            //   [!] 这是分清"AI 选了医术"还是"本地选了医术"的唯一办法 ——
            //      两者要改的地方完全不同（前者改候选/提示词，后者改打分）。
            try
            {
                _最近选择 = 最好 == null
                    ? $"缺口{缺口:F0} 无可选（明细：{明细.ToString().Trim()}）"
                    : $"缺口{缺口:F0} 选[{最好.名}]={最高分:F2}" +
                      (最好.是盾 ? "(盾)" : "") +
                      $"｜候选：{明细.ToString().Trim()}";
            }
            catch { }

            return 最好;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>能不能放（冷却 / 资源 / 移动 三条）</summary>
    private static bool 可用(治疗技能 技, bool 移动中, bool 只瞬发)
    {
        try
        {
            // 移动中读条必然被打断 —— 实测日志里 SelfCastCancel 一大把
            if (移动中 && !技.瞬发) return false;
            if (只瞬发 && !技.瞬发) return false;

            return SpellUtil.可用(技.Id);
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// **综合打分** —— 分数越高越该用。
    ///
    /// ⚠️ 各项的量纲不同，所以先用**归一化**再乘权重 ——
    ///    直接相加会让"恢复力数字"压倒一切。
    /// </summary>
    // ══════════════════════════════════════════════════════════════
    //  ★ 最近一次"本地为什么选它" ★
    //
    //  [!] 为什么需要（用户实测的疑点）：
    //      日志里 AI 说"用能力技单奶自己"，但实际一直看到医术。
    //      **分不清是 AI 选了医术、还是 AI 建议被无视后本地自己选了医术** ——
    //      而这两者要改的地方完全不同（前者改提示词/候选，后者改本地打分）。
    //
    //  [!] 也用于验证"盾加权"那次改动的效果：
    //      `诊断` 里能看到"候选里有哪些、各自多少分、最后选了谁"。
    // ══════════════════════════════════════════════════════════════
    private static string _最近选择 = "";

    /// <summary>最近一次本地治疗选择（一行，给调试窗/日志）</summary>
    public static string 最近选择 => _最近选择;
    /// <summary>
    /// **盾的真实系数**（盾值占这次治疗量的比例）。
    ///
    /// [!] 三级回退，顺序是刻意的：
    ///      ① **候选自己写的** `盾百分比` —— 最准（技能说明原文里的数字，
    ///         比如 意气轩昂之策 180%、天星交错 200% 这种，buff 表里查不到）
    ///      ② 查 `减伤状态表.护盾`（游戏 Status 表的 ParamModifier，
    ///         鼓舞 / 水流幕 / 均衡诊断 / 慰藉 都是 100%）
    ///      ③ 兜底 **0.5** —— 不改变原有行为，方向也安全（低估盾）
    ///
    /// [!] 我原来在这里写「具体百分比游戏没给，0.5 是下限估计」—— **那是错的**，
    ///     仓库里本来就有游戏数据。已改正。
    /// </summary>
    /// <summary>
    /// **公开的盾系数** —— 给"渲染候选描述"用（本地打分自己用的是 `盾真实系数`）。
    ///
    /// [!] 为什么需要公开（H4，审计确认）：候选描述里要把盾标成 `盾x180%`，
    ///     否则**两个盾在模型眼里一模一样**，而本地打分按 1.8 倍算 ==> 会选错。
    ///     例：士气高扬之策 100% vs 意气轩昂之策 180%；天星交错 / 神爱抚 200%。
    /// </summary>
    public static float 公开盾系数(治疗技能? 技)
    {
        if (技 == null || !技.是盾) return 0f;
        try { return 盾真实系数(技); } catch { return 0f; }
    }
    
    private static float 盾真实系数(治疗技能 技)
    {
        const float 兜底 = 0.5f;

        try
        {
            if (技.盾百分比 > 0) return 技.盾百分比 / 100f;

            var buff = AuraIds.技能转Buff(技.Id);
            if (buff == 0) return 兜底;

            if (!减伤状态表.护盾.TryGetValue(buff, out var 百分比) || 百分比 <= 0)
                return 兜底;

            return 百分比 / 100f;
        }
        catch
        {
            return 兜底;
        }
    }

    
    private static float 打分(治疗技能 技, float 缺口, bool 命悬一线, float 效率权重, bool 移动中)
    {
        var 单次 = 技.即时恢复力;
        if (单次 <= 0f) return float.NegativeInfinity;

        // ══ ① 有效性：真实补上的血（过量折价 70%）══
        var 真实 = MathF.Min(单次, 缺口);
        var 过量 = MathF.Max(0f, 单次 - 缺口);

        // ⚠️ **过量惩罚必须截断**（数值推演发现的 bug）——
        //    不截断的话「天赐祝福 9999」对 2500 缺口会算出
        //    `2500 - 7499*0.7 = -2749`，**救命技变成最低分**，
        //    而"缺口的 5 个 GCD 都补不满"的小治疗反而排前面。
        //
        //    过量治疗的浪费上限就是**缺口本身** ——
        //    你最多只能多治"一个缺口"的量，不存在浪费 5249 这种事。
        var 过量罚 = MathF.Min(过量, 缺口) * 0.7f;
        var 有效 = 真实 - 过量罚;

        // ══ ② 救急：命悬一线时"补不满"要重罚 ══
        if (命悬一线)
        {
            // 覆盖率 = 这一口能补掉缺口的百分之多少
            var 覆盖 = MathF.Min(1f, 单次 / 缺口);
            // 覆盖率 <1 时急剧掉分（指数放大），=1 时不罚
            有效 *= MathF.Pow(覆盖, 4f) * 3f;
        }

        // ══ ②b **要几个 GCD 才补满** —— 最稀缺的资源，后面几项都要用 ══
        //
        //  ⚠️ 这一项**必须独立于"有效治疗量"**：
        //     有效治疗量只看"这一发补了多少"，看不出"要几发才够"。
        //     缺口 2500 时，救疗 800 要 4 发、治疗 500 要 5 发 ——
        //     差别就是**一个 GCD**，而 GCD 比 MP 稀缺得多。
        var GCD数 = 1;
        if (单次 < 缺口)
        {
            // ⚠️ 减 0.001 容差 —— 否则 `1500/500 = 3.0000001` 会被 Ceiling
            //    成 4，把"刚好 3 发补满"误判成"要 4 发"。
            GCD数 = Math.Max(1, (int)MathF.Ceiling(缺口 / MathF.Max(1f, 单次) - 0.001f));
        }
        var 效率项 = 1f / GCD数;

        // ══ ③ 效率：MP / 真实治疗量 ══
        var 效率罚 = 0f;
        if (技.MP > 0)
        {
            // 归一化：以"每 100 MP 换 100 恢复力"为基准 1.0
            var 每点 = 技.MP / MathF.Max(1f, 真实);
            效率罚 = 每点 * 100f * 0.5f * 效率权重;
        }

        // ══ ④ 移动中瞬发额外加分（移动时能放本身就是稀缺能力）══
        var 移动加分 = 移动中 && 技.瞬发 ? 0.15f : 0f;

        // ══ ⑤ GCD 成本：能力技不占 GCD，加分 ══
        //
        //  ⚠️ 加分要**按"省下多少 GCD"缩放**，不能无条件给满
        //     （数值推演发现的初值问题）：
        //
        //     缺口 500 时，治疗一次就够（1 个 GCD），
        //     此时用神祝祷（30 秒 CD）只是**白烧冷却**，没省下任何 GCD。
        //     而缺口 900 时，神名一口补上 = 省下 1 个 GCD，那才值得。
        //
        //  ⇒ 用 `(1 - 1/GCD数)` 缩放：一次补满时给满，要 N 次才补满时给 1/N。
        //     缺口 ≤ 单次恢复力 → GCD数=1 → 缩放=0 → **不给加分**
        //     （这种时候 GCD 治和它一样快，能力技的"不占 GCD"没价值）
        var 省下比例 = 1f - (1f / GCD数);
        // [!] 用 `技.不占GCD`（= `是能力技_实际`）而不是 `技.冷却 > 0f` ——
        //     它们是**同一个问题的两个谓词**，而 H13 的教训正是"两处判据不同源"：
        //     那时 `只要GCD` 用推导值、候选集用 `冷却 > 0f`，结果同一批百合技
        //     在本地被当能力技、在模型眼里是 GCD。
        //     这里判的就是"这个动作占不占 GCD"，所以必须和 `只要GCD` 同一个入口（F③）。
        var GCD加分 = 技.不占GCD ? 0.20f * 省下比例 : 0f;

        // ══ ⑥ HoT 的部分：只有"时间够"才有价值（缺口不紧急时）══
        var HoT加分 = 0f;
        if (技.HoT恢复力 > 0 && !命悬一线)
            HoT加分 = 技.总恢复力 * 0.15f / MathF.Max(1f, 缺口);

        // ══════════════════════════════════════════════════════════════
        //  ★ ⑦ 护盾：把【预期吸收】算进收益（用户："学者 50 级不会打医术"）★
        //
        //  ── 官表实测（不是猜）──
        //    190 医术         读条 1.50s  恢复力低
        //    185 鼓舞激励之策  读条 2.00s  恢复力 300
        //        说明原文："追加效果：为目标附加能够抵御一定伤害的防护罩鼓舞
        //                  鼓舞效果：**抵消相当于治疗量%的伤害**  持续 30 秒"
        //    ⇒ 鼓舞 = **300 治疗 + 等量护盾**，一份 GCD 干两份活。
        //
        //  ── 原来的算法 ──
        //        var 盾加分 = 技.是盾 && !命悬一线 ? 0.10f * 覆盖比例 : 0f;
        //    盾的价值只在**10% 的乘数**上 —— 严重低估，
        //    于是"医术（纯治疗、恢复力更低）"能压过"鼓舞（治疗+盾）"。
        //
        //  ── 为什么不能只把 0.10 调大 ──
        //    `有效` 算的是**治疗部分**；盾是**额外的吸收量**。
        //    两者应该**相加**，而不是给治疗量乘一个系数 ——
        //    乘系数会让"盾"永远只是治疗的一个零头。
        //
        //  [!] **修正（自查发现）：盾系数不用猜，仓库里就有游戏真实百分比。**
        //      我原来在这里写「具体百分比游戏没给，0.5 是下限估计」—— **错的**。
        //      `减伤状态表.护盾` 就是游戏 Status 表的 `ParamModifier`：
        //          [297]  鼓舞       100      [1889] 天星交错   100
        //          [3086] 水流幕     100      [2607] 均衡诊断   100
        //          [3098] 慰藉       100      [1918] 激励       125
        //      ⇒ 用 0.5 等于**把盾低估 2 倍**。
        //
        //  [!] 查法：技能 -> Buff（`AuraIds.技能转Buff`）-> `减伤状态表.护盾`；
        //      查不到退回 0.5（见 `盾真实系数`），不改变原有行为。
// ══════════════════════════════════════════════════════════════
        var 覆盖比例 = MathF.Min(1f, 单次 / MathF.Max(1f, 缺口));

        // ★ 盾的预期吸收量加进"有效" ★
        //   [!] 用同一个过量罚逻辑：盾也会"过量"（缺口小时吸收量用不上）
        if (技.是盾 && 单次 > 0f)
        {
            var 吸收 = 单次 * 盾真实系数(技);

            // 缺口已被治疗填掉一部分，盾能吸收的"有效部分"按剩余缺口折算
            var 剩余缺口 = MathF.Max(0f, 缺口 - 真实);
            var 吸收有效 = MathF.Min(吸收, MathF.Max(剩余缺口, 缺口 * 0.5f));

            有效 += 吸收有效;
        }

        // 非紧急时的额外偏好（小权重 —— 主要价值已经在上面算进"有效"了）
        var 盾加分 = 技.是盾 && !命悬一线 ? 0.10f * 覆盖比例 : 0f;

        // ══ 合成 ══
        //   有效治疗量是主项；`效率项`（1/GCD）是**乘法**修正 ——
        //   因为"要几个 GCD"直接决定这笔治疗的总成本；
        //   其余（移动 / 能力技 / HoT / 盾）是比例加分；效率罚是减法。
        var 基准 = MathF.Max(1f, 缺口);
        return 有效 / 基准 * 效率项 * (1f + 移动加分 + GCD加分 + HoT加分 + 盾加分)
               - 效率罚 / 基准;
    }

    /// <summary>
    /// **针对一个具体目标挑最优治疗** —— 给「必须奶满」这类
    /// "目标已经锁定、只需要挑技能"的场景用。
    ///
    /// ⚠️ 和 <see cref="选最优"/> 的区别：
    ///     那个只管"缺口多少"，这个**自己算缺口** ——
    ///     因为调用方（`Res_MustFullHeal`）手上只有 `IBattleChara`。
    ///
    /// ⚠️ `命悬一线` 的判据用 `目标.有效血量比例() <= 0.30`
    ///     （和 `HealSettings.紧急单奶阈值` 同一个语义）——
    ///     中"必须奶满"机制的人**血可能还很高**，
    ///     所以还要看调用方传的 `强制紧急`。
    /// </summary>
    public static 治疗技能? 给目标选最优(
        治疗候选集 候选,
        IBattleChara 目标,
        bool 强制紧急 = false,
        bool 只群体 = false,
        bool 只瞬发 = false)
    {
        try
        {
            // ⚠️ 用**未来缺口**（含预测掉血）而不是当前缺口 ——
            //    否则"现在满血、3 秒后吃机制"的情况会判定成"不用治"。
            var 缺口 = 未来缺口(目标);
            if (缺口 <= 0f) return null;

            var 命悬 = 强制紧急;
            if (!命悬)
            {
                try { 命悬 = 目标.有效血量比例() <= 0.30f; } catch { }
            }

            return 选最优(候选, 缺口, 命悬, SpellUtil.不能读条(), 只群体, 只瞬发);
        }
        catch
        {
            return null;
        }
    }

    /// <summary>
    /// 目标还差多少血。
    ///
    /// ⚠️ 用 `有效血量比例`（含盾）而不是裸血量 ——
    ///    已经套了盾的人"看起来血少"但实际不缺治疗。
    /// </summary>
    public static float 缺口量(IBattleChara 目标)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            var 上限 = 目标.MaxHp;
            if (上限 <= 0) return 0f;
            return MathF.Max(0f, 上限 * (1f - 目标.有效血量比例()));
        }
        catch
        {
            return 0f;
        }
    }

    /// <summary>
    /// **未来缺口**（毫秒）—— 把"未来这几秒还会掉多少血"算进来。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要它（用户的要求）★
    ///
    ///    只看当前缺口的问题是**永远慢一步**：
    ///      现在 90% 血 → 判定"不需要治" → 3 秒后机制落地掉到 30% → 才反应。
    ///    而如果有 40% 的伤害在路上，**现在就该铺盾/HoT**。
    ///
    ///    用户原话："ai也要学会预测伤害…这样才不会思考好了已经过时了"
    ///
    ///  ★ 怎么算 ★
    ///    未来缺口 = max(当前缺口, 当前缺口 + 预计掉血 - 当前剩余护盾空间)
    ///    简化成：**当前缺口 + 预计掉血**（预测的掉血一定需要补）。
    ///
    ///  ⚠️ 窗口取多少：
    ///    太长会把"很久以后的伤害"当成"现在就该治" → 过度治疗。
    ///    默认 **2.5 秒** —— 一个 GCD 多一点，正好是"这一发治疗能覆盖到"的范围。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static float 未来缺口(IBattleChara 目标, float 预测秒 = 2.5f)
    {
        try
        {
            var 当前 = 缺口量(目标);
            var 预测 = 伤害预测.预计掉血(目标, 预测秒);
            return 当前 + MathF.Max(0f, 预测);
        }
        catch
        {
            return 缺口量(目标);
        }
    }

    /// <summary>当前蓝量比例（0~1）；读不到返回 1（当作满蓝，不偏向省蓝）</summary>
    private static float 蓝量比例()
    {
        try
        {
            var 最大 = Core.Me.MaxMp;
            if (最大 <= 0) return 1f;
            return Core.Me.CurrentMp / (float)最大;
        }
        catch
        {
            return 1f;
        }
    }
