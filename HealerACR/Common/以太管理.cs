using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;

namespace HealerACR.Common;

/// <summary>
/// 以太管理 —— 参考同类 ACR 的 `AetherflowManager.SetNoAetherflowTrue`。
///
/// ══════════════════════════════════════════════════════════════════
///  ⚠️ 用户实测指出的问题：**「以太保留数」的用途被我搞窄了。**
///
///  我原来的实现是"静态保留"：
///      以太 > 保留数 → 打豆子（能量吸收）
///  这只能保证"永远留着 N 颗"，但**分不清现在是不是有压力** ——
///  平静期也一直在留，白白浪费输出。
///
///  同类 ACR 的做法是"**动态抑制**"：
///      · 每用掉一颗豆子（不屈/活性法/罩子/契约）→ 记一个时间戳
///      · **7 秒内不再打豆子**
///      · 7 秒后没再动用 → 认为压力过去了，可以打
///
///  **核心洞察**：豆子要留是因为**要应急奶**。
///  而"刚用过豆子"这件事本身就是**有压力的最强信号** ——
///  比任何血量阈值都直接（血线可能已经从低谷涨回来了，
///  但治疗刚花掉的资源还没补上）。
///
///  所以正确做法是**两者结合**：
///      保留数  → 保底（永远留 N 颗）
///      动态抑制 → 自适应（刚用过就多留一会儿）
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 以太管理
{
    /// <summary>
    /// 用掉豆子后的抑制时长（毫秒）。
    /// 同类 ACR 用的是 7 秒 —— 约 2~3 个 GCD，
    /// 正好覆盖"刚用完可能还要再用"的那个窗口。
    /// </summary>
    private const int 抑制时长 = 7000;

    /// <summary>上次观察到以太数量变化的时间</summary>
    private static long _上次用豆子;

    /// <summary>上次看到的以太数量（用来检测"用掉了"）</summary>
    private static int _上次以太 = -1;

    /// <summary>以太超流的 buff id</summary>
    private const uint 以太Buff = 304;

    /// <summary>
    /// 现在是不是处于"刚用过豆子"的抑制期。
    /// **true = 短期内不要再打豆子**（留着应急）。
    /// </summary>
    public static bool 抑制中
    {
        get
        {
            try { return TimeHelper.Now() - _上次用豆子 < 抑制时长; }
            catch { return false; }
        }
    }

    /// <summary>还剩多少毫秒解除抑制（调试显示用）</summary>
    public static int 剩余抑制毫秒
    {
        get
        {
            try
            {
                var 剩 = 抑制时长 - (int)(TimeHelper.Now() - _上次用豆子);
                return Math.Max(0, 剩);
            }
            catch { return 0; }
        }
    }

    /// <summary>当前以太数量</summary>
    public static int 当前以太
    {
        get
        {
            try { return Core.Me.GetAuraStack(以太Buff); }
            catch { return -1; }
        }
    }

    /// <summary>
    /// 每帧调用：**通过观察以太数量变化来自动检测"用掉了豆子"**。
    ///
    /// **为什么用观察而不是让每个技能显式上报**：
    ///   需要上报的地方有 4 个以上（不屈/活性法/罩子/契约/转化…），
    ///   每加一个技能都要记得改，很容易漏。
    ///   而"以太从 3 变成 2"这件事本身**就等价于用掉了一颗**，
    ///   观察它比让所有人上报更可靠。
    /// </summary>
    public static void 每帧更新()
    {
        try
        {
            var 现在 = 当前以太;
            if (现在 < 0) return;

            // 第一次记录，不做判断
            if (_上次以太 < 0)
            {
                _上次以太 = 现在;
                return;
            }

            // 数量变少 → 用掉了豆子
            if (现在 < _上次以太)
            {
                _上次用豆子 = TimeHelper.Now();
            }

            _上次以太 = 现在;
        }
        catch { }
    }

    /// <summary>
    /// 综合判断：**现在该不该打豆子（能量吸收）**。
    ///
    /// 三个条件全部满足才打：
    ///   ① 不处于"刚用过豆子"的抑制期
    ///   ② 以太数量超过保底值
    ///   ③ 当前不是治疗压力场景（由调用方判断）
    /// </summary>
    /// <param name="以太数量">当前以太</param>
    /// <param name="保底">用户设的保留数</param>
    public static bool 可以打豆子(int 以太数量, int 保底)
    {
        if (以太数量 <= 0) return false;

        // ① 动态抑制：刚用过就不打
        if (抑制中) return false;

        // ② 静态保底：留够用户设的数量
        return 以太数量 > Math.Clamp(保底, 0, 3);
    }

    /// <summary>
    /// **以太超流快转好了吗** —— 转好之前该把剩下的豆子用掉。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 这条规则的道理（用户要求的新机制）★
    ///
    ///    以太超流的机制是**补满到 3 颗**，不是"加 3 颗"。
    ///    所以如果转好时手里还有豆子，**那些豆子就白溢出了**。
    ///
    ///    结论：**在它转好之前把手里的豆子清空，等于白赚输出。**
    ///
    ///  ⚠️ 但"清空"有个前提：**这段时间内不能有治疗压力** ——
    ///     万一清空了正好来人需要活性法/不屈，就没牌了。
    ///     所以这个判断**只是"可以卸"的条件之一**，
    ///     真正的治疗压力判断在调用方（`SCHSpellTable.输出能力技`）里做。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <param name="提前毫秒">还剩这么久转好就开始卸（默认 8 秒 ≈ 3 个 GCD，够把豆子打完）</param>
    public static bool 以太超流快转好(int 提前毫秒 = 8000)
    {
        try
        {
            var 技能 = SpellIds.取("以太超流");
            if (技能 == 0) return false;

            var 剩余秒 = CharacterExt.冷却剩余秒(技能);

            // 读不到（-1）→ **不当作"快转好"**
            //   ⚠️ 方向很重要：读不到就卸豆的话，
            //      万一读取接口挂了，豆子会被无脑打光。宁可保守。
            if (剩余秒 < 0f) return false;

            // 已经转好（0）也算"该卸了"—— 因为下一发马上就能补满
            return 剩余秒 * 1000f <= 提前毫秒;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// **现在是不是爆发窗口** —— 爆发期间豆子该拿去换输出，不受保留数限制。
    ///
    /// 用户要求："默认留，除非开爆发…"
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 用「一键爆发」开关判意图，**不加血量门槛** ★
    ///
    ///  ── 用户实测报的问题 ──
    ///    "启用一键爆发没有效果，豆子没有全打出去"
    ///
    ///  ── 原来为什么没效果 ──
    ///    这里原来有一道 `低于阈值人数(0.35f) > 0 → return false`。
    ///    在 50 级「究极神兵」这种本里，**全程都有人 <35%** ——
    ///    于是这个窗口**永远为假**，勾了「一键爆发」也一颗豆子都不卸。
    ///
    ///  ── 为什么这道门槛是多余的 ──
    ///    它是**第二层**保险，而第一层（`Res_OffensiveAbility` 里
    ///    `有人在等治疗() → return -1`）已经挡住了"该救人的时候不卸豆"。
    ///    两道门槛用的是同一个判据（都是"有人低于阈值"），
    ///    区别只是**阈值高低**（0.35 vs 单体治疗阈值）。
    ///    ⇒ 结果不是"更安全"，而是**苛刻到永不触发**。
    ///
    ///  ⚠️ 而且语义上就不对：
    ///     用户**显式按下了「一键爆发」**，那就是"我要现在爆发"。
    ///     他按按钮的那一刻就已经表达了意图，不需要我们再替他判断
    ///     "现在够不够安全" —— 真危险的时候第一层会挡。
    ///
    ///  ⚠️ 保留的两条：
    ///     · 开关没开 → 不是爆发窗口（这是开关的本意）
    ///     · 脱战 → 不卸豆（脱战卸豆纯浪费）
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static bool 在爆发窗口()
    {
        try
        {
            if (!HealQt.GetQt("一键爆发", false)) return false;
            if (!Core.Me.InCombat()) return false;

            return true;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>战斗重置</summary>
    public static void 重置()
    {
        _上次用豆子 = 0;
        _上次以太 = -1;
    }
}
