    /// <summary>
    /// **威力档位** —— 用来判断"贴身时该用破阵法还是毁坏"。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  ★ 数据逐字来自**游戏数据宏**（不是攻略站的数字）★
    ///
    ///    用 `tools\HealPotency` 的 `raw` 模式解出（`ToMacroString()`）：
    ///
    ///      破阵法 16539:
    ///        <if([gnum68==28], <if([gnum72>=54], 165, 150)>, 150)>
    ///         └ 是学者 ┘        └ 等级≥54 ┘  高   低
    ///
    ///      毁坏 17870:
    ///        <if(学者, <if(等级>=82, 220,
    ///              <if(等级>=72, 200,
    ///              <if(等级>=64, 180,
    ///              <if(等级>=54, 160, 140)>)>)>)>, 140)>
    ///
    ///      裂阵法 25866:  180（**无档位**，恒定）
    ///      极炎法 25865:  <if(学者, <if(等级>=94, 320, 295)>, 295)>
    ///
    ///  ★ 为什么必须按等级比（而不是固定用一个）★
    ///
    ///    两者的相对高低**随等级翻转**：
    ///        46~53  破阵法 150 > 毁坏 140   ← 贴身该用**破阵法**
    ///        54~63  破阵法 165 > 毁坏 160   ← 还是破阵法
    ///        64~71  毁坏   180 > 破阵法 165 ← **翻转！**该用毁坏
    ///        72~81  毁坏   200 > 破阵法 165
    ///        82+    毁坏   220 > 裂阵法 180
    ///
    ///  ⚠️ 我曾经两次判错这件事：
    ///    ① 凭印象说"破阵法 600 > 毁坏 500"（那两个数没有出处）
    ///    ② 拿 The Balance 的 **100 级**数据（毁坏 220 / 裂阵法 180）
    ///       去判断 50 级 —— 而 50 级其实是 破阵法 150 / 毁坏 140，
    ///       **结论正好相反**。
    ///    威力**每个资料片都会重做**，且**每级档位不同** ——
    ///    必须按当前等级查。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **咏唱时间**（秒）—— 数据来自 `tools\CastProbe`（游戏 `Cast100ms` 字段）。
    ///
    /// ⚠️ 学者的读条填充技**全是 1.5 秒**，瞬发的全是 0 ——
    ///    而复唱都是 2.5 秒，所以两者都只占一个 GCD，
    ///    **咏唱时间在"选最优"的排序里约掉了**（比威力即可）。
    ///    见 `JobSpellTable.咏唱时间表` 的说明。
    /// </summary>
    public override IReadOnlyDictionary<uint, float> 咏唱时间表 { get; } = new Dictionary<uint, float>
    {
        [SpellIds.取("毁灭")]   = 1.5f,
        [SpellIds.取("毁坏")]   = 0f,      // 瞬发
        [SpellIds.取("破阵法")] = 0f,      // 瞬发
        [SpellIds.取("裂阵法")] = 0f,      // 瞬发
        [SpellIds.取("气炎法")] = 1.5f,
        [SpellIds.取("魔炎法")] = 1.5f,
        [SpellIds.取("死炎法")] = 1.5f,
        [SpellIds.取("极炎法")] = 1.5f,
    };

    protected override (int 等级, int 威力)[]? 威力表(uint 技能Id)
    {
        // 破阵法（46 级学）→ 54 级提升一档
        if (技能Id == SpellIds.取("破阵法"))
            return new[] { (54, 165), (0, 150) };

        // 裂阵法（82 级学）—— 无档位
        if (技能Id == SpellIds.取("裂阵法"))
            return new[] { (0, 180) };

        // ══════════════════════════════════════════════════════════════
        //  ★ 毁灭 —— **必须在这一档里**（用户实测发现缺失）★
        //
        //  [!] 现象：AI 连续 34 次建议 `17870`（毁坏），本地每次选
        //      `17869`（毁灭）—— **本地是对的**。
        //
        //  [!] 为什么 AI 选错：`威力表` 里**没有毁灭** =>
        //      `查威力(毁灭)` 返回 0 => 即使 prompt 给了"力NNN"字段，
        //      AI 也只看到 毁坏=140、毁灭=（空）—— 只能保守选瞬发的那个。
        //
        //  [!] 真值：毁坏 50 级 = 140（瞬发）；毁灭 = 150（1.5 秒读条）。
        //      站定 -> 150 更优；移动 -> 只能 140。
        //      补齐之后 AI 才能做这个比较。
        // ══════════════════════════════════════════════════════════════
        if (技能Id == SpellIds.取("毁灭"))
            return new[] { (0, 150) };

        // 毁坏（38 级学）→ 54 / 64 / 72 / 82 各提一档
        if (技能Id == SpellIds.取("毁坏"))
            return new[] { (82, 220), (72, 200), (64, 180), (54, 160), (0, 140) };

        // ══════════════════════════════════════════════════════════════
        //  ★ 魔炎法(64) / 死炎法(72) —— **补上，否则 64~81 级在打错技能** ★
        //
        //  [!] 现象（逐等级模拟发现）：
        //      64~81 级 `基础输出` 解析成 魔炎法 / 死炎法，
        //      而威力表**没有这两个** ⇒ `查威力` = 0 ⇒ 选不出来
        //      ⇒ 逐级落到「破阵法 165」⇒ **每发少打 75~90 威力**
        //        （魔炎法 240 / 死炎法 255  vs  破阵法 165）。
        //
        //  [!] 数值来源：**官方 `Action:<id>` 页**（wiki，权威）——
        //        `炎法精通II`（64级）：气炎法变为魔炎法，并将毁坏的威力提高到180
        //        `炎法精通III`（72级）：魔炎法变为死炎法，并将毁坏的威力提高到200
        //      ⇒ 240 / 255 是官方写明的，不是估的。
        //
        //  [!] 顺带证实：官方的"精通"特性把每个副作用都写明了，
        //      所以下面 破阵法(165@54) / 毁坏(160/180/200/220) 的档位**都是对的**。
        // ══════════════════════════════════════════════════════════════
        if (技能Id == SpellIds.取("魔炎法"))
            return new[] { (0, 240) };

        if (技能Id == SpellIds.取("死炎法"))
            return new[] { (0, 255) };

        // 极炎法（82 级学）→ 94 级提升一档
        if (技能Id == SpellIds.取("极炎法"))
            return new[] { (94, 320), (0, 295) };

        // ══════════════════════════════════════════════════════════════
        //  ★ 气炎法（54 级学）★ —— 补上，否则 54~81 级 AI 看不到它的威力
        //
        //  [!] 缺口：`基础输出` 的链条是
        //        极炎法(82) / 死炎法(72) / 魔炎法(64) / 气炎法(54) / 毁坏(38) / 毁灭(1)
        //      而 `威力表` 只覆盖了 破阵法/裂阵法/毁灭/毁坏/极炎法 ——
        //      **气炎法、死炎法、魔炎法全都不在里面** => `查威力` 返回 0。
        //
        //  ⇒ 54~81 级时 `基础输出` 取到气炎法，但清单里它的威力是空的，
        //     AI 只能拿它跟"毁坏 140"比 —— 而气炎法实际是 **220**，
        //     **每发少 80 威力**（比用户发现的 -10 严重得多）。
        //
        //  [!] 只写有依据的档位。不确定的**宁可不写** ——
        //      错的威力会让 AI 选错技能，比缺一个数字更糟。
        // ══════════════════════════════════════════════════════════════
        if (技能Id == SpellIds.取("气炎法"))
            return new[] { (0, 220) };

        // ══════════════════════════════════════════════════════════════
        //  ★ DoT 三档 + 能量吸收 —— **补上缺口**（用户要求：缺口会影响 AI 决策）★
        //
        //  [!] 为什么原来缺：**游戏数据宏不写它们的威力** ——
        //      `pow_potency.tsv` 里这三条只有
        //        「对目标附加无属性持续伤害状态」，**没有「威力：」那一句**。
        //      所以按数据宏建表时它们全是空的。
        //
        //  [!] 数值来源：`beta.xivapi.com/api/1/sheet/Action/<id>`
        //      （游戏 Action 表 + ActionTransient 的镜像）—— **不是攻略站**。
        //      逐字原文：
        //        17864 毒菌    Deals unaspected damage over time. Potency: 20  Duration: 30s
        //        17865 猛毒菌  Deals unaspected damage over time. Potency: 40  Duration: 30s
        //        16540 蛊毒法  Deals unaspected damage over time. Potency: 85  Duration: 30s
        //        167   能量吸收 Deals unaspected damage with a potency of 100.
        //
        //  [!] 口径 = **每跳**（和 `HoT恢复力` 同语义）——
        //      这三个 DoT 的描述里**只有一个 Potency**（它们没有直伤），
        //      和白魔「天辉 85」「烈风 50」同一口径（见 `WhiteMageACR.cs` L98-101）。
        //
        //  [!] 为什么值得补：
        //      DoT 走 `值得上Dot()`（判血量/血量倍数）**不比较威力** ——
        //      所以缺口**不会导致选错技能**。
        //      但提示词里 `力N` 空着时，AI 判该不该补 DoT只能凭训练记忆，
        //      这正是用户说的会影响 AI 决策。
        // ══════════════════════════════════════════════════════════════
        if (技能Id == SpellIds.取("毒菌")) return new[] { (0, 20) };
        if (技能Id == SpellIds.取("猛毒菌")) return new[] { (0, 40) };
        if (技能Id == SpellIds.取("蛊毒法")) return new[] { (0, 85) };
        
        // 能量吸收：直伤（不是 DoT），同样是输出能力技里唯一缺威力的那条
        if (技能Id == SpellIds.取("能量吸收")) return new[] { (0, 100) };
        
        return null;
    }

    // 能量吸收是"以太换输出"，卡 CD 打（跟法令一个道理）
    // 能量吸收是拿以太换输出。
    // ⚠️ 关键：以太**读不到**时不能判死 —— JobApiHelper 读失败会返回 0，
    //    如果直接写 "以太 >= 1"，读不到就等于"永远没以太"，永远不打能量吸收。
    /// <summary>
    /// 输出能力技（能量吸收）—— **默认留着，只在两种时机卸**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 机制（替换原来的"有豆子就卸"）★
    ///
    ///    **默认留**，只有满足下面任一条才打能量吸收：
    ///
    ///    ① **开爆发** —— 爆发窗口里豆子就该换输出，不受保留数限制
    ///    ② **补豆技快转好了**（以太超流或转化取先转好的那个），且**无治疗压力** ——
    ///       在它转好之前把豆子清空
    ///
    ///  ── 为什么②是对的（这段是理解的关键）──
    ///
    ///    以太超流的机制是**补满到 3 颗**，**不是"加 3 颗"**。
    ///    所以如果它转好时你手里还攥着豆子，**那些豆子直接白溢出**。
    ///
    ///    ⇒ 在它转好前把手里清空 = **白赚输出**，没有任何代价。
    ///    ⇒ 反过来，转好还早的时候卸豆就是纯亏 ——
    ///       因为豆子留在手里既能应急、又能在它补满前一直存着。
    ///
    ///    这就是"默认留"的全部道理：**留到快溢出为止**。
    ///
    ///  ── 旧逻辑错在哪（留个记录，别再改回去）──
    ///
    ///    原来是"队伍血量健康 + 以太 > 保留数 → 卸"，
    ///    再加上"小怪阶段卸到剩 1 颗"和"满 3 颗必卸"。
    ///    问题：**转好还早就把豆子打光了**，
    ///    等到以太超流转好时手里没豆子，那 3 颗就只是"补回来"，
    ///    没有产生任何额外输出 —— 等于把资源浪费在"提前打掉"上。
    ///
    ///  ⚠️ 读不到以太时**不卸**（保守）：
    ///     旧代码是"读不到就卸"（`if (!读得到) return new[]{能量吸收}`）——
    ///     那在读取接口抽风时会把豆子无脑打光。现在改成读不到就留着。
    ///
    ///  ⚠️ 「以太保留数」设置有冲突：
    ///     新机制下"留着"是默认行为，这个设置已经**没有意义**了
    ///     （它想表达的"留几颗"就是现在的默认）。
    ///     保留它只是为了不破坏旧存档，界面上仍可调但不影响本逻辑。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public override uint[] 输出能力技
    {
        get
        {
            var 能量吸收 = SpellIds.取("能量吸收");
            if (能量吸收 == 0) return Array.Empty<uint>();

            // ⚠️ 读不到以太 → **留着**（不要卸）。
            //    方向很重要：读不到就卸的话，接口一抽风豆子就没了。
            if (!JobApiHelper.读得到("以太")) return Array.Empty<uint>();

            // 总开关（用户可能想完全禁掉卸豆）
            if (!HealQt.GetQt("能量吸收", true)) return Array.Empty<uint>();

            // 蓝量见底时停手 —— 蓝要留给治疗
            if (蓝量.低蓝停手()) return Array.Empty<uint>();

            var 以太 = JobApiHelper.以太;
            if (以太 <= 0) return Array.Empty<uint>();   // 没豆子，等以太超流补

            // ── 条件①：爆发窗口 → 拿去换输出 ──
            if (以太管理.在爆发窗口()) return new[] { 能量吸收 };

            // ── 条件②：补豆技（超流/转化）快转好 + 无治疗压力 → 清空免得溢出 ──
            // ══════════════════════════════════════════════════════════════
            //  ★ 卸豆诊断（用户报告「转好前没把豆子用完」）★
            //
            //  [!] 为什么要打这个：
            //      用户实测「以太超流补满 16 次 / 能量吸收 0 次」。
            //      但**那条日志大部分在脱战**（`以太超流` 只能战斗中放），
            //      所以那个数字**不能证明卸豆逻辑坏了**。
            //      ==> 让代码自己说：把判据的每一项都打出来。
            //
            //  [!] 只在该卸的窗口里打（`消耗技快转好()` 成立 + 有豆子），
            //      否则每帧一条会把日志刷满。
            // ══════════════════════════════════════════════════════════════
            if (以太 > 0 && 以太管理.消耗技快转好())
            {
                try
                {
                    var 告急人数 = HealTargetHelper.低于阈值人数(HealSettings.Instance.紧急单奶阈值);
                    var 群疗线人数 = HealTargetHelper.低于阈值人数(HealSettings.Instance.群体治疗阈值);
                    LogHelper.Info($"[卸豆] 以太={以太} 快转好=True" +
                                   $" 告急线={HealSettings.Instance.紧急单奶阈值:F2}({告急人数}人)" +
                                   $" 群疗线={HealSettings.Instance.群体治疗阈值:F2}({群疗线人数}人)" +
                                   $" 爆发窗口={以太管理.在爆发窗口()}" +
                                   $" => {(告急人数 == 0 ? "全卸" : "留着（有人告急）")}");
                }
                catch { }
            }
            
            // ══════════════════════════════════════════════════════════════
            //  ★ 条件②：补豆技快转好 -> **把剩下的豆子全卸掉** ★
            //
            //  [!] 机制（游戏数据，`Action:166`）逐字：
            //        "Restores 20% of maximum MP."
            //        "Additional Effect: **Aetherflow III**"
            //        "**Can only be executed while in combat.**"
            //      ==> 它**补满到 3 颗**（不是加 3 颗）。
            //          所以转好时手里还有豆子 -> **那些豆子白溢出**。
            //          转好前清空 = **白赚 100 威力 × N**。
            //      ==> 这是用户明确要求的：「下一个以太超流转好了记得把剩下的豆子全用了，
            //          没治疗缺口就能量吸收，不要浪费豆子」
            //
            //  [!] 判据 = **没有人告急**（不是没有人低于群疗线）——
            //
            //      原来写的是 `低于阈值人数(群体治疗阈值 = 0.62) == 0`，
            //      那是必须零治疗压力才敢卸。**太严了**：
            //        只要有 1 个人在 61% -> 一颗都不卸 -> 快转好时 3 颗全溢出。
            //      而真正的风险窗口只有**那 8 秒** —— 8 秒后补满到 3，
            //      我们卸掉的每一颗都换来实打实的 100 威力。
            //      ==> 改成只看有没有人告急：
            //            有人低于 `紧急单奶阈值`（默认 0.30）-> 留着（那才是真需要瞬时 Ability 的场景）
            //            无人告急                              -> 全卸
            //
            //  ⚠️ **不看 `以太保留数`**（用户设的那个）——
            //      快转好时那颗豆子**马上就会被覆盖掉**，留着等于白扔。
            //      保留数只在没快转好时有意义，而那条路已经无条件留着（见函数末尾）。
            // ══════════════════════════════════════════════════════════════
            if (以太管理.消耗技快转好())
            {
                var 告急人数 = 0;
                try { 告急人数 = HealTargetHelper.低于阈值人数(HealSettings.Instance.紧急单奶阈值); }
                catch { }
            
                // 没人告急 -> 全卸（8 秒后补满，等于白赚输出）
                if (告急人数 == 0) return new[] { 能量吸收 };
            }

            // ── 其他情况：一律留着 ──
            return Array.Empty<uint>();
        }
    }
}

