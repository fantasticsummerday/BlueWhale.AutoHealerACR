            if ((AI.Instance?.BattleData?.CurrBattleTimeInMs ?? 0) <= 5000) return -9;
        }
        catch { }

        return SpellUtil.可用(技能) ? 2 : -1;
    }

    public void Build(Slot slot)
    {
        var spell = SpellUtil.Get(技能);
        if (spell != null) slot.Add(spell);
    }
