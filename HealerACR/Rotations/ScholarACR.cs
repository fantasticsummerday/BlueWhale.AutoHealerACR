    private 治疗候选集? _治疗候选;

    /// <summary>

    /// **按等级查两档恢复力**（高等级档 / 低等级档）。

    ///

    /// [!] 游戏数据宏的形式是 `if(等级>=N, 高, 低)`。

    ///     来源：`dump_healpot.tsv`（游戏 ActionTransient 说明）。

    ///

    /// [!] 为什么要分档：不分档会把低等级段的恢复力**高估**

    ///     （医术 450/400 ⇒ 85 级以下高估 12.5%），

    ///     而医术 vs 鼓舞激励之策只差 150，就可能翻转选择。

    /// </summary>

    private static int 档位(uint 技能Id, int 高, int 低, int 提升等级)

    {

        try { return CharacterExt.我的等级() >= 提升等级 ? 高 : 低; }

        catch { return 低; }

    }

    
    public override 治疗候选集 治疗候选
    {
        get
        {
            if (_治疗候选 != null) return _治疗候选;

            var c = new 治疗候选集();

            // ── 单体 GCD ──
            // [!] 恢复力**分档**（450/400，85 级提升）——
            //     原来写死 450 ⇒ 85 级以下**高估 12.5%**，
            //     真值来源：`dump_healpot.tsv` 的 `恢复力=450/400`。
            c.加(new 治疗技能 { Id = SpellIds.取("医术"), 名 = "医术", 等级 = 4,
                恢复力 = 档位(SpellIds.取("医术"), 450, 400, 85), MP = 400, 咏唱 = 1.5f, 复唱 = 2.5f });

            // ── 单体 GCD 盾 ──
            c.加(new 治疗技能 { Id = SpellIds.取("鼓舞激励之策"), 名 = "鼓舞激励之策", 等级 = 30,
                恢复力 = 300, MP = 900, 咏唱 = 2.0f, 复唱 = 2.5f, 是盾 = true });

            // ── 群体 GCD 盾 ──
            // ══════════════════════════════════════════════════════════════
            //  [!] **修正：盾被算了两次**（数据核对发现）
            //
            //      原来写 `恢复力 = 520`（= 200 × 2.6，已把盾折进去）
            //      **同时又标 `是盾 = true`** ⇒ 打分里 `盾真实系数` 会**再加一次盾**。
            //
            //      真值（`dump_healpot.tsv` 原文）：
            //          恢复力：200
            //          追加效果：附加防护罩，**抵消相当于治疗量%的伤害**  持续 30 秒
            //      ⇒ 治疗 200 + 盾（100%）⇒ 恢复力写 **200**，盾交给 `是盾` 处理。
            // ══════════════════════════════════════════════════════════════
            c.加(new 治疗技能 { Id = SpellIds.取("士气高扬之策"), 名 = "士气高扬之策", 等级 = 35,
                恢复力 = 200, MP = 900, 咏唱 = 2.0f, 复唱 = 2.5f, 群体 = true, 是盾 = true });

            // [!] 盾 **180%**（数据核对）——
            //     原文：「该防护罩能够抵消相当于治疗量 **180%** 的伤害」
            //     `减伤状态表.护盾` 查不到这个倍率（它写在技能说明里），
            //     所以必须由候选自己给出，否则会退回 0.5 兜底，低估 3.6 倍。
            c.加(new 治疗技能 { Id = SpellIds.取("意气轩昂之策"), 名 = "意气轩昂之策", 等级 = 96,
                恢复力 = 200, MP = 900, 咏唱 = 2.0f, 复唱 = 2.5f, 群体 = true,
                是盾 = true, 盾百分比 = 180 });

            // ── 单体能力技 ──
            c.加(new 治疗技能 { Id = SpellIds.取("生命活性法"), 名 = "生命活性法", 等级 = 45,
                恢复力 = 600, MP = 0, 咏唱 = 0f, 冷却 = 1f, 资源消耗 = 1 });

            c.加(new 治疗技能 { Id = SpellIds.取("深谋远虑之策"), 名 = "深谋远虑之策", 等级 = 62,
                恢复力 = 800, MP = 0, 咏唱 = 0f, 冷却 = 45f });

            // ── 群体能力技 ──
            c.加(new 治疗技能 { Id = SpellIds.取("不屈不挠之策"), 名 = "不屈不挠之策", 等级 = 52,
                恢复力 = 400, MP = 0, 咏唱 = 0f, 冷却 = 30f, 群体 = true, 资源消耗 = 1 });

            // [!] **修正：凭空虚构了一个 HoT**（数据核对发现）
            //     真值（`dump_healpot.tsv` 原文）：
            //         「恢复自身及周围队员的体力　恢复力：320　发动条件：小仙女处于同行状态」
            //     ⇒ **纯直疗，没有 HoT**。
            //     原来多写了 `HoT恢复力 = 320, HoT持续 = 21f` ——
            //     `总恢复力` 会从 320 变成 320 + 320×(21/3)×0.6 = **1664**，
            //     把它算成了 5 倍的治疗量，会严重挤掉真正该用的技能。
            c.加(new 治疗技能 { Id = SpellIds.取("异想的祥光"), 名 = "异想的祥光", 等级 = 76,
                恢复力 = 320, MP = 0, 咏唱 = 0f, 冷却 = 60f, 群体 = true });

            // [!] **补上盾标记**（数据核对发现漏了）
            //     真值（`dump_healpot.tsv` 原文）：
            //         「恢复周围队员的体力　恢复力：250
            //           追加效果：附加防护罩，**抵消相当于治疗量 100% 的伤害**　持续 30 秒」
            //     ⇒ 250 治疗 + 等量盾 = 一份能力技干两份活，原来完全没算盾。
            c.加(new 治疗技能 { Id = SpellIds.取("慰藉"), 名 = "慰藉", 等级 = 80,
                恢复力 = 250, MP = 0, 咏唱 = 0f, 冷却 = 30f, 群体 = true, 充能 = 2,
                是盾 = true, 盾百分比 = 100 });

            // [!] **修正：它是纯 HoT，没有直疗**（数据核对发现）
            //     真值（`dump_healpot.tsv` 原文）：
            //         「持续恢复周围队员的体力　恢复力：80　持续时间：21秒」
            //     ⇒ 80 是**每跳**，不是"直疗 80 + HoT 80"。
            //     原来写 `恢复力 = 80`（直疗）+ `HoT恢复力 = 80` ⇒ 多算了一口直疗。
            c.加(new 治疗技能 { Id = SpellIds.取("仙光的低语"), 名 = "仙光的低语", 等级 = 20,
                恢复力 = 0, MP = 0, 咏唱 = 0f, 冷却 = 60f, 群体 = true,
                HoT恢复力 = 80, HoT持续 = 21f });

            _治疗候选 = c;
            return c;
        }
    }

