            {
                if (团减快照.已有减伤()) return -5;
            }
            catch { }

            // ══════════════════════════════════════════════════════════════
        //  ★ 占星 `中间学派`：**5000ms Boss 读条门里的"让路"**（照抄 youshu IL）★
        //
        //  [!] IL 原文（`.il\cls_youshu\ACR.Astrologian.Resolvers.中间学派.txt`）：
        //      · `IL_0092`：`HasBossCastingAoeWithin(5000)`
        //      · `IL_009e~IL_00de`：自身 `849`（命运之轮）/ `3895` / `3896` 任一在身 ⇒ `-4`
        //        —— **这三条已由上面 `团减快照.已有减伤()`（`白魔占星Ids`）的 `-5` 拦住** ✓
        //      · `IL_00b0~IL_00ba`：`IsReady(3613)`（**命运之轮在手上**）⇒ `-4` 让路
        //        —— 这一条原来我们没有 ⇒ 同一拍里团减一路会跟命运之轮抢 ✗
        //      ⇒ 负数 = **不放**：5 秒内要挨 Boss AOE 时，让 6000ms 门内的命运之轮先走
        //        （`Res_GroupMitigationExtra` 排它）。
        //
        //  [!] 复用项：`HasBossCastingAoeWithin(5000)` = `减伤Helper.即将来大伤害(5000)`
        //      （`Common/MitigationHelper.cs:21`），窗口 **5000 照 IL 原值**。
        //  ⚠️ 只对**占星**的 `中间学派` 生效 —— 学者 / 贤者那两支一行不动。
        // ══════════════════════════════════════════════════════════════
        if (_t.Job == Jobs.Astrologian && _t.团队减伤 == SpellIds.取("中间学派"))
        {
            try
            {
                if (减伤Helper.即将来大伤害(5000)
                    && SpellUtil.可用(SpellIds.取("命运之轮"))) return -4;
            }
            catch { }
        }

        if (!时间轴要求 && !读条要求 && !敌人够多 && !血线要求) return -1;

            // ══════════════════════════════════════════════════════════
            //  ★ **团减编排**（表 #121）：触发条件成立之后，
            //    贤者优先走"坚角+泛输血 / 坚角+整体论"这套组合 ——
            //    组合失败（都没好）再退到群盾兜底，最后才走原来的单发路径。
            //  [!] 这一段必须在**触发条件之后**：编排本身不判断"该不该交"，
            //      它只回答"交的话交哪几个"（分工和 `OffGcd闸门` 一样）。
            // ══════════════════════════════════════════════════════════
            if (_t.Job == Jobs.Sage)
            {
                var 编排 = 团减编排();
                if (编排.Count > 0) return 14;

                if (群盾兜底()) return 13;
            }

            // ══════════════════════════════════════════════════════════
            //  ★ **学者 组合优先级**（复刻 youshu `自动减伤.GetAoeMitigationSpells`）★
            //    罩子(188) 打头，与 幻光(16538) / 跑快快(25868) / 慰藉(16546) 组合，
            //    单发垫底 —— 逐条照 IL（见 `学者团减编排()` 里的 IL_xxxx 出处）。
            //  [!] 只到"选哪几个"：该不该交仍由上面的触发条件回答（和贤者那支同源）。
            //  [!] 贤者那一段**原样保留**（上面几行没动）。
            //  [!] ★ 2026-10-15：**传入"地面站得稳"** —— 含罩子的组合①~⑤必须先过这道，
            //      否则这里的 `return 16` 会把下方三道地面守卫整条绕过（见方法内注释）。
            // ══════════════════════════════════════════════════════════
            if (_t.Job == Jobs.Scholar
                && 学者团减编排(HealerACR.Common.敌人移动检测.地面站得稳())) return 16;

            // ══════════════════════════════════════════════════════════
            //  ★ **移动中不铺地面减伤**（道中小怪阶段实测报的问题）★
            //
            //  ── 现象 ──
            //     "在小怪阶段移动过程中又下罩子了" —— 跑路时往脚下丢一个罩子，
            //     人一走开，**整个罩子等于白铺**（还占了个大 CD）。
            //
            //  ── 根因 ──
            //    ① 地面技能是**瞬发**的，所以 `移动中可用()` 判 true，
            //       移动守卫拦不住它（读条守卫对地面技能天然失效）
            //    ② 落点逻辑 `敌人移动检测.地面技能位置()`：
            //         优选敌人**稳定观察满 3 秒** → 放它脚下
            //         否则                        → **放自己脚下**
            //       而道中小怪基本一直在动 → 永远走"放自己脚下"那条路 ——
            //       移动中放自己脚下 = 铺在一个马上没人待的位置
            //
            //  ── 判据 ──
            //     `敌人够多` 是**弱判据**（小怪群殴时永远成立），
            //     不足以支撑"移动中也要铺"。
            //     而 `时间轴要求` / `读条要求` 是**明确的即将来伤害** ——
            //     哪怕在移动，那一发也是真要吃的，值得铺。
            //
            //     ⇒ 移动中：**只认时间轴 / 读条这两个强判据**。
            //       仅靠"敌人够多"就先别铺，站定了再铺不迟
            //       （罩子持续 15 秒以上，站定的那一刻铺完全来得及）。
            // ══════════════════════════════════════════════════════════
            //  [!] 用 `不能读条()`（含跳跃）而不是 `在移动()` ——
            //      这里判的是"地面技**现在能不能放**"，而跳跃同样放不出，
            //      与 `移动中可用()` / `移动中能放()` 的判据同源（开发约定 F③）。
            if (是地面 && SpellUtil.不能读条() && !时间轴要求 && !读条要求) return -6;
            // ══════════════════════════════════════════════════════════════
            //  ★ **我停了还不够 —— T 也得停**（用户实测报的问题）★
            //
            //  ── 现象 ──
            //     70 级「死亡大地终末焦土」小怪阶段：
            //     **T 在路上停了一下**（我也跟着停），罩子就铺下去了 ——
            //     然后 T 继续往前拉 ==> **罩子落在马上没人待的位置**，白铺。
            //
            //  ── 为什么上面那条判据拦不住 ──
            //     它只看 `SpellUtil.在移动()` = **我自己**在不在动。
            //     道中拉怪时 T 停、我停是常态（等怪聚拢），但**那不是站定**。
            //
            //  ── 判据 ──
            //     地面减伤要几方都稳：
            //       ① 我（上面那条 `SpellUtil.在移动()` 已经判过）
            //       ② **T 站得稳**（`敌人移动检测.玩家站得稳`，和我同一套判据：
            //          观察满 3 秒 + 采样 ≥4 + 平均速度 < 2.5 米/秒）
            //       ③ 落点目标（当前目标）站得稳
            //
            //  [!] 数据不足时 `玩家站得稳` 返回 false ==> **宁可多等一秒，不要误铺**。
            //      罩子持续 15 秒以上，站定的那一刻铺完全来得及。
            //
            //  [!] 时间轴 / 读条仍可越过这条 —— 那是**明确的即将来伤害**，
            //      哪怕在跑动那一发也是真要吃的，值得铺（和上面同源逻辑）。
            //
            //  [!] 返回值用 -7 / -8 而不是 -6：排查时能一眼看出
            //      是“我自己在动”还是“T 在动”还是“落点在动”。
            // ══════════════════════════════════════════════════════════════
            if (是地面 && !时间轴要求 && !读条要求)
            {
                try
                {
                    // ② T 站定了没
                    var 主坦 = HealTargetHelper.队伍里的坦克();
                    if (主坦 != null && !HealerACR.Common.敌人移动检测.玩家站得稳(主坦))
                        return -7;      // T 还在动（或数据不足）-> 先别铺
            
                    // ③ 落点站定了没 —— 不稳定的话落点会退回自己脚下，
                    //    那等于铺在我站的地方，小怪一冲就废
                    var 落点目标 = HealTargetHelper.当前目标();
                    if (落点目标 != null && 落点目标.CurrentHp > 0 &&
                        !HealerACR.Common.敌人移动检测.移动很少(落点目标))
                        return -8;      // 落点还在动 -> 先别铺
                }
                catch { }
            }
            

            // ⚠️ 队伍里坦克正在假死 → 这段时间整体压力不大，罩子先留着
            //    （参考同类 ACR 的罩子 Check 里的 409/811/810）
            try
            {
                var 主坦 = HealTargetHelper.队伍里的坦克();
                if (主坦 != null && 主坦.处于假死状态()) return -5;
            }
            catch { }

        // ══════════════════════════════════════════════════════════════════
        //  ★ 2026-10-15：**白魔·任一队友带「告解 1219」⇒ 不交节制** ★
        //    （复刻 youshu `节制.txt` 的 Boss-AOE 分支）
        //
        //  [!] youshu 原文（`缺口清单-白魔.md` 节制那一行 + `对比报告` 第 54 行）：
        //       Boss AOE 3 秒内 —— `RecentlyUsed(7433 全大赦, 5000)` **或**
        //       **任一队友 `HasAura(1219)`** ⇒ `-5`；否则 ⇒ `60`。
        //       `1219 = 告解`（官方 `Status.csv` 核验）= 全大赦给队友挂的增疗 buff
        //       ⇒ **队友身上有告解 = 全大赦已经交过**，这一拍再交节制就是叠两层群减。
        //
        //  [!] 我们已有的两层：① 自身 1219 —— 已在 `团减快照` 里（本方法开头就查）；
        //       ② 节制↔全大赦 5500ms 互斥。**缺的正是"队友"这一层** ✗
        //       （自身挂了告解才有快照拦得住；队友身上有告解时快照看不见。）
        //
        //  [!] 只对白魔的「节制」这一条判：占星的中间学派/太阳星座各有自己的防叠（见 `自身门`）。
        // ══════════════════════════════════════════════════════════════════
        if (_t.Job == Jobs.WhiteMage && _t.团队减伤 == SpellIds.取("节制"))
        {
            try
            {
                foreach (var a in HealTargetHelper.可治疗队友(30f))
                {
                    if (a == null || !a.对象有效() || !a.活着()) continue;
                    if (a.HasAura(1219)) return -5;      // 告解：全大赦已在队友身上生效
                }
            }
            catch { }
        }

        // ★ 2026-10-15：**单发路径才用「罩子没资源」否决**（见 Check 前半段那个标志）★
        //   [!] 为什么放在这里而不是提前 return：学者组合⑥「单发跑快快」与
        //       ⑦「单发慰藉」**不吃豆子**，提前否决会把它们一起挡掉；
        //       而走到这行的学者只剩"单发罩子"一种可能 ⇒ 在这里判语义等价 ✓
        //   [!] 组合链自己的 `罩子就绪` 里已经含同样的条件（有以太 ‖ 秘策 1896），
        //       所以不会出现"组合链判不就绪、这里又放行"的矛盾。
        if (罩子没资源) return -2;

        return SpellUtil.可用(_t.团队减伤) ? 15 : -1;
    }

    public void Build(Slot slot)
    {
        // ★ 表外审计 W3：白魔 节制 交出去就记互斥锁（参考 `节制.txt:142` 的 MarkGroupMitigation；
        //   Build 被调到 = Check 已放行，这里无条件记，和"判 A 放 A"同源）
        if (_t.Job == Jobs.WhiteMage) 记白魔群减互斥();

        // ★ **团减编排分支**（表 #121）—— Check 算好的编排在这里照放 ★
        //   [!] 判 A 放 A（开发约定 F③）：组合 / 群盾兜底都在 Check 里选定，
        //       Build 只负责把 `_本帧编排` 里那几个按顺序塞进去。
        if (_本帧编排.Count > 0)
        {
            foreach (var id in _本帧编排)
            {
                // 群盾（预后）要带护盾前置（均衡），且目标是自己（自身中心 AOE）
                if (_t.Job == Jobs.Sage && id == _t.群体盾)
                {
                    if (_t.护盾前置 != 0 && !JobApiHelper.均衡中 && SpellUtil.可用(_t.护盾前置))
                    {
                        var pre = SpellUtil.Get(_t.护盾前置);
                        if (pre != null) slot.Add(pre);
                    }

                    var 盾 = SpellUtil.当前形态(_t.群体盾);
                    if (盾 != null) slot.Add(new Spell(盾.Id, SpellTargetType.Self));
                    continue;
                }

                // ★ 学者 罩子(188) 是**地面放置型**（CastType=7）——
                //   必须带落点坐标：直接 `SpellUtil.Get` 会丢掉"主坦脚下 / 目标脚下"的选位
                //   ⇒ 组合链里的罩子会放歪 ✗（400ms 延迟放置同理）
                if (技能数据.是地面技能(id))
                {
                    if (HealQt.GetQt("脚下放罩", false))
                        slot.Add(new Spell(id, CharacterExt.我的位置()));
                    else
                        放地面团减(slot, id);
                    continue;
                }

                var sp = SpellUtil.Get(id);
                if (sp != null) slot.Add(sp);
            }

            记团减锁();
            _本帧编排.Clear();
            return;
        }

        try
        {
            // ── 地面放置型技能的位置选择（参考同类 ACR 的 Qt「脚下放罩」）──
            //   · 勾上：放**自己脚下**（小怪散开时更稳，自己一定在队伍里）
            //   · 不勾：放**当前目标处**（Boss 战放 Boss 脚下，近战都在那）
            //
            // 自动识别"这个技能是不是要放地上"（对照 CastType=7），
            // 这样以后加新的地面技能不用再去改表。
            //
            // ⚠️ `Check` 里也有一份同名的 —— 两个方法各自作用域，不冲突。
            //    那边的用途是"移动中不铺"的判断（见 Check 里的说明）。
            //
            // ⚠️ 这里原来还有一行 `var 是地面 = 技能数据.是地面技能(_t.团队减伤);`
            //    —— **赋值后从未被读**（纯遗留死代码，已删）。
            //    [!] 为什么删掉是安全的：本方法**只被"地面型团队减伤"用**
            //        （学者野战治疗阵 / 占星命运之轮…），所以它无条件走
            //        "指定落点"那条分支，不需要判"是不是地面"。
            //        真要做这个判断应该在 `Check()` 里 ——
            //        开发约定 F③：判断在 Check，Build 只负责放。

            var 放脚下 = HealQt.GetQt("脚下放罩", false);

            if (放脚下)
            {
                // 地面技能需要指定坐标
                slot.Add(new Spell(_t.团队减伤, CharacterExt.我的位置()));
                return;
            }

            var spell = SpellUtil.Get(_t.团队减伤);
            if (spell == null) return;

            // ── 延迟放置（参考同类 ACR 的 Slot.AddDelaySpell）──
            //   450ms 是它用的值：等动画锁结束再放，避免"技能按了但没落下去"。
            //   地面技能尤其容易吃这个亏 —— 按下去人一动，位置就飘了。
            //
            // ══════════════════════════════════════════════════════════
            //  ★ 选位 —— **与对照实现一致的三分支**（IL 直证）★
            //
            //  ── 参考实现（`Scholar_SacredSoil.Build`）逐条还原 ──
            //     ① 先找**带特殊标记的队友** → 落点 = 那个人的位置
            //        （它查的是自己的 `SpecialBuffs` 表；
            //          语义 = "某个队友被机制点名了，把罩子给他"）
            //     ② 否则：**当前目标存在 且 `HitboxRadius <= 19`**
            //        → 落点 = 当前目标的位置
            //     ③ 否则 → 落点 = 自己脚下
            //
            //  ── 我们原来错在哪 ──
            //     我们的 `敌人移动检测.地面技能位置()` 要求敌人
            //     "稳定观察满 3 秒"，道中小怪一直在动 → **永远不满足**
            //     → 永远退回"放自己脚下" → 移动中铺在自己脚下、人一走白铺。
            //
            //     **参考实现根本不做"敌人稳不稳"这个判断** ——
            //     它直接把落点放在目标脚下（目标比玩家更不容易走开）。
            //
            //  ── 关于那个 19 ──
            //     它用的是 `HitboxRadius <= 19`（`Ldc_r4 19` + `Bgt_un`），
            //     **不是 15**。含义：**排除超大体积的 Boss** ——
            //     那种目标脚下给的坐标可能落在模型内部/场地外，罩子会放歪。
            //     不要改成 15。
            //
            //  ⚠️ 我们**没有** `SpecialBuffs` 那张表（那是参考实现自己的数据）。
            //     用等价的"必须奶满目标"顶上 —— 同一个语义：
            //     "被机制点名、必须照顾的那个人"。
            //     拿不到就跳到 ②。
            // ══════════════════════════════════════════════════════════
            var 落点 = CharacterExt.我的位置();   // ③ 兜底：自己脚下（和参考实现一致）

            try
            {
                // ① 坦克脚下（2026-10-04 修）
                //   [!] 原来这一支是"被机制点名的队友"（必须奶满.找目标()）—— 那是三个
                //      「必须奶满」类的机制 debuff，与坦克无关 ✗
                //   [!] 后果：道中拉怪时罩子铺在"中了机制的那个人"脚下，
                //      而坦克（= 怪堆中心）脚下收不到 ✗ ⇒ 实测"罩子乱放"
                //   [!] 现在改成"队伍里的坦克"；坦克为空则跳过这一支，落到下一支 ✓
                // ★ 用 `主坦()`：它是「被最多敌人盯着的那个 T」（含 1500ms 粘滞）；
                  //   而 `队伍里的坦克()` 取的是**血量最低**的坦克 ⇒ ST 掉血时罩子会铺到 ST 脚下 ✗
                  var 坦克落点 = HealTargetHelper.主坦();
                if (坦克落点 != null && 坦克落点.活着())
                    落点 = 坦克落点.Position;
                else
                {
                    // ② 当前目标（且体积不过大）
                    var 目标 = 输出目标.选();
                    if (目标 != null && 目标.活着() && 目标.HitboxRadius <= 19f)
                        落点 = 目标.Position;
                }
            }
            catch { }

            // ★ 2026-10-04 修（补深度发现）：**非地面技能不要给坐标** ✗
            //   占星的「中间学派」(16559) 是**自身增益 oGCD**（CastType=1、Range=0），
            //   给它一个地面坐标很可能**整条按不出去** ⇒ 团减线整个失效 ✗
            if (!技能数据.是地面技能(_t.团队减伤))
            {
                var 非地面 = SpellUtil.Get(_t.团队减伤);
                if (非地面 != null) slot.Add(非地面);
                return;
            }

            slot.AddDelaySpell(450, new Spell(_t.团队减伤, 落点));
        }
        catch (Exception e)
        {
            LogHelper.Info("[HealerACR] 团减放置失败，退回普通放置：" + e.Message);

            var 兜底 = SpellUtil.Get(_t.团队减伤);
            if (兜底 != null) slot.Add(兜底);
        }
    }
