    /// <summary>
    /// 学者"下一帧补交"的技能 id（IL 的 `pendingMitigation` 字段）。
    ///
    /// [!] IL_0261（罩子）/ IL_02dc（疾风怒涛之计）：炽天使**不在场**时，参考当帧只排
    ///     [炽天召唤(16545), 慰藉(16546)]，把罩子 / 跑快快记进 `pendingMitigation`，
