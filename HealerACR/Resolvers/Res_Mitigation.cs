        //      ② IL_010d~011f：`CountNeededGroupShieldsWithin20(群盾阈值) < Clamp(群奶人数,0,8)`
        //         → `-6`（需要补盾的人不够多 ⇒ 不值得交这一发）
        //      ③ IL_01c1~01cb：`CountBleedingTargetsWithin20() >= 4` → **返回 10**（提权）
        //         —— 这一档发生在"确定要铺"之后，是**优先级提升**不是新的触发源。
        //
        //  [!] 与上面那条通用 `需要盾 >= 1` 的分工：
        //        通用那条是**所有职业共用**的下限（至少 1 个人缺盾）；
        //        这里 ② 是**学者专属**的更高门槛（要够 `群奶人数` 那么多人才交）。
        //
        //  [!] ③ 的血线参数：参考的 helper 只收范围（`...Within20`，20 米、**无血线参数**）；
        //      我们的 `出血队友数量(血线, 半径)` 签名要求一个血线 ⇒ 传 **1.0f = 不过滤血量**，
        //      与参考同名 helper 的语义对齐（不是"80% 以下"那一档，那是贤者的用法）。
        // ══════════════════════════════════════════════════════════════
        if (_t.Job == Jobs.Scholar)
        {
            try
            {
                var 群人数 = Math.Clamp(HealSettings.Instance.群奶最少人数, 0, 8);

                // ① 20 米内已有群盾的人 ≥ 4 ⇒ 别再铺
                var 已有盾 = 0;
                foreach (var a in HealTargetHelper.可治疗队友(20f))
                {
                    if (a == null || !a.对象有效() || !a.活着()) continue;
                    if (a.有该技能的Buff(_t.群体盾)) 已有盾++;
                }
                if (已有盾 >= 4) return -6;

                // ② 需要补盾的人 < Clamp(群奶人数,0,8) ⇒ 不值得
                if (需要盾 < 群人数) return -6;

                // ③ 流血目标 ≥ 4 ⇒ 提权（放在"确定要铺"之后，与参考同序）
                if (出血队友数量(1.0f, 20f) >= 4) return 12;
            }
            catch { }
        }

        return SpellUtil.可用(_t.群体盾) ? 11 : -1;
    }

    public void Build(Slot slot)
    {
        // ⚠️ 必须和 Check 同源：Check 已经判过"要用前置且前置可用"，
        //    这里只重放同样的条件（判 A 放 A）
        if (_t.护盾前置 != 0 && !JobApiHelper.均衡中 && SpellUtil.可用(_t.护盾前置))
        {
            var pre = SpellUtil.Get(_t.护盾前置);
            if (pre != null) slot.Add(pre);
        }

        // ══════════════════════════════════════════════════════════════
        //  ★ **活化（Zoe）是群盾的一步，不是独立 resolver**（表 #129）★
        //
        //  [!] 参考（`群盾.txt`）：`shouldUseZoe` 这个字段是**群盾 Check 里算出来的**，
        //      `Build` 时如果它为真就**先塞活化再塞群盾** ——
        //      也就是说活化**从来不是一条独立的决策**，
        //      它只是"这一发群盾要不要先加个成"的一个分支 ✓
        //
        //  [!] 我们原来做成了独立 resolver（`Res_HealAmp` 之外的 `Res_HealBooster`），
        //      它自己判断时机、自己排队 ⇒ **可能和群盾错开**：
        //      活化的 20 秒增疗窗口开在"没有盾要铺"的时刻 ✗
        //
        //  [!] 现在按参考：只有 `群盾要活化` 为真（= 出血人数那一档成立、
        //      等级 ≥45、身上没有活化）时才在这里补一发。
        //      ⚠️ 独立 resolver 保留（别的职业/别的场景还要用它），
        //      但**贤者这一路**由群盾接管 —— 见 `SageACR` 队列里的说明。
        // ══════════════════════════════════════════════════════════════
        if (_t.Job == Jobs.Sage && 群盾要活化 && 活化 != 0)
        {
            var zoe = SpellUtil.Get(活化);
            if (zoe != null && SpellUtil.可用(活化) && !CharacterExt.我有光环(AuraIds.活化))
                slot.Add(zoe);
        }

        // 用当前形态：贤者的"预后"在均衡状态下会变成"均衡预后"
        var 盾 = SpellUtil.当前形态(_t.群体盾);
        if (盾 == null) return;
        slot.Add(new Spell(盾.Id, SpellTargetType.Self));

        群盾要活化 = false;   // 用完即清（下一帧重新算）
    }
}

/// <summary>
/// 团减快照 —— 「现在身上已经有减伤了吗」。
///
/// ★ 2026-10-04 新增：对照实现的 CurrentMitigation() 会在放团减前先查一层快照，
///   任一已有 ⇒ 整体放弃；我们的 5 个团减/群疗各自为战 ⇒
///   同一帧可能连出 2~3 个大 CD（坚角清汁 + 泛输血 + 整体论）。
///
/// 快照内容（照对照实现的 IL）：
///   · 2613 泛输血 / 2643 泛血印
///   · 3033 暗血   / 3365 整体盾（整体论的盾）
///   · 2618 坚角清汁
/// </summary>
public static class 团减快照
{
    /// <summary>
    /// **贤者 / 学者**的减伤类状态（照对照实现的 `CurrentMitigation` IL）：
    ///   · 2613 泛输血 / 2643 泛血印
    ///   · 3033 暗血   / 3365 整体盾（整体论的盾）
    ///   · 2618 坚角清汁
    /// </summary>
    private static readonly uint[] 贤者学者Ids = { 2613, 2643, 3033, 3365, 2618 };

    /// <summary>
    /// **白魔 / 占星**的减伤类状态（表外审计 P2-3 补）。
    ///
    /// [!] 原来这份快照**只有贤者/学者那 5 个 id** ——
    ///     白魔/占星身上挂着 节制(1873) 或 庇护所(1911) 时，
    ///     `已有减伤()` 仍然返回 false ⇒ 会**再叠一层** ✗
    ///
    /// [!] 数值来自参考 IL（2026-10-15 逐条重读 youshu 减伤类 resolver 原文，
    ///     并用官方 `D:\Download\Status.csv` 核验了每个 id 的正式名）：
    ///     · 白魔 `节制.txt`：查 `1911`（庇护所）、`1873`（节制）、`1219`（告解，查了两次）
    ///     · 白魔 `庇护所.txt`：查 `1911` + `1873`（互相防叠）
    ///     · 白魔 `全大赦.txt`：查 `1873`（节制）
    ///     · 占星 `中间学派.txt`：查 `849`（命运之轮）、`3895`（太阳星座预备）、`3896`（太阳星座）
    ///     · 占星 `太阳星座.txt`：查 `849`（命运之轮）+ `3895`（太阳星座预备，带剩余时间）
    ///     ⇒ 这六个 id 都是**"别的技能挂出来的团队减伤态"**，正是本快照的语义。
    ///
    /// [!] **刻意不收 `2718`**（虽然审计清单里提到过）：
    ///     · 官方 `Status.csv` 里 `2718` 的正式名是**大宇宙**，
    ///       **不是**"中间学派"（中间学派是 `1892`/`1921`）——审计那句是转述错误；
    ///     · `2718` 只在**占星中间学派自己的 Check** 里被查（"大宇宙在身就别开中间学派"），
    ///       它是**伤害存储型治疗技**的状态，不是团队减伤态；
    ///     · 本快照是**跨职业全局门**，收录它会在占星一开大宇宙时把别职业的罩子一起拦掉 ——
    ///       而 youshu 的学者 `野战治疗阵.txt` **根本没有这条检查**（IL 里 0 个 HasAura）✗
    ///     ⇒ 2718 改挂"技能自身门"（见 `自身门`），语义才对齐参考。
    /// </summary>
    private static readonly uint[] 白魔占星Ids = { 1873, 1911, 1219, 849, 3895, 3896 };

    /// <summary>
    /// **技能自身的去重门** —— 只对**那一个技能**生效，不放进全局 `已有减伤()`
    /// （放进全局会跨职业误拦，见上面 `白魔占星Ids` 的说明）。
    ///
    /// 全部逐条来自 youshu 对应 resolver 的 IL 原文：
    ///   · `中间学派` 16559：自身带 `2718`（大宇宙）⇒ 不放
    ///       —— `中间学派.txt`：`Me.HasAura(2718)` → `-2`
    ///   · `地星` 7439：自身带 `1224`（地星主宰）/ `1248`（巨星主宰）⇒ 不放
    ///       —— `地星.txt`：两条各 → `-1`（已挂地星别再放一次）
    ///
    /// [!] 名字按官方 `Status.csv` 标注；id 照 IL 原文，不做推断。
    /// </summary>
    public static bool 自身门(uint 团队减伤)
    {
        try
        {
            var 我 = AEAssist.Core.Me;
            if (我 == null || !我.对象有效()) return false;

            if (团队减伤 == SpellIds.取("中间学派"))
                return 我.HasAura(2718);                       // 大宇宙在身

            if (团队减伤 == SpellIds.取("地星"))
                return 我.HasAura(1224) || 我.HasAura(1248);    // 地星主宰 / 巨星主宰

            return false;
        }
        catch
        {
            return false;   // 读失败 → 不拦
        }
    }

    /// <summary>自己身上已经有这些减伤之一 ⇒ 不要再叠。</summary>
    public static bool 已有减伤()
    {
        try
        {
            var 我 = AEAssist.Core.Me;
            if (我 == null || !我.对象有效()) return false;

            foreach (var id in 贤者学者Ids)
                if (我.HasAura(id)) return true;

            foreach (var id in 白魔占星Ids)
                if (我.HasAura(id)) return true;

            return false;
        }
        catch
        {
            return false;   // 读失败 → 不拦（宁可放，也别把团减全堵死）
        }
    }
}
