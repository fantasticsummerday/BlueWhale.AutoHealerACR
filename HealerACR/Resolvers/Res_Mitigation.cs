    //
    //  [!] 参考实现（`自动减伤.txt`）：交完一发团减就写
    //        `mitigationLockUntil = Environment.TickCount64 + 6000`
    //      下一次 Check 开头先比这个时间戳，没到就直接 `-1`。
    //
    //  [!] 为什么需要它：团减是**大 CD**，而"boss 要 AOE"这个条件
