using AEAssist;
using AEAssist.Extension;      // HasAura 的扩展方法在这里
using HealerACR.Common;

namespace HealerACR.Resolvers;

/// <summary>
/// **召唤宠物**（学者的「朝日召唤」= 小仙女）。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么单独一个 resolver，而不是塞进 `脱战准备技能` ★
///
///    `Res_PrepareResources` 只在**脱战**时工作
///    （`if (Core.Me.InCombat()) return -1;`）。
///    而宠物在**战斗中也会没**：
///      · 被「转化」（Dissipation）主动牺牲掉换以太
///      · 被打死
///
///    那时候不补，小仙女给的免费治疗就全没了 —— 学者的治疗量会明显下降，
///    而且「异想的祥光」「异想的幻光」「以太契约」「炽天召唤」**全部放不出来**。
///
///  ★ 触发条件 ★
///
///    ① 这个职业有宠物（`召唤宠物 != 0`）
///    ② **宠物不在场**（`JobApiHelper.有小仙女 == false`）
///    ③ 技能已解锁（Lv4 起）
///    ④ 技能可用（CD —— 朝日召唤 2.5 秒，几乎总是可用）
///    ⑤ **不在「转化」状态**（`AuraIds.转化中`）
///       —— 转化期间小仙女是被**主动牺牲**的，那时召唤无效；
///          硬召会白白占一个 GCD（同类 ACR 用的也是这个判据）
///
///  ⚠️ **不限制"必须在副本里"** —— 野外/城里召唤也完全无害，
///     而且能覆盖"忘了召就进本了"的情况。多一个限制只会多一种失效方式。
///
///  ⚠️ 放在队列**很靠前**的位置：宠物是一切的先决条件，
///     晚一拍召唤就晚一拍开始享受它的收益。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public class Res_SummonPet : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_SummonPet(JobSpellTable table) => _t = table;

    /// <summary>上次召唤的时刻（防抖用）</summary>
    private static long _上次召唤时刻;

    /// <summary>
    /// **待确认的重召** —— 已经发出过"重召"的指令，但还没确认宠物出现。
    ///
    /// ⚠️ 只在 `Build` 里置位，在 `Check` 里看到"宠物已经在场"才清掉。
    ///    这样读条被打断（CancelCast）时标记仍在 → 会自动重试，
    ///    而不是"一次被打断就把本局的重召机会用掉了"。
    /// </summary>
    private static bool _待确认重召;

    /// <summary>
    /// 召唤后的冷却（毫秒）—— 防止"以为没宠物"时重复召唤。
    ///
    /// ⚠️ 为什么需要：**炽天召唤**（16545）会把小仙女**变成炽天使**，
    ///    而炽天使期间 `JobApi_Scholar.HasPet` 可能读成 false →
    ///    我们会以为"没宠物"→ 又召一只 →
    ///    白白浪费一个 GCD，还可能把炽天使顶掉。
    ///
    ///    参考实现用的是 `RecentlyUsed(技能id, 毫秒)`（"这个技能最近用过吗"），
    ///    我们用一个朴素但等效的：记下自己上次召唤的时刻。
    ///
    /// ⚠️ 3 秒的依据：朝日召唤自己读条约 1.2 秒 + 宠物实体出现约 0.4 秒，
    ///    留一点余量。太短挡不住重复，太长会在宠物真死时迟迟不补。
    /// </summary>
    private const int 重召冷却毫秒 = 3000;

    private static long 现在 => AEAssist.Helper.TimeHelper.Now();

    /// <summary>
    /// 身上有没有「即刻咏唱」buff（学者 167）。
    ///
    /// ⚠️ 判 buff 而不是判技能 CD：即刻的 buff 是**放出来才有**，
    ///    而技能 CD 在"放了但没生效"时也会显示转圈 —— 判 buff 更准。
    /// </summary>
    private static bool 有即刻
    {
        get
        {
            try { return Core.Me.HasAura(AuraIds.即刻); }
            catch { return false; }
        }
    }

    /// <summary>【临时诊断】每 2 秒最多一条</summary>
    private static long _上次诊断;

    private void 诊断(string 说明)
    {
        try
        {
            var n = AEAssist.Helper.TimeHelper.Now();
            if (n - _上次诊断 < 2000) return;
            _上次诊断 = n;

            var 转化 = false;
            try { 转化 = Core.Me.HasAura(AuraIds.转化中); } catch { }

            AEAssist.Helper.LogHelper.Info(
                $"[召唤诊断] {说明} ｜ 有宠={JobApiHelper.有小仙女} " +
                $"重召标记={进本识别.有重召标记} 待确认={_待确认重召} " +
                $"转化={转化} 移动={SpellUtil.在移动()} 副本={进本识别.在副本里()} " +
                $"解锁={SpellUtil.已解锁(_t.召唤宠物)} 可用={SpellUtil.可用(_t.召唤宠物)} " +
                $"QT={HealQt.GetQt("自动召唤", true)} " +
                $"距上次召={(现在 - _上次召唤时刻)}ms");
        }
        catch { }
    }

    public int Check()
    {
        if (_t.召唤宠物 == 0) return -102;                  // 这个职业没有宠物

        诊断("Check");

        // ★ Qt 开关 —— 用户能关掉（和「小仙女」那个开关分开：
        //   那个管"用不用小仙女的技能"，这个管"召不召唤"）
        if (!HealQt.GetQt("自动召唤", true)) { 诊断("挡：自动召唤 QT 关着"); return -101; }

        // ══════════════════════════════════════════════════════════
        //  ★ 进本重召：这一次**忽略"已经在场"** ★
        //
        //  ⚠️ 小仙女跟着进本，`HasPet` 一直是 true ——
        //     只判"不在场"的话，进本后永远不会重召。
        //     用户要的是"每次进本重新召一次"。
        //
        //  ⚠️ 这里**只看、不取**（`有重召标记`）——
        //     取走要等 `Check` 确认宠物真的出现了（见下面的二段确认）。
        //     在读到标记时就取的话，后面任何一条返回负值
        //     （CD 没好、转化中…）都会把标记**白白丢掉**，
        //     而 `Check` 每帧会被调很多次 → 本局再也不重召。
        // ══════════════════════════════════════════════════════════
        var 要重召 = 进本识别.有重召标记;

        var 有宠物 = JobApiHelper.有小仙女;

        // ══════════════════════════════════════════════════════════
        //  ★ 二段确认：宠物**已经在场** → 说明上次的召唤**真的成功了** ★
        //
        //  ⚠️ 为什么要这样而不是在 `Build` 里直接消费标记：
        //     `Build` 只代表"**要放**"，不代表"放成功"。
        //     朝日召唤是 1.5 秒读条，**移动会取消它**（日志里的 CancelCast）。
        //     在 Build 里消费的话，一次被打断就把本局的重召机会**用掉了** ——
        //     之后就算站定也不会再召（因为标记没了）。
        //
        //  ⚠️ 判据用"宠物在场"而不是"技能放成功"：
        //     宠物出现是**最终结果**，比任何中间信号都可靠，
        //     而且不需要引入事件订阅之类的新机制。
        //
        //  ⚠️ 顺序：这一段必须在"要重召"的读取**之后** ——
        //     否则本帧刚消费掉，下面又读成 false 了。
        // ══════════════════════════════════════════════════════════
        if (有宠物 && _待确认重召)
        {
            _待确认重召 = false;
            进本识别.取走重召标记();     // 确认成功 → 这时才真正消费
        }

        // 已经在场、且本局没要求重召 → 不用召
        // ⚠️ 窗口内（`要重召 == true`）**跳过"有宠物就不召"** ——
        //    这正是"进本重召一次"的语义：即使小仙女还在，也要为这一局重召。
        if (有宠物 && !要重召) { 诊断("挡：有宠物且无需重召"); return -1; }

        // ★ 防抖：**只在"有宠物但想重召"时**才限制频率 ★
        //
        // ⚠️ 这条的范围很关键（实测踩的坑）：
        //
        //  ── 冷却是为谁设计的 ──
        //    「炽天召唤」（16545）会把小仙女**变成炽天使**，
        //    而炽天使期间 `JobApi_Scholar.HasPet` 可能读成 false →
        //    我们会以为"没宠物"→ 又召一只 →
        //    白白浪费一个 GCD，还可能把炽天使顶掉。
        //    ⇒ 所以要防的是**"明明有、却以为没有"**这种情况。
        //
        //  ── 为什么不能管"根本没宠物" ──
        //    宠物真不在场时，第一次起手**哪怕被打断**（移动取消读条）
        //    也会记下时刻 → 之后 3 秒内**连试都不试**。
        //    日志实证：32.198 起手 → 32.765 被打断 → **35.070 才再试**
        //    （那 2.3 秒空档就是这个冷却造成的，看起来像"卡住了"）。
        //
        //  ⇒ 所以：**没宠物时不设冷却**（尽快重试），
        //          有宠物时要冷却（防止把炽天使顶掉）。
        if (有宠物 && 现在 - _上次召唤时刻 < 重召冷却毫秒) { 诊断("挡：重召冷却"); return -3; }

        // 转化期间召唤无效（小仙女被主动牺牲了）
        try
        {
            if (Core.Me.HasAura(AuraIds.转化中)) { 诊断("挡：转化中"); return -4; }
        }
        catch { }

        if (!SpellUtil.已解锁(_t.召唤宠物)) { 诊断("挡：没解锁"); return -2; }
        if (!SpellUtil.可用(_t.召唤宠物)) { 诊断("挡：不可用"); return -5; }

        // ★ **移动守卫** —— 朝日召唤是 **1.5 秒读条**，移动中会被打断 ★
        //
        // ⚠️ 这条是实测补的：没有它的时候，进本落地那一段（人还在走位）
        //    会出现"起手 → 被打断 → 下一帧再起手 → 再被打断"的循环，
        //    **看起来就像"根本没在召唤"**（日志里只有一串 Request 没有 success）。
        //
        //    游戏规则决定了读条技移动中放不出来，所以"移动中不召"不是保守，
        //    而是**避免无意义的重复起手**。站定之后立刻就会召。
        //
        // ⚠️ 朝日召唤是 GCD 技（`CastTime=1.48`、`IsAbility=False`）——
        //    它自己就占一个 GCD 位，所以"晚一个 GCD 召"没有任何额外代价。
        // ★ 开关：移动中允许用「即刻咏唱」强制瞬发 ★
        //
        // ⚠️ 这是"落地立刻召"的**唯一保证手段**：
        //    朝日召唤 1.5 秒读条，进本落地那段人还在走位 → 必然被打断。
        //    即刻咏唱（7561 → buff 167）能让它瞬发，不受移动影响。
        //
        // ⚠️ 默认关（见 `HealerEntryBase` 里注册开关时的说明）：
        //    即刻是 60 秒 CD，一般留给复活/紧急治疗 —— 这是一笔不划算的交换。
        var 用即刻 = HealQt.GetQt("召唤用即刻", false);

        if (SpellUtil.在移动() && 用即刻 && !有即刻)
        {
            // 开了"召唤用即刻"但身上还没有即刻 buff → 等即刻放出来再召
            // （Build 里会先把即刻排进去，下一帧这里就能过）
            return -6;
        }

        // ══════════════════════════════════════════════════════════
        //  ⚠️ **移动中不再直接挡掉**（实测的教训）★
        //
        //  ── 原来为什么挡 ──
        //    朝日召唤是 1.5 秒读条，移动会被打断，所以想"省下无效起手"。
        //
        //  ── 为什么这个想法是错的 ──
        //    日志实证：落地 39.995 → 战斗开始 41.956 → **51.178 才第一次尝试**，
        //    中间 9.2 秒**一个动作都没有** —— 因为守卫每个 GCD 都 `return -6`。
        //    而 54.062 那次成功证明人当时是站着的 ——
        //    **那 9 秒里很可能早就有能读条的窗口，只是我们连试都没试。**
        //
        //    而且框架**自己会立刻重试**：51.767 被打断 → 51.788 就再试了
        //    （间隔 21 毫秒）。所以"起手被打断"的代价**几乎为零**，
        //    而"不试"的代价是**真的不召**。
        //
        //  ⇒ 试了才知道能不能成。让游戏去判定（它会在移动时取消读条），
        //    我们只负责"有机会就试"。
        // ══════════════════════════════════════════════════════════

        // ══════════════════════════════════════════════════════════
        //  ★ **在副本里 → 提高优先级，抢在输出之前** ★
        //
        //  ⚠️ 用户要求："进本落地那一刻就该召"。
        //
        //    条件是"落地"（地图稳定）+ "没宠物" —— 两者一满足，
        //    这时候最该做的事就是召出来：
        //      · 小仙女是学者治疗体系的地基（见类注释）
        //      · 后面打输出 / 加血全都要用到它
        //      · 晚召就是晚享受它的免费治疗
        //
        //  ⚠️ 优先级数字的语义（开发约定 F③ 那条链）：
        //    这里返回的**正值大小不参与仲裁**，排队的先后由注册顺序决定。
        //    所以"提高优先级"靠的是**位置**（已经在 Res_PrepareResources 之前），
        //    这里返回不同值只是为了日志上好区分是哪种情况触发的。
        // ══════════════════════════════════════════════════════════
        if (进本识别.在副本里()) { 诊断("通过（在副本，返回 15）"); return 15; }

        诊断("通过（返回 8）");
        return 8;
    }

    public void Build(Slot slot)
    {
        var spell = SpellUtil.Get(_t.召唤宠物);

        if (spell == null) return;

        // ★ 需要即刻时，**先插即刻再召**（同一个 slot 里两步）★
        //
        // ⚠️ 顺序不能反：即刻是**能力技**（瞬发、不进 GCD），
        //    先放它才能让后面的召唤吃到瞬发。
        if (HealQt.GetQt("召唤用即刻", false) && SpellUtil.在移动() && !有即刻)
        {
            var 即刻 = SpellUtil.Get(AuraIds.即刻);
            if (即刻 != null && 即刻.IsReadyWithCanCast()) slot.Add(即刻);
        }

        // ⚠️ 记时刻的语义：**"有宠物的情况下刚重召过"** ——
        //    只有那种情况才需要防抖（见 Check 里的说明）。
        //    没宠物时不记，免得自己的起手把下一次重试挡住。
        if (JobApiHelper.有小仙女) _上次召唤时刻 = 现在;

        // ★ 只有**真正的重召**才挂起待确认 ★
        //
        //  ⚠️ 这里原来是无条件置位，于是"宠物本来就不在场"的**普通重试**
        //     也挂起了待确认 → 等宠物一出现，`Check` 的消费逻辑就误判成
        //     "重召成功" → 又召一次 → **把刚召出来的小仙女杀掉**。
        //
        //     日志实证：52.845 成功召出 → 52.977 Unit创建 →
        //              54.062 又召 → 55.244 `ActorDeath 朝日小仙女`
        //
        //  ⚠️ 判据用"当时有没有宠物"：真正的重召只发生在
        //     "**已经有宠物、但本局要求重召**"的那一刻 ——
        //     那时 `有小仙女` 还是 true（新的那只还没替换掉它）。
        if (JobApiHelper.有小仙女) _待确认重召 = true;

        // ⚠️ 「朝日召唤」是**对自己放**的（`Range = 0`，查官方技能表），
        //    不带目标就是默认行为 —— 不要写 `new Spell(id, 队友)`。
        slot.Add(spell);
    }
}
