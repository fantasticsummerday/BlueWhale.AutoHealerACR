using AEAssist;
using AEAssist.Extension;      // HasAura 的扩展方法在这里
using HealerACR.Common;

namespace HealerACR.Resolvers;

/// <summary>
/// **召唤宠物**（学者的「朝日召唤」= 小仙女）。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么单独一个 resolver，而不是塞进 `脱战准备技能` ★
///
///    `Res_PrepareResources` 只在**脱战**时工作
///    （`if (Core.Me.InCombat()) return -1;`）。
///    而宠物在**战斗中也会没**：
///      · 被「转化」（Dissipation）主动牺牲掉换以太
///      · 被打死
///
///    那时候不补，小仙女给的免费治疗就全没了 —— 学者的治疗量会明显下降，
///    而且「异想的祥光」「异想的幻光」「以太契约」「炽天召唤」**全部放不出来**。
///
///  ★ 触发条件 ★
///
///    ① 这个职业有宠物（`召唤宠物 != 0`）
///    ② **宠物不在场**（`JobApiHelper.有小仙女 == false`）
///    ③ 技能已解锁（Lv4 起）
///    ④ 技能可用（CD —— 朝日召唤 2.5 秒，几乎总是可用）
///    ⑤ **不在「转化」状态**（`AuraIds.转化中`）
///       —— 转化期间小仙女是被**主动牺牲**的，那时召唤无效；
///          硬召会白白占一个 GCD（同类 ACR 用的也是这个判据）
///
///  ⚠️ **不限制"必须在副本里"** —— 野外/城里召唤也完全无害，
///     而且能覆盖"忘了召就进本了"的情况。多一个限制只会多一种失效方式。
///
///  ⚠️ 放在队列**很靠前**的位置：宠物是一切的先决条件，
///     晚一拍召唤就晚一拍开始享受它的收益。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public class Res_SummonPet : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_SummonPet(JobSpellTable table) => _t = table;

    /// <summary>上次召唤的时刻（防抖用）</summary>
    private static long _上次召唤时刻;

    /// <summary>
    /// 召唤后的冷却（毫秒）—— 防止"以为没宠物"时重复召唤。
    ///
    /// ⚠️ 为什么需要：**炽天召唤**（16545）会把小仙女**变成炽天使**，
    ///    而炽天使期间 `JobApi_Scholar.HasPet` 可能读成 false →
    ///    我们会以为"没宠物"→ 又召一只 →
    ///    白白浪费一个 GCD，还可能把炽天使顶掉。
    ///
    ///    参考实现用的是 `RecentlyUsed(技能id, 毫秒)`（"这个技能最近用过吗"），
    ///    我们用一个朴素但等效的：记下自己上次召唤的时刻。
    ///
    /// ⚠️ 3 秒的依据：朝日召唤自己读条约 1.2 秒 + 宠物实体出现约 0.4 秒，
    ///    留一点余量。太短挡不住重复，太长会在宠物真死时迟迟不补。
    /// </summary>
    private const int 重召冷却毫秒 = 3000;

    private static long 现在 => AEAssist.Helper.TimeHelper.Now();

    public int Check()
    {
        if (_t.召唤宠物 == 0) return -102;                  // 这个职业没有宠物

        // ★ Qt 开关 —— 用户能关掉（和「小仙女」那个开关分开：
        //   那个管"用不用小仙女的技能"，这个管"召不召唤"）
        if (!HealQt.GetQt("自动召唤", true)) return -101;

        // ══════════════════════════════════════════════════════════
        //  ★ 进本重召：这一次**忽略"已经在场"** ★
        //
        //  ⚠️ 小仙女跟着进本，`HasPet` 一直是 true ——
        //     只判"不在场"的话，进本后永远不会重召。
        //     用户要的是"每次进本重新召一次"。
        //
        //  ⚠️ 这里**只看、不取**（`有重召标记`）——
        //     取走必须等到 `Build` 真的把技能放进 slot。
        //     在 Check 里取的话，后面任何一条返回负值
        //     （移动中被挡、CD 没好、转化中…）都会把标记**白白丢掉**，
        //     而 `Check` 每帧会被调很多次 → 本局再也不重召。
        // ══════════════════════════════════════════════════════════
        var 要重召 = 进本识别.有重召标记;

        // 已经在场就不重复召（除非本局要求重召）
        if (JobApiHelper.有小仙女 && !要重召) return -1;

        // ★ 防抖：刚召唤过就别再召（学参考实现的 RecentlyUsed）★
        //
        // ⚠️ 为什么需要：**炽天召唤**（16545）会把小仙女**变成炽天使**，
        //    炽天使期间 `HasPet` 可能读成 false →
        //    我们会以为"没宠物"→ 又召一只 →
        //    白白浪费一个 GCD，还可能把炽天使顶掉。
        //
        //    参考实现在这里用的是 `RecentlyUsed`（"这个技能最近用过吗"），
        //    我们用一个更朴素但等效的：记下自己上次召唤的时刻。
        if (现在 - _上次召唤时刻 < 重召冷却毫秒) return -3;

        // 转化期间召唤无效（小仙女被主动牺牲了）
        try
        {
            if (Core.Me.HasAura(AuraIds.转化中)) return -4;
        }
        catch { }

        if (!SpellUtil.已解锁(_t.召唤宠物)) return -2;
        if (!SpellUtil.可用(_t.召唤宠物)) return -5;

        // ★ **移动守卫** —— 朝日召唤是 **1.5 秒读条**，移动中会被打断 ★
        //
        // ⚠️ 这条是实测补的：没有它的时候，进本落地那一段（人还在走位）
        //    会出现"起手 → 被打断 → 下一帧再起手 → 再被打断"的循环，
        //    **看起来就像"根本没在召唤"**（日志里只有一串 Request 没有 success）。
        //
        //    游戏规则决定了读条技移动中放不出来，所以"移动中不召"不是保守，
        //    而是**避免无意义的重复起手**。站定之后立刻就会召。
        //
        // ⚠️ 朝日召唤是 GCD 技（`CastTime=1.48`、`IsAbility=False`）——
        //    它自己就占一个 GCD 位，所以"晚一个 GCD 召"没有任何额外代价。
        if (SpellUtil.在移动()) return -6;

        // ══════════════════════════════════════════════════════════
        //  ★ **在副本里 → 提高优先级，抢在输出之前** ★
        //
        //  ⚠️ 用户要求："进本落地那一刻就该召"。
        //
        //    条件是"落地"（地图稳定）+ "没宠物" —— 两者一满足，
        //    这时候最该做的事就是召出来：
        //      · 小仙女是学者治疗体系的地基（见类注释）
        //      · 后面打输出 / 加血全都要用到它
        //      · 晚召就是晚享受它的免费治疗
        //
        //  ⚠️ 优先级数字的语义（开发约定 F③ 那条链）：
        //    这里返回的**正值大小不参与仲裁**，排队的先后由注册顺序决定。
        //    所以"提高优先级"靠的是**位置**（已经在 Res_PrepareResources 之前），
        //    这里返回不同值只是为了日志上好区分是哪种情况触发的。
        // ══════════════════════════════════════════════════════════
        if (进本识别.在副本里()) return 15;

        return 8;
    }

    public void Build(Slot slot)
    {
        var spell = SpellUtil.Get(_t.召唤宠物);

        if (spell == null) return;

        // 记下时刻 —— 给防抖用（下次 3 秒内不再召）
        _上次召唤时刻 = 现在;

        // ★ 到这里技能才真的会放出去 → 这时才取走"重召"标记 ★
        //   （放到 Build 里就是为了"只有真放出去才消费掉"）
        进本识别.取走重召标记();

        // ⚠️ 「朝日召唤」是**对自己放**的（`Range = 0`，查官方技能表），
        //    不带目标就是默认行为 —— 不要写 `new Spell(id, 队友)`。
        slot.Add(spell);
    }
}
