using AEAssist;
using AEAssist.Extension;      // HasAura 的扩展方法在这里
using AEAssist.Helper;
using HealerACR.Common;

namespace HealerACR.Resolvers;

/// <summary>
/// **召唤宠物**（学者的「朝日召唤」= 小仙女）。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 判据**只有一条**：宠物不在场就召 ★
///
///    前面几版堆了一堆条件（重召标记、有效期、冷却、移动守卫、待确认…），
///    结果互相干扰、越修越乱，实测表现为：
///      · 落地后 11 秒才召
///      · 召出来之后**又召一次，把刚召出的杀掉了**
///
///    现在砍到最简：**没宠物就召，有宠物就不召**。
///
///  ── 为什么这一条就够，不需要"进本重召" ──
///    小仙女跟着玩家进本，所以进本时它通常**已经在场** ——
///    那不需要重召（它跟着你，位置也是对的）。
///    而它**不在场**的几种情况本来就要召：
///      · 被「转化」主动牺牲掉换以太
///      · 被打死
///      · 刚进游戏 / 切职业还没召
///    ⇒ "不在场就召"自然覆盖全部情况，不需要额外的标记和窗口。
///
///  ── 唯一保留的额外限制 ──
///    ① Qt 开关「自动召唤」—— 用户能关掉
///    ② **转化中不召** —— 那时小仙女是被主动牺牲的，召了也无效
///    ③ 起手间隔 —— 防止读条被打断后**同一毫秒**疯狂起手
///
///  ⚠️ **没有移动守卫**。朝日召唤是 1.5 秒读条，移动会被游戏取消，
///     但那**不花额外代价**（框架自己会立刻重试，实测间隔 21 毫秒）。
///     反过来"因为可能在移动就不试"会让它**一直不召** —— 那是更糟的失败。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public class Res_SummonPet : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_SummonPet(JobSpellTable table) => _t = table;

    /// <summary>上次**起手**的时刻（不是成功时刻）</summary>
    private static long _上次起手;

    /// <summary>
    /// 两次起手之间至少隔这么久。
    ///
    /// ⚠️ 1 秒的依据：朝日召唤读条约 1.18 秒。隔着这个间隔，
    ///    上一次要么已经成功、要么已经被取消 ——
    ///    不会出现"上一发还在读、又起手一发"。
    ///
    /// ⚠️ 不能更长：读条被打断后要能**很快重试**（那是唯一的恢复手段）。
    /// </summary>
    private const int 起手间隔毫秒 = 1000;

    public int Check()
    {
        if (_t.召唤宠物 == 0) return -102;                     // 这个职业没有宠物
        if (!HealQt.GetQt("自动召唤", true)) return -101;      // 用户关掉了

        // ★ 唯一的判据：宠物不在场就召 ★
        if (JobApiHelper.有小仙女) return -1;

        // ══════════════════════════════════════════════════════════════════
        //  ★★★ **正在读条时不重召** —— 崩溃修复的第二道保险 ★★★
        //
        //  [!] 为什么必须加（外部审查报告 P0 + 日志实证）：
        //      「朝日召唤」是**读条技能**，实测
        //          `17215 读条成功 用时 1182ms`
        //      ==> **读条那 1.18 秒里，小仙女还不存在**
        //      ==> `有小仙女` 一直是 false
        //      ==> 这一条 `Check()` 会**反复通过** ⇒ 反复 `slot.Add`
        //      ==> 反复触发 Unit 创建 ⇒ **同步递归** ⇒ `0xc00000fd`（栈溢出）
        //
        //  [!] 原来只靠 `_上次起手` 那 1 秒间隔挡 —— 但读条要 1.18 秒，
        //      **1 秒的窗口比读条还短** ⇒ 挡不住。这里再加一道"在读条就完全不召"。
        //
        //  [!] 读不到就放行（不因为读不到状态而永远不召）。
        // ══════════════════════════════════════════════════════════════════
        try
        {
            if (CharacterExt.我在读条()) return -7;
        }
        catch { }

        // 转化中召了也无效（小仙女被主动牺牲了）
        try
        {
            if (CharacterExt.我有光环(AuraIds.转化中)) return -4;
        }
        catch { }

        // ★ 朝日召唤 24 秒节流（复刻 shiyuvi GetPet）：炽天召唤后 24 秒内不重召。
        //    炽天附体结束小仙女会自动回来，这个窗口里召等于打断附体或白召。
        try { if (SpellExtension.RecentlyUsed(SpellIds.取("炽天召唤"), 24000)) return -8; } catch { }

        if (!SpellUtil.已解锁(_t.召唤宠物)) return -2;
        if (!SpellUtil.可用(_t.召唤宠物)) return -5;

        // 起手间隔（防同一毫秒疯狂起手）—— 与"读条中不重召"配合成双保险
        var 现在 = TimeHelper.Now();
        if (现在 - _上次起手 < 起手间隔毫秒) return -6;

        return 20;
    }

    public void Build(Slot slot)
    {
        // ══════════════════════════════════════════════════════════════════
        //  ★ **「召唤用即刻」终于接线了**（表外审计查出来的假开关）★
        //
        //  [!] 现象：这个 QT 从 1.x 就注册了，UI 里也画着，注释写着
        //      「召不出来时用即刻咏唱强制瞬发」—— 但**全项目没有任何读取点** ✗
        //      ⇒ 勾了没反应（典型的"注册了但没人读"）。
        //
        //  [!] 语义（照注释实现，不擅自扩大）：
        //      · 默认 **false** —— 即刻是 60 秒 CD 的宝贵资源，一般留给复活/急救；
        //        拿它换"落地立刻召出小仙女"是**用大资源换小便利**，
        //        只有用户明确想要那种即时性时才开。
        //      · 只在**真的要召**这一拍、且**身上还没有即刻**、且即刻可用时才补一发。
        //      · 即刻是 oGCD，直接塞在召唤前面 —— 和 `预铺起手` 里
        //        "先均衡再单体盾"是同一个套路。
        //
        //  [!] 开关关着时这一段**整段不执行**，行为和原来完全一致。
        // ══════════════════════════════════════════════════════════════════
        try
        {
            if (HealQt.GetQt("召唤用即刻", false))
            {
                var 即刻 = SpellIds.取("即刻咏唱");
                if (即刻 != 0
                    && SpellUtil.已解锁(即刻)
                    && SpellUtil.可用(即刻)
                    && !CharacterExt.我有光环(AuraIds.即刻))
                {
                    var 疾 = SpellUtil.Get(即刻);
                    if (疾 != null) slot.Add(疾);
                }
            }
        }
        catch { }

        var spell = SpellUtil.Get(_t.召唤宠物);
        if (spell == null) return;

        _上次起手 = TimeHelper.Now();

        // ⚠️ 「朝日召唤」是**对自己放**的（`Range = 0`，查官方技能表），
        //    不带目标就是默认行为 —— 不要写 `new Spell(id, 队友)`。
        slot.Add(spell);
    }
}
