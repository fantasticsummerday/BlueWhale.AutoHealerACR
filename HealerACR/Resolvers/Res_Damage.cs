/// <summary>
/// 挂 DoT。
///
/// ⚠️ 这里有个坑：**DoT 升级会换 buff id**
///    （占星 烧灼838 → 炽灼843 → 焚灼1881，学者 毒菌179 → 猛毒菌189 → 蛊毒法1895）。
///    只检查一个 buff 的话，满级打最高级 DoT 时永远对不上 → 无限补 DoT。
///    所以走 <see cref="JobSpellTable.所有DotBuff"/> 把所有等级段都查一遍。
///
///    另外还有一根保险丝：刚放过 2.5 秒内不再放，防止任何形式的死循环。
/// </summary>
public class Res_Dot : ISlotResolver
{
    private readonly JobSpellTable _t;

    /// <summary>诊断只打一次的开关（每个 DoT buff 各一条）</summary>
    private static readonly HashSet<uint> _已诊断 = new();

    public Res_Dot(JobSpellTable table) => _t = table;

    public int Check()
    {
        if (!HealQt.GetQt("DOT", true)) return -100;
        if (!HealQt.GetQt("输出", true)) return -101;
        if (蓝量.低蓝停手()) return -9;   // 蓝留给治疗
        if (_t.Dot技能 == 0) return -102;
        if (!SpellUtil.已解锁(_t.Dot技能)) return -2;

        // ⚠️ 用我们自己的目标选择器（带粘滞 + 只挑有仇恨的）
        var target = 输出目标.选();
        if (target == null) return -1;

        // ── 视线检查：目标在柱子/墙后面时距离够也打不到 ──
        //    不检查的话会一直"选中了技能但打不出去"，表现为输出卡住。
        //    （兜底偏向放行，见 技能数据.打得到 的说明）
        // [!] **必须传技能真实射程** —— 自身中心 AOE（破阵法 5 米）按默认 25 米判会「离怪老远也判打得到」（用户实测）
        if (!技能数据.打得到(target, 技能数据.取有效射程(_t.Dot技能) is var 射程 && 射程 > 0 ? 射程 : 25f)) return -6;

        if (!HealTargetHelper.木桩模式 && HealTargetHelper.目标快死了()) return -3;

        // ══════════════════════════════════════════════════════════
        //  ★ **这个怪值不值得上 DoT**（照抄参考实现的 ShouldSkipDotByHp）★
        //
        //  ⚠️ 和上面「目标快死了」的区别：
        //     · `目标快死了()` 只看**血线** —— 一只满血的杂兵不算"快死了"
        //     · 本判据看**血量上限** —— 杂兵的上限本来就低，
        //       上了 30 秒 DoT 它 5 秒就死，剩下 25 秒全浪费
        //
        //  ⇒ 这才是"小怪阶段不要挨个上毒"的正解。
        //     原来的行为是：一波 5 只小怪，挨个上 30 秒 DoT，
        //     每个 DoT 实际只生效几秒 —— **纯亏 5 个 GCD**。
        // ══════════════════════════════════════════════════════════
        if (!HealTargetHelper.木桩模式 && !HealTargetHelper.值得上Dot(target)) return -4;

        // ── DoT 黑名单（参考同类 ACR 的 DotBlacklistHelper）──
        //   有些怪免疫 DoT 或者吃不上，往它们身上补 = 每 30 秒白费一个 GCD，
        //   而且因为 buff 永远上不去，DoT 会反复触发、把输出循环卡死。
        if (!Dot黑名单.可以上Dot(target)) return -5;

        诊断剩余时间(target);

        // ⚠️ 判断走**共享**的 Dot补判（含防死循环保险丝）——
        //    不要在这里自己写一套：AI 建议那条路也用它，
        //    两边必须看同一份数据（否则就是开发约定 F③ 那个坑）。
        if (!Dot补判.该补(target, _t.所有DotBuff, HealSettings.Instance.Dot持续时间 - 3f))
            return -4;

        var spell = SpellUtil.当前形态(_t.Dot技能);
        if (spell == null) return -1;

        // ⚠️ **移动守卫**：DoT 多数是读条的（天辉 / 焚灼…）。
        //
        //    ⚠️ 但这条要小心 —— 挡住之后会出现"移动时没有自动补 DoT"。
        //       挡住读条 DoT 之后，**必须有瞬发替代**顶上，否则就是"该补却不补"。
        //       白魔的 天辉 是读条，所以移动中确实放不了 ——
        //       这时正确的降级是转去放瞬发的 安慰之心/闪飒，而不是硬读天辉。
        //       （AI 那条路也走 Dot补判，同样会被这里挡住。）
        if (!SpellUtil.移动中可用(spell.Id)) return -7;

        return spell.IsReadyWithCanCast() ? 6 : -1;
    }

    /// <summary>
    /// **一次性诊断**：把这个 DoT 的"剩余时间"接口实际返回什么打出来。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要它 ★
    ///
    ///    现象：天辉每 ~4.9 秒放一次（日志里连续 15 次）。
    ///    正常应该是 30 秒一次 —— 说明下面这条判断**恒为真**：
    ///        `撑不过N个Gcd(buff, 2, 1.5)`  → 以为"DoT 快没了"
    ///
    ///    候选根因（光看代码分不出来）：
    ///      ① `GetAuraTimeleft` 返回的其实是"秒×100"(3000) 而不是毫秒(30000)
    ///         → 除以 1000 = 3 秒 → 恒判该补
    ///      ② `fromMe=true` 取不到我挂的 buff → 返回 0/负数 → 恒判该补
    ///      ③ `HasLocalPlayerAura` 失效 → 走"一个 buff 都没配"的兜底分支
    ///
    ///    ⚠️ 所以这里**不管有没有 buff 都打一条** —— 否则情况③
    ///       会因为"没 buff 就 return"而永远看不到输出。
    ///       每个 buff 各一行，第一场战斗打一次就够。
    ///
    ///  确认结论后，把本方法和 `_已诊断` 一起删掉。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private void 诊断剩余时间(IBattleChara target)
    {
        try
        {
            if (_已诊断.Count > 0) return;   // 已经打过一整轮 → 不再刷屏

            var 候选 = _t.所有DotBuff;
            var 描述 = new System.Text.StringBuilder();
            描述.Append($"[HealerACR][DoT诊断] 技能={_t.Dot技能} 候选buff数={(候选?.Length ?? 0)}");

            if (候选 != null)
            {
                foreach (var b in 候选)
                {
                    if (b == 0) continue;

                    var 有 = target.HasLocalPlayerAura(b);
                    var 原始 = target.我的Buff剩余毫秒(b);
                    var 秒 = target.我的Buff剩余秒(b);
                    var 撑不过 = target.撑不过N个Gcd(b, 2, 1.5f);

                    描述.Append($" || buff={b} 在身上={有} 接口返回={原始}" +
                                $" 按毫秒={原始 / 1000f:F1}s 按秒x100={原始 / 100f:F1}s" +
                                $" 剩余秒()={秒:F2} 撑不过2GCD={撑不过}");
                    _已诊断.Add(b);
                }
            }

            LogHelper.Info(描述.ToString());
        }
        catch (Exception e)
        {
            LogHelper.Info("[HealerACR][DoT诊断] 异常：" + e.Message);
        }
    }

    public void Build(Slot slot)
    {
        // ⚠️ **必须和 Check 同源** —— Check 判的是 `输出目标.选()`，
        //    这里再读 `当前目标()`（玩家选中那个）就是"判 A 放 B"：
        //    DoT 会挂到玩家选的怪身上，而不是我们判定该挂的那只。
        var target = 输出目标.选();
        if (target == null) return;

        var spell = SpellUtil.当前形态(_t.Dot技能);
        if (spell == null) return;

        slot.Add(new Spell(spell.Id, target));

        // ⚠️ 记到**共享**的 Dot补判 里（不是本类的静态字段）——
        //    保险丝必须两条路径（优先级队列 / AI 建议）共用，
        //    否则 AI 那条能绕过它，等于没装。
        Dot补判.记一次施放(target);   // 按目标记：避免误伤别的目标

        // ★ 同时记一条"待确认" ★ —— 隔几秒回头看 buff 上去没有。
        //   上不去就累计失败，连续 3 次把这个**种类**自适应拉黑。
        //   （审计发现 `记补失败` 原来**一个调用点都没有** ——
        //     自适应黑名单从来没生效过。）
        Dot黑名单.记按下(target, _t.所有DotBuff);
    }
}

/// <summary>群体输出：需求 1，自动挑能打到最多敌人的目标。</summary>
public class Res_AoEDamage : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_AoEDamage(JobSpellTable table) => _t = table;

    public int Check()
    {
        if (!HealQt.GetQt("输出")) return -100;
        if (!HealQt.GetQt("AOE")) return -101;
        if (蓝量.低蓝停手()) return -9;   // 蓝留给治疗
        if (_t.群体输出 == 0) return -102;
        if (!SpellUtil.已解锁(_t.群体输出)) return -2;

        var spell = SpellUtil.当前形态(_t.群体输出);
        if (spell == null) return -1;

        // ⚠️ **移动守卫（放在智能选目标之前）**：
        //    AOE 基本都是读条的（神圣 / 重力 / 蚀魂…），移动中硬放会一直被打断。
        //
        //    ⚠️ 位置很重要：**必须放在下面"智能选目标"之前** ——
        //       那一步会遍历敌人算"哪个落点能打到最多"，
        //       移动中算完再否决纯属白费（而且那是每帧都在跑的热路径）。
        if (!SpellUtil.移动中可用(spell.Id)) return -7;

        // ⚠️ **必须和 Build 同源**（开发约定 F③）——
        //    走同一个 `选最佳落点()`，避免"Check 判了直线逻辑、Build 用圆形逻辑"。
        var 最佳 = 选最佳落点(spell.Id);

        if (最佳 == null) return -1;

        // 落点也得看得见（AOE 是打在地上的，视线被墙挡住同样打不到）
        // [!] **必须传技能真实射程** —— 自身中心 AOE（破阵法 5 米）按默认 25 米判会「离怪老远也判打得到」（用户实测）
        if (!技能数据.打得到(最佳, 技能数据.取有效射程(spell.Id) is var 射程 && 射程 > 0 ? 射程 : 25f)) return -6;

        return spell.IsReadyWithCanCast() ? 5 : -1;
    }

    /// <summary>
    /// 选 AOE 的**最佳落点**。Check 和 Build **必须都走这里**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 修的是一个真「判 A 放 B」bug（全量审计发现）★
    ///
    ///  ── 原来错在哪 ──
    ///    Check 里分了两条路：
    ///        · **直线**技能 → `智能选目标.按形状选最优`（遍历敌人算落点）
    ///        · 圆形技能     → `TargetHelper.GetMostCanTargetObjects`
    ///    而 Build 只有一句 `HealTargetHelper.AOE最佳目标(...)`，
    ///    它内部**只调 `GetMostCanTargetObjects`** ——
    ///    也就是**圆形逻辑**。
    ///
    ///  ⇒ 直线 AOE（占星的「重力」等）会出现：
    ///      Check 按直线找到了一个能命中 4 个的落点 → 判定该放，
    ///      Build 却用圆形逻辑找了另一个（或干脆退回当前目标）
    ///      → **技能打在不是判定的那个位置上**，命中数远少于预期。
    ///
    ///  ── 修法 ──
    ///    把选择逻辑提成这个方法，Check 和 Build 都调它。
    ///    这样"判哪个落点"和"打哪个落点"在代码上就是**同一个表达式**，
    ///    不可能再分叉。
    ///
    ///  ⚠️ 异常兜底也跟着走这里：拿不到就用"数邻居"的老办法，
    ///    返回当前目标（可能为 null，由调用方处理）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private IBattleChara? 选最佳落点(uint 技能Id)
    {
        try
        {
            if (智能选目标.是直线技能(技能Id))
            {
                // [!] 用**按等级**的门槛 —— 白魔 72+/贤者 94+ 恰好 2 只怪时
            //     群体技是负收益（算术核实），详见 `AOE门槛(int)`。
            return 智能选目标.按形状选最优(技能Id, _t.AOE伤害范围, 门槛());
            }

            // [!] 同上：按等级的门槛
            return TargetHelper.GetMostCanTargetObjects(技能Id, 门槛());
        }
        catch
        {
            // 拿不到就退回"数邻居"的老办法（至少不比原来差）
            return HealTargetHelper.当前目标();
        }
    }

    public void Build(Slot slot)
    {
        var spell = SpellUtil.当前形态(_t.群体输出);
        if (spell == null) return;

        // ⚠️ 和 Check 同源：同一个 `选最佳落点()`
        var 目标 = 选最佳落点(spell.Id);
        if (目标 != null)
        {
            slot.Add(new Spell(spell.Id, 目标));
            return;
        }

        slot.Add(spell);
    }
        /// <summary>
        /// **当前等级下的 AOE 门槛** —— 只把 `AOE门槛(等级)` 包一层取等级。
        ///
        /// [!] 为什么不直接写 `_t.AOE门槛((int)Core.Me.Level)`：
        ///      Check 和 Build **两处**都要用（开发约定 F③ 要求同源），
        ///      取等级的写法容易改一处忘一处。集中在这里更稳。
        /// </summary>
        private int 门槛()
        {
            try { return _t.AOE门槛((int)CharacterExt.我的等级()); }
            catch { return _t.AOE最少敌人数; }
        }
}

/// <summary>兜底单体输出。必须是 GCD 队列的最后一个。</summary>
public class Res_BaseDamage : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_BaseDamage(JobSpellTable table) => _t = table;

    public int Check()
    {
        if (!HealQt.GetQt("输出")) return -100;
        if (蓝量.低蓝停手()) return -9;   // 蓝留给治疗
        if (!SpellUtil.已解锁(_t.基础输出)) return -2;

        // ⚠️ **用我们自己的目标选择器，不是玩家选中那个** ——
        //    见 `输出目标` 的长注释：原来直接读 `GetCurrTarget()`，
        //    于是"坦克拉到的怪不打、去打玩家选中的远处怪"。
        //    带粘滞，不会每帧乱切。
        var 目标 = 输出目标.选();
        if (目标 == null) return -1;

        // 视线被挡就别按了 —— 按了也放不出去，白白占着 GCD 让循环卡住
        // [!] **必须传技能真实射程** —— 自身中心 AOE（破阵法 5 米）按默认 25 米判会「离怪老远也判打得到」（用户实测）
        if (!技能数据.打得到(目标, 技能数据.取有效射程(_t.基础输出) is var 射程 && 射程 > 0 ? 射程 : 25f)) return -6;

        // 基础输出被游戏替换掉了（白魔神速期间 = 闪飒预备），硬放会失败
        if (_t.有特殊输出形态) return -5;

        // ⚠️ 和 Build **同源**：同一个目标 + 同一个 `选填充技(目标)`
        var spell = 选填充技(目标);
        // ⚠️ **移动守卫**：移动中不要放读条技能。
        //    不加这条的后果：读条被移动打断 → 下一帧再塞 → 再断，
        //    表现成"反复尝试读条"，GCD 全空转。
        //    挡住之后，瞬发技能（学者的毁坏 / 白魔的安慰之心…）自然轮到前面。
        //    ⚠️ 用 `选填充技()` 之后的 spell.Id —— 形态可能被游戏换掉。
        if (spell != null && !SpellUtil.移动中可用(spell.Id)) return -7;
        return spell != null && spell.IsReadyWithCanCast() ? 1 : -1;
    }

    /// <summary>
    /// **挑这一发打什么** —— 近距离时用「近战填充技」，否则用基础输出。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么 Check 和 Build 必须走同一个方法（开发约定 F③）★
    ///
    ///    如果 Check 判"该用破阵法"、Build 却 `Add(基础输出)`，
    ///    结果就是**判 A 放 B** —— 白白多花 100 威力，而且日志上完全看不出来
    ///    （技能确实放出去了，只是放错了那个）。
    ///
    ///  ── 判据 ──
    ///    ① 这个职业有「近战填充技」（表里填了）
    ///    ② 目标在 `近战填充距离` 内（远了打不到，硬放 = 空转一个 GCD）
    ///    ③ 技能已解锁且当前形态可用（学者 82 级后自动升级成裂阵法）
    ///
    ///  ⚠️ 拿不到距离时**退回基础输出** —— 保守方向是"打得不最优"，
    ///     而不是"空放一个打不到的技能"。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **挑这一发打什么** —— 近距离时用「近战填充技」，否则用基础输出。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么 Check 和 Build 必须走同一个方法（开发约定 F③）★
    ///
    ///    如果 Check 判"该用破阵法"、Build 却 `Add(基础输出)`，
    ///    结果就是**判 A 放 B** —— 白白多花 100 威力，而且日志上完全看不出来。
    ///
    ///  ★★ 距离判定：**交给游戏，不要自己算中心距** ★★
    ///
    ///  ── 原来的错（实测报的）──
    ///      `Vector3.Distance(我, 目标.Position) <= 近战填充距离`
    ///      那是**中心到中心**。而破阵法是**以我为中心 5 米**的圆形，
    ///      判定应该看"能不能够到**目标圈**"。
    ///
    ///      大型 Boss 的目标圈半径有 5~10 米 —— 人站在圈上时，
    ///      中心距轻松超过 5 米，于是**永远判"够不着"**，一直打毁坏。
    ///
    ///  ── 修法：**够得到目标圈** ──
    ///      `有效距离 = 中心距 - 目标.HitboxRadius`，再和半径比。
    ///
    ///      这才对应"技能能不能打到那个圈"：
    ///      你站在圈上时，中心距可能 7~8 米，但扣掉圈半径就只有 1~2 米。
    ///
    ///  ── 试过但要避开的做法（实测把正常循环搞坏了）──
    ///      用 `new Spell(id, 目标).IsReadyWithCanCast()` 让游戏自己判：
    ///        · `SpellHelper.GetTarget(spell)` 的 switch 里
    ///          默认分支取的是 `Core.Me.GetCurrTarget()`（玩家选中那个），
    ///          传目标进去**改变了目标语义**，连带影响判定
    ///        · 框架判定失败时整条链会返回 null → **不放技能** →
    ///          表现成"输出循环断断续续"
    ///
    ///      ⇒ 所以保持原结构（**哪个 Spell 对象能用就直接用它**），
    ///        只把"中心距"换成"够得到目标圈"。CD 由框架在真正施放时把关。
    ///
    ///  ⚠️ 偏向是**刻意选的**：宁可偶尔多打一次高威力技能
    ///     （打空只是浪费一个 GCD），也不偏保守
    ///     （永远打低威力那个，那正是这个 bug）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **挑这一发打什么** —— **按威力选最优**（不是固定用某一个）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 判据：当前等级下**哪个威力高就用哪个** ★
    ///
    ///  ── 为什么不能固定 ──
    ///    威力档位是**交叉**的，两个技能的相对高低**随等级翻转**。
    ///    学者实例（数据来自游戏宏，见 `ScholarACR.威力表`）：
    ///
    ///        46~53  破阵法 150 > 毁坏 140   ← 贴身该用**破阵法**
    ///        54~63  破阵法 165 > 毁坏 160
    ///        64~71  毁坏   180 > 破阵法 165 ← **翻转**
    ///        72~81  毁坏   200 > 破阵法 165
    ///        82+    毁坏   220 > 裂阵法 180
    ///
    ///  ── 我在这件事上错过两次 ──
    ///    ① 凭印象说"破阵法 600 > 毁坏 500"（那两个数没有出处）
    ///    ② 拿 The Balance 的 **100 级**数据（毁坏 220 / 裂阵法 180）
    ///       判断 50 级 —— 而 50 级其实是 破阵法 150 / 毁坏 140，
    ///       **结论正好相反**。
    ///    ⇒ 教训：威力**既不能凭印象，也不能跨等级套用**。
    ///
    ///  ── 拿不到威力时怎么办 ──
    ///    表里没填（`当前威力` 返回 0）→ **退回"贴身就用"的旧行为**。
    ///    理由：没有数据时保持原样，比基于猜测去改安全。
    ///
    ///  ⚠️ 距离判定用 `够得到目标圈`（含 hitbox）——
    ///    大型 Boss 站目标圈上时中心距 7~8 米，纯中心距会误判"够不着"。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **挑这一发打什么** —— 把所有候选**按威力排序**，取当前能放的最高那个。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 候选与优先级（威力数据是权威的，见 `ScholarACR.威力表`）★
    ///
    ///    ① **近战填充技**（破阵法/裂阵法）—— 够得到目标圈时参与比较
    ///    ② **移动填充技**（毁坏）—— 瞬发兜底，任何时候都能放
    ///    ③ **基础输出**（气炎法/极炎法）—— 最高威力，但多数是读条
    ///
    ///  ★ 为什么必须按等级比，不能固定用一个 ★
    ///
    ///    威力档位是**交叉**的，相对高低随等级翻转。学者实例：
    ///        46~53  破阵法 150 > 毁坏 140   ← 贴身该用破阵法
    ///        54~63  破阵法 165 > 毁坏 160
    ///        64~71  毁坏   180 > 破阵法 165 ← **翻转**
    ///        72~81  毁坏   200 > 破阵法 165
    ///        82+    毁坏   220 > 裂阵法 180
    ///
    ///  ★ 移动中要选"瞬发里最高的" ★
    ///
    ///    50 级：破阵法 150（瞬发）> 毁坏 140（瞬发）≫ 气炎法 220（读条）
    ///      站定 → 读气炎法（220）
    ///      移动 → 气炎法放不出来 → 该选**破阵法**（150），不是毁坏（140）
    ///    ⇒ 固定用 `移动填充技` 会让移动中白白少 10 威力。
    ///
    ///  ⚠️ 拿不到威力（表里没填，`当前威力` 返回 0）时：
    ///     退回"距离优先"的旧行为，不做威力比较。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **挑这一发打什么** —— 按"这一发 GCD 的期望伤害"取最优。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 有效威力怎么算 ★
    ///
    ///    群体技（破阵法/裂阵法，`CastType=2 射程=0 效果范围=5`）：
    ///        有效威力 = 威力 × **我自己周围 5 米内的敌人数**
    ///    单体技（毁坏/气炎法/极炎法）：
    ///        有效威力 = 威力
    ///
    ///  ⚠️ 为什么群体技必须折算：
    ///    拿 AOE 威力直接和单体威力比是错的 —— 打单体时 AOE 是亏的。
    ///    学者实例：
    ///        50 级  破阵法 150×n  vs  毁坏 140
    ///             n=1 → 150 vs 140   → 破阵法（优 10）
    ///             n=2 → 300 vs 140   → 破阵法（优 160）
    ///        82 级  裂阵法 180×n  vs  毁坏 220
    ///             n=1 → 180 vs 220   → **毁坏**（AOE 打单体亏）
    ///             n=2 → 360 vs 220   → 裂阵法（优 140）
    ///
    ///  ★ 威力随等级翻转（所以不能固定用一个）★
    ///        46~53  破阵法 150 > 毁坏 140
    ///        54~63  破阵法 165 > 毁坏 160
    ///        64~71  毁坏   180 > 破阵法 165
    ///        72~81  毁坏   200 > 破阵法 165
    ///        82+    毁坏   220 > 裂阵法 180（单体时）
    ///
    ///  ★ 咏唱时间为什么不在排序里 ★
    ///    实测：读条 1.5s / 瞬发 0s，**复唱都是 2.5s** ——
    ///    两者都只占一个 GCD ⇒ 单位时间收益 = 威力 ÷ 2.5s ⇒ **约掉了**。
    ///    它只决定"移动中能不能放"，那个由 `移动中可用` 判
    ///    （走游戏数据，不是我猜的）。
    ///
    ///  ⚠️ 拿不到威力（表里没填，`当前威力` 返回 0）→ 退回距离优先的旧行为。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    internal Spell? 选填充技(IBattleChara? 目标)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return null;
        try
        {
            var 等级 = 0;
            try { 等级 = (int)CharacterExt.我的等级(); } catch { }

            // ══════════════════════════════════════════════════════════
            //  ★ 自身 AOE 技：**遍历候选列表**，取第一个"已解锁"的 ★
            //
            //  ⚠️ 为什么是列表不是单个：白魔有两档（神圣 → 豪圣）、
            //    贤者有两档（失衡 → 失衡II）、学者有两档（破阵法 → 裂阵法）——
            //    `当前形态` 只处理同 id 的形态升级，处理不了**不同 id 的档位**。
            //
            //  ⚠️ 半径**按技能查**（白魔 8 米 / 学者·贤者 5 米）——
            //    用统一半径会算错"能打到几个"，进而选错技能。
            // ══════════════════════════════════════════════════════════
            Spell? 近战 = null;
            var 近战半径 = 0f;
            foreach (var id in _t.自身AOE候选)
            {
                if (id == 0 || !SpellUtil.已解锁(id)) continue;
                近战 = SpellUtil.当前形态(id);
                if (近战 != null) { 近战半径 = _t.自身AOE半径(近战.Id).半径; break; }
            }

            var 移动 = _t.移动填充技 != 0 ? SpellUtil.当前形态(_t.移动填充技) : null;
            var 基础 = SpellUtil.当前形态(_t.基础输出);

            // ══════════════════════════════════════════════════════════════
            //  ★ `站定填充技` **必须进候选**（本轮实测抓到的真 bug）★
            //
            //  [!] 现象（用户第三次报）：50 级究极神兵（**单体**）还在打破阵法。
            //
            //  [!] 实测日志（本轮加的诊断打出来的，逐字）：
            //        [填充技] 基础[毁坏=140/400] 近战[破阵法=150/400 可用True]
            //                 移动[毁坏=140/400] => 选[破阵法=150/400]｜近战命中数=1
            //        [填充技·敌人明细] 半径5.0 [究极神兵 直8.3-圈6.0=2.3] => 命中1
            //      ⇒ **命中数 = 1**（不是圆心/半径/HitboxRadius 的问题），
            //        而**基础那一项是 `毁坏 140`，不是 `毁灭 150`** ——
            //        ==> `站定填充技`（毁灭）**根本不在候选里**！
            //
            //  [!] 于是本地的比较是：毁坏 140 vs 破阵法 150
            //        150 > 140×1.05 ⇒ **破阵法赢** —— 按当时的候选列表它没错。
            //      而正确答案是 **毁灭 150 / 300 蓝**（同威力、少 100 蓝）。
            //      ==> **本地看不到毁灭，所以永远选不出它。**
            //
            //  [!] 根因是之前那次修复只做了一半：
            //      用户报「远处应该打毁灭，而不是毁坏，少 10 威力」时，
            //      我**只在 AI 侧**（`候选集` / `AiSituation` 的散文清单）加了 `站定填充技`，
            //      **没加进这里** ==> AI 看得到毁灭、本地看不到
            //      ==> 两边判据不一致，本地按"更差的候选集"做决定，
            //          而 AI 的建议反而更对（日志里 AI 一直说"5米内只有1个不适合AOE"）。
            //
            //  [!] 补齐之后字典序自动给出正确结论：
            //        站定 单目标：毁灭 150/300 vs 破阵法 150/400
            //                    -> 同级（差 0%）-> **比蓝耗 -> 毁灭赢** ✔
            //        站定 2 目标：破阵法 300/400 vs 毁灭 150/300
            //                    -> 破阵法威力高一倍 -> **破阵法赢** ✔
            //        移动中：毁灭读条放不出来（`移动中可用` 拦）-> 破阵法/毁坏 ✔
            //
            //  ⚠️ 和 `基础输出` 重复时**不去重** —— 重复项在字典序里等价，
            //     不会改变结果，而去重要多一处判据（多一处就可能不一致）。
            // ══════════════════════════════════════════════════════════════
            var 站定 = _t.站定填充技 != 0 ? SpellUtil.当前形态(_t.站定填充技) : null;

            // 自身 AOE 要够得到目标圈才算候选（半径按技能查）
            var 近战距离 = 近战半径 > 0 ? 近战半径 : _t.近战填充距离;
            var 近战可用 = 近战 != null && 目标 != null
                           && 够得到目标圈(目标, 近战距离);

            var 近战威力 = 近战可用 ? 有效威力(近战!, 等级) : 0;
            var 移动威力 = 移动 != null ? 有效威力(移动, 等级) : 0;
            var 基础威力 = 基础 != null ? 有效威力(基础, 等级) : 0;
            var 站定威力 = 站定 != null ? 有效威力(站定, 等级) : 0;

            // 威力数据缺失 → 退回旧行为
            if (近战威力 == 0 && 移动威力 == 0 && 基础威力 == 0 && 站定威力 == 0)
            {
                // ⚠️ 只在**近战技确实有威力**时才返回它 ——
                //    否则会返回一个威力未知的技能（等于瞎选）。
                if (近战可用 && 近战 != null && _t.当前威力(近战.Id, 等级) > 0) return 近战;
                return 基础;
            }

            // ══════════════════════════════════════════════════════════════
            //  ★ 排序键 = **每点威力的 MP 成本**（用户要求）★
            //
            //  [!] 现象（用户实测）：
            //      "本地一直在打破阵法，ai建议毁灭 这是对的，
            //       因为毁灭少用100蓝"（破阵法 500 / 毁灭 400，用户确认）
            //
            //  [!] 根因：原来按**纯威力**排：
            //        破阵法150 × 命中数  vs  毁灭150
            //      单目标时**威力持平**，而破阵法是瞬发的 ⇒ 必然被选中，
            //      可它多花 100 蓝 —— 长时间下来蓝耗差很多。
            //
            //  [!] 修法：`取舍分 = 威力 / MP成本`（越高越划算）
            //        单目标   破阵法 150/500=0.300  毁灭 150/400=0.375 -> **毁灭赢**
            //        2 目标   破阵法 300/500=0.600  毁灭 0.375        -> **破阵法赢**
            //      ⇒ 用户说的"综合考虑目标数带来的收益"自动成立，
            //        而且单目标就是"按 1 来"（命中数 = Math.Max(1, 命中数)）。
            //
            //  [!] MP 为 0（没填/查不到）=> 分 = 威力，**退回纯威力排序** ——
            //      不会因为缺数据把某个技能误杀。
            // ══════════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★ 字典序取舍：**输出优先，相同才比蓝**（用户规则）★
            //
            //  [v] 用户原话：
            //      "输出：gcd内最高输出优先 相同的情况下按照条件选少蓝量
            //       （例如刚刚说到的50级环境下移动下才用破阵法）"
            //
            //  [!] 为什么不用加权（我上一版写成 `威力/MP`，那是错的）：
            //        A: 300 威力 / 500 蓝
            //        B: 295 威力 / 400 蓝   -> 加权后 **B 赢**
            //      可用户要的是"**最高输出优先**" —— 5 威力不是"相同"，
            //      不该因为省蓝就丢掉 5 威力。
            //      加权会让"输出"和"蓝耗"**互相抵消**；字典序是分层的，不会。
            //
            //  [!] 相对容差 5%：输出技的威力几乎不会精确相等（295 vs 300），
            //      要求精确相等等于"比蓝"这一层**永远不生效**。
            //      5% 是"同级"的合理边界，也正好覆盖 150/150 这种真平手。
            //
            //  [!] 这条规则完整覆盖用户的例子：
            //       站定 50 级：破阵法 150 vs 毁灭 150 -> 差 0% -> 同级
            //                   -> 比蓝 -> **毁灭赢**（400 < 500）
            //       移动中：只有瞬发可放 -> 破阵法是唯一候补 -> 选它
            //       小怪 2 只：破阵法 300 vs 毁灭 150 -> 差 100% -> **破阵法赢**
            //
            //  [!] MP 未知（0）**不参与比较** —— 0 的语义是"不知道"，
            //      不是"不耗蓝"。让未知无理由胜出是错的；两边都未知就保持原顺序。
            // ══════════════════════════════════════════════════════════════
            const float 同级容差 = 0.05f;   // 5%

            var 候选 = new List<(int 威力, int MP, Spell? 技, bool 可放)>
            {
                (基础威力, 查MP(基础), 基础, 基础 != null && SpellUtil.移动中可用(基础.Id)),
                (近战威力, 查MP(近战), 近战, 近战可用 && 近战 != null && SpellUtil.移动中可用(近战.Id)),
                (移动威力, 查MP(移动), 移动, 移动 != null && SpellUtil.移动中可用(移动.Id)),
                // ★ `站定填充技`（毁灭）—— **这一项原来缺失**（本轮实测的根因）★
                //   它通常和 `基础输出` 是同一个（表里没填时 = 0 -> null -> 威力 0 -> 被跳过），
                //   只有两者**不同**时才起作用（例：学者 基础=毁坏140 / 站定=毁灭150）。
                //   ⚠️ 可放判据用 `移动中可用`：毁灭是读条的 -> 移动中自动被排除。
                (站定威力, 查MP(站定), 站定, 站定 != null && SpellUtil.移动中可用(站定.Id)),
            };

            (int 威力, int MP, Spell? 技, bool 可放)? 最优 = null;

            foreach (var 项 in 候选)
            {
                // [!] 判据是**威力 > 0**（表示"有数据"），不是"分"——
                //     威力为 0 = 这个技能没数值，不该被选中。
                if (项.技 == null || 项.威力 <= 0 || !项.可放) continue;

                if (最优 == null) { 最优 = 项; continue; }

                var 当前 = 最优.Value;

                // ⚠️ **顺序要紧**（模拟测试抓到过 bug）：
                //
                //   [反例] 当前 A(300威力/500蓝)，新项 B(290威力/400蓝)
                //     如果把"高出容差"放在前面：
                //        ① 290 > 315 ? 否
                //        ② 290 < 285 ? **否**（285 < 290）← 没拦住
                //        ③ 落到"同级" -> B 蓝少 -> **B 赢**
                //     ⇒ B 价值低 3.3% 却因省蓝胜出，**违反"最高输出优先"**。
                //
                //   ⇒ 先判"**明显更低**"（跳过），再判"明显更高"（换），
                //     最后才是同级比蓝。
                //     单边落在容差内、另一边落在容差外时，取**更高**那一方。

                // ① 价值明显更低 -> 不换（**必须放在"更高"之前**）
                if (项.威力 < 当前.威力 * (1f - 同级容差)) continue;

                // ② 价值明显更高 -> 换（输出优先）
                if (项.威力 > 当前.威力 * (1f + 同级容差)) { 最优 = 项; continue; }

                // ③ 同级 -> 比蓝耗（少的赢）
                if (项.MP > 0 && 当前.MP > 0 && 项.MP < 当前.MP) 最优 = 项;
            }

            // ══════════════════════════════════════════════════════════════
            //  ★ 决策日志 —— 记下"为什么选它"★
            //
            //  [!] 用户报「50 级究极神兵（单体）还在打破阵法」，已确认是**本地**选的
            //      （日志有 `CastSpell success: 16539`，AI 的采纳数是 0），
            //      而本函数的字典序规则**看起来是对的**（同级该比蓝耗）。
            //      ==> 嫌疑在 `有效威力(破阵法)` 算出了 > 150（即命中数 > 1）。
            //      加这条日志就能一次看清：命中数、各自威力、各自 MP、最终选了谁。
            //
            //  [!] 只在有多个候补时才打（单候补是绝大多数情况，每条都打会刷屏）。
            // ══════════════════════════════════════════════════════════════
            try
            {
                var 名 = (Spell? s) => s == null ? "-" : SpellIds.反查(s.Id);
                var 明细 = $"基础[{名(基础)}={基础威力}/{查MP(基础)}] 站定[{名(站定)}={站定威力}/{查MP(站定)}]" +
                            $" 近战[{名(近战)}={近战威力}/{查MP(近战)} 可用{近战可用}]" +
                            $" 移动[{名(移动)}={移动威力}/{查MP(移动)}]" +
                            $" => 选[{名(最优?.技)}={最优?.威力}/{最优?.MP}]";
                if (近战可用)
                {
                    // 专门把"命中数"单独报一条 —— 它是这次的嫌疑点
                    var 命中 = 近战 == null ? 0 : 有效威力(近战, 等级) / Math.Max(1, _t.当前威力(近战.Id, 等级));
                    LogHelper.Info($"[填充技] {明细}｜近战命中数={命中}");
                    LogHelper.Info($"[填充技·敌人明细] {HealTargetHelper.自身周围敌人明细(_t.自身AOE半径(近战?.Id ?? 0).半径)}");
                }
                else LogHelper.Info($"[填充技] {明细}");
            }
            catch { }
            
            if (最优 != null) return 最优.Value.技;

            // 全放不出来（移动中且只有读条技）→ 返回基础输出让上层判
            return 基础 ?? 移动 ?? 近战;
        }
        catch { }

        return SpellUtil.当前形态(_t.基础输出);
    }
        /// <summary>
        /// **取某个技能的 MP 消耗**（0 = 不知道）。
        ///
        /// [!] 为什么单独包一层：`选填充技` 的候选要同时拿"威力"和"MP"
        ///     两个维度做**字典序**比较（价值优先，同级才比蓝）。
        ///
        /// [!] 0 的语义是"**未知**"，不是"不耗蓝" ——
        ///     比较时两边都已知才比；否则让"未知"无理由胜出是错的。
        /// </summary>
        private int 查MP(Spell? 技能)
        {
            if (技能 == null) return 0;
            try { return _t.查MP(技能.Id); }
            catch { return 0; }
        }
    

    private int 有效威力(Spell 技能, int 等级)
    {
        try
        {
            var 单发 = _t.当前威力(技能.Id, 等级);
            if (单发 <= 0) return 0;

            // ⚠️ 半径**按技能查**（破阵法 5 米 / 神圣 8 米），不能统一用 5 ——
            //    用错半径会算错命中数，进而选错技能。
            var (是自身AOE, 半径) = _t.自身AOE半径(技能.Id);
            if (!是自身AOE) return 单发;

            var 命中数 = HealTargetHelper.自身周围敌人数量(半径);
            return 单发 * Math.Max(1, 命中数);
        }
        catch
        {
            return 0;
        }
    }

    /// <summary>
    /// **够不够得到目标的"圈"** —— 用 `距离 - 目标碰撞半径` 近似。
    ///
    /// ⚠️ 为什么不能用"中心到中心"的距离：
    ///    破阵法/裂阵法是**以自己为中心**的圆形，判定该看"能不能够到**目标圈**"。
    ///    大型 Boss 的目标圈半径有 5~10 米 —— 人站在圈上时，
    ///    中心距轻松超过 5 米，纯中心距会**永远判"够不着"**。
    ///
    ///     实测日志：`有效距 1.27 = 中心 7.27 - 碰撞 6.00`
    ///     —— 中心距 7.27 米，但站在圈上，实际只差 1.27 米。
    /// </summary>
    private static bool 够得到目标圈(IBattleChara 目标, float 半径)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return false;
        try
        {
            var 中心距 = Vector3.Distance(CharacterExt.我的位置(), 目标.Position);
            var 有效距 = 中心距 - 目标.HitboxRadius;
            return 有效距 <= 半径;
        }
        catch
        {
            return false;
        }
    }

    public void Build(Slot slot)
    {
        // ⚠️ 和 Check **同源**：同一个目标 + 同一个 `选填充技(目标)`
        var 目标 = 输出目标.选();
        if (目标 == null) return;

        var spell = 选填充技(目标);
        if (spell == null) return;

        // ⚠️ **必须显式带目标** ——
        //    `slot.Add(spell)` 打的是**玩家选中**那个，
        //    而 Check 判的是 `输出目标.选()` 的结果 —— 不带目标就是"判 A 放 B"。
        slot.Add(new Spell(spell.Id, 目标));
    }
}

/// <summary>
/// **多目标 DoT** —— 当前目标 DoT 还在时，把 DoT 补到**别的被拉到的怪**身上。
/// </summary>
public class Res_MultiDot : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_MultiDot(JobSpellTable table) => _t = table;

    /// <summary>最多同时维持几个副目标的 DoT（防止在怪堆里无限上毒不输出）</summary>
    private const int 副目标上限 = 2;

    public int Check()
    {
        if (!HealQt.GetQt("DOT", true)) return -100;
        if (!HealQt.GetQt("输出", true)) return -101;
        if (蓝量.低蓝停手()) return -9;

        var 技 = _t.Dot技能;
        if (技 == 0) return -102;
        if (!SpellUtil.已解锁(技)) return -2;

        // ⚠️ **当前目标必须已经有 DoT** —— 否则这是 `Res_Dot` 的活，
        //    不该由我们抢（它的判据更完整：含黑名单 / 止血 / 快死目标等）。
        var 当前 = 输出目标.选();   // 和 Res_Dot 用同一个选择器，别分叉
        if (当前 == null) return -1;

        var buffs = _t.所有DotBuff;
        if (buffs == null || buffs.Length == 0) return -1;

        var 当前有 = false;
        try
        {
            foreach (var b in buffs)
                if (b != 0 && 当前.HasAura(b)) { 当前有 = true; break; }
        }
        catch { }

        if (!当前有) return -1;   // 主目标还没上 → 让 Res_Dot 管

        var spell = SpellUtil.当前形态(技);
        if (spell == null) return -1;

        // 移动守卫：DoT 多数读条。移动中交给移动填充。
        if (!SpellUtil.移动中可用(spell.Id)) return -7;

        if (选目标() == null) return -1;

        return spell.IsReadyWithCanCast() ? 4 : -1;
    }

    public void Build(Slot slot)
    {
        // ⚠️ **必须和 Check 同源**（开发约定 F③）—— 同一个 `选目标()`
        var 目标 = 选目标();
        if (目标 == null) return;

        var spell = SpellUtil.当前形态(_t.Dot技能);
        if (spell == null) return;

        slot.Add(new Spell(spell.Id, 目标));
    }

    /// <summary>
    /// 选一个"该补 DoT"的副目标 —— **只从有仇恨的里面选**。
    ///
    /// 复用 `HealTargetHelper.可补Dot的敌人`：它已经做了
    /// 「有仇恨 + 没有我的 DoT + 排除当前目标」的全部过滤。
    /// 这里只再加两道本地约束（黑名单、贴脸不打）。
    /// </summary>
    private IBattleChara? 选目标()
    {
        try
        {
            var 候选 = HealTargetHelper.可补Dot的敌人(_t.所有DotBuff, 25f, 副目标上限 + 2);

            foreach (var c in 候选)
            {
                // DoT 黑名单（免疫 / 吃不上的怪，补了也白费，还会反复触发）
                if (!Dot黑名单.可以上Dot(c)) continue;

                // 贴脸的怪别上 —— 那种距离该放 AOE，上 DoT 反而浪费一个 GCD
                try { if (Vector3.Distance(CharacterExt.我的位置(), c.Position) < 3f) continue; }
                catch { }

                return c;
            }
        }
        catch { }

        return null;
    }
}
