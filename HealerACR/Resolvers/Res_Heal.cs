using AEAssist.CombatRoutine;
using HealerACR.Common;
using HealerACR.Timeline;

namespace HealerACR.Resolvers;

// ============================================================================
//  三层治疗结构：
//    能力技大加（不占 GCD）→ 群体治疗 → 单体治疗 GCD
//
//  两个横切规则：
//    · 木桩模式（需求 5）：治疗全部让路，输出按最优策略打
//    · 资源充足度（需求 3）：能力技资源不够时退回 GCD 群奶，
//      把资源留给更急的时候
// ============================================================================

/// <summary>
/// 「必须奶满」—— 独立的高优先 GCD 治疗。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么要独立成一个 resolver（审计发现的问题）★
///
///  这段逻辑原来写在 `Res_HealSingleGcd` 里（返回 30，注释写"优先级高于一切"）。
///  但 **`Check()` 的返回值不参与仲裁** —— 真正决定顺序的是它在队列里的**行号**
///  （反汇编证据见 `Res_SingleHoT` 的注释）。
///
///  而 `Res_HealSingleGcd` 在各职业队列里排在**几乎最后**：
///      再生 → 狂喜之心 → 安慰之心 → 医济 → **单体治疗**
///  于是中「塞壬的歌声(370)」「渐渐石化(1628)」「混沌之泥土(1604)」的人，
///  只要场上①有 1 人 <52%（被再生抢走 GCD）或②≥2 人 <62%（被医济抢走），
///  这个"必须奶满"就**永远拿不到 GCD** —— 倒计时归零人直接没了。
///
///  ⇒ 拆成独立 resolver，插到决策队列**最前面**（复活/驱散之后），
///    这样才配得上"优先级高于一切"这句话。
///
///  ⚠️ 它只在**真的有人中机制**时才返回 >=0，
///     平时完全不占位（返回 -1，框架继续试后面的）。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public class Res_MustFullHeal : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_MustFullHeal(JobSpellTable table) => _t = table;

    public int Check()
    {
        if (HealTargetHelper.木桩模式) return -300;
        if (!HealQt.GetQt("奶人")) return -100;
        if (!HealQt.GetQt("单奶")) return -101;

        // 没有人为"必须奶满"机制时立刻让位（常态路径，不占 GCD）
        if (必须奶满.找目标() == null) return -1;

        // ══════════════════════════════════════════════════════════
        //  ★ 技能选择交给 `治疗决策`（综合判定）★
        //
        //  ⚠️ 原来调的是 `治疗量最大的单体()` —— 它**写死了白魔的二选一**
        //     （救疗 / 治疗），于是：
        //       · 神名（700 瞬发能力技）、天赐祝福（直接奶满）
        //         **永远不会被考虑**
        //       · 其他三职业直接用槽位那一个，连"最大"都没挑
        //       · 移动中能不能放、要几个 GCD —— 全没算
        //
        //  ⚠️ `强制紧急: true` —— 中这类机制的人**每秒都在倒计时**，
        //     "一次补满"比"省蓝"重要得多（`命悬一线` 分支会重罚补不满的）。
        // ══════════════════════════════════════════════════════════
        var (目标, 决定技) = 决定奶满();
        if (目标 == null) return -1;

        // 候选集挑不出（职业没填）→ 退回旧的硬编码路径
        var 技 = 决定技?.Id ?? 治疗量最大的单体();
        if (技 == 0) return -1;

        // ══════════════════════════════════════════════════════════════
        //  ★ 移动中**改走瞬发** —— 不是放弃救人 ★
        //
        //  ── 原来的注释说 ──
        //    "不加重移动守卫的判断：中这类机制时**不能因为走位就放弃救人**"
        //    **这个顾虑是对的，但解法是错的**：
        //    移动中读条**必然被打断**（日志里 SelfCastCancel 87 条为证），
        //    结果不是"救到了"，而是"读条被打断 + 这一发白费"。
        //
        //  ── 正确解法 ──
        //    移动中**改用瞬发能力技**（神名 / 天赐祝福 / 生命活性法 / 先天禀赋）——
        //    它们不读条，能真的把这一口给出去。
        //    这些技能**治疗量够大**（天赐直接到满），救急完全够用。
        //
        //  ⚠️ 顺序：**先瞬发，再读条**。
        //     站定时读条的那个治疗量更大（比如救疗 > 神名），所以站定优先读条；
        //     移动时读条必然失败，所以必须换成瞬发。
        // ══════════════════════════════════════════════════════════════
        // ⚠️ 用 `不能读条()`（= 移动中 **或** 空中）而不是 `在移动()` ——
        //    [!] 下面那一整段判的是"**能不能读条**"：
        //          · 能读条 -> 走读条技（治疗量更大）
        //          · 不能   -> 改走瞬发，或者干脆放弃（别硬读，白费 GCD）
        //    [!] 而 `在移动()` **不含跳跃**（框架的 `IsPlayerMoving` 不因跳跃改变，
        //        见 `空中检测.cs` 的类注释）==>
        //        跳起来时 `移动中 == false` -> 跳过整段 -> 走读条技 -> **放不出来**。
        //        而同一段里 `SpellUtil.移动中可用(技)` **本来就含跳跃** ——
        //        两行判据不同源，说明这里的原意就是"能不能读条"。
        //    [!] 这是**救命路径**（中致死机制时唯一解），判错的代价比别处大。
        var 不能读 = SpellUtil.不能读条();

        if (不能读)
        {
            // 移动中：只要有一个瞬发可用就交给它 —— 本 resolver 让路，
            // 因为 `Res_InstantHealAbility` / `Res_HealEmergency` 排在后面，
            // 它们会接住（而且它们的目标选择更精确）。
            if (有瞬发可用()) return -1;

            // 连瞬发都没有 → 读条在移动中也放不出，这一发只能放弃。
            //   ⚠️ 不要"硬读" —— 那是白费 GCD（日志里就发生过）。
            if (!SpellUtil.移动中可用(技)) return -1;
        }

        return SpellUtil.可用(技) ? 40 : -1;
    }

    // ══════════════════════════════════════════════════════════════
    //  ★ 同帧缓存 —— 保证 Check / Build 选同一个技能（开发约定 F③）★
    //
    //  ⚠️ 这条是**救命路径**（中致死机制时唯一解），
    //     判 A 放 B 的后果比别处严重得多。
    // ══════════════════════════════════════════════════════════════
    private static long _缓存帧;
    private static ulong _缓存目标Id;
    private static 治疗技能? _缓存技能;

    /// <summary>
    /// **必须奶满时该用哪个技能**（Check / Build 共用）。
    ///
    /// ⚠️ `强制紧急: true` —— 中这类机制的人**每秒都在倒计时**，
    ///    "一次补满"比"省蓝"重要得多。
    ///
    /// ⚠️ 候选集挑不出（职业没填）时返回 `null`，
    ///    调用方回退到旧的 `治疗量最大的单体()`。
    /// </summary>
    private (IBattleChara? 目标, 治疗技能? 技) 决定奶满()
    {
        try
        {
            var 目标 = 必须奶满.找目标();
            if (目标 == null) return (null, null);

            var 帧 = AEAssist.Helper.TimeHelper.Now() / 50;
            if (帧 == _缓存帧 && 目标.GameObjectId == _缓存目标Id)
                return (目标, _缓存技能);

            // ══════════════════════════════════════════════════════════════
            //  ★ 移动中改走瞬发 —— 且**不让路** ★
            //
            //  [!] 原设计是移动中让路（交给 `Res_InstantHealAbility` /
            //      `Res_HealEmergency`），但**实测接不住** ——
            //      那两条路的入口都有这道门：
            //        `Res_AllExtra.cs`:
            //            if (必须奶满.找目标() == null && 低于阈值人数(0.30f) == 0) return 26;
            //        `Res_Heal.cs` 的 `Res_HealEmergency`:
            //            var 奶满目标 = 必须奶满.找目标();   // 非空 -> 只走"一次到满"分支
            //      ⇒ **有人中致死机制时 `找目标()` 必然非空** ⇒ 瞬发分支被排除。
            //      ⇒ 移动中 + "一次到满"能力技在 CD + 中「塞壬的歌声」
            //        = 没有任何 resolver 会奶他，
            //          而白魔此时明明有**瞬发的百合 安慰之心（800）**可用。
            //
            //  [!] 修在**这里**而不是 `Check()` 里，是因为 `Build()` 也用本方法
            //      ⇒ Check / Build 自动同源（开发约定 F③），
            //        不会出现"Check 选瞬发、Build 放读条"的判 A 放 B。
            //
            //  [!] 不需要额外过滤：`治疗决策.可用()` 里已经有
            //          `if (移动中 && !技.瞬发) return false;`
            //      ⇒ `移动中: true` 时选出来的必然是瞬发技。
            // ══════════════════════════════════════════════════════════════
            var 技 = SpellUtil.不能读条()
                ? 治疗决策.选最优(
                    _t.治疗候选,
                    缺口: MathF.Max(1f, 目标.MaxHp - 目标.CurrentHp),
                    命悬一线: true,          // 中致死机制 = 命悬一线（重罚补不满）
                    移动中: true,
                    只群体: false,
                    只瞬发: true)
                : 治疗决策.给目标选最优(_t.治疗候选, 目标, 强制紧急: true);

            _缓存帧 = 帧;
            _缓存目标Id = 目标.GameObjectId;
            _缓存技能 = 技;
            return (目标, 技);
        }
        catch
        {
            return (null, null);
        }
    }

    /// <summary>
    /// 现在有没有**可用的瞬发单体治疗能力技**（移动中救急用）。
    ///
    /// 检查顺序：瞬发单奶能力技 → 预铺单奶能力技 → 紧急单奶。
    /// 任一可用就返回 true —— 本 resolver 好让路给它们。
    /// </summary>
    private bool 有瞬发可用()
    {
        try
        {
            // ★ 优先问**治疗候选集**（它含全部治疗手段，比三个槽位全）★
            foreach (var h in _t.治疗候选.已解锁())
            {
                if (!h.瞬发) continue;
                if (SpellUtil.可用(h.Id)) return true;
            }
        }
        catch { }

        // 候选集空 → 退回槽位
        try
        {
            foreach (var id in new[] { _t.瞬发单奶能力技, _t.预铺单奶能力技, _t.紧急单奶 })
            {
                if (id == 0) continue;
                if (!SpellUtil.已解锁(id)) continue;
                if (SpellUtil.可用(id)) return true;
            }
        }
        catch { }

        return false;
    }

    public void Build(Slot slot)
    {
        // ⚠️ 和 Check **同一个** `决定奶满()`（内含同帧缓存）——
        //    两边同源才不会有"判 A 放 B"（开发约定 F③）。
        var (目标, 决定技) = 决定奶满();
        if (目标 == null) return;

        var 技 = 决定技?.Id ?? 治疗量最大的单体();
        if (技 == 0) return;

        slot.Add(new Spell(技, 目标));
    }

    /// <summary>
    /// 「必须奶满」时该用的单体治疗 —— 挑**治疗量最大**的那个。
    ///
    /// ⚠️ 不能直接用 <c>_t.单体治疗GCD</c>："最低级优先"是它给普通掉血用的，
    ///    而中继发症状病时**每一秒都在倒计时**，需要用最高效的治疗尽快奶满。
    ///
    /// 白魔的候选顺序：**救疗(135) → 治疗(120)**（治疗量从高到低）。
    ///
    ///   ⚠️ 这里原来还列了「愈疗(131)」并注释"治疗量从高到低"。**那是错的**：
    ///      已核实 dump_actions.tsv —— 131 愈疗 = `CastType=2 / EffectRange=10`，
    ///      它是**群疗**（以目标为中心 10 米），不是单体，治疗量也不是最高档。
    ///      而且它 Lv40 比救疗 Lv30 后解锁，`取已解锁` 永远选不到它（死代码）。
    ///
    /// 其余职业目前只有单档单体 GCD 治疗，直接用表里的值。
    /// 拿不到任何候选时退回 <c>_t.单体治疗GCD</c>（宁可放一个弱治疗，也别不放）。
    /// </summary>
    private uint 治疗量最大的单体()
    {
        try
        {
            if (_t.Job == Jobs.WhiteMage)
            {
                var 最优 = SpellUtil.取已解锁(
                    SpellIds.取("救疗"),
                    SpellIds.取("治疗"));

                if (最优 != 0) return 最优;
            }

            return _t.单体治疗GCD;
        }
        catch
        {
            return _t.单体治疗GCD;
        }
    }
}

/// <summary>紧急单奶（OffGcd）：天赐祝福 / 深谋远虑之策 / 先天禀赋 / 输血 这类。</summary>
public class Res_HealEmergency : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_HealEmergency(JobSpellTable table) => _t = table;

    // ══════════════════════════════════════════════════════════════
    //  ★ 常规急救的同帧缓存（保证 Check / Build 一致）★
    // ══════════════════════════════════════════════════════════════
    private static long _缓存帧;
    private static ulong _缓存目标Id;
    private static 治疗技能? _缓存技能;

    /// <summary>
    /// **常规急救**用哪个技能（Check / Build 共用）。
    ///
    /// ⚠️ 和上方 `奶满技能` 的区别：
    ///    那是"中致死机制、血可能很高"的特例，只挑一次到满类；
    ///    这是**普通濒死**（血 ≤ `紧急单奶阈值`，默认 0.30）——
    ///    血真的低，所以"随血降低而增强"的技能（先天禀赋）**反而正好合适**。
    ///
    /// ⚠️ `只瞬发: true` —— 急救是能力技的活，读条在移动中会失败
    ///    （而且急救本来就该用能力技，不占 GCD）。
    /// </summary>
    private (IBattleChara? 目标, 治疗技能? 技) 决定常规急救()
    {
        try
        {
            var 目标 = HealTargetHelper.最低血量队友(HealSettings.Instance.紧急单奶阈值);
            if (目标 == null) return (null, null);

            var 帧 = AEAssist.Helper.TimeHelper.Now() / 50;
            if (帧 == _缓存帧 && 目标.GameObjectId == _缓存目标Id)
                return (目标, _缓存技能);

            var 技 = 治疗决策.给目标选最优(
                _t.治疗候选, 目标,
                强制紧急: true,
                只群体: false,
                只瞬发: true);      // 急救只认瞬发能力技

            _缓存帧 = 帧;
            _缓存目标Id = 目标.GameObjectId;
            _缓存技能 = 技;
            return (目标, 技);
        }
        catch
        {
            return (null, null);
        }
    }

    /// <summary>
    /// 「必须奶满」时用的技能 —— 只挑"一次到满"那类（拿不到返回 0）。
    ///
    /// ⚠️ 和 <see cref="_t.紧急单奶"/> 的区别见 `必须奶满.最该用的能力技` 的注释：
    ///    那张表里有"血高时无效"的技能（学者深谋远虑之策要降到阈值才触发、
    ///    占星先天禀赋随血量降低而增强），**中 Doom 的人血还很高**，
    ///    交那些技能等于没治。
    /// </summary>
    private uint 奶满技能 => 必须奶满.最该用的能力技(_t);

    public int Check()
    {
        if (HealTargetHelper.木桩模式) return -300;          // 木桩不奶
        if (!HealQt.GetQt("奶人")) return -100;
        if (!HealQt.GetQt("单奶")) return -101;

        // ══════════════════════════════════════════════════════════════
        //  ⚠️ **能力技队列深度闸门**（对照分析发现的缺口）
        //
        //    参考实现的每个 oGCD resolver 都有 `CanUseOffGcd(1)`
        //    （IL 直证 `HealerResolverBase.CanUseOffGcd`），
        //    防止血崩瞬间把 天赐 / 慰藉 / 不屈 / 法令 连着几帧全倒出去。
        //
        //    ⚠️ **必须放在最前面** —— 本 resolver 有两条出口：
        //       ① 「必须奶满」分支（`return 35`）
        //       ② 常规急救分支
        //       放在 ① 之后就只管得住 ②，两条路行为不一致。
        //
        //    ⚠️ 失败方向是**放行**（见 `OffGcd闸门` 注释）：
        //       读不到队列时宁可多放一个，也不要**把治疗全哑掉**。
        // ══════════════════════════════════════════════════════════════
        if (!OffGcd闸门.可以排(1)) return -1;

        // ══════════════════════════════════════════════════════════════
        //  ★ 「必须奶满」优先：**不受紧急单奶阈值限制** ★
        //
        //    下面那条 `最低血量队友(紧急单奶阈值)` 是给普通急救用的。
        //    中 Doom/石化/塞壬之歌的人**血量可能很高**（80%+），
        //    按血线判断会直接把他过滤掉 —— 白白浪费"一次到满"的机会，
        //    然后倒计时归零人没了。
        //
        //    所以这里先无条件检查有没有人中机制；有就把能力技交给他。
        // ══════════════════════════════════════════════════════════════
        var 奶满目标 = 必须奶满.找目标();
        if (奶满目标 != null)
        {
            var 技 = 奶满技能;

            if (技 != 0 && SpellUtil.已解锁(技) && SpellUtil.可用(技)) return 35;

            // ⚠️ 没有"一次到满"的能力技时，**不要 return -1** ——
            //    那会把**整个 resolver**（包括下面的常规急救）一起否掉。
            //
            //    审计发现的后果：只要场上有**任何一个人**中 370/1604/1628
            //    （最长 20 秒），而一次性到满的技能在 CD
            //    （占星永远返回 0 / 白魔天赐 180s / 学者贤者的对应技能转 CD），
            //    这条 `return -1` 会让**另一个濒死队友也拿不到常规急救** ——
            //    因为 :62 那条路被跳过，整条能力技急救链全部失效。
            //
            //    ⇒ 正确做法：**落下去走常规急救**。机制那个人交给 GCD 治疗链
            //      （`Res_HealSingleGcd` 里有"必须奶满"分支，不会被血线挡住），
            //      而这条能力技留给真正濒死的另一个人。
        }

        // ══════════════════════════════════════════════════════════
        //  ★ 常规急救 —— 技能选择交给 `治疗决策` ★
        //
        //  ⚠️ 原来只有 `_t.紧急单奶` 一个槽位（白魔=天赐祝福，180 秒 CD）——
        //     于是 30% 血的人**只能等天赐**，而神名（700 瞬发、60 秒 CD）
        //     明明也能救、而且便宜得多。
        //
        //  ⚠️ `只瞬发: true` ⇒ 读条技自动排除（急救就该用能力技）。
        // ══════════════════════════════════════════════════════════
        var (target, 决定技) = 决定常规急救();
        if (target == null) return -1;

        if (决定技 != null)
            return SpellUtil.可用(决定技.Id) ? 30 : -1;

        // 候选集挑不出 → 退回旧槽位（行为与接入前完全一致）
        if (_t.紧急单奶 == 0) return -102;
        if (!SpellUtil.已解锁(_t.紧急单奶)) return -2;
        return SpellUtil.可用(_t.紧急单奶) ? 30 : -1;
    }

    public void Build(Slot slot)
    {
        // ⚠️ 必须和 Check 同源（开发约定 F③）。
        //
        //    ⚠️ 这里曾经**不同源**：Build 一看到「有奶满目标」就 return，
        //       但 Check 在"没有一次性到满技能"时会**落到常规急救**。
        //       结果：Check 返回 30（走常规急救那条路），Build 却因为
        //       奶满目标 != null 直接 return → **slot 是空的** →
        //       框架看到 Build 没产出就继续试下一个 resolver →
        //       这条能力技急救**静默失效**。
        //
        //    ⇒ 两边用**同一个判断**：只有在"奶满目标存在**且**奶满技能真的可用"时
        //      才走奶满分支，否则一致地落到常规急救。
        var 奶满目标 = 必须奶满.找目标();
        var 技 = 奶满技能;

        if (奶满目标 != null && 技 != 0 && SpellUtil.已解锁(技) && SpellUtil.可用(技))
        {
            slot.Add(new Spell(技, 奶满目标));
            return;
        }

        var (target, 决定技) = 决定常规急救();
        if (target == null) return;

        // ⚠️ 和 Check **同一个** `决定常规急救()`（内含同帧缓存）——
        //    两边同源才不会有"判 A 放 B"（开发约定 F③）。
        if (决定技 != null)
        {
            slot.Add(new Spell(决定技.Id, target));
            return;
        }

        // 候选集挑不出 → 退回旧槽位
        if (_t.紧急单奶 != 0)
            slot.Add(new Spell(_t.紧急单奶, target));
    }
}

/// <summary>群体治疗能力技（OffGcd）：不屈不挠之策 / 天星冲日 / 消化 / 法令 之类。</summary>
public class Res_HealAoEAbility : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_HealAoEAbility(JobSpellTable table) => _t = table;

    public int Check()
    {
        // 木桩模式治疗让路 —— 但"输出型群奶技"（白魔法令）不算治疗，
        // 它是卡 CD 打的输出，必须放行，否则木桩就永远不打法令了
        if (HealTargetHelper.木桩模式 && !_t.群体治疗能力技是输出型) return -300;
        if (!HealQt.GetQt("奶人")) return -100;
        if (!HealQt.GetQt("群奶")) return -101;
        if (_t.群体治疗能力技 == 0) return -102;
        if (!SpellUtil.已解锁(_t.群体治疗能力技)) return -2;

        // ⚠️ **能力技队列深度闸门**（对照分析发现的缺口）——
        //    参考实现里群疗能力技用 `CanUseOffGcd(1)` / `(2)`。
        //
        //    ⚠️ **输出型（白魔法令）不受闸门限制** —— 它是卡 CD 打的输出，
        //       被节流就变成白漏伤害。这和"血崩时别连发治疗"是两回事，
        //       不能一刀切（开发约定 ⑦）。
        if (!_t.群体治疗能力技是输出型 && !OffGcd闸门.可以排(1)) return -1;

        var s = HealSettings.Instance;
        // ⚠️ 必须传**技能真实半径**（20 米）—— 不传就落到默认 30 米，
        //    会把 20 米外的人也算成"该群疗" → 交掉一个大 CD 却只治到 1 个人。
        //    （不屈不挠之策 3583 / 天星冲日 16553 / 消化 24301 都是 20 米）
        var 低于血线 = HealTargetHelper.低于阈值人数(s.群体治疗阈值, 20f);

        // 输出型（白魔法令）：卡 CD 打，不等掉血。
        // 注意**不要**检查当前目标 —— 法令是"以自己为中心"的范围技，
        // 和之前王冠之领主犯的是同一个错。
        if (_t.群体治疗能力技是输出型)
        {
            return SpellUtil.可用(_t.群体治疗能力技) ? 25 : -1;
        }

        // ══════════════════════════════════════════════════════════════
        //  ★ 门槛改成**设置项**（对齐两套参考实现）★
        //
        //  [!] 原来写的是 `Math.Max(1, s.群奶最少人数 - 1)` ——
        //      **默认 2 => 只要 1 个人低于血线就交掉一个群疗能力技**。
        //
        //  [!] 参考实现怎么做的（IL 实证，两套一致）：
        //        shiyuvi `Scholar_Indomitability`：`count >= AOEHealCount`（默认 **2**）
        //                `Scholar_WhisperingDawn` 同样是 `AOEHealCount`
        //        youshu  `CountLowHpAlliesNear(...) < Clamp(群奶人数,0,8)` -> 放弃
        //                群奶人数默认 **2**，且**所有群疗**都用同一个数
        //      ==> 两套都是「**设置项本身**」，没有 `-1` 这种折扣。
        //
        //  [!] 为什么原来会写成 `-1`：
        //      能力技比 GCD 群奶"便宜"（不占 GCD、CD 独立），
        //      所以想让能力技更舍得交。**这个意图是对的**，
        //      但**用 `-1` 表达它是错的** —— 它把门槛和设置项脱钩了：
        //        用户把「群奶最少人数」调到 3，能力技仍然只要 2 人（3-1=2）；
        //        调到 2（默认），能力技只要 **1 人** —— 一个人掉血就交全团 CD。
        //
        //  [!] 而 `Res_HealAoEGcd` 用的是 `HealTargetHelper.群奶人数要求()` ——
        //      那是**另一条公式**（四人本 `max(2,基础-1)`；八人本 `max(基础,3)`）。
        //      于是同一个"群奶人数"设置在两条路上算出**两个不同的数**，
        //      这违反项目开发约定 F③（同一个决策不论从哪条路进来判断必须一致）。
        //      **本次先把能力技这条对齐设置项**；`群奶人数要求()` 那条留给
        //      单独一轮（它有明确的用户拍板记录：八人本 4 -> 3，不能顺手改）。
        //
        //  [!] 保守性：`Clamp(_, 1, 8)` 保证"至少 1 人"（用户把设置调到 0 时
        //      不该变成"永远不交"），上限 8 = 队伍规模。
        // ══════════════════════════════════════════════════════════════
        var 要求人数 = HealTargetHelper.群疗能力技人数要求(s.群奶最少人数);
        if (低于血线 < 要求人数) return -1;

        // 资源不够（学者没以太、贤者没蛇胆）→ 让给 GCD 群奶，除非掉血的人明显更多
        if (!_t.治疗资源充足 && 低于血线 < s.群奶最少人数) return -103;

        // 时间轴预报：更大的伤害马上要来，这个能力技留着那时候用
        if (HealSettings.Instance.时间轴攒资源 && TimelineManager.未来有减伤(5.0)
            && 低于血线 < s.群奶最少人数 + 1)
        {
            return -5;
        }

        return SpellUtil.可用(_t.群体治疗能力技) ? 20 : -1;
    }

    public void Build(Slot slot)
    {
        // 能力技不等服务器回包（文档建议），避免能力技之间互相卡顿
        slot.Add(CharacterExt.能力技(_t.群体治疗能力技));
    }
}

/// <summary>群体治疗 GCD：医济 / 士气高扬之策 / 阳星 / 预后。</summary>
public class Res_HealAoEGcd : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_HealAoEGcd(JobSpellTable table) => _t = table;

    // ══════════════════════════════════════════════════════════════
    //  ★ 同帧缓存 —— 保证 Check / Build 选同一个技能 ★
    //    （和 `Res_HealSingleGcd` 同一套做法，理由见那边）
    // ══════════════════════════════════════════════════════════════
    private static long _缓存帧;
    private static 治疗技能? _缓存技能;

    /// <summary>
    /// **这一发该用哪个群体治疗**（Check / Build 共用）。
    ///
    /// ⚠️ 缺口取"该奶的那几个人里**最大**的那个缺口"：
    ///    群体治疗一次覆盖所有人，用最大缺口判断"够不够"最稳妥 ——
    ///    用平均值会让"有人快死了但平均还行"被低估。
    /// </summary>
    private 治疗技能? 决定()
    {
        try
        {
            var s = HealSettings.Instance;
            var 半径 = 20f;

            // ══════════════════════════════════════════════════════════════
            //  ★ 群疗 GCD 的门槛：按**槽位技能**查表 ★
            //
            //  [!] 为什么用"槽位技能"而不是"最终选中的技能"：
            //      本函数的顺序是 **① 先按门槛数人 -> ② 再挑技能**，
            //      而 ① 需要门槛时**还不知道会挑中哪个** —— 顺序上查不了"选中那个"的表。
            //
            //  [!] 参考实现是**反过来**的（IL 实证）：
            //        shiyuvi `Scholar_AOEGCDHeal` 一个类里分三段
            //                （LowLevelAoeHeal 0.75 / GCDShield 0.8 / Succor 0.65），
            //                **每段各自用各自的阈值数人**
            //        youshu  同样分技能
            //      ==> 它们不存在"先数人再挑技能"这个顺序。
            //
            //  [!] 为什么**不**把顺序倒过来（先挑技能再数人）：
            //      挑了技能之后 `低血.Count` 会变 ==> `缺口` 也变 ==>
            //      而 `决定()` 被 `Check` 和 `Build` **各调一次**（F③ 要同源）。
            //      两次之间只要人数差一个，就会"Check 说放 A、Build 放了 B"。
            //      ==> 拆那个顺序的代价是**引入一个新的不一致风险**，
            //          而收益只是"门槛更精确一点"。
            //          **这一轮不拆**（记录在案，要拆得单独设计同帧缓存）。
            //
            //  [!] 所以取**槽位技能**的门槛：它四个职业都是确定的
            //        （学者 士气高扬之策 / 贤者 预后 / 白魔 医养系 / 占星 阳星系）
            //      ==> 比统一阈值精确（学者 0.62 -> 0.65），而且**不引入新风险**。
            // ══════════════════════════════════════════════════════════════
            var 本技血线 = 治疗阈值表.取(_t.群体治疗GCD, s.群体治疗阈值);

            var 低血 = HealTargetHelper.可治疗队友(半径)
                .Where(r => r.有效血量比例() <= 本技血线)
                .ToList();

            if (低血.Count < HealTargetHelper.群奶人数要求(s.群奶最少人数)) return null;

            // ── 缺口 = 最大的那个 ──
            var 缺口 = 0f;
            foreach (var r in 低血)
                缺口 = MathF.Max(缺口, 治疗决策.缺口量(r));
            if (缺口 <= 0f) return null;

            // ── 同帧缓存 ──
            var 帧 = AEAssist.Helper.TimeHelper.Now() / 50;
            if (帧 == _缓存帧) return _缓存技能;

            var 技 = 治疗决策.选最优(
                _t.治疗候选, 缺口,
                命悬一线: false,          // 群体治疗不承担"救急"职责（那是单奶/能力技的活）
                移动中: SpellUtil.不能读条(),
                只群体: true, 只要GCD: true,   // GCD 槽不能塞 oGCD 能力技
                只瞬发: false);

            _缓存帧 = 帧;
            _缓存技能 = 技;
            return 技;
        }
        catch
        {
            return null;
        }
    }

    public int Check()
    {
        if (HealTargetHelper.木桩模式) return -300;
        if (!HealQt.GetQt("奶人")) return -100;
        if (!HealQt.GetQt("群奶")) return -101;

        var 技 = 决定();

        // ★ 候选集挑不出 → 退回旧槽位（行为与接入前完全一致）★
        if (技 == null)
        {
            if (_t.群体治疗GCD == 0) return -102;
            if (!SpellUtil.已解锁(_t.群体治疗GCD)) return -2;

            var s0 = HealSettings.Instance;
            // ★ 和 `决定()` 用**同一个**门槛（同一个决策不能两条路给不同的数，F③）★
            //   原来这里读统一群疗阈值、`决定()` 读的也是它 —— 一致。
            //   现在两条都改成"按槽位技能查表"，**仍然一致**。
            var 回退血线 = 治疗阈值表.取(_t.群体治疗GCD, s0.群体治疗阈值);
            if (HealTargetHelper.低于阈值人数(回退血线, 20f)
                < HealTargetHelper.群奶人数要求(s0.群奶最少人数)) return -1;

            if (!SpellUtil.移动中可用(_t.群体治疗GCD)) return -7;
            return SpellUtil.可用(_t.群体治疗GCD) ? 12 : -1;
        }

        // ⚠️ `决定()` 返回非 null 就说明它已确认"放得出来"（含移动判定），
        //    这里再确认一次是为了防"两次调用之间状态变了"。
        return SpellUtil.可用(技.Id) && SpellUtil.移动中可用(技.Id) ? 12 : -1;
    }

    public void Build(Slot slot)
    {
        // ⚠️ 和 Check 同源（开发约定 F③）
        var 技 = 决定();

        if (技 != null)
        {
            slot.Add(new Spell(技.Id, SpellTargetType.Self));
            return;
        }

        // 候选集挑不出 → 退回旧槽位
        if (_t.群体治疗GCD != 0)
            slot.Add(new Spell(_t.群体治疗GCD, SpellTargetType.Self));
    }
}

/// <summary>单体治疗 GCD。目标永远是"血最少的那个人"。</summary>
public class Res_HealSingleGcd : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_HealSingleGcd(JobSpellTable table) => _t = table;

    public int Check()
    {
        // ★ 木桩 / 开关仍然要尊重 —— 用户关掉治疗就该真的不治
        if (HealTargetHelper.木桩模式) return -300;
        if (!HealQt.GetQt("奶人")) return -100;
        if (!HealQt.GetQt("单奶")) return -101;
        if (_t.单体治疗GCD == 0) return -102;
        if (!SpellUtil.已解锁(_t.单体治疗GCD)) return -2;

        // ══════════════════════════════════════════════════════════════
        //  ⚠️ 「必须奶满」已经**移出去**了 —— 见 `Res_MustFullHeal`
        //
        //  这里原来是：
        //      if (奶满目标 != null) return 治疗量最大的单体() != 0 ? 30 : -1;
        //  注释写"优先级高于一切血线判断"。**但返回值不参与仲裁** ——
        //  决定顺序的是**队列行号**，而本 resolver 在各职业队列里排**几乎最后**
        //  （再生 → 狂喜 → 安慰 → 医济 → 单体治疗）。
        //
        //  后果：中「塞壬的歌声」的人只要场上有 1 人 <52%（被再生抢）
        //  或 ≥2 人 <62%（被医济抢），这条"必须奶满"就**拿不到 GCD**。
        //
        //  ⇒ 现在由 `Res_MustFullHeal` 承担，它插在决策队列**最前面**。
        //    本 resolver 只负责普通血线治疗。
        //    （历史教训见 `Res_SingleHoT` 的注释：**别再用返回值表达优先级**。）
        // ══════════════════════════════════════════════════════════════

        // ⚠️ 先锁定"该奶谁 + 用哪个技能"，再判断"这个人还需要奶吗" —— 顺序不能反。
        //
        //  ⚠️ 这里调的是**和 Build 同一个** `决定()`（内含同帧缓存）——
        //     两边同源才不会有"判 A 放 B"（开发约定 F③）。
        var (target, 技) = 决定();
        if (target == null) return -1;

        // ── 目标已经有厚盾就别再刷治疗：血量 + 盾已经溢出，再读条是纯浪费 GCD ──
        //    （不加检查的后果：学者会"每次都奶两次"。）
        //
        // ⚠️ 这个判断**必须针对"真正要奶的那个人"**，不能拿坦克当替身。
        //
        //    曾经写成"血量最低的坦克有盾 -> return -3"，那是个真 bug：
        //      `-3` 否决的是**整个单体 GCD 治疗**，不分对象 ——
        //      于是坦克挂着 30 秒鼓舞的期间，队伍里掉到 30% 血的 DPS
        //      **一次单奶都拿不到**。单奶链等于被坦克的盾绑架了。
        //      （静默失效：不报错，只是"该救的人没被救"。）
        try
        {
            // ⚠️ **不能在这里 `return -3` 掉整个单体治疗**（上面 L659-663 记着这个真 bug）：
            //    `-3` 否决的是**整个单体 GCD 治疗**，不分对象 ——
            //    坦克挂着盾的期间，掉到 30% 的 DPS **一次单奶都拿不到**。
            //
            // ★ 所以只做**换目标**（见 `决定()` 里的 `预铺跳过`），不否决整条路 ★
            //   [!] 而"已有一套预铺（盾/绿帽/水流幕/天星交错）就不该再铺"这件事，
            //       由 `决定()` 在**选目标时**跳过那个人来实现 —— 判据走共享的 `已有预铺()`。
            if (_t.单体盾 != 0
                && target.有该技能的Buff(_t.单体盾)
                && target.我的Buff还剩超过N秒(AuraIds.技能转Buff(_t.单体盾), 5f))
            {
                return -3;
            }
        }
        catch { }

        // ⚠️ **移动守卫**：单体治疗 GCD 基本都读条（治疗 / 救疗 / 鼓舞…），
        //    移动中硬读会被打断。
        //
        //    ⚠️ 注意它**只挡 GCD 治疗** —— 上面「必须奶满」那条已经提前 return 了
        //       （中继死机制时不能因为走位就放弃救人），
        //       而能力技治疗（天赐祝福 / 神名 / 活性法…）走
        //       Res_HealEmergency，不受这条限制。
        //       所以移动中**仍然有救急手段**，只是不用读条那条路。
        // ══════════════════════════════════════════════════════════════
        //  ★ 可用性判**决定出来的那个技能**，不是槽位技能 ★
        //
        //  ⚠️ 移动守卫现在由 `治疗决策.选最优` 内部处理（移动中只认瞬发）——
        //     `决定()` 返回非 null 就说明**它已经确认这个技能放得出来**。
        //     这里再确认一次是为了防"两次调用之间状态变了"。
        // ══════════════════════════════════════════════════════════════
        if (技 != null)
            return SpellUtil.可用(技.Id) && SpellUtil.移动中可用(技.Id) ? 10 : -1;

        // 候选集挑不出 → 退回旧槽位（行为与接入前完全一致）
        if (!SpellUtil.移动中可用(_t.单体治疗GCD)) return -7;

        return SpellUtil.可用(_t.单体治疗GCD) ? 10 : -1;
    }

    // ══════════════════════════════════════════════════════════════
    //  ★ 同帧缓存 —— 保证 `Check` 和 `Build` 选**同一个技能** ★
    //
    //  ⚠️ 为什么需要：
    //     `治疗决策.选最优` 依赖**动态状态**（目标血量 / MP / 冷却）。
    //     两次调用之间状态可能变 → Check 判了「救疗」、Build 放了「治疗」
    //     —— 这就是开发约定 F③ 说的"判 A 放 B"，也是这一行最阴的 bug。
    //
    //  ⇒ Check 算一次存起来，Build 直接取用；过了一帧（或目标变了）才重算。
    // ══════════════════════════════════════════════════════════════
    private static long _缓存帧;
    private static ulong _缓存目标Id;
    private static 治疗技能? _缓存技能;

    /// <summary>
    /// **这一发该用哪个单体治疗**（Check / Build 共用）。
    ///
    /// 返回 null = 没有合适的（目标不需要奶 / 技能都放不出来）。
    /// </summary>
    private (IBattleChara? 目标, 治疗技能? 技) 决定()
    {
        try
        {
            // ══════════════════════════════════════════════════════════════
            //  ★ **每技能各查各的血线**（照参考实现的结构）★
            //
            //  [!] 原来错在哪：
            //      `var 阈值 = HealSettings.Instance.单体治疗阈值;` 然后
            //      `最低血量队友(阈值)` —— **先用一个大类阈值锁定目标，再选技能**。
            //      而 `治疗阈值表` 里明明有**每个技能自己的值**
            //      （白魔：天赐 20 / 神名 75 / 安慰之心 40 / 愈疗 40 / 医治 45 …，
            //        全部标着 `// youshu xxx阈值 NN` 的 IL 依据）。
            //
            //  [!] 后果（白魔最明显）：
            //      安慰之心 IL 依据是 **40%**，而它实际吃的是大类 **52%** ==>
            //      **在 40~52 这段会提前交掉**（把蓝花浪费在还没到线的人身上）。
            //      反过来说，凡是"比大类更晚"的技能**永远等不到那个时机**
            //      （目标先被大类阈值捞走，然后选了别的技能）。
            //
            //  [!] 参考实现的结构（youshu / shiyuvi 都是）：
            //      每个技能一个 resolver，**各自**判"有没有人低于**我这个技能的**血线"。
            //      ==> 谁的血线到了，谁才有机会被选中。这才是"逐技能复刻"。
            //
            //  [!] 为什么可以按技能查（不会循环）：
            //      `缺口量()` / `打分()` 都**不读阈值** —— 阈值只决定
            //      "该不该治**这个人**"，不参与"这个技能好多少"的排序。
            //      所以流程是：对每个技能找它自己的目标 -> 打分 -> 取最高分。
            //
            //  [!] 代价：技能数（约 10~14）× 一次队友扫描，**一帧一次**（有同帧缓存）。
            //      第一版按"最低血量队友"来选，所以每个技能只看**最危险的那个人** ——
            //      和原来的语义一致（原来也只治最危险的那个），只是血线变准了。
            // ══════════════════════════════════════════════════════════════
            IBattleChara? 目标 = null;
            // ── ① 按**每个技能自己的血线**筛出"够格的技能" ──
            //
            //  [!] 这一步**只筛不选** —— 选交给下面的 `治疗决策.选最优`（统一打分）。
            //      为什么不在这一层选：`对目标打分` 和 `选最优` 的打分口径
            //      **不一致**（前者用 `未来缺口(目标)` + 硬编码 0.30 判命悬，
            //      后者的缺口/命悬由调用方传入）——
            //      混用会重现本轮审计追着修的那类"两处口径不同"的问题（开发约定 F③）。
            //      ==> 所以这里只产出一个**更小的候选集**，打分口径仍然只有一个。
            var 够格的 = new 治疗候选集();
            foreach (var c in _t.治疗候选.已解锁())
            {
                if (c == null || c.Id == 0) continue;
                // 只考虑 GCD 单体（本 resolver 走 Gcd 槽，能力技有各自的 resolver）
                if (c.群体) continue;
                // ⚠️ **必须用 `是能力技_实际`，不能用 `冷却 > 0f`** ——
                //    `治疗技能.cs` L115-123 记着这个真 bug（H13）：
                //      曾经用 `MP <= 0 && 冷却 <= 0f` 判能力技，把
                //      **MP 0 + 冷却 0 的 GCD 技**（白魔 安慰之心 / 狂喜之心）判成能力技
                //      ==> 它们被排除出 GCD 路径，而候选集告诉 AI 它们是 GCD
                //      ==> **模型对、本地错**。
                //    `是能力技_实际` 就是那次修好的判据，`治疗决策.选最优` 的
                //    `只要GCD` 过滤也用它（同源，开发约定 F③）。
                //    [!] 我第一版这里写的是 `c.冷却 > 0f` —— **同一个坏谓词**。
                //        当时没出错只是因为安慰之心的冷却确实是 0；
                //        下次有人给某个 GCD 治疗填了冷却值，它就会被静默滤掉。
                if (c.是能力技_实际) continue;
                try { if (!SpellUtil.已解锁(c.Id)) continue; } catch { continue; }

                // ★ 这个技能自己的血线（表里有就用表里的，并叠加 AI 的三种偏移）★
                var 本技血线 = 治疗阈值表.取(c.Id, HealSettings.Instance.单体治疗阈值);

                // 这个技能自己的目标 —— 有人低于**它的**血线才算它够格
                var 候选目标 = HealTargetHelper.最低血量队友(本技血线, 30f);
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (候选目标 == null || !候选目标.对象有效()) continue;

                够格的.加(c);

                // 目标取"所有够格技能里最危险的那个"（和原来的语义一致：
                // 原来也是只治最危险的那个，只是血线来自大类）
                if (目标 == null || 候选目标.有效血量比例() < 目标.有效血量比例())
                    目标 = 候选目标;
            }

            // ⚠️ 一个都不够格 -> 不是 `return (null,null)`，而是**继续往下走**：
            //    下面有"候选集挑不出就退回 `_t.单体治疗GCD` 槽位"的兜底，
            //    那条兜底是"保证不会没人治"的保险，这里不能把它短路掉。
            if (目标 == null) 目标 = HealTargetHelper.最低血量队友(HealSettings.Instance.单体治疗阈值, 30f);
            if (目标 == null) return (null, null);

            // ── 缺口 / 命悬（给下面的"打分挑技能"和 Build 用）──
            var 缺口 = 缺口量(目标);
            var 命悬 = 目标.有效血量比例() <= HealSettings.Instance.紧急单奶阈值;

            // ── 同帧缓存 ──
            var 帧 = AEAssist.Helper.TimeHelper.Now() / 50;   // 50ms 一档
            if (帧 == _缓存帧 && 目标.GameObjectId == _缓存目标Id && _缓存技能 != null)
                return (目标, _缓存技能);

            // ══════════════════════════════════════════════════════════════
            //  ★ 修正：本 resolver 走 **GCD 槽**，必须排除 oGCD 能力技 ★
            //
            //  [!] 原来没有这个过滤 ⇒ 候选集里的 oGCD 单体能力技会被它选中
            //      并塞进 Gcd 槽，最严重的是**白魔 天赐祝福**
            //      （9999 恢复力、冷却 **180 秒**）——
            //      打分里 `GCD加分` 只看"冷却是否 > 0"，不区分 30 秒与 180 秒，
            //      于是缺口一大它就恒为最高分，**保命大被当常规治疗烧掉**。
            //
            //  [!] 加过滤之后这些能力技不会消失 —— 它们由各自的
            //      resolver 负责（`Res_InstantHealAbility` / `Res_HealEmergency`
            //      / 职业专属），那些 resolver 在队列里排得更靠前，
            //      而且带正确的资源/冷却闸门。
            // ══════════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★ 从【够格的技能】里选（不是全部候选）★
            //
            //  [!] 上面的筛选已经按"每个技能自己的血线"过了一遍；
            //      这里只负责**打分排序**，口径和别处完全一致（开发约定 F③）。
            //  [!] 一个都不够格时 `够格的` 是空的 -> `选最优` 返回 null ->
            //      走下面的兜底槽位（保证不会"没人治"）。
            // ══════════════════════════════════════════════════════════════
            var 技 = 治疗决策.选最优(
                够格的, 缺口, 命悬,
                移动中: SpellUtil.不能读条(),
                只群体: false,
                只瞬发: false,
                只要GCD: true);

            // ── 候选集为空 / 挑不出 → 退回旧槽位（保证不会"没人治"）──
            if (技 == null && _t.单体治疗GCD != 0)
            {
                _缓存帧 = 帧; _缓存目标Id = 目标.GameObjectId; _缓存技能 = null;
                return (目标, null);
            }

            _缓存帧 = 帧;
            _缓存目标Id = 目标.GameObjectId;
            _缓存技能 = 技;
            return (目标, 技);
        }
        catch
        {
            return (null, null);
        }
    }

    /// <summary>目标还差多少血（按**有效血量比例**算，把盾也算进去）</summary>
    private static float 缺口量(IBattleChara 目标)
    {
        // ★ 入口判有效性：参数是游戏对象，读它的属性会因【已释放对象】而
        //   触发原生访问违例（穿 catch / 无转储 / 进程直接没）。
        //   本项目 12 次崩溃全部是这一类 —— 不假设调用方判过。
        if (目标 == null || !目标.对象有效()) return 0f;
        try
        {
            var 上限 = 目标.MaxHp;
            if (上限 <= 0) return 0f;

            // ⚠️ 用 `有效血量比例`（含盾）而不是裸血量 ——
            //    已经套了盾的人"看起来血少"但实际不缺治疗。
            var 缺 = 上限 * (1f - 目标.有效血量比例());
            return MathF.Max(0f, 缺);
        }
        catch
        {
            return 0f;
        }
    }

    public void Build(Slot slot)
    {
        // ⚠️ 必须和 Check 用**同一套**决定逻辑（开发约定 F③）。
        //    这里调的是**同一个** `决定()`，且它内部有同帧缓存 ——
        //    所以两次调用拿到的一定是同一个技能。
        var (目标, 技) = 决定();
        if (目标 == null) return;

        if (技 != null)
        {
            slot.Add(new Spell(技.Id, 目标));
            return;
        }

        // 候选集挑不出 → 退回旧槽位（宁可放个弱治疗，也别不放）
        if (_t.单体治疗GCD != 0)
            slot.Add(new Spell(_t.单体治疗GCD, 目标));
    }
}

/// <summary>单体盾（预铺）：学者鼓舞 / 贤者均衡诊断。</summary>
public class Res_HealShield : ISlotResolver
{
    private readonly JobSpellTable _t;

    public Res_HealShield(JobSpellTable table) => _t = table;

    public int Check()
    {
        if (HealTargetHelper.木桩模式) return -300;
        if (!HealQt.GetQt("奶人")) return -100;
        if (_t.单体盾 == 0) return -102;
        if (!SpellUtil.已解锁(_t.单体盾)) return -2;

        var 该铺 = 减伤Helper.即将来大伤害();
        var 坦克 = 选目标(该铺);
        if (坦克 == null) return -1;

        // ⚠️ **盾的剩余时间**判断：鼓舞的盾有 30 秒，快过期的盾等于没有。
        //
        //    原来只判"有没有 buff"，于是盾快断了也不补（等它真断才反应，已经晚了）。
        //    现在改成：**剩下的盾撑不过 5 秒，就当没有**。
        //
        //    📌 注：这段注释原来写着"参考同类 ACR 的 Scholar_SingleGCDHeal：
        //       它判的是 buff 时间小于或不存在" —— **那个归因是错的，已删**。
        //       对照分析逐行读过它的 IL：它对盾**只判有没有**（`!HasAura(297)`），
        //       那个"3 秒剩余窗口"是用在 `DeadBuffs`（死亡类 debuff）上的。
        //       按 开发约定.md ⑧：**错误归因的注释比没有注释更危险** ——
        //       它会让人以为"对方也这么做"，从而不敢改、或照着错的抄。
        //       结论不变（剩余时间判断是对的，而且三家只有我们做了），
        //       但理由是"我们自己的判断"，不是"跟对方学的"。
        //
        //    ⚠️ 再加上本地施放记录（官方文档 L129：服务器状态是滞后的）：
        //       刚放完盾的那 0.x 秒里，内存里还看不到盾 buff ——
        //       光看服务器状态会**又放一次**。本地记录不滞后，能盖住这个空窗。
        if (本地施放记录.刚放过(_t.单体盾)) return -3;

        // ★ 已有任何「预铺」就跳过 —— 不只查单体盾自己 ★
        //   [!] 修的正是用户报的「T 身上有绿帽还读单盾，完全是浪费」。
        if (HealTargetHelper.已有预铺(坦克)) return -3;
        
        if (坦克.有该技能的Buff(_t.单体盾) && 坦克.我的Buff还剩超过N秒(AuraIds.技能转Buff(_t.单体盾), 5f))
        {
            return -3;
        }

        // ⚠️ **移动守卫**：护盾 GCD 基本都读条
        //    （学者鼓舞激励之策 2 秒读条；贤者诊断是瞬发，这条对它自动放行）。
        //
        //    审计发现这里**漏了**这一行 —— 同文件的 Res_HealAoEGcd 和
        //    Res_HealSingleGcd 都加了，只有单体盾漏掉。
        //    后果：学者移动中反复把读条盾塞进 slot、被中断、再塞
        //    （正是 `SpellUtil.移动中能放` 那段注释里记的问题）。
        if (!SpellUtil.移动中可用(_t.单体盾)) return -7;

        // ⚠️ **护盾前置（贤者「均衡」）也必须在这里判**（审计发现）——
        //    原来只有 Build 里无条件加它，Check 里完全没有这一句。
        //    ⇒ 均衡在 CD 时 Build 照样把它塞进 slot 第一个位置，
        //      那个动作无效，而且盾**可能因此根本出不来**
        //      （贤者靠盾吃饭；`SGE_Dot` 注释也写过"同一帧按完均衡
        //        就立刻放均衡诊断是放不出来的"）。
        if (_t.护盾前置 != 0 && !JobApiHelper.均衡中 && !SpellUtil.可用(_t.护盾前置))
        {
            return -1;
        }

        return SpellUtil.可用(_t.单体盾) ? 3 : -1;
    }

    /// <summary>
    /// 选盾的目标。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 修正说明（与 Res_SingleHoT 同一类问题）★
    ///
    ///  原来**只给坦克**：
    // ══════════════════════════════════════════════════════════════
    //  ★ 盾的门槛**必须跟着 `单体治疗阈值` 一起动** ★
    //
    //  [!] 原来写死 `该铺 ? 1f : 0.7f` —— 于是：
    //      · AI 切保守/激进改的是 `单体治疗阈值`，**对盾完全无效**
    //      · 而 `Res_HealShield` 排在 `Res_HealSingleGcd` **之后**（同队列），
    //        坦克在 52%~70% 时：评分那条说不用治、盾这条说该铺，
    //        **同一个问题两条路给相反答案** ==> 表现就是日志里
    //        「医术与鼓舞交替出现」，看着自相矛盾。
    //
    //  [!] 为什么盾的门槛**可以**比治疗高：
    //      盾要**伤害落地前**铺才有价值，比治疗更主动是应该的。
    //      但不能是写死的 0.7 或任何血量的坦克 —— 那等于盾不受策略控制。
    //
    //  [!] 所以：治疗阈值 + **固定提前量**，并夹在与 `AiThresholdAdapter`
    //      相同的 [0.30, 0.95] 区间里。这样 AI 的策略对盾也生效。
    ///      if (坦克 == null) return -1;        // ← 没坦克就整个不触发
    ///
    ///  但 `_t.单体盾` 配的是：
    ///      · 学者 → **鼓舞激励之策**（学者核心单盾）
    ///      · 贤者 → **诊断**
    ///  这两个技能在游戏里都是给**任何要挨打的人**的，不是坦克专属。
    ///  于是没坦克的场景（单人 / 特殊内容）**学者核心单盾永远不放** ——
    ///  静默失效，不报错。
    ///
    ///  ── 为什么这个"坦克替身"写法反复出问题 ──
    ///    上面那条盾判断的注释里已经记过一次：
    ///    "曾经写成'血量最低的坦克有盾 -> return -3'，那是个真 bug"。
    ///    同一个思路（拿坦克当全队的替身）错了两次，所以这次彻底按
    ///    "**先坦克、后其他人**"的两层来写，而不是只留坦克。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private IBattleChara? 选目标(bool 该铺)
    {
        try
        {
            // ── ① 坦克优先（盾给坦克收益最稳）──
            // ══════════════════════════════════════════════════════════════
            //  ★ 盾线**必须跟着 `单体治疗阈值` 一起动**（不是写死的 0.7）★
            //
            //  [!] 原来写死 `该铺 ? 1f : 0.7f`，而 `Res_HealShield` 排在
            //      `Res_HealSingleGcd` **之后**（学者队列 L604 -> L605）：
            //        坦克 52%~70% 时 —— 评分那条说不用治、盾这条说该铺，
            //        **同一个问题两条路给相反答案**。
            //        表现就是用户日志里「医术与鼓舞交替出现」，看着自相矛盾。
            //
            //  [!] 为什么盾线**可以**比治疗线高：
            //      盾要在**伤害落地前**铺才有价值，比治疗主动是应该的。
            //      但不能写死 —— 那等于 **AI 的保守/激进对盾完全失效**
            //      （AI 改的是 `单体治疗阈值`）。
            //
            //  [!] 所以：治疗阈值 + 固定提前量，夹在与 `AiThresholdAdapter`
            //      相同的 [0.30, 0.95] 区间 —— AI 的策略对盾也生效。
            // ══════════════════════════════════════════════════════════════
            // 盾相对治疗阈值的**提前量**：盾要比奶早一档铺
            const float 盾提前量 = 0.15f;

            // ══════════════════════════════════════════════════════════════
            //  ★★ 盾线改成**按技能查表** —— 顺带修一个真 bug ★★
            //
            //  [!] 修的 bug（用户报的「T 身上血很多还读单盾，完全是浪费」）：
            //      坦克那条路**无条件返回主坦**（见下面 `if (坦克 != null) return 坦克;`），
            //      **盾线根本没参与判断** —— 它只在"非坦克"那条路用了。
            //      ==> 只要坦克身上没有盾/绿帽 buff，**满血也会被铺盾**。
            //
            //  [!] 对比参考实现（IL 实证）：两套的盾都是**按血线选人**的：
            //        shiyuvi `Scholar_SingleGCDHeal` / `TankSingleShield`：
            //                `hp + shield/100 <= Adloquium(0.4)` 才计数
            //        youshu  `鼓舞激励之策`：`ShieldTarget == null -> -6`，
            //                选区走 `单盾阈值`(45) / `TankAdloquium`
            //      ==> 参考实现里**没有"坦克无条件铺盾"这回事**。
            //
            //  [!] 为什么用 `治疗阈值表`：
            //      单盾的门槛在参考里也是**每技能一个**（白魔 水流幕 70 / 学者 鼓舞 45），
            //      而共享 resolver 拿到的是 `_t.单体盾` —— 正好是查表的 key。
            //      查不到才回落到原来的 `单体治疗阈值 + 盾提前量`（行为不变）。
            //
            //  [!] `该铺`（即将来大伤害）**保持无条件** —— 那是强判据，
            //      同 `Res_Mitigation` 的语义，不该被血线挡住。
            // ══════════════════════════════════════════════════════════════
            var 盾线 = 该铺
                ? 1f      // 明确的即将来伤害：任何血线都该铺（强判据，同 `Res_Mitigation`）
                : Math.Clamp(治疗阈值表.取(_t.单体盾,
                        HealSettings.Instance.单体治疗阈值 + 盾提前量), 0.30f, 0.95f);

            var 坦克 = HealTargetHelper.主坦();
            if (坦克 != null)
            {
                // ★ 坦克也要过血线（或"伤害要来"）—— 这是本次修的核心 ★
                //   用 `有效血量比例()`（含盾），与参考的 `hp + shield/100` 同口径。
                if (该铺 || 坦克.有效血量比例() <= 盾线) return 坦克;

                // 坦克还没到线 -> **不能直接返回 null**，继续往下看有没有别人需要
                //   （原来的代码在这里是 `return 坦克`，等于跳过了 ② 那一层）
            }

            // ── ② 没有坦克 / 坦克不需要 → 给血线最低的那个人 ──
            //
            //   ⚠️ 这一层原来缺了。没它的话，学者在无坦克场景下
            //      **一次鼓舞都放不出来**。
            var 阈值 = 该铺 ? 0.95f : 盾线;   // 同一套语义（见上）
            var 队友 = HealTargetHelper.最低血量队友(阈值);

            if (队友 != null && 队友.GameObjectId != CharacterExt.我的ObjectId() && 队友.可以治())
                return 队友;

            return null;
        }
        catch
        {
            return null;
        }
    }

    public void Build(Slot slot)
    {
        var 该铺 = 减伤Helper.即将来大伤害();

        // ⚠️ **必须和 Check 同源**（开发约定 F③）：判谁就放谁，
        //    否则会出现"Check 说该给 A 放盾，Build 却给了 B"。
        var 目标 = 选目标(该铺);
        if (目标 == null) return;

        if (_t.护盾前置 != 0 && !JobApiHelper.均衡中 && SpellUtil.可用(_t.护盾前置))
        {
            var pre = SpellUtil.Get(_t.护盾前置);
            if (pre != null) slot.Add(pre);
        }

        // 用当前形态：贤者的"诊断"在均衡状态下会变成"均衡诊断"
        var 盾 = SpellUtil.当前形态(_t.单体盾);
        if (盾 == null) return;
        slot.Add(new Spell(盾.Id, 目标));
    }
