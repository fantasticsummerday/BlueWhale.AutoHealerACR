"""
估算 AI 局面报告里**每一段占多少字符** —— 压缩前先量，别凭感觉改。

原理：
  `AiSituation.采集()` 各段是顺序 AppendLine 的。
  我用逐段**扫描源码**的方式，把他们写入的**固定文本**累加起来，
  再加上"每条数据"的估算成本（队友数 / 技能数 / 机制数）。

[!] 这是**估算**，不是精确运行时测量 —— 目的是找出"哪一段是大头"，
   以及"压缩哪一段收益最大"。偏差不影响排序结论。

用法：
    python tools/PromptBudget.py
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "BlueWhale.AutoHealerACR"

# 各段的采集方法（按 采集() 里的真实顺序）
采集顺序 = [
    ("采副本", "副本"),
    ("采自己", "我"),
    ("采资源", "职业资源"),
    ("采队友", "队伍"),
    ("采必须奶满", "必须奶满机制"),      # 外部：HealerACR/Common/必须奶满.cs
    ("采敌人", "敌人"),
    ("采坦克压力", "坦克压力"),          # 外部：BlueWhale/坦克压力.cs
    ("采可选技能", "可选技能"),
    ("采时间轴", "副本与机制时间轴"),
    ("采记忆库", "记忆库"),              # 外部：记忆库.取相关记忆
]

最大长度 = 6000


def 提取方法体(text: str, 名: str):
    """粗略取出一个方法体的文本"""
    m = re.search(rf"private static void {re.escape(名)}\(StringBuilder sb\)\s*\{{", text)
    if not m:
        return ""
    # 花括号配平
    i = m.end() - 1
    depth = 0
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[m.end():i]
        i += 1
    return text[m.end():]


def 字面量总长(体: str):
    """方法里所有双引号字面量的总长度（含插值串的静态部分）"""
    total = 0
    字面量 = []
    for m in re.finditer(r'\$?"((?:[^"\\]|\\.)*)"', 体):
        s = m.group(1)
        # 去掉插值表达式 {xxx} 的内容（那是数据，不是固定文本）
        s2 = re.sub(r"\{[^}]*\}", "", s)
        total += len(s2)
        if s2.strip():
            字面量.append(s2)
    return total, 字面量


def main():
    text = (SRC / "AiSituation.cs").read_text(encoding="utf-8")

    print("=" * 66)
    print("  AI 局面报告 —— 各段字符预算估算")
    print("=" * 66)
    print()

    总固定 = 0
    明细 = []

    for 方法, 段名 in 采集顺序:
        体 = 提取方法体(text, 方法)
        if not 体:
            明细.append((段名, -1, "（方法体没找到）"))
            continue
        固定, _ = 字面量总长(体)
        总固定 += 固定
        明细.append((段名, 固定, ""))

    print(f"{'段名':<20} {'固定文本':>10}   说明")
    print("-" * 66)

    先 = True
    for 段名, 固定, 备注 in 明细:
        if 段名 == "可选技能" and 先:
            print("-" * 66)
            先 = False
        if 固定 < 0:
            print(f"{段名:<20} {'?':>10}   {备注}")
        else:
            print(f"{段名:<20} {固定:>10}   {备注}")

    print("-" * 66)
    print(f"{'固定文本小计':<20} {总固定:>10}")
    print()

    # ── 动态部分估算 ──
    print("=" * 66)
    print("  动态部分（随局面变化）")
    print("=" * 66)
    print()

    # [!] 「技能类别说明」的条数和长度**从源码量**，不要硬编码。
    #    第一版我写死了 `14 条 × 42`，结果压缩之后工具完全没反映出来
    #    （还显示 588），等于这个工具在骗自己。
    #    凡是能自动量的就别写死。
    说明体 = 提取方法体(text, "采技能效果说明")
    _, 说明行 = 字面量总长(说明体)
    # 第一条是段标题，不算内容行
    说明内容行 = [s for s in 说明行 if s.strip() and not s.startswith("【")]
    说明单条 = int(sum(len(s) for s in 说明内容行) / max(1, len(说明内容行)))
    说明小计 = sum(len(s) for s in 说明内容行)
    说明条数 = len(说明内容行)

    估算 = [
        ("我身上的状态", 12, 14, "最多 12 个，每个约「天辉 22s、」≈14 字符"),
        ("队友", 4, 26, "4 人本每行约「名字 XX% 状态」≈26 字符"),
        ("队友汇总行", 3, 22, "固定几行"),
        # 技能清单：单条长度也用实测值（压缩前是 62）
        ("可选技能", 25, 48, "每个约「16534 = 医济（群体治疗） CD3.2 读条2.0 蓝1000」"),
        ("技能类别说明", 说明条数, 说明单条, f"从源码量：{说明条数} 行 / 平均 {说明单条} 字符"),
        ("其他敌人", 6, 40, "每个约「腐朽兵：88%（12m）  [**没有我的DoT**]」"),
        ("机制预告", 8, 30, "每条约「  16.1s 后   Skyruin (fire phase)  ← 大伤害，考虑预铺」"),
        ("记忆库", 3, 300, "已加硬上限：单条 500 / 整段 900 字符"),
    ]

    print(f"{'动态来源':<18} {'条数':>6} {'单条':>6} {'小计':>8}")
    print("-" * 66)
    动态总 = 0
    for 名, 条数, 单条, 说明 in 估算:
        # 技能类别说明的"小计"用实测总和，不是乘法
        小计 = 说明小计 if 名 == "技能类别说明" else 条数 * 单条
        动态总 += 小计
        print(f"{名:<18} {条数:>6} {单条:>6} {小计:>8}   {说明}")

    print("-" * 66)
    print(f"{'动态小计':<18} {'':>6} {'':>6} {动态总:>8}")
    print()

    # 记忆库的实际上限（硬约束，比估算更可信）
    print(f"  注：记忆库整段硬上限 900 字符（见 记忆库.取相关记忆）——")
    print(f"      上面按 3×300=900 估，**正好是上限**，不会更多。")
    print()

    合计 = 总固定 + 动态总
    print("=" * 66)
    print(f"  估算总计：{合计} 字符   （上限 {最大长度}）")
    占比 = 合计 * 100 // 最大长度
    print(f"  占用率：  {占比}%")
    print("=" * 66)
    print()

    if 合计 > 最大长度:
        print("[!] 已经超限 —— 会触发截断（先丢记忆库 → 机制预告 → 坦克压力 → 敌人）")
    else:
        print(f"[OK] 还有 {最大长度 - 合计} 字符余量")
    print()

    print("=== 已做的压缩（记录在这，避免以后重复劳动）===")
    已做 = [
        ("技能类别说明", "588 → 332", "14 行 → 8 行；只留 AI 猜不到的反直觉要点，删掉常识"),
        ("可选技能", "1550 → 1200", "`CD剩余`→`CD`、`蓝耗`→`蓝`；射程只在 ≤15m 时给"),
        ("记忆库", "1200 → 900 硬上限", "单条 500 / 整段 900；超出截断并标注"),
    ]
    for 名, 量, 做法 in 已做:
        print(f"  {名:<14} {量:<18} {做法}")
    print()

    print("=== 还能再压的（按收益排序，需要时再做）===")
    可压 = [
        ("可选技能", 25 * 48, "只列**当前局面用得上**的类别（比如满血时不列治疗技能）"),
        ("记忆库", 900, "整段上限可降到 600；或改成\"只给最近一条\""),
        ("技能类别说明", 332, "整个搬到**初始化**里发一次（但 AI 跨轮可能忘）"),
        ("其他敌人", 6 * 40, "6 → 4 条"),
        ("机制预告", 8 * 30, "8 → 6 条；或窗口 20 秒 → 15 秒"),
        ("我身上的状态", 12 * 14, "12 → 8 个"),
    ]
    可压.sort(key=lambda x: -x[1])
    for 名, 量, 建议 in 可压:
        print(f"  {量:>5} 字符  {名:<14} {建议}")
    print()
    print("[!] 压缩原则：**先压静态，再压增强，最后才压当前事实**。")
    print("   静态段（技能类别说明）每轮一样，压它信息损失最小；")
    print("   当前事实段（血量/状态/必须奶满）压了会直接导致误判。")

    return 0


if __name__ == "__main__":
    sys.exit(main())
