def 提取方法体(text: str, 名: str):
    """粗略取出一个方法体的文本"""
    m = re.search(rf"private static void {re.escape(名)}\(StringBuilder sb\)\s*\{{", text)
    if not m:
        return ""
    # 花括号配平
    i = m.end() - 1
    depth = 0
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[m.end():i]
        i += 1
    return text[m.end():]


def 字面量总长(体: str):
    """方法里所有双引号字面量的总长度（含插值串的静态部分）"""
    total = 0
    字面量 = []
    for m in re.finditer(r'\$?"((?:[^"\\]|\\.)*)"', 体):
        s = m.group(1)
        # 去掉插值表达式 {xxx} 的内容（那是数据，不是固定文本）
        s2 = re.sub(r"\{[^}]*\}", "", s)
        total += len(s2)
        if s2.strip():
            字面量.append(s2)
    return total, 字面量


