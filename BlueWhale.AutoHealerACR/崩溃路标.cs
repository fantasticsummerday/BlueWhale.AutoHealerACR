using AEAssist.Helper;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// 崩溃路标 —— 用来定位"加载 ACR 后进程被杀、且不留任何痕迹"的崩溃。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么需要它（连续 5 次崩溃的排查结论）★
///
///  [!] 现象（用户实测，日志 `Log-3527802.log` 等）：
///        最后一条日志是「重建 AI 上下文」那一行，之后进程就没了，而：
///          · 没有转储、没有 .NET Runtime 事件
///          · 崩溃处理器报 `error 0x6d`（读不到异常信息）后直接杀进程
///          · **全局异常钩子（含 FirstChance 访问违例）一次都没触发**
///        ==> 不是托管异常，也不是托管层可见的访问违例 → **原生层崩**。
///
///  [!] 静态排查已排除（每一项都有检查记录，见 `tools/崩溃防护检查.py`）：
///        同步 HTTP / `Thread.Sleep` / ImGui Begin-End 不配对 /
///        逐击键写盘 / 反射重载歧义 / 时间轴重扫 / 时间轴跳转死循环 /
///        `async void` / 无界循环 / 设置面板绘制路径（路标证明没走到）
///
///  [!] 所以唯一的路是**把每一小步编号**，崩了看最后那个号。
///
///  ══════════════════════════════════════════════════════════════
///  [!] 号段约定
///  ══════════════════════════════════════════════════════════════
///    0-15   设置面板绘制（见 `HealerEntryBase.面板路标`）
///    20     进本识别回调 进入
///    21     识别摘要 完成
///    22     重建横幅 完成
///    23     Ai初始化.重置() 完成
///    24     Ai初始化.开始() 完成 —— 回调即将返回
///    30     AI 跑一次() 进入
///    31     AI 跑一次() 进入重试循环
///    32     AI 单次尝试() 进入
///    33     局面采集 完成 —— 即将发 HTTP
///    34     AI 单次尝试() HTTP 已返回
///  ══════════════════════════════════════════════════════════════
///
///  [!] **限流规则**（很重要 —— 本项目已栽过两次刷屏）：
///        · 号**变了** → 立刻打（一次不丢）
///        · 号**没变** → 最多 1 秒 1 条
///      这样即使某处在循环里狂调，也不会把日志刷爆，
///      而"最后走到哪一号"这个关键信息永远保留。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 崩溃路标
{
    private static int _上次号 = -1;
    private static long _上次毫秒;
    private static long _累计;

    /// <summary>打一个路标。号变了立刻打；号没变最多 1 秒 1 条。</summary>
    public static void 记(int 号, string 说明)
    {
        try
        {
            _累计++;
            var 现在 = TimeHelper.Now();

            // 号变了 → 立刻打（关键的"走到哪了"信息）
            if (号 != _上次号)
            {
                _上次号 = 号;
                _上次毫秒 = 现在;
                LogHelper.Info($"[BlueWhale.路标] {号}（{说明}）｜累计 {_累计} 次");
                return;
            }

            // 号没变 → 1 秒 1 条（防刷屏）
            if (现在 - _上次毫秒 < 1000) return;
            _上次毫秒 = 现在;
            LogHelper.Info($"[BlueWhale.路标] {号}（{说明}）· 重复 ｜累计 {_累计} 次");
        }
        catch { }
    }
}
