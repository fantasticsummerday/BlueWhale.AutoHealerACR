using System;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// **调试窗驱动** —— 每帧把 `调试窗.画(启用, ACR在用)` **在本程序集内部直接调一次**。
///
/// ══════════════════════════════════════════════════════════════════════════
///  [!] 为什么需要这个类（2026-10-06 的架构级修法）
///
///      旧架构：**入口侧**（`HealerEntryBase.画AI层调试窗`）反射找
///              `BlueWhale.AutoHealerACR.调试窗.画(bool,bool)`，
///              把 `Delegate` 缓存进静态字段，每帧调用。
///
///      真因：那个缓存的委托**指向"上一次加载的程序集"里的类型** ——
///            ACR 重载时旧程序集不会被卸载（`UiBuilder.Draw` 的订阅、
///            各种静态引用都留着），于是：
///              · 委托照常**返回**（所以 catch 里一条异常都没有）
///              · 方法体**不执行**（所以窗口侧一行诊断都没有）
///              · 用户看到的是「开关勾着，窗口就是不出现」
///
///      用户原话（这是本类存在的理由）：
///        「调试窗开关还是没用」「我点 x 关闭调试窗之后设置里面的开关就失效了」
///
///  [!] ✅ 修法：**让调用发生在同一程序集内部**。
///        · 入口侧只写**纯数据**（`HealerACR.Common.调试窗请求`）
///        · 本类（BlueWhale 侧）每帧读那份数据，然后**直接**调 `调试窗.画(...)`
///      ==> 本类与 `调试窗` 都在 BlueWhale.dll 里，是编译期就确定的直接调用，
///          **一个反射都没有** ⇒ 不可能指向旧程序集。
///
///  [!] 为什么本类成立（**不要想当然，这是有实测依据的**）：
///        `HealerACR.dll` **从来不部署** —— 部署目录里只有 BlueWhale.dll
///        （见 `BlueWhale.AutoHealerACR.csproj` 里那段"两份静态状态呢？"）。
///        而 BlueWhale.dll 编译了 HealerACR 的源码
///        ⇒ 入口侧（写请求）与窗口侧（读请求）在**同一个程序集**里
///        ⇒ 读的是**同一份 static**。
///
///  [!] 谁调本类：
///        `HealerACR.Common.独立设置窗.每帧画()`（Dalamud 的 `UiBuilder.Draw` 驱动）。
///        那一句在 `#if !HEALERACR_STANDALONE` 里 —— 也就是**只编进 BlueWhale.dll**。
///        HealerACR 独立编译时那一句不存在（那边本来也没有调试窗）。
/// ══════════════════════════════════════════════════════════════════════════
/// </summary>
public static class 调试窗驱动
{
    /// <summary>连续失败几次就冷却（防止每帧抛异常把渲染线程拖死）。</summary>
    private const int 失败上限 = 5;

    /// <summary>冷却多久（毫秒）。</summary>
    /// <remarks>
    /// [!] 原来是**永久**跳过（自锁：计数器只在成功后清零，而失败之后永远没有成功）
    ///     ⇒ 用户唯一的出路是重启游戏。改成"冷却 30 秒再试"既能防每帧抛，又不会自锁。
    /// </remarks>
    private const long 冷却毫秒 = 30_000;

    private static int _连续失败;
    private static long _冷却起点毫秒;

    /// <summary>
    /// **每帧调一次** —— 把请求数据交给窗口侧，并做失败自禁用（带冷却）。
    ///
    /// [!] 每帧**必须**调到：常驻悬浮窗少提交一帧，它在那一帧就"不存在"
    ///     （那就是用户看到的"闪"）。所以这里**不设任何节流门**。
    /// </summary>
    public static void 每帧画()
    {
        try
        {
            var 现在 = Environment.TickCount64;

            // ── 失败冷却（不是自锁：30 秒后一定重试）──────────────────────
            if (_连续失败 >= 失败上限)
            {
                if (现在 - _冷却起点毫秒 < 冷却毫秒)
                {
                    调试窗请求.记失败(_连续失败, true);
                    调试窗调用链.记(
                        $"【窗口侧】被『失败自禁用』冷却挡住：连续失败 {_连续失败} 次，" +
                        $"还要 {(_冷却起点毫秒 + 冷却毫秒 - 现在) / 1000} 秒" +
                        $" ｜副本={调试窗调用链.副本号}");
                    return;
                }

                _连续失败 = 0;
                调试窗请求.记失败(0, false);
                try { LogHelper.Info("[BlueWhale] 调试窗连续失败冷却已过，重新尝试绘制"); }
                catch { }
            }

            调试窗请求.记驱动();

            // ══════════════════════════════════════════════════════════════
            //  ★★★ **同程序集直接调用** —— 全工程唯一一处画调试窗的地方 ★★★
            //
            //  [!] 两个参数都是**入口侧算好的结论**（读自 `调试窗请求`：
            //      · `启用`    = 用户在设置里勾的那个开关
            //      · `ACR在用` = 入口侧判的"框架当前跑的是不是我们"
            //      窗口侧**不做任何跨程序集判断** —— 那是 0.6.5.1 失败的根因。
            // ══════════════════════════════════════════════════════════════
            调试窗.画(调试窗请求.启用, 调试窗请求.ACR在用);

            // 成功一次就清零（偶发失败不算）
            if (_连续失败 != 0)
            {
                _连续失败 = 0;
                调试窗请求.记失败(0, false);
            }
        }
        catch (Exception e)
        {
            _连续失败++;
            调试窗请求.记失败(_连续失败, _连续失败 >= 失败上限);

            // [!] 只在第一次和进入冷却时写日志 —— 绘制期异常是每帧都抛的，
            //     不能每帧打一条（会刷爆宿主日志）。
            if (_连续失败 == 1)
            {
                try
                {
                    LogHelper.Error("[BlueWhale] 调试窗绘制异常：" + e.Message + "\n" + e.StackTrace);
                }
                catch { }
            }

            if (_连续失败 >= 失败上限)
            {
                _冷却起点毫秒 = Environment.TickCount64;
                try
                {
                    LogHelper.Error($"[BlueWhale] 调试窗连续失败 {失败上限} 次，" +
                                    $"已进入 30 秒冷却（**不会关闭开关**；冷却过后自动重试）");
                }
                catch { }
            }

            调试窗调用链.记(
                $"【窗口侧】驱动抛异常 第{_连续失败}次：{e.GetType().Name} {e.Message}" +
                $" ｜副本={调试窗调用链.副本号}");
        }
    }

    /// <summary>
    /// **复位失败计数与冷却** —— 用户在设置里把开关重新勾上时调
    /// （由 `HealerEntryBase` 那条勾选分支转发过来）。
    /// </summary>
    public static void 复位失败计数()
    {
        _连续失败 = 0;
        _冷却起点毫秒 = 0;
        调试窗请求.复位诊断();
    }
}
