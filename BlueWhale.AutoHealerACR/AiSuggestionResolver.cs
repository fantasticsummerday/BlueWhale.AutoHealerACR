        }
    }

    /// <summary>
    /// **统一收尾** —— 技能真的进了 slot 之后必须走这里。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  [!] 为什么要抽出来（第二轮审阅第 8 条）：
    ///      `Build()` 里有**多条成功路径**（显式目标 / 类别推断 / 完全采信兜底…），
    ///      原来只有最后一条走了收尾，其它路径直接 `return` 就出去了。
    ///
    ///      最严重的是漏掉 `AiDecisionLayer.消费()` ——
    ///      它才是**推进队列**的那一步。漏了就会：
    ///          AI 说放 C1 -> 放出去 -> 队列没推进
    ///          -> 下一帧队首还是 C1 -> 又放 -> **无限重复同一个技能**
    ///
    ///  [!] 所以：**任何"技能已进 slot"的路径都必须调它**，
    ///      不要再在 `Build()` 里写"加完 slot 就 return"。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// **统一收尾** —— 技能真的进了 slot 之后必须走这里。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] **本方法无条件消费**（外部审查 P0-4，我核实确认为真）
    ///
    ///      原来的第一行是：
    ///          if (施法目标 == null || !施法目标.对象有效()) return;
    ///      而本方法是在 `slot.Add()` **之后**被调的
    ///      ==> 目标若在这一瞬间失效，就直接 return
    ///      ==> **`AiDecisionLayer.消费()` 没执行**
    ///      ==> 但框架这一帧**仍然会执行那个 Spell**（它已在 Slot 里）
    ///      ==> 后果：**建议没被消费** ⇒ 下一帧还在队列里 ⇒ 重复建议
    ///
    ///  [!] 原则（报告原话）：
    ///        **一旦 `slot.Add()` 成功，就把该建议标记为 Consume。**
    ///      "目标有效性"是**执行前**该检查的东西 ——
    ///      它们已经在 `slot.Add()` 之前检查过了（见本文件各调用点）。
    ///      放到这里等于"事后反悔"，而事已经做了。
    ///
    ///  [!] 另一处同样的问题：原来读 `施法目标.Name` 拼日志 ——
    ///      那是 **live 游戏对象属性**，在"目标可能刚好失效"的时刻读它
    ///      正是本项目的崩溃路径。改成**从建议里取名字**（纯托管数据）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <param name="是Dot">是不是 DoT 技能（决定要不要记一次施放）</param>
    /// <param name="施法目标">本次施法的目标（**可以为 null / 已失效** —— 见说明）</param>
    private static void 收尾(bool 是Dot, IBattleChara? 施法目标)
    {
        try
        {
            // ══════════════════════════════════════════════════════════════
            //  ★ 先**尽力**取目标信息，失败了也不影响"消费" ★
            //
            //  [!] 这两步各自包 try 且**都不 return** ——
            //      目标失效是"日志少一行名字"的事，不是"不消费"的理由。
            //      （`对象有效()` 本身已是安全判据，读 `Name` 前必判它。）
            // ══════════════════════════════════════════════════════════════
            var 目标名 = "已失效";
            var 目标Id = 0ul;
            try
            {
                if (施法目标 != null && 施法目标.对象有效())
                {
                    目标名 = 施法目标.Name.ToString();   // Name 是 SeString，要 ToString（工程统一写法）
                    目标Id = 施法目标.GameObjectId;
                }
            }
            catch { }

            var 建议 = AiDecisionLayer.当前建议;
            if (建议 != null)
            {
                Ai调试.日志($"采纳建议：{建议.技能Id} = {SpellIds.反查(建议.技能Id)}（{建议.理由}）" +
                             $"｜目标 {目标名}" +
                             $"｜出生排队第 {建议.出生时队列位置 + 1} 位 / 批次 {建议.批次}" +
                             $" / 等了 {建议.已等毫秒}ms");
            }

            // DoT 记账：**即使读不到对象名也要记保险丝**
            //   （`已知Id=0` 时它只记全局时间戳 —— 那才是保险丝主体）
            if (是Dot) Dot补判.记一次施放(目标Id);

            // ★★ **无条件消费** —— Spell 已经进 Slot，这条建议就是"已采纳" ★★
            //    [!] 这一行原来被上面的 `if (!对象有效()) return;` 挡掉了：
            //        目标刚好失效 => 不消费 => 下一帧重复建议。
            AiDecisionLayer.消费();
        }
        catch (Exception e)
        {
            Ai调试.日志("收尾失败（已忽略）：" + e.Message);
        }
    }

    /// <summary>
    /// **按 id 找一个活着的目标**（队友或敌人）。
    ///
    /// [!] 只返回**还活着**的 —— 调用方靠"返回 null"判断"候选目标已失效"。
    ///     这是"不再偷偷换目标"的基础（本轮审阅第 13 条）：
    ///     AI 选的是"治疗坦克"这个具体行为，目标死了就该**拒绝**，
    ///     而不是改成治别人（那是执行了一个 AI 没选过的动作）。
    /// </summary>
    private static IBattleChara? 找目标(ulong id, 候选集.目标模式 模式)
    {
        if (id == 0) return null;

        try
        {
            if (模式 == 候选集.目标模式.敌人)
            {
                foreach (var e in Data.AllHostileTargets)
                {
                    try
                    {
                        if (e != null && e.GameObjectId == id && e.活着()) return e;
                    }
                    catch { }
                }
                return null;
            }

            // 队友（含自己 —— 复活是唯一会找"倒地的"，那由 待复活队友 处理）
            foreach (var r in HealTargetHelper.可治疗队友(50f))
            {
                try
                {
                    if (r != null && r.GameObjectId == id && r.活着()) return r;
                }
                catch { }
            }
        }
        catch { }

        return null;
    }

