    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static bool 在技能表里(uint id)
    {
        if (id == 0) return false;
        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return false;
    
            // 单个槽位
            if (id == 表.基础输出 || id == 表.群体输出 || id == 表.Dot技能) return true;
            if (id == 表.单体治疗GCD || id == 表.群体治疗GCD) return true;
            if (id == 表.紧急单奶 || id == 表.群体治疗能力技) return true;
            if (id == 表.单体HoT || id == 表.单体盾 || id == 表.群体盾) return true;
            if (id == 表.护盾前置 || id == 表.团队减伤 || id == 表.个人减伤) return true;
            if (id == 表.复活 || id == 表.驱散 || id == 表.醒梦) return true;
            if (id == 表.预铺单奶能力技 || id == 表.瞬发单奶能力技) return true;
            if (id == 表.移动填充技 || id == 表.站定填充技 || id == 表.近战填充技) return true;
            if (id == 表.药尾声填充技 || id == 表.召唤宠物) return true;
    
            // 数组槽位
            foreach (var x in 表.输出能力技 ?? Array.Empty<uint>()) if (x == id) return true;
            foreach (var x in 表.脱战准备技能 ?? Array.Empty<uint>()) if (x == id) return true;
            foreach (var x in 表.自身AOE候选 ?? Array.Empty<uint>()) if (x == id) return true;
    
            // 治疗候选池（里面有些技能不在任何槽位上）
            foreach (var h in 表.治疗候选.全部)
                if (h != null && h.Id == id) return true;
        }
        catch { }
        return false;
    }
    
