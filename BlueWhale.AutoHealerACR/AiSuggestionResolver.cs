using AEAssist;
using AEAssist.CombatRoutine;
using AEAssist.CombatRoutine.Module;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// AI 建议执行器 —— **AI 给建议，原有逻辑终审。**
///
/// ═══ 这是整个阶段 B 的安全设计核心 ═══
///
/// AI 的建议**不是命令**，只是一个"插队申请"：
///   1. 它把建议的技能提到队列最前面（最高优先级）
///   2. 但**仍然要过一遍原来的可用性判断**（已解锁 / 可用 / 有目标）
///   3. 任何一项不满足 → 直接放弃，让原来的队列照常跑
///
/// **为什么必须这样**：
///   白名单只能挡住"清单外的 ID"，挡不住"清单内但用错场景"的。
///   比如 AI 建议"以太超流"，ID 完全合法，但**以太已经满了** ——
///   这时候白名单是拦不住的，必须靠原有的 Check 条件。
///
/// **所以 AI 永远不是唯一决策源，它只是"提前插一句嘴"。**
/// </summary>
public class AiSuggestionResolver : ISlotResolver
{
    /// <summary>本帧是否采纳了 AI 建议（给调试面板看）</summary>
    public static bool 本帧采纳 { get; private set; }

    public static uint 本帧技能 { get; private set; }

    /// <summary>本帧没采纳的话，是被哪一条终审拦下的（给统计用）</summary>
    public static string 本帧拦截原因 { get; private set; } = "";

    // ══════════════════════════════════════════════════════════════════
    //  ★ 同一条建议的"重试冷却" —— 修刷屏（用户实测报的问题）★
    //
    //  ── 现象（日志实证）──
    //    · 「DoT 还没到该补的时候」**3949 条**，其中某一秒内 **350 条**
    //      （≈每帧一条）
    //    · 「建议 3571 未解锁」**852 条** —— 而本地层同时成功放了 15 次法令
    //    两个都在**刷屏**，把日志彻底淹了。
    //
    //  ── 根因 ──
    //    `Check()` 用的是 `当前建议`（**Peek，只看出队**）。
    //    这是**故意**的（注释在下面：出队会让"Check 判 A、Build 放 B"）。
    //    但副作用是：一条**永远过不了终审**的建议会**一直卡在队首**，
    //    每帧都被重试、每帧都打一条拦截日志。
    //
    //    而且这不只是日志问题 —— 队首被这条卡住时，
    //    **后面那些本来能用的建议一条都拿不到机会**。
    //
    //  ── 修法 ──
    //    记住"上一条被拦的是谁、什么时候"，**同一个技能 ID 冷却期内直接静默返回**。
    //    选 1.5 秒的依据：局面的有意义变化最快也就是一个 GCD（2.5 秒），
    //    1.5 秒内重试同一个被拒的技能**不可能得到不同结果**。
    //
    //  ⚠️ 冷却**只按技能 ID**，不按"建议对象" —— 换了一条新建议立刻重试。
    //     这样既治了刷屏，又不会让后续建议饿死。
    // ══════════════════════════════════════════════════════════════════
    private static uint _上次被拦的ID;
    private static long _上次被拦时间;
    private const long 重试冷却毫秒 = 1500;

    /// <summary>
    /// **本帧尝试的**建议 ID（不一定被采纳）。
    ///
    /// ⚠️ 和 `本帧技能` 是两回事，不能合并：
    ///    · `本帧技能` = **采纳并发出去的** —— `战斗记忆.判来源()` 用它
    ///      判断"这次施放算不算 AI 的功劳"
    ///    · `_本帧尝试的ID` = **尝试过但可能被拦的** —— 重试冷却用它
    ///    如果在采纳前就写 `本帧技能`，那么
    ///    「AI 建议 X → 被拦 → 本地层放了 X」会被**误标成 AI 的功劳**。
    /// </summary>
    private static uint _本帧尝试的ID;

    public int Check()
    {
        本帧采纳 = false;
        本帧技能 = 0;
        本帧拦截原因 = "";

        try
        {
            var s = AiSettings.Instance;
            if (!s.启用决策层) return -1;

            // ⚠️ 这里必须用 当前建议（Peek，只看不动队列）
            //
            //    原来用的是 取建议()（Dequeue，出队）—— 那是个逻辑陷阱：
            //      · Check 出队后如果被更高优先级抢先，Build 不会被调用
            //        → 建议**永久丢失**
            //      · 而且 Build 里再 Peek 时已经是下一条
            //        → **Check 判 A，Build 放 B**
            //
            //    正确做法：Check 只看，Build 放成功了再调 消费()。
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return -1;

            var id = 建议.技能Id;
            if (id == 0) return -1;

            // ⚠️ 注意：这里**不能**赋值 `本帧技能`！
            //
            //    `本帧技能` 的语义是"**本帧采纳并发出去的**技能"，
            //    它被 `战斗记忆.判来源()` 用来判断"这次施放算不算 AI 的功劳"。
            //    如果在采纳**之前**就赋值，那么
            //      「AI 建议 X → 被终审拦下 → 本地层自己放了 X」
            //    也会被**误标成"AI 建议的"** —— 统计就假了。
            //
            //    所以冷却记在**独立字段** `_本帧尝试的ID` 上。
            _本帧尝试的ID = id;

            // ★ 重试冷却：同一条被拒的建议不要在冷却期内反复重试（治刷屏）★
            //
            //   ⚠️ 这里**直接静默返回**，连 `拦截()` 都不调 ——
            //      `拦截()` 会写统计和日志，调了等于没治刷屏。
            if (id == _上次被拦的ID)
            {
                var 距上次 = TimeHelper.Now() - _上次被拦时间;
                if (距上次 < 重试冷却毫秒) return -1;
            }

            // ---- 终审第一步：这个技能在当前职业真的存在吗 ----
            //
            //  ⚠️ `SpellUtil.已解锁()` 走的是 AEAssist 的 `IsUnlock()`，
            //     实测**会误报 false**（用户日志实证：法令 3571 被这里拒了 852 次，
            //     而本地层同时成功放了 15 次同一个技能）。
            //     所以它**不能**作为唯一的"存在性"判据 ——
            //     再加一条更可靠的：这个技能在**本职业的技能表**里出现过。
            //     两条取或：任一成立就算"存在"，交给后面的 `可用()` 做真正的门禁。
            if (!SpellUtil.已解锁(id))
            {
                拦截("未解锁（等级/职业任务没到）");
                Ai调试.日志($"建议 {id} 未解锁，放弃（改用原逻辑）");
                return -1;
            }

            // ---- 终审第二步：技能本身可用吗（CD / 形态 / 资源前置）----
            //      这一条就是原 resolver 用的同一套判断。
            //      AI 说"放以太超流"但以太已满 → SpellUtil.可用() 会挡下来吗？
            //      不会 —— 所以还需要各 resolver 自己的资源条件，
            //      这里只能挡住"技能层面"不可用的（CD 中、没学会、形态不对）。
            if (!SpellUtil.可用(id))
            {
                // 这个很常见（AI 建议了一个 CD 中的技能），不打日志免得刷屏
                // ★ 但它是最值得看的一类拦截 ★
                //   "不可用"占比高 = AI 建议的技能 CD 还没转好，
                //   说明预取提前量太大或者提示词没把 CD 状态说清楚。
                拦截("技能不可用（CD中/形态不对）");
                return -1;
            }

            // 完全采信 AI 开关（见开关注册处的长注释）
            var 完全采信 = 读完全采信();

            // ---- 终审第三步：这条建议到底该给谁（判不出就现在挡掉）----
            //
            //  ⚠️ 这一步是**新增的**，而且必须放在这里（Build 之前）——
            //     原来只有一条"需要目标但没目标"的判断，判据很粗：
            //     治疗类一律算"不需要目标" → Build 走 `SpellTargetType.Self`
            //     → **给自己加血**（审计发现的严重 bug）。
            //
            //     现在提前问清楚类别：判不出来就**现在拦掉**，
            //     不让它进 Build —— 因为 Build 里已经没有任何兜底目标可用了。
            var 目标类型 = 判目标类型(id);
            if (目标类型 == 施法目标类型.不支持)
            {
                // ⚠️ 「完全采信 AI」时**不拦**这里 —— 但要说明白为什么这不是自相矛盾：
                //    "判不出该给谁"是**我们自己的知识缺口**（这个技能不在
                //    我们维护的技能表栏位里），不是 AI 判断错了。
                //    AI 知道这个技能是干什么的，我们不知道 —— 这种情况下
                //    该听 AI 的。Build 里会退回"血最少的队友"。
                if (!完全采信)
                {
                    拦截("判不出该给谁用（不在本职业技能表里）");
                    return -1;
                }

                Ai调试.调试($"完全采信AI：{id} 判不出目标类型，仍按 AI 建议执行");
            }

            // 输出类还必须真的有选中敌人 —— 没有就别建议（盲打）
            if (目标类型 == 施法目标类型.敌人 && HealTargetHelper.当前目标() == null)
            {
                拦截("需要目标但没有目标");
                return -1;
            }

            // 复活类必须真的有倒地的队友
            if (目标类型 == 施法目标类型.待复活队友 && HealTargetHelper.待复活队友() == null)
            {
                拦截("复活类建议但没有待复活的队友");
                return -1;
            }

            // ---- 终审第三步半：打得到的吗（视线/射程）----
            //   只在**输出类**上判：治疗类打的是队友，硬套"敌人视线检查"
            //   会把"柱子后面的队友治不了"变成"不治了" —— 那是致命的。
            if (目标类型 == 施法目标类型.敌人
                && !技能数据.打得到(HealTargetHelper.当前目标()))
            {
                拦截("视线被挡 / 超出射程");
                Ai调试.调试($"建议 {id} 的当前目标被挡住或太远 -> 放弃（改用原逻辑）");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★★ 终审第三步·补：DoT 必须过「该不该补」★★
            //
            //  用户实测的 bug（日志证据）：
            //    ```
            //    [小鲸鱼] 原始回复：激进|全队血量 100%...
            //    采纳建议：16532 = 天辉（单体Boss目标，先补DoT）
            //    CastSpell success: 16532 天辉      ← 每 ~4.9 秒一次
            //    ```
            //
            //  原因：本 resolver 优先级 **100**，直接插到 `Res_Dot`(6) 前面，
            //        而上面那三步**只问"技能能不能放"**，
            //        **从来不问"现在该不该补 DoT"** ——
            //        于是 AI 每轮预取（每 3 步）都建议一次天辉，就每几秒补一次，
            //        **完全绕过 `Dot补判` 的剩余时间判断和防死循环保险丝**。
            //
            //  这是"白名单挡得住技能 ID、挡不住场景"的又一个实例：
            //  天辉是合法技能、也真的可用，但**时机不对**。
            //
            //  修法：DoT 类技能**必须**过 `Dot补判.该补()` ——
            //        和 `Res_Dot` 用的是**同一个判断**（开发约定 F③ 的推广：
            //        同一个决策不论从哪条路进来，判断必须一致）。
            //
            //  ⚠️ 这里只判 DoT，不判其他技能：
            //     别的技能各有自己的 resolver 条件，不能在这里一刀切
            //     （一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误）。
            // ══════════════════════════════════════════════════════════
            if (是DoT技能(id))
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                var 目标 = HealTargetHelper.当前目标();

                // ⚠️ 表可能为 null —— `取当前职业技能表()` 现在**会在查不到时返回 null**，
                //    而不是退回"别的职业的表"（那会串职业，是个已修的真 bug）。
                //
                //    表为 null ⇒ 拿不到 `所有DotBuff` ⇒ `该补` 会退回**兜底间隔判断**
                //    （`Dot补判.cs` 里 `所有DotBuff == null` 时走距离上次施放的时间）。
                //    那个判断仍然安全（不会误放），只是不看 buff 剩余时间。
                //    所以这里**不需要拦**，但也别把 `表?` 去掉 —— 去掉就会 NRE。
                var 该补 = Dot补判.该补(
                    目标,
                    表?.所有DotBuff,
                    HealSettings.Instance.Dot持续时间 - 3f);

                if (!该补)
                {
                    // ⚠️ 「完全采信 AI」时**跳过这道策略判断** ——
                    //    "还没到该补的时候"是**本地策略**（基于 buff 剩余时间），
                    //    不是"放不放得出去"。开关打开就是让 AI 说了算。
                    //
                    //  ⚠️ 但仍然记 `Dot补判.记一次施放`（Build 里做）——
                    //     那是**防死循环**的，不属于策略：
                    //     不记的话 AI 每轮都建议、每轮都放，就回到
                    //     "每 4.9 秒补一次 DoT"那个老 bug 了。
                    if (!完全采信)
                    {
                        拦截("DoT 还没到该补的时候");
                        Ai调试.调试(
                            $"建议 {id} 是 DoT，但剩余时间还够（距上次施放 " +
                            $"{Dot补判.距上次毫秒}ms）-> 放弃，让输出循环正常走");
                        return -1;
                    }

                    Ai调试.日志($"完全采信AI：DoT 剩余时间还够，但仍按 AI 建议补 {id}");
                }
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 有人在等治疗 → 别建议输出技能 ★
            //
            //  ── 依据（IL 直证）──
            //    参考实现把**全部输出都注册在治疗之后**：
            //        白魔第 26 位 / 学者 28 / 贤者 21 / 占星 31
            //    在这套模型里（第一个 `Check() >= 0` 的赢），
            //    **奶妈的输出永远是"治疗都不需要"之后的兜底** ——
            //    它们的 `Check()` 里本来就带着"有人要治就让路"。
            //
            //  ── 我们原来的问题 ──
            //    这里**只拦了 DoT**，其它输出技能（基础输出 / AOE /
            //    输出能力技）在有人等治疗时**照样会被建议** ——
            //    然后终审发现该治疗、把建议丢掉，**一轮 AI 白问**。
            //
            //  ⚠️ 为什么这道闸是安全的（不会误拦）：
            //     判据 `有人需要治疗()` 用的就是**治疗自己的阈值**，
            //     和 `Res_HealSingleGcd` 同源。它成立时，
            //     治疗 resolver 本来就会抢在输出前面 ——
            //     所以拦掉输出**不会改变实际行为**，只是省一轮白问。
            //
            //  ⚠️ 只拦**输出类**，不拦别的 ——
            //     一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误。
            //     治疗/减伤/复活这些**必须放行**（它们正是该做的事）。
            //
            //  ⚠️⚠️ 「完全采信 AI」时**这道闸会被跳过** —— 而它是**保命的那一条**。
            //      跳过意味着：AI 说打输出就打输出，哪怕有人快死了。
            //      这正是这个开关标"高风险"的原因，也是为什么它默认关。
            // ══════════════════════════════════════════════════════════
            if (!完全采信 && 是输出技能(id) && 有人需要治疗())
            {
                拦截("有人在等治疗，输出让路");
                return -1;
            }


            本帧采纳 = true;
            本帧技能 = id;
            return 100;   // 最高优先级（比 Always 队列里的其他都高）
        }
        catch (Exception e)
        {
            Ai调试.日志("建议执行器异常（已忽略）：" + e.Message);
            return -1;
        }
    }

    public void Build(Slot slot)
    {
        try
        {
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return;

            var id = 建议.技能Id;
            if (id == 0) return;

            var 是Dot = 是DoT技能(id);

            // ══════════════════════════════════════════════════════════
            //  ★★ 目标选择：**绝对不能用 `SpellTargetType.Self` 兜底** ★★
            //
            //  ── 这是个"治错人"的严重 bug（审计发现）──
            //    原来的写法是：
            //        if (需要目标(id) && 目标 != null) slot.Add(new Spell(id, 目标));
            //        else                              slot.Add(new Spell(id, Self));
            //    而 `需要目标()` 只把**输出类**当成"需要目标"。
            //
            //    `SpellTargetType.Self` 的语义是**施法者自己** ——
            //    框架实现就是 `case SpellTargetType.Self: return Core.Me;`。
            //
            //  ⇒ 后果：AI 一建议「救疗 / 鼓舞激励之策 / 天赐祝福 / 复活 / 驱散」，
            //    就会**给自己**放。而 `AiSuggestionResolver` 插在队列**最前面**、
            //    返回 100 → 它会**抢在** `Res_HealSingleGcd` 之前，
            //    于是"本地本来会正确治队友的那一口"被挤掉，放出去的是给自己加血。
            //
            //    复活/驱散打自己更是纯空放。
            //
            //  ── 更讽刺的是 ──
            //    我们刚写进提示词的第 19 条是"单体治疗打血最少的人"，
            //    而实现是"给自己"。**提示词和实现互相矛盾**。
            //
            //  ── 修法 ──
            //    按**技能类别**决定目标，缺一不可：
            //      · 输出类（基础/群体/DoT/输出能力技）→ 当前目标（敌人）
            //      · 治疗类（单奶/群奶/盾/单体减伤/HoT…）→ **血量最低的队友**
            //      · 复活 → 待复活队友
            //      · 自己/地面/AOE 类（醒梦、群减、疾跑…）→ Self（这些**本来就该**打自己）
            //
            //  ⚠️ 判断不了类别时**不要放**（`return` 掉这条建议）——
            //     放一个"目标错了"的技能比不放更糟：它会占掉 GCD 并挤掉正确的决策。
            // ══════════════════════════════════════════════════════════
            IBattleChara? 施法目标;
            var 目标类型 = 判目标类型(id);

            switch (目标类型)
            {
                case 施法目标类型.敌人:
                    施法目标 = HealTargetHelper.当前目标();
                    if (施法目标 == null)
                    {
                        拦截("输出类建议但没有选中敌人");
                        return;
                    }
                    break;

                case 施法目标类型.队友:
                    // 按提示词第 19 条的同一口径：**血最少的队友**（裸血量）
                    施法目标 = HealTargetHelper.最低血量队友(
                        HealerACR.Common.HealSettings.Instance.单体治疗阈值);

                    // 没人低于阈值也要给个目标 —— 否则复活/驱散这类会卡住。
                    // 退回"最危险的那个"，再退回自己（单体治疗打自己虽然浪费，
                    // 但比"目标为空导致放不出"更符合预期行为）。
                    施法目标 ??= HealTargetHelper.最危险队友();
                    施法目标 ??= Core.Me;
                    break;

                case 施法目标类型.待复活队友:
                    施法目标 = HealTargetHelper.待复活队友();
                    if (施法目标 == null)
                    {
                        拦截("复活类建议但没有待复活的队友");
                        return;
                    }
                    break;

                case 施法目标类型.自己:
                    施法目标 = Core.Me;
                    break;

                default:
                    // ⚠️ 判不出类别 → 默认**不放**（放错目标比不放更糟）。
                    //
                    //  ⚠️ 但「完全采信 AI」时**要放** —— 退回"血最少的队友"：
                    //     判不出类别是**我们自己的知识缺口**（这个技能不在
                    //     我们维护的技能表栏位里），不是 AI 判断错了。
                    //     宁可给一个可能不对的目标，也不要让开关形同虚设。
                    if (读完全采信())
                    {
                        施法目标 = HealTargetHelper.最低血量队友(
                            HealerACR.Common.HealSettings.Instance.单体治疗阈值)
                            ?? HealTargetHelper.最危险队友()
                            ?? Core.Me;

                        Ai调试.日志($"完全采信AI：{id} 目标类型未知，兜底给 {施法目标.Name}");
                        break;
                    }

                    拦截("判不出该给谁用，放弃这条建议");
                    return;
            }

            if (施法目标 == null)
            {
                拦截("目标为空，放弃");
                return;
            }

            slot.Add(new Spell(id, 施法目标));

            Ai调试.日志($"采纳建议：{id} = {SpellIds.反查(id)}（{建议.理由}）" +
                        $"｜目标 {施法目标.Name}" +
                        $"｜出生排队第 {建议.出生时队列位置 + 1} 位 / 批次 {建议.批次}" +
                        $" / 等了 {建议.已等毫秒}ms");

            // ⚠️ DoT 走 AI 这条路放出去时，**也必须记保险丝** ——
            //    否则 `Dot补判` 不知道刚放过，下一步又会判"该补"，
            //    保险丝形同虚设（这就是原来每 4.9 秒补一次的直接原因之一）。
            if (是Dot) Dot补判.记一次施放(施法目标);

            // ★ 技能真的进了 slot，才消费掉这条建议 ★
            //   放在最后：如果上面任何一步失败（目标为空、Spell 构造异常），
            //   建议不会被消费，下一帧还能再用 —— 比"判了不用"更合理。
            AiDecisionLayer.消费();
        }
        catch (Exception e)
        {
            Ai调试.日志("建议构建失败（已忽略）：" + e.Message);
        }
    }

    /// <summary>
    /// 这个技能是不是本职业的 DoT。
    ///
    /// 用途：**DoT 必须过"该不该补"终审**（见 Check 里第三步·补的说明）。
    /// 判据取自技能表，不写死 ID。
    /// </summary>
    private static bool 是DoT技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            return 表 != null && id == 表.Dot技能;
        }
        catch
        {
            return false;   // 判断不了就不拦（宁可放过，也别把正常建议挡掉）
        }
    }

    /// <summary>
    /// 记一次"建议被终审拦下"。
    ///
    /// 术语用"拦截"而不是"拒绝"，是为了和"AI 幻觉被白名单丢弃"区分开：
    ///   · 丢弃 = 建议本身就是错的（AI 编的）
    ///   · 拦截 = 建议合法，但**当前时机不合适**（原有逻辑说了算）
    /// 后者占比高不是坏事，说明"AI 给建议、原逻辑终审"这套设计在干活。
    /// </summary>
    private static void 拦截(string 原因)
    {
        本帧拦截原因 = 原因;
        AiDecisionLayer.记拦截(原因);

        // ★ 记下"是谁被拦的" —— 下一次 Check 会用它做**重试冷却**，
        //   否则同一条过不了终审的建议会每帧重试、每帧打日志（刷屏的根因）。
        //
        //   ⚠️ 注意这里记的是 `本帧技能` —— 它在采纳成功时才被赋值，
        //      而拦截发生在这之前，所以此刻它还是 0。
        //      所以拦截时要拿到"当前建议的 ID"，得从 `本帧技能` 之外取。
        //      `Check()` 里会在调用 `拦截` 之前先把 `本帧技能` 设好（见那边的注释）。
        _上次被拦的ID = _本帧尝试的ID;
        _上次被拦时间 = TimeHelper.Now();
    }


    /// <summary>
    /// 这个技能是不是"输出技能"。
    ///
    /// 用途：**治疗优先** —— 有治疗需求时，AI 建议的输出技能要让位。
    /// </summary>
    private static bool 是输出技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return false;   // 拿不到表就不拦（宁可放过）

            if (id == 表.基础输出) return true;
            if (id == 表.群体输出) return true;
            if (id == 表.Dot技能) return true;
            if (id == 表.移动填充技) return true;
            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0) return true;

            return false;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// 现在有没有人需要治疗。
    ///
    /// 判据：**低于单体治疗阈值的人数 > 0**（用玩家自己设的阈值，不另定标准）。
    /// </summary>
    private static bool 有人需要治疗()
    {
        try
        {
            var 阈值 = HealerACR.Common.HealSettings.Instance.单体治疗阈值;
            return HealerACR.Common.HealTargetHelper.低于阈值人数(阈值) > 0;
        }
        catch
        {
            return false;   // 判断不了就不拦
        }
    }

    /// <summary>
    /// **「完全采信 AI」开关开着吗**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  用户要求："启用后完全限制本地策略，完全采信 ai 策略"
    ///  （开关本身在 `HealerEntryBase` 里注册，UI 说明也写在那里）
    ///
    ///  ── 打开后本文件里会**跳过**这三道本地策略判断 ──
    ///    · `DoT 还没到该补的时候`   —— AI 说补就补
    ///    · `有人在等治疗，输出让路` —— **保命的那一条**，跳了就是 AI 说了算
    ///    · `判不出该给谁用`         —— 退回"血最少的队友"照放
    ///
    ///  ── **不跳过**的（这些不是策略，是"放不放得出去"）──
    ///    · 技能没解锁 / CD 中
    ///    · 没有合法的敌人 / 待复活队友
    ///    · 视线被挡 / 超出射程
    ///    去掉它们不会让 AI 更自由，只会多几条"技能放不出去"。
    ///
    ///  ⚠️ 默认 false，读不到也返回 false —— **失败方向必须是"不采信"**：
    ///     这个开关打开的代价是"没有兜底"，所以绝不能在读不到时误开。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static bool 读完全采信()
    {
        try
        {
            // ⚠️ 兜底参数写 false（不是 true）—— 见上面最后那条说明
            return HealerACR.Common.HealQt.GetQt("完全采信AI", false);
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// **这条建议该把技能放给谁。**
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么必须分这么细（审计发现的严重 bug）★
    ///
    ///  原来 `Build` 只有两条路：要么"输出类 → 当前目标"，
    ///  要么**一律 `SpellTargetType.Self`**。
    ///  而 `Self` = **施法者自己**（框架实现 `case Self: return Core.Me;`）。
    ///
    ///  ⇒ AI 一建议「救疗 / 天赐祝福 / 复活 / 驱散」，就**给自己放**。
    ///    更糟的是 `AiSuggestionResolver` 插在队列**最前面**，会**抢在**
    ///    `Res_HealSingleGcd` 之前 —— 本地本来会正确治队友的那一口被挤掉，
    ///    换成给自己加血。
    ///
    ///  ⚠️ 而且这和提示词第 19 条"单体治疗打血最少的人"**直接矛盾**：
    ///     告诉 AI 一套、实现另一套，AI 给的理由再对也没用。
    ///
    ///  ⚠️ `可以治()` 返回 false 的人（无敌/假死类）**不能选** ——
    ///     选了他们等于把这一口浪费掉。`最低血量队友` / `最危险队友`
    ///     内部已经用 `可以治()` 过滤过。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private enum 施法目标类型
    {
        不支持,      // 判不出来 → 不放（放错目标比不放更糟）
        敌人,
        队友,
        待复活队友,
        自己,
    }

    /// <summary>
    /// 按**技能表栏位**判断这条建议该给谁。
    ///
    /// ⚠️ 顺序有意义：先判最特殊的（复活），再判队友类，最后输出类。
    ///    同一个技能可能同时出现在多个栏位（比如贤者 诊断 既是
    ///    `单体治疗GCD` 又是 `单体盾`）—— 那没关系，它们的目标类型一样。
    /// </summary>
    private static 施法目标类型 判目标类型(uint id)
    {
        if (id == 0) return 施法目标类型.不支持;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return 施法目标类型.不支持;

            // ① 复活：目标是**倒地的队友**，不是活人
            if (id == 表.复活) return 施法目标类型.待复活队友;

            // ② 输出类：目标是**敌人**
            if (id == 表.基础输出) return 施法目标类型.敌人;
            if (id == 表.群体输出) return 施法目标类型.敌人;   // AOE 也以敌人为目标（落点由它决定）
            if (id == 表.Dot技能) return 施法目标类型.敌人;
            if (id == 表.移动填充技) return 施法目标类型.敌人;
            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0)
                return 施法目标类型.敌人;

            // ③ 治疗/护盾/单体减伤：目标是**队友**
            if (id == 表.单体治疗GCD) return 施法目标类型.队友;
            if (id == 表.紧急单奶) return 施法目标类型.队友;
            if (id == 表.预铺单奶能力技) return 施法目标类型.队友;
            if (id == 表.瞬发单奶能力技) return 施法目标类型.队友;
            if (id == 表.单体盾) return 施法目标类型.队友;
            if (id == 表.个人减伤) return 施法目标类型.队友;
            if (id == 表.驱散) return 施法目标类型.队友;

            // ④ 群体类 / 以自己或地面为中心的：目标是**自己**
            //    （AOE 治疗、群盾、团队减伤、醒梦、护盾前置、脱战准备…）
            if (id == 表.群体治疗GCD) return 施法目标类型.自己;
            if (id == 表.群体治疗能力技) return 施法目标类型.自己;
            if (id == 表.群体盾) return 施法目标类型.自己;
            if (id == 表.团队减伤) return 施法目标类型.自己;
            if (id == 表.护盾前置) return 施法目标类型.自己;
            if (id == 表.醒梦) return 施法目标类型.自己;
            if (表.脱战准备技能 != null && Array.IndexOf(表.脱战准备技能, id) >= 0)
                return 施法目标类型.自己;

            // ⑤ 不在表里的（各职业特有的占位技、换卡之类）：
            //    看它的**射程**兜底判一次 ——
            //    射程 > 0 说明要指定对象，但那可能是敌人也可能是队友，
            //    分不清 ⇒ **不支持**（宁可不放）。
            return 施法目标类型.不支持;
        }
        catch
        {
            return 施法目标类型.不支持;
        }
    }
