using AEAssist;
using AEAssist.CombatRoutine;
using AEAssist.CombatRoutine.Module;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// AI 建议执行器 —— **AI 给建议，原有逻辑终审。**
///
/// ═══ 这是整个阶段 B 的安全设计核心 ═══
///
/// AI 的建议**不是命令**，只是一个"插队申请"：
///   1. 它把建议的技能提到队列最前面（最高优先级）
///   2. 但**仍然要过一遍原来的可用性判断**（已解锁 / 可用 / 有目标）
///   3. 任何一项不满足 → 直接放弃，让原来的队列照常跑
///
/// **为什么必须这样**：
///   白名单只能挡住"清单外的 ID"，挡不住"清单内但用错场景"的。
///   比如 AI 建议"以太超流"，ID 完全合法，但**以太已经满了** ——
///   这时候白名单是拦不住的，必须靠原有的 Check 条件。
///
/// **所以 AI 永远不是唯一决策源，它只是"提前插一句嘴"。**
/// </summary>
public class AiSuggestionResolver : ISlotResolver
{
    /// <summary>本帧是否采纳了 AI 建议（给调试面板看）</summary>
    public static bool 本帧采纳 { get; private set; }

    public static uint 本帧技能 { get; private set; }

    /// <summary>本帧没采纳的话，是被哪一条终审拦下的（给统计用）</summary>
    public static string 本帧拦截原因 { get; private set; } = "";

    // ══════════════════════════════════════════════════════════════════
    //  ★ 同一条建议的"重试冷却" —— 修刷屏 ★
    //
    //  ── 现象（日志实证）──
    //    · 「DoT 还没到该补的时候」**3949 条**，其中某一秒内 **350 条**
    //      （≈每帧一条）
    //    · 「建议 3571 未解锁」**852 条** —— 而本地层同时成功放了 15 次法令
    //    两个都在**刷屏**，把日志彻底淹了。
    //
    //  ── 根因 ──
    //    `Check()` 用的是 `当前建议`（**Peek，只看出队**）。
    //    这是**故意**的（注释在下面：出队会让"Check 判 A、Build 放 B"）。
    //    但副作用是：一条**永远过不了终审**的建议会**一直卡在队首**，
    //    每帧都被重试、每帧都打一条拦截日志。
    //
    //    而且这不只是日志问题 —— 队首被这条卡住时，
    //    **后面那些本来能用的建议一条都拿不到机会**。
    //
    //  ── 修法 ──
    //    记住"上一条被拦的是谁、什么时候"，**同一个技能 ID 冷却期内直接静默返回**。
    //    选 1.5 秒的依据：局面的有意义变化最快也就是一个 GCD（2.5 秒），
    //    1.5 秒内重试同一个被拒的技能**不可能得到不同结果**。
    //
    //  ⚠️ 冷却**只按技能 ID**，不按"建议对象" —— 换了一条新建议立刻重试。
    //     这样既治了刷屏，又不会让后续建议饿死。
    // ══════════════════════════════════════════════════════════════════
    private static uint _上次被拦的ID;
    private static long _上次被拦时间;
    private const long 重试冷却毫秒 = 1500;

    /// <summary>
    /// **本帧尝试的**建议 ID（不一定被采纳）。
    ///
    /// ⚠️ 和 `本帧技能` 是两回事，不能合并：
    ///    · `本帧技能` = **采纳并发出去的** —— `战斗记忆.判来源()` 用它
    ///      判断"这次施放算不算 AI 的功劳"
    ///    · `_本帧尝试的ID` = **尝试过但可能被拦的** —— 重试冷却用它
    ///    如果在采纳前就写 `本帧技能`，那么
    ///    「AI 建议 X → 被拦 → 本地层放了 X」会被**误标成 AI 的功劳**。
    /// </summary>
    private static uint _本帧尝试的ID;

    public int Check()
    {
        本帧采纳 = false;
        本帧技能 = 0;
        本帧拦截原因 = "";

        try
        {
            var s = AiSettings.Instance;
            if (!s.启用决策层) return -1;

            // ⚠️ 这里必须用 当前建议（Peek，只看不动队列）
            //
            //    原来用的是 取建议()（Dequeue，出队）—— 那是个逻辑陷阱：
            //      · Check 出队后如果被更高优先级抢先，Build 不会被调用
            //        → 建议**永久丢失**
            //      · 而且 Build 里再 Peek 时已经是下一条
            //        → **Check 判 A，Build 放 B**
            //
            //    正确做法：Check 只看，Build 放成功了再调 消费()。
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return -1;

            var id = 建议.技能Id;
            if (id == 0) return -1;

            // ⚠️ 注意：这里**不能**赋值 `本帧技能`！
            //
            //    `本帧技能` 的语义是"**本帧采纳并发出去的**技能"，
            //    它被 `战斗记忆.判来源()` 用来判断"这次施放算不算 AI 的功劳"。
            //    如果在采纳**之前**就赋值，那么
            //      「AI 建议 X → 被终审拦下 → 本地层自己放了 X」
            //    也会被**误标成"AI 建议的"** —— 统计就假了。
            //
            //    所以冷却记在**独立字段** `_本帧尝试的ID` 上。
            _本帧尝试的ID = id;

            // ★ 重试冷却：同一条被拒的建议不要在冷却期内反复重试（治刷屏）★
            //
            //   ⚠️ 这里**直接静默返回**，连 `拦截()` 都不调 ——
            //      `拦截()` 会写统计和日志，调了等于没治刷屏。
            if (id == _上次被拦的ID)
            {
                var 距上次 = TimeHelper.Now() - _上次被拦时间;
                if (距上次 < 重试冷却毫秒) return -1;
            }

            // ---- 终审第一步：这个技能在当前职业真的存在吗 ----
            //
            //  ⚠️ `SpellUtil.已解锁()` 走的是 AEAssist 的 `IsUnlock()`，
            //     实测**会误报 false**（用户日志实证：法令 3571 被这里拒了 852 次，
            //     而本地层同时成功放了 15 次同一个技能）。
            //     所以它**不能**作为唯一的"存在性"判据 ——
            //     再加一条更可靠的：这个技能在**本职业的技能表**里出现过。
            //     两条取或：任一成立就算"存在"，交给后面的 `可用()` 做真正的门禁。
            if (!SpellUtil.已解锁(id))
            {
                拦截("未解锁（等级/职业任务没到）");
                Ai调试.日志($"建议 {id} 未解锁，放弃（改用原逻辑）");
                return -1;
            }

            // ---- 终审第二步：技能本身可用吗（CD / 形态 / 资源前置）----
            //      这一条就是原 resolver 用的同一套判断。
            //      AI 说"放以太超流"但以太已满 → SpellUtil.可用() 会挡下来吗？
            //      不会 —— 所以还需要各 resolver 自己的资源条件，
            //      这里只能挡住"技能层面"不可用的（CD 中、没学会、形态不对）。
            if (!SpellUtil.可用(id))
            {
                // 这个很常见（AI 建议了一个 CD 中的技能），不打日志免得刷屏
                // ★ 但它是最值得看的一类拦截 ★
                //   "不可用"占比高 = AI 建议的技能 CD 还没转好，
                //   说明预取提前量太大或者提示词没把 CD 状态说清楚。
                拦截("技能不可用（CD中/形态不对）");
                return -1;
            }

            // 完全采信 AI 开关（见开关注册处的长注释）
            var 完全采信 = 读完全采信();

            // ---- 终审第三步：这条建议到底该给谁（判不出就现在挡掉）----
            //
            //  ⚠️ 这一步是**新增的**，而且必须放在这里（Build 之前）——
            //     原来只有一条"需要目标但没目标"的判断，判据很粗：
            //     治疗类一律算"不需要目标" → Build 走 `SpellTargetType.Self`
            //     → **给自己加血**（审计发现的严重 bug）。
            //
            //     现在提前问清楚类别：判不出来就**现在拦掉**，
            //     不让它进 Build —— 因为 Build 里已经没有任何兜底目标可用了。
            var 目标类型 = 判目标类型(id);
            if (目标类型 == 施法目标类型.不支持)
            {
                // ★ 判不出该给谁 -> **一律拒绝**（完全采信也一样）★
                //
                //  [!] 原来「完全采信 AI」时这里放行，Build 里退回"血最少的队友"
                //      —— 那是 **AI 决策 + 本地猜目标**（第二轮审阅 P1-10）。
                //
                //  [!] 现在为什么可以安全地拒绝：批次三之后技能 ID 的来源变可信了
                //      · 候选路径：候选**全部取自职业表具名栏位**
                //        （治疗候选集 / 基础输出 / 群体输出 / Dot技能）
                //        => 类别必然判得出来，走不到这里
                //      · 老格式：AI 报了一个表外的 ID —— **那正是我们不知道
                //        该怎么用的情况**
                //
                //  [!] 判据是"本地合法性 100%"：判不出目标 = 无法保证放对 = 拒绝。
                //      放错目标比不放更糟 —— 它会占掉 GCD、挤掉正确的决策，
                //      还可能把治疗打到错误的人身上。
                拦截("判不出该给谁用（不在本职业技能表里）");
                return -1;
            }

            // 输出类还必须真的有选中敌人 —— 没有就别建议（盲打）
            if (目标类型 == 施法目标类型.敌人 && 建议施法目标(建议.目标Id, 建议.施法目标模式) == null)
            {
                拦截("需要目标但没有目标");
                return -1;
            }

            // 复活类必须真的有倒地的队友
            if (目标类型 == 施法目标类型.待复活队友 && HealTargetHelper.待复活队友() == null)
            {
                拦截("复活类建议但没有待复活的队友");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★★ 移动守卫 —— AI 这条路**原来完全没有** ★
            //
            //  ── 现象 ──
            //    "偶发移动的时候继续尝试咏唱"
            //
            //  ── 日志实证 ──
            //    `SelfCastCancel` **87 条**，而且被取消的**全是读条技能**：
            //      127 坚石 ×25 / 25859 闪灼 ×24 / 24283 注药 ×15 /
            //      135 救疗 ×12 / 185 鼓舞 ×5 / 25865 极炎法 ×5 / 24284 诊断 ×1
            //    ⇒ 移动中把读条技能塞进了 slot，走两步就被打断。
            //
            //  ── 为什么本地层有守卫、AI 这条路没有 ──
            //    本地每个 resolver 自己调 `SpellUtil.移动中可用()`（7+ 处），
            //    而 AI 建议走的是**另一条路**（`AiSuggestionResolver`），
            //    它只判了"技能可用 / 目标对不对 / 视线"，
            //    **从来没判过"我现在动不动"**。
            //
            //  ── 为什么这条不算"限制 AI 策略" ──
            //    移动中放不出读条技能**不是策略问题，是物理限制**——
            //    和"技能没解锁""CD 中"同一类。所以它：
            //      · 不受「完全采信AI」开关影响（那道开关放的是**策略**判断）
            //      · 拦住之后本地会自然降级到瞬发技能 / 移动填充
            //
            //  ⚠️ `移动中可用()` 内部已经处理了**瞬发豁免**
            //     （即刻咏唱 / 连续咏唱 / 光速 / 炽天附体），
            //     所以"开着即刻想移动中拉人"不会被误挡。
            // ══════════════════════════════════════════════════════════
            if (!SpellUtil.移动中可用(id))
            {
                拦截("移动中，读条技能放不出来");
                Ai调试.调试($"建议 {id} 需要读条，但当前在移动 -> 放弃（等站定或改瞬发）");
                return -1;
            }

            // ---- 终审第三步半：打得到的吗（视线/射程）----
            //   只在**输出类**上判：治疗类打的是队友，硬套"敌人视线检查"
            //   会把"柱子后面的队友治不了"变成"不治了" —— 那是致命的。
            if (目标类型 == 施法目标类型.敌人
                && !技能数据.打得到(建议施法目标(建议.目标Id, 建议.施法目标模式), 技能数据.取有效射程(id)))
            {
                拦截("视线被挡 / 超出射程");
                Ai调试.调试($"建议 {id} 的当前目标被挡住或太远 -> 放弃（改用原逻辑）");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★★ 终审第三步·补：DoT 必须过「该不该补」★★
            //
            //  现象（日志证据）：
            //    ```
            //    [小鲸鱼] 原始回复：激进|全队血量 100%...
            //    采纳建议：16532 = 天辉（单体Boss目标，先补DoT）
            //    CastSpell success: 16532 天辉      ← 每 ~4.9 秒一次
            //    ```
            //
            //  原因：本 resolver 优先级 **100**，直接插到 `Res_Dot`(6) 前面，
            //        而上面那三步**只问"技能能不能放"**，
            //        **从来不问"现在该不该补 DoT"** ——
            //        于是 AI 每轮预取（每 3 步）都建议一次天辉，就每几秒补一次，
            //        **完全绕过 `Dot补判` 的剩余时间判断和防死循环保险丝**。
            //
            //  这是"白名单挡得住技能 ID、挡不住场景"的又一个实例：
            //  天辉是合法技能、也真的可用，但**时机不对**。
            //
            //  修法：DoT 类技能**必须**过 `Dot补判.该补()` ——
            //        和 `Res_Dot` 用的是**同一个判断**（开发约定 F③ 的推广：
            //        同一个决策不论从哪条路进来，判断必须一致）。
            //
            //  ⚠️ 这里只判 DoT，不判其他技能：
            //     别的技能各有自己的 resolver 条件，不能在这里一刀切
            //     （一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误）。
            // ══════════════════════════════════════════════════════════
            if (是DoT技能(id))
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                var 目标 = 建议施法目标(建议.目标Id, 建议.施法目标模式);

                // ⚠️ 表可能为 null —— `取当前职业技能表()` 现在**会在查不到时返回 null**，
                //    而不是退回"别的职业的表"（那会串职业，是个已修的真 bug）。
                //
                //    表为 null ⇒ 拿不到 `所有DotBuff` ⇒ `该补` 会退回**兜底间隔判断**
                //    （`Dot补判.cs` 里 `所有DotBuff == null` 时走距离上次施放的时间）。
                //    那个判断仍然安全（不会误放），只是不看 buff 剩余时间。
                //    所以这里**不需要拦**，但也别把 `表?` 去掉 —— 去掉就会 NRE。
                var 该补 = Dot补判.该补(
                    目标,
                    表?.所有DotBuff,
                    HealSettings.Instance.Dot持续时间 - 3f);

                if (!该补)
                {
                    // ⚠️ 「完全采信 AI」时**跳过这道策略判断** ——
                    //    "还没到该补的时候"是**本地策略**（基于 buff 剩余时间），
                    //    不是"放不放得出去"。开关打开就是让 AI 说了算。
                    //
                    //  ⚠️ 但仍然记 `Dot补判.记一次施放`（Build 里做）——
                    //     那是**防死循环**的，不属于策略：
                    //     不记的话 AI 每轮都建议、每轮都放，就回到
                    //     "每 4.9 秒补一次 DoT"那个老 bug 了。
                    if (!完全采信)
                    {
                        拦截("DoT 还没到该补的时候");
                        Ai调试.调试(
                            $"建议 {id} 是 DoT，但剩余时间还够（距上次施放 " +
                            $"{Dot补判.距上次毫秒}ms）-> 放弃，让输出循环正常走");
                        return -1;
                    }

                    Ai调试.日志($"完全采信AI：DoT 剩余时间还够，但仍按 AI 建议补 {id}");
                }
            }

            // ══════════════════════════════════════════════════════════════
            //  ★★ 终审第三步·补：群体输出必须过「敌数门槛」★★
            //
            //  ── 现象（子代理审查 + 我核实）──
            //    敌数门槛**只写在候选集里**：
            //        候选集.cs  `敌数 >= 技能表.AOE最少敌人数` 才把群体输出加进候选
            //    而 `在可选清单里()`（AiDecisionLayer）和本文件的 `判目标类型()`
            //    都是**按技能表栏位无条件放行** `群体输出` —— 不看敌数。
            //
            //    本 resolver 返回 **100**，高于 `Res_AoEDamage` 的 **5**
            //    ⇒ **门槛被彻底绕开：场上只有一只怪时也能以最高优先级放群体技。**
            //      单发威力低于单体填充技，纯亏输出。
            //
            //  ── 为什么在这里加、而不是动本地 resolver ──
            //    下面 L272-274 那段注释说"不在这里一刀切别的技能"——
            //    但那个理由是"别的技能各有自己的 resolver 条件"。
            //    而 AOE 这个门槛**不是 resolver 条件，是"该不该放"的场景判据**，
            //    和 DoT 的 `该补()` **完全同类**（都是"技能合法但时机不对"）。
            //    ⇒ 照 DoT 的模式加，符合这个文件自己的架构意图。
            //
            //  [!] 判据和候选集**逐字相同** —— 开发约定 F③：
            //      "同一个决策不论从哪条路进来，判断必须一致"。
            // ══════════════════════════════════════════════════════════════
            if (是群体输出技能(id))
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();

                if (表 != null)
                {
                    // [!] **必须用 `AOE门槛(等级)`，不是 `AOE最少敌人数`**（GAP-3，审计确认）——
                    //     白魔 ≥72 / 贤者 ≥94 时门槛是 **3**（2 只怪时 AOE 是负收益，算术核实过），
                    //     而 `AOE最少敌人数` 恒为 2 ==> 守卫会**放行**按负收益放的 AOE。
                    //     本地、候选集、提示词用的都是 `AOE门槛(等级)` —— 这里原来不一致，
                    //     而它自己的注释还写着「判据和候选集逐字相同」。
                    var 需要 = Math.Max(1, 表.AOE门槛((int)Core.Me.Level));
                    var 半径 = Math.Max(1f, 表.AOE伤害范围);

                    var 敌数 = 0;
                    try { 敌数 = HealTargetHelper.周围敌人数量(半径, 25f); }
                    catch { 敌数 = 需要; }   // 查不到就放行（宁可放过，别把 AOE 全挡死）

                    if (敌数 < 需要)
                    {
                        // ⚠️ 「完全采信 AI」时**跳过** —— 和 DoT 那边同一套逃生口，
                        //    开关打开就是让 AI 说了算（高风险功能，用户已知）。
                        if (!完全采信)
                        {
                            拦截($"群体输出：{半径:F0} 米内只有 {敌数} 个，需要 ≥{需要}");
                            Ai调试.调试(
                                $"建议 {id} 是群体输出，但 {半径:F0} 米内只有 {敌数} 个" +
                                $"（需要 ≥{需要}）-> 放弃，让输出循环正常走");
                            return -1;
                        }

                        Ai调试.日志(
                            $"完全采信AI：{半径:F0} 米内只有 {敌数} 个，但仍按 AI 建议放 AOE");
                    }
                }
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 有人在等治疗 → 别建议输出技能 ★
            //
            //  ── 依据（IL 直证）──
            //    参考实现把**全部输出都注册在治疗之后**：
            //        白魔第 26 位 / 学者 28 / 贤者 21 / 占星 31
            //    在这套模型里（第一个 `Check() >= 0` 的赢），
            //    **奶妈的输出永远是"治疗都不需要"之后的兜底** ——
            //    它们的 `Check()` 里本来就带着"有人要治就让路"。
            //
            //  ── 我们原来的问题 ──
            //    这里**只拦了 DoT**，其它输出技能（基础输出 / AOE /
            //    输出能力技）在有人等治疗时**照样会被建议** ——
            //    然后终审发现该治疗、把建议丢掉，**一轮 AI 白问**。
            //
            //  ⚠️ 为什么这道闸是安全的（不会误拦）：
            //     判据 `有人需要治疗()` 用的就是**治疗自己的阈值**，
            //     和 `Res_HealSingleGcd` 同源。它成立时，
            //     治疗 resolver 本来就会抢在输出前面 ——
            //     所以拦掉输出**不会改变实际行为**，只是省一轮白问。
            //
            //  ⚠️ 只拦**输出类**，不拦别的 ——
            //     一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误。
            //     治疗/减伤/复活这些**必须放行**（它们正是该做的事）。
            //
            //  ⚠️⚠️ 「完全采信 AI」时**这道闸会被跳过** —— 而它是**保命的那一条**。
            //      跳过意味着：AI 说打输出就打输出，哪怕有人快死了。
            //      这正是这个开关标"高风险"的原因，也是为什么它默认关。
            // ══════════════════════════════════════════════════════════
            if (!完全采信 && 是输出技能(id) && 有人需要治疗())
            {
                拦截("有人在等治疗，输出让路");
                return -1;
            }


            本帧采纳 = true;
            本帧技能 = id;
            return 100;   // 最高优先级（比 Always 队列里的其他都高）
        }
        catch (Exception e)
        {
            Ai调试.日志("建议执行器异常（已忽略）：" + e.Message);
            return -1;
        }
    }

    public void Build(Slot slot)
    {
        try
        {
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return;

            var id = 建议.技能Id;
            if (id == 0) return;

            var 是Dot = 是DoT技能(id);

            // ══════════════════════════════════════════════════════════
            //  ★★ 目标选择：**绝对不能用 `SpellTargetType.Self` 兜底** ★★
            //
            //  ── 这是个"治错人"的严重 bug（审计发现）──
            //    原来的写法是：
            //        if (需要目标(id) && 目标 != null) slot.Add(new Spell(id, 目标));
            //        else                              slot.Add(new Spell(id, Self));
            //    而 `需要目标()` 只把**输出类**当成"需要目标"。
            //
            //    `SpellTargetType.Self` 的语义是**施法者自己** ——
            //    框架实现就是 `case SpellTargetType.Self: return Core.Me;`。
            //
            //  ⇒ 后果：AI 一建议「救疗 / 鼓舞激励之策 / 天赐祝福 / 复活 / 驱散」，
            //    就会**给自己**放。而 `AiSuggestionResolver` 插在队列**最前面**、
            //    返回 100 → 它会**抢在** `Res_HealSingleGcd` 之前，
            //    于是"本地本来会正确治队友的那一口"被挤掉，放出去的是给自己加血。
            //
            //    复活/驱散打自己更是纯空放。
            //
            //  ── 更讽刺的是 ──
            //    我们刚写进提示词的第 19 条是"单体治疗打血最少的人"，
            //    而实现是"给自己"。**提示词和实现互相矛盾**。
            //
            //  ── 修法 ──
            //    按**技能类别**决定目标，缺一不可：
            //      · 输出类（基础/群体/DoT/输出能力技）→ 当前目标（敌人）
            //      · 治疗类（单奶/群奶/盾/单体减伤/HoT…）→ **血量最低的队友**
            //      · 复活 → 待复活队友
            //      · 自己/地面/AOE 类（醒梦、群减、疾跑…）→ Self（这些**本来就该**打自己）
            //
            //  ⚠️ 判断不了类别时**不要放**（`return` 掉这条建议）——
            //     放一个"目标错了"的技能比不放更糟：它会占掉 GCD 并挤掉正确的决策。
            // ══════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★ 候选带了显式目标就用它，否则按技能类别推断 ★
            //
            //  [!] 为什么优先显式目标：
            //      候选是本地生成的（带目标的那一个），AI 挑的**就是**那个候选。
            //      不采信的话会退回"血最少的队友" —— 于是
            //      "AI 说治坦克" 变成 "治了血最少的别人"，
            //      AI 的目标判断完全白费（这正是候选层要解决的问题）。
            //
            //  [!] 但要校验目标**还活着且可治疗** —— 候选是几帧前生成的，
            //      期间目标可能死了/退队了。失效就退回本地推断（不报错）。
            // ══════════════════════════════════════════════════════════════
            IBattleChara? 显式目标 = null;
            if (建议.目标Id != 0)
            {
                try
                {
                    foreach (var r in HealTargetHelper.可治疗队友(50f))
                    {
                        if (r != null && r.GameObjectId == 建议.目标Id && r.活着())
                        {
                            显式目标 = r;
                            break;
                        }
                    }
                    // 敌人目标（输出类）单独找一次
                    if (显式目标 == null)
                    {
                        foreach (var e in Data.AllHostileTargets)
                        {
                            if (e != null && e.GameObjectId == 建议.目标Id && e.活着())
                            {
                                显式目标 = e;
                                break;
                            }
                        }
                    }
                }
                catch { 显式目标 = null; }
            }

            IBattleChara? 施法目标;

            // ══════════════════════════════════════════════════════════════
            //  ★ 第一优先：候选声明的**施法目标模式** ★
            //
            //  [!] `自己` 模式必须走在这里、且**不查任何目标** ——
            //      这是本轮审阅抓到的真 bug 的修法核心：
            //        群疗 / 群盾 / 团队减伤 / 个人减伤 的施法目标是**自己**
            //        （项目里就是 `new Spell(id, SpellTargetType.Self)`），
            //        而"最缺血的队友"只是**为什么现在该群疗**的理由。
            //        原来两者挤在一个 `目标Id` 里，于是群疗被以那个队友为中心放。
            //
            //  [!] 老格式（AI 直接报技能 ID）没有这个字段 ——
            //      默认是 `队友`，于是落到下面的本地推断（行为不变）。
            // ══════════════════════════════════════════════════════════════
            if (建议.施法目标模式 == 候选集.目标模式.自己)
            {
                施法目标 = Core.Me;
                本帧采纳 = true;
                slot.Add(new Spell(id, SpellTargetType.Self));
                收尾(是Dot, 施法目标);
                return;
            }

            // ══════════════════════════════════════════════════════════════
            //  ★ 候选指定了具体目标 -> 必须找到它，**找不到就拒绝** ★
            //
            //  [!] 为什么不再"退回本地推断"（本轮审阅第 13 条）：
            //      AI 选的是"**治疗坦克**"这个具体行为，不是"治一个血少的"。
            //      目标死了就改成治别人 = **执行了一个 AI 没选过的动作**，
            //      而且从统计上看不出来（会被算成"AI 选对了"）。
            //      => 正确做法是拒绝，让队列继续走下一个候选。
            //
            //  [!] 这里**不能**直接 `return` 而不收尾 —— 但要分清：
            //      拒绝时**不该** `消费()`（那条建议还没执行，留着下帧可能又有效）。
            //      所以走 `拦截()` + `return`，和别的拒绝路径一致。
            //
            //  [!] 成功路径必须走 `收尾()`（含 `消费()`）——
            //      漏了会导致**无限重复放同一个技能**（第二轮审阅第 8 条）。
            // ══════════════════════════════════════════════════════════════
            if (建议.目标Id != 0 &&
                (建议.施法目标模式 == 候选集.目标模式.队友 ||
                 建议.施法目标模式 == 候选集.目标模式.敌人))
            {
                施法目标 = 找目标(建议.目标Id, 建议.施法目标模式);
                if (施法目标 == null)
                {
                    // [!] 说清是"目标失效"，不要笼统说"没目标" ——
                    //     这两者在排查时完全不同：前者是候选过期，后者是局面本身没有。
                    拦截(建议.施法目标模式 == 候选集.目标模式.敌人
                        ? "候选指定的敌人已不在（死亡/消失/切走了）"
                        : "候选指定的队友已失效（死亡/退队）—— 不换目标，放弃这条");
                    Ai调试.调试($"候选目标 {建议.目标Id} 已失效，" +
                                $"拒绝执行（不改成治别人）");
                    return;
                }

                本帧采纳 = true;
                slot.Add(new Spell(id, 施法目标));
                收尾(是Dot, 施法目标);
                return;
            }

            // ── 以下是老格式（AI 直接报技能 ID）的本地推断路径 ──
            var 目标类型 = 判目标类型(id);

            switch (目标类型)
            {
                case 施法目标类型.敌人:
                    施法目标 = HealTargetHelper.当前目标();
                    if (施法目标 == null)
                    {
                        拦截("输出类建议但没有选中敌人");
                        return;
                    }
                    break;

                case 施法目标类型.队友:
                    // 按提示词第 19 条的同一口径：**血最少的队友**（裸血量）
                    施法目标 = HealTargetHelper.最低血量队友(
                        HealerACR.Common.HealSettings.Instance.单体治疗阈值);

                    // 没人低于阈值也要给个目标 —— 否则复活/驱散这类会卡住。
                    // 退回"最危险的那个"，再退回自己（单体治疗打自己虽然浪费，
                    // 但比"目标为空导致放不出"更符合预期行为）。
                    施法目标 ??= HealTargetHelper.最危险队友();
                    施法目标 ??= Core.Me;
                    break;

                case 施法目标类型.待复活队友:
                    施法目标 = HealTargetHelper.待复活队友();
                    if (施法目标 == null)
                    {
                        拦截("复活类建议但没有待复活的队友");
                        return;
                    }
                    break;

                case 施法目标类型.自己:
                    施法目标 = Core.Me;
                    break;

                default:
                    // ★ 判不出类别 -> **不放**（完全采信也一样）★
                    //
                    //  [!] 这里原来是"完全采信时退回 血最少队友 -> 最危险队友 -> 自己"
                    //      —— 即 **AI 决策 + 本地猜目标**（第二轮审阅 P1-10）。
                    //
                    //  [!] 现在统一成"拒绝"，判据是**本地合法性 100%**：
                    //      判不出该给谁 = 无法保证放对 = 不执行，而不是猜一个。
                    //
                    //  [!] 为什么可以安全地拒绝（批次三之后技能来源变可信了）：
                    //      · 候选路径：候选全部取自职业表具名栏位
                    //        （治疗候选集 / 基础输出 / 群体输出 / Dot技能）
                    //        => 类别必然判得出来，走不到这里
                    //      · 老格式：AI 报了一个表外的 ID
                    //        => **那正是我们不知道该怎么用的情况**
                    //
                    //  ⚠️ 代价：「完全采信 AI」会少放一些表外技能。
                    //     但**放错目标比不放更糟** —— 它会占掉 GCD、
                    //     挤掉正确的决策，还可能把治疗打到错误的人身上。
                    拦截("判不出该给谁用，放弃这条建议");
                    return;
            }

            if (施法目标 == null)
            {
                拦截("目标为空，放弃");
                return;
            }

            slot.Add(new Spell(id, 施法目标));
            收尾(是Dot, 施法目标);
        }
        catch (Exception e)
        {
            Ai调试.日志("建议构建失败（已忽略）：" + e.Message);
        }
    }

    /// <summary>
    /// **统一收尾** —— 技能真的进了 slot 之后必须走这里。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  [!] 为什么要抽出来（第二轮审阅第 8 条）：
    ///      `Build()` 里有**多条成功路径**（显式目标 / 类别推断 / 完全采信兜底…），
    ///      原来只有最后一条走了收尾，其它路径直接 `return` 就出去了。
    ///
    ///      最严重的是漏掉 `AiDecisionLayer.消费()` ——
    ///      它才是**推进队列**的那一步。漏了就会：
    ///          AI 说放 C1 -> 放出去 -> 队列没推进
    ///          -> 下一帧队首还是 C1 -> 又放 -> **无限重复同一个技能**
    ///
    ///  [!] 所以：**任何"技能已进 slot"的路径都必须调它**，
    ///      不要再在 `Build()` 里写"加完 slot 就 return"。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static void 收尾(bool 是Dot, IBattleChara 施法目标)
    {
        try
        {
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 != null)
            {
                Ai调试.日志($"采纳建议：{建议.技能Id} = {SpellIds.反查(建议.技能Id)}（{建议.理由}）" +
                            $"｜目标 {施法目标.Name}" +
                            $"｜出生排队第 {建议.出生时队列位置 + 1} 位 / 批次 {建议.批次}" +
                            $" / 等了 {建议.已等毫秒}ms");
            }

            // ⚠️ DoT 走 AI 这条路放出去时，**也必须记保险丝** ——
            //    否则 `Dot补判` 不知道刚放过，下一步又会判"该补"，
            //    保险丝形同虚设（这就是原来每 4.9 秒补一次的直接原因之一）。
            if (是Dot) Dot补判.记一次施放(施法目标);

            // ★ 技能真的进了 slot，才消费掉这条建议 ★
            //   放在最后：如果上面任何一步失败，建议不会被消费，下一帧还能再用
            //   —— 比"判了不用"更合理。
            //   ⚠️ 但**成功路径必须调到它**，否则会重复放同一个技能（见方法说明）。
            AiDecisionLayer.消费();
        }
        catch (Exception e)
        {
            Ai调试.日志("收尾失败（已忽略）：" + e.Message);
        }
    }

    /// <summary>
    /// **按 id 找一个活着的目标**（队友或敌人）。
    ///
    /// [!] 只返回**还活着**的 —— 调用方靠"返回 null"判断"候选目标已失效"。
    ///     这是"不再偷偷换目标"的基础（本轮审阅第 13 条）：
    ///     AI 选的是"治疗坦克"这个具体行为，目标死了就该**拒绝**，
    ///     而不是改成治别人（那是执行了一个 AI 没选过的动作）。
    /// </summary>
    private static IBattleChara? 找目标(ulong id, 候选集.目标模式 模式)
    {
        if (id == 0) return null;

        try
        {
            if (模式 == 候选集.目标模式.敌人)
            {
                foreach (var e in Data.AllHostileTargets)
                {
                    try
                    {
                        if (e != null && e.GameObjectId == id && e.活着()) return e;
                    }
                    catch { }
                }
                return null;
            }

            // 队友（含自己 —— 复活是唯一会找"倒地的"，那由 待复活队友 处理）
            foreach (var r in HealTargetHelper.可治疗队友(50f))
            {
                try
                {
                    if (r != null && r.GameObjectId == id && r.活着()) return r;
                }
                catch { }
            }
        }
        catch { }

        return null;
    }

    /// <summary>
    /// 这个技能是不是本职业的 DoT。
    ///
    /// 用途：**DoT 必须过"该不该补"终审**（见 Check 里第三步·补的说明）。
    /// 判据取自技能表，不写死 ID。
    /// </summary>
    private static bool 是DoT技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            return 表 != null && id == 表.Dot技能;
        }
        catch
        {
            return false;   // 判断不了就不拦（宁可放过，也别把正常建议挡掉）
        }
    }

    /// <summary>
    /// **这个 ID 是不是本职业的群体输出技**（给"AOE 敌数门槛"复审用）。
    ///
    /// [!] 和 `是DoT技能` 完全对称 —— 两者都是"技能合法，但要过场景判据"：
    ///      DoT 过 `该补()`，AOE 过"敌数 ≥ 门槛"。
    ///      这条对称是我们刻意维持的：同一个决策不论从哪条路进来，
    ///      判断必须一致（开发约定 F③）。
    /// </summary>
    private static bool 是群体输出技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null || 表.群体输出 == 0) return false;

            // [!] 用 `当前形态` 判 —— AOE 有等级升级链
            //     （破阵法 → 裂阵法），AI 可能回的是**升级后的 ID**，
            //     直接比 `表.群体输出` 会漏判。
            if (id == 表.群体输出) return true;

            try
            {
                var 形态 = HealerACR.Common.SpellUtil.当前形态(表.群体输出);
                if (形态 != null && 形态.Id != 0 && id == 形态.Id) return true;
            }
            catch { }

            return false;
        }
        catch
        {
            return false;   // 判断不了就不拦
        }
    }

    /// <summary>
    /// 记一次"建议被终审拦下"。
    ///
    /// 术语用"拦截"而不是"拒绝"，是为了和"AI 幻觉被白名单丢弃"区分开：
    ///   · 丢弃 = 建议本身就是错的（AI 编的）
    ///   · 拦截 = 建议合法，但**当前时机不合适**（原有逻辑说了算）
    /// 后者占比高不是坏事，说明"AI 给建议、原逻辑终审"这套设计在干活。
    /// </summary>
    private static void 拦截(string 原因)
    {
        本帧拦截原因 = 原因;
        AiDecisionLayer.记拦截(原因);

        // ★ 记下"是谁被拦的" —— 下一次 Check 会用它做**重试冷却**，
        //   否则同一条过不了终审的建议会每帧重试、每帧打日志（刷屏的根因）。
        //
        //   ⚠️ 注意这里记的是 `本帧技能` —— 它在采纳成功时才被赋值，
        //      而拦截发生在这之前，所以此刻它还是 0。
        //      所以拦截时要拿到"当前建议的 ID"，得从 `本帧技能` 之外取。
        //      `Check()` 里会在调用 `拦截` 之前先把 `本帧技能` 设好（见那边的注释）。
        _上次被拦的ID = _本帧尝试的ID;
        _上次被拦时间 = TimeHelper.Now();
    }


    /// <summary>
    /// 这个技能是不是"输出技能"。
    ///
    /// 用途：**治疗优先** —— 有治疗需求时，AI 建议的输出技能要让位。
    /// </summary>
    private static bool 是输出技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return false;   // 拿不到表就不拦（宁可放过）

            if (id == 表.基础输出) return true;
            if (id == 表.群体输出) return true;
            if (id == 表.Dot技能) return true;
            if (id == 表.移动填充技) return true;
            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0) return true;

            return false;
        }
        catch
        {
            return false;
        }
    }

