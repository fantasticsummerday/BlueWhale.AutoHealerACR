using AEAssist;
using AEAssist.CombatRoutine;
using AEAssist.CombatRoutine.Module;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// AI 建议执行器 —— **AI 给建议，原有逻辑终审。**
///
/// ═══ 这是整个阶段 B 的安全设计核心 ═══
///
/// AI 的建议**不是命令**，只是一个"插队申请"：
///   1. 它把建议的技能提到队列最前面（最高优先级）
///   2. 但**仍然要过一遍原来的可用性判断**（已解锁 / 可用 / 有目标）
///   3. 任何一项不满足 → 直接放弃，让原来的队列照常跑
///
/// **为什么必须这样**：
///   白名单只能挡住"清单外的 ID"，挡不住"清单内但用错场景"的。
///   比如 AI 建议"以太超流"，ID 完全合法，但**以太已经满了** ——
///   这时候白名单是拦不住的，必须靠原有的 Check 条件。
///
/// **所以 AI 永远不是唯一决策源，它只是"提前插一句嘴"。**
/// </summary>
public class AiSuggestionResolver : ISlotResolver
{
    /// <summary>本帧是否采纳了 AI 建议（给调试面板看）</summary>
    public static bool 本帧采纳 { get; private set; }

    public static uint 本帧技能 { get; private set; }

    /// <summary>本帧没采纳的话，是被哪一条终审拦下的（给统计用）</summary>
    public static string 本帧拦截原因 { get; private set; } = "";

    // ══════════════════════════════════════════════════════════════════
    //  ★ 同一条建议的"重试冷却" —— 修刷屏 ★
    //
    //  ── 现象（日志实证）──
    //    · 「DoT 还没到该补的时候」**3949 条**，其中某一秒内 **350 条**
    //      （≈每帧一条）
    //    · 「建议 3571 未解锁」**852 条** —— 而本地层同时成功放了 15 次法令
    //    两个都在**刷屏**，把日志彻底淹了。
    //
    //  ── 根因 ──
    //    `Check()` 用的是 `当前建议`（**Peek，只看出队**）。
    //    这是**故意**的（注释在下面：出队会让"Check 判 A、Build 放 B"）。
    //    但副作用是：一条**永远过不了终审**的建议会**一直卡在队首**，
    //    每帧都被重试、每帧都打一条拦截日志。
    //
    //    而且这不只是日志问题 —— 队首被这条卡住时，
    //    **后面那些本来能用的建议一条都拿不到机会**。
    //
    //  ── 修法 ──
    //    记住"上一条被拦的是谁、什么时候"，**同一个技能 ID 冷却期内直接静默返回**。
    //    选 1.5 秒的依据：局面的有意义变化最快也就是一个 GCD（2.5 秒），
    //    1.5 秒内重试同一个被拒的技能**不可能得到不同结果**。
    //
    //  ⚠️ 冷却**只按技能 ID**，不按"建议对象" —— 换了一条新建议立刻重试。
    //     这样既治了刷屏，又不会让后续建议饿死。
    // ══════════════════════════════════════════════════════════════════
    private static uint _上次被拦的ID;
    private static long _上次被拦时间;

    /// <summary>
    /// 同一条被拦建议的重试冷却（毫秒）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] **从 1500 降到 400**（第三方审计 P0-4「队首阻塞」）：
    ///
    ///      原判据是"局面的有意义变化最快是一个 GCD（2.5 秒），
    ///      1.5 秒内重试同一个被拒的技能不可能得到不同结果"。
    ///      **那个判据忽略了一件事**：被拦的建议**留在队首不消费**，
    ///      所以冷却期内**后面的建议一条都拿不到机会**——
    ///      1.5 秒 ≈ **0.6 个 GCD 被白白卡住**（排队 3 条时更明显）。
    ///
    ///  [!] 为什么不是"直接消费掉、换下一条"：
    ///      被拦的原因里有一类是**瞬时的**（"有人在等治疗" / "没轮到这个 off-gcd"），
    ///      下一帧就成立。直接消费会**白白丢掉一个好建议**。
    ///      而 400ms（≈0.16 个 GCD）足够让瞬时条件翻转，
    ///      又不会把队首卡到影响 GCD —— 两边都兼顾。
    ///
    ///  [!] 刷屏问题：冷却再短也只是"多试几次"，
    ///      而 `拦截()` 的统计和日志有独立节流（见 `拦截` 的说明），
    ///      所以不会因为冷却变短而刷屏。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private const long 重试冷却毫秒 = 400;

    /// <summary>
    /// **靠「技能表兜底」放行的累计次数**（第三方审计 P1-9 的验证数据）。
    ///
    /// [!] 为什么记它：`SpellUtil.已解锁()` 会误报 false 这件事
    ///     原来只有**注释**声称（法令 3571 被拒了 852 次），
    ///     而代码里的兜底**从来没实现过** —— 所以那个数字无法验证。
    ///     现在有了这个计数：
    ///       · 数字持续增长 => 误报是**真实的**，兜底确实在救回建议
    ///       · 恒为 0        => 说明误报在当前环境下**不发生**，
    ///                          那就可以考虑把兜底收掉（少一条判据）
    ///     ==> **用数据决定这条兜底留不留**，而不是靠注释里的一句话。
    /// </summary>
    public static int 靠技能表放行次数 { get; private set; }

    /// <summary>
    /// **本帧尝试的**建议 ID（不一定被采纳）。
    ///
    /// ⚠️ 和 `本帧技能` 是两回事，不能合并：
    ///    · `本帧技能` = **采纳并发出去的** —— `战斗记忆.判来源()` 用它
    ///      判断"这次施放算不算 AI 的功劳"
    ///    · `_本帧尝试的ID` = **尝试过但可能被拦的** —— 重试冷却用它
    ///    如果在采纳前就写 `本帧技能`，那么
    ///    「AI 建议 X → 被拦 → 本地层放了 X」会被**误标成 AI 的功劳**。
    /// </summary>
    private static uint _本帧尝试的ID;

    public int Check()
    {
        本帧采纳 = false;
        本帧技能 = 0;
        本帧拦截原因 = "";

        try
        {
            var s = AiSettings.Instance;
            if (!s.启用决策层) return -1;

            // ⚠️ 这里必须用 当前建议（Peek，只看不动队列）
            //
            //    原来用的是 取建议()（Dequeue，出队）—— 那是个逻辑陷阱：
            //      · Check 出队后如果被更高优先级抢先，Build 不会被调用
            //        → 建议**永久丢失**
            //      · 而且 Build 里再 Peek 时已经是下一条
            //        → **Check 判 A，Build 放 B**
            //
            //    正确做法：Check 只看，Build 放成功了再调 消费()。
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return -1;

            var id = 建议.技能Id;
            if (id == 0) return -1;

            // ⚠️ 注意：这里**不能**赋值 `本帧技能`！
            //
            //    `本帧技能` 的语义是"**本帧采纳并发出去的**技能"，
            //    它被 `战斗记忆.判来源()` 用来判断"这次施放算不算 AI 的功劳"。
            //    如果在采纳**之前**就赋值，那么
            //      「AI 建议 X → 被终审拦下 → 本地层自己放了 X」
            //    也会被**误标成"AI 建议的"** —— 统计就假了。
            //
            //    所以冷却记在**独立字段** `_本帧尝试的ID` 上。
            _本帧尝试的ID = id;

            // ★ 重试冷却：同一条被拒的建议不要在冷却期内反复重试（治刷屏）★
            //
            //   ⚠️ 这里**直接静默返回**，连 `拦截()` 都不调 ——
            //      `拦截()` 会写统计和日志，调了等于没治刷屏。
            if (id == _上次被拦的ID)
            {
                var 距上次 = TimeHelper.Now() - _上次被拦时间;
                if (距上次 < 重试冷却毫秒) return -1;
            }

            // ---- 终审第一步：这个技能在当前职业真的存在吗 ----
            //
            //  ⚠️ `SpellUtil.已解锁()` 走的是 AEAssist 的 `IsUnlock()`，
            //     实测**会误报 false**（用户日志实证：法令 3571 被这里拒了 852 次，
            //     而本地层同时成功放了 15 次同一个技能）。
            //     所以它**不能**作为唯一的"存在性"判据 ——
            //     再加一条更可靠的：这个技能在**本职业的技能表**里出现过。
            //     两条取或：任一成立就算"存在"，交给后面的 `可用()` 做真正的门禁。
            //
            //  [!] **这两条取或原来只在注释里，代码没实现**（第三方审计 P1-9，我核实确认）——
            //      注释写着"两条取或"，而代码只有 `if (!已解锁) return -1;` 一条。
            //      ==> 那条注释描述的修复**从来没生效**，法令那 852 次拒绝仍然会发生。
            //
            //  [!] **为什么不改 `SpellUtil.已解锁` 本身**：
            //      那个函数**本地层有 7+ 处在用**（各 resolver 的硬安全门）。
            //      给它加"技能表里出现过就算解锁"会让本地也开始放
            //      **真的没学会**的技能 —— 风险远大于收益。
            //      ==> 兜底只加在 AI 终审这一处：这里多放进来一个，
            //          后面 `SpellUtil.可用(id)` 还会再拦一次（那才是真正的门禁）。
            if (!SpellUtil.已解锁(id) && !在技能表里(id))
            {
                拦截("未解锁（等级/职业任务没到，且不在本职业技能表里）");
                Ai调试.日志($"建议 {id} 未解锁且不在技能表里，放弃（改用原逻辑）");
                return -1;
            }

            // 记录"靠技能表兜底放行"的次数 —— 这个数字能证明那条注释描述的问题是否真实存在
            if (!SpellUtil.已解锁(id)) 靠技能表放行次数++;

            // ---- 终审第二步：技能本身可用吗（CD / 形态 / 资源前置）----
            //      这一条就是原 resolver 用的同一套判断。
            //      AI 说"放以太超流"但以太已满 → SpellUtil.可用() 会挡下来吗？
            //      不会 —— 所以还需要各 resolver 自己的资源条件，
            //      这里只能挡住"技能层面"不可用的（CD 中、没学会、形态不对）。
            if (!SpellUtil.可用(id))
            {
                // ══════════════════════════════════════════════════════════
                //  ★ **先判"与本地一致"**（2026-10-03 用户实测原话）：
                //     「本地判定打毁灭、AI 也建议毁灭，但因为有延迟，AI 建议落地时
                //       本地**已经把毁灭打出去了** —— 这种就不应该算作没有命中」
                //
                //  [!] 这种情况的特征：技能此刻确实"不可用"，但**不是 CD 没转好**，
                //      而是**刚刚被我们自己放出去** ⇒ 判定为"与本地一致"：
                //        · 计入命中（新格子），**不算过期/丢弃**
                //        · 仍然 return -1（已经放过了，不必再采纳）—— 但语义完全不同
                //  [!] 只有真的不是"刚放过"时，才走原来的拦截 ✗
                // ══════════════════════════════════════════════════════════
                try { HealerACR.Common.最近释放.确保订阅(); } catch { }

                if (HealerACR.Common.最近释放.刚刚放过(id))
                {
                    // [!] 只有「真的记了一次」才打日志 —— 同一条建议每帧都会被复核，
                    //     不去重就会刷屏（用户实测）。去重逻辑在 `记与本地一致` 里。
                    if (AiDecisionLayer.记与本地一致(id))
                        Ai调试.日志($"建议 {id} 与本地一致（本地刚放过这个技能，此刻在 CD 里）—— 计入命中");
                    return -1;
                }

                // 这个很常见（AI 建议了一个 CD 中的技能），不打日志免得刷屏
                // ★ 但它是最值得看的一类拦截 ★
                //   "不可用"占比高 = AI 建议的技能 CD 还没转好，
                //   说明预取提前量太大或者提示词没把 CD 状态说清楚。
                拦截("技能不可用（CD中/形态不对）");
                return -1;
            }

            // ══════════════════════════════════════════════════════════════
            //  ---- 终审第二步半：**它是不是「预测性预铺」类** ----
            //
            //  [!] 2026-10-03 用户定的分工（原话）：
            //      「a 层改阈值，b 层只给预测的治疗建议，其他的全给倾向，本地计算放什么」
            //      ⇒ 喂给 AI 的候选已经**只留 治疗 / 减伤** 两类（见 `候选集.描述`），
            //        这里再加一道**白名单**：AI 自己编出来的、或不属于这两类的技能，
            //        一律拒绝（双保险，防止它绕过清单点名别的技能）。
            //
            //  [!] 判据用"当前快照里有没有这个 id 且属于那两类" ——
            //      与喂给它的清单**同源**，不会出现"清单里有、终审却不认"的矛盾。
            // ══════════════════════════════════════════════════════════════
            try
            {
                var 快照 = 候选集.生成();
                var 在预测性清单里 = false;
                foreach (var c in 快照.候选表)
                {
                    if (c.技能Id != id) continue;
                    if (c.类 == 候选集.类别.治疗 || c.类 == 候选集.类别.减伤) { 在预测性清单里 = true; break; }
                }

                if (!在预测性清单里)
                {
                    拦截("不属于预测性预铺类（输出 / 驱散 / 濒死救人由本地逻辑算，AI 只给倾向）");
                    return -1;
                }
            }
            catch { }

            // 完全采信 AI 开关（见开关注册处的长注释）
            var 完全采信 = 读完全采信();

            // ---- 终审第三步：这条建议到底该给谁（判不出就现在挡掉）----
            //
            //  ⚠️ 这一步是**新增的**，而且必须放在这里（Build 之前）——
            //     原来只有一条"需要目标但没目标"的判断，判据很粗：
            //     治疗类一律算"不需要目标" → Build 走 `SpellTargetType.Self`
            //     → **给自己加血**（审计发现的严重 bug）。
            //
            //     现在提前问清楚类别：判不出来就**现在拦掉**，
            //     不让它进 Build —— 因为 Build 里已经没有任何兜底目标可用了。
            var 目标类型 = 判目标类型(id);
            if (目标类型 == 施法目标类型.不支持)
            {
                // ★ 判不出该给谁 -> **一律拒绝**（完全采信也一样）★
                //
                //  [!] 原来「完全采信 AI」时这里放行，Build 里退回"血最少的队友"
                //      —— 那是 **AI 决策 + 本地猜目标**（第二轮审阅 P1-10）。
                //
                //  [!] 现在为什么可以安全地拒绝：批次三之后技能 ID 的来源变可信了
                //      · 候选路径：候选**全部取自职业表具名栏位**
                //        （治疗候选集 / 基础输出 / 群体输出 / Dot技能）
                //        => 类别必然判得出来，走不到这里
                //      · 老格式：AI 报了一个表外的 ID —— **那正是我们不知道
                //        该怎么用的情况**
                //
                //  [!] 判据是"本地合法性 100%"：判不出目标 = 无法保证放对 = 拒绝。
                //      放错目标比不放更糟 —— 它会占掉 GCD、挤掉正确的决策，
                //      还可能把治疗打到错误的人身上。
                拦截("判不出该给谁用（不在本职业技能表里）");
                return -1;
            }

            // 输出类还必须真的有选中敌人 —— 没有就别建议（盲打）
            if (目标类型 == 施法目标类型.敌人 && 建议施法目标(建议.目标Id, 建议.施法目标模式) == null)
            {
                拦截("需要目标但没有目标");
                return -1;
            }

            // 复活类必须真的有倒地的队友
            if (目标类型 == 施法目标类型.待复活队友 && HealTargetHelper.待复活队友() == null)
            {
                拦截("复活类建议但没有待复活的队友");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★★ 移动守卫 —— AI 这条路**原来完全没有** ★
            //
            //  ── 现象 ──
            //    "偶发移动的时候继续尝试咏唱"
            //
            //  ── 日志实证 ──
            //    `SelfCastCancel` **87 条**，而且被取消的**全是读条技能**：
            //      127 坚石 ×25 / 25859 闪灼 ×24 / 24283 注药 ×15 /
            //      135 救疗 ×12 / 185 鼓舞 ×5 / 25865 极炎法 ×5 / 24284 诊断 ×1
            //    ⇒ 移动中把读条技能塞进了 slot，走两步就被打断。
            //
            //  ── 为什么本地层有守卫、AI 这条路没有 ──
            //    本地每个 resolver 自己调 `SpellUtil.移动中可用()`（7+ 处），
            //    而 AI 建议走的是**另一条路**（`AiSuggestionResolver`），
            //    它只判了"技能可用 / 目标对不对 / 视线"，
            //    **从来没判过"我现在动不动"**。
            //
            //  ── 为什么这条不算"限制 AI 策略" ──
            //    移动中放不出读条技能**不是策略问题，是物理限制**——
            //    和"技能没解锁""CD 中"同一类。所以它：
            //      · 不受「完全采信AI」开关影响（那道开关放的是**策略**判断）
            //      · 拦住之后本地会自然降级到瞬发技能 / 移动填充
            //
            //  ⚠️ `移动中可用()` 内部已经处理了**瞬发豁免**
            //     （即刻咏唱 / 连续咏唱 / 光速 / 炽天附体），
            //     所以"开着即刻想移动中拉人"不会被误挡。
            // ══════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★★ 本地兜底闸门 —— AI 路径**必须同样遵守** ★★
            //
            //  [!] 修的是两条AI 开着比关掉更差的路径（兜底审计确认）：
            //
            //   ① **低蓝闸门被绕过**
            //      `Res_低蓝闸门.套上()` 是在 `HealerEntryBase.构建决策队列()` 里
            //      **就地包装**的，而本 resolver 是之后 `Insert(0)` 进去的
            //      ==> **从来没被包过**；`低蓝停手` 在 BlueWhale 里**零引用**。
            //      后果：AI 关掉时 2000 蓝以下所有输出全停、蓝留给治疗；
            //            AI 开着时**可以继续输出把最后的蓝花光** ==> 然后治不了人。
            //
            //   ② **必须奶满 被输出建议抢占**
            //      `Res_MustFullHeal` 在 AI 路径上**没有对应物**，而唯一那条
            //      治疗优先闸门是按**血线**判的 —— 提示词自己都写着
            //      「那个人可能血量看着很健康（比如 80%）」==> 闸门不触发。
            //      后果：AI 一条输出建议就能把必须奶满挤掉。
            //
            //  [!] 判据用**本地同一个函数**（`蓝量.低蓝停手()` / `必须奶满.找目标()`），
            //      不自己造（开发约定 F③：同一决策只有一种判法）。
            // ══════════════════════════════════════════════════════════════
            try
            {
                var 是输出技 = 这个ID是输出技(id);
            
                // ① 低蓝停手（和本地装饰器同源）
                if (是输出技 && HealerACR.Common.蓝量.低蓝停手())
                {
                    拦截("低蓝停手：输出让位，蓝留给治疗");
                    return -1;
                }
            
                // ② 有人「必须奶满」-> 非治疗建议一律让位
                if (!是治疗技(id))
                {
                    var 要紧的 = HealerACR.Common.必须奶满.找目标();
                    if (要紧的 != null)
                    {
                        拦截("有人必须奶满：先救他，其余建议让位");
                        return -1;
                    }
                }
            }
            catch { }
            
            // ══════════════════════════════════════════════════════════════
            //  ★★ 本地四道闸门 —— AI 路径原来一道都没有（H12，审计确认）★★
            //
            //  [!] 本地实现（`Res_Heal.cs`）：
            //    ① 木桩模式       -> `return -300`（L48/334/572/624/825）
            //    ② 厚盾跳过       -> 目标已有该盾且剩余 >5s 就跳（L666-668）
            //    ③ 本地施放记录   -> 刚放过 1200ms 内不再放（L851；服务器状态滞后）
            //    ④ OffGcd闸门     -> 急救排队闸门（L353）
            //
            //  [!] 缺了它们的后果：
            //    · 木桩上 AI 能治人 —— 而设置里「木桩优先输出」的意图是**一律不治**
            //    · 目标挂着 30 秒的盾，AI 还会再铺一次（过量 + 白费 GCD）
            //    · 刚放完盾的 0.x 秒空窗里又放一次（本地记录就是为了盖这个空窗）
            //
            //  [!] 为什么放在这里：此时 `目标类型` 已知、**还没做任何策略判断** ——
            //      这四条都是放不放得出去/该不该放，不是策略取舍。
            // ══════════════════════════════════════════════════════════════
            try
            {
                var 是治疗类 = 目标类型 == 施法目标类型.队友 || 目标类型 == 施法目标类型.自己;
            
                // ① 木桩模式：一律不治（本地同源）
                if (是治疗类 && HealTargetHelper.木桩模式)
                {
                    拦截("木桩模式：本地一律不治疗，把 GCD 让给输出");
                    return -1;
                }
            
                // ②③ 盾类：已有厚盾 / 刚放过 -> 跳过
                if (是治疗类)
                {
                    var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                    var 盾 = 表?.单体盾 ?? 0;
                    if (盾 != 0 && id == 盾)
                    {
                        // ⚠️ 判的是**真正要放的那个人**，不是坦克 ——
                        //    本地注释写明：曾经用坦克当替身是个真 bug
                        var 盾目标 = 建议施法目标(建议.目标Id, 建议.施法目标模式);
                        if (盾目标 != null)
                        {
                            // ③a 刚放过（服务器状态滞后，本地记录不滞后）
                            if (HealerACR.Common.本地施放记录.刚放过(盾))
                            {
                                拦截("刚放过这个盾（本地记录盖住服务器滞后的空窗）");
                                return -1;
                            }
                            // ② 已有厚盾（剩余 >5s）
                            if (盾目标.有该技能的Buff(盾)
                                && 盾目标.我的Buff还剩超过N秒(HealerACR.Common.AuraIds.技能转Buff(盾), 5f))
                            {
                                拦截("这个盾还有 5 秒以上，现在铺是过量");
                                return -1;
                            }
                        }
                    }
                }
            
                // ④ OffGcd闸门：只挡急救类（本地那条在必须奶满之后）
                if (目标类型 == 施法目标类型.队友)
                {
                    var 表2 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                    if (表2 != null)
                    {
                        // 急救 = 能力技那一栏（本地 `Res_HealEmergency` 用的就是它）
                        var 是急救 = 表2.群体治疗能力技 != 0 && id == 表2.群体治疗能力技;
                        if (是急救 && !HealerACR.Common.OffGcd闸门.可以排(1))
                        {
                            拦截("OffGcd 排队闸门：这一刻不排急救（让位给更该放的）");
                            return -1;
                        }
                    }
                }
            }
            catch { }
            
            if (!SpellUtil.移动中可用(id))
            {
                拦截("移动中，读条技能放不出来");
                Ai调试.调试($"建议 {id} 需要读条，但当前在移动 -> 放弃（等站定或改瞬发）");
                return -1;
            }

            // ---- 终审第三步半：打得到的吗（视线/射程）----
            //   只在**输出类**上判：治疗类打的是队友，硬套"敌人视线检查"
            //   会把"柱子后面的队友治不了"变成"不治了" —— 那是致命的。
            if (目标类型 == 施法目标类型.敌人
                && !技能数据.打得到(建议施法目标(建议.目标Id, 建议.施法目标模式), 技能数据.取有效射程(id)))
            {
                拦截("视线被挡 / 超出射程");
                Ai调试.调试($"建议 {id} 的当前目标被挡住或太远 -> 放弃（改用原逻辑）");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★★ 终审第三步·补：DoT 必须过「该不该补」★★
            //
            //  现象（日志证据）：
            //    ```
            //    [小鲸鱼] 原始回复：激进|全队血量 100%...
            //    采纳建议：16532 = 天辉（单体Boss目标，先补DoT）
            //    CastSpell success: 16532 天辉      ← 每 ~4.9 秒一次
            //    ```
            //
            //  原因：本 resolver 优先级 **100**，直接插到 `Res_Dot`(6) 前面，
            //        而上面那三步**只问"技能能不能放"**，
            //        **从来不问"现在该不该补 DoT"** ——
            //        于是 AI 每轮预取（每 3 步）都建议一次天辉，就每几秒补一次，
            //        **完全绕过 `Dot补判` 的剩余时间判断和防死循环保险丝**。
            //
            //  这是"白名单挡得住技能 ID、挡不住场景"的又一个实例：
            //  天辉是合法技能、也真的可用，但**时机不对**。
            //
            //  修法：DoT 类技能**必须**过 `Dot补判.该补()` ——
            //        和 `Res_Dot` 用的是**同一个判断**（开发约定 F③ 的推广：
            //        同一个决策不论从哪条路进来，判断必须一致）。
            //
            //  ⚠️ 这里只判 DoT，不判其他技能：
            //     别的技能各有自己的 resolver 条件，不能在这里一刀切
            //     （一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误）。
            // ══════════════════════════════════════════════════════════
            if (是DoT技能(id))
            {
            // ══════════════════════════════════════════════════════════════
            //  ★★ 本地 DoT 守卫 —— AI 路径原来**一道都没有**（GAP-5，审计确认）★★
            //
            //  [!] 本地 `Res_Dot` 有四道（`Res_Damage.cs`）：
            //        GetQt("DOT") / GetQt("输出")   <- 用户开关
            //        目标快死了()                   <- 30 秒 DoT 砸快死的怪最亏
            //        值得上Dot(target)              <- 血太少 / 波次快结束
            //        Dot黑名单.可以上Dot(target)    <- 自适应拉黑连续补失败的怪
            //
            //  [!] 缺了它们的后果（审计原话）：
            //      **AI 会给 5 只小怪挨个上 30 秒 DoT = 5 个白费 GCD**
            //      —— 那正是之前修过的那类回归。
            //
            //  [!] 是否受「完全采信AI」影响 —— **分开对待**：
            //      · `值得上Dot` 是**策略**（值不值得）-> 和 `该补` 一样，开关打开时跳过
            //      · `Dot黑名单` 是**纠错记录** -> **永远拦**（理由同 `记一次施放`：防死循环，不是策略）
            //      · QT 开关是**用户意图** -> **永远拦**（用户关了就得关）
            //
            //  [!] 为什么另起一段、而不是塞进下面那个块：
            //      下面那块里有个 `if (!完全采信) { … return -1; }`，
            //      往里插代码会让它后面的语句变成**不可达**（编译器 CS0162 实测报出来了）。
            //      这里另起一段**不动任何已有大括号**，也不影响下面那块本身的结论。
            // ══════════════════════════════════════════════════════════════
                var 靶子 = 建议施法目标(建议.目标Id, 建议.施法目标模式);
                
                // 策略类：和 `该补` 一样尊重「完全采信」开关
                if (!完全采信)
                {
                    try
                    {
                        if (!HealTargetHelper.木桩模式 && HealTargetHelper.目标快死了())
                        {
                            拦截("目标快死了：DoT 砸在它身上收不回来");
                            return -1;
                        }
                        if (靶子 != null && !HealTargetHelper.木桩模式 && !HealTargetHelper.值得上Dot(靶子))
                        {
                            拦截("这个目标不值得上 DoT（血太少 / 波次快结束）");
                            return -1;
                        }
                    }
                    catch { }
                }
                
                // 纠错记录：**不受开关影响**（防死循环）
                try
                {
                    if (靶子 != null && !HealerACR.Common.Dot黑名单.可以上Dot(靶子))
                    {
                        拦截("这个目标在 DoT 黑名单里（连续补失败，已自适应拉黑）");
                        return -1;
                    }
                }
                catch { }
            }

            // ══════════════════════════════════════════════════════════════
            //  ★★ 修的是一个**严重 bug**：这里原来是【裸块】★★
            //
            //  [!] 现象（用户实测：「命中率甚至是 0」）：
            //      上面那段 DoT 守卫写成了
            //          if (是DoT技能(id))
            //          {
            //              ...
            //          }          <- if 在这里就闭合了
            //          {          <- 这是**裸块**：无条件执行
            //              ... 该补 判断 ...
            //              if (!该补) { 拦截(...); return -1; }
            //          }
            //      ==> **任何一条** AI 建议（不只是 DoT）都会过 `Dot补判.该补`，
            //          而目标身上只要有我方 DoT 且剩余 > ~6.5 秒，`该补` 就是 false
            //          ==> 建议被 `拦截("DoT 还没到该补的时候")` 拒掉。
            //
            //  [!] 为什么影响这么大：DoT 持续 30 秒，而"该补"窗口只在最后 3 秒，
            //      ==> **30 秒里有 27 秒，AI 的建议一条都执行不了。**
            //
            //  [!] 怎么来的（我自己的错，记下来免得再犯）：
            //      我当时为了绕开"插进去会让后面的语句不可达"（CS0162），
            //      把大括号配成了"另起一段、不动任何已有大括号" ——
            //      **编译器挡住了不可达，却没人发现裸块等于无条件执行。**
            //      ==> 教训：改大括号结构时，必须回头确认**外层条件还在不在**。
            // ══════════════════════════════════════════════════════════════
            if (是DoT技能(id))
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                var 目标 = 建议施法目标(建议.目标Id, 建议.施法目标模式);

                // ⚠️ 表可能为 null —— `取当前职业技能表()` 现在**会在查不到时返回 null**，
                //    而不是退回"别的职业的表"（那会串职业，是个已修的真 bug）。
                //
                //    表为 null ⇒ 拿不到 `所有DotBuff` ⇒ `该补` 会退回**兜底间隔判断**
                //    （`Dot补判.cs` 里 `所有DotBuff == null` 时走距离上次施放的时间）。
                //    那个判断仍然安全（不会误放），只是不看 buff 剩余时间。
                //    所以这里**不需要拦**，但也别把 `表?` 去掉 —— 去掉就会 NRE。
                var 该补 = Dot补判.该补(
                    目标,
                    表?.所有DotBuff,
                    HealSettings.Instance.Dot持续时间 - 3f);

                if (!该补)
                {
                    // ⚠️ 「完全采信 AI」时**跳过这道策略判断** ——
                    //    "还没到该补的时候"是**本地策略**（基于 buff 剩余时间），
                    //    不是"放不放得出去"。开关打开就是让 AI 说了算。
                    //
                    //  ⚠️ 但仍然记 `Dot补判.记一次施放`（Build 里做）——
                    //     那是**防死循环**的，不属于策略：
                    //     不记的话 AI 每轮都建议、每轮都放，就回到
                    //     "每 4.9 秒补一次 DoT"那个老 bug 了。
                    if (!完全采信)
                    {
                        拦截("DoT 还没到该补的时候");
                        Ai调试.调试(
                            $"建议 {id} 是 DoT，但剩余时间还够（距上次施放 " +
                            $"{Dot补判.距上次毫秒}ms）-> 放弃，让输出循环正常走");
                        return -1;
                    }

                    Ai调试.日志($"完全采信AI：DoT 剩余时间还够，但仍按 AI 建议补 {id}");
                }
            }

            // ══════════════════════════════════════════════════════════════
            //  ★★ 终审第三步·补：群体输出必须过「敌数门槛」★★
            //
            //  ── 现象（子代理审查 + 我核实）──
            //    敌数门槛**只写在候选集里**：
            //        候选集.cs  `敌数 >= 技能表.AOE最少敌人数` 才把群体输出加进候选
            //    而 `在可选清单里()`（AiDecisionLayer）和本文件的 `判目标类型()`
            //    都是**按技能表栏位无条件放行** `群体输出` —— 不看敌数。
            //
            //    本 resolver 返回 **100**，高于 `Res_AoEDamage` 的 **5**
            //    ⇒ **门槛被彻底绕开：场上只有一只怪时也能以最高优先级放群体技。**
            //      单发威力低于单体填充技，纯亏输出。
            //
            //  ── 为什么在这里加、而不是动本地 resolver ──
            //    下面 L272-274 那段注释说"不在这里一刀切别的技能"——
            //    但那个理由是"别的技能各有自己的 resolver 条件"。
            //    而 AOE 这个门槛**不是 resolver 条件，是"该不该放"的场景判据**，
            //    和 DoT 的 `该补()` **完全同类**（都是"技能合法但时机不对"）。
            //    ⇒ 照 DoT 的模式加，符合这个文件自己的架构意图。
            //
            //  [!] 判据和候选集**逐字相同** —— 开发约定 F③：
            //      "同一个决策不论从哪条路进来，判断必须一致"。
            // ══════════════════════════════════════════════════════════════
            if (是群体输出技能(id))
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();

                if (表 != null)
                {
                    // [!] **必须用 `AOE门槛(等级)`，不是 `AOE最少敌人数`**（GAP-3，审计确认）——
                    //     白魔 ≥72 / 贤者 ≥94 时门槛是 **3**（2 只怪时 AOE 是负收益，算术核实过），
                    //     而 `AOE最少敌人数` 恒为 2 ==> 守卫会**放行**按负收益放的 AOE。
                    //     本地、候选集、提示词用的都是 `AOE门槛(等级)` —— 这里原来不一致，
                    //     而它自己的注释还写着「判据和候选集逐字相同」。
                    var 需要 = Math.Max(1, 表.AOE门槛((int)CharacterExt.我的等级()));
                    var 半径 = Math.Max(1f, 表.AOE伤害范围);

                    // [!] **必须用 `群攻命中数()`（按技能类型选圆心）** ——
                    //     这里原来写死 `周围敌人数量(半径, 25f)`，两处都错：
                    //       · 25 米是写死的（破阵法只有 5 米）
                    //       · `周围敌人数量` 以**目标**为中心，而破阵法以**我**为中心
                    //     ==> 圆心错了 ==> 把够不着的怪数成"能打到" ==> 门槛放行
                    //     （用户第三次报的症状：「50级神兵又在打 aoe」）
                    var 敌数 = 0;
                    try { 敌数 = 表.群攻命中数(id); }
                    catch { 敌数 = 需要; }   // 查不到就放行（宁可放过，别把 AOE 全挡死）

                    if (敌数 < 需要)
                    {
                        // ⚠️ 「完全采信 AI」时**跳过** —— 和 DoT 那边同一套逃生口，
                        //    开关打开就是让 AI 说了算（高风险功能，用户已知）。
                        if (!完全采信)
                        {
                            拦截($"群体输出：{半径:F0} 米内只有 {敌数} 个，需要 ≥{需要}");
                            Ai调试.调试(
                                $"建议 {id} 是群体输出，但 {半径:F0} 米内只有 {敌数} 个" +
                                $"（需要 ≥{需要}）-> 放弃，让输出循环正常走");
                            return -1;
                        }

                        Ai调试.日志(
                            $"完全采信AI：{半径:F0} 米内只有 {敌数} 个，但仍按 AI 建议放 AOE");
                    }
                }
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 有人在等治疗 → 别建议输出技能 ★
            //
            //  ── 依据（IL 直证）──
            //    参考实现把**全部输出都注册在治疗之后**：
            //        白魔第 26 位 / 学者 28 / 贤者 21 / 占星 31
            //    在这套模型里（第一个 `Check() >= 0` 的赢），
            //    **奶妈的输出永远是"治疗都不需要"之后的兜底** ——
            //    它们的 `Check()` 里本来就带着"有人要治就让路"。
            //
            //  ── 我们原来的问题 ──
            //    这里**只拦了 DoT**，其它输出技能（基础输出 / AOE /
            //    输出能力技）在有人等治疗时**照样会被建议** ——
            //    然后终审发现该治疗、把建议丢掉，**一轮 AI 白问**。
            //
            //  ⚠️ 为什么这道闸是安全的（不会误拦）：
            //     判据 `有人需要治疗()` 用的就是**治疗自己的阈值**，
            //     和 `Res_HealSingleGcd` 同源。它成立时，
            //     治疗 resolver 本来就会抢在输出前面 ——
            //     所以拦掉输出**不会改变实际行为**，只是省一轮白问。
            //
            //  ⚠️ 只拦**输出类**，不拦别的 ——
            //     一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误。
            //     治疗/减伤/复活这些**必须放行**（它们正是该做的事）。
            //
            //  ⚠️⚠️ 「完全采信 AI」时**这道闸会被跳过** —— 而它是**保命的那一条**。
            //      跳过意味着：AI 说打输出就打输出，哪怕有人快死了。
            //      这正是这个开关标"高风险"的原因，也是为什么它默认关。
            // ══════════════════════════════════════════════════════════
            if (!完全采信 && 是输出技能(id) && 有人需要治疗())
            {
                拦截("有人在等治疗，输出让路");
                return -1;
            }


            本帧采纳 = true;
            本帧技能 = id;
            return 100;   // 最高优先级（比 Always 队列里的其他都高）
        }
        catch (Exception e)
        {
            Ai调试.日志("建议执行器异常（已忽略）：" + e.Message);
            return -1;
        }
    }

    public void Build(Slot slot)
    {
        try
        {
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return;

            var id = 建议.技能Id;
            if (id == 0) return;

            var 是Dot = 是DoT技能(id);

            // ══════════════════════════════════════════════════════════
            //  ★★ 目标选择：**绝对不能用 `SpellTargetType.Self` 兜底** ★★
            //
            //  ── 这是个"治错人"的严重 bug（审计发现）──
            //    原来的写法是：
            //        if (需要目标(id) && 目标 != null) slot.Add(new Spell(id, 目标));
            //        else                              slot.Add(new Spell(id, Self));
            //    而 `需要目标()` 只把**输出类**当成"需要目标"。
            //
            //    `SpellTargetType.Self` 的语义是**施法者自己** ——
            //    框架实现就是 `case SpellTargetType.Self: return Core.Me;`。
            //
            //  ⇒ 后果：AI 一建议「救疗 / 鼓舞激励之策 / 天赐祝福 / 复活 / 驱散」，
            //    就会**给自己**放。而 `AiSuggestionResolver` 插在队列**最前面**、
            //    返回 100 → 它会**抢在** `Res_HealSingleGcd` 之前，
            //    于是"本地本来会正确治队友的那一口"被挤掉，放出去的是给自己加血。
            //
            //    复活/驱散打自己更是纯空放。
            //
            //  ── 更讽刺的是 ──
            //    我们刚写进提示词的第 19 条是"单体治疗打血最少的人"，
            //    而实现是"给自己"。**提示词和实现互相矛盾**。
            //
            //  ── 修法 ──
            //    按**技能类别**决定目标，缺一不可：
            //      · 输出类（基础/群体/DoT/输出能力技）→ 当前目标（敌人）
            //      · 治疗类（单奶/群奶/盾/单体减伤/HoT…）→ **血量最低的队友**
            //      · 复活 → 待复活队友
            //      · 自己/地面/AOE 类（醒梦、群减、疾跑…）→ Self（这些**本来就该**打自己）
            //
            //  ⚠️ 判断不了类别时**不要放**（`return` 掉这条建议）——
            //     放一个"目标错了"的技能比不放更糟：它会占掉 GCD 并挤掉正确的决策。
            // ══════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★ 候选带了显式目标就用它，否则按技能类别推断 ★
            //
            //  [!] 为什么优先显式目标：
            //      候选是本地生成的（带目标的那一个），AI 挑的**就是**那个候选。
            //      不采信的话会退回"血最少的队友" —— 于是
            //      "AI 说治坦克" 变成 "治了血最少的别人"，
            //      AI 的目标判断完全白费（这正是候选层要解决的问题）。
            //
            //  [!] 但要校验目标**还活着且可治疗** —— 候选是几帧前生成的，
            //      期间目标可能死了/退队了。失效就退回本地推断（不报错）。
            // ══════════════════════════════════════════════════════════════
            IBattleChara? 显式目标 = null;
            if (建议.目标Id != 0)
            {
                try
                {
                    foreach (var r in HealTargetHelper.可治疗队友(50f))
                    {
                        if (r != null && r.GameObjectId == 建议.目标Id && r.活着())
                        {
                            显式目标 = r;
                            break;
                        }
                    }
                    // 敌人目标（输出类）单独找一次
                    if (显式目标 == null)
                    {
                        foreach (var e in Data.AllHostileTargets)
                        {
                            if (e != null && e.GameObjectId == 建议.目标Id && e.活着())
                            {
                                显式目标 = e;
                                break;
                            }
                        }
                    }
                }
                catch { 显式目标 = null; }
            }

            IBattleChara? 施法目标;

            // ══════════════════════════════════════════════════════════════
            //  ★ 第一优先：候选声明的**施法目标模式** ★
            //
            //  [!] `自己` 模式必须走在这里、且**不查任何目标** ——
            //      这是本轮审阅抓到的真 bug 的修法核心：
            //        群疗 / 群盾 / 团队减伤 / 个人减伤 的施法目标是**自己**
            //        （项目里就是 `new Spell(id, SpellTargetType.Self)`），
            //        而"最缺血的队友"只是**为什么现在该群疗**的理由。
            //        原来两者挤在一个 `目标Id` 里，于是群疗被以那个队友为中心放。
            //
            //  [!] 老格式（AI 直接报技能 ID）没有这个字段 ——
            //      默认是 `队友`，于是落到下面的本地推断（行为不变）。
            // ══════════════════════════════════════════════════════════════
            // ══════════════════════════════════════════════════════════════
            //  ★★ **护盾前置**（贤者「均衡」）—— AI 路径原来完全没有 ★★
            //
            //  [!] 修的是第三方审计 P0-3（我核实确认）：
            //      本地 `Res_Mitigation`（群体盾）和 `Res_Heal`（单体盾）都做了两件事：
            //        ① Check 判要不要前置、前置能不能放（不能放就整条不触发）
            //        ② Build 先 `slot.Add(pre)` 再放盾
            //      而 **AI 路径两件都没有** ==>
            //        · 贤者不在均衡状态时，AI 选的「预后 / 诊断」**形态不对、放不出来**
            //      贤者靠盾吃饭 ==> 这是整个失效，不是差一点。
            //
            //  [!] 为什么不在这里 return 拦截：
            //      前置可用时应该**正常放**（加前置 + 放盾）；
            //      不可用时走下面的 `判目标类型`/可用性检查自然会拒 ——
            //      和本地 `Res_Mitigation` 的 `return -1` 同一个效果。
            //
            //  [!] `护盾前置 == 0`（学者/白魔/占星）时这段整体跳过，行为不变。
            // ══════════════════════════════════════════════════════════════
            var 前置技能 = 0u;
            var 前置不可用 = false;
            try
            {
                var 表0 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                if (表0 != null && 表0.护盾前置 != 0)
                {
                    前置技能 = 表0.护盾前置;
                    // 只在这条建议是**盾**时才需要前置
                    if (id == 表0.单体盾 || id == 表0.群体盾)
                    {
                        // 已经在均衡状态 -> 不需要再放前置（和本地 `!JobApiHelper.均衡中` 同源）
                        // 前置放不出来 -> 记下来，下面整条放弃
                        //   （和本地 `Res_Mitigation` 的 `return -1` 同源）
                        if (!JobApiHelper.均衡中 && !SpellUtil.可用(前置技能))
                            前置不可用 = true;
                    }
                }
            }
            catch { }

            // ⚠️ **不能在这里 `slot.Add()`** —— 注意本方法是 `Build(Slot)` 里的
            //    `Check()` 已经返回过"接受"，这里放弃**不会**让框架自动落到下一个候选
            //    （`Check >= 0` 但 `Build` 不加任何东西时框架会继续找下一个 resolver，
            //      见 `PVE_RunSlotHelper` 的 `"异常情况: … 的Build方法没有构造一个可用的技能"`）。
            //    ==> 所以"放弃"= 什么都别加，让框架走下一个。
            if (前置不可用)
            {
                拦截("护盾前置（均衡）放不出来：盾的形态不对，硬放会失败");
                Ai调试.调试($"建议 {id} 是盾，但护盾前置 {前置技能} 不可用 -> 放弃，让本地盾逻辑走");
                return;   // 空 Build -> 框架落到下一个 resolver
            }
            
            if (建议.施法目标模式 == 候选集.目标模式.自己)
            {
                施法目标 = Core.Me;
                本帧采纳 = true;
                // ★ **必须检查返回值**（外部审查 P0-3，我核实确认为真）
                //   返回 false = **Spell 没进 Slot** ⇒ 这一帧什么都没执行
                //   ⇒ **不能收尾**（收尾会 Consume / 记统计 / 记 DoT，
                //      让 AI 以为已经放过 ⇒ 下一帧同一条建议又被"消费"）
                if (!放技能(slot, id, Core.Me, 建议.是盾技能))
                {
                    本帧采纳 = false;
                    拦截("放技能 返回 false（Spell 未进 Slot）—— 不消费这条建议");
                    return;
                }
                收尾(是Dot, 施法目标);
                return;
            }

            // ══════════════════════════════════════════════════════════════
            //  ★ **地面放置** —— 落点必须**现在算**，不能用候选里的位置 ★
            //
            //  [!] 修的是第三方审计 P0-2（我核实确认）：
            //      原来 `目标模式` 只有 自己/队友/敌人 三个分支，
            //      **没有 `地面`** ==> 地面技能（野战治疗阵 / 庇护所 / 地星）
            //      掉进"自己"那一支，被放成 `SpellTargetType.Self`（**自己脚下**），
            //      而本地是 `new Spell(团队减伤, 落点)`（`Res_Mitigation.cs:245`）
            //      ==> **AI 选的这个动作和本地放的不是同一个动作。**
            //
            //  [!] **为什么在这里现算、而不是把落点存进候选**：
            //      候选要经 AI 往返（≈2.6 秒）才执行，
            //      而 `敌人移动检测.地面技能位置()` 读的是**当下**的敌人位置 ——
            //      冻结在候选里的落点**执行时已经过期**（可能扔到已经没人的地方）。
            //      ==> 落点在执行这一刻算，用和本地 resolver **同一个函数**（F③）。
            //
            //  [!] 落点规则也一致：优选敌人**稳定够久**才放它脚下，否则放自己脚下
            //      （`地面技能位置` 内部就是这个判据，小怪刚出现那几秒会自动退回自己脚下）。
            // ══════════════════════════════════════════════════════════════
            if (建议.施法目标模式 == 候选集.目标模式.地面 || 是地面技能(id))
            {
                var 落点 = CharacterExt.我的位置();
                try
                {
                    // 优选敌人：优先用候选指定的那个（AI 想罩谁就罩谁那边）
                    IBattleChara? 优选 = null;
                    if (建议.目标Id != 0)
                        优选 = 找目标(建议.目标Id, 候选集.目标模式.敌人);
                    优选 ??= HealTargetHelper.当前目标();
                    落点 = 敌人移动检测.地面技能位置(优选);
                }
                catch { }

                施法目标 = Core.Me;      // 地面技能没有"施法目标"，落点才是关键
                本帧采纳 = true;
                // [!] 地面这条**不能**走 `放技能()`（它要传 Vector3 落点，不是角色）——
                //     所以前置在这里单独补一次（同样是只写一处判据的例外，注释说明）。
                try
                {
                    var 表G = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                    if (表G != null && 表G.护盾前置 != 0 && !JobApiHelper.均衡中
                        && (id == 表G.单体盾 || id == 表G.群体盾))
                    {
                        var preG = SpellUtil.Get(表G.护盾前置);
                        if (preG != null) slot.Add(preG);
                    }
                }
                catch { }
                slot.Add(new Spell(SpellUtil.当前形态(id)?.Id ?? id, 落点));
                收尾(是Dot, 施法目标);
                return;
            }

            // ══════════════════════════════════════════════════════════════
            //  ★ 候选指定了具体目标 -> 必须找到它，**找不到就拒绝** ★
            //
            //  [!] 为什么不再"退回本地推断"（本轮审阅第 13 条）：
            //      AI 选的是"**治疗坦克**"这个具体行为，不是"治一个血少的"。
            //      目标死了就改成治别人 = **执行了一个 AI 没选过的动作**，
            //      而且从统计上看不出来（会被算成"AI 选对了"）。
            //      => 正确做法是拒绝，让队列继续走下一个候选。
            //
            //  [!] 这里**不能**直接 `return` 而不收尾 —— 但要分清：
            //      拒绝时**不该** `消费()`（那条建议还没执行，留着下帧可能又有效）。
            //      所以走 `拦截()` + `return`，和别的拒绝路径一致。
            //
            //  [!] 成功路径必须走 `收尾()`（含 `消费()`）——
            //      漏了会导致**无限重复放同一个技能**（第二轮审阅第 8 条）。
            // ══════════════════════════════════════════════════════════════
            if (建议.目标Id != 0 &&
                (建议.施法目标模式 == 候选集.目标模式.队友 ||
                 建议.施法目标模式 == 候选集.目标模式.敌人))
            {
                施法目标 = 找目标(建议.目标Id, 建议.施法目标模式);
                if (施法目标 == null)
                {
                    // [!] 说清是"目标失效"，不要笼统说"没目标" ——
                    //     这两者在排查时完全不同：前者是候选过期，后者是局面本身没有。
                    拦截(建议.施法目标模式 == 候选集.目标模式.敌人
                        ? "候选指定的敌人已不在（死亡/消失/切走了）"
                        : "候选指定的队友已失效（死亡/退队）—— 不换目标，放弃这条");
                    Ai调试.调试($"候选目标 {建议.目标Id} 已失效，" +
                                $"拒绝执行（不改成治别人）");
                    return;
                }

                本帧采纳 = true;
                // ★ **必须检查返回值**（外部审查 P0-3）—— 见上面第一处的说明
                if (!放技能(slot, id, 施法目标, 建议.是盾技能))
                {
                    本帧采纳 = false;
                    拦截("放技能 返回 false（Spell 未进 Slot）—— 不消费这条建议");
                    return;
                }
                收尾(是Dot, 施法目标);
                return;
            }

            // ── 以下是老格式（AI 直接报技能 ID）的本地推断路径 ──
            var 目标类型 = 判目标类型(id);

            switch (目标类型)
            {
                case 施法目标类型.敌人:
                    施法目标 = HealTargetHelper.当前目标();
                    if (施法目标 == null)
                    {
                        拦截("输出类建议但没有选中敌人");
                        return;
                    }
                    break;

                case 施法目标类型.队友:
                    // 按提示词第 19 条的同一口径：**血最少的队友**（裸血量）
                    // ══════════════════════════════════════════════════════════════
                    //  ★ **「必须奶满」优先于“血量最低”**（H9，审计确认）★
                    //
                    //  [!] 原来这里只按血量挑（最低血量队友 -> 最危险队友 -> 自己），
                    //      **完全没考虑必须奶满**。
                    //      而提示词 7~10 条明确命令 AI「优先对那个人使用治疗技能」，
                    //      并写明「不许因为他血还挺多而把治疗给别人」。
                    //      ==> AI 用 ID 格式回答时，**治疗会落到血量最低的另一个人
                    //          （极端情况甚至自己）身上** —— 等于放弃了他。
                    //
                    //  [!] 判据用和本地同一个函数 `必须奶满.找目标()`（开发约定 F③）。
                    // ══════════════════════════════════════════════════════════════
                    施法目标 = null;
                    try { 施法目标 = HealerACR.Common.必须奶满.找目标(); } catch { }
                    
                    施法目标 ??= HealTargetHelper.最低血量队友(
                        HealerACR.Common.HealSettings.Instance.单体治疗阈值);

                    // 没人低于阈值也要给个目标 —— 否则复活/驱散这类会卡住。
                    // 退回"最危险的那个"，再退回自己（单体治疗打自己虽然浪费，
                    // 但比"目标为空导致放不出"更符合预期行为）。
                    施法目标 ??= HealTargetHelper.最危险队友();
                    施法目标 ??= Core.Me;
                    break;

                case 施法目标类型.待复活队友:
                    施法目标 = HealTargetHelper.待复活队友();
                    if (施法目标 == null)
                    {
                        拦截("复活类建议但没有待复活的队友");
                        return;
                    }
                    break;

                case 施法目标类型.自己:
                    施法目标 = Core.Me;
                    break;

                default:
                    // ★ 判不出类别 -> **不放**（完全采信也一样）★
                    //
                    //  [!] 这里原来是"完全采信时退回 血最少队友 -> 最危险队友 -> 自己"
                    //      —— 即 **AI 决策 + 本地猜目标**（第二轮审阅 P1-10）。
                    //
                    //  [!] 现在统一成"拒绝"，判据是**本地合法性 100%**：
                    //      判不出该给谁 = 无法保证放对 = 不执行，而不是猜一个。
                    //
                    //  [!] 为什么可以安全地拒绝（批次三之后技能来源变可信了）：
                    //      · 候选路径：候选全部取自职业表具名栏位
                    //        （治疗候选集 / 基础输出 / 群体输出 / Dot技能）
                    //        => 类别必然判得出来，走不到这里
                    //      · 老格式：AI 报了一个表外的 ID
                    //        => **那正是我们不知道该怎么用的情况**
                    //
                    //  ⚠️ 代价：「完全采信 AI」会少放一些表外技能。
                    //     但**放错目标比不放更糟** —— 它会占掉 GCD、
                    //     挤掉正确的决策，还可能把治疗打到错误的人身上。
                    拦截("判不出该给谁用，放弃这条建议");
                    return;
            }

            if (施法目标 == null)
            {
                拦截("目标为空，放弃");
                return;
            }

            // ★ **必须检查返回值**（外部审查 P0-3）—— 见上面第一处的说明
            if (!放技能(slot, id, 施法目标, 建议.是盾技能))
            {
                本帧采纳 = false;
                拦截("放技能 返回 false（Spell 未进 Slot）—— 不消费这条建议");
                return;
            }
            收尾(是Dot, 施法目标);
        }
        catch (Exception e)
        {
