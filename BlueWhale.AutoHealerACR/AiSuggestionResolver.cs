        catch { return ""; }
    }

    private static void 拦截(string 原因)
    {
        本帧拦截原因 = 原因;
        AiDecisionLayer.记拦截(原因);

        // ★ 记下"是谁被拦的" —— 下一次 Check 会用它做**重试冷却**，
        //   否则同一条过不了终审的建议会每帧重试、每帧打日志（刷屏的根因）。
        //
        //   ⚠️ 注意这里记的是 `本帧技能` —— 它在采纳成功时才被赋值，
        //      而拦截发生在这之前，所以此刻它还是 0。
        //      所以拦截时要拿到"当前建议的 ID"，得从 `本帧技能` 之外取。
        //      `Check()` 里会在调用 `拦截` 之前先把 `本帧技能` 设好（见那边的注释）。
        _上次被拦的ID = _本帧尝试的ID;
        _上次被拦时间 = TimeHelper.Now();

        // ══════════════════════════════════════════════════════════════
        //  ★ 记下"最近一次被拒的建议 + 原因"（2026-10-03 新增）
        //
        //  [!] 用户实测：等级同步的副本里（极神兵破坏作战，50 级），
        //      AI 凭记忆报出本等级拿不到的技能 id ⇒ 这里拦下 ⇒ 回退本地逻辑。
        //      拦是对的，但**它学不到** —— 下一次还是照报，白问一轮。
        //  ⇒ 记在这里（全部 37 个拦截点共用的唯一入口），
        //    给两处用：下一次请求的提示词（教它别重复）、调试窗（让用户看得见）。
        // ══════════════════════════════════════════════════════════════
        最近被拒 = $"{_本帧尝试的ID}｜{原因}";
        最近被拒时刻 = Environment.TickCount64;
    }


