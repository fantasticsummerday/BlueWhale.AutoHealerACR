    /// <summary>
    /// **这条建议该把技能放给谁。**
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么必须分这么细（审计发现的严重 bug）★
    ///
    ///  原来 `Build` 只有两条路：要么"输出类 → 当前目标"，
    ///  要么**一律 `SpellTargetType.Self`**。
    ///  而 `Self` = **施法者自己**（框架实现 `case Self: return Core.Me;`）。
    ///
    ///  ⇒ AI 一建议「救疗 / 天赐祝福 / 复活 / 驱散」，就**给自己放**。
    ///    更糟的是 `AiSuggestionResolver` 插在队列**最前面**，会**抢在**
    ///    `Res_HealSingleGcd` 之前 —— 本地本来会正确治队友的那一口被挤掉，
    ///    换成给自己加血。
    ///
    ///  ⚠️ 而且这和提示词第 19 条"单体治疗打血最少的人"**直接矛盾**：
    ///     告诉 AI 一套、实现另一套，AI 给的理由再对也没用。
    ///
    ///  ⚠️ `可以治()` 返回 false 的人（无敌/假死类）**不能选** ——
    ///     选了他们等于把这一口浪费掉。`最低血量队友` / `最危险队友`
    ///     内部已经用 `可以治()` 过滤过。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private enum 施法目标类型
    {
        不支持,      // 判不出来 → 不放（放错目标比不放更糟）
        敌人,
        队友,
        待复活队友,
        自己,
    }

    /// <summary>
    /// 按**技能表栏位**判断这条建议该给谁。
    ///
    /// ⚠️ 顺序有意义：先判最特殊的（复活），再判队友类，最后输出类。
    ///    同一个技能可能同时出现在多个栏位（比如贤者 诊断 既是
    ///    `单体治疗GCD` 又是 `单体盾`）—— 那没关系，它们的目标类型一样。
    /// </summary>
    /// <summary>
    /// **这条建议真正会打谁** —— 所有守卫都必须用它，不能用 `当前目标()`。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  [!] 修的是一个**真 bug**（审计确认，`AiSuggestionResolver` 的 4 处判据）：
    ///
    ///      守卫判的是 `HealTargetHelper.当前目标()`（= 玩家选中的那个，
    ///      **只判 CurrentHp > 0，可以是队友**），
    ///      而 `Build` 按候选带来的 `目标Id` 施法（`输出目标.选()` 挑的**敌人**）。
    ///
    ///  [!] 为什么两者必然不同：
    ///      `输出目标.当前选中的()` 对**友方目标返回 null**
    ///      ==> 奶妈选中坦克（奶妈的常态）时，
    ///          `输出目标.选()` 会另挑一个有仇恨的敌人。
    ///
    ///  ==> 后果：
    ///      ① `打得到(坦克)` 恒过 ==> 可以往**够不着/被挡**的敌人身上放
    ///      ② `Dot补判.该补(坦克,…)` 查不到记录 ==> 返回 true
    ///         ==> **每 4.9 秒补一次 DoT那个保险丝被绕过**
    ///      ③ `周围敌人数量(…, 25f)` 是**围着坦克**数的 ==> AOE 判据错
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static IBattleChara? 建议施法目标(ulong 目标Id, 候选集.目标模式 模式)
    {
        try
        {
            // 候选带了具体敌人 -> 就是它（和 `Build` 找的是同一个）
            if (目标Id != 0)
            {
                var 找到 = 找目标(目标Id, 模式);
                if (找到 != null) return 找到;
            }
    
            // 老格式（AI 直接报技能 ID）没有候选 -> 退回玩家选中的
            var 当前 = HealTargetHelper.当前目标();
            if (当前 != null && 当前.IsEnemy()) return 当前;
        }
        catch { }
        return null;
    }
    
    private static 施法目标类型 判目标类型(uint id)
    {
        if (id == 0) return 施法目标类型.不支持;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return 施法目标类型.不支持;

            // ① 复活：目标是**倒地的队友**，不是活人
            if (id == 表.复活) return 施法目标类型.待复活队友;

            // ② 输出类：目标是**敌人**
            if (id == 表.基础输出) return 施法目标类型.敌人;
            if (id == 表.群体输出) return 施法目标类型.敌人;   // AOE 也以敌人为目标（落点由它决定）
            if (id == 表.Dot技能) return 施法目标类型.敌人;
            if (id == 表.移动填充技) return 施法目标类型.敌人;
            // [!] **站定填充技 必须在这里**（GAP-1，审计确认）——
            //     候选集和散文清单都列出了它，但这里原来没有 ==>
            //     `判不出该给谁用` 把它拒了 ==> 学者 Lv38-81 永远放不出「毁灭」，
            //     而且那个死候选还占掉输出桶 3 个名额之一。
            if (id == 表.站定填充技) return 施法目标类型.敌人;
            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0)
                return 施法目标类型.敌人;

            // ③ 治疗/护盾/单体减伤：目标是**队友**
            // ══════════════════════════════════════════════════════════════
            //  ★ **治疗候选池里的技能一律按「队友」类处理** ★
            //
            //  [!] 修的是 AI 路径的**自相矛盾**（子代理核实、我已逐关核对）：
            //      · `AiDecisionLayer.在可选清单里()` 遍历 `表.治疗候选.全部` ==> **放行**
            //      · `AiSituation` 把整池列给 AI  ==> 提示词里**明确写着** `190=医术`
            //      · 但这里原来只有 `id == 表.单体治疗GCD`（学者 = 185）这一条单奶判据
            //        ==> 190 一路落到 `return 施法目标类型.不支持`
            //        ==> **拦截(判不出该给谁用（不在本职业技能表里）)**
            //
            //  ==> 结果：AI 被**引导**去建议一个永远执行不了的技能，
            //      而且它永远不会被统计成「采纳」—— 白问一轮，还看不出原因。
            //
            //  [!] 为什么按队友类是对的：
            //      `治疗候选集` 这个池子的定义**就是**能对队友用的治疗技能，
            //      白名单已经认它了 ==> 两处口径必须一致（开发约定 F③：同一决策只有一种判法）。
            //
            //  [!] 放在 `单体治疗GCD` 那条**之前**：
            //      池子里也包含群体治疗技（群体性其实由候选的 `群体` 字段表达，
            //      目标仍按队友走 —— 实际施法目标模式由候选自己带，见 `施法目标模式`）。
            // ══════════════════════════════════════════════════════════════
            try
            {
                foreach (var h in 表.治疗候选.全部)
                {
                    if (h != null && h.Id != 0 && id == h.Id) return 施法目标类型.队友;
                }
            }
            catch { }
            
            if (id == 表.单体治疗GCD) return 施法目标类型.队友;
            if (id == 表.紧急单奶) return 施法目标类型.队友;
            if (id == 表.预铺单奶能力技) return 施法目标类型.队友;
            if (id == 表.瞬发单奶能力技) return 施法目标类型.队友;
            if (id == 表.单体盾) return 施法目标类型.队友;
            // ★ 个人减伤 -> **自己**（本轮审阅第 6 条，已核实）★
            //
            //  [!] 项目里就是这么放的（`Res_Mitigation.cs`）：
            //          var spell = SpellUtil.Get(_t.个人减伤);
            //          if (spell != null) slot.Add(spell);   // 没有目标参数 = 自己
            //      原来归到"队友"会去找"血最少的队友" —— 目标完全错。
            //
            //  [!] 名字里的"个人"就是"给自己"的意思，不是"给某个人"。
            if (id == 表.个人减伤) return 施法目标类型.自己;
            if (id == 表.驱散) return 施法目标类型.队友;

            // ④ 群体类 / 以自己或地面为中心的：目标是**自己**
            //    （AOE 治疗、群盾、团队减伤、醒梦、护盾前置、脱战准备…）
            if (id == 表.群体治疗GCD) return 施法目标类型.自己;
            if (id == 表.群体治疗能力技) return 施法目标类型.自己;
            if (id == 表.群体盾) return 施法目标类型.自己;
            if (id == 表.团队减伤) return 施法目标类型.自己;
            if (id == 表.护盾前置) return 施法目标类型.自己;
            if (id == 表.醒梦) return 施法目标类型.自己;
            if (表.脱战准备技能 != null && Array.IndexOf(表.脱战准备技能, id) >= 0)
                return 施法目标类型.自己;

            // ⑤ 不在表里的（各职业特有的占位技、换卡之类）：
            //    看它的**射程**兜底判一次 ——
            //    射程 > 0 说明要指定对象，但那可能是敌人也可能是队友，
            //    分不清 ⇒ **不支持**（宁可不放）。
            return 施法目标类型.不支持;
        }
        catch
        {
            return 施法目标类型.不支持;
        }
    }
