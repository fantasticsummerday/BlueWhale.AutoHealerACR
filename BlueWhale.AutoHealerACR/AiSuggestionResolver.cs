using AEAssist;
using AEAssist.CombatRoutine;
using AEAssist.CombatRoutine.Module;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// AI 建议执行器 —— **AI 给建议，原有逻辑终审。**
///
/// ═══ 这是整个阶段 B 的安全设计核心 ═══
///
/// AI 的建议**不是命令**，只是一个"插队申请"：
///   1. 它把建议的技能提到队列最前面（最高优先级）
///   2. 但**仍然要过一遍原来的可用性判断**（已解锁 / 可用 / 有目标）
///   3. 任何一项不满足 → 直接放弃，让原来的队列照常跑
///
/// **为什么必须这样**：
///   白名单只能挡住"清单外的 ID"，挡不住"清单内但用错场景"的。
///   比如 AI 建议"以太超流"，ID 完全合法，但**以太已经满了** ——
///   这时候白名单是拦不住的，必须靠原有的 Check 条件。
///
/// **所以 AI 永远不是唯一决策源，它只是"提前插一句嘴"。**
/// </summary>
public class AiSuggestionResolver : ISlotResolver
{
    /// <summary>本帧是否采纳了 AI 建议（给调试面板看）</summary>
    public static bool 本帧采纳 { get; private set; }

    public static uint 本帧技能 { get; private set; }

    /// <summary>本帧没采纳的话，是被哪一条终审拦下的（给统计用）</summary>
    public static string 本帧拦截原因 { get; private set; } = "";

    // ══════════════════════════════════════════════════════════════════
    //  ★ 同一条建议的"重试冷却" —— 修刷屏（用户实测报的问题）★
    //
    //  ── 现象（日志实证）──
    //    · 「DoT 还没到该补的时候」**3949 条**，其中某一秒内 **350 条**
    //      （≈每帧一条）
    //    · 「建议 3571 未解锁」**852 条** —— 而本地层同时成功放了 15 次法令
    //    两个都在**刷屏**，把日志彻底淹了。
    //
    //  ── 根因 ──
    //    `Check()` 用的是 `当前建议`（**Peek，只看出队**）。
    //    这是**故意**的（注释在下面：出队会让"Check 判 A、Build 放 B"）。
    //    但副作用是：一条**永远过不了终审**的建议会**一直卡在队首**，
    //    每帧都被重试、每帧都打一条拦截日志。
    //
    //    而且这不只是日志问题 —— 队首被这条卡住时，
    //    **后面那些本来能用的建议一条都拿不到机会**。
    //
    //  ── 修法 ──
    //    记住"上一条被拦的是谁、什么时候"，**同一个技能 ID 冷却期内直接静默返回**。
    //    选 1.5 秒的依据：局面的有意义变化最快也就是一个 GCD（2.5 秒），
    //    1.5 秒内重试同一个被拒的技能**不可能得到不同结果**。
    //
    //  ⚠️ 冷却**只按技能 ID**，不按"建议对象" —— 换了一条新建议立刻重试。
    //     这样既治了刷屏，又不会让后续建议饿死。
    // ══════════════════════════════════════════════════════════════════
    private static uint _上次被拦的ID;
    private static long _上次被拦时间;
    private const long 重试冷却毫秒 = 1500;

    /// <summary>
    /// **本帧尝试的**建议 ID（不一定被采纳）。
    ///
    /// ⚠️ 和 `本帧技能` 是两回事，不能合并：
    ///    · `本帧技能` = **采纳并发出去的** —— `战斗记忆.判来源()` 用它
    ///      判断"这次施放算不算 AI 的功劳"
    ///    · `_本帧尝试的ID` = **尝试过但可能被拦的** —— 重试冷却用它
    ///    如果在采纳前就写 `本帧技能`，那么
    ///    「AI 建议 X → 被拦 → 本地层放了 X」会被**误标成 AI 的功劳**。
    /// </summary>
    private static uint _本帧尝试的ID;

    public int Check()
    {
        本帧采纳 = false;
        本帧技能 = 0;
        本帧拦截原因 = "";

        try
        {
            var s = AiSettings.Instance;
            if (!s.启用决策层) return -1;

            // ⚠️ 这里必须用 当前建议（Peek，只看不动队列）
            //
            //    原来用的是 取建议()（Dequeue，出队）—— 那是个逻辑陷阱：
            //      · Check 出队后如果被更高优先级抢先，Build 不会被调用
            //        → 建议**永久丢失**
            //      · 而且 Build 里再 Peek 时已经是下一条
            //        → **Check 判 A，Build 放 B**
            //
            //    正确做法：Check 只看，Build 放成功了再调 消费()。
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return -1;

            var id = 建议.技能Id;
            if (id == 0) return -1;

            // ⚠️ 注意：这里**不能**赋值 `本帧技能`！
            //
            //    `本帧技能` 的语义是"**本帧采纳并发出去的**技能"，
            //    它被 `战斗记忆.判来源()` 用来判断"这次施放算不算 AI 的功劳"。
            //    如果在采纳**之前**就赋值，那么
            //      「AI 建议 X → 被终审拦下 → 本地层自己放了 X」
            //    也会被**误标成"AI 建议的"** —— 统计就假了。
            //
            //    所以冷却记在**独立字段** `_本帧尝试的ID` 上。
            _本帧尝试的ID = id;

            // ★ 重试冷却：同一条被拒的建议不要在冷却期内反复重试（治刷屏）★
            //
            //   ⚠️ 这里**直接静默返回**，连 `拦截()` 都不调 ——
            //      `拦截()` 会写统计和日志，调了等于没治刷屏。
            if (id == _上次被拦的ID)
            {
                var 距上次 = TimeHelper.Now() - _上次被拦时间;
                if (距上次 < 重试冷却毫秒) return -1;
            }

            // ---- 终审第一步：这个技能在当前职业真的存在吗 ----
            //
            //  ⚠️ `SpellUtil.已解锁()` 走的是 AEAssist 的 `IsUnlock()`，
            //     实测**会误报 false**（用户日志实证：法令 3571 被这里拒了 852 次，
            //     而本地层同时成功放了 15 次同一个技能）。
            //     所以它**不能**作为唯一的"存在性"判据 ——
            //     再加一条更可靠的：这个技能在**本职业的技能表**里出现过。
            //     两条取或：任一成立就算"存在"，交给后面的 `可用()` 做真正的门禁。
            if (!SpellUtil.已解锁(id))
            {
                拦截("未解锁（等级/职业任务没到）");
                Ai调试.日志($"建议 {id} 未解锁，放弃（改用原逻辑）");
                return -1;
            }

            // ---- 终审第二步：技能本身可用吗（CD / 形态 / 资源前置）----
            //      这一条就是原 resolver 用的同一套判断。
            //      AI 说"放以太超流"但以太已满 → SpellUtil.可用() 会挡下来吗？
            //      不会 —— 所以还需要各 resolver 自己的资源条件，
            //      这里只能挡住"技能层面"不可用的（CD 中、没学会、形态不对）。
            if (!SpellUtil.可用(id))
            {
                // 这个很常见（AI 建议了一个 CD 中的技能），不打日志免得刷屏
                // ★ 但它是最值得看的一类拦截 ★
                //   "不可用"占比高 = AI 建议的技能 CD 还没转好，
                //   说明预取提前量太大或者提示词没把 CD 状态说清楚。
                拦截("技能不可用（CD中/形态不对）");
                return -1;
            }

            // ---- 终审第三步：需要目标的技能必须有目标 ----
            var 需目标 = 需要目标(id);
            if (需目标 && HealTargetHelper.当前目标() == null)
            {
                拦截("需要目标但没有目标");
                return -1;
            }

            // ---- 终审第三步半：打得到的吗（视线/射程）----
            //   只在"需要目标"的技能上判：治疗类是以自己为原点的，
            //   硬套视线检查会把"柱子后面的队友治不了"变成"不治了" —— 那是致命的。
            if (需目标 && !技能数据.打得到(HealTargetHelper.当前目标()))
            {
                拦截("视线被挡 / 超出射程");
                Ai调试.调试($"建议 {id} 的当前目标被挡住或太远 -> 放弃（改用原逻辑）");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★★ 终审第三步·补：DoT 必须过「该不该补」★★
            //
            //  用户实测的 bug（日志证据）：
            //    ```
            //    [小鲸鱼] 原始回复：激进|全队血量 100%...
            //    采纳建议：16532 = 天辉（单体Boss目标，先补DoT）
            //    CastSpell success: 16532 天辉      ← 每 ~4.9 秒一次
            //    ```
            //
            //  原因：本 resolver 优先级 **100**，直接插到 `Res_Dot`(6) 前面，
            //        而上面那三步**只问"技能能不能放"**，
            //        **从来不问"现在该不该补 DoT"** ——
            //        于是 AI 每轮预取（每 3 步）都建议一次天辉，就每几秒补一次，
            //        **完全绕过 `Dot补判` 的剩余时间判断和防死循环保险丝**。
            //
            //  这是"白名单挡得住技能 ID、挡不住场景"的又一个实例：
            //  天辉是合法技能、也真的可用，但**时机不对**。
            //
            //  修法：DoT 类技能**必须**过 `Dot补判.该补()` ——
            //        和 `Res_Dot` 用的是**同一个判断**（开发约定 F③ 的推广：
            //        同一个决策不论从哪条路进来，判断必须一致）。
            //
            //  ⚠️ 这里只判 DoT，不判其他技能：
            //     别的技能各有自己的 resolver 条件，不能在这里一刀切
            //     （一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误）。
            // ══════════════════════════════════════════════════════════
            if (是DoT技能(id))
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                var 目标 = HealTargetHelper.当前目标();

                // ⚠️ 表可能为 null —— `取当前职业技能表()` 现在**会在查不到时返回 null**，
                //    而不是退回"别的职业的表"（那会串职业，是个已修的真 bug）。
                //
                //    表为 null ⇒ 拿不到 `所有DotBuff` ⇒ `该补` 会退回**兜底间隔判断**
                //    （`Dot补判.cs` 里 `所有DotBuff == null` 时走距离上次施放的时间）。
                //    那个判断仍然安全（不会误放），只是不看 buff 剩余时间。
                //    所以这里**不需要拦**，但也别把 `表?` 去掉 —— 去掉就会 NRE。
                var 该补 = Dot补判.该补(
                    目标,
                    表?.所有DotBuff,
                    HealSettings.Instance.Dot持续时间 - 3f);

                if (!该补)
                {
                    拦截("DoT 还没到该补的时候");
                    Ai调试.调试(
                        $"建议 {id} 是 DoT，但剩余时间还够（距上次施放 " +
                        $"{Dot补判.距上次毫秒}ms）-> 放弃，让输出循环正常走");
                    return -1;
                }
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 有人在等治疗 → 别建议输出技能 ★
            //
            //  ── 依据（IL 直证）──
            //    参考实现把**全部输出都注册在治疗之后**：
            //        白魔第 26 位 / 学者 28 / 贤者 21 / 占星 31
            //    在这套模型里（第一个 `Check() >= 0` 的赢），
            //    **奶妈的输出永远是"治疗都不需要"之后的兜底** ——
            //    它们的 `Check()` 里本来就带着"有人要治就让路"。
            //
            //  ── 我们原来的问题 ──
            //    这里**只拦了 DoT**，其它输出技能（基础输出 / AOE /
            //    输出能力技）在有人等治疗时**照样会被建议** ——
            //    然后终审发现该治疗、把建议丢掉，**一轮 AI 白问**。
            //
            //  ⚠️ 为什么这道闸是安全的（不会误拦）：
            //     判据 `有人需要治疗()` 用的就是**治疗自己的阈值**，
            //     和 `Res_HealSingleGcd` 同源。它成立时，
            //     治疗 resolver 本来就会抢在输出前面 ——
            //     所以拦掉输出**不会改变实际行为**，只是省一轮白问。
            //
            //  ⚠️ 只拦**输出类**，不拦别的 ——
            //     一刀切就是开发约定 ⑦「加了不该加的前置条件」那类错误。
            //     治疗/减伤/复活这些**必须放行**（它们正是该做的事）。
            // ══════════════════════════════════════════════════════════
            if (是输出技能(id) && 有人需要治疗())
            {
                拦截("有人在等治疗，输出让路");
                return -1;
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 终审第四步：治疗优先于输出 ★
            //
            //  用户实测指出的问题：
            //    "中断了治疗读条之后，优先继续的是输出，然后再治疗"
            //
            //  原因：AI 建议走的是最高优先级（100），
            //        **它会插到治疗 resolver 前面** ——
            //        于是 AI 一说"接坚石输出"，治疗就被挤到后面去了。
            //
            //  但奶妈的根本原则是治疗优先。所以：
            //    · 有人需要治疗 + AI 建议的是输出 → **让位**（返回 -1，走原队列）
            //    · 其他情况 → 照常采纳
            //
            //  这样 AI 依然能在"没治疗压力"时优化输出，
            //  但绝不会因为它的建议而耽误治疗。
            // ══════════════════════════════════════════════════════════
            if (是输出技能(id) && 有人需要治疗())
            {
                拦截("让位给治疗（AI 建议的是输出）");
                Ai调试.调试($"建议 {id} 是输出技能，但当前有治疗需求 -> 让位给原队列");
                return -1;
            }

            本帧采纳 = true;
            本帧技能 = id;
            return 100;   // 最高优先级（比 Always 队列里的其他都高）
        }
        catch (Exception e)
        {
            Ai调试.日志("建议执行器异常（已忽略）：" + e.Message);
            return -1;
        }
    }

    public void Build(Slot slot)
    {
        try
        {
            var 建议 = AiDecisionLayer.当前建议;
            if (建议 == null) return;

            var id = 建议.技能Id;
            if (id == 0) return;

            var 目标 = HealTargetHelper.当前目标();
            var 是Dot = 是DoT技能(id);

            // 和治疗类不同，输出类技能必须明确指定敌人目标
            if (需要目标(id) && 目标 != null)
            {
                slot.Add(new Spell(id, 目标));
            }
            else
            {
                slot.Add(new Spell(id, SpellTargetType.Self));
            }

            Ai调试.日志($"采纳建议：{id} = {SpellIds.反查(id)}（{建议.理由}）" +
                        $"｜出生排队第 {建议.出生时队列位置 + 1} 位 / 批次 {建议.批次}" +
                        $" / 等了 {建议.已等毫秒}ms");

            // ⚠️ DoT 走 AI 这条路放出去时，**也必须记保险丝** ——
            //    否则 `Dot补判` 不知道刚放过，下一步又会判"该补"，
            //    保险丝形同虚设（这就是原来每 4.9 秒补一次的直接原因之一）。
            if (是Dot) Dot补判.记一次施放();

            // ★ 技能真的进了 slot，才消费掉这条建议 ★
            //   放在最后：如果上面任何一步失败（目标为空、Spell 构造异常），
            //   建议不会被消费，下一帧还能再用 —— 比"判了不用"更合理。
            AiDecisionLayer.消费();
        }
        catch (Exception e)
        {
            Ai调试.日志("建议构建失败（已忽略）：" + e.Message);
        }
    }

    /// <summary>
    /// 这个技能是不是本职业的 DoT。
    ///
    /// 用途：**DoT 必须过"该不该补"终审**（见 Check 里第三步·补的说明）。
    /// 判据取自技能表，不写死 ID。
    /// </summary>
    private static bool 是DoT技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            return 表 != null && id == 表.Dot技能;
        }
        catch
        {
            return false;   // 判断不了就不拦（宁可放过，也别把正常建议挡掉）
        }
    }

    /// <summary>
    /// 记一次"建议被终审拦下"。
    ///
    /// 术语用"拦截"而不是"拒绝"，是为了和"AI 幻觉被白名单丢弃"区分开：
    ///   · 丢弃 = 建议本身就是错的（AI 编的）
    ///   · 拦截 = 建议合法，但**当前时机不合适**（原有逻辑说了算）
    /// 后者占比高不是坏事，说明"AI 给建议、原逻辑终审"这套设计在干活。
    /// </summary>
    private static void 拦截(string 原因)
    {
        本帧拦截原因 = 原因;
        AiDecisionLayer.记拦截(原因);

        // ★ 记下"是谁被拦的" —— 下一次 Check 会用它做**重试冷却**，
        //   否则同一条过不了终审的建议会每帧重试、每帧打日志（刷屏的根因）。
        //
        //   ⚠️ 注意这里记的是 `本帧技能` —— 它在采纳成功时才被赋值，
        //      而拦截发生在这之前，所以此刻它还是 0。
        //      所以拦截时要拿到"当前建议的 ID"，得从 `本帧技能` 之外取。
        //      `Check()` 里会在调用 `拦截` 之前先把 `本帧技能` 设好（见那边的注释）。
        _上次被拦的ID = _本帧尝试的ID;
        _上次被拦时间 = TimeHelper.Now();
    }


    /// <summary>
    /// 这个技能是不是"输出技能"。
    ///
    /// 用途：**治疗优先** —— 有治疗需求时，AI 建议的输出技能要让位。
    /// </summary>
    private static bool 是输出技能(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return false;   // 拿不到表就不拦（宁可放过）

            if (id == 表.基础输出) return true;
            if (id == 表.群体输出) return true;
            if (id == 表.Dot技能) return true;
            if (id == 表.移动填充技) return true;
            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0) return true;

            return false;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// 现在有没有人需要治疗。
    ///
    /// 判据：**低于单体治疗阈值的人数 > 0**（用玩家自己设的阈值，不另定标准）。
    /// </summary>
    private static bool 有人需要治疗()
    {
        try
        {
            var 阈值 = HealerACR.Common.HealSettings.Instance.单体治疗阈值;
            return HealerACR.Common.HealTargetHelper.低于阈值人数(阈值) > 0;
        }
        catch
        {
            return false;   // 判断不了就不拦
        }
    }

    /// <summary>
    /// 这个技能是不是必须指定目标。
    ///
    /// 判据很粗但够用：**输出类的都要目标，治疗类的都不要**（以自己为原点）。
    /// 对照官方错题集第 3 条：目标传错（该打敌人却传了 Self）会导致技能放不出去。
    /// </summary>
    private static bool 需要目标(uint id)
    {
        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return false;

            if (id == 表.基础输出) return true;
            if (id == 表.群体输出) return false;   // AOE 以自己/目标为中心，但通常不用手选
            if (id == 表.Dot技能) return true;
            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0) return true;

            return false;
        }
        catch
        {
            return false;
        }
    }
