using AEAssist;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// 对局收尾 —— 判断"这场打完了"，触发落盘 + AI 提炼。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 怎么判断"副本结束"（用户选的方案 + 一处工程取舍）★
///
///    用户要的是：**副本完成提示 + 脱战**。
///
///    工程现实：AEAssist 没有暴露"副本完成"这个事件，
///    能拿到的只有 `Data.CurrentContentFinderConditionId`（副本 ID）——
///    它在**离开副本时变 0**，但"打完但还没出去"这段是检测不到的。
///
///    所以实际实现是**两个条件都往保守方向做**：
///      ① **脱战** —— 这是必要条件
///      ② **连续脱战 ≥ <see cref="收尾延迟秒"/> 秒** —— 代替"完成提示"
///         这样能避开副本内小怪之间的正常脱战间隙
///         （那种间隙一般十几秒，Boss 打完的收尾更长）
///      ③ 样本条数 ≥ <see cref="最少条数"/> —— 太短的（比如刚进本就被踢）不提炼
///
///    ⚠️ **取舍说明（如实记录）**：
///       延迟判定是**启发式**，不是精确的"副本完成"信号。
///       后果：
///         · 小怪阶段如果脱战超过 20 秒 → 会**提前提炼一次**
///           （不是错误，只是把一局拆成几段，结论仍然有效）
///         · 如果打完立刻退本 → 脱战计时可能不够 → 那局**不会自动提炼**
///           （兜底：GUI 上有「立即提炼」按钮，也可以下次进本时手动补）
///       之所以选它，是因为它**不会误报成"副本完成"然后丢数据** ——
///       最坏情况只是多提炼或少提炼，数据本身**总是已经落盘了**
///       （落盘是脱战就写，不等延迟）。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 对局收尾
{
    /// <summary>连续脱战多少秒算"这局结束了"</summary>
    public const int 收尾延迟秒 = 20;

    /// <summary>少于这么多条记录就不提炼（样本太少，提不出东西）</summary>
    public const int 最少条数 = 30;

    private static bool _上次在战斗;
    private static long _脱战开始;
    private static bool _已落盘等待提炼;

    /// <summary>上次收尾的结果（给 GUI 显示）</summary>
    public static string 上次结果 { get; private set; } = "（还没有收尾过）";

    /// <summary>每帧调用（挂在心跳里）</summary>
    public static void 每帧更新()
    {
        try
        {
            // ⚠️ 只在记录模式里工作 —— 非记录模式完全没有记录，
            //    不判断也不落盘（否则会对每个副本都跑一遍空逻辑）
            if (!记录模式.开启)
            {
                _上次在战斗 = false;
                _脱战开始 = 0;
                _已落盘等待提炼 = false;
                return;
            }

            var 在战斗 = 在战斗中();

            // ── 战斗刚开始 → 重置计时 ──
            if (在战斗)
            {
                _上次在战斗 = true;
                _脱战开始 = 0;
                return;
            }

            // ── 刚脱战 → 记下时刻，并**立刻落盘**（不等延迟）──
            //    理由：数据先存下来最要紧。万一这之后卡了、崩了、退出游戏，
            //          记录不会丢。提炼可以慢，落盘不能等。
            if (_上次在战斗 && !在战斗)
            {
                // ★ 本局综合效果指标打一条日志（**打完一把**才有意义）
                //   [!] 放在"刚脱战"这里而不是进战时 —— 进战时上一局的数据还在，会记错。
                //   [!] 必须在 `return` 之前 —— 这个分支末尾是 return，
                //       插在它后面就是不可达（编译器 CS0162 会直接报出来）。
                try { 战斗指标.打日志(); } catch { }

                _上次在战斗 = false;
                _脱战开始 = TimeHelper.Now();

                if (对局记录.有记录)
                {
                    var 文件 = 对局记录.落盘("脱战");
                    if (!string.IsNullOrEmpty(文件))
                    {
                        _已落盘等待提炼 = true;
                        上次结果 = $"已落盘（{对局记录.本局条数} 条），等待提炼";
                    }
                }
                return;
            }

            // ── 脱战中：够久了就提炼 ──
            if (_已落盘等待提炼 && _脱战开始 > 0 &&
                TimeHelper.Now() - _脱战开始 >= 收尾延迟秒 * 1000L)
            {
                _已落盘等待提炼 = false;
                _脱战开始 = 0;

                var 文件 = 对局记录.最后文件;
                if (string.IsNullOrEmpty(文件))
                {
                    上次结果 = "落盘文件丢失，跳过提炼";
                    return;
                }

                if (对局记录.上次条数 < 最少条数)
                {
                    上次结果 = $"样本太少（{对局记录.上次条数} < {最少条数}），跳过提炼";
                    LogHelper.Info("[对局收尾] " + 上次结果);
                    return;
                }
                上次结果 = "正在提炼…";
                _ = 记忆库.提炼(文件);
            }
        }
        catch (Exception e)
        {
            // 收尾逻辑绝不能影响战斗
            LogHelper.Error("[对局收尾] 异常：" + e.Message);
        }
    }

    /// <summary>手动触发一次收尾（GUI 按钮）—— 用户不想等 20 秒时用</summary>
    public static void 立即收尾()
    {
        try
        {
            if (!对局记录.有记录)
            {
                上次结果 = "当前没有正在记录的对局";
                return;
            }

            var 条数 = 对局记录.本局条数;
            var 文件 = 对局记录.落盘("手动收尾");
            _已落盘等待提炼 = false;
            _脱战开始 = 0;

            if (string.IsNullOrEmpty(文件))
            {
                上次结果 = "落盘失败";
                return;
            }

            if (条数 < 最少条数)
            {
                上次结果 = $"已落盘（{条数} 条），但样本太少不提炼";
                return;
            }

            上次结果 = $"已落盘并开始提炼（{条数} 条）";
            _ = 记忆库.提炼(文件);
        }
        catch (Exception e)
        {
            上次结果 = "手动收尾失败：" + e.Message;
        }
    }

    private static bool 在战斗中()
    {
        try { return Core.Me.InCombat(); }
        catch { return false; }
    }

    /// <summary>
    /// 距离上次脱战过了多久（秒）；正在战斗或没有计时返回 -1。
    /// 给 GUI 显示"还要等多久"用。
    /// </summary>
    public static double 脱战已过秒()
    {
        if (_脱战开始 == 0 || _上次在战斗) return -1;
        try { return (TimeHelper.Now() - _脱战开始) / 1000.0; }
        catch { return -1; }
    }

    /// <summary>战斗重置 / 换本 / 切职业时清</summary>
    public static void 重置()
    {
        _上次在战斗 = false;
        _脱战开始 = 0;
        _已落盘等待提炼 = false;
    }
}
