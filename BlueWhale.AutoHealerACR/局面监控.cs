using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// 局面监控 —— **给 <see cref="AiDecisionLayer.局面剧变"/> 补上触发点。**
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么需要这个类 ★
///
///    `AiDecisionLayer.局面剧变()` 早就写好了（清空预取队列），
///    注释里也写明了判据是"换目标 / 血量骤降 / 进战脱战"——
///    但**没有任何地方调用它**，等于整段逻辑是死的。
///
///    这是个很典型的"静默失效"：代码能编译、不报错、不影响运行，
///    就是不做任何事。光看 `AiDecisionLayer` 自己看不出来 ——
///    必须**从调用点反查**才会发现"写了却没人调"。
///
///  ── 为什么不在 Check 里判，要单独一个类 ──
///
///    判据需要"上一帧的值"来对比（血量、目标、战斗状态），
///    这就是**状态**。而按开发约定，带状态的模块必须：
///      · 在 OnResetBattle 清一次
///      · 在 OnTerritoryChanged 清一次
///    集中在这一个类里，清理点只有一处，不容易漏。
///
///  ── 为什么会误触发也没关系 ──
///
///    清空队列的代价只是"重新问一次 AI"，
///    而**留着过期建议的代价是"按错的技能"** —— 后者严重得多。
///    所以阈值取得偏灵敏（见下面的常量）。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 局面监控
{
    /// <summary>一个人血量在单帧内掉超过这么多 → 判"骤降"</summary>
    private const float 骤降阈值 = 0.12f;
    
    /// <summary>
    /// **只有坦克在掉血时**用的宽阈值 —— 那是坦克正常承伤，不是局面变了。
    ///
    /// [!] 小怪阶段 T 被几只怪围着打、单帧掉 12% 是常态；
    ///     用 0.12 会**每 2 秒触发一次剧变**，队列永远攒不满。
    /// </summary>
    private const float 坦克骤降阈值 = 0.30f;

    /// <summary>两次剧变之间至少隔这么久（毫秒）—— 防止拉群怪时疯狂重取</summary>
    private const long 冷却毫秒 = 2000;

    private static long _上次剧变;

    /// <summary>上一帧看的"队伍最低血量"。-1 = 还没有基准</summary>
    private static float _上次最低血量 = -1f;

    /// <summary>上一帧的当前目标 ID（0 = 没目标）</summary>
    private static uint _上次目标;

    /// <summary>上一帧是否在战斗中</summary>
    private static bool _上次战斗中;

    /// <summary>最近一次剧变的原因（给调试面板看）</summary>
    public static string 最近原因 { get; private set; } = "（还没有过）";

    /// <summary>累计剧变次数</summary>
    public static int 剧变次数 { get; private set; }

    /// <summary>
    /// 每帧调用（挂在 <c>AiHeartbeat</c> 的心跳里）。
    ///
    /// 顺序有意安排：**先算出基准值，再判是否剧变** ——
    /// 反过来的话第一次调用会因为"没有上一帧"而误判。
    /// </summary>
    public static void 每帧更新()
    {
        try
        {
            var 战斗现在 = Core.Me.InCombat();

            // ══════════════════════════════════════════════════════════
            //  ★ **AI 初始化没成功之前，不做任何"剧变重取"** ★
            //
            //  ── 为什么（日志实证）──
            //     进本时会连续看到：
            //        局面剧变：进战 -> 作废预取队列
            //        局面剧变：目标切换 -> 作废预取队列
            //     而 `触发()` 走的是 **`局面剧变并重取()`** —— 它会
            //     **立刻发一次新请求**。
            //
            //     于是：初始化那一次大请求还在跑，这边又插进来几次小的，
            //     互相抢连接/额度，初始化更容易超时 ——
            //     而初始化在成功之前，AI 层本来就是哑的，
            //     这些预取**取回来也没人用**。
            //
            //  ── 所以 ──
            //     初始化没成功 = 一律跳过。这期间**完全依赖本地逻辑**
            //     （本地 resolver 不依赖 AI，本来就是能独立工作的）。
            //
            //  ⚠️ 只是"跳过触发"，**基准照常维护** ——
            //     否则初始化完成的那一刻会攒出一个巨大的假跌幅，
            //     立刻误触发一次"血量骤降"。
            //     所以下面用 `跳过触发` 标记，而不是 return。
            // ══════════════════════════════════════════════════════════
            var AI还没好 = false;
            try { AI还没好 = !Ai初始化.已完成; } catch { }

            // ① 战斗状态变化：脱战 → 进战（这是最强的"局面变了"信号）
            //    脱战方向不用管 —— OnResetBattle 已经会清一次了。
            if (战斗现在 && !_上次战斗中)
            {
                _上次战斗中 = 战斗现在;
                基准归零();          // 进战瞬间血量/目标都要重新取基准
                if (!AI还没好) { 触发("进战"); return; }
            }
            _上次战斗中 = 战斗现在;

            if (!战斗现在)
            {
                基准归零();
                return;              // 不在战斗里不用管（也没队列要维护）
            }

            var 现在 = TimeHelper.Now();

            // ② 当前目标换了
            //    预取的建议是"针对某个目标"给的（打谁、给谁上 DoT），
            //    目标一换，队列里剩下的建议很可能全是给旧目标的。
            // ══════════════════════════════════════════════════════════════
            //  ★ **盯「我们在打的目标」，不是「玩家手动选中的目标」** ★
            //
            //  [!] 原来这里是 `HealTargetHelper.当前目标()` ——
            //      它就是 `Core.Me.GetCurrTarget()`，**玩家自己选的那个**。
            //      ==> 玩家切一下目标就触发一次剧变（清队 + 立刻重取）。
            //      ==> 用户实测：「有小怪阶段一直在切换目标」正是这个。
            //
            //  [!] 为什么那是错的对象：
            //      我们**输出用的是 `输出目标.选()`**（自己的粘滞选择器），
            //      它**不看玩家选谁**（`输出目标.cs` 类注释原文：
            //      「本类只返回该打的目标…玩家选中的目标不会被改」）。
            //      ==> 玩家切目标**不构成「局面变了」** ——
            //          预取建议针对的是 `输出目标` 粘住的那个，它没变。
            //
            //  [!] 改用 `输出目标.粘住的目标`（0 时退回玩家选中的，比如刚开怪）。
            //      顺带：这个值**不再每帧抖**，所以目标切换触发次数会大幅下降。
            // ══════════════════════════════════════════════════════════════
            var 目标Id = HealTargetHelper.当前目标()?.EntityId ?? 0;
            try
            {
                var 粘 = 输出目标.粘住的目标;
                if (粘 != 0) 目标Id = (uint)粘;
            }
            catch { }

            if (目标Id != _上次目标)
            {
                var 从有到有 = _上次目标 != 0 && 目标Id != 0;
                _上次目标 = 目标Id;

                // 只在"从一个目标换到另一个目标"时算剧变。
                // 从无到有 / 从有到无 不算 —— 那是很常见的瞬间状态
                // （目标死了、切视角），不值得重取。
                if (从有到有 && !AI还没好 && 现在 - _上次剧变 >= 冷却毫秒)
                {
                    基准归零();
                    触发("目标切换");
                    return;
                }

                // ⚠️ AI 还没好：**基准归零，但不触发** ——
                //    归零是必要的（换目标了，旧基准没意义），
                //    不触发是因为这会儿取回来的建议没人用，
                //    而且会和初始化那次大请求抢资源。
                if (从有到有 && AI还没好) 基准归零();
            }

            // ③ 队伍血量骤降
            // ══════════════════════════════════════════════════════════════
            //  ★ 门槛分档：**只有 T 在掉血 = 坦克正常承伤，不是「局面变了」** ★
            //
            //  [!] 用户原话：
            //      「小怪阶段 T 血量波动大很正常 但是看日志 ai 一直在局面巨变」
            //      「在只有 T 掉血的情况下 能不能取 T 的预测综合
            //        作为小怪阶段触不触发局面巨变」
            //
            //  [!] 为什么这是真问题：
            //      每次触发 = `局面剧变并重取()` = **清空队列 + 立刻发新请求**。
            //      小怪阶段 T 被几只怪围着打、单帧掉 12% 是常态
            //      ==> 队列**永远攒不满** ==> AI 建议老是还没有或被丢掉
            //      ==> 这就是用户问的「整体命中率不高」。
            //
            //  [!] 判据（按用户建议的思路）：
            //      · **只有坦克在明显掉血**（其他人都稳）= 坦克在正常承伤 ->
            //        阈值放宽（用 `坦克骤降阈值`），因为那不是局面变了。
            //      · 有**多人**同时掉血 / 自己也掉 = 真的来大伤害了 ->
            //        用原来敏感的 `骤降阈值`。
            //
            //  [!] 为什么不用 `伤害预测` 的坦克预测值当门槛：
            //      预测量是未来 6 秒累计，而这里是单帧跌幅，量纲不同；
            //      硬凑会让阈值变得无法解释。用**固定但更宽**的坦克阈值更稳，
            //      而且谁在掉血这个信号本身就已经把两种情况分开了。
            // ══════════════════════════════════════════════════════════════
            var 最低 = 队伍最低血量();
            if (最低 < 0f) return;

            if (_上次最低血量 >= 0f)
            {
                var 跌幅 = _上次最低血量 - 最低;

                // 跌幅超过阈值 = 有人突然吃了一大口伤害
                // 注意：HoT 回血造成的"上涨"不算剧变，所以只判跌幅
                // [!] 阈值分档 —— 只有 T 掉血时用宽阈值（见 `坦克骤降阈值` 的说明）
                var 本次阈值 = 只有坦克在掉血() ? 坦克骤降阈值 : 骤降阈值;
                if (跌幅 >= 本次阈值 && !AI还没好 && 现在 - _上次剧变 >= 冷却毫秒)
                {
                    // ⚠️ 顺序要紧：**先用旧值拼好文案，再更新基准**。
                    //    反过来写的话 _上次最低血量 已经被覆盖成新值，
                    //    日志里的跌幅会永远显示成 0%（自己踩过一次）。
                    var 旧 = _上次最低血量;
                    _上次最低血量 = 最低;

                    触发($"血量骤降 {跌幅 * 100f:F0}%（{旧 * 100f:F0}% -> {最低 * 100f:F0}%）");
                    return;
                }
            }

            _上次最低血量 = 最低;
        }
        catch
        {
            // 监控本身绝不能影响战斗
        }
    }

    /// <summary>真正触发：清空 + 立刻重取 + 记录</summary>
    private static void 触发(string 原因)
    {
        try
        {
            _上次剧变 = TimeHelper.Now();
            剧变次数++;
            最近原因 = 原因;

            Ai调试.日志($"局面剧变：{原因} -> 作废预取队列");

            // 用"并重取"而不是"只清空"：
            // 只清空的话还要等预取节流过去才补货，
            // 而剧变之后那几秒正是最需要建议的时候。
            AiDecisionLayer.局面剧变并重取();
        }
        catch { }
    }

    /// <summary>取队伍里的最低血量比例；取不到返回 -1</summary>
    /// <summary>
    /// **是不是只有坦克在明显掉血**（其他人都不缺）—— 用来给骤降阈值分档。
    ///
    /// [!] 判定：队伍里（除坦克外）没有任何人低于 `健康线`，且坦克确实在掉。
    ///     这种情况小怪阶段极其常见，**不该算局面剧变**（用户实测）。
    ///
    /// [!] 判不了就返回 **false**（用敏感的默认阈值）——
    ///     宁可多触发一次，也不要该触发时没触发。
    /// </summary>
    private static bool 只有坦克在掉血()
    {
        try
        {
            const float 健康线 = 0.85f;
            var 坦克Id = 0ul;
            try { 坦克Id = HealTargetHelper.队伍里的坦克()?.GameObjectId ?? 0; } catch { }
            if (坦克Id == 0) return false;      // 没坦克就别自作聪明
    
            // 自己也要健康（奶妈挨打是大事）
            if (Core.Me.CurrentHp * 1f / Math.Max(1u, Core.Me.MaxHp) < 健康线) return false;
    
            var 队友 = PartyHelper.CastableAlliesWithin30;
            if (队友 == null) return false;
    
            foreach (var r in 队友)
            {
                // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                if (r == null || !r.对象有效()) continue;
                if (r.GameObjectId == 坦克Id) continue;      // 坦克跳过
                if (r.GameObjectId == Core.Me.GameObjectId) continue;
                var 比例 = r.CurrentHp * 1f / Math.Max(1u, r.MaxHp);
                if (比例 < 健康线) return false;   // 还有别人缺 -> 不是只有坦克
            }
    
            return true;
        }
        catch
        {
            return false;
        }
    }
    
    private static float 队伍最低血量()
    {
        try
        {
            var 最低 = 2f;
            var 有 = false;

            // 自己也算一个 —— 奶妈自己吃伤害同样影响决策
            var 我 = Core.Me.CurrentHp * 1f / Math.Max(1u, Core.Me.MaxHp);
            最低 = 我;
            有 = true;

            var 队友 = PartyHelper.CastableAlliesWithin30;
            if (队友 != null)
            {
                foreach (var r in 队友)
                {
                    // ★ 判 对象有效()：换图时成员被释放但仍非 null（哨兵 0x12345679），只判 null 会崩
                    if (r == null || !r.对象有效()) continue;
                    var 比例 = r.CurrentHp * 1f / Math.Max(1u, r.MaxHp);
                    if (比例 < 最低) 最低 = 比例;
                    有 = true;
                }
            }

            return 有 ? Math.Clamp(最低, 0f, 1f) : -1f;
        }
        catch
        {
            return -1f;
        }
    }

    private static void 基准归零()
    {
        _上次最低血量 = -1f;
        _上次目标 = 0;
    }

    /// <summary>战斗重置 / 换本时清（配合 状态重置钩子）</summary>
    public static void 重置()
    {
        try
        {
            _上次剧变 = 0;
            _上次战斗中 = false;
            基准归零();
            最近原因 = "（还没有过）";
        }
        catch { }
    }

    /// <summary>一行状态（设置页 / 调试用）</summary>
    public static string 状态描述()
        => $"局面剧变 {剧变次数} 次｜最近：{最近原因}";
}
