    /// <summary>
    /// 把一行"可能有格式噪声"的回复**归一化**成 `技能ID|理由`。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么要做这个（日志实证）★
    ///
    ///   实测日志里出现过：`解析失败（批次 32）：『1. 25865|单体环境，用基础输出填充』`
    ///   —— AI 的**内容完全正确**，只是前面多了个 `1. ` 序号，就被整条丢了。
    ///
    ///   同一个日志里还有更糟的：AI 说
    ///      "或者考虑给T减伤？没有T减伤技能在列表里。野战治疗阵是团队减伤，但CD中（27.9）。"
    ///   这句在日志里**连"解析失败"都没记**（因为不以数字开头、也不含竖线），
    ///   等于**静默丢弃** —— 用户完全看不到 AI 其实考虑过减伤。
    ///
    ///  ── 原则 ──
    ///    格式宽容、**语义严格**：
    ///      · 归一化只去掉**列表标记 / 引号 / 空白**这类纯排版噪声
    ///      · 归一化后仍然必须满足 `数字|理由`，内容一个字都不改
    ///      · 真正不合格式的（纯散文），照旧计失败 —— 那样才能发现提示词在漂移
    ///
    ///  ⚠️ 归一化**改动过的**行要留日志：否则提示词格式约束失效了我们都不知道。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static string 归一化行(string 原始)
    {
        var s = 原始.Trim();

        // ① 去掉 markdown 列表标记：`1. ` `1) ` `- ` `* ` `• ` `1、`
        s = Regex.Replace(s, @"^\s*(?:[-*•]|\d+\s*[.)、:])\s*", "");

        // ② 去掉包裹的引号 / 反引号 / 书名号（AI 爱把输出包起来）
        s = s.Trim('`', '"', '\'', '「', '」', '『', '』', '“', '”');

        // ③ 去掉 markdown 加粗标记（`**25859**|...`）
        s = s.Replace("**", "");

        return s.Trim();
    }

    private static int 解析并填充(string 回复, int 批次 = 0, 候选集.快照? 快照 = null)
    {
        var 条数 = 0;

        // ══════════════════════════════════════════════════════════════
        //  ★ 记下进入时の世代 —— 入队前再校验一次 ★
        //
        //  [!] 为什么调用方已经有校验（`预取()` 里 L613），这里还要再来一次：
        //      防御要放在**被保护的一方**。`解析并填充` 会被多条路径调到，
        //      将来有人加了一个新调用点、忘了校验世代，这里能兜住。
        //      本项目已经在"以为调用方会做、结果漏了"上栽过多次。
        //
        //  [!] 中途被作废的判定点：每入队一条之前查一次 ——
        //      一次解析可能要几毫秒，期间完全可能发生局面剧变。
        // ══════════════════════════════════════════════════════════════
        var 进入世代 = _世代;

        try
        {
            var 行 = 回复.Split('\n', StringSplitOptions.RemoveEmptyEntries);

            foreach (var 原始行 in 行)
            {
                if (条数 >= 每次请求步数) break;

                if (string.IsNullOrWhiteSpace(原始行)) continue;

                var 归一 = 归一化行(原始行);

                // 归一化改动了内容 → 记一笔（说明提示词的格式约束在漂移，
                // 该去调提示词，而不是靠解析器一直兜着）
                if (归一 != 原始行.Trim() && 归一.Length > 0)
                {
                    格式噪声次数++;
                    Ai调试.调试($"格式噪声（批次 {批次}）：『{原始行.Trim()}』-> 『{归一}』");
                }

                var 段 = 归一.Split('|', 2);
                if (段.Length == 0) continue;

                // ══════════════════════════════════════════════════════════
                //  ★ 候选编号 `C1|理由` —— 候选层的主格式 ★
                //
                //  [!] 为什么优先解析它：
                //      候选是**本地生成的、已验证合法**的动作（**带目标**）。
                //      让 AI 引用编号比让它写技能 ID 更安全：
                //        · 不会幻觉出不存在的技能（编号只可能来自我们的候选表）
                //        · **目标明确** —— 不再"AI 说治坦克、本地治了血最少的别人"
                //
                //  [!] 解析不出候选就**退回老格式**（`技能ID|理由`）——
                //      候选层异常/为空时不能整个失效，那是向后兼容的底线。
                // ══════════════════════════════════════════════════════════
                var 首段 = 段[0].Trim();
                if (首段.Length >= 2 &&
                    (首段[0] == 'C' || 首段[0] == 'c') &&
                    uint.TryParse(首段.AsSpan(1), out _))
                {
                    // ★ 按**请求时那份快照**解析 —— 不是按当前候选 ★
                    //
                    //  [!] 两轮审阅的共同修法核心：
                    //      用"当前候选"解析会出现
                    //          AI 请求时 C1 = 治坦克
                    //          期间候选重排，C1 变成 DoT Boss
                    //          AI 回 C1 -> 解析成 DoT Boss -> **执行错动作**
                    //      按请求时的快照解析，C1 永远是 AI 当时看到的那个动作。
                    //
                    //  [!] 现在是**直接收对象**（不是按号再查）：
                    //      少一次查表就少一个失败模式 —— "快照已淘汰"
                    //      这种情况在新写法下根本不存在。
                    if (快照 == null)
                    {
                        解析失败次数++;
                        Ai调试.调试("候选快照为空，本批建议全部丢弃（候选层可能异常）");
                        return 条数;
                    }

                    var 候 = 快照.解析(首段);
                    if (候 == null)
                    {
                        解析失败次数++;
                        Ai调试.调试($"候选 {首段} 在快照 #{快照.快照Id} 里找不到，丢弃");
                        continue;
                    }

                    if (进入世代 != _世代) return 条数;

                    入队(new 建议
                    {
                        技能Id = 候.技能Id,
                        施法目标模式 = 候.施法目标模式,   // ★ 群疗=自己、单奶=队友 ★
                        目标Id = 候.目标Id,
                        关注目标名 = 候.关注目标名,
                        理由 = (段.Length > 1 ? 段[1].Trim() : "") + $"（候选{首段}）",
                        生成时间 = TimeHelper.Now(),
                        出生时队列位置 = 队列计数(),
                        批次 = 批次,
                    });
                    条数++;
                    continue;
                }

                if (!uint.TryParse(首段, out var id))
                {
                    // ★ 记下来：这是"AI 没按格式回" ★
                    //   原来直接 continue，统计上看不见 ——
                    //   而格式问题恰恰是提示词要调的最常见原因。
                    解析失败次数++;
                    Ai调试.调试($"解析失败（批次 {批次}）：『{原始行.Trim()}』不是 `技能ID|理由` 格式");
                    continue;
                }

                if (id == 0) continue;   // AI 说"数据不足"，跳过这行（这是**合规**回复，不算失败）

                // ★ 白名单校验：防幻觉的最后一道闸 ★
                if (!在可选清单里(id))
                {
                    丢弃幻觉次数++;
                    Ai调试.日志($"建议的技能 {id} 不在可选清单里，已丢弃（疑似幻觉）");
                    continue;
                }

                // ★ 入队前再校验：期间发生局面剧变就不入队了 ★
                //   注意此时**不能** `return 条数` 之外还继续解析 ——
                //   剩下的条目同样是基于旧局面的，全部丢弃。
                if (进入世代 != _世代)
                {
                    Ai调试.调试($"解析期间局面剧变（第 {进入世代} 代 -> 第 {_世代} 代），" +
                                $"丢弃剩余 {每次请求步数 - 条数} 条建议");
                    return 条数;
                }

                入队(new 建议
                {
                    技能Id = id,
                    理由 = 段.Length > 1 ? 段[1].Trim() : "",
                    生成时间 = TimeHelper.Now(),
                    出生时队列位置 = 队列计数(),   // 排在它前面的已有几条
                    批次 = 批次,
                });

                条数++;
            }
        }
        catch (Exception e)
        {
            Ai调试.日志("建议解析异常：" + e.Message);
        }

        return 条数;
    }

