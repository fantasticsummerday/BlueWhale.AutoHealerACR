using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;
using System.Text.RegularExpressions;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// 决策层（阶段 B）—— AI 出**具体技能建议**。
///
/// ══════════════════════════════════════════════════════════════════
///  ⚠️ 核心设计：**预取多步**（不要"现问现用"）
///
///  第一版是"每次都现问下一个 GCD"：
///      GCD 2.5 秒 → 问 AI 要 1.5~3 秒 → 答案回来时 GCD 早过了 → 过期
///      实测统计：命中 681 / 过期 875 —— **一半以上是白问的**
///
///  改成本版的思路：**让 AI 提前备货**
///      · 一次请求让它给出**接下来 3 步**的技能序列（不是一个）
///      · 后台持续维持队列里有 2~3 条待用建议
///      · 主循环从队列头部取 —— 取的时候它通常已经躺在那儿了
///
///  这样一来，"AI 响应慢" 就不致命的 ——
///  因为**它是在为未来备货，而不是为当下救火**。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class AiDecisionLayer
{
    /// <summary>一条 AI 建议</summary>
    public sealed class 建议
    {
        public uint 技能Id;
        public string 理由 = "";
        public long 生成时间;

        /// <summary>
        /// 有效期：**按 GCD 数算**（比按毫秒合理）。
        /// 一个 GCD 2.5 秒，给 2 个 GCD 的容忍度 = 5 秒。
        /// </summary>
        public const long 有效期毫秒 = 5000;

        /// <summary>
        /// 这条建议"被预取出来的那一刻"，队列里已经排了几条。
        ///
        /// 用途：**判断命中率低是不是"排队排太久"造成的** ——
        /// 一次请求给 3 步，第 3 步天然要等 2 个 GCD 才轮得到，
        /// 本来就更容易过期。有这个字段才能把"排太后面"和
        /// "AI 建议得不对"两种情况分开。
        /// </summary>
        public int 出生时队列位置;

        /// <summary>被 AI 建议时，这一批是第几批发出来的</summary>
        public int 批次;

        public bool 还新鲜 => TimeHelper.Now() - 生成时间 <= 有效期毫秒;

        /// <summary>已经等了多久（毫秒）</summary>
        public long 已等毫秒 => TimeHelper.Now() - 生成时间;
    }

    /// <summary>预取队列（先进先出）</summary>
    private static readonly Queue<建议> _队列 = new();

    /// <summary>队列维持的目标长度 —— 低于这个数就去补货</summary>
    private const int 目标长度 = 3;

    /// <summary>一次请求让 AI 给几步</summary>
    private const int 每次请求步数 = 3;

    private static long _上次预取;
    private static bool _预取中;
    private static long _上次局面变化;   // 局面剧变时强制清空队列重来

    public static bool 预取中 => _预取中;
    public static int 队列长度 => _队列.Count;

    /// <summary>队首建议（不消费），给 UI 显示用</summary>
    public static 建议? 当前建议
    {
        get
        {
            foreach (var s in _队列)
            {
                if (s.还新鲜) return s;
            }
            return null;
        }
    }

    // ==================== 统计（给"阶段 B 命中率"看） ====================
    //
    // ══════════════════════════════════════════════════════════════════
    //  ⚠️ 旧统计只有一个「过期」计数，它把**两件完全不同的事**混在了一起：
    //
    //     · 建议被采纳入 slot 之后，用完了 → 正常损耗
    //     · 建议躺在队列里没人用，等到过期 → **真正的浪费**
    //
    //    所以"命中 681 / 过期 875"这个 44% 里，有一部分其实是
    //    "用过了但也被算进过期"，真实的浪费比例是**看不出来的**。
    //
    //  现在按"为什么没被用上"分开记，才能定位到底卡在哪一环：
    //    解析失败  → 提示词/格式问题
    //    幻觉丢弃  → AI 编了清单外的技能
    //    局面清空  → 建议是对的，但战场变了（这是**好**的，说明保护生效）
    //    排队过期  → 预取节奏 vs GCD 节奏不匹配
    // ══════════════════════════════════════════════════════════════════

    /// <summary>被采纳并放进 slot 的次数（= 真正用上的）</summary>
    public static int 命中次数 { get; private set; }

    /// <summary>躺在队列里没人用、等到过期的条数（= 真正的浪费）</summary>
    public static int 过期次数 { get; private set; }

    /// <summary>其中"因为排在其他建议后面才等到过期"的条数（预取节奏问题）</summary>
    public static int 排队过期条数 { get; private set; }

    /// <summary>AI 返回了但解析不出技能 ID 的行数（格式问题）</summary>
    public static int 解析失败次数 { get; private set; }

    /// <summary>
    /// 需要**归一化才解析出来**的行数（列表序号 / 引号 / 加粗之类的格式噪声）。
    ///
    /// 单列这个是为了区分两件事：
    ///   · 解析失败 = AI 没给 `ID|理由`，要调**提示词**
    ///   · 格式噪声 = 内容对了、外面裹了层壳，解析器能兜住，但提示词也该收紧
    /// 混在一起看的话，会把"能兜住的"和"真丢了的"当成一回事。
    /// </summary>
    public static int 格式噪声次数 { get; private set; }

    /// <summary>因不在白名单被丢弃的条数（疑似幻觉）</summary>
    public static int 丢弃幻觉次数 { get; private set; }

    /// <summary>因局面剧变被清空的条数（保护性丢弃，不算浪费）</summary>
    public static int 清空丢弃条数 { get; private set; }

    /// <summary>局面剧变清空队列的次数</summary>
    public static int 清空次数 { get; private set; }

    /// <summary>成功拿到 AI 回复并填进队列的次数</summary>
    public static int 预取成功次数 { get; private set; }

    /// <summary>预取请求失败的次数（超时 / 网络 / 熔断）</summary>
    public static int 预取失败次数 { get; private set; }

    /// <summary>已经发出多少批预取请求（批次号）</summary>
    private static int _批次号;

    /// <summary>上一次统计汇总打印的时间（每 30 秒打一条，日志别刷屏）</summary>
    private static long _上次汇总;

    /// <summary>
    /// 「建议被终审拦下」的原因计数（原因 → 次数）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么还要这一层 —— 命中率只告诉你"多少用上了"，
    ///    但**不告诉你"没用上的卡在哪"**。
    ///
    ///    阶段 B 的链条是：AI 出建议 → 白名单 → 终审（解锁/可用/目标/治疗优先）
    ///    → 进 slot → 真的放出去。
    ///    任何一个环节断掉，表现都是"命中率低"，但修法完全不同：
    ///      · 全是"未解锁" → 技能表里配了当前等级拿不到的东西
    ///      · 全是"不可用" → 预取提前量太大，AI 建议的 CD 还没转好
    ///      · 全是"让位给治疗" → AI 偏输出，而队伍一直在掉血
    ///      · 全是"视线被挡" → 站位问题
    ///    有了这个字典，看面板就知道该调哪一环。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static readonly Dictionary<string, int> _拦截原因 = new();

    /// <summary>记一次"建议被终审拦下"</summary>
    public static void 记拦截(string 原因)
    {
        try
        {
            if (string.IsNullOrEmpty(原因)) return;
            _拦截原因.TryGetValue(原因, out var 旧);
            _拦截原因[原因] = 旧 + 1;
        }
        catch { }
    }

    /// <summary>拦截原因的一行摘要（按次数从多到少）</summary>
    public static string 拦截摘要()
    {
        try
        {
            if (_拦截原因.Count == 0) return "（还没有建议被拦下）";

            var 排序 = new List<KeyValuePair<string, int>>(_拦截原因);
            排序.Sort((a, b) => b.Value.CompareTo(a.Value));

            var 段 = new List<string>();
            foreach (var kv in 排序) 段.Add($"{kv.Key} {kv.Value}");

            return string.Join("｜", 段);
        }
        catch
        {
            return "（读取失败）";
        }
    }

    /// <summary>
    /// 命中率 —— **分母只算"有机会被用的"**。
    ///
    /// 不清空的条数不计入分母：它们不是"没用上"，是"局面变了不该用"。
    /// 这个口径比"命中 /(命中+过期)"更能反映真实水平。
    /// </summary>
    public static float 命中率
    {
        get
        {
            var 有机会 = 命中次数 + 过期次数;
            return 有机会 == 0 ? 0f : 命中次数 * 100f / 有机会;
        }
    }

    /// <summary>一行状态描述（设置页 + 日志汇总共用）</summary>
    public static string 状态描述()
    {
        return $"命中 {命中次数} / 过期 {过期次数}（命中率 {命中率:F0}%）" +
               $"｜预取成功 {预取成功次数} 失败 {预取失败次数}" +
               $"｜幻觉丢弃 {丢弃幻觉次数} 解析失败 {解析失败次数} 格式噪声 {格式噪声次数}" +
               $"｜局面清空 {清空次数} 次({清空丢弃条数} 条)" +
               $"｜队列 {_队列.Count}/{目标长度}";
    }

    /// <summary>给"装上实测"看的两行完整统计</summary>
    public static string 详细统计()
    {
        return 状态描述()
               + Environment.NewLine
               + $"被终审拦下：{拦截摘要()}"
               + Environment.NewLine
               + $"其中排在队列第 2 位之后才过期的：{排队过期条数} 条"
               + Environment.NewLine
               + DeepSeekClient.缓存描述();
    }

    // ==================== 每帧驱动 ====================

    /// <summary>每帧调用（很轻：只维护队列 + 到点启动一次后台任务）</summary>
    public static void 每帧更新()
    {
        var s = AiSettings.Instance;

        if (!s.启用决策层 || !s.已配置) return;

        // ① 清掉队首的过期建议
        清理过期();

        // ①.5 定期把统计打一条日志（装上去实测时靠这个看命中率）
        定期汇总();

        if (_预取中) return;
        if (DeepSeekClient.熔断中) return;

        // ② 队列够长 → 不用补货（这是"预取"的关键：有货就不问）
        if (_队列.Count >= 目标长度) return;

        // ③ 补货节流
        var 间隔 = Math.Max(300, s.决策预取毫秒);
        if (TimeHelper.Now() - _上次预取 < 间隔) return;

        _上次预取 = TimeHelper.Now();
        _ = 预取();
    }

    private static void 清理过期()
    {
        // 队列是 FIFO，过期的都在前面
        while (_队列.Count > 0)
        {
            var 头 = _队列.Peek();
            if (头.还新鲜) break;

            _队列.Dequeue();
            过期次数++;

            // ★ 区分"排太后面等过期"和"AI 建议得不对" ★
            //   出生时队列位置 > 0 = 它前面还排着别的建议 → 轮到它时已经晚了，
            //   属于**预取节奏问题**，不是 AI 判断错误。
            if (头.出生时队列位置 > 0)
            {
                排队过期条数++;
                Ai调试.调试(
                    $"建议 {头.技能Id} 过期未用（排在第 {头.出生时队列位置 + 1} 位，" +
                    $"等了 {头.已等毫秒}ms，批次 {头.批次}）");
            }
        }
    }

    /// <summary>
    /// 每 30 秒把统计打一条日志。
    ///
    /// **为什么要定期汇总**：单条日志看不出"命中率"这种比率，
    /// 而装上去实测时不可能一直盯着面板 —— 事后翻日志要能直接看到结论。
    /// </summary>
    private static void 定期汇总()
    {
        try
        {
            var 现在 = TimeHelper.Now();
            if (现在 - _上次汇总 < 30000) return;
            _上次汇总 = 现在;

            // 一次都没跑过就不刷（没开 AI / 没配 Key）
            if (命中次数 + 过期次数 + 预取成功次数 == 0) return;

            Ai调试.日志("【阶段B统计】" + 状态描述());
        }
        catch { }
    }

    /// <summary>
    /// 局面剧变（换目标 / 血量骤降 / 进战脱战）时清空队列。
    ///
    /// **为什么需要**：预取的本质是"赌局面不变"。
    /// 局面一变，队列里剩下的建议就全是错的 ——
    /// **过期的建议比没有建议更危险**（会做出与当前战场无关的决策）。
    /// </summary>
    public static void 局面剧变()
    {
        try
        {
            if (_队列.Count == 0) return;

            var 丢掉 = _队列.Count;
            _队列.Clear();
            _上次局面变化 = TimeHelper.Now();

            // ★ 计入统计 ★
            //   不记的话，"命中率低"到底是被丢弃、过期，还是被局面剧变清掉，
            //   在事后完全分不出来 —— 那样统计就没法用来定位问题。
            清空次数++;
            清空丢弃条数 += 丢掉;

            Ai调试.日志($"局面剧变 -> 清空 {丢掉} 条待用建议（队列归零，下一帧重新预取）");
        }
        catch { }
    }

    /// <summary>
    /// 局面剧变 + **立刻重新预取**。
    ///
    /// ⚠️ 这是给"战斗中局面真的变了"用的（换目标 / 团血骤降）。
    ///
    ///    只调 <see cref="局面剧变"/> 的话，队列是空的，但仍要等
    ///    「决策预取毫秒」节流过去才会补货 —— 在日随里这个空窗期
    ///    正好是"最需要建议的时候"，等于没帮上忙。
    ///    所以这里顺手把节流时间戳也一起重置，让下一帧就补货。
    ///
    ///    不会因此打爆 API：`_预取中` 保证同一时刻只有一个请求在飞，
    ///    熔断检查和队列长度检查也都还在。
    /// </summary>
    public static void 局面剧变并重取()
    {
        try
        {
            局面剧变();

            // 把节流时间戳清掉 → 下一帧就能补货（但 _预取中 仍然挡住并发）
            _上次预取 = 0;

            var s = AiSettings.Instance;
            if (!s.启用决策层 || !s.已配置) return;
            if (_预取中) return;
            if (DeepSeekClient.熔断中) return;

            Ai调试.日志("局面剧变 -> 立刻重新预取");
            _ = 预取();
        }
        catch { }
    }

    // ==================== 预取 ====================

    private static async Task 预取()
    {
        _预取中 = true;
        var 本批 = ++_批次号;
        try
        {
            var 局面 = AiSituation.采集();

            // 决策层：给 3 秒 —— 它是在"备货"，不必卡在 GCD 内
            // 超时 8 秒 —— deepseek-flash 是**推理型模型**，会先思考再回答，通常 3~10 秒。
            // 反正是预取备货，慢一点没关系：备好了等着用，比"快但总超时"强。
            //
            // ⚠️ `期望_ID理由格式: true` —— 这是**唯一**需要它的调用点：
            //    正文被截断成空时，允许从思考里捞 `ID|理由`（见 处理推理型回复）。
            //    其他调用点（倾向/提炼）要的是散文，捞不得 —— 那会把
            //    "思考过程"当成"结论"交上去，而且看不出来是半成品。
            var 回复 = await DeepSeekClient.提问(系统提示, 局面, 8000,
                         期望_ID理由格式: true).ConfigureAwait(false);

            if (回复 == null)
            {
                // ★ 失败要计数 ★
                //   原来只是静默 return —— 于是"命中率低"到底是
                //   AI 建议不好、还是请求根本一直在失败，事后分不出来。
                预取失败次数++;
                Ai调试.日志($"预取失败（批次 {本批}，无回复）" +
                            $"｜累计 成功 {预取成功次数} / 失败 {预取失败次数}");
                return;
            }

            var 条数 = 解析并填充(回复, 本批);

            if (条数 > 0)
            {
                预取成功次数++;
                Ai调试.日志($"预取 {条数} 步（批次 {本批}，队列 {_队列.Count}/{目标长度}）");
            }
            else
            {
                预取失败次数++;
                Ai调试.日志($"预取解析出 0 条（批次 {本批}）—— 看下面『解析失败/疑似幻觉』的明细");
            }
        }
        catch (Exception e)
        {
            预取失败次数++;
            Ai调试.日志("决策预取异常（已忽略）：" + e.Message);
        }
        finally
        {
            _预取中 = false;
        }
    }

    // ==================== 提示词 ====================

    /// <summary>
    /// 系统提示 —— 和策略层同一条铁律：**不许编机制，不许编技能。**
    ///
    /// **改成一口气要 3 步**：这样一次请求就能填满队列，
    /// 不必每个 GCD 都问一次（省 token 又抗延迟）。
    /// </summary>
    private static readonly string 系统提示 = $"""
        你是 FF14 治疗职业的战斗决策助手。
        根据【数据】里的局面，给出**接下来 {每次请求步数} 个 GCD** 最该放的技能，按先后顺序。

        ═══ 铁律 ═══
        1. 你【不了解】这个副本的机制。不要猜测、不要回忆、不要描述机制。
        2. 只能从【可选技能】清单里选技能 ID。清单外的 ID 一律不许输出。
        3. 数据不足就输出：0|数据不足
        4. 理由必须对应【数据】里某一项。
        5. 禁止编造技能名或机制名。
        6. 后面的步骤是**预判**：如果前面几步之后局面可能变化，按你的判断给最合理的后续。
           不确定就重复当前最优解，**不要为了凑数编技能**。

        ═══ 最高优先级：必须奶满 ═══
        7. 【数据】里出现「必须奶满机制」段时 —— **它的优先级高于一切**。
        那段会写明目标名字和状态名，你必须**优先对那个人使用治疗技能**。
        8. ⚠️ 判断依据**不是血量**：那个人可能血量看着很健康（比如 80%），
        但状态效果结束时他会**直接无法战斗**。**不许**因为"他血还挺多"
        而把治疗给别人 —— 那等于放弃他。
        9. 这个状态**只能靠治疗解除**，没有别的办法。理由里请写"必须奶满"。
        10. 只有在【数据】里**没有**「必须奶满机制」段时，才按血量/人数等常规判断走。

        ═══ 移动相关（用户实测指出的问题，务必遵守）═══
        11. 【数据】里的「移动状态」**决定你能建议什么技能**：
            · 写着「**移动中**」→ **只能建议瞬发技能**（技能表里标了「瞬发」的那些）。
              建议读条技能没有意义 —— 本地逻辑会把它挡掉，等于白问一轮。
              你自己看技能清单挑：标「读条 X.Xs」的一律不要选。
            · 写着「站定」→ 读条技能可以正常建议。
            · 写着「正在读条」→ 那一发已经在读了，不要再建议同一个技能。
        12. 移动中**没有瞬发输出技能可用**时，可以建议**瞬发治疗**或干脆
            输出 `0|移动中无瞬发技能可用，等站定`。**不要硬推读条技能凑数。**

        ═══ 位置稳定性 ═══
        13. 【敌人】里的「位置稳定性」**决定地面技能值不值得铺**：
            · 「稳定」→ 罩子 / 地星 / 庇护所这类地面技能可以建议。
            · 「不稳定/观察中」→ **不要建议地面技能**，敌人一走就白铺了；
              改用能立即生效的技能。

        ═══ 副本与机制预告（用户要求新增，务必看懂）═══
        14. 【副本与机制时间轴】一栏告诉你**接下来会发生什么**。用法：

            · 「正在发生：XXX」→ 那一下往往就是**当前掉血的原因**。
              把理由和它对上，比如"XX 机制刚结算，3 人掉血，群抬"，
              比笼统说"有人掉血"有用得多。

            · 「后续机制」列表里 **5 秒内**的条目 → 现在就该准备了：
              要减伤的提前铺、HoT 可以现在挂上（它需要时间起效）、
              别把群奶能力技在无事发生的时候花掉。

            · **10~20 秒后**的条目 → 用来决定"现在能不能花资源"：
              后面有大伤害就别把蓝花/以太清空；后面很平就放心打输出。

            · 「没有匹配到时间轴」→ **这不等于没有机制**，只等于我们查不到。
              这种情况**保守一点**：血线留高些、能力技别乱花。

        15. ⚠️ **绝对不许凭副本名回忆机制。**
            副本名**不是**让你去回忆这个本有什么机制的 ——
            那是你最容易编错的地方（你并不真正记得，只会编得像）。
            · 只准用「机制预告」里**明确列出来**的条目。
            · 没写的就当作"不知道"，写 `0|后续未知，按当前血线判断`。
            · 编一个不存在的机制名，比什么都不说**危害大得多**。

        ═══ 全部敌人（DoT 判断必须看它）═══
        16. 【敌人】里的「**其他敌人**」列表 = 当前目标之外，附近最需要关注的几个。
            每行的 `[**没有我的DoT**]` / `[**已有我的DoT**]` 是关键。

            · **补不补 DoT 看最后一行的覆盖率汇总**，不是只看当前目标：
              「5 个里 4 个有」→ **别补**，只差一个不值得占 GCD。
              「5 个里 1 个有」→ 可以补。
              当前目标有 ≠ 全都有 —— 反过来也一样。

            · 标了 `残血`（≤25%）且汇总说"这一波快清完了" →
              **别交群奶、别交爆发、别补 DoT**，省给下一波。

            · 标了 `近(Xm)` 的 → AOE 能一起打到，`适合放 AOE：是` 时优先。

        17. 【敌人】写着「当前没有选中目标」→ **看不到 DoT 覆盖**。
            这种情况**不要补 DoT**（盲打），可以治疗或输出 `0|无目标，不补DoT`。

        ═══ 技能可用性（务必遵守）═══
        18. 【可选技能】里**只列了当前等级真的能用的技能**。
            · **不许建议清单外的任何技能** —— 哪怕你确定"这个职业有那个技能"。
            · 清单末尾写着「另有 M 个因等级/职业任务没到未列出」的那些，
              **就是现在用不了的**，一个字都别建议。
            · 写着「等级同步中」时，**以副本内的等级为准** —— 高等级技能会变灰。

        ═══ 怎么选目标（这几条最容易选错）═══
        19. **单体治疗打血最少的那个人**（按**裸血量**比，不看盾）。
            没有"坦克优先"这回事 —— 谁最危险治谁。

        20. ⚠️ **看到"无敌/假死"类状态就别治他，也别给减伤。**
            坦克开 死斗 / 行尸走肉 / 超火流星 的那几秒**它本来就不会死**，
            这时候灌治疗、交大减伤是**纯浪费**（CD 和资源都白交）。
            · 例外：**死而不僵**是"要奶"的那一段 —— 该治就治。
            · 判断依据是【队伍】/【敌人】段里标出来的状态，
              **没有标明就别自己猜**。

        21. **坦克才是预铺减伤的目标**（绿帽 / 水流幕 / 天星交错 / 输血这类）。
            给非坦克铺预铺减伤通常没意义 —— 伤害本来就不打他。

        22. **DoT 只铺主目标**，别给每只小怪都补。
            一波小怪里补 2~3 个就够；剩一只残血的更不值得。

        ═══ 花 GCD 之前先想一句 ═══
        23. 你建议的每个技能都**要占一个 GCD 或一次能力技机会**。
            开口前先问："这一下比另一个选择更好吗？"
            · 群里只有 1 个人掉血 → **别群奶**，单体更省。
            · 血线还很稳（全队 >85%）→ **别治疗**，去打输出。
            · 想补 DoT 但当前目标已有 → 看覆盖率汇总再决定。

        24. **能用能力技（不读条）就别用读条治疗** ——
            能力技不占 GCD、不受移动影响，还能把 GCD 留给输出。
            只在能力技都在 CD 时才考虑读条。

        ═══ 输出格式 ═══
        每行一条，最多 {每次请求步数} 行：
        技能ID|理由

        ═══ 示例 ═══
        16534|低于35%有2人，需要群抬
        16534|血线还没拉回来，继续群抬
        16540|血线稳了，补DoT
        37009|移动中，用瞬发的闪飒填充
        0|移动中无瞬发技能可用，等站定
        16534|8秒后有大伤害，先把血线抬满
        0|后续未知，按当前血线判断
        0|附近5个敌人里4个已有DoT，不值得再占GCD
        0|残血小怪快清完了，省资源给下一波
        0|清单里没有可用的治疗手段，等 GCD 转好
        """;

    // ==================== 解析 + 白名单 ====================

    /// <summary>
    /// 把一行"可能有格式噪声"的回复**归一化**成 `技能ID|理由`。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么要做这个（日志实证）★
    ///
    ///   实测日志里出现过：`解析失败（批次 32）：『1. 25865|单体环境，用基础输出填充』`
    ///   —— AI 的**内容完全正确**，只是前面多了个 `1. ` 序号，就被整条丢了。
    ///
    ///   同一个日志里还有更糟的：AI 说
    ///      "或者考虑给T减伤？没有T减伤技能在列表里。野战治疗阵是团队减伤，但CD中（27.9）。"
    ///   这句在日志里**连"解析失败"都没记**（因为不以数字开头、也不含竖线），
    ///   等于**静默丢弃** —— 用户完全看不到 AI 其实考虑过减伤。
    ///
    ///  ── 原则 ──
    ///    格式宽容、**语义严格**：
    ///      · 归一化只去掉**列表标记 / 引号 / 空白**这类纯排版噪声
    ///      · 归一化后仍然必须满足 `数字|理由`，内容一个字都不改
    ///      · 真正不合格式的（纯散文），照旧计失败 —— 那样才能发现提示词在漂移
    ///
    ///  ⚠️ 归一化**改动过的**行要留日志：否则提示词格式约束失效了我们都不知道。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static string 归一化行(string 原始)
    {
        var s = 原始.Trim();

        // ① 去掉 markdown 列表标记：`1. ` `1) ` `- ` `* ` `• ` `1、`
        s = Regex.Replace(s, @"^\s*(?:[-*•]|\d+\s*[.)、:])\s*", "");

        // ② 去掉包裹的引号 / 反引号 / 书名号（AI 爱把输出包起来）
        s = s.Trim('`', '"', '\'', '「', '」', '『', '』', '“', '”');

        // ③ 去掉 markdown 加粗标记（`**25859**|...`）
        s = s.Replace("**", "");

        return s.Trim();
    }

    private static int 解析并填充(string 回复, int 批次 = 0)
    {
        var 条数 = 0;

        try
        {
            var 行 = 回复.Split('\n', StringSplitOptions.RemoveEmptyEntries);

            foreach (var 原始行 in 行)
            {
                if (条数 >= 每次请求步数) break;

                if (string.IsNullOrWhiteSpace(原始行)) continue;

                var 归一 = 归一化行(原始行);

                // 归一化改动了内容 → 记一笔（说明提示词的格式约束在漂移，
                // 该去调提示词，而不是靠解析器一直兜着）
                if (归一 != 原始行.Trim() && 归一.Length > 0)
                {
                    格式噪声次数++;
                    Ai调试.调试($"格式噪声（批次 {批次}）：『{原始行.Trim()}』-> 『{归一}』");
                }

                var 段 = 归一.Split('|', 2);
                if (段.Length == 0) continue;

                if (!uint.TryParse(段[0].Trim(), out var id))
                {
                    // ★ 记下来：这是"AI 没按格式回" ★
                    //   原来直接 continue，统计上看不见 ——
                    //   而格式问题恰恰是提示词要调的最常见原因。
                    解析失败次数++;
                    Ai调试.调试($"解析失败（批次 {批次}）：『{原始行.Trim()}』不是 `技能ID|理由` 格式");
                    continue;
                }

                if (id == 0) continue;   // AI 说"数据不足"，跳过这行（这是**合规**回复，不算失败）

                // ★ 白名单校验：防幻觉的最后一道闸 ★
                if (!在可选清单里(id))
                {
                    丢弃幻觉次数++;
                    Ai调试.日志($"建议的技能 {id} 不在可选清单里，已丢弃（疑似幻觉）");
                    continue;
                }

                _队列.Enqueue(new 建议
                {
                    技能Id = id,
                    理由 = 段.Length > 1 ? 段[1].Trim() : "",
                    生成时间 = TimeHelper.Now(),
                    出生时队列位置 = _队列.Count,   // 排在它前面的已有几条
                    批次 = 批次,
                });

                条数++;
            }
        }
        catch (Exception e)
        {
            Ai调试.日志("建议解析异常：" + e.Message);
        }

        return 条数;
    }

    // ==================== 消费 ====================

    /// <summary>
    /// 取建议（**出队**）。返回 null 表示"没有可用建议"。
    ///
    /// ⚠️ **不要在 Check() 里调这个** —— 会导致逻辑陷阱：
    ///
    ///    Check 出队 A → 返回高分
    ///      ↓
    ///    如果这一帧被更高优先级的 resolver 抢先，Build 没被调用
    ///      → **A 已经出队，永久丢失** ❌
    ///
    ///    而且 Build 里再读"当前建议"（Peek）时已经不是 A 了
    ///      → **Check 判的是 A，Build 放的可能是 B** ❌
    ///
    ///  正确用法：
    ///    Check → 用 当前建议（只看）
    ///    Build → 用 当前建议 + 放完之后调 消费()
    /// </summary>
    public static 建议? 取建议()
    {
        清理过期();

        if (_队列.Count == 0) return null;

        var s = _队列.Dequeue();

        // ⚠️ 这里**不**加命中计数 —— 命中只应由 消费() 记。
        //
        //    原因：这个方法是"出队"，它无条件把建议拿走，
        //    **不保证技能真的放出去了**（可能被更高优先级抢掉）。
        //    如果这里也 ++ 命中次数，命中率会被虚高 ——
        //    统计一旦不可信，就没法用来判断"预取队列重写到底有没有效"。
        //    所以计数口径统一收敛到 消费()。
        return s;
    }

    /// <summary>
    /// 消费队首建议（**技能真的放出去了才调**）。
    ///
    /// 这是 Check/Build 分离的正确做法：
    ///   Check 只看（Peek）→ 不动队列
    ///   Build 放成功后 → 调这个出队
    /// </summary>
    public static void 消费()
    {
        try
        {
            清理过期();
            if (_队列.Count == 0) return;

            _队列.Dequeue();
            命中次数++;
        }
        catch { }
    }

    public static void 重置()
    {
        _队列.Clear();
        _上次预取 = 0;
        _上次局面变化 = 0;
        _上次汇总 = 0;
        _预取中 = false;
        _批次号 = 0;

        命中次数 = 0;
        过期次数 = 0;
        排队过期条数 = 0;
        解析失败次数 = 0;
        格式噪声次数 = 0;
        丢弃幻觉次数 = 0;
        清空丢弃条数 = 0;
        清空次数 = 0;
        预取成功次数 = 0;
        预取失败次数 = 0;
        _拦截原因.Clear();
    }

    /// <summary>
    /// 这个 ID 是不是当前职业真的会用的技能。
    ///
    /// **白名单是防幻觉的硬手段** —— 提示词只是"请求"它别编，
    /// 这里是"验证"它有没有编。两道一起上才稳。
    /// </summary>
    private static bool 在可选清单里(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return true;   // 拿不到表就不拦（宁可放过也别全丢）

            if (id == 表.基础输出) return true;
            if (id == 表.群体输出) return true;
            if (id == 表.Dot技能) return true;
            if (id == 表.移动填充技) return true;
            if (id == 表.单体治疗GCD) return true;
            if (id == 表.群体治疗GCD) return true;
            if (id == 表.紧急单奶) return true;
            if (id == 表.群体治疗能力技) return true;
            if (id == 表.单体盾) return true;
            if (id == 表.群体盾) return true;
            if (id == 表.团队减伤) return true;
            if (id == 表.复活) return true;
            if (id == 表.驱散) return true;
            if (id == 表.醒梦) return true;

            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0) return true;
            if (表.脱战准备技能 != null && Array.IndexOf(表.脱战准备技能, id) >= 0) return true;
            if (表.所有DotBuff != null && Array.IndexOf(表.所有DotBuff, id) >= 0) return true;

            return false;
        }
        catch
        {
            return true;
        }
    }
