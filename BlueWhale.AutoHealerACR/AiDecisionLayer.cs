namespace BlueWhale.AutoHealerACR;

/// <summary>
/// 决策层（阶段 B）—— AI 出**具体技能建议**。
///
/// ══════════════════════════════════════════════════════════════════
///  ⚠️ 核心设计：**预取多步**（不要"现问现用"）
///
///  第一版是"每次都现问下一个 GCD"：
///      GCD 2.5 秒 → 问 AI 要 1.5~3 秒 → 答案回来时 GCD 早过了 → 过期
///      实测统计：命中 681 / 过期 875 —— **一半以上是白问的**
///
///  改成本版的思路：**让 AI 提前备货**
///      · 一次请求让它给出**接下来 3 步**的技能序列（不是一个）
///      · 后台持续维持队列里有 2~3 条待用建议
///      · 主循环从队列头部取 —— 取的时候它通常已经躺在那儿了
///
///  这样一来，"AI 响应慢" 就不致命的 ——
///  因为**它是在为未来备货，而不是为当下救火**。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class AiDecisionLayer
{
    /// <summary>一条 AI 建议</summary>
    public sealed class 建议
    {
        public uint 技能Id;
        public string 理由 = "";
        public long 生成时间;

        /// <summary>
        /// **技能往哪儿放** —— 从候选带过来，执行层照这个放。
        ///
        /// [!] 为什么必须有它（本轮审阅第 4/5/6 条，三条都是真 bug）：
        ///     原来只有一个 `目标Id`，它被迫同时表达
        ///       ① 技能往谁身上放（施法目标）
        ///       ② 为什么选它（判断依据）
        ///     于是群疗把"最缺血的队友"当成了施法目标 ——
        ///     而群疗的正确写法是 `SpellTargetType.Self`（以自己为中心）。
        ///
        /// [!] 方向也是"老格式没有它"时的默认值：
        ///     老格式（AI 直接报技能 ID）走本地推断，用 `队友` 起步最安全。
        /// </summary>
        public 候选集.目标模式 施法目标模式 = 候选集.目标模式.队友;

        /// <summary>
        /// **显式目标**（0 = 让本地按技能类别推断）。
        ///
        /// [!] 只在 `施法目标模式` 是 `队友` / `敌人` 时才有意义 ——
        ///     `自己` 模式不看它（这是修群疗 bug 的关键）。
        ///
        /// [!] 为空时**不报错** —— 退回本地推断（向后兼容老格式 `技能ID|理由`）。
        /// </summary>
        public ulong 目标Id;

        /// <summary>因为谁才选这条（只给日志/界面看，执行层不读）</summary>
        public string 关注目标名 = "";

        /// <summary>
        /// 有效期：**按 GCD 数算**（比按毫秒合理）。
        /// 一个 GCD 2.5 秒，给 2 个 GCD 的容忍度 = 5 秒。
        /// </summary>
        public const long 有效期毫秒 = 5000;

        /// <summary>
        /// 这条建议"被预取出来的那一刻"，队列里已经排了几条。
        ///
        /// 用途：**判断命中率低是不是"排队排太久"造成的** ——
        /// 一次请求给 3 步，第 3 步天然要等 2 个 GCD 才轮得到，
        /// 本来就更容易过期。有这个字段才能把"排太后面"和
        /// "AI 建议得不对"两种情况分开。
        /// </summary>
        public int 出生时队列位置;

        /// <summary>被 AI 建议时，这一批是第几批发出来的</summary>
        public int 批次;

        public bool 还新鲜 => TimeHelper.Now() - 生成时间 <= 有效期毫秒;

        /// <summary>已经等了多久（毫秒）</summary>
        public long 已等毫秒 => TimeHelper.Now() - 生成时间;
    }

    // ══════════════════════════════════════════════════════════════════
    //  ★ AI 建议队列 —— **跨线程访问，必须串行化** ★
    //
    //  ── 为什么（已核实的竞争路径）──
    //      预取是 `await ... .ConfigureAwait(false)`，
    //      ⇒ 它回来时在**线程池线程**上，接着就 `解析并填充 → Enqueue`。
    //      而游戏线程同时在 `Peek / Dequeue / Clear`。
    //      `Queue<T>` **不是线程安全容器** —— 并发读写下内部数组会错乱：
    //      丢条目、读到已移除项、极端情况抛异常。
    //
    //  ── 为什么用锁，不直接换 `ConcurrentQueue` ──
    //      `ConcurrentQueue` 只保证**单次操作**原子；
    //      而本文件有 `Peek` → 判断 → `Dequeue` 这种**复合序列**
    //      （见 `清理过期()`），换容器挡不住序列交错。
    //      锁能一次盖住整段，且队列操作都是 O(1)，开销可忽略。
    //
    //  ── 不去碰游戏状态 ──
    //      线程池线程**只做入队**。队列元素是纯数据
    //      （技能 Id / 理由 / 时间戳 / 批次）。
    //      真正的游戏交互（选目标 / 施法）全在游戏线程的 Check/Build 里。
    //      ⇒ "后台线程永远不要直接修改游戏决策状态"。
    // ══════════════════════════════════════════════════════════════════
    private static readonly Queue<建议> _队列 = new();

    /// <summary>队列锁 —— 所有队列访问都必须持有它</summary>
    private static readonly object _队列锁 = new();

    private static int 队列计数()
    {
        // [!] 必须用**字段的原始成员** `_队列.Count` ——
        //     这里原来写的是 `return 队列计数();`（调用自己），
        //     是批量替换包装方法时误伤的 => **无限递归** => 栈溢出 => 闪退。
        //     包装方法内部**绝不能再调包装方法**。
        lock (_队列锁) return _队列.Count;
    }

    /// <summary>入队（**线程池线程也会调**）</summary>
    private static void 入队(建议 条)
    {
        lock (_队列锁) _队列.Enqueue(条);
    }

    /// <summary>取队首但不移除；空队列返回 null</summary>
    private static 建议? 看队首()
    {
        lock (_队列锁) return _队列.Count > 0 ? _队列.Peek() : null;
    }

    /// <summary>移除队首</summary>
    private static void 出队()
    {
        lock (_队列锁)
        {
            if (_队列.Count > 0) _队列.Dequeue();
        }
    }

    /// <summary>找第一个还新鲜的（不移除，给 UI / 取建议用）</summary>
    private static 建议? 找新鲜()
    {
        lock (_队列锁)
        {
            foreach (var s in _队列)
                if (s.还新鲜) return s;
        }
        return null;
    }

    /// <summary>清空，返回清掉几条</summary>
    private static int 清空队列()
    {
        // [!] 同样必须用原始成员 —— 这里原来是
        //       `var n = 队列计数(); 清空队列();`
        //     后者是**调用自己**（无限递归），前者是多余的再取锁。
        //     正确写法：取长度 + 清空，都走 `_队列`。
        lock (_队列锁)
        {
            var n = _队列.Count;
            _队列.Clear();
            return n;
        }
    }

    /// <summary>队列维持的目标长度 —— 低于这个数就去补货</summary>
    private const int 目标长度 = 3;

    /// <summary>一次请求让 AI 给几步</summary>
    private const int 每次请求步数 = 3;

    private static long _上次预取;
    private static bool _预取中;
    private static long _上次局面变化;   // 局面剧变时强制清空队列重来

    public static bool 预取中 => _预取中;
    public static int 队列长度 => 队列计数();

    /// <summary>队首建议（不消费），给 UI 显示用</summary>
    public static 建议? 当前建议
    {
        get
        {
            return 找新鲜();
        }
    }

    // ==================== 统计（给"阶段 B 命中率"看） ====================
    //
    // ══════════════════════════════════════════════════════════════════
    //  ⚠️ 旧统计只有一个「过期」计数，它把**两件完全不同的事**混在了一起：
    //
    //     · 建议被采纳入 slot 之后，用完了 → 正常损耗
    //     · 建议躺在队列里没人用，等到过期 → **真正的浪费**
    //
    //    所以"命中 681 / 过期 875"这个 44% 里，有一部分其实是
    //    "用过了但也被算进过期"，真实的浪费比例是**看不出来的**。
    //
    //  现在按"为什么没被用上"分开记，才能定位到底卡在哪一环：
    //    解析失败  → 提示词/格式问题
    //    幻觉丢弃  → AI 编了清单外的技能
    //    局面清空  → 建议是对的，但战场变了（这是**好**的，说明保护生效）
    //    排队过期  → 预取节奏 vs GCD 节奏不匹配
    // ══════════════════════════════════════════════════════════════════

    /// <summary>被采纳并放进 slot 的次数（= 真正用上的）</summary>
    public static int 命中次数 { get; private set; }

    /// <summary>躺在队列里没人用、等到过期的条数（= 真正的浪费）</summary>
    public static int 过期次数 { get; private set; }

    /// <summary>其中"因为排在其他建议后面才等到过期"的条数（预取节奏问题）</summary>
    public static int 排队过期条数 { get; private set; }

    /// <summary>AI 返回了但解析不出技能 ID 的行数（格式问题）</summary>
    public static int 解析失败次数 { get; private set; }

    /// <summary>
    /// 需要**归一化才解析出来**的行数（列表序号 / 引号 / 加粗之类的格式噪声）。
    ///
    /// 单列这个是为了区分两件事：
    ///   · 解析失败 = AI 没给 `ID|理由`，要调**提示词**
    ///   · 格式噪声 = 内容对了、外面裹了层壳，解析器能兜住，但提示词也该收紧
    /// 混在一起看的话，会把"能兜住的"和"真丢了的"当成一回事。
    /// </summary>
    public static int 格式噪声次数 { get; private set; }

    /// <summary>因不在白名单被丢弃的条数（疑似幻觉）</summary>
    public static int 丢弃幻觉次数 { get; private set; }

    /// <summary>因局面剧变被清空的条数（保护性丢弃，不算浪费）</summary>
    public static int 清空丢弃条数 { get; private set; }

    /// <summary>局面剧变清空队列的次数</summary>
    public static int 清空次数 { get; private set; }

    /// <summary>成功拿到 AI 回复并填进队列的次数</summary>
    public static int 预取成功次数 { get; private set; }

    /// <summary>预取请求失败的次数（超时 / 网络 / 熔断）</summary>
    public static int 预取失败次数 { get; private set; }

    /// <summary>已经发出多少批预取请求（批次号）</summary>
    private static int _批次号;

    /// <summary>
    /// **世代号** —— 只有最新一代的预取结果可以进队列。
    ///
    /// ⚠️ 和 `Ai初始化._世代` 是**同一个修法、同一个 bug**：
    ///    `重置()` 不能作废**已经发出去的异步请求** ——
    ///    它回来时会直接 `解析并填充 → Enqueue`，
    ///    把**按旧局面/旧职业**得出的建议塞进**新队列**。
    ///
    /// ⚠️ 这里只管"结果能不能进队列"；
    ///    `_预取中` 的清零也要过世代校验 ——
    ///    否则过期的那次会把**正在跑的新请求**"放行"出第三个并发。
    /// </summary>
    private static int _世代;

    /// <summary>上一次统计汇总打印的时间（每 30 秒打一条，日志别刷屏）</summary>
    private static long _上次汇总;

    /// <summary>
    /// 「建议被终审拦下」的原因计数（原因 → 次数）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么还要这一层 —— 命中率只告诉你"多少用上了"，
    ///    但**不告诉你"没用上的卡在哪"**。
    ///
    ///    阶段 B 的链条是：AI 出建议 → 白名单 → 终审（解锁/可用/目标/治疗优先）
    ///    → 进 slot → 真的放出去。
    ///    任何一个环节断掉，表现都是"命中率低"，但修法完全不同：
    ///      · 全是"未解锁" → 技能表里配了当前等级拿不到的东西
    ///      · 全是"不可用" → 预取提前量太大，AI 建议的 CD 还没转好
    ///      · 全是"让位给治疗" → AI 偏输出，而队伍一直在掉血
    ///      · 全是"视线被挡" → 站位问题
    ///    有了这个字典，看面板就知道该调哪一环。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static readonly Dictionary<string, int> _拦截原因 = new();

    /// <summary>记一次"建议被终审拦下"</summary>
    public static void 记拦截(string 原因)
    {
        try
        {
            if (string.IsNullOrEmpty(原因)) return;
            _拦截原因.TryGetValue(原因, out var 旧);
            _拦截原因[原因] = 旧 + 1;
        }
        catch { }
    }

    /// <summary>拦截原因的一行摘要（按次数从多到少）</summary>
    public static string 拦截摘要()
    {
        try
        {
            if (_拦截原因.Count == 0) return "（还没有建议被拦下）";

            var 排序 = new List<KeyValuePair<string, int>>(_拦截原因);
            排序.Sort((a, b) => b.Value.CompareTo(a.Value));

            var 段 = new List<string>();
            foreach (var kv in 排序) 段.Add($"{kv.Key} {kv.Value}");

            return string.Join("｜", 段);
        }
        catch
        {
            return "（读取失败）";
        }
    }

    /// <summary>
    /// 命中率 —— **分母只算"有机会被用的"**。
    ///
    /// 不清空的条数不计入分母：它们不是"没用上"，是"局面变了不该用"。
    /// 这个口径比"命中 /(命中+过期)"更能反映真实水平。
    /// </summary>
    public static float 命中率
    {
        get
        {
            var 有机会 = 命中次数 + 过期次数;
            return 有机会 == 0 ? 0f : 命中次数 * 100f / 有机会;
        }
    }

    /// <summary>一行状态描述（设置页 + 日志汇总共用）</summary>
    public static string 状态描述()
    {
        return $"命中 {命中次数} / 过期 {过期次数}（命中率 {命中率:F0}%）" +
               $"｜预取成功 {预取成功次数} 失败 {预取失败次数}" +
               $"｜幻觉丢弃 {丢弃幻觉次数} 解析失败 {解析失败次数} 格式噪声 {格式噪声次数}" +
               $"｜局面清空 {清空次数} 次({清空丢弃条数} 条)" +
               $"｜队列 {队列计数()}/{目标长度}";
    }

    /// <summary>给"装上实测"看的两行完整统计</summary>
    public static string 详细统计()
    {
        return 状态描述()
               + Environment.NewLine
               + $"被终审拦下：{拦截摘要()}"
               + Environment.NewLine
               + $"其中排在队列第 2 位之后才过期的：{排队过期条数} 条"
               + Environment.NewLine
               + DeepSeekClient.缓存描述();
    }

    // ==================== 每帧驱动 ====================

    // ══════════════════════════════════════════════════════════════
    //  ★ 局面指纹 —— AI 请求去重 ★
    //
    //  ⚠️ 为什么要（两份评估都提到，且是对的）：
    //     `每帧更新()` 的补货只看"队列长度 + 节流时间"，
    //     **局面完全没变时照样发请求**。
    //     典型浪费：接怪前、木桩阶段、战斗平稳期。
    //
    //  ⚠️ 为什么要**量化**而不是哈希原始值：
    //     原始血量一直在小幅抖动（自然回复、平A、HoT），
    //     精确哈希每帧都不一样 → **等于没去重**。
    //     所以按档位量化：血量 **5% 一档**、MP **10% 一档**。
    //
    //  ⚠️ 量化粒度的取舍：
    //     太细 → 指纹一直变，去重失效
    //     太粗 → 局面真的变了却不发请求，**漏掉该有的决策**
    //     5% / 10% 是折中：跨档才重新请求。
    //
    //  ⚠️ **局限（必须说清）**：只省"有货可发"时的重复请求。
    //     队列空了照样补货 —— 否则就没建议可用了。
    //     ⇒ 主要省的是**平稳期 / 接怪前**，不是战斗中的高频决策。
    // ══════════════════════════════════════════════════════════════
    private static long _上次局面指纹;
    private static int 去重跳过次数;

    /// <summary>局面指纹（量化后的状态摘要的哈希）</summary>
    private static long 算局面指纹()
    {
        try
        {
            var sb = new System.Text.StringBuilder(64);

            // ── 自己：HP 5% 一档、MP 10% 一档 ──
            var 我 = AEAssist.Core.Me;
            sb.Append((int)(我.血量比例() * 20));      // 0~20
            sb.Append(':').Append((int)(我.蓝量比例() * 10));   // 0~10

            // ── 队友：按 id 排序后取血量档位（顺序稳定才可比）──
            var 队 = HealTargetHelper.可治疗队友(50f);
            var 项 = new List<(ulong Id, int 档)>(队.Count);
            foreach (var r in 队)
            {
                if (r == null) continue;
                项.Add((r.GameObjectId, (int)(r.有效血量比例() * 20)));
            }
            项.Sort((a, b) => a.Id.CompareTo(b.Id));
            foreach (var (id, 档) in 项) sb.Append('|').Append(档);

            // ── 敌人数量（不取血量 —— 小怪血量抖得厉害）──
            sb.Append('#').Append(HealTargetHelper.附近敌人总数(30f));

            // ── 时间轴：有没有"接下来要来的伤害"（这是关键决策输入）──
            sb.Append('@').Append(HealTargetHelper.木桩模式 ? 1 : 0);
            try
            {
                sb.Append('~').Append(HealerACR.Timeline.TimelineManager.未来有减伤(4.0) ? 1 : 0);
            }
            catch { }

            // ── 必须奶满机制（有人中 Doom 时局面性质完全不同）──
            try
            {
                sb.Append('!').Append(HealerACR.Common.必须奶满.找目标() != null ? 1 : 0);
            }
            catch { }

            // FNV-1a 64 位
            var 哈希 = 1469598103934665603UL;
            foreach (var c in sb.ToString())
            {
                哈希 ^= c;
                哈希 *= 1099511628211UL;
            }
            return unchecked((long)哈希);
        }
        catch
        {
            return 0;     // 算不出来 → 返回 0，调用方会当作"变了"照常请求
        }
    }

    /// <summary>每帧调用（很轻：只维护队列 + 到点启动一次后台任务）</summary>
    public static void 每帧更新()
    {
        var s = AiSettings.Instance;

        if (!s.启用决策层 || !s.已配置) return;

        // ① 清掉队首的过期建议
        清理过期();

        // ①.5 定期把统计打一条日志（装上去实测时靠这个看命中率）
        定期汇总();

        if (_预取中) return;
        // ★ 只查**决策通道** —— 别的通道熔断不该停掉预取（P1-11）★
        if (DeepSeekClient.该停发(DeepSeekClient.通道.决策)) return;

        // ② 队列够长 → 不用补货（这是"预取"的关键：有货就不问）
        if (队列计数() >= 目标长度) return;

        // ③ 补货节流
        var 间隔 = Math.Max(300, s.决策预取毫秒);
        if (TimeHelper.Now() - _上次预取 < 间隔) return;

        // ══════════════════════════════════════════════════════════
        //  ★ ④ 局面指纹去重 —— 局面没变就别问 ★
        //
        //  ⚠️ 只在**队列里还有货**时才跳 ——
        //     队列空了必须补，否则就没建议可用了。
        //     （这条限制决定了它主要省"平稳期"，见上面字段处的说明。）
        // ══════════════════════════════════════════════════════════
        var 指纹 = 算局面指纹();
        if (指纹 != 0 && 指纹 == _上次局面指纹 && 队列计数() > 0)
        {
            去重跳过次数++;
            if (去重跳过次数 % 20 == 1)   // 不刷屏：每 20 次报一条
                Ai调试.调试($"局面未变（指纹 {指纹:X}），跳过本次预取（累计跳 {去重跳过次数} 次）");
            return;
        }
        _上次局面指纹 = 指纹;

        _上次预取 = TimeHelper.Now();
        _ = 预取();
    }

    private static void 清理过期()
    {
        // 队列是 FIFO，过期的都在前面
        while (true)
        {
            var 头 = 看队首();
            if (头 == null || 头.还新鲜) break;

            出队();
            过期次数++;

            // ★ 区分"排太后面等过期"和"AI 建议得不对" ★
            //   出生时队列位置 > 0 = 它前面还排着别的建议 → 轮到它时已经晚了，
            //   属于**预取节奏问题**，不是 AI 判断错误。
            if (头.出生时队列位置 > 0)
            {
                排队过期条数++;
                Ai调试.调试(
                    $"建议 {头.技能Id} 过期未用（排在第 {头.出生时队列位置 + 1} 位，" +
                    $"等了 {头.已等毫秒}ms，批次 {头.批次}）");
            }
        }
    }

    /// <summary>
    /// 每 30 秒把统计打一条日志。
    ///
    /// **为什么要定期汇总**：单条日志看不出"命中率"这种比率，
    /// 而装上去实测时不可能一直盯着面板 —— 事后翻日志要能直接看到结论。
    /// </summary>
    private static void 定期汇总()
    {
        try
        {
            var 现在 = TimeHelper.Now();
            if (现在 - _上次汇总 < 30000) return;
            _上次汇总 = 现在;

            // 一次都没跑过就不刷（没开 AI / 没配 Key）
            if (命中次数 + 过期次数 + 预取成功次数 == 0) return;

            Ai调试.日志("【阶段B统计】" + 状态描述());
        }
        catch { }
    }

    /// <summary>
    /// 局面剧变（换目标 / 血量骤降 / 进战脱战）时清空队列。
    ///
    /// **为什么需要**：预取的本质是"赌局面不变"。
    /// 局面一变，队列里剩下的建议就全是错的 ——
    /// **过期的建议比没有建议更危险**（会做出与当前战场无关的决策）。
    /// </summary>
    public static void 局面剧变()
    {
        // ══════════════════════════════════════════════════════════════
        //  ★ 先让"还在飞的旧预取"作废 —— **必须在任何 early return 之前** ★
        //
        //  [!] 这是第三方审阅指出的真 bug（已核实）：
        //      原来 `_世代++` **只在 `重置()` 里**（切职业 / 换本才走）。
        //      于是局面剧变时：
        //          请求发出（世代 N）
        //            -> 血线骤降 -> 局面剧变 -> 清空队列
        //            -> 旧请求回来 -> `我的世代 == _世代` -> **照常入队**
        //          => 一条基于"旧局面"的建议进了新队列，
        //             而且它是**基于已经不存在的情况**做的判断。
        //
        //  [!] 为什么放在 try 的第一行、early return **之前**：
        //      原来 `if (队列计数() == 0) return;` 在最前面 ——
        //      而"队列刚被清空、请求还在飞"恰恰是最常见的场景
        //      （上次剧变清空了 -> 队列 0 -> 这次剧变直接 return -> 世代没增）
        //      => 那个在飞的请求永远不会被作废。
        //
        //  [!] 静态字段的自增不是原子操作，但这里的读写在
        //      **游戏线程**上（局面监控.每帧更新 由 AiHeartbeat 驱动），
        //      和后台线程只读不写 —— 所以不需要 Interlocked。
        //      （后台线程只在 L613 读它做比较。）
        // ══════════════════════════════════════════════════════════════
        _世代++;

        try
        {
            if (队列计数() == 0) return;

            var 丢掉 = 队列计数();
            清空队列();
            _上次局面变化 = TimeHelper.Now();
            _上次局面指纹 = 0;      // 局面剧变 → 指纹作废，下次一定请求

            // ★ 计入统计 ★
            //   不记的话，"命中率低"到底是被丢弃、过期，还是被局面剧变清掉，
            //   在事后完全分不出来 —— 那样统计就没法用来定位问题。
            清空次数++;
            清空丢弃条数 += 丢掉;

            Ai调试.日志($"局面剧变 -> 清空 {丢掉} 条待用建议（队列归零，下一帧重新预取）");
        }
        catch { }
    }

    /// <summary>
    /// 局面剧变 + **立刻重新预取**。
    ///
    /// ⚠️ 这是给"战斗中局面真的变了"用的（换目标 / 团血骤降）。
    ///
    ///    只调 <see cref="局面剧变"/> 的话，队列是空的，但仍要等
    ///    「决策预取毫秒」节流过去才会补货 —— 在日随里这个空窗期
    ///    正好是"最需要建议的时候"，等于没帮上忙。
    ///    所以这里顺手把节流时间戳也一起重置，让下一帧就补货。
    ///
    ///    不会因此打爆 API：`_预取中` 保证同一时刻只有一个请求在飞，
    ///    熔断检查和队列长度检查也都还在。
    /// </summary>
    public static void 局面剧变并重取()
    {
        try
        {
            局面剧变();

            // 把节流时间戳清掉 → 下一帧就能补货（但 _预取中 仍然挡住并发）
            _上次预取 = 0;

            var s = AiSettings.Instance;
            if (!s.启用决策层 || !s.已配置) return;
            if (_预取中) return;
            // ★ 只查**决策通道** —— 别的通道熔断不该停掉预取（P1-11）★
        if (DeepSeekClient.该停发(DeepSeekClient.通道.决策)) return;

            Ai调试.日志("局面剧变 -> 立刻重新预取");
            _ = 预取();
        }
        catch { }
    }

    // ==================== 预取 ====================

    private static async Task 预取()
    {
        _预取中 = true;
        var 本批 = ++_批次号;

        // ══════════════════════════════════════════════════════════════
        //  ★ 世代号：过期的预取结果**一个字都不许进队列** ★
        //
        //  ── 为什么（和 `Ai初始化` 刚修的是同一个 bug）──
        //    `重置()` 把 `清空队列()`、`_预取中 = false`，
        //    **但已经发出去的异步请求还在飞**。
        //    它回来时会直接 `解析并填充 → Enqueue`，
        //    把**按旧局面/旧职业**得出的建议塞进**新队列**。
        //
        //    而且 `_预取中 = false` 会放行下一个请求 →
        //    **两个请求并发在飞**，谁后回来谁的条目排在队尾，
        //    统计（预取成功/失败）还会重复计。
        //
        //  ── 症状 ──
        //    切职业 / 换本之后头几秒，AI 的建议可能"驴唇不对马嘴"：
        //    理由是旧局面的（"队伍在掉血→建议群奶"），
        //    而白名单是用**新职业的表**校验的 —— 所以只有两个职业
        //    都存在的 ID 进得来，看起来"技能对、时机不对"，极难排查。
        //
        //  ── 修法 ──
        //    和 `Ai初始化` 完全一致：记下自己的世代，回来时对不上就丢弃。
        // ══════════════════════════════════════════════════════════════
        var 我的世代 = _世代;

        try
        {
            // ★ 记下**本次请求对应的候选快照** ★
            //
            //  [!] 为什么必须在"发请求前"取（第二轮审阅 P0-1/P0-3）：
            //      `C1/C2` 只是排序后的位置，缓存 300ms 一过就重排重编号。
            //      AI 请求要等 2~8 秒，回来时 C1 很可能已经是**另一个动作**。
            //      所以：
            //        · 请求前取一次快照，把"快照号"写进提示词
            //        · 响应回来时按那个快照号取回**当时那份候选表**解析
            //        · 取不到（太久远）就整个丢弃 —— 绝不用当前候选凑合
            // ★ 一个 Snapshot 贯穿：候选段、提示词、响应解析**都用这一份** ★
            //
            //  [!] 为什么不传"号"而要传"对象"：
            //      传号就要在解析时**按号再查一次**，而那次查可能查不到
            //      （快照被淘汰）—— 于是整批建议静默丢弃。
            //      传对象则整个生命周期都握着同一份不可变数据，
            //      连"查不到"这个失败模式都不存在。
            var 本次快照 = 候选集.生成();
            var 局面 = AiSituation.采集(本次快照);

            // 决策层：给 3 秒 —— 它是在"备货"，不必卡在 GCD 内
            // 超时 8 秒 —— deepseek-flash 是**推理型模型**，会先思考再回答，通常 3~10 秒。
            // 反正是预取备货，慢一点没关系：备好了等着用，比"快但总超时"强。
            //
            // ⚠️ `期望_ID理由格式: true` —— 这是**唯一**需要它的调用点：
            //    正文被截断成空时，允许从思考里捞 `ID|理由`（见 处理推理型回复）。
            //    其他调用点（倾向/提炼）要的是散文，捞不得 —— 那会把
            //    "思考过程"当成"结论"交上去，而且看不出来是半成品。
            // ★ 关思考 —— 这是**唯一的超高频调用点**，必须关 ★
            //
            //  [!] 官方默认开启思考且 effort=high；实测不关时中位耗时 2.6 秒，
            //      而 GCD 只有 2.5 秒 —— 答案回来就过期了（实测命中率 33%、
            //      46% 过期待废，大部分是这个原因）。
            //
            //  [!] 决策层是"备货"，不需要深度推理：
            //      局面报告已经把选项、缺口、减伤、时间轴都算好了，
            //      它只要按规则挑一个 —— 这是**快**比**深**重要的场景。
            var 回复 = await DeepSeekClient.提问(拼系统提示(), 局面, 8000,
                         期望_ID理由格式: true,
                         关思考: true,
                         // ★ 独立通道 —— 决策层是**最容易失败**的一层（高频、
                         //   有硬延迟上限），绝不能让它的失败拖垮策略层。
                         道: DeepSeekClient.通道.决策).ConfigureAwait(false);

            // ★ 世代校验：过期就整个丢弃，连统计都不记（那会污染命中率）★
            if (我的世代 != _世代)
            {
                Ai调试.调试($"预取第 {我的世代} 代已过期（当前 {_世代} 代），丢弃本次结果");
                return;
            }

            if (回复 == null)
            {
                // ★ 失败要计数 ★
                //   原来只是静默 return —— 于是"命中率低"到底是
                //   AI 建议不好、还是请求根本一直在失败，事后分不出来。
                预取失败次数++;
                Ai调试.日志($"预取失败（批次 {本批}，无回复）" +
                            $"｜累计 成功 {预取成功次数} / 失败 {预取失败次数}");
                return;
            }

            var 条数 = 解析并填充(回复, 本批, 本次快照);

            if (条数 > 0)
            {
                预取成功次数++;
                Ai调试.日志($"预取 {条数} 步（批次 {本批}，队列 {队列计数()}/{目标长度}）");
            }
            else
            {
                预取失败次数++;
                Ai调试.日志($"预取解析出 0 条（批次 {本批}）—— 看下面『解析失败/疑似幻觉』的明细");
            }
        }
        catch (Exception e)
        {
            预取失败次数++;
            Ai调试.日志("决策预取异常（已忽略）：" + e.Message);
        }
        finally
        {
            // ⚠️ 只有**最新一代**才能清 `_预取中`。
            //    过期的那次如果也清了，就会把仍在跑的新请求
            //    "放行"出第三个并发请求。
            if (我的世代 == _世代) _预取中 = false;
        }
    }

    // ==================== 提示词 ====================

    /// <summary>
    /// 拼出这次实际发的系统提示 = 固定规则 + **可选的"完全采信"补充**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么不能在 `系统提示` 那个字段里直接写死 ★
    ///
    ///    它是 `static readonly` —— **进程启动时求值一次**，
    ///    而「完全采信AI」是**运行时随时能勾/取消**的开关。
    ///    写死的话：勾了开关，AI 那边**永远不知道**自己已经全权了。
    ///
    ///  ── 为什么必须告诉 AI ──
    ///    不告诉它，它会**按原来那套保守规则出牌**（"有人在等治疗就别输出"），
    ///    而本地已经不拦了 —— 开关就形同虚设（等于白勾）。
    ///    开关的语义是"AI 说了算"，那就得让 AI 知道"你现在说了算"。
    ///
    ///  ⚠️ 补充内容**放在最前面**：这是最高优先级的上下文变更，
    ///    埋在末尾容易被模型当成附加说明忽略掉。
    ///
    ///  ⚠️ 提示词里**不要**写"高风险""出事别怪我"这类话 ——
    ///    那不会让模型更谨慎，只会占字符、干扰它理解规则。
    ///    要写的是**可执行的行为变更**。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static string 拼系统提示()
    {
        try
        {
            if (!HealerACR.Common.HealQt.GetQt("完全采信AI", false)) return 系统提示;

            return """
                ═══ 本次为「完全采信 AI」模式（最高优先级，覆盖下面全部默认倾向）═══
                本地逻辑**已经不再复核你的建议** —— 你说放什么就放什么。
                所以你必须**自己承担**下面这些判断（平时是本地兜的）：
                  · **有人快死了就先救人** —— 没有任何东西会替你拦下"该治疗却打输出"
                  · DoT 该不该补**由你判断剩余时间**（平时本地会拦"还没到该补的时候"）
                  · **优先用【可选动作】里的候选编号**（形如 C1）—— 候选已经带好了目标。
                  候选不够用时才写技能 ID，那时目标由本地按类别推断。
                这不是让你更激进，是让你**更负责** —— 请比平时更谨慎。

                """ + 系统提示;
        }
        catch
        {
            return 系统提示;   // 读不到开关 → 用原提示（失败方向是"不采信"）
        }
    }

    /// <summary>
    /// 系统提示 —— 和策略层同一条铁律：**不许编机制，不许编技能。**
    ///
    /// **改成一口气要 3 步**：这样一次请求就能填满队列，
    /// 不必每个 GCD 都问一次（省 token 又抗延迟）。
    /// </summary>
    private static readonly string 系统提示 = $"""
        你是 FF14 治疗职业的战斗决策助手。
        根据【数据】里的局面，给出**接下来 {每次请求步数} 个 GCD** 最该放的技能，按先后顺序。

        ═══ 铁律 ═══
        1. 你【不了解】这个副本的机制。不要猜测、不要回忆、不要描述机制。
        2. 只能从【可选技能】清单里选技能 ID。清单外的 ID 一律不许输出。
        3. 数据不足就输出：0|数据不足
        4. 理由必须对应【数据】里某一项。
        5. 禁止编造技能名或机制名。
        6. 后面的步骤是**预判**：如果前面几步之后局面可能变化，按你的判断给最合理的后续。
           不确定就重复当前最优解，**不要为了凑数编技能**。
        6b. 【队伍】里标 `[自己]` 的那行就是你，**不是另一个队友**。
           数治疗/坦克人数时别把它多算一个 —— 否则你会以为"有人兜底"而少交技能。

        ═══ 最高优先级：必须奶满 ═══
        7. 【数据】里出现「必须奶满机制」段时 —— **它的优先级高于一切**。
        那段会写明目标名字和状态名，你必须**优先对那个人使用治疗技能**。
        8. ⚠️ 判断依据**不是血量**：那个人可能血量看着很健康（比如 80%），
        但状态效果结束时他会**直接无法战斗**。**不许**因为"他血还挺多"
        而把治疗给别人 —— 那等于放弃他。
        9. 这个状态**只能靠治疗解除**，没有别的办法。理由里请写"必须奶满"。
        10. 只有在【数据】里**没有**「必须奶满机制」段时，才按血量/人数等常规判断走。

        ═══ 移动相关（务必遵守）═══
        11. 【数据】里的「移动状态」**决定你能建议什么技能**：
            · 「**移动中**」→ **只能建议标了「瞬发」的技能**（含能力技）。
              读条技能会被本地挡掉，等于白问一轮 —— 标「读条 X.Xs」的一律别选。
            · 「站定」→ 读条技能可以正常建议。
            · 「正在读条」→ 那一发已经在读了，不要再建议同一个技能。
        12. 移动中没有瞬发输出技能时，可以建议**瞬发治疗**，或输出
            `0|移动中无瞬发技能可用，等站定`。**不要硬推读条技能凑数。**

        ═══ 位置稳定性 ═══
        13. 【敌人】里的「位置稳定性」**决定地面技能值不值得铺**：
            · 「稳定」→ 罩子 / 地星 / 庇护所这类地面技能可以建议。
            · 「不稳定/观察中」→ **不要建议地面技能**，敌人一走就白铺了；
              改用能立即生效的技能。

        ═══ 副本与机制预告 ═══
        14. 【副本与机制时间轴】告诉你**接下来会发生什么**：

            · 「正在发生：XXX」= 当前掉血的**原因**。理由里对上它，
              比笼统说"有人掉血"有用得多。

            · **5 秒内**的条目 → 现在就准备：提前铺减伤、
              挂上 HoT（要时间起效）、别在这时候把群奶能力技花掉。

            · **10~20 秒后**的条目 → 决定"现在能不能花资源"：
              后面有大伤害就别清空资源；后面很平就放心输出。

            · 「没有匹配到时间轴」**不等于没有机制**，只等于查不到 →
              **保守一点**：血线留高、能力技别乱花。

        15. ⚠️ **绝对不许凭副本名回忆机制。**
            副本名不是让你回忆这个本有什么机制的 —— 那是你最容易编错的地方
            （你并不真正记得，只会编得像）。
            · 只准用「机制预告」里**明确列出来**的条目。
            · 没写的就当作"不知道"，写 `0|后续未知，按当前血线判断`。
            · 编一个不存在的机制名，比什么都不说**危害大得多**。

        ═══ 全部敌人（DoT 判断必须看它）═══
        16. 【敌人】里的「**其他敌人**」列表 = 当前目标之外，附近最需要关注的几个。
            每行的 `[**没有我的DoT**]` / `[**已有我的DoT**]` 是关键。

            · **补不补 DoT 看最后一行的覆盖率汇总**，不是只看当前目标：
              「5 个里 4 个有」→ **别补**，只差一个不值得占 GCD。
              「5 个里 1 个有」→ 可以补。
              当前目标有 ≠ 全都有 —— 反过来也一样。

            · 标了 `残血`（≤25%）且汇总说"这一波快清完了" →
              **别交群奶、别交爆发、别补 DoT**，省给下一波。

            · 标了 `近(Xm)` 的 → AOE 能一起打到，`适合放 AOE：是` 时优先。

        17. 【敌人】写着「当前没有选中目标」→ **看不到 DoT 覆盖**。
            这种情况**不要补 DoT**（盲打），可以治疗或输出 `0|无目标，不补DoT`。

        ═══ 技能可用性（务必遵守）═══
        18. 【可选技能】里**只列了当前等级真的能用的技能**。
            · **不许建议清单外的任何技能** —— 哪怕你确定"这个职业有那个技能"。
            · 清单末尾写着「另有 M 个因等级/职业任务没到未列出」的那些，
              **就是现在用不了的**，一个字都别建议。
            · 写着「等级同步中」时，**以副本内的等级为准** —— 高等级技能会变灰。

        ═══ 怎么选目标（最容易选错的地方）═══
        19. **单体治疗打血最少的人**（比**裸血量**，不看盾）——
            **没有"坦克优先"**，谁最危险治谁。

        20. ⚠️ **标了"无敌中"的人：别治、别给减伤。**
            那几秒**他本来就不会死**，灌治疗是纯浪费（CD 全白交）。
            例外：标了「**死而不僵（要奶）**」的**要治**。
            只按标记走，**没标就别猜**。

        21. **预铺减伤只给坦克**（绿帽 / 水流幕 / 天星交错 / 输血）。
            给非坦克铺没意义 —— 伤害本来就不打他。

        22. **DoT 只铺主目标**，一波补 2~3 个够，别每只小怪都补。

        ═══ 输出填充技：按清单里的威力挑，不要凭记忆 ═══
        22b. 清单里每个技能后面的 `力N` 就是它的威力/恢复力。
             **同一次选择里挑 `力` 最大的那个**（治疗比恢复力，输出比威力）。

             · ⚠️ **不要**凭训练记忆说"XX 才是主力填充"。攻略里的循环
               是**满级**的，而你现在可能是等级同步的副本 ——
               你记忆里的那个技能**清单里没有，就是现在用不了**。
             · ⚠️ **不要因为"某个技能是瞬发"就优先它**：
               瞬发只在**移动中**才有价值。
               【数据】的「移动状态」写 **站定** 时，**读条但威力更高的
               那个更好** —— 多 10 威力也是多，没理由让给瞬发。
               写 **移动中** 时才退而求其次选瞬发。
             · 清单里可能同时列了「基础输出」和「站定填充」两类，
               那是本地按你的**当前等级**挑出来的可用技能 ——
               站定就看它们的 `力`，挑大的。

        ═══ 花资源前先想一句 ═══
        23. 你建议的每个技能都**要占一个 GCD 或一次能力技机会**，
            所以先问"这一下比另一个选择更好吗？"
            · 只有 1 个人掉血 → **别群奶**。
            · 全队 >85% → **别治疗**，去打输出。
            · 主目标已有 DoT → 看覆盖率汇总再决定。

        24. **能用能力技就别用读条治疗** —— 能力技不占 GCD、
            不受移动影响，能把 GCD 留给输出。

        ═══ 爆发与长 CD 技能 ═══
        25. ⚠️ **小怪快清完时别开爆发 / 别交长 CD 技能。**
