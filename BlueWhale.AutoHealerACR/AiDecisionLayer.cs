    /// <summary>
    /// 取建议（**出队**）。返回 null 表示"没有可用建议"。
    ///
    /// ⚠️ **不要在 Check() 里调这个** —— 会导致逻辑陷阱：
    ///
    ///    Check 出队 A → 返回高分
    ///      ↓
    ///    如果这一帧被更高优先级的 resolver 抢先，Build 没被调用
    ///      → **A 已经出队，永久丢失** ❌
    ///
    ///    而且 Build 里再读"当前建议"（Peek）时已经不是 A 了
    ///      → **Check 判的是 A，Build 放的可能是 B** ❌
    ///
    ///  正确用法：
    ///    Check → 用 当前建议（只看）
    ///    Build → 用 当前建议 + 放完之后调 消费()
    /// </summary>
    public static 建议? 取建议()
    {
        清理过期();

        // ⚠️ 用"看队首 + 出队"两个包装方法，而不是"判空再 Dequeue" ——
        //    后者是**复合序列**，两步之间队列可能被线程池线程改动。
        var s = 看队首();
        if (s == null) return null;
        出队();

        // ⚠️ 这里**不**加命中计数 —— 命中只应由 消费() 记。
        //
        //    原因：这个方法是"出队"，它无条件把建议拿走，
        //    **不保证技能真的放出去了**（可能被更高优先级抢掉）。
        //    如果这里也 ++ 命中次数，命中率会被虚高 ——
        //    统计一旦不可信，就没法用来判断"预取队列重写到底有没有效"。
        //    所以计数口径统一收敛到 消费()。
        return s;
    }

    /// <summary>
    /// 消费队首建议（**技能真的放出去了才调**）。
    ///
    /// 这是 Check/Build 分离的正确做法：
    ///   Check 只看（Peek）→ 不动队列
    ///   Build 放成功后 → 调这个出队
    /// </summary>
    public static void 消费()
    {
        try
        {
            清理过期();

            // ⚠️ 出队本身已经是"空队列就什么都不做"，不需要先判空 ——
            //    判空再出队是**复合序列**，两步之间队列可能被改动。
            出队();
            命中次数++;
        }
        catch { }
    }

    public static void 重置()
    {
        清空队列();
        _上次预取 = 0;
        _上次局面变化 = 0;
        _上次汇总 = 0;
        _预取中 = false;
        _批次号 = 0;

        // ★ 让"还在飞的旧预取"作废 ★
        //   只清 `_预取中` 不够 —— 那个标志管不了已经离开的异步任务。
        _世代++;

        命中次数 = 0;
        过期次数 = 0;
        排队过期条数 = 0;
        解析失败次数 = 0;
        格式噪声次数 = 0;
        丢弃幻觉次数 = 0;
        清空丢弃条数 = 0;
        清空次数 = 0;
        预取成功次数 = 0;
        预取失败次数 = 0;
        _拦截原因.Clear();
    }

    /// <summary>
    /// 这个 ID 是不是当前职业真的会用的技能。
    ///
    /// **白名单是防幻觉的硬手段** —— 提示词只是"请求"它别编，
    /// 这里是"验证"它有没有编。两道一起上才稳。
    /// </summary>
    private static bool 在可选清单里(uint id)
    {
        if (id == 0) return false;

        try
        {
            var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null) return true;   // 拿不到表就不拦（宁可放过也别全丢）

            if (id == 表.基础输出) return true;
            if (id == 表.群体输出) return true;
            if (id == 表.Dot技能) return true;
            if (id == 表.移动填充技) return true;
            if (id == 表.单体治疗GCD) return true;
            if (id == 表.群体治疗GCD) return true;
            if (id == 表.紧急单奶) return true;
            if (id == 表.群体治疗能力技) return true;
            if (id == 表.单体盾) return true;
            if (id == 表.群体盾) return true;
            if (id == 表.团队减伤) return true;
            if (id == 表.复活) return true;
            if (id == 表.驱散) return true;
            if (id == 表.醒梦) return true;

            // ══════════════════════════════════════════════════════════════
            //  ★ 治疗候选池 —— **必须查**（核实发现的漏洞）★
            //
            //  [!] 现象：`采可选技能` 把 `表.治疗候选.全部` **整池列给 AI**，
            //      但白名单只逐槽位比（单体治疗GCD / 群体治疗GCD / 紧急单奶 /
            //      群体治疗能力技 / 单体盾 / 群体盾 …）。
            //
            //      学者的治疗池有 10 项，其中**小仙女系那几项**
            //      （异想的祥光 / 慰藉 / 仙光的低语）和**深谋远虑之策**
            //      **不在任何白名单槽位里** => AI 从清单里抄它们 =>
            //      被判"幻觉"丢弃，`丢弃幻觉次数++`。
            //
            //  [!] 这比"漏列"更糟：**我们列给它的东西我们不认** ——
            //      于是 AI 的**正确行为被统计成错误行为**，
            //      "幻觉率""命中率"这些数字也跟着失真。
            //
            //  [!] 直接查治疗池、不再逐槽位列举 —— 槽位会变，池才是清单的来源。
            // ══════════════════════════════════════════════════════════════
            try
            {
                foreach (var 技 in 表.治疗候选.全部)
                {
                    if (技 != null && 技.Id != 0 && id == 技.Id) return true;
                }
            }
            catch { }

            if (表.输出能力技 != null && Array.IndexOf(表.输出能力技, id) >= 0) return true;
            if (表.脱战准备技能 != null && Array.IndexOf(表.脱战准备技能, id) >= 0) return true;

            // ⚠️ 这里原来还有一行：
            //       if (表.所有DotBuff != null && Array.IndexOf(表.所有DotBuff, id) >= 0) return true;
            //    **已删**（审计发现）—— 那是个类型错误：
            //      · `所有DotBuff` 是**状态(buff) ID** 数组
            //        （白魔那里填的是 `AuraIds.白魔Dot` 这类）
            //      · 而 DoT 的**技能 ID** 上面第 778 行 `表.Dot技能` 已经判过了
            //    ⇒ 那行既是冗余，又让 buff ID（1871/2035/1895…）**冒充合法技能**
            //      混进白名单 —— 结果是"AI 回了个 buff ID"不被算作幻觉，
            //      `丢弃幻觉次数` 少算，统计失真。
            //
            //  ⚠️ 白名单只能放**技能 ID** —— 这是它存在的唯一意义。
            //     buff ID 混进来就等于开了一个洞（哪怕后面终审还会挡）。

            return false;
        }
        catch
        {
            return true;
        }
    }
