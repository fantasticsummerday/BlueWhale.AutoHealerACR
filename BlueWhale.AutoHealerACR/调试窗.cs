                else if (!表命中 && 时间轴)
                    ImGui.TextDisabled(
                        "  ↑ 表没命中但时间轴在跑 ⇒ 判据②把它当副本。" +
                        "野外不该跑时间轴（`test.txt` 是测试用的）—— 不想这样就把「启用时间轴」关掉");
            }
            catch { }

            try
            {
                var 我 = Core.Me;
                // ⚠️ **必须判 `对象有效()`，只判 `!= null` 不够** ——
                //    `Core.Me` 指向的对象在换图/切区时会被**释放**，
                //    但它**不是 null**（Dalamud 会写成哨兵地址 `0x12345679`）。
                //    只判 null 就会去读一个已释放对象的结构体 ==>
                //    **原生访问违例**（穿 catch、无转储、全局钩子不触发）。
