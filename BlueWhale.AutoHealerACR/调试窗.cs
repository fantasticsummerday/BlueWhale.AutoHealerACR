            //        只有"折叠"这一种状态下才会走到，所以开发时没踩到。
            // ══════════════════════════════════════════════════════════════
            //  ★★★ **探针必须在 `Begin` 之前** —— 这是被实测逼出来的 ★★★
            //
            //  [!] 上一版把探针放在 `Begin` 之后，结果：**0 条输出**。
