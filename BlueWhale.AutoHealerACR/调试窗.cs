            //  ★ 判据来源展开（用户报「70 级本显示 在副本里=false」）★
            //
            //  [!] 为什么需要这一行：
            //      `在副本里()` 是 **两条判据取或**，显示 false 时看不出是哪条没过：
            //        ① `地名.是副本(地图)` —— 查表（表缺条目就 false）
            //        ② `时间轴在跑()`     —— 要求 `启用时间轴 && Runner.有数据`
            //      一个「不在表里 + 没 cactbot 时间轴」的副本**两条都 false**
