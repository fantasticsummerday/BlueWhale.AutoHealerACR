                    $"｜缓存地图={缓存}{(缓存 != 地图 ? "  <- 刚切图，缓存还没跟上" : "")}");
                if (!表命中 && !时间轴)
                    ImGui.TextDisabled(
                        "  ↑ 两条都 false ⇒ 判成不在副本。若是真在副本里，说明这个地图 id 缺表条目");
                // ★ **表没命中但时间轴在跑** —— 这是"野外加载了时间轴"的情况，
                //   判据②会把它当成副本。用户实测截图问过「未战斗却在预测」时
