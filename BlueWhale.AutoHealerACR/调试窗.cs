            //      两者不一致说明"地图刚变、缓存还没更新"（不是 bug，是时序）。
            // ══════════════════════════════════════════════════════════════
            try
            {
                var 表命中 = 地图 != 0 && 地名.是副本(地图);
                var 时间轴 = false;
                try { 时间轴 = TimelineManager.时间轴在跑(); } catch { }
                var 时间轴开关 = false;
                try { 时间轴开关 = HealerACR.Common.HealSettings.Instance.启用时间轴; } catch { }
