                System.IO.Directory.CreateDirectory(目录);
                _诊断路径 = System.IO.Path.Combine(目录, "调试窗-绘制.txt");
            }
            catch
            {
                try
                {
                    _诊断路径 = System.IO.Path.Combine(
                        System.IO.Path.GetTempPath(), "BlueWhale调试窗-绘制.txt");
                }
                catch
                {
                    _诊断路径 = "BlueWhale调试窗-绘制.txt";
                }
            }
            return _诊断路径;
        }
    }

