    /// <summary>
    /// 安全读 **GameObjectId + DataId**（种类 id）—— 用于诊断"是哪个对象失效了"。
    ///
    /// [!] 为什么单独包一层：失效对象上读属性会触发**原生访问违例**
    ///      （`0xc0000005`，**直接穿透 C# 的 catch**），
    ///      而这里正是在"**怀疑对象已失效**"时去读它。
    ///
    /// [!] 为什么用 `DataId` 而不是 `NameId`：
    ///      `NameId` 在 `IBattleChara` 上（`AEAssist.Extension.IBattleChara`），
    ///      而本文件拿到的是 `IGameObject` —— 强转会引入额外依赖与失败点。
    ///      `DataId` 是 `IGameObject` 自带的，**够用**（它就是"哪一种怪/人"的 id）。
    ///
    /// [!] ⚠️ **两个属性各自独立 try** —— 一个读失败不能影响另一个。
    /// </summary>
    private static string Safe身份(object? o)
    {
        var 对象 = "";
        try
        {
            if (o is Dalamud.Game.ClientState.Objects.Types.IGameObject g)
                对象 = g.GameObjectId.ToString();
        }
        catch { 对象 = "读取失败"; }

        var 种类 = "";
        try
        {
            // ⚠️ `DataId` 已被 Dalamud 改名为 `BaseId`（编译期 CS0618 警告）。
            //    这里只用于**显示**，所以直接用新名字；旧名字在同版本上仍可用，
            //    但留着会一直刷警告。
            if (o is Dalamud.Game.ClientState.Objects.Types.IGameObject g2)
                种类 = g2.BaseId.ToString();
        }
        catch { 种类 = "读取失败"; }

        return $"GameObjectId={对象} BaseId={种类}";
    }

    private static void 记诊断(string 内容)
    {
        try
        {
            _记诊断次数++;

            // ══════════════════════════════════════════════════════════════
            //  ★★★ 两道门**都失效过** —— 实测写出 **69 MB / 467,915 行** ★★★
            //
            //  [!] 实测证据（`%APPDATA%\BlueWhale\调试窗-绘制.txt`）：
            //        69,568 KB、467,915 行、跨度 20.6 小时
            //        ⇒ 平均 **每秒 6.3 次写入** ⇒ 磁盘 I/O 长期饱和
            //        ⇒ 症状：**整机卡顿 + 鼠标延迟 + UI 帧提交被拖慢（闪）**
            //
            //  [!] 门①（时间）：**用了 `TimeHelper.Now()`** ——
            //      而这个东西的语义**已被实测证伪**（把它当毫秒用会失效：
            //      面板绘制门设 8ms 却仍被画 680 次/秒）。
            //      ==> `现在 - _上次毫秒 < 1000` **几乎从不成立** ⇒ 门形同虚设。
            //      ==> 改成 `Environment.TickCount64`（文档明确的毫秒、单调、无分配）。
            //
            //  [!] 门②（内容）：`内容 == _上次诊断` ——
            //      但**内容里带了每次调用都变的计数器**（`#编号`、`第N次`），
            //      ==> 内容**永远不同** ==> 门**永远不命中**。
            //      ==> 调用方**不许**把计数器写进内容（见 `画()` 里的说明）。
            //
            //  [!] 再加一道**文件大小闸门** —— 前两道是"少写"，
            //      这一道保证"**再怎么出错也不会长成 69 MB**"。
            // ══════════════════════════════════════════════════════════════
            var 现在 = Environment.TickCount64;
            if (_记诊断次数 > 5 && 现在 - _记诊断上次毫秒 < 1000) return;
            _记诊断上次毫秒 = 现在;
            if (_记诊断次数 > 5 && 内容 == _上次诊断) return;
            _上次诊断 = 内容;

            // ── 文件大小闸门：超过 1 MB 就清空重来（不留备份，它是诊断文件）──
            try
            {
                var 路径 = 诊断路径;
                var 信息 = new System.IO.FileInfo(路径);
                if (信息.Exists && 信息.Length > 1_048_576)
                {
                    System.IO.File.WriteAllText(路径,
                        $"[{DateTime.Now:HH:mm:ss}] （文件超过 1 MB，已清空重来）{Environment.NewLine}");
                }
            }
            catch { }

            var 行 = $"[{DateTime.Now:HH:mm:ss}] {内容}{Environment.NewLine}";
            System.IO.File.AppendAllText(诊断路径, 行);
        }
        catch (Exception e)
        {
            // [!] **写失败也要留痕** —— 否则"写不进去"和"没执行到"看起来一样。
            //     这是这次排查踩的坑：HealerACR 侧有输出、这边一片空白，
            //     但完全看不出是哪种原因。
            try
            {
                var 兜底 = System.IO.Path.Combine(
                    System.IO.Path.GetTempPath(), "BlueWhale调试窗-写失败.txt");
                System.IO.File.AppendAllText(兜底,
                    $"[{DateTime.Now:HH:mm:ss}] 写 {诊断路径} 失败：{e.GetType().Name} {e.Message}{Environment.NewLine}");
            }
            catch { }
        }
    }

