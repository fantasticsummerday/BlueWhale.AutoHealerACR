            //        · `BeginPopup` / `BeginMenu` / `BeginTable` / `BeginTabBar`
            //          / `BeginCombo` / `BeginTooltip` -> **只有返回 true 才 End**
            //
            //  [!] ⚠️ **本文件里曾经有一段注释把这两类写反了**：
