            //      并且每一步**各自包 try** —— 一处失败不会让整条探针哑掉。
            //      这样下一次运行不管发生哪种情况，日志里都有明确答案。
            // ══════════════════════════════════════════════════════════════
            var 现在诊断2 = Environment.TickCount64;
