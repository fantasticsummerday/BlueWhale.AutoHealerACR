            }

            // ══════════════════════════════════════════════════════════════
            //  ★★★ 窗口开着的标志 —— 用**局部变量**，不要复用 `_窗口开` ★★★
            //
            //  [!] 为什么要这个变量（这是**全局闪烁**的真正原因）：
            //
            //      原来这里写的是：
            //          if (!begin结果) { ImGui.End(); return; }   // 我加的
            //          ...
            //          finally { ImGui.End(); }                     // 本来就有
            //
            //      `return` 会**触发 `finally`** ⇒ 那条路径上 `End()` 被调了
            //      **两次** ⇒ ImGui 窗口栈**多弹了一层**。
            //
            //  [!] 为什么这会"全局"闪：
            //      ImGui 的窗口栈是**进程级共享**的。多弹一层等于把**别人的窗口**
            //      （Dalamud 自己的、框架的、设置面板的）从栈上弹掉
            //      ⇒ **每个窗口都错位一层** ⇒ 画到别人身上 ⇒ 双重曝光 + 闪烁。
            //      这正好解释了用户实测「设置面板和 Dalamud 窗口**一起**闪」。
            //
            //  [!] 证据（用户对照法，一步命中）：
            //      把「能跑的 0.4.2.2」与当前版本的全部 ImGui 调用逐个对比：
            //        · 34 种调用里 **33 种完全相同**
            //        · **唯一的变化**：`ImGui.End` 从 **1 次 → 2 次**
            //      ==> 多出来的那个 `End()` 就是原因。
            //
            //  [!] 正确做法（既满足 ImGui 契约，又只 End 一次）：
            //      · `Begin` 返回 false 时**只是"内容不该画"**，窗口**仍在栈上**
            //        （源码实证：`Begin` 无条件 `CurrentWindowStack.push_back`，
            //          返回的是 `!window->SkipItems`）
            //      · 所以**必须** End —— 但**交给 `finally` 去做**，
            //        自己**不要**再 End 一次。
            // ══════════════════════════════════════════════════════════════
            //  ⚠️ 原来这里有个 `var 窗口在栈上 = true;` 的局部标志，
            //     但 `finally` 结构本身已经保证"必 End"，那个标志**从未被读过**
            //     （CS0219）。已删除，避免留一个"看起来在控制流程"的死变量。
            var begin结果 = ImGui.Begin("小鲸鱼 · 实时数据（只读）", ref _窗口开,
                                        ImGuiWindowFlags.NoCollapse);

                   记诊断($"Begin={begin结果} 屏={屏.X:F0}x{屏.Y:F0}");
                   // 实际位置/尺寸在 Begin 之后才拿得到（见下面的 GetWindowPos）

            // ══════════════════════════════════════════════════════════════
            //  [!] `Begin` 返回 false = **内容不该画**（窗口被折叠/完全裁剪），
            //      但窗口**仍在栈上** ⇒ 仍然需要 End —— 由下面的 `finally` 负责。
            //
            //  ⚠️ **这里绝对不能自己调 `ImGui.End()`** —— 那会让 `finally`
            //      再弹一次（`return` 会触发 `finally`）⇒ 全局窗口栈错位 ⇒
            //      **所有窗口一起闪**。这是本项目最严重的一个"看起来对"的 bug。
            // ══════════════════════════════════════════════════════════════
            if (!begin结果)
            {
                return;   // End 由 finally 配对（只调一次）
            }

        // ══════════════════════════════════════════════════════════════
        //  ★ 这段【必须在 `Begin` 之后】—— 修的是「顺序颠倒」★
        //
        //  [!] 实测证据（为什么必须移到这里）：
        //      · `绘制()` 确实在跑（调用探针每次运行都报）
        //      · 但 `★Begin前` 探针 **0 条**、`记诊断` 的 `Begin=` **0 条**
        //      · 外层 catch 会写日志，也是 **0 条** ⇒ 不是异常
        //      ==> 执行在到达探针之前就被挡走了 —— 挡路的就是这段队伍校验。
        //
        //  [!] 原来的顺序是**反的**：
        //        重活（遍历 `CastableAlliesWithin30` + 逐个 `对象有效()`）
        //        在 `Begin` **之前**做，而结果只在 `Begin` **之后**用。
        //      ==> `Begin` 返回 false（窗口没显示）时那些重活**完全白跑**，
        //          而且**白跑 60 次/秒**。
        //
        //  [!] 它还是历史上「读到已释放对象 ⇒ 原生访问违例杀进程」的同一段代码；
        //      移到 `Begin` 之后，只在**真要画内容**时才碰游戏对象，风险更低。
        //
        //  [!] 上面那两条区域检查（`IsBetweenAreas` / 副本 id）**留在前面** ——
        //      它们是一次廉价调用，而且要在探针里报出来。
        // ══════════════════════════════════════════════════════════════

            // ③ ★ 本版新增：**队伍整体可信吗** ★
            //
            //  [!] 为什么还需要第③条（用户实测「进本就闪退」）：
            //      ①②都放行、但**队友对象已经失效**的那一小段窗口确实存在：
            //      进本/出本瞬间 `IsBetweenAreas()` 可能已经返回 false、
            //      地图 id 也已经非 0，而**队伍里的角色对象还在重建**。
            //      那一刻读 buff -> `StatusList` 抛/踩空 -> **进程被杀**。
            //
            //  [!] ⚠️ **关键认识：这类崩溃 `try/catch` 兜不住** ——
            //      它是访问违例（`0xc0000005`）级别，**直接穿透 C# 的 catch**。
            //      所以"在外层包一个 try"是**无效的**（外面本来就有，照样崩）。
            //      ==> 唯一有效的办法是**读之前就判定"不能读"**。
            //
            //  [!] 判据：逐个确认队伍成员对象**当下**有效。
            //      只要有一个读不到，就当整个队伍不可信（宁可少显示）。
            //
            //  [!] ⚠️ **但要能说出是哪个对象** —— 否则"某个对象永久失效"
            //      会让窗口**永久空白**，而现象只是"加载不出来"，无从下手。
            if (可以读游戏状态)
            {
                try
                {
                    var 队 = PartyHelper.CastableAlliesWithin30;
                    if (队 == null)
                    {
                        可以读游戏状态 = false;
                        挡住原因 = "③ CastableAlliesWithin30 == null";
                    }
                    else
                    {
                        var 序号 = 0;
                        foreach (var r in 队)
                        {
                            序号++;
                            if (r == null)
                            {
                                可以读游戏状态 = false;
                                挡住原因 = $"③ 队伍第{序号}个对象 == null";
                                break;
                            }
                            if (!r.对象有效())
                            {
                                可以读游戏状态 = false;
                                挡住原因 = $"③ 队伍第{序号}个对象【对象有效()=false】（{Safe身份(r)}）";
                                break;
                            }
                        }
                    }
                }
                catch (Exception e)
                {
                    可以读游戏状态 = false;
                    挡住原因 = $"③ 读队伍时抛异常：{e.GetType().Name} {e.Message}";
                }
            }

            // ══════════════════════════════════════════════════════════════

            // ── 记住用户拖动后的位置（下一帧的钳制基于它）──
            try
            {
                var 实际 = ImGui.GetWindowPos();
                if (实际.X > 0f || 实际.Y > 0f) _目标位置 = 实际;
                var 实际尺寸 = ImGui.GetWindowSize();
                if (实际尺寸.X >= 320f && 实际尺寸.Y >= 240f) _目标尺寸 = 实际尺寸;

                // ★ **Begin 之后的实测值**（只记下来，不打日志 —— 打日志在上面）
                try
                {
                    _上次实测位置文 = string.Format("({0:F0},{1:F0})", 实际.X, 实际.Y);
                    _上次实测尺寸文 = string.Format("{0:F0}x{1:F0}", 实际尺寸.X, 实际尺寸.Y);
                }
                catch { }
            }
            catch (Exception e)
            {
                // [!] **读窗口几何失败也要留痕** —— 这正是上一版探针哑掉的可能原因之一
                try { _上次实测位置文 = "GetWindowPos/Size 抛异常：" + e.GetType().Name; } catch { }
            }

            // [!] 说明窗**可以拖** —— 用户实测遇到"AI 设置不见了"，
            //     实际是这个窗口压在了设置面板上。写一句省得再困惑。
            ImGui.TextDisabled("  这个窗可以拖标题栏移动；挡住设置面板时拖开即可");
            ImGui.Separator();

            try
            {
                if (!_窗口开)
                {
                    // 用户点了右上角关闭 -> 同步回设置（下次不再自动开）
                    // ══════════════════════════════════════════════════════════
                    //  [!] **不能在这里直接改设置**（跨程序集静态状态的第二处）
                    //
                    //      `HealSettings` 编进两个 DLL ⇒ `Instance` 是两份。
                    //      设置页的勾选框读的是 **HealerACR 那份**，
                    //      而这里写 `HealSettings.Instance.启用调试窗 = false`
                    //      改的是 **BlueWhale 那份** ⇒
                    //      存档改了，但设置页下一帧又读回 true
                    //      ⇒ 现象是「**点 X 关不掉**，窗口闪一下又回来」（用户实测）。
                    //
                    //  [!] 正解：这里只**置一个请求标志**，
                    //      由 HealerACR 侧（持有设置的那一侧）代为落盘。
                    //      见 `HealerEntryBase.画AI层调试窗()`。
                    // ══════════════════════════════════════════════════════════
                    _请求关闭 = true;
                }

                // ══════════════════════════════════════════════════════════════
                //  ★ **换区/加载时读游戏状态 = 闪退**（Windows 事件 1026）★
                //
                //  [!] 崩溃堆栈就是从这里出去的：
                //        画预测() -> 伤害预测.状态描述() -> 可治疗队友() -> StatusList
                //      出本那一刻队伍对象已失效，而本方法是**每帧**跑的
                //      ==> 异常从 UI 回调逃逸 ==> **游戏进程被杀**。
                //
                //  [!] 这些都是**纯显示** —— 换区时不显示它毫无损失，
                //      但崩一次的代价是整个游戏。
                //
                //  [!] 窗口外壳照常画（标题/开关/位置都正常），
                //      只是内容区显示一行提示 —— 用户能看出现在是换区，不是坏了。
                // ══════════════════════════════════════════════════════════════
                if (可以读游戏状态)
                {
                    画基础();
                    画读条();
                    画预测();
                    画技能();
                    画AI();
                }
                else
                {
                    ImGui.TextDisabled("  （换区 / 加载中 —— 暂不读取游戏状态，避免崩溃）");
                }
            }
            finally
            {
                ImGui.End();
            }
        }
        catch { }
    }

