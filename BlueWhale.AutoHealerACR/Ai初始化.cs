using AEAssist;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// AI 初始化 —— 每次启用 ACR 时，让 AI 先把当前局面完整过一遍。
///
/// ══════════════════════════════════════════════════════════════════
///  为什么需要"初始化"而不是直接开始跑：
///
///    阶段 A（策略层）平时是每 10 秒刷一次，但**刚加载时没有任何结论** ——
///    那段时间里 当前倾向 = 未知，阈值偏移 = 0，AI 等于没起作用。
///
///    如果什么都不做，用户会遇到：
///      · 加载后前 10 秒 AI 是"哑"的
///      · 面板上显示"还没请求过"，看起来像没配好
///
///    初始化做的事：**加载后立刻跑一次完整请求**，
///    把副本 / 队伍 / 资源 / 敌人全部喂进去，拿到第一个倾向结论。
///
///  ── 用屏幕横幅告知结果 ──
///
///    设计取舍：不让人翻日志，直接在游戏里看到一行字。
///    所以：
///      · 成功 → "AI 已就绪：倾向 XXX"
///      · 失败 → "AI 初始化失败：<原因>"
///      · 熔断 → "AI 已熔断，期间走原版逻辑"
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class Ai初始化
{
    /// <summary>正在初始化</summary>
    public static bool 进行中 { get; private set; }

    /// <summary>有没有完成过一次</summary>
    public static bool 已完成 { get; private set; }

    /// <summary>上次初始化的结果描述</summary>
    public static string 结果 { get; private set; } = "（还没初始化）";

    private static long 开始时间;

    /// <summary>
    /// **重试循环正在跑吗**。
    ///
    /// ⚠️ `每帧更新()` 的超时检查要靠它让路 —— 详见那里的说明：
    ///    两个地方同时写 `已完成` / `结果` / `进行中` 会互相打架。
    /// </summary>
    private static bool _重试中;

    /// <summary>
    /// **世代号** —— 只有最新一代的请求可以写结果。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要它 ★
    ///
    ///  日志实证（一次成功被一次失败覆盖）：
    ///    ```
    ///    19:59:05.266  切换职业 -> 已重置 AI 层，重新初始化
    ///    19:59:05.266  开始初始化
    ///    19:59:07.546  初始化完成          <- 第一次成功（只用了 2.3 秒）
    ///    19:59:20.270  初始化未拿到回复：请求失败（走原版逻辑）
    ///    19:59:20.270  初始化失败：超时      <- 把"就绪"覆盖成"失败"
    ///    ```
    ///  中间**没有任何新的「开始初始化」** —— 说明是**两个请求在并发**。
    ///
    ///  ── 根因 ──
    ///    `重置()` 把 `进行中` 置回 false，**但已经发出的异步请求还在飞**。
    ///    于是下一次 `开始()` 能过 `if (进行中) return;` 这一关，又发一个请求。
    ///    两个请求各自 `await` 完，**都往共享的 `结果` 写** ——
    ///    谁后回来谁赢。慢的那个是超时失败，就把快的那个成功覆盖了。
    ///
    ///  ── 为什么标志位治不了 ──
    ///    `进行中` 只能回答"**现在有没有人正在跑**"，
    ///    回答不了"**这个跑完的人是不是最新的那一个**"。
    ///    重置一个 bool 也**影响不到已经离开的异步任务** ——
    ///    它醒来时照样会写 `结果`。
    ///
    ///  ⇒ 正确的做法是**世代号**：
    ///    · 每次 `重置()` / `开始()` 让世代 +1
    ///    · 每个请求在**发出前**记下自己的世代
    ///    · 回来时**世代对不上就整个丢弃**，一个字都不写
    ///    这样"过期的请求"就不可能污染最新结果。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static int _世代;

    /// <summary>
    /// 初始化单次请求的超时（毫秒）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么是 25 秒（原来是 15000）★
    ///
    ///  ── 日志实证 ──
    ///    连续三次尝试的耗时：
    ///        第 1 次：22:21:40 → 22:21:54   14.0 秒  超时
    ///        第 2 次：22:21:57 → 22:22:12   15.0 秒  超时
    ///        第 3 次：22:22:16 → 22:22:30   14.0 秒  **成功**
    ///
    ///    三次都在 14 秒上下 —— 而 15000 的线正好卡在那里，
    ///    于是**前两次必然超时**、只有第三次侥幸压线返回。
    ///    现象就是"请求失败 / 重试 / 重试 / 才成功"。
    ///
    ///  ── 为什么不是"模型太慢"，是我们的线画错了 ──
    ///    `deepseek-flash` 是**推理型模型**，回答前要先思考；
    ///    初始化的输出又是一大段策略分析（## 局势判断 + 结论），
    ///    十几秒是**它的正常速度**，不是异常。
    ///
    ///  ── 为什么加到 25 秒是划算的 ──
    ///    初始化**一局只跑一次**（进本时），多等 10 秒完全无感；
    ///    而省掉的是两次 4-8 秒的退避重试 + 两次超时日志 + 一次失败提示。
    ///    **净效果是更快到达"就绪"**，不是更慢。
    ///
    ///  ⚠️ 为什么不同时把重试去掉：
    ///     25 秒仍然可能不够（网络抖动 / 服务端排队），
    ///     重试是兜底，不能因为"线画宽了"就拆掉。
    ///
    ///  ⚠️ 决策层（`AiDecisionLayer`）不走这个值 —— 它是**预取备货**，
    ///     有自己的 8 秒超时，不能跟着一起放宽（会拖慢战斗反应）。
    ///     这个常量**只在初始化里用**。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private const int 超时 = 40000;

    /// <summary>
    /// 启动初始化（入口 Build 时调）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★★ 幂等：**已经初始化过就不再重来**（除非显式 `重置()`）★★
    ///
    ///  ── 反复踩的坑（日志实证）──
    ///    ```
    ///    重新加载dll成功，如果当前有打开的时间轴编辑器，请保存后重新打开
    ///    切换职业 -> 已重置 AI 层，重新初始化      <- 重置() + 开始()  => 3 代
    ///    开始初始化 —— 让 AI 先把当前局面过一遍
    ///    原始回复：## 策略倾向：保守稳健·单目标输出优先
    ///    初始化第 1 代已过期（当前 3 代），丢弃本次结果   <- 1 代还在飞
    ///    请求失败（超时），第 1 次，走降级
    ///    初始化未拿到回复：请求失败（走原版逻辑）
    ///    初始化失败：超时                        <- 把成功覆盖成失败
    ///    ```
    ///
    ///  ── 怎么会同时有 1 代和 3 代 ──
    ///    `Ai层挂载.挂载()` 里有一句**无条件的** `Ai初始化.开始()`（"启动初始化"）。
    ///    而切职业那条路（`记忆钩子.进入循环`）也会 `重置()` + `开始()`。
    ///    两个入口都跑 → 两次初始化**并发**。
    ///
    ///    更糟的是 `开始()` 每次都 `已完成 = false` ——
    ///    于是后发的那次（慢、超时）回来时**把先发那次（快、成功）的结果覆盖掉**。
    ///
    ///  ── 修法 ──
    ///    让 `开始()` **幂等**：
    ///      · 正在跑 → 不重来（原有行为）
    ///      · **已经成功过 → 也不重来**（新增）
    ///    要重来必须先 `重置()`（切职业 / 换本 / 手动解除熔断都走那条路）。
    ///
    ///  ⚠️ 为什么这条能治本而不是"少一次调用"：
    ///    就算以后又有人加了一个会调 `开始()` 的入口，
    ///    也只会被挡掉 —— **不再可能出现两次并发初始化**。
    ///    加守卫比在调用点一个个补条件可靠（本项目已经在"漏一处"上栽过多次）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>重复调用提示的节流间隔（毫秒）—— 见 `开始()` 里的说明</summary>
    private const int 重复提示间隔毫秒 = 10000;

    private static long _上次重复提示;
    private static long _上次完成提示;

    public static void 开始()
    {
        try
        {
            var s = AiSettings.Instance;

            // 没配 Key → 不初始化，也不打扰用户
            if (!s.已配置)
            {
                结果 = "未配置 API Key（走原版逻辑）";
                return;
            }

            // 两个阶段都没开 → 同样不打扰
            if (!s.启用策略层 && !s.启用决策层)
            {
                结果 = "AI 未启用（走原版逻辑）";
                return;
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 幂等守卫（见上面的说明）★
            //
            //  [!] 两条守卫都加了**同一条日志的节流**（实测刷屏）：
            //      调用方可能是**每帧**的路径（如 `进本识别.每帧检查()` 的回调链），
            //      而初始化本身要跑好几秒 ⇒ 那几秒里会连打几百条同样的日志。
            //      用户截图里就是这个现象（同一秒内连续多条）。
            //
            //  [!] 节流放在这里而不是改 `Ai调试`：
            //      别的日志需要实时，只有"重复调用"这种噪音该压。
            // ══════════════════════════════════════════════════════════
            if (进行中)
            {
                if (TimeHelper.Now() - _上次重复提示 > 重复提示间隔毫秒)
                {
                    _上次重复提示 = TimeHelper.Now();
                    Ai调试.日志("已经在初始化中，忽略重复的 开始()（后续 10 秒内不再提示）");
                }
                return;
            }

            if (已完成 && 结果 == "就绪")
            {
                if (TimeHelper.Now() - _上次完成提示 > 重复提示间隔毫秒)
                {
                    _上次完成提示 = TimeHelper.Now();
                    Ai调试.日志("已经初始化成功过，不重复初始化（要重来请先 重置()）");
                }
                return;
            }

            进行中 = true;
            已完成 = false;
            开始时间 = TimeHelper.Now();
            结果 = "初始化中…";

            // ★ 新一代：让还没回来的旧请求从此失效 ★
            var 我的世代 = ++_世代;

            _ = 跑一次(我的世代);
        }
        catch (Exception e)
        {
            进行中 = false;
            结果 = "初始化异常：" + e.Message;
            Ai调试.错误("初始化异常：" + e.Message);
        }
    }

    private static async Task 跑一次(int 我的世代)
    {
        _重试中 = true;
        try
        {
            // ══════════════════════════════════════════════════════════
            //  ★ 自动重新初始化 ★
            //
            //  ── 为什么需要它（日志实证）──
            //    失败链（日志实证）：
            //        开始初始化            (t=0，世代 1)
            //        切换职业 -> 重新初始化  (t=1.8，世代 3 —— 重置+开始各 +1)
            //        第 1 代已过期（当前 3 代），丢弃
            //        请求失败（超时）        (t=7.3)
            //        初始化失败：超时
            //    之后**就没有下文了** —— AI 层整场都是哑的，直到下次切职业/重载。
            //
            //  ── 为什么要重试，而不是"让旧请求自己成功" ──
            //    切职业会让**所有在飞的请求作废**（世代不匹配），
            //    而新请求只有一次机会。一次超时就永久哑掉，代价太大。
            //
            //  ── 重试上限交给谁 ──
            //    **不自己设上限**，交给 `DeepSeekClient` 的熔断器：
            //      · 超时类失败的上限 = `连续失败上限 * 4`（默认 12）
            //      · 非超时类（Key 错 / 网络不通）上限 = `连续失败上限`（默认 3）
            //    这样"临时超时要能自愈"和"Key 错了别死循环"两个要求同时满足，
            //    而且只有**一处**上限配置（设置界面那个），不会两处打架。
            //
            //  ⚠️ 每次尝试前都要**重查世代** —— 用户可能在重试途中又切职业，
            //     那时该停手让新一代跑，而不是继续用旧局面重试。
            //
            //  ⚠️ 每次尝试前要**重置 `开始时间`** —— `每帧更新()` 的超时检查
            //     是按它算的。不重置的话，第二次尝试一开始就会被判超时。
            // ══════════════════════════════════════════════════════════
            // ⚠️ **固定 3 秒，不做指数退避** ——
            //
            //    原来是 2→4→8→15→15 秒，配合 25 秒超时，
            //    一轮 8 次尝试要 **2 分钟以上**，而人就在本里等着开怪。
            //
            //    指数退避是给"服务端过载、别雪上加霜"准备的；
            //    这里的情况是**单次请求太慢**，不是被限流 ——
            //    退避久一点并不能让下一次更快，只是白等。
            const int 首次退避毫秒 = 3000;
            const int 最大退避毫秒 = 3000;   // 和上面相同 = 退避不增长

            var 第几次 = 0;
            var 退避 = 首次退避毫秒;
            string? 回复 = null;

            while (true)
            {
                第几次++;

                if (我的世代 != _世代)
                {
                    Ai调试.调试($"初始化第 {我的世代} 代已过期（当前 {_世代} 代），停止重试");
                    return;
                }

                if (第几次 > 1)
                {
                    Ai调试.日志($"初始化自动重试：第 {第几次} 次尝试（{退避 / 1000} 秒退避后）");
                    屏幕提示.提示("小鲸鱼", $"初始化重试中…（第 {第几次} 次）", "ai-init-retry");
                }

                开始时间 = TimeHelper.Now();   // ⚠️ 每次尝试独立计时（见上）
                进行中 = true;

                回复 = await 单次尝试().ConfigureAwait(false);

                if (回复 != null) break;

                // ── 失败 ──
                if (我的世代 != _世代) return;          // 重试途中被换掉 → 让位
                if (DeepSeekClient.该走原版逻辑) break;   // 熔断器叫停 → 不再重试

                await Task.Delay(退避).ConfigureAwait(false);
                退避 = Math.Min(退避 * 2, 最大退避毫秒);

                // ⚠️ 退避期间世代可能又变了 —— 下一轮开头会再查一次
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 世代校验：过期就整个丢弃，一个字都不写 ★
            //
            //  ⚠️ 这一句必须放在**所有写操作之前**（下面的 已完成 / 结果 /
            //     屏幕提示 全是写操作）。少写一处，那个字段就还会被污染 ——
            //     现象正是"`结果` 被慢请求覆盖"。
            //
            //  ⚠️ 也**不要**在这里补 `进行中 = false`：
            //     那是"最新那次"的责任，过期的那次不该动这个标志 ——
            //     它一动，就会把正在跑的新请求放行出第二个并发请求。
            // ══════════════════════════════════════════════════════════
            if (我的世代 != _世代)
            {
                Ai调试.调试($"初始化第 {我的世代} 代已过期（当前 {_世代} 代），丢弃本次结果");
                return;
            }

            // ══════════════════════════════════════════════════════════
            //  ⚠️ **`已完成` 只在成功时置 true** —— 不要写在分支外面。
            //
            //  ── 原来的错 ──
            //      这一句原来放在 `if (回复 != null)` **之前**，
            //      于是"重试 N 次仍然拿不到回复"也把 `已完成` 标成 true：
            //          已完成 = true
            //          结果   = "请求失败（走原版逻辑）"
            //
            //      而下游闸门读的是 `已完成`（`局面监控` 用它判"AI 还好的吗"）
            //      ⇒ 表现成"初始化没成功，但 AI 又像在参与"。
            //
            //  ── 正确语义 ──
            //      `已完成` == "成功拿到过回复"。
            //      失败/超时/熔断/异常一律 false → 全程走本地策略。
            // ══════════════════════════════════════════════════════════
            if (回复 != null)
            {
                已完成 = true;

                结果 = "就绪";
                Ai调试.日志(第几次 > 1
                    ? $"初始化完成（第 {第几次} 次尝试成功）"
                    : "初始化完成");

                // ══════════════════════════════════════════════════════
                //  ★ 初始化成功 = 链路通了 ≠ 策略已生效 ★
                //
                //  [!] 这里立刻触发一次真正的策略刷新（第三方审阅指出的缺口）：
                //      初始化的回复只用来判断"通不通"，**没有变成策略**。
                //      不触发的话，面板显示「AI 就绪」而
                //      `策略层：上次结果 =（还没请求过）` ——
                //      治疗阈值实际还是本地默认值，用户以为 AI 已经在调。
                //
                //  [!] 用策略层自己那套 prompt/解析（不是解析初始化的散文）——
                //      避免同一个概念出现两套格式实现。
                // ══════════════════════════════════════════════════════
                try { AiStrategyLayer.立刻刷新(); } catch { }

                // ══════════════════════════════════════════════════════
                //  ★ 把"识别结果"打在对话框里 ★
                //
                //    "进本后 ai 初始化成功要输出识别到什么副本什么职业什么等级"
                //
                //  ── 为什么这个比"初始化成功"有用 ──
                //    "初始化成功"只说明**请求通了**；
                //    用户真正要确认的是**它认对了没有** ——
                //    进的是不是这个本、认的是不是这个职业、等级对不对。
                //    这三个错了，后面 AI 说得再对也是错的。
                //
                //  ⚠️ 重试成功时把次数带上 —— 用户能从"第几次"看出网络状况。
                //
                //  ⚠️ **只调用一次 Print**，不要把识别结果和完成状态拆成两次 ——
                //     两条横幅会先后弹出、互相顶掉，用户只来得及看清一条。
                //     串成一条，信息全在，也不会被顶。
                // ══════════════════════════════════════════════════════
                var 识别 = AiSituation.识别摘要();
                Ai调试.日志("识别：" + 识别);

                // ★ 核对：AI 到底收到了什么 ★
                //
                //   ⚠️ 这一条比上面那条重要 ——
                //      "识别" 只说了本地看到了什么，
                //      "上下文核对" 才说明**发给 AI 的报告里真的有那些内容**。
                //      两者不一致就是 bug（比如副本名知道但没写进报告）。
                //
                //   ⚠️ 重点看「时间轴段」和「可选技能段」：
                //      这两个为空时 AI 仍然会回话，只是回的话没用。
                Ai调试.日志("上下文核对：" + AiSituation.上下文核对());

                // ★ 彩蛋：低概率排一段"歌词"，之后每句间隔 1~2 秒发 ★
                //
                //  ⚠️ `试试()` 只**排队**，不在这里发 ——
                //     真正的发送由本地层的每帧驱动（见 彩蛋.每帧更新）。
                //     这样就算初始化这条横幅还没显示完，歌词也不会挤在一起。
                HealerACR.Common.彩蛋.试试();

                // ★ 初始化成功 → 清零累计失败计数 ★
                //   （超时也计数，不清的话那些超时会把熔断器推上去）
                DeepSeekClient.清零失败计数();

                屏幕提示.成功(第几次 > 1
                    ? $"{识别}，AI 就绪（第 {第几次} 次尝试）"
                    : $"{识别}，AI 就绪", "ai-init-done");
            }
            else
            {
                结果 = DeepSeekClient.该走原版逻辑 ? "熔断中（走原版逻辑）" : "请求失败（走原版逻辑）";
                Ai调试.日志($"初始化未拿到回复（共尝试 {第几次} 次）：" + 结果);

                // ★ 失败时必须给出**具体原因** ★
                //   只说"失败了"用户没法排查 —— 得让他知道
                //   是 Key 错、网络不通、超时、还是模型名不对。
                var 原因 = string.IsNullOrWhiteSpace(DeepSeekClient.上次失败原因)
                    ? "未知（详见日志 [BlueWhale.AI]）"
                    : DeepSeekClient.上次失败原因;

                屏幕提示.警告($"初始化失败（已重试 {第几次} 次）：{原因}｜继续走本地策略",
                              "ai-init-fail");
            }
        }
        catch (Exception e)
        {
            // ⚠️ 异常路径同样要过世代校验 —— 否则一个过期请求的异常
            //    会把最新一次的结果覆盖成"初始化异常"。
            if (我的世代 != _世代) return;

            // ⚠️ `已完成` 保持 false —— 异常 == 没成功（见上面 L337 那段说明）
            已完成 = false;
            结果 = "初始化异常：" + e.Message;
            Ai调试.错误("初始化异常：" + e.Message);

            屏幕提示.警告($"初始化失败：{e.Message}", "ai-init-ex");
        }
        finally
        {
            // ⚠️ 只有**最新一代**才能清 `进行中`。
            //    过期的那次如果也清了，就会把仍在跑的新请求"放行"出第三个并发。
            if (我的世代 == _世代) 进行中 = false;

            // ⚠️ `_重试中` **只能由最新一代清** ——
            //    过期的那次清了，会让"新一代的重试循环"被 `每帧更新()`
            //    误判成"没人重试"，从而把状态改成超时。
            if (我的世代 == _世代) _重试中 = false;
        }
    }

    /// <summary>
    /// **单次尝试** —— 采一次局面、问一次 AI。成功返回正文，失败返回 null。
    ///
    /// ⚠️ 这个方法**不做世代校验、不写任何状态** ——
    ///    校验与收尾全交给 `跑一次()` 的重试循环，
    ///    否则会出现"重试过程中每一轮都判一次过期"的混乱。
    /// </summary>
    private static async Task<string?> 单次尝试()
    {
        // 直接走策略层的刷新逻辑 —— 它采集的情境最完整
        // （副本 / 时间轴 / 自己 / 资源 / 队友 / 敌人 / 可选技能）
        var 局面 = AiSituation.采集();

        return await DeepSeekClient.提问(
            "这是一次初始化。请根据下面的局面给出你对该场战斗的策略倾向。",
            局面,
            超时,
            // ★ 独立通道 —— 初始化失败不该被决策层的高频失败牵连
            道: DeepSeekClient.通道.初始化,
            // ══════════════════════════════════════════════════════
            //  ★ 必须显式给足额度 ★
            //
            //  日志实证（初始化连续失败两次）：
            //    「正文为空（推理型模型把额度用在思考上、没来得及输出正文）」
            //    「初始化未拿到回复：请求失败（走原版逻辑）」
            //
            //  ── 根因 ──
            //    这里原来只传了 `超时`，**`最大Token` 走默认的 2000**。
            //    而初始化的输出是一大段策略分析（`## 局势判断` + 结论），
            //    推理型模型**思考也占 max_tokens** ——
            //    2000 被思考吃光，正文一个字都没来得及写。
            //
            //    日志里 AI 的思考内容其实是**对的**
            //    （"队伍只有两名治疗没有坦克，我既是奶也是半个承伤位"），
            //    **纯粹是被额度截断**，不是它答不出来。
            //
            //  ⚠️ 同批还有一个一样的错：`AiStrategyLayer` 那里写着
            //     "给足 10 秒"、传的却是 `超时` —— 额度同样是默认 2000。
            //     策略层和初始化**都是大段正文**，都必须显式给额度。
            // ══════════════════════════════════════════════════════
            最大Token: 6000).ConfigureAwait(false);
    }

    /// <summary>每帧检查超时</summary>
    public static void 每帧更新()
    {
        try
        {
            if (!进行中) return;
            if (TimeHelper.Now() - 开始时间 < 超时) return;

            // ══════════════════════════════════════════════════════════
            //  ★ 已经成功过就不标超时 ★
            //
            //  ── 现象（日志实证）──
            //    ```
            //    初始化完成                    <- 这次成功了
            //    初始化第 1 代已过期（当前 3 代），丢弃本次结果
            //    请求失败（超时），第 1 次，走降级
            //    初始化未拿到回复：请求失败（走原版逻辑）
            //    初始化失败：超时              <- 把"完成"覆盖成"失败"
            //    ```
            //    现象是显示"初始化失败"，而**其实已经成功了**。
            //
            //  ── 为什么会这样 ──
            //    这条超时检查是按 `开始时间` 算的，而那是**最新一次**的开始时间；
            //    如果同时有更早的一次请求还在飞（或刚成功），
            //    它的超时会**落在已经成功的结果之上**。
            //
            //  ⚠️ 根因（两次并发初始化）已经在 `开始()` 的幂等守卫里治掉了；
            //     这里再加一道，保证**就算还有路径能并发，也不会把成功改成失败**。
            //
            //  ⚠️ 注意 `完成` 那个横幅由 `跑一次()` 弹，这里只改状态，不弹任何东西。
            // ══════════════════════════════════════════════════════════
            if (结果 == "就绪")
            {
                进行中 = false;   // 只是别卡住后续流程，但**不动结果**
                return;
            }

            // ⚠️ **重试循环正在跑时，这里什么都不做**（本次新增）——
            //
            //    重试循环自己会检查世代、自己会收尾、自己会写 `结果`。
            //    如果这里同时把 `已完成` 设成 true、`结果` 写成"初始化超时"，
            //    会出现两个问题：
            //      ① 重试成功后写 `结果 = "就绪"` 时状态已被标成"超时完成"，
            //         面板上看起来"超时了但其实成功了"（正是用户反复报的那类）
            //      ② 重试循环里的 `进行中` 会被这里清掉，
            //         下一轮 `进行中 = true` 又设回来 —— 状态来回跳
            //
            //    所以：**有重试在跑就交给它**，这里只处理"没人重试"的情况
            //    （比如重试循环因为世代变化提前 return 了，那时会清掉 `_重试中`）。
            if (_重试中)
            {
                return;
            }

            // ⚠️ 超时了但请求还在飞 —— 这里**只把状态标成超时并放行下一轮**，
            //    不加世代号：世代号一加，那个还在飞的请求回来时就被丢弃，
            //    它本来可能马上成功（实测有 2.3 秒就返回的情况）。
            //
            //    这里也不弹"失败"横幅 —— 让 `跑一次()` 自己收尾，
            //    它能区分"真超时"和"其实成功了只是慢"。
            进行中 = false;

            // ══════════════════════════════════════════════════════════
            //  ⚠️ **`已完成` 必须保持 false** —— 超时等于"没成功"。
            //
            //  ── 原来的错（实测暴露的设计缺口）──
            //      这里原来写的是 `已完成 = true`，于是 `已完成` 和 `结果`
            //      **语义打架**：
            //          已完成 = true
            //          结果   = "初始化超时（走原版逻辑）"
            //
            //      而下游两个闸门读的都是 `已完成`：
            //        · `局面监控` → `AI还没好 = !Ai初始化.已完成`
            //          ⇒ 以为 AI 好了 → 进战/换目标/血量骤降照常作废预取队列
            //        · 面板/日志的判断也把它当"就绪"
            //
            //      ⇒ 表现就是**"初始化没成功，但 AI 又像在参与"** ——
            //        用户报的正是这个。
            //
            //  ── 正确语义 ──
            //      `已完成` 只表示**成功拿到过回复**。
            //      超时/熔断/失败一律保持 false →
            //      全程走本地策略，直到某次真的成功。
            //
            //  ⚠️ 不影响重试：重试循环看的是世代和 `回复 != null`，
            //     不看 `已完成`。而且它成功时会在 L337 把它设成 true。
            // ══════════════════════════════════════════════════════════
            已完成 = false;
            结果 = "初始化超时（走原版逻辑）";
            Ai调试.日志("初始化超时 —— AI 未就绪，继续走本地策略");
        }
        catch { }
    }

    /// <summary>熔断状态变化时提示（由心跳调用）</summary>
    private static bool _上次熔断;

    public static void 检查熔断提示()
    {
        try
        {
            var 现在熔断 = DeepSeekClient.该走原版逻辑;
            if (现在熔断 == _上次熔断) return;

            _上次熔断 = 现在熔断;

            if (现在熔断)
            {
                // 熔断也要说清原因 —— 和初始化失败一个道理
                var 原因 = string.IsNullOrWhiteSpace(DeepSeekClient.上次失败原因)
                    ? "未知"
                    : DeepSeekClient.上次失败原因;

                屏幕提示.警告($"已熔断：{原因}", "ai-fuse-on");
            }
            else
            {
                屏幕提示.成功("熔断已解除", "ai-fuse-off");
            }
        }
        catch { }
    }

    /// <summary>重置（换本 / 手动重载）</summary>
    public static void 重置()
    {
        进行中 = false;
        已完成 = false;
        结果 = "（还没初始化）";
        _上次熔断 = false;

        // ⚠️ 也要清 `_重试中` ——
        //    旧的重试循环看到世代变了会自己 return（它的 finally 里那句
        //    `if (我的世代 == _世代)` 不成立，所以不会清这个标志）。
        //    不在这里清的话，新一代的重试会被 `每帧更新()` 一直跳过。
        _重试中 = false;

        屏幕提示.重置();

        // ★ 让"还在飞的旧请求"作废 ★
        //
        //  ⚠️ 只把 `进行中` 置回 false **不够** —— 那个标志管不了
        //     已经离开的异步任务：它醒来时照样会往 `结果` 写。
        //     "成功被超时覆盖"就是这么来的。
        //     世代 +1 之后，旧请求回来时会发现自己过期，直接丢弃。
        //
        //  ⚠️ 但**只在真有请求在飞时才 ++**（实测踩的坑）：
        //
        //     原来无条件 `++`，而 `开始()` 也会 `++` ——
        //     于是"重置() + 开始()"一次就把世代推进 **2**。
        //     触发三次 → 世代 11 涨到 17，而第一次的结果回来时
        //     带的是"第 15 代" → 被判过期 → **丢弃** → 白等一轮，
        //     那 6 秒里 AI 完全是哑的。
        //
        //     没有请求在飞的时候，`++` 没有任何东西可以作废，
        //     只会白白让后续 `开始()` 的世代跳号。
        if (进行中) _世代++;
    }
