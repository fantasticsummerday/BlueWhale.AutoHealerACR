    private static void 存快照(快照 s)
    {
        _快照表[s.快照Id] = s;
        _快照序.Enqueue(s.快照Id);
        while (_快照序.Count > 快照保留)
        {
            var 旧 = _快照序.Dequeue();
            if (旧 != s.快照Id) _快照表.Remove(旧);
        }
    }

    private static void 加治疗候选()
    {
        var 技能表 = 职业表();
        if (技能表 == null) { _诊断治疗 = "拿不到职业技能表"; return; }

        var 队 = HealTargetHelper.可治疗队友(30f);
        if (队.Count == 0) { _诊断治疗 = "没有可治疗队友（" + HealTargetHelper.最近空原因 + "）"; return; }

        var 进前 = _当前表.Count;

            // [!] 这三个值整轮循环不变 —— 放在循环外算一次（见下面的说明）
            var 受限 = false;
            try { 受限 = SpellUtil.在移动() || 空中检测.在空中; } catch { }

            var 有即刻Buff = false;
            // ★ 读 buff 之前先判有效性 —— HasAura 走 StatusList，
                //   换图时 `Core.Me` 可能已释放（哨兵 0x12345679），
                //   而原生访问违例会穿透下面的 catch。
                try
                {
                    if (Core.Me != null && Core.Me.对象有效())
                        有即刻Buff = Core.Me.HasAura(AuraIds.即刻);
                }
                catch { }

            var 即刻能放 = 即刻可用();


        foreach (var 技 in 技能表.治疗候选.已解锁())
        {
            if (技.Id == 0) continue;
            try
            {
                if (!SpellUtil.已解锁(技.Id)) continue;
                // [!] 放宽为「即将可用」—— 候选是备货（给 2~3 个 GCD 后），
                //     用「此刻能不能放」筛会把「马上就好」的技能全砍掉。
                //
                // ★ 视野用 `建议视野秒()`（= 3 个 GCD，约 7.5 秒），**不是默认的 2.5 秒** ★
                //   [!] 默认 2.5 秒是给**本地 resolver** 的（它只关心"这一帧能不能放"），
                //       而**候选集是给 AI 备货的** —— AI 建议的是**未来 3 个 GCD**。
                //   [!] 用 2.5 秒的后果：CD 还剩 5 秒的技能进不了候选,
                //       但它 5 秒后就好了、而 AI 的第 2~3 个建议正是那个时候
                //       ==> **AI 无法建议它**。表现是"AI 建议总是那几个廉价技能，
                //           大招/长 CD 技从不出现" —— **不是模型不行，是它看不到**。
                if (!SpellUtil.即将可用(技.Id, SpellUtil.建议视野秒())) continue;
            }
            catch { continue; }
                // ══════════════════════════════════════════════════════════
                //  [!] 移动 / 空中时，读条治疗能不能放（用户实测："全程移动 ai 不奶了"）
                //
                //      核实过的事实（别再搞错）：
                //        · `SpellUtil.移动中能放()` **有**即刻豁免，
                //          但那个豁免要求**已经开着即刻 buff**
                //        · 移动中"**要不要开即刻**"没有任何地方判断
                //
                //      ⇒ 这里：
                //         · 已经有即刻 buff    -> 读条治疗照收（真能放）
                //         · 没 buff 但即刻可用 -> 也收，同时下面会把即刻列成候选
                //           （AI 选了即刻，下一步那个读条治疗就能放出来）
                //         · 没 buff 且即刻在 CD -> **不收**（收了也是白决策一次）
                //
                //  [!] 为什么放在 try 之外预先算：三个值在整轮循环里不变，
                //      放进循环里每轮都查 buff 是浪费。
                // ══════════════════════════════════════════════════════════
                if (受限 && !技.瞬发 && 技.咏唱 > 0f)
                {
                    if (!有即刻Buff && !即刻能放) continue;
                }


            if (技.群体)
            {
                IBattleChara? 最缺 = null;
                var 最缺量 = 0f;
                var 有人 = 0;
                foreach (var r in 队)
                {
                    var g = 治疗决策.缺口量(r);
                    if (g <= 0.01f) continue;
                    有人++;
                    if (g > 最缺量) { 最缺量 = g; 最缺 = r; }
                }
                if (有人 == 0 || 最缺 == null) continue;

                // ★ 群疗：**一次性构造完**，不再构造后改（候选不可变，见类头说明）★
                //
                //  [!] 群疗的**施法目标是自己**、最缺的人是「关注目标」：
                //      项目里群疗的正确写法是（`Res_Heal.cs`）
                //          slot.Add(new Spell(_t.群体治疗GCD, SpellTargetType.Self));
                //      群疗是**以自己为中心**的范围技 —— 目标是你自己。
                //      而「最缺血的队友」只是**为什么现在该群疗**的理由。
                //
                //  [!] 原来把那个队友当成施法目标 ⇒ 群疗以他为中心放，
                //      别人不在范围内就治不到（本轮审阅抓到的真 bug）。
                var 候选 = 造(技, 最缺, 最缺量,
                               关注目标Id: 最缺.GameObjectId,
                               关注目标名: 名(最缺),
                               关注原因: $"队里 {有人} 人缺血，他最缺（{最缺量 * 100f:F0}%）",
                               群体: true);
                if (候选 != null)
                {
                    // 施法目标改成「自己」，并把命中的成员数折成本地分
                    _当前表.Add(候选 with
                    {
                        施法目标模式 = 目标模式.自己,
                        目标Id = 0,
                        目标名 = "",
                        本地分 = 候选.本地分 + Math.Min(1.0f, 有人 * 0.15f),
                    });
                }
            }
            else
            {
                foreach (var r in 队)
                {
                    var 缺口 = 治疗决策.缺口量(r);
                    
                    // ══════════════════════════════════════════════════════════════
                    //  ★ **「必须奶满」的目标必须无条件有候选**（H9，审计确认）★
                    //
                    //  [!] 原来这里是 `if (缺口 <= 0.01f) continue;` —— 满血/满有效血 的目标
                    //      **一个候选都没有**。而必须奶满**不看血量**
                    //      （提示词自己都写着「他可能看着 80% 健康」），
                    //      极端情况（有效血满、或盾让他“看起来”满）下那个目标会从候选里消失。
                    //
                    //  [!] 后果：提示词 7~10 条命令 AI 去治必须奶满那个人，
                    //      但**候选里没有带他 id 的项** ==> AI 只能用 ID 格式回答
                    //      ==> 落到“别人”身上（见 AiSuggestionResolver 的兜底目标）。
                    //
                    //  [!] 所以：中了必须奶满的机制就**无条件加候选**，缺口为 0 也加 ——
                    //      那一下本来就是要“过量也要灌满”的。
                    // ══════════════════════════════════════════════════════════════
                    var 是要紧的 = false;
                    try { 是要紧的 = 必须奶满.命中状态(r) != 0; } catch { }
                    
                    if (缺口 <= 0.01f && !是要紧的) continue;
                    var 候选 = 造(技, r, 缺口);
                    if (候选 != null) _当前表.Add(候选);
                }
            }
        }

        // ★ 移动中 + 有治疗需求 -> 把即刻咏唱列出来（见 加即刻候选 的说明）★
        加即刻候选(队);
    }

    /// <summary>本地真实分（吞掉异常，读不到返回负无穷 = 不渲染）。</summary>
    private static float 本地真实分(治疗技能 技, IBattleChara 目标)
    {
        try { return HealerACR.Common.治疗决策.对目标打分(技, 目标); }
        catch { return float.NegativeInfinity; }
    }
    
    private static 候选? 造(治疗技能 技, IBattleChara 目标, float 缺口,
                                ulong 关注目标Id = 0, string 关注目标名 = "",
                                string 关注原因 = "", bool 群体 = false)
    {
        try
        {
            var 目标Id = 目标.GameObjectId;
            foreach (var x in _当前表)
                if (x.技能Id == 技.Id && x.目标Id == 目标Id) return null;

            var 上限 = 最大血(目标);
            var 单次 = MathF.Max(1f, 技.总恢复力);
            
            // ══════════════════════════════════════════════════════════════
            //  ★ **入参 `缺口` 是「绝对 HP」，这里必须转成「比例」** ★
            //
            //  [!] 修的是一个**毁灭级**的单位错误（审计确认）：
            //      `治疗决策.缺口量()` 返回的是 `MaxHp * (1 - 有效血量比例)` ——
            //      **绝对值**（例如 3000）。
            //      而这里原来写的是：
            //          var 缺口绝对值 = 缺口 * 上限;      // ← 又乘了一次 MaxHp！
            //          ...
            //          缺口 = Math.Clamp(缺口, 0f, 1f)  // ← 3000 被夹成 1.0
            //      后果：
            //        ① 模型看到的每个治疗候选都是 `缺口100%`、`过量0%` ⇒ **无法比较**
            //        ② `缺口 >= 0.55f` **恒真** ⇒ **所有治疗都进紧急桶**（上限 3），
            //           紧急桶被 必须奶满(1000)/复活(900) 占满后只剩任意几个 800
            //           ⇒ **模型可能根本看不到它需要的那条治疗**
            //        ③ `过量` 恒 0、`覆盖` ≈ 0 ⇒ `本地分` ≈ 1e-6 ⇒ 桶内排序**实际任意**
            //
            //  [!] 换算只做一次，之后 `缺口(比例)` / `单次(威力)` 同量纲，
            //      `过量`/`覆盖`/`本地分` 全部按比例算 —— 和 `治疗决策.打分()` 的口径一致。
            // ══════════════════════════════════════════════════════════════
            var 缺口比例 = 上限 > 0f ? Math.Clamp(缺口 / 上限, 0f, 1f) : 0f;
            var 缺口绝对值 = 缺口;          // 已经是绝对值，**不要再乘上限**
            var 过量 = 单次 > 0f ? MathF.Max(0f, (单次 - 缺口绝对值) / 单次) : 0f;
            var 覆盖 = MathF.Min(1f, 单次 / MathF.Max(1f, 缺口绝对值));

            // ══════════════════════════════════════════════════════════
            //  ★ 治疗数值模型：即时 / 3s / 6s（第三轮审阅第 16 条）★
            //
            //  [!] 为什么不能只给"量"：
            //      瞬发治疗 3000 和 HoT 总量 6000 **不能直接比较** ——
            //      前者立刻回 3000，后者要十几秒才回完。
            //      救命看的是"这 3 秒能回多少"，不是"总共能回多少"。
            // ══════════════════════════════════════════════════════════
            var 即时 = (int)技.即时恢复力;
            var 每跳 = (int)技.HoT恢复力;
            const float 跳间隔 = 3f;      // FF14 的 HoT 默认 3 秒一跳
            const float 窗口 = 6f;
            var 预测3 = 即时;
            var 预测6 = 即时;
            if (每跳 > 0 && 技.HoT持续 > 0f)
            {
                var 总跳数 = 技.HoT持续 / 跳间隔;
                预测3 += (int)(每跳 * MathF.Min(总跳数, 3f / 跳间隔));
                预测6 += (int)(每跳 * MathF.Min(总跳数, 窗口 / 跳间隔));
            }

            // ── 类别判定：依据是**局面**，不是技能表 ──
            //   同一个技能在"队友濒死"时是救急，在"只掉一点血"时是常规治疗。
            var 类 = 类别.治疗;
            var 紧急 = 0;
            var 血比 = 血比例(目标);

            if (缺口比例 >= 0.55f || 血比 <= 0.25f) { 类 = 类别.紧急; 紧急 = 800; }
            // [!] 用 `命中状态(目标) != 0` 而不是 `是必须奶满状态(...)` ——
            //     后者要传状态 Id，而这里只想问"**这个人**中了必须奶满的机制吗"。
            //     `命中状态` 就是干这个的（返回 0 = 没中）。
            try
            {
                // ★ 必须奶满 = 最高级（1000）★
                //   [!] 它**不看血量**（那人可能看着 80% 健康），只能靠状态判。
                //      所以必须无条件压过其它紧急项 —— 否则会被挤掉。
                if (必须奶满.命中状态(目标) != 0) { 类 = 类别.紧急; 紧急 = 1000; }
            }
            catch { }

            // ── 施法目标模式 ──
            //   [!] 默认是"队友"（单奶/单盾/复活/驱散都是），
            //      群体技能由调用方改成"自己"，地面技能改成"地面"。
            var 模式 = 目标模式.队友;
            try
            {
                if (技能数据.是地面技能(技.Id)) 模式 = 目标模式.地面;
            }
            catch { }

            return new 候选
            {
                类 = 类,
                紧急等级 = 紧急,
                施法目标模式 = 模式,
                技能Id = 技.Id,
                技能名 = string.IsNullOrEmpty(技.名) ? ("技能" + 技.Id) : 技.名,
                目标Id = 目标Id,
                目标名 = 名(目标),
                群体 = 群体 || 技.群体,   // 技表判定 或 调用方指定
                能力技 = 技.不占GCD,
                瞬发 = 技.瞬发,
                量 = (int)技.总恢复力,
                是盾 = 技.是盾,
            即时治疗 = 即时,
                预测3秒 = 预测3,
                预测6秒 = 预测6,
                命中数 = 1,
                缺口 = 缺口比例,   // ★ 比例（不是绝对值）—— 描述() 会渲染成 缺口N%
                过量 = Math.Clamp(过量, 0f, 1f),
                耗蓝 = 技.MP,
                冷却 = 技.冷却,
                资源 = 技.资源消耗,
                本地分 = 覆盖 * 2f - 过量 * 1.5f + (技.不占GCD ? 0.3f : 0f),
                
                // [!] **本地真实分**（H2）—— 在 `选最优` 内部用**完全相同**的判据算一遍。
                //     这里同时有技能对象和目标对象，所以能算；描述() 那边没有 id 找角色的工具。
                本地真实分 = 本地真实分(技, 目标),
                // ★ 群疗 / 关注目标：**在构造时就定死**（不可变，见类头说明）★
                关注目标Id = 关注目标Id,
                关注目标名 = 关注目标名,
                关注原因 = 关注原因,
            };
        }
        catch { return null; }
    }

    /// <summary>
    /// **输出候选** —— 只加 4 类：基础输出 / 群体输出 / DoT / 站定填充技。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ **哪些输出动作【有意】不进 AI 的候选集**（横向审查问过这个，别再当缺口）★
    ///
    ///  [!] 一句话概括：**AI 只管"打哪个技能"，不管"怎么走位"、"交不交职业大**。
    ///
    ///  [!] 具体不在候选集里的（都不是漏了）：
    ///        · **移动填充技 / 近战填充技** —— 它们由 `选填充技` 按
    ///          "能不能读条 / 命中几个 / 谁省蓝"**本地实时决定**。
    ///          那是**走位层**的判断，AI 每次要等一轮往返（数秒），
    ///          等它回来时机已经过了 ==> 交给本地。
    ///        · **各职业专属输出能力技**（学者 连环计 / 埋伏之毒、白魔 神速咏唱 / 闪飒、
    ///          占星 占卜 / 光速 / 抽卡、贤者 发炎 / 心神风息 / 根素…）——
    ///          它们各有**自己的 resolver**（`SCH_ChainStratagem` 等），
    ///          在决策队列里按**行号 + 自己的资源/冷却闸门**触发。
    ///          AI 的价值在"取舍"，而这些技**没有取舍空间**
    ///          （该交就交、不该交就不交，判据已经写死在 resolver 里）。
    ///        · **`输出能力技` 槽位** —— 只有学者用它（`能量吸收`），
    ///          因为那是**资源倾泻**（豆子溢出了要花掉），带取舍。
    ///
    ///  [!] **AI 看得到相关【状态】**：`AiSituation` 会报
    ///      "神速咏唱还剩几秒"这类（L513-514 的注释写了为什么：
    ///      "还能打几个闪飒"必须能预测）。所以 AI 知道**局面**，
    ///      只是不负责**按下那个键**。
    ///
    ///  [!] 所以：**做"本地动作 vs AI 候选"一致性检查时，这批要排除**，
    ///      否则每次都会报出二十多条假缺口。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 加输出候选()
    {
        var 技能表 = 职业表();
        if (技能表 == null) { _诊断输出 = "拿不到职业技能表"; return; }

        var 目标 = 输出目标.选();
        if (目标 == null || !目标.活着()) { _诊断输出 = "没有可选敌人（" + 输出目标.最近空原因 + "）"; return; }

        var 进前 = _当前表.Count;

        var 等级 = (int)CharacterExt.我的等级();

        加输出(技能表.基础输出, 技能表.查威力(技能表.基础输出, 等级), 1, 目标, false);

        try
        {
            // [!] **必须用 `群攻命中数()` —— 它会按技能类型选对圆心** ★
            //
            //     50 级学者「破阵法」是**自身中心 5 米** AOE，而
            //     `HealTargetHelper.周围敌人数量()` 是**以当前目标为中心**数的
            //     （那个函数是为"目标中心 AOE"写的，它自己的注释写着"奶妈站远程位"）。
            //
            //     ==> **圆心错了会把够不着的怪数进来** ==> 命中数虚高
            //         ==> 喂给 AI 的 `力150x2=300` 是**假的** ==> AI 按总量选它。
            //
            //     [!] 这正是用户报的「50 级神兵又在打 aoe」：
            //         本地 `选填充技` 用的是**正确的** `自身周围敌人数量`（所以本地对），
            //         而 AI 这边数错了（所以 AI 错）—— 两边判据不一致。
            //
            //     `群攻命中数` 内部：自身中心 AOE -> `自身周围敌人数量`；
            //     其余 -> `周围敌人数量`（且施法距离用**技能真实射程**，不是写死的 25）。
            var 敌数 = 技能表.群攻命中数(技能表.群体输出, 目标);
            if (敌数 >= 技能表.AOE门槛(等级) && 技能表.群体输出 != 0)
            {
                var 单体 = 技能表.查威力(技能表.群体输出, 等级);
                加输出(技能表.群体输出, 单体 * 敌数, 敌数, 目标, true, 单体);
            }
        }
        catch { }

        try
        {
            if (技能表.Dot技能 != 0 && HealTargetHelper.值得上Dot(目标))
                加输出(技能表.Dot技能, 技能表.查威力(技能表.Dot技能, 等级), 1, 目标, false);
        }
        catch { }

        // ══════════════════════════════════════════════════════════════
        //  ★ 站定填充技 —— 站定时也列出来（用户实测）★
        //
        //  [!] 现象："远处应该打毁灭，而不是毁坏，少10威力"。
        //
        //  [!] 根因：50 级时 `基础输出` = **毁坏（140，瞬发）**，
        //      而 `毁灭`（150，读条）**从来不是候选** => AI 看不到它 =>
        //      只能一直建议唯一可见的填充技。
        //      **不是"不会比较"，是"没得比"。**
        //
        //  [!] 只在**没在移动/空中**时加 —— 移动中它放不出来，
        //      列进去只会让 AI 白选一个被本地挡掉的技能。
        //      移动时本来就有 `移动填充技`（毁坏）可用。
        // ══════════════════════════════════════════════════════════════
        try
        {
            var 站定 = 技能表.站定填充技;
            if (站定 != 0 && 站定 != 技能表.基础输出)
            {
                var 受限 = SpellUtil.在移动() || 空中检测.在空中;
                if (!受限)
                    加输出(站定, 技能表.查威力(站定, 等级), 1, 目标, false);
            }
        }
        catch { }
    }

    private static void 加输出(uint 技能Id, int 总威力, int 命中数,
                              IBattleChara 目标, bool 群体, int 单体威力 = 0)
    {
        if (技能Id == 0) return;
        try
        {
            if (!SpellUtil.已解锁(技能Id)) return;

            // [!] 放宽为「即将可用」—— 见 `SpellUtil.即将可用` 的说明
            if (!SpellUtil.即将可用(技能Id, SpellUtil.建议视野秒())) return;
        }
        catch { return; }

        foreach (var c in _当前表)
            if (c.技能Id == 技能Id) return;

        bool 瞬发;
        try { 瞬发 = SpellUtil.移动中可用(技能Id); } catch { 瞬发 = false; }

        _当前表.Add(new 候选
        {
            类 = 类别.输出,
            施法目标模式 = 目标模式.敌人,
            技能Id = 技能Id,
            技能名 = 取技能名(技能Id),
            目标Id = 目标.GameObjectId,
            目标名 = 名(目标),
            群体 = 群体,
            能力技 = false,
            瞬发 = 瞬发,
            量 = 总威力,
            命中数 = 命中数,
            单体威力 = 单体威力,
            // [!] **输出候选也要给 MP**（GAP-11，审计确认）——
            //     本地 `选填充技` 是**先比威力、同级再比蓝**，而 AI 看到的输出候选原来没有 MP，
            //     ==> 无法复现同级才比蓝（破阵法 500 vs 毁灭/毁坏 400 那条规则）。
            耗蓝 = 职业表()?.查MP(技能Id) ?? 0,
            本地分 = 总威力 / 100f,
        });
    }

