                        目标Id = 要驱.GameObjectId,
                        目标名 = 名(要驱),
                        // ★ 驱散也是 **GCD 技**（官表：复唱 0.3 秒 = GCD）★
                        //   [!] 同样从"能力技+瞬发"改回真实值 ——
                        //      AI 才会正确计算"这一下要占一个 GCD"。
                        能力技 = false,
                        瞬发 = false,
                        本地分 = 2.5f,
                    });
                }
            }
        }
        catch { }
    
    // ══════════════════════════════════════════════════════════════
    //  ★ 「盾」候选 —— 贤者这一面原来**完全没被覆盖** ★
    //
    //  [!] 用户指出的问题：「预后分均衡预后和预后 一个盾 一个纯奶 确定是分清了嗷」
    //
    //      贤者的盾和纯奶**共用同一个基础 id**（游戏机制）：
    //        `SageACR.cs:140`  治疗池：预后 = **纯治疗 300**，`是盾 = false`
    //        `SageACR.cs:239`  技能表：`群体盾 => 预后`，靠 `均衡` 变形态
    //      ==> 治疗池里那条是**纯奶**，而盾这一面**没有任何候选**
    //          ==> AI 想铺盾时**选不到**（只能靠本地）。
    //
    //  [!] **只在治疗池没覆盖时才加**：
    //      · SCH 鼓舞激励之策 / WHM 神祝祷 —— 在池里且已标 `是盾 = true` => 不加（避免重复）
    //      · SGE 诊断 / 预后 —— 在池里但标的是**纯奶** => **要加**（盾这一面缺）
    //      判据：槽位 id **不在治疗池里** 才补。
    //      （在池里的那条已经带正确数据 —— 恢复力/MP/咏唱，比这里手写的准）
    //
    //  [!] `是盾技能 = true` 是**必须的** —— 它让执行层知道要先放前置。
    //      而**绝不能按 id 判**（预后 也是纯奶）—— 意图只能由候选声明。
    // ══════════════════════════════════════════════════════════════
    try
    {
        // 治疗池里已有的 id（那些的盾面已经被正确地标过了）
        var 池里有的 = new HashSet<uint>();
        try
        {
            foreach (var h in 技能表.治疗候选.全部)
                if (h != null && h.Id != 0) 池里有的.Add(h.Id);
        }
        catch { }
    
        // 单体盾 / 群体盾（去掉 0 和重复）
        var 盾槽 = new List<(uint Id, bool 群体)>();
        if (技能表.单体盾 != 0) 盾槽.Add((技能表.单体盾, false));
        if (技能表.群体盾 != 0 && 技能表.群体盾 != 技能表.单体盾)
            盾槽.Add((技能表.群体盾, true));
    
        foreach (var (盾Id, 是群) in 盾槽)
        {
            try
            {
                // 池里已经有 -> 跳过（那条的数据更准，别重复）
                if (池里有的.Contains(盾Id)) continue;
                if (!SpellUtil.已解锁(盾Id)) continue;
                if (!SpellUtil.即将可用(盾Id, SpellUtil.建议视野秒())) continue;
                // ══════════════════════════════════════════════════════════
                //  ★ **盾还在场就别再铺** —— 判据必须和本地 `Res_HealShield` 同源 ★
                //
                //  [!] 这一行原来是 `if (SpellUtil.Get(盾Id) == null) continue;`
                //      —— **注释说"已经在场就别再铺"，代码做的却是"拿不到技能数据"**。
                //      `SpellUtil.Get(id)` 是 `id.GetSpell()`（技能**数据对象**），
                //      对已解锁的技能**恒不为 null** ==>
                //      **这条守卫从来没生效过**，"盾已在场"一次都没被过滤掉。
                //      （开发约定 ⑧：注释和代码说的不是一件事，比没有注释更危险。）
                //
                //  [!] 本地真正的判据（`Res_Heal.cs` L935，已经核实）：
                //          `坦克.有该技能的Buff(_t.单体盾)`
                //        && `坦克.我的Buff还剩超过N秒(AuraIds.技能转Buff(盾), 5f)`
                //      = **有那个 buff** 且 **剩余 > 5 秒** 才算"还在场"。
                //      （只判"有 buff"会在**剩 0.2 秒**时也跳过，反而漏掉该补的时机。）
                //
                //  [!] 目标怎么取：
                //        群体盾 / 自身盾 -> 判自己（盾以自己为中心）
                //        单体盾          -> 判坦克（本地就是铺给坦克的，`选目标()` 的坦克分支）
                //      取不到目标时**不跳过**（宁可多给一个候选，也不要漏掉该铺的盾）。
                //
                //  [!] 为什么这条重要：盾还在的时候把"铺盾"列给 AI，
                //      而本地 `Res_HealShield` 会拒绝 --> 这是用户报过的
                //      「AI 建议的东西本地不做」的一类成因（两边判据不同源，F③）。
                // ══════════════════════════════════════════════════════════
                try
                {
                    var 盾Buff = AuraIds.技能转Buff(盾Id);
                    if (盾Buff != 0)
                    {
                        var 判谁 = 是群 ? Core.Me : (HealTargetHelper.主坦() ?? (IBattleChara?)Core.Me);
                        if (判谁 != null
                            && 判谁.有该技能的Buff(盾Id)
                            && 判谁.我的Buff还剩超过N秒(盾Buff, 5f))
                            continue;
                    }
                }
                catch { }
                foreach (var c in _当前表)
                    if (c.技能Id == 盾Id) goto 下一条盾;
    
                _当前表.Add(new 候选
                {
                    类 = 类别.减伤,
                    // 盾是**预防**，比补救值钱：分给高一点但不抢救急
                    紧急等级 = 600,
                    施法目标模式 = 目标模式.自己,   // 群盾/自身；单盾由执行层按目标放
                    技能Id = 盾Id,
                    技能名 = string.IsNullOrEmpty(取技能名(盾Id))
                        ? (是群 ? "群体盾" : "单体盾") : 取技能名(盾Id),
                    能力技 = true,
                    瞬发 = true,
                    群体 = 是群,
                    是盾 = true,
                    // ★ 意图：这条是盾，执行层要先放前置（贤者 = 均衡）★
                    //   `护盾前置 == 0` 的职业不受影响。
                    是盾技能 = true,
                    // 盾的收益没法像减伤那样算成百分点（它是吸收量），
                    // 用固定的中高分让它进得了桶、但不压过救急
                    本地分 = 2.0f,
                });
                下一条盾: ;
            }
            catch { }
        }
    }
    catch { }
    }

