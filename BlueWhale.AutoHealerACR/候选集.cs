    private static string 取技能名(uint 技能Id)
    {
        try
        {
            var 表 = 职业表();
            if (表 != null)
                foreach (var 技 in 表.治疗候选.全部)
                    if (技.Id == 技能Id && !string.IsNullOrEmpty(技.名)) return 技.名;
        }
        catch { }
        return "技能" + 技能Id;
    }

    /// <summary>**即刻咏唱现在能放吗**（`7561`，能力技）</summary>
    private static bool 即刻可用()
    {
        try
        {
            var id = SpellIds.取("即刻咏唱");
            return id != 0 && SpellUtil.已解锁(id) && SpellUtil.可用(id);
        }
        catch { return false; }
    }

    /// <summary>
    /// **移动中 + 只有读条治疗可用 → 把即刻咏唱本身列成候选**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要它（用户实测："全程移动 ai 不奶了"）：
    ///      移动/空中时读条治疗放不出来，而 oGCD 治疗都有 CD 或用资源
    ///      （以太超流 / 小仙女）。资源一空，候选表就空了 => AI 无从选择。
    ///
    ///      "开即刻再补"是玩家的标准操作，也是移动中救命的最后手段 ——
    ///      但**没有任何地方判断"要不要开即刻"**。
    ///
    ///  [!] 它作为**独立候选**（`类别.功能`）而不是自动组合：
    ///      选了它 -> 即刻 buff 就有了 -> 那个读条治疗就能在移动中放出去。
    ///      这样 AI 仍然掌握"要不要花掉这个 60 秒 CD"的决定权。
    ///
    ///  [!] 只在**真的有治疗需求**时才列（有人缺口 > 阈值），
    ///      否则会白白建议开即刻（它在爆发里还有用）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 加即刻候选(List<IBattleChara> 队)
    {
        try
        {
            var 受限 = SpellUtil.在移动() || 空中检测.在空中;
            if (!受限) return;

            // 已经有即刻 buff -> 不需要再开（再来一次是浪费）
            try { if (Core.Me.HasAura(AuraIds.即刻)) return; } catch { }

            if (!即刻可用()) return;

            // 有治疗需求吗？（有人的缺口够大才值得花即刻）
            var 阈值 = 0.25f;   // 低于这个缺口不值得为它花即刻
            var 有需求 = false;
            foreach (var r in 队)
            {
                try
                {
                    if (治疗决策.缺口量(r) >= 阈值) { 有需求 = true; break; }
                }
                catch { }
            }
            if (!有需求) return;

            var id = SpellIds.取("即刻咏唱");
            if (id == 0) return;

            foreach (var c in _当前表)
                if (c.技能Id == id) return;      // 去重

            _当前表.Add(new 候选
            {
                类 = 类别.功能,
                施法目标模式 = 目标模式.自己,
                技能Id = id,
                技能名 = "即刻咏唱",
                能力技 = true,
                瞬发 = true,
                // [!] 分数要够高 —— 它是**解锁移动中治疗**的钥匙，
                //     不选它的话这一轮就一口都奶不上。
                本地分 = 2.2f,
            });
        }
        catch { }
    }

    private static float 血比例(IBattleChara 目标)
    {
        try { return 目标.有效血量比例(); } catch { return 1f; }
    }

    private static float 最大血(IBattleChara 目标)
    {
        try { return MathF.Max(1f, 目标.MaxHp); } catch { return 1f; }
    }

    private static string 名(IBattleChara 目标)
    {
        try { return 目标.Name.ToString(); } catch { return "?"; }
    }
