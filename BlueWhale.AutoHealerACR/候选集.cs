    //  [!] 数字怎么定的：
    //      紧急 3（濒死的人不会超过 3 个真正该救的）
    //      功能 2（复活 + 驱散，**有就必须给**）
    //      减伤 3（团队 + 个人 + 盾，见 `桶上限` 里的说明）
    //      治疗 3（单奶 / 群奶 / 盾各一够取舍）
    //      输出 3（基础 / AOE / DoT）
    //      合计 **14**
    //
    //  ★ **总上限不能低于各桶上限之和**（本轮修的）★
    //
    //  [!] 修的是什么：原来 `最多 = 12` 而各桶之和 = **14**
    //      ==> **只要各类都有候选，就必然超 2 个，每个决策周期都走回收序**
    //      ==> 而回收序是 `输出 0 -> 减伤 1 -> 治疗 2 -> 功能 3 -> 紧急 4`，
    //          **被砍的永远是输出** ——
    //          即"桶上限说输出可以有 3 个"，而总上限**从来不允许它有 3 个**。
