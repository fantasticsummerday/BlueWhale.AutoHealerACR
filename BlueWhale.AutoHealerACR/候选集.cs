using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// **候选动作集** —— 本地把"当前合法且值得考虑的动作"算成一组**不可变快照**。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么需要它（第一轮审阅第 9/10/24 条）★
///
///    现状：`AI -> SkillId`。白名单只能证明"这个技能本职业有"，
///    不能证明"这个局面下该用它"。
///    ⇒ 本类把游戏世界压缩成一组**真实、合法、可执行**的候选，AI 只做取舍。
///
///  ══════════════════════════════════════════════════════════════════
///  ★★ 第二轮审阅指出的两个 P0（本类已按它重构）★★
///
///  【P0-1】`C1/C2` 原来只是**排序后的位置** —— 不是身份
///      `_本帧.Sort(...)` 之后按位置重编号，缓存 300ms 一过就重算。
///      于是 AI 请求发出时选的是"C1 = 治坦克"，回来时 C1 已经变成"DoT Boss"
///      ⇒ **AI 的选择被执行成了另一个动作**。
///
///      ⇒ 修法：`候选Id` 由 **快照号 + 序号** 生成（形如 `S18231-3`），
///        **永不重编号**；解析时先认 `候选Id`，再兼容显示编号。
///        显示用的 `C1/C2` 仍然给 AI 看（好写好读）。
///
///  【P0-2】`_本帧` 是 `static List`，游戏线程 Clear/Add/Sort，
///      后台线程（AI 回复的续体）按编号查 ⇒ **完全没有同步**（lock 0 处）
///      —— 和本项目已经栽过两次的 bug 一模一样
///      （`AiDecisionLayer._队列`、`AiStrategyLayer.历史`）。
///
///      ⇒ 修法：对外只发**不可变快照**；后台线程只读它自己那份快照，
///         永远不碰正在被改的列表。
///
///  ★ 快照的生命周期 ★
///      每个快照按 `快照Id` 存进有界表（保留最近若干），
///      AI 回复回来时按**请求时记下的快照Id**去取 ——
///      取不到（太久远）就整个丢弃，**不做"用当前候选凑合"的猜测**。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 候选集
{
    /// <summary>
    /// **候选类别** —— 决定它在分桶分配里进哪个桶。
    ///
    /// [!] 为什么需要分类（第三轮审阅第 4/5 条，实测成立的**设计缺陷**）：
    ///      原来 `Sort(按本地分) 后取前 8`。而 4 人本里
    ///      **一个单奶技能会给每个受伤队友各生成一个候选** ——
    ///      几个奶技就把 8 个名额占满，**伤害候选一个都进不来**
    ///      （AI 永远看不到"可以打输出"，ACR 退化成只会奶）；
    ///      反过来输出分高（威力/100 常常大于治疗分）时，
    ///      复活 / 驱散 / 救急会被裁掉 ——
    ///      而 Prompt 里还写着"必须奶满"，AI 却找不到对应候选。
    ///
    ///      根因：治疗决策的价值**不是可比单一标量**。
    ///      "奶满坦克"漏了会死人，"补一个 DoT"漏了只是少输出 ——
    ///      用同一个分数排序，必然在某个局面上把该保的挤掉。
    ///      => 必须**分类保底**，不能全局排序。
    /// </summary>
    public enum 类别
    {
        紧急,     // 濒死 / 必须奶满 / 复活 —— **漏了会死人**
        功能,     // 驱散等辅助
        减伤,     // 团队 / 个人减伤
        治疗,     // 常规治疗 / 护盾
        输出,     // 伤害 / DoT
    }

    /// <summary>
    /// **施法目标模式** —— 技能实际往哪儿放。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么必须和 `TargetId` 分开（本轮审阅第 4/5/6 条）★
    ///
    ///    原来只有一个 `TargetId`，它被迫同时表达两件事：
    ///      ① **技能往谁身上放**（施法目标）
    ///      ② **为什么选它**（判断依据）
    ///
    ///    于是出了两个真 bug（都已核实）：
    ///
    ///    【群疗】项目里的正确写法是（`Res_Heal.cs`）：
    ///        slot.Add(new Spell(_t.群体治疗GCD, SpellTargetType.Self));
    ///      群疗是**以自己为中心**的范围技 —— 目标是你自己。
    ///      而"最缺血的队友"只是**为什么现在该群疗**的理由。
    ///      => 候选把那个队友当成了施法目标，群疗会以他为中心放，
    ///         别人不在范围内就治不到。
    ///
    ///    【个人减伤】项目里（`Res_Mitigation.cs`）：
    ///        slot.Add(spell);        // 没有目标参数 = 自己施放
    ///      而 `判目标类型` 把它归到"队友"，会去找"血最少的队友"。
    ///
    ///  ⇒ 修法：施法目标由 `TargetMode` 决定，`TargetId` 只在
    ///     `TargetMode` 是 `队友` / `敌人` 时才有意义。
    ///     "为什么选它"单独放 `关注目标`。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public enum 目标模式
    {
        /// <summary>对自己施放（群疗 / 群盾 / 团队减伤 / 个人减伤 / 地面放置）</summary>
        自己,

        /// <summary>对 `TargetId` 指定的队友施放（单奶 / 单体盾 / 驱散 / 复活）</summary>
        队友,

        /// <summary>对 `TargetId` 指定的敌人施放（输出 / DoT）</summary>
        敌人,

        /// <summary>地面技能 —— 没有施法目标，落点由本地算</summary>
        地面,
    }

    /// <summary>一个候选动作（构建后不再改动）</summary>
    public sealed class 候选
    {
        /// <summary>
        /// **稳定身份** —— `S{快照Id}-{序号}`，形如 `S18231-3`。
        /// [!] 这是**唯一**用于解析的身份；位置编号（C1/C2）只是给人看。
        /// </summary>
        public string 候选Id = "";

        /// <summary>显示用短编号（C1/C2…）—— **不参与解析身份**</summary>
        public string 编号 = "";

        /// <summary>类别 —— 决定分桶（见 `类别` 的说明）</summary>
        public 类别 类 = 类别.治疗;

        public uint 技能Id;
        public string 技能名 = "";

        /// <summary>
        /// **技能实际往哪儿放** —— 执行层照这个放。
        /// [!] `队友` / `敌人` 时才看 `目标Id`；`自己` 时不看。
        /// </summary>
        public 目标模式 施法目标模式 = 目标模式.队友;

        /// <summary>施法目标 id（只在 `施法目标模式` 是 队友/敌人 时有效）</summary>
        public ulong 目标Id;
        public string 目标名 = "";

        // ══════════════════════════════════════════════════════════════
        //  ★ 关注目标 —— "为什么选这个候选" ★
        //
        //  [!] 和 `目标Id` 的区别（本轮审阅第 5 条）：
        //      `目标Id` = 技能往谁身上放。
        //      `关注目标` = 这个候选是**因为谁**才被提出来的。
        //
        //      群疗是最好的例子：施法目标是自己，但"因为坦克快死了"
        //      才是选它的理由。原来这两件事挤在一个字段里，于是群疗
        //      被打到了坦克身上。
        //
        //  [!] 它**只用于显示和解释**，执行层不读它。
        // ══════════════════════════════════════════════════════════════

        /// <summary>因为谁才提这个候选（0 = 无特定对象）。只给 AI 看。</summary>
        public ulong 关注目标Id;

        /// <summary>关注目标的名字</summary>
        public string 关注目标名 = "";

        /// <summary>关注它的原因（一句话，给 AI 解释用）</summary>
        public string 关注原因 = "";

        public bool 群体;
        public bool 能力技;
        public bool 瞬发;

        /// <summary>恢复力 / 威力（AOE 时是**总量** = 单体 × 命中数）</summary>
        public int 量;

        /// <summary>命中数（>1 表示 AOE 总量）</summary>
        public int 命中数 = 1;

        /// <summary>单体威力（AOE 时给出，避免把总量误当单体值）</summary>
        public int 单体威力;

        /// <summary>目标当前缺口（% 最大血，0~1）</summary>
        public float 缺口;

        /// <summary>预计过量（0~1）</summary>
        public float 过量;

        // ══════════════════════════════════════════════════════════════
        //  ★ 治疗数值模型（第三轮审阅第 16 条）★
        //
        //  [!] 为什么不能只给"量"：
        //      一个瞬发治疗 3000 和一个 HoT 总量 6000 **不能直接比较** ——
        //      前者立刻回 3000，后者要十几秒才回完。
        //      救命看的是"这 3 秒能回多少"，不是"总共能回多少"。
        // ══════════════════════════════════════════════════════════════

        /// <summary>**即时**治疗量（不含 HoT）—— 救命看它，不是看总量</summary>
        public int 即时治疗;

        /// <summary>3 秒内预计总治疗（即时 + 这 3 秒的 HoT 跳数）</summary>
        public int 预测3秒;

        /// <summary>6 秒内预计总治疗</summary>
        public int 预测6秒;

        public int 耗蓝;
        public float 冷却;
        public int 资源;

        /// <summary>
        /// **紧急等级** —— 桶内优先级的**第一关键字**。
        ///
        /// ══════════════════════════════════════════════════════════════
        ///  [!] 为什么不能只看本地分（本轮审阅第 11 条）：
        ///      紧急桶上限 3，而有四类东西都往里挤：
        ///          必须奶满 / 复活 / 濒死 / 普通紧急治疗
        ///      纯按本地分排，"必须奶满"**可能被挤出去** ——
        ///      而 Prompt 里写着"必须奶满优先级最高"。
        ///      => 提示词和候选列表互相矛盾，AI 想遵守也没有那个选项。
        ///
        ///  [!] 分级（数字只用于比较，不显示）：
        ///        1000  必须奶满   —— 不奶就是死，无条件最高
        ///         900  复活       —— 少一个人可能就打不过
        ///         800  濒死       —— 血量极低
        ///           0  其余
        /// ══════════════════════════════════════════════════════════════
        /// </summary>
        public int 紧急等级;

        /// <summary>本地算分（只用于排序，**不给 AI 看**）</summary>
        public float 本地分;
    }

    /// <summary>
    /// **候选快照** —— 一次生成的结果，构造后不可变。
    /// [!] AI 请求与响应之间传递的就是它。
    /// </summary>
    public sealed class 快照
    {
        public long 快照Id;
        public long 生成时刻;
        public IReadOnlyList<候选> 候选表 = Array.Empty<候选>();

        ///
        /// [!] 为什么挂在快照上、而不是独立的静态字段（用户实测的矛盾）：
        ///      独立字段会和快照**对不上** —— `生成()` 有 300ms 缓存，
        ///      缓存命中时返回**旧快照**，但那些字段可能已被别处的
        ///      新一轮生成刷新过。调试窗于是显示出
        ///      "0 个候选 + 四个生成器都有产出" 这种自相矛盾的东西。
        ///
        ///      挂进快照之后，**结构上不可能不同步**。
        /// </summary>
        public string 生成诊断 = "";

        /// <summary>按**稳定身份**取候选</summary>
        public 候选? 按Id(string? id)
        {
            if (string.IsNullOrWhiteSpace(id)) return null;
            var 要 = id.Trim();
            foreach (var c in 候选表)
                if (string.Equals(c.候选Id, 要, StringComparison.OrdinalIgnoreCase))
                    return c;
            return null;
        }

        /// <summary>按**显示编号**取候选（C1/C2）—— 兼容 AI 直接回编号</summary>
        public 候选? 按编号(string? 编号)
        {
            if (string.IsNullOrWhiteSpace(编号)) return null;
            var 要 = 编号.Trim();
            foreach (var c in 候选表)
                if (string.Equals(c.编号, 要, StringComparison.OrdinalIgnoreCase))
                    return c;
            return null;
        }

        /// <summary>先按稳定 Id、再按显示编号（两种都接受）</summary>
        public 候选? 解析(string? 引用) => 按Id(引用) ?? 按编号(引用);
    }

    // ══════════════════════════════════════════════════════════════
    //  ★ 分桶名额（第三轮审阅第 5 条）★
    //
    //  [!] 为什么每类都要**保底**而不是全局 Top-N：
    //      治疗的价值不是单一标量。"奶满坦克"漏了会死人，
    //      "补 DoT"漏了只是少输出 —— 用同一个分数排序，
    //      必然在某个局面上把该保的挤掉。
    //
    //  [!] 数字怎么定的：
    //      紧急 3（濒死的人不会超过 3 个真正该救的）
    //      功能 2（复活 + 驱散，**有就必须给**）
    //      减伤 2（团队 + 个人）
    //      治疗 3（单奶 / 群奶 / 盾各一够取舍）
    //      输出 3（基础 / AOE / DoT）
    //      合计 13；总上限 12，超了按 `回收序` 砍
    // ══════════════════════════════════════════════════════════════
    private const int 最多 = 12;

    /// <summary>每桶最多几个</summary>
    private static int 桶上限(类别 c) => c switch
    {
        类别.紧急 => 3,
        类别.功能 => 2,
        类别.减伤 => 2,
        类别.治疗 => 3,
        类别.输出 => 3,
        _ => 2,
    };

    /// <summary>
    /// 名额不够时**先从哪个桶回收**（数字越小越先被牺牲）。
    ///
    /// [!] 顺序按"漏了的代价"排，是刻意的：
    ///      输出最可牺牲（少打一点而已）-> 减伤（还有治疗兜）
    ///      -> 治疗 -> 功能（复活/驱散几乎不可牺牲）
    ///      -> 紧急（**绝不牺牲**，漏了就是死人）
    /// </summary>
    private static int 回收序(类别 c) => c switch
    {
        类别.输出 => 0,
        类别.减伤 => 1,
        类别.治疗 => 2,
        类别.功能 => 3,
        类别.紧急 => 4,
        _ => 1,
    };

    private const int 缓存毫秒 = 300;
    private const int 快照保留 = 12;

    // ══════════════════════════════════════════════════════════════
    //  ★ 线程安全：只在这把锁里改 `_当前表` / `_快照表` ★
    //
    //  [!] 为什么必须（第二轮审阅 P0-2）：
    //      写点 = 游戏线程（`生成()` 里 Clear/Add/Sort）；
    //      读点 = **后台线程**（AI 回复的续体里解析候选）。
    //      原来这里是裸 `static List`，lock 0 处 ——
    //      和本项目栽过的 `AiDecisionLayer._队列` / `AiStrategyLayer.历史` 同一个 bug。
    //
    //  [!] 但对外**只发快照**：调用方拿到的是不可变对象，
    //      遍历它不需要持锁 —— 从根上消除"遍历期被改"。
    // ══════════════════════════════════════════════════════════════
    private static readonly object _锁 = new();

    private static readonly List<候选> _当前表 = new();
    private static long _本帧时刻;

    private static readonly Dictionary<long, 快照> _快照表 = new();
    private static readonly Queue<long> _快照序 = new();

    private static long _下一个快照Id;
    private static 快照 _当前 = new();

    // ══════════════════════════════════════════════════════════════
    //  ★ 生成过程的逐步统计（诊断用）★
    //
    //  [!] 为什么要它（用户实测）：
    //      调试窗显示"候选快照 #23868（0 个）" —— 但**看不出是哪一步归零的**：
    //        拿不到技能表？没队友受伤？没敌人？减伤没配置？
    //      四个生成器各有多个提前 return，只报"0 个"等于没线索。
    //
    //  [!] 只记**原因字符串**，不记对象 —— 它是诊断数据，不该拖住 GC。
    // ══════════════════════════════════════════════════════════════
    // [!] 这些是**本轮生成的临时状态**，生成完就打包进快照的 `生成诊断`。
    //     不再对外暴露 —— 对外的入口是 `快照.生成诊断`（见那里的说明）。
    private static string _诊断治疗 = "";
    private static string _诊断输出 = "";
    private static string _诊断减伤 = "";
    private static string _诊断功能 = "";

    /// <summary>把本轮诊断拼成一行（挂进快照）</summary>
    private static string 拼诊断(int 治疗, int 输出, int 减伤, int 功能, int 总数)
    {
        string 段(string 名, int 数, string 原因)
            => 数 > 0 ? $"{名}={数}" : $"{名}=0({(string.IsNullOrEmpty(原因) ? "无原因" : 原因)})";

        return $"总数={总数}｜" +
               string.Join("｜", new[]
               {
                   段("治疗", 治疗, _诊断治疗),
                   段("输出", 输出, _诊断输出),
                   段("减伤", 减伤, _诊断减伤),
                   段("功能", 功能, _诊断功能),
               });
    }

    // ==================== 对外 ====================

    /// <summary>生成（或 300ms 内复用）当前候选快照。返回的是**不可变快照**。</summary>
    public static 快照 生成()
    {
        lock (_锁)
        {
            var 现在 = TimeHelper.Now();

            // ══════════════════════════════════════════════════════════════
            //  [!] 缓存判据**不能再看 `_当前表.Count > 0`**（原实现的缺陷）
            //
            //      原来写的是：
            //          if (_当前表.Count > 0 && 现在 - _本帧时刻 < 缓存毫秒) return _当前;
            //      「候选为空」被当成了"还没生成过" => **空表永远不命中缓存**
            //      => 每个调用点都重新生成 => 每 300ms 一个新快照号。
            //
            //      而"候选为空"其实是一个**合法结果**（没队友受伤 / 没敌人 /
            //      不在战斗…），它同样该被缓存 —— 否则既浪费算力，
            //      又让快照号无意义地涨（用户实测截到 `#23868`）。
            //
            //  [!] 溢出本身不用担心：`_下一个快照号` 是 `long`（上限 9.2e18），
            //      每 300ms 一个也要跑几十亿年。要修的是**无意义的增长**。
            // ══════════════════════════════════════════════════════════════
            if (_本帧时刻 != 0 && 现在 - _本帧时刻 < 缓存毫秒) return _当前;

            _当前表.Clear();
            _本帧时刻 = 现在;

            // [!] 每次生成前清空诊断 —— 不清的话，上一次的"没队友受伤"
            //     会残留到这一次，看起来像"这次也没队友受伤"（误导）。
            _诊断治疗 = ""; _诊断输出 = ""; _诊断减伤 = ""; _诊断功能 = "";

            // ══════════════════════════════════════════════════════════════
            //  ★ 每个生成器**真去数**加了多少条 ★
            //
            //  [!] 原来我用的是错误推断：
            //          if (string.IsNullOrEmpty(_诊断治疗)) _诊断治疗 = "有产出";
            //      「没有提前 return」**不等于**「真的产出了候选」——
            //      技能可能全部不可用、目标可能全被跳过、去重可能全撞上。
            //      所以必须**数 `_当前表` 的增量**。
            // ══════════════════════════════════════════════════════════════
            int 治疗条 = 0, 输出条 = 0, 减伤条 = 0, 功能条 = 0;
            int 前;

            前 = _当前表.Count;
            try { 加治疗候选(); }
            catch (Exception e) { Ai调试.调试("候选集(治疗)异常：" + e.Message); }
            治疗条 = _当前表.Count - 前;

            前 = _当前表.Count;
            try { 加输出候选(); }
            catch (Exception e) { Ai调试.调试("候选集(输出)异常：" + e.Message); }
            输出条 = _当前表.Count - 前;

            前 = _当前表.Count;
            try { 加减伤候选(); }
            catch (Exception e) { Ai调试.调试("候选集(减伤)异常：" + e.Message); }
            减伤条 = _当前表.Count - 前;

            前 = _当前表.Count;
            try { 加功能候选(); }
            catch (Exception e) { Ai调试.调试("候选集(功能)异常：" + e.Message); }
            功能条 = _当前表.Count - 前;

            // ★ 分桶取候选（不是全局 Top-N）—— 见 `分桶取候选` 的说明 ★
            var 选中 = 分桶取候选();

            // [!] `候选Id` = 快照号 + 序号 ⇒ **永不重编号**；
            //     位置编号 `C1/C2` 每次重排都会变，**不能**当身份。
            var id = ++_下一个快照Id;
            for (var i = 0; i < 选中.Count; i++)
            {
                选中[i].编号 = "C" + (i + 1);
                选中[i].候选Id = "S" + id + "-" + (i + 1);
            }

            快照 新 = new()
            {
                快照Id = id,
                生成时刻 = 现在,
                候选表 = 选中.ToArray(),   // ★ 副本 —— 之后 _当前表 再改也不影响它

                // [!] 诊断**跟着快照走** —— 这样调试窗显示的快照和诊断
                //     必然来自同一次生成（不会出现"0 个 + 四个有产出"那种矛盾）
                生成诊断 = 拼诊断(治疗条, 输出条, 减伤条, 功能条, 选中.Count),
            };

            _当前 = 新;
            存快照(新);
            return 新;
        }
    }

