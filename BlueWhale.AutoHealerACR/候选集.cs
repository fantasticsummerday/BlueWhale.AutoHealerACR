    //      （DoT 该补了 / 敌人够多该 AOE 了 / 能力技转好了）。
    //      把输出候选砍掉 = **AI 看不到那些选项** = 它只能建议治疗，
    //      于是"输出最优"这一半**结构性地做不到**。
    //
    //  [!] 为什么不是"调回收序"而是"提总上限"：
    //      回收序本身是合理的（它决定了"必须丢东西时先丢哪类"），
    //      问题在于**"必须丢"这件事被一个过低的总上限人为制造出来了**。
    //      ==> 提总上限 = 让"每桶上限"真正成为**分类上限**，而不是被全局压掉。
