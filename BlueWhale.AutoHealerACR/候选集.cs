    private static void 存快照(快照 s)
    {
        _快照表[s.快照Id] = s;
        _快照序.Enqueue(s.快照Id);
        while (_快照序.Count > 快照保留)
        {
            var 旧 = _快照序.Dequeue();
            if (旧 != s.快照Id) _快照表.Remove(旧);
        }
    }

    private static void 加治疗候选()
    {
        var 技能表 = 职业表();
        if (技能表 == null) { _诊断治疗 = "拿不到职业技能表"; return; }

        var 队 = HealTargetHelper.可治疗队友(30f);
        if (队.Count == 0) { _诊断治疗 = "没有可治疗队友"; return; }

        var 进前 = _当前表.Count;

            // [!] 这三个值整轮循环不变 —— 放在循环外算一次（见下面的说明）
            var 受限 = false;
            try { 受限 = SpellUtil.在移动() || 空中检测.在空中; } catch { }

            var 有即刻Buff = false;
            try { 有即刻Buff = Core.Me.HasAura(AuraIds.即刻); } catch { }

            var 即刻能放 = 即刻可用();


        foreach (var 技 in 技能表.治疗候选.已解锁())
        {
            if (技.Id == 0) continue;
            try
            {
                if (!SpellUtil.已解锁(技.Id)) continue;
                if (!SpellUtil.可用(技.Id)) continue;
            }
            catch { continue; }
                // ══════════════════════════════════════════════════════════
                //  [!] 移动 / 空中时，读条治疗能不能放（用户实测："全程移动 ai 不奶了"）
                //
                //      核实过的事实（别再搞错）：
                //        · `SpellUtil.移动中能放()` **有**即刻豁免，
                //          但那个豁免要求**已经开着即刻 buff**
                //        · 移动中"**要不要开即刻**"没有任何地方判断
                //
                //      ⇒ 这里：
                //         · 已经有即刻 buff    -> 读条治疗照收（真能放）
                //         · 没 buff 但即刻可用 -> 也收，同时下面会把即刻列成候选
                //           （AI 选了即刻，下一步那个读条治疗就能放出来）
                //         · 没 buff 且即刻在 CD -> **不收**（收了也是白决策一次）
                //
                //  [!] 为什么放在 try 之外预先算：三个值在整轮循环里不变，
                //      放进循环里每轮都查 buff 是浪费。
                // ══════════════════════════════════════════════════════════
                if (受限 && !技.瞬发 && 技.咏唱 > 0f)
                {
                    if (!有即刻Buff && !即刻能放) continue;
                }


            if (技.群体)
            {
                IBattleChara? 最缺 = null;
                var 最缺量 = 0f;
                var 有人 = 0;
                foreach (var r in 队)
                {
                    var g = 治疗决策.缺口量(r);
                    if (g <= 0.01f) continue;
                    有人++;
                    if (g > 最缺量) { 最缺量 = g; 最缺 = r; }
                }
                if (有人 == 0 || 最缺 == null) continue;

                var 候选 = 造(技, 最缺, 最缺量);
                if (候选 != null)
                {
                    候选.群体 = true;

                    // ★ 群疗的**施法目标是自己**、最缺的人是"关注目标" ★
                    //
                    //  [!] 本轮审阅抓到的真 bug（已核实）：
                    //      项目里群疗的正确写法是（`Res_Heal.cs`）
                    //          slot.Add(new Spell(_t.群体治疗GCD, SpellTargetType.Self));
                    //      群疗是**以自己为中心**的范围技 —— 目标是你自己。
                    //      而"最缺血的队友"只是**为什么现在该群疗**的理由。
                    //
                    //      原来候选把那个队友当成了施法目标 =>
                    //      群疗会以他为中心放，别人不在范围内就治不到。
                    候选.施法目标模式 = 目标模式.自己;
                    候选.目标Id = 0;
                    候选.目标名 = "";
                    候选.关注目标Id = 最缺.GameObjectId;
                    候选.关注目标名 = 名(最缺);
                    候选.关注原因 = $"队里 {有人} 人缺血，他最缺（{最缺量 * 100f:F0}%）";

                    候选.本地分 += Math.Min(1.0f, 有人 * 0.15f);
                    _当前表.Add(候选);
                }
            }
            else
            {
                foreach (var r in 队)
                {
                    var 缺口 = 治疗决策.缺口量(r);
                    if (缺口 <= 0.01f) continue;
                    var 候选 = 造(技, r, 缺口);
                    if (候选 != null) _当前表.Add(候选);
                }
            }
        }

        // ★ 移动中 + 有治疗需求 -> 把即刻咏唱列出来（见 加即刻候选 的说明）★
        加即刻候选(队);
    }

    private static 候选? 造(治疗技能 技, IBattleChara 目标, float 缺口)
    {
        try
        {
            var 目标Id = 目标.GameObjectId;
            foreach (var x in _当前表)
                if (x.技能Id == 技.Id && x.目标Id == 目标Id) return null;

            var 上限 = 最大血(目标);
            var 单次 = MathF.Max(1f, 技.总恢复力);
            var 缺口绝对值 = 缺口 * 上限;
            var 过量 = 单次 > 0f ? MathF.Max(0f, (单次 - 缺口绝对值) / 单次) : 0f;
            var 覆盖 = MathF.Min(1f, 单次 / MathF.Max(1f, 缺口绝对值));

            // ══════════════════════════════════════════════════════════
            //  ★ 治疗数值模型：即时 / 3s / 6s（第三轮审阅第 16 条）★
            //
            //  [!] 为什么不能只给"量"：
            //      瞬发治疗 3000 和 HoT 总量 6000 **不能直接比较** ——
            //      前者立刻回 3000，后者要十几秒才回完。
            //      救命看的是"这 3 秒能回多少"，不是"总共能回多少"。
            // ══════════════════════════════════════════════════════════
            var 即时 = (int)技.即时恢复力;
            var 每跳 = (int)技.HoT恢复力;
            const float 跳间隔 = 3f;      // FF14 的 HoT 默认 3 秒一跳
            const float 窗口 = 6f;
            var 预测3 = 即时;
            var 预测6 = 即时;
            if (每跳 > 0 && 技.HoT持续 > 0f)
            {
                var 总跳数 = 技.HoT持续 / 跳间隔;
                预测3 += (int)(每跳 * MathF.Min(总跳数, 3f / 跳间隔));
                预测6 += (int)(每跳 * MathF.Min(总跳数, 窗口 / 跳间隔));
            }

            // ── 类别判定：依据是**局面**，不是技能表 ──
            //   同一个技能在"队友濒死"时是救急，在"只掉一点血"时是常规治疗。
            var 类 = 类别.治疗;
            var 紧急 = 0;
            var 血比 = 血比例(目标);

            if (缺口 >= 0.55f || 血比 <= 0.25f) { 类 = 类别.紧急; 紧急 = 800; }
            // [!] 用 `命中状态(目标) != 0` 而不是 `是必须奶满状态(...)` ——
            //     后者要传状态 Id，而这里只想问"**这个人**中了必须奶满的机制吗"。
            //     `命中状态` 就是干这个的（返回 0 = 没中）。
            try
            {
                // ★ 必须奶满 = 最高级（1000）★
                //   [!] 它**不看血量**（那人可能看着 80% 健康），只能靠状态判。
                //      所以必须无条件压过其它紧急项 —— 否则会被挤掉。
                if (必须奶满.命中状态(目标) != 0) { 类 = 类别.紧急; 紧急 = 1000; }
            }
            catch { }

            // ── 施法目标模式 ──
            //   [!] 默认是"队友"（单奶/单盾/复活/驱散都是），
            //      群体技能由调用方改成"自己"，地面技能改成"地面"。
            var 模式 = 目标模式.队友;
            try
            {
                if (技能数据.是地面技能(技.Id)) 模式 = 目标模式.地面;
            }
            catch { }

            return new 候选
            {
                类 = 类,
                紧急等级 = 紧急,
                施法目标模式 = 模式,
                技能Id = 技.Id,
                技能名 = string.IsNullOrEmpty(技.名) ? ("技能" + 技.Id) : 技.名,
                目标Id = 目标Id,
                目标名 = 名(目标),
                群体 = 技.群体,
                能力技 = 技.冷却 > 0f,
                瞬发 = 技.瞬发,
                量 = (int)技.总恢复力,
                即时治疗 = 即时,
                预测3秒 = 预测3,
                预测6秒 = 预测6,
                命中数 = 1,
                缺口 = Math.Clamp(缺口, 0f, 1f),
                过量 = Math.Clamp(过量, 0f, 1f),
                耗蓝 = 技.MP,
                冷却 = 技.冷却,
                资源 = 技.资源消耗,
                本地分 = 覆盖 * 2f - 过量 * 1.5f + (技.冷却 > 0f ? 0.3f : 0f),
            };
        }
        catch { return null; }
    }

    private static void 加输出候选()
    {
        var 技能表 = 职业表();
        if (技能表 == null) { _诊断输出 = "拿不到职业技能表"; return; }

        var 目标 = 输出目标.选();
        if (目标 == null || !目标.活着()) { _诊断输出 = "没有可选敌人"; return; }

        var 进前 = _当前表.Count;

        var 等级 = (int)Core.Me.Level;

        加输出(技能表.基础输出, 技能表.查威力(技能表.基础输出, 等级), 1, 目标, false);

        try
        {
            var 敌数 = HealTargetHelper.周围敌人数量(技能表.AOE伤害范围, 25f);
            if (敌数 >= 技能表.AOE最少敌人数 && 技能表.群体输出 != 0)
            {
                var 单体 = 技能表.查威力(技能表.群体输出, 等级);
                加输出(技能表.群体输出, 单体 * 敌数, 敌数, 目标, true, 单体);
            }
        }
        catch { }

        try
        {
            if (技能表.Dot技能 != 0 && HealTargetHelper.值得上Dot(目标))
                加输出(技能表.Dot技能, 技能表.查威力(技能表.Dot技能, 等级), 1, 目标, false);
        }
        catch { }

        // ══════════════════════════════════════════════════════════════
        //  ★ 站定填充技 —— 站定时也列出来（用户实测）★
        //
        //  [!] 现象："远处应该打毁灭，而不是毁坏，少10威力"。
        //
        //  [!] 根因：50 级时 `基础输出` = **毁坏（140，瞬发）**，
        //      而 `毁灭`（150，读条）**从来不是候选** => AI 看不到它 =>
        //      只能一直建议唯一可见的填充技。
        //      **不是"不会比较"，是"没得比"。**
        //
        //  [!] 只在**没在移动/空中**时加 —— 移动中它放不出来，
        //      列进去只会让 AI 白选一个被本地挡掉的技能。
        //      移动时本来就有 `移动填充技`（毁坏）可用。
        // ══════════════════════════════════════════════════════════════
        try
        {
            var 站定 = 技能表.站定填充技;
            if (站定 != 0 && 站定 != 技能表.基础输出)
            {
                var 受限 = SpellUtil.在移动() || 空中检测.在空中;
                if (!受限)
                    加输出(站定, 技能表.查威力(站定, 等级), 1, 目标, false);
            }
        }
        catch { }
    }

    private static void 加输出(uint 技能Id, int 总威力, int 命中数,
                              IBattleChara 目标, bool 群体, int 单体威力 = 0)
    {
        if (技能Id == 0) return;
        try
        {
            if (!SpellUtil.已解锁(技能Id)) return;
            if (!SpellUtil.可用(技能Id)) return;
        }
        catch { return; }

        foreach (var c in _当前表)
            if (c.技能Id == 技能Id) return;

        bool 瞬发;
        try { 瞬发 = SpellUtil.移动中可用(技能Id); } catch { 瞬发 = false; }

        _当前表.Add(new 候选
        {
            类 = 类别.输出,
            施法目标模式 = 目标模式.敌人,
            技能Id = 技能Id,
            技能名 = 取技能名(技能Id),
            目标Id = 目标.GameObjectId,
            目标名 = 名(目标),
            群体 = 群体,
            能力技 = false,
            瞬发 = 瞬发,
            量 = 总威力,
            命中数 = 命中数,
            单体威力 = 单体威力,
            本地分 = 总威力 / 100f,
        });
    }

