    /// <summary>
    /// **移动中 + 只有读条治疗可用 → 把即刻咏唱本身列成候选**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么需要它（用户实测："全程移动 ai 不奶了"）：
    ///      移动/空中时读条治疗放不出来，而 oGCD 治疗都有 CD 或用资源
    ///      （以太超流 / 小仙女）。资源一空，候选表就空了 => AI 无从选择。
    ///
    ///      "开即刻再补"是玩家的标准操作，也是移动中救命的最后手段 ——
    ///      但**没有任何地方判断"要不要开即刻"**。
    ///
    ///  [!] 它作为**独立候选**（`类别.功能`）而不是自动组合：
    ///      选了它 -> 即刻 buff 就有了 -> 那个读条治疗就能在移动中放出去。
    ///      这样 AI 仍然掌握"要不要花掉这个 60 秒 CD"的决定权。
    ///
    ///  [!] 只在**真的有治疗需求**时才列（有人缺口 > 阈值），
    ///      否则会白白建议开即刻（它在爆发里还有用）。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 加即刻候选(List<IBattleChara> 队)
    {
        try
        {
            var 受限 = SpellUtil.在移动() || 空中检测.在空中;
            if (!受限) return;

            // 已经有即刻 buff -> 不需要再开（再来一次是浪费）
            // ★ 同上：读 buff 前先判有效性
            try { if (Core.Me != null && Core.Me.对象有效() && Core.Me.HasAura(AuraIds.即刻)) return; }
            catch { }

            if (!即刻可用()) return;

            // 有治疗需求吗？（有人的缺口够大才值得花即刻）
            var 阈值 = 0.25f;   // 低于这个缺口不值得为它花即刻
            var 有需求 = false;
            foreach (var r in 队)
            {
                try
                {
                    if (治疗决策.缺口量(r) >= 阈值) { 有需求 = true; break; }
                }
                catch { }
            }
            if (!有需求) return;

            var id = SpellIds.取("即刻咏唱");
            if (id == 0) return;

            foreach (var c in _当前表)
                if (c.技能Id == id) return;      // 去重

            _当前表.Add(new 候选
            {
                类 = 类别.功能,
                施法目标模式 = 目标模式.自己,
                技能Id = id,
                技能名 = "即刻咏唱",
                能力技 = true,
                瞬发 = true,
                // [!] 分数要够高 —— 它是**解锁移动中治疗**的钥匙，
                //     不选它的话这一轮就一口都奶不上。
                本地分 = 2.2f,
            });
        }
        catch { }
    }

    // ══════════════════════════════════════════════════════════════════
    //  ★★ 下面三个是**读游戏对象的统一入口** —— 必须在读之前判有效性 ★★
    //
    //  [!] 它们原来只有 `try/catch`，那是**完全无效**的防线：
    //      对象在换图/切区时被释放（但不是 null，而是哨兵 `0x12345679`），
    //      读它的血量/名字会触发**原生访问违例** ——
    //        · **穿透 C# 的 `catch`**（本项目既定结论）
    //        · **不产生转储**
    //        · 全局异常钩子（含 FirstChance）**不触发**
    //        · 进程直接没
    //
    //  [!] 实测定位（`Log-5148620.log`，0.4.0.9 的路标）：
    //        路标 3310「伤害预测 完成」有、3311「采可选技能 完成」**没有**
    //        ==> 崩在 `采可选技能()` 里。
    //        它第一件事就是 `候选集.描述(快照)` -> 快照为空时走 `生成()`
    //        -> 一路走到这三个函数读队友/敌人的血量和名字。
    //
    //  [!] 唯一有效的防线是**读之前先判**：
    //      `目标 != null && 目标.对象有效()`。
    //      `对象有效()` 会挡住哨兵地址、空指针区、内核区。
    //
    //  [!] 拿不到就给中性值（血比例 1f / 血量 1f / 名字 "?"）——
    //      方向很重要：**宁可让 AI 少看到一个人，也不能把游戏打崩**。
    //      中性值不会诱导错误决策（1f = "满血，不用治"），
    //      而读取失败本来就不该产生治疗建议。
    // ══════════════════════════════════════════════════════════════════
    private static float 血比例(IBattleChara 目标)
    {
        try
        {
            if (目标 == null || !目标.对象有效()) return 1f;
            return 目标.有效血量比例();
        }
        catch { return 1f; }
    }

    private static float 最大血(IBattleChara 目标)
    {
        try
        {
            if (目标 == null || !目标.对象有效()) return 1f;
            return MathF.Max(1f, 目标.MaxHp);
        }
        catch { return 1f; }
    }

    private static string 名(IBattleChara 目标)
    {
        try
        {
            if (目标 == null || !目标.对象有效()) return "?";
            return 目标.Name.ToString();
        }
        catch { return "?"; }
    }
