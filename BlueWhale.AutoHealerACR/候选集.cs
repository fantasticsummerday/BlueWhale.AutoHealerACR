    /// <summary>把本轮诊断拼成一行（挂进快照）</summary>
    private static string 拼诊断(int 治疗, int 输出, int 减伤, int 功能, int 总数)
    {
        string 段(string 名, int 数, string 原因)
            => 数 > 0 ? $"{名}={数}" : $"{名}=0({(string.IsNullOrEmpty(原因) ? "无原因" : 原因)})";

        return $"总数={总数}｜" +
               string.Join("｜", new[]
               {
                   段("治疗", 治疗, _诊断治疗),
                   段("输出", 输出, _诊断输出),
                   段("减伤", 减伤, _诊断减伤),
                   段("功能", 功能, _诊断功能),
               });
    }

