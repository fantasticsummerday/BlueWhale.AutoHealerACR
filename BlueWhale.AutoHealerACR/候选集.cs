                    //     它是专门为「解释为什么有这个候选」加的字段（类注释：只用于显示和解释），
                    //     群疗时填了「队里 3 人缺血，他最缺 31%」，但原来**从不打印**
                    //     （只在 `目标Id != 0` 时打目标名，而群疗把 目标Id 清零了）。
                    //     ==> 模型看到 `C3=医济[治疗] 群体` 却不知道**为什么**该群疗。
                    if (!string.IsNullOrEmpty(c.关注原因))
                        sb.Append('(').Append(c.关注原因).Append(')');

                // 类别标签 —— AI 一眼看出这是哪类动作
                sb.Append('[').Append(类名(c.类)).Append(']');

                sb.Append(c.群体 ? " 群体" : " 单体");
                sb.Append(c.能力技 ? " 能力技" : " GCD");
                if (c.瞬发) sb.Append(" 瞬发");

                // [!] 盾单独标 —— 它和"回多少血"不是一回事：
                //     盾是**预防**（提前吸收），治疗是**补救**（事后回血）。
                //     不标的话 AI 只能靠技能名猜（审查发现）。
                // [!] **盾要给真实倍率**（H4，审计确认）——
                //     本地 `治疗决策.盾真实系数` 按真实倍率算（士气高扬 100% vs 意气轩昂 **180%**、
                //     天星交错 200%、神爱抚 200%），而这里原来只打一个「盾」
                //     ==> **两个盾在模型眼里一模一样** ==> 会选错（同「AOE 只给单体威力」一类）。
                if (c.是盾)
                {
                    sb.Append(" 盾");
                    try
                    {
                        var 倍 = 盾系数(c.技能Id);
                        if (倍 > 0f) sb.Append('x').Append((倍 * 100f).ToString("F0")).Append('%');
                    }
                    catch { }
                }

                // [!] AOE 分开给"单体威力 x 命中数 = 总量" ——
                //     只给"量=900"会让人（和 AI）误以为是单体 900
                if (c.命中数 > 1 && c.单体威力 > 0)
                    sb.Append(" 单体").Append(c.单体威力).Append('x').Append(c.命中数)
                      .Append('=').Append(c.量);
                else if (c.量 > 0)
                    sb.Append(" 量").Append(c.量);

                // [!] 即时治疗单独给 —— HoT 的"总量"和"立刻回多少"不是一回事
                if (c.即时治疗 > 0 && c.即时治疗 != c.量)
                    sb.Append(" 即时").Append(c.即时治疗);
                if (c.预测3秒 > 0 && c.预测3秒 != c.即时治疗)
                    sb.Append(" 3s").Append(c.预测3秒);
                // [!] 审计 P1-8：原来"减伤百分点"嵌在 `预测6秒 > 0` 里，
                //     而减伤候选**根本不填 预测6秒** ⇒ 算出来的 8%/12%/18% AI 看不到 ✗
                //     ⇒ 现在**独立渲染**：有百分点就渲染，与 6s 无关 ✓
                if (c.减伤百分点 > 0) sb.Append(" 减伤").Append(c.减伤百分点).Append('%');

                if (c.预测6秒 > 0 && c.预测6秒 != c.预测3秒)
                    sb.Append(" 6s").Append(c.预测6秒);

                if (c.缺口 > 0.01f) sb.Append(" 缺口").Append((int)(c.缺口 * 100f)).Append('%');
                if (c.过量 > 0.04f) sb.Append(" 过量").Append((int)(c.过量 * 100f)).Append('%');
                if (c.耗蓝 > 0) sb.Append(" MP").Append(c.耗蓝);
                
                // [!] **本地真实分必须给**（H2，审计确认）——
                //     本地真正用来选技能的 `治疗决策.打分()` 有 AI 完全看不到的维度：
                //     **GCD数**（缺口要几个 GCD 补满）/ 效率罚（MP 每点有效治疗）/
                //     盾吸收 / 过量折价 70% / 低蓝 ×2.5。
                //     不给的话 AI 只能自己猜算术 ——
                //     例：缺口 2500 时本地选救疗（800 -> 4 个 GCD）而不是治疗（500 -> 5 个 GCD），
                //     **而 AI 的数据里根本没有「要几个 GCD」这个概念**。
                //
                //     ⚠️ 分数在 `造()` 里**就算好了**（那里同时有技能对象和目标对象）；
                //        这里只渲染 —— 因为候选集里**没有"按 id 找角色"的工具**。
                if (!float.IsNegativeInfinity(c.本地真实分))
                    sb.Append(" 本地分").Append(c.本地真实分.ToString("F1"));
                if (c.冷却 > 0.5f) sb.Append(" CD").Append((int)c.冷却).Append('s');
                if (c.资源 > 0) sb.Append(" 资源").Append(c.资源);

                sb.AppendLine();
            }

            sb.AppendLine("  回答：`C1|一句话理由`，一行一个，按先后顺序。");
            return sb.ToString();
        }
        catch
        {
            return "";
        }
    }

    // ==================== 分桶分配 ====================

    /// <summary>
    /// **按类别分桶，每桶取前几名，再按优先级回收超编**。
    ///
    /// ══════════════════════════════════════════════════════════════
    ///  [!] 为什么不能 `Sort 后取前 N`（第三轮审阅第 4/5 条，实测成立）：
    ///
    ///      4 人本里，**一个**单奶技能会为**每个受伤队友**各生成一个候选：
    ///          4 个单奶技能 x 4 个队友 = 16 个治疗候选
    ///      而名额原来只有 8 ⇒ **伤害候选一个都进不来**。
    ///
    ///      反向也会出事：输出技能的"威力/100"常常大于治疗分，
    ///      占满名额时**复活 / 驱散 / 救急会被裁掉**。
    ///
    ///  [!] 所以：**每类都要有代表**；名额不够时按"漏了的代价"回收
    ///      （输出最可牺牲，紧急绝不牺牲）。
    /// ══════════════════════════════════════════════════════════════
    /// </summary>
    private static List<候选> 分桶取候选()
    {
        var 桶 = new Dictionary<类别, List<候选>>();
        foreach (var c in _当前表)
        {
            if (!桶.TryGetValue(c.类, out var l))
            {
                l = new List<候选>();
                桶[c.类] = l;
            }
            l.Add(c);
        }

        // ══════════════════════════════════════════════════════════════
        //  桶内排序：**先比紧急等级，再比本地分**
        //
        //  [!] 顺序是刻意的（本轮审阅第 11 条）：
        //      紧急桶上限 3，而"必须奶满 / 复活 / 濒死 / 普通救急"都往里挤。
        //      纯按本地分排的话，"必须奶满"可能被挤出去 ——
        //      而 Prompt 里写着"必须奶满优先级最高"，AI 却没有那个选项。
        //      => 紧急等级当第一关键字，本地分只在同级内比较。
        // ══════════════════════════════════════════════════════════════
        foreach (var kv in 桶)
            kv.Value.Sort((a, b) =>
            {
                var c = b.紧急等级.CompareTo(a.紧急等级);
                if (c != 0) return c;
            
                // ★ AI 减伤倾向：**只参与排序**，不动 真实收益 / 减伤百分点 / 盾倍率 / 本地分
                //   （审查文档第 5/8/19 节：AI 只表达「我现在更看重它多少」）
                //   紧急时偏置恒为 0（本地硬规则优先）；盾第一版不加偏置。
                var sa = a.本地分 + HealerACR.Common.Ai倾向.减伤偏置(a.是盾, a.紧急等级 > 0);
                var sb = b.本地分 + HealerACR.Common.Ai倾向.减伤偏置(b.是盾, b.紧急等级 > 0);
                return sb.CompareTo(sa);
            });

        // 每桶先取到自己的上限
        var 取 = new Dictionary<类别, List<候选>>();
        var 总 = 0;
        foreach (var kv in 桶)
        {
            var 上 = Math.Min(桶上限(kv.Key), kv.Value.Count);
            var l = kv.Value.GetRange(0, 上);
            取[kv.Key] = l;
            总 += l.Count;
        }

        // 总数超了 -> 从"最可牺牲"的桶开始砍（每桶至少留 1 个）
        if (总 > 最多)
        {
            var 序 = new List<类别>(取.Keys);
            序.Sort((a, b) => 回收序(a).CompareTo(回收序(b)));

            // 第一轮：不动紧急
            foreach (var 类 in 序)
            {
                if (总 <= 最多) break;
                if (类 == 类别.紧急) continue;
                var l = 取[类];
                while (总 > 最多 && l.Count > 1)
                {
                    l.RemoveAt(l.Count - 1);
                    总--;
                }
            }

            // 第二轮：还超（各桶都只剩 1 个）才动紧急
            foreach (var 类 in 序)
            {
                if (总 <= 最多) break;
                var l = 取[类];
                while (总 > 最多 && l.Count > 1)
                {
                    l.RemoveAt(l.Count - 1);
                    总--;
                }
            }
        }

        // ── 汇总，顺序 = 重要度 ──
        //   [!] 顺序影响 C1/C2 的编号，而 AI 倾向选**先看到的**。
        //      所以救急/功能放前面，输出放最后 —— 与"漏了的代价"一致。
        var 结果 = new List<候选>();
        foreach (var 类 in new[] { 类别.紧急, 类别.功能, 类别.减伤, 类别.治疗, 类别.输出 })
            if (取.TryGetValue(类, out var l))
                结果.AddRange(l);

        return 结果;
    }

    /// <summary>类别名（给 Prompt 用）</summary>
    private static string 类名(类别 c) => c switch
    {
        类别.紧急 => "救急",
        类别.功能 => "功能",
        类别.减伤 => "减伤",
        类别.治疗 => "治疗",
        类别.输出 => "输出",
        _ => "其他",
    };

    // ==================== 减伤候选 ====================

    /// <summary>
    /// **减伤 / 护盾** —— 本轮审阅第 7/8 条指出的空缺。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 为什么必须补上：
    ///      `类别.减伤` 和它的桶上限早就定义了，但**没有任何地方往桶里放** ——
    ///      于是 AI 策略层被要求判断"未来几秒有没有高伤害、该不该提前减伤"，
    ///      而**候选列表里根本没有减伤可选**，它只能去猜技能 ID。
    ///      => 候选架构在减伤这条路上等于没生效。
    ///
    ///  [!] 施法目标各有不同（这正是 `TargetMode` 要解决的问题）：
    ///      · 团队减伤  -> **自己**（以自己为中心的范围效果）
    ///      · 个人减伤  -> **自己**（`Res_Mitigation.cs` 里 `slot.Add(spell)` 无目标）
    ///      · 护盾前置  -> **自己**（贤者的均衡之类）
    ///      · 单体盾    -> **队友**（这部分在治疗候选里已经覆盖）
    ///
    ///  [!] 不做"该不该交"的判断 —— 那是 AI 的事。
    ///      这里只保证"**能用**的减伤出现在候选里"，让 AI 有得选。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 加减伤候选()
    {
        var 技能表 = 职业表();
        if (技能表 == null) { _诊断减伤 = "拿不到职业技能表"; return; }

        var 进前 = _当前表.Count;

        // [!] 用"时间轴说接下来有大伤害"当**加分项**而不是门槛 ——
        //     门槛会让 AI 在"时间轴没数据"的副本里完全看不到减伤选项
        //     （而时间轴只覆盖 45% 的副本）。
        var 要来大伤害 = false;
        try { 要来大伤害 = HealerACR.Timeline.TimelineManager.未来有减伤(5f); } catch { }
        if (!要来大伤害)
        {
            try { 要来大伤害 = HealerACR.Common.伤害预测.要预铺(5f); } catch { }
        }

        void 一个(string 标签, uint id, int 紧急 = 0, bool 群体 = false)
        {
            if (id == 0) return;
            try
            {
                if (!SpellUtil.已解锁(id)) return;
                // [!] 放宽为「即将可用」—— 候选是备货（给 2~3 个 GCD 后），
                //     用「此刻能不能放」筛会把「马上就好」的技能全砍掉。
                if (!SpellUtil.即将可用(id, SpellUtil.建议视野秒())) return;
            }
            catch { return; }

            foreach (var c in _当前表)
                if (c.技能Id == id) return;      // 去重

            // ══════════════════════════════════════════════════════════════
            //  ★ 减伤候选要带【数字】★ —— "交了这个能少掉多少"
            //
            //  [!] 用户要求："总体还是以数字说话"。
            //      原来这里只给 `本地分`，AI 看到的是：
            //          `C3=野战治疗阵[减伤] 单体 能力技 瞬发`
            //      **一个数字都没有** —— 它知道"该预铺"（预测段有数字），
            //      但无从判断"哪个减伤更值"。
            //
            //  [!] **必须把技能 ID 转成 Buff ID** ★（差点写错）：
            //      `伤害预测.减伤收益()` 走 `减伤乘数.加上()`，
            //      后者查的是 `减伤状态表.减伤[减伤Buff]` —— **键是 Buff ID**。
            //      直接传技能 ID 会永远查不到 => 收益恒为 0 => 等于没加。
            //      => 先 `AuraIds.技能转Buff(id)`。
            //
            //  [!] 护盾类技能不在"减伤乘数"里（盾是"先扣盾再扣血"），
            //      所以它们算出来是 0 —— 那不表示"没用"，
            //      而是"这个模型不覆盖盾"。用 `要预铺` 的时机信息补。
            // ══════════════════════════════════════════════════════════════
            // [!] **必须传真实目标** —— 传 null 会永远返回 0（已核实）：
            //     `减伤收益 -> 加减伤后的预计 -> if (目标 == null) return 0f`
            //     签名带 `?` 不代表可以用 null。这是我自己写错过一次的地方。
            //
            //     目标取**坦克**（见下），
            //     那正是"减伤最该保护的人"和"值不值得交"的判断对象。
            var 收益 = 0f;
            try
            {
                var buff = AuraIds.技能转Buff(id);
                if (buff != 0)
                {
                    // ══════════════════════════════════════════════════════════════
                    //  ★ 靶子取**坦克**，不是全队最危险的人 ★
                    //
                    //  [!] 原来取 `最危险(5f, 1f)` = 全队最缺血的那个。
                    //      但提示词第 21 条规则明确写着：
                    //          「预铺减伤**只给坦克**（绿帽 / 水流幕 / 天星交错 / 输血）。
                    //            给非坦克铺没意义」
                    //      ==> 拿全队最危险的人去算减伤收益，算的对象和实际要铺的对象**不是一个人**。
                    //      渲染出来的 `6s<数字>` 会偏大（DPS 血比坦克少，比例掉得更多），
                    //      AI 可能因此高估这个减伤的价值。
                    //
                    //  [!] 没有坦克时（四人本 T 死了 / 单人）退回全队最危险的人 ——
                    //      那种场合我们就是承伤位，取谁都比取 0 好。
                    // ══════════════════════════════════════════════════════════════
                    var 靶子 = HealTargetHelper.队伍里的坦克()
                               ?? HealerACR.Common.伤害预测.最危险(5f, 1f);
                    if (靶子 != null)
                        收益 = HealerACR.Common.伤害预测.减伤收益(靶子, buff, 5f);
                }
            }
            catch { }

            // [!] **地面技能必须标成 `地面`，不能一律 `自己`**（审计 P0-2，我核实确认）——
            //     野战治疗阵 / 庇护所 / 地星 这类是**地面放置**，本地用 `new Spell(id, 落点)` 放；
            //     标成 `自己` 会让 Build 走 `SpellTargetType.Self` == 放在自己脚下，
            //     **和本地放的不是同一个动作**。
            //     非地面减伤（节制 / 坚角清汁 / 命运之轮…）仍然是自己施放。
            // ⚠️ 这个局部量必须算在**对象初始化器外面**（`{ }` 里不能写语句）。
            var 这个减伤是地面 = false;
            try { 这个减伤是地面 = 技能数据.是地面技能(id); } catch { }

            _当前表.Add(new 候选
            {
                类 = 类别.减伤,
                紧急等级 = 紧急,
                施法目标模式 = 这个减伤是地面 ? 目标模式.地面 : 目标模式.自己,
                技能Id = id,
                技能名 = string.IsNullOrEmpty(取技能名(id)) ? 标签 : 取技能名(id),
                能力技 = true,                    // 减伤基本都是能力技
                瞬发 = true,
                // [!] 团队/个人减伤是"降低受到的伤害"，不是盾（吸收）
                //     两者都算"预防"，但机制不同 —— 描述里都不打"盾"标记，
                //     靠技能名 + 类别.减伤 区分。
                // [!] **群体 / 是盾 都要判，不能写死**（H7，审计确认）——
                //     ① 团队减伤原来是单体（从不设 `群体`）==> AI 以为野战治疗阵/节制是单体
                //     ② 写死 `是盾 = false` 对**团队减伤**是对的（降低伤害 ≠ 吸收），
                //        但白魔「神祝祷」同时是 `个人减伤` **和** `单体盾` ——
                //        本地 `Res_HealShield` 是把它当**盾**铺给坦克的，
                //        这里说它不是盾 ==> **两处口径不一致**。
                群体 = 群体,
                是盾 = (id == 技能表.单体盾 || id == 技能表.群体盾),
                减伤百分点 = (int)MathF.Round(收益 * 100f),
                是地面技能 = 这个减伤是地面,

                // ★ 数值：交出去能少掉几个百分点（百分点，不是比例）★
                //   [!] 用 `预测6秒` 这个字段承载 —— 描述() 会把它渲染成 `6s<数字>`。
                //      语义上它是"未来这段窗口内的影响"，和 6 秒窗口一致。
                // [!] **不要再填 `预测6秒`**（H7）——
                //     那是治疗量字段，图例里写着「这几秒内累计能回多少（HoT 和直疗）」，
                //     把减伤百分点塞进去会让 AI 读成"回 8 点血"。
                //     数字改由 `减伤百分点` 承载，`描述()` 渲染成 `减伤8%`。
                // 预测6秒 = (int)MathF.Round(收益 * 100f),   // <- 已废弃，见上

                // [!] 没数据时给 1.0（**不低于输出**），
                //     这样减伤在"没有时间轴数据"时也进得了桶
                //     —— 桶是分类的，本来就不会互相挤，这里只是让它在桶内排前面。
                //     有收益数字时让它排更前面（收益越大越该交）。
                本地分 = 要来大伤害 ? 2.0f + 收益 * 10f : 1.0f + 收益 * 10f,
            });
        }

        一个("团队减伤", 技能表.团队减伤, 群体: true);
        一个("个人减伤", 技能表.个人减伤);
        // ══════════════════════════════════════════════════════════════
        //  [!] **不把 `护盾前置` 当独立候选**（本轮核实的一处矛盾）
        //
        //      它原来在这里被当成【功能候选】给 AI：
        //          一个("护盾前置", 技能表.护盾前置);
