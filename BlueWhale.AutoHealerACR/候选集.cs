using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;
using HealerACR.Common;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// **候选动作集** —— 本地把"当前合法且值得考虑的动作"算成一组**不可变快照**。
///
/// ══════════════════════════════════════════════════════════════════
///  ★ 为什么需要它（第一轮审阅第 9/10/24 条）★
///
///    现状：`AI -> SkillId`。白名单只能证明"这个技能本职业有"，
///    不能证明"这个局面下该用它"。
///    ⇒ 本类把游戏世界压缩成一组**真实、合法、可执行**的候选，AI 只做取舍。
///
///  ══════════════════════════════════════════════════════════════════
///  ★★ 第二轮审阅指出的两个 P0（本类已按它重构）★★
///
///  【P0-1】`C1/C2` 原来只是**排序后的位置** —— 不是身份
///      `_本帧.Sort(...)` 之后按位置重编号，缓存 300ms 一过就重算。
///      于是 AI 请求发出时选的是"C1 = 治坦克"，回来时 C1 已经变成"DoT Boss"
///      ⇒ **AI 的选择被执行成了另一个动作**。
///
///      ⇒ 修法：`候选Id` 由 **快照号 + 序号** 生成（形如 `S18231-3`），
///        **永不重编号**；解析时先认 `候选Id`，再兼容显示编号。
///        显示用的 `C1/C2` 仍然给 AI 看（好写好读）。
///
///  【P0-2】`_本帧` 是 `static List`，游戏线程 Clear/Add/Sort，
///      后台线程（AI 回复的续体）按编号查 ⇒ **完全没有同步**（lock 0 处）
///      —— 和本项目已经栽过两次的 bug 一模一样
///      （`AiDecisionLayer._队列`、`AiStrategyLayer.历史`）。
///
///      ⇒ 修法：对外只发**不可变快照**；后台线程只读它自己那份快照，
///         永远不碰正在被改的列表。
///
///  ★ 快照的生命周期 ★
///      每个快照按 `快照Id` 存进有界表（保留最近若干），
///      AI 回复回来时按**请求时记下的快照Id**去取 ——
///      取不到（太久远）就整个丢弃，**不做"用当前候选凑合"的猜测**。
/// ══════════════════════════════════════════════════════════════════
/// </summary>
public static class 候选集
{
    /// <summary>
    /// **候选类别** —— 决定它在分桶分配里进哪个桶。
    ///
    /// [!] 为什么需要分类（第三轮审阅第 4/5 条，实测成立的**设计缺陷**）：
    ///      原来 `Sort(按本地分) 后取前 8`。而 4 人本里
    ///      **一个单奶技能会给每个受伤队友各生成一个候选** ——
    ///      几个奶技就把 8 个名额占满，**伤害候选一个都进不来**
    ///      （AI 永远看不到"可以打输出"，ACR 退化成只会奶）；
    ///      反过来输出分高（威力/100 常常大于治疗分）时，
    ///      复活 / 驱散 / 救急会被裁掉 ——
    ///      而 Prompt 里还写着"必须奶满"，AI 却找不到对应候选。
    ///
    ///      根因：治疗决策的价值**不是可比单一标量**。
    ///      "奶满坦克"漏了会死人，"补一个 DoT"漏了只是少输出 ——
    ///      用同一个分数排序，必然在某个局面上把该保的挤掉。
    ///      => 必须**分类保底**，不能全局排序。
    /// </summary>
    public enum 类别
    {
        紧急,     // 濒死 / 必须奶满 / 复活 —— **漏了会死人**
        功能,     // 驱散等辅助
        减伤,     // 团队 / 个人减伤
        治疗,     // 常规治疗 / 护盾
        输出,     // 伤害 / DoT
    }

    /// <summary>
    /// **施法目标模式** —— 技能实际往哪儿放。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么必须和 `TargetId` 分开（本轮审阅第 4/5/6 条）★
    ///
    ///    原来只有一个 `TargetId`，它被迫同时表达两件事：
    ///      ① **技能往谁身上放**（施法目标）
    ///      ② **为什么选它**（判断依据）
    ///
    ///    于是出了两个真 bug（都已核实）：
    ///
    ///    【群疗】项目里的正确写法是（`Res_Heal.cs`）：
    ///        slot.Add(new Spell(_t.群体治疗GCD, SpellTargetType.Self));
    ///      群疗是**以自己为中心**的范围技 —— 目标是你自己。
    ///      而"最缺血的队友"只是**为什么现在该群疗**的理由。
    ///      => 候选把那个队友当成了施法目标，群疗会以他为中心放，
    ///         别人不在范围内就治不到。
    ///
    ///    【个人减伤】项目里（`Res_Mitigation.cs`）：
    ///        slot.Add(spell);        // 没有目标参数 = 自己施放
    ///      而 `判目标类型` 把它归到"队友"，会去找"血最少的队友"。
    ///
    ///  ⇒ 修法：施法目标由 `TargetMode` 决定，`TargetId` 只在
    ///     `TargetMode` 是 `队友` / `敌人` 时才有意义。
    ///     "为什么选它"单独放 `关注目标`。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public enum 目标模式
    {
        /// <summary>对自己施放（群疗 / 群盾 / 团队减伤 / 个人减伤 / 地面放置）</summary>
        自己,

        /// <summary>对 `TargetId` 指定的队友施放（单奶 / 单体盾 / 驱散 / 复活）</summary>
        队友,

        /// <summary>对 `TargetId` 指定的敌人施放（输出 / DoT）</summary>
        敌人,

        /// <summary>地面技能 —— 没有施法目标，落点由本地算</summary>
        地面,
    }

    /// <summary>一个候选动作（构建后不再改动）</summary>
    /// <summary>
    /// [!] **不可变**：字段全是 `{ get; init; }` —— 构造完就不能改。
    ///     这样快照之间共享引用也不会被谁偷偷改掉（外部审阅第 26 条），
    ///     而且"AI 选中的候选"与"执行时读的候选"必然是同一份。
    /// </summary>
    public sealed record 候选
    {
        /// <summary>
        /// **稳定身份** —— `S{快照Id}-{序号}`，形如 `S18231-3`。
        /// [!] 这是**唯一**用于解析的身份；位置编号（C1/C2）只是给人看。
        /// </summary>
        public string 候选Id { get; init; } = "";

        /// <summary>显示用短编号（C1/C2…）—— **不参与解析身份**</summary>
        public string 编号 { get; init; } = "";

        /// <summary>类别 —— 决定分桶（见 `类别` 的说明）</summary>
        public 类别 类 { get; init; } = 类别.治疗;

        public uint 技能Id { get; init; }
        public string 技能名 { get; init; } = "";

        /// <summary>
        /// **技能实际往哪儿放** —— 执行层照这个放。
        /// [!] `队友` / `敌人` 时才看 `目标Id`；`自己` 时不看。
        /// </summary>
        public 目标模式 施法目标模式 { get; init; } = 目标模式.队友;

        /// <summary>施法目标 id（只在 `施法目标模式` 是 队友/敌人 时有效）</summary>
        public ulong 目标Id { get; init; }
        public string 目标名 { get; init; } = "";

        // ══════════════════════════════════════════════════════════════
        //  ★ 关注目标 —— "为什么选这个候选" ★
        //
        //  [!] 和 `目标Id` 的区别（本轮审阅第 5 条）：
        //      `目标Id` = 技能往谁身上放。
        //      `关注目标` = 这个候选是**因为谁**才被提出来的。
        //
        //      群疗是最好的例子：施法目标是自己，但"因为坦克快死了"
        //      才是选它的理由。原来这两件事挤在一个字段里，于是群疗
        //      被打到了坦克身上。
        //
        //  [!] 它**只用于显示和解释**，执行层不读它。
        // ══════════════════════════════════════════════════════════════

        /// <summary>因为谁才提这个候选（0 = 无特定对象）。只给 AI 看。</summary>
        public ulong 关注目标Id { get; init; }

        /// <summary>关注目标的名字</summary>
        public string 关注目标名 { get; init; } = "";

        /// <summary>关注它的原因（一句话，给 AI 解释用）</summary>
        public string 关注原因 { get; init; } = "";

        public bool 群体 { get; init; }
        public bool 能力技 { get; init; }
        public bool 瞬发 { get; init; }

        /// <summary>
        /// **这个候选是护盾类**（盾的价值 ≠ 恢复量）。
        ///
        /// ══════════════════════════════════════════════════════════════════
        ///  [!] 为什么必须让 AI 知道（审查发现）★
        ///
        ///    本地 `治疗决策.打分()` 把盾的**预期吸收量直接加进"有效治疗"**
        ///    （`盾系数 0.5` + 覆盖比例加分）—— "盾"在本地有明确权重。
        ///
        ///    而候选描述里**没有任何盾的标记** =>
        ///    AI 只能靠**技能名回忆**"鼓舞激励之策是盾吗"——
        ///    正是我们一直在消除的"凭记忆"。
        ///
        ///  [!] 有它之后 AI 才能做这个判断：
        ///      "有人缺口 40%，但他**马上要挨一刀** → 该用盾（预防）
        ///        而不是纯治疗（补不上第二刀）"。
        /// ══════════════════════════════════════════════════════════════════
        /// </summary>
        public bool 是盾 { get; init; }

        /// <summary>恢复力 / 威力（AOE 时是**总量** = 单体 × 命中数）</summary>
        public int 量 { get; init; }

        /// <summary>命中数（>1 表示 AOE 总量）</summary>
        public int 命中数 { get; init; } = 1;

        /// <summary>单体威力（AOE 时给出，避免把总量误当单体值）</summary>
        public int 单体威力 { get; init; }

        /// <summary>目标当前缺口（% 最大血，0~1）</summary>
        public float 缺口 { get; init; }

        /// <summary>预计过量（0~1）</summary>
        public float 过量 { get; init; }

        // ══════════════════════════════════════════════════════════════
        //  ★ 治疗数值模型（第三轮审阅第 16 条）★
        //
        //  [!] 为什么不能只给"量"：
        //      一个瞬发治疗 3000 和一个 HoT 总量 6000 **不能直接比较** ——
        //      前者立刻回 3000，后者要十几秒才回完。
        //      救命看的是"这 3 秒能回多少"，不是"总共能回多少"。
        // ══════════════════════════════════════════════════════════════

        /// <summary>**即时**治疗量（不含 HoT）—— 救命看它，不是看总量</summary>
        public int 即时治疗 { get; init; }

        /// <summary>3 秒内预计总治疗（即时 + 这 3 秒的 HoT 跳数）</summary>
        public int 预测3秒 { get; init; }

        /// <summary>6 秒内预计总治疗</summary>
        public int 预测6秒 { get; init; }

        public int 耗蓝 { get; init; }
        public float 冷却 { get; init; }
        public int 资源 { get; init; }

        /// <summary>
        /// **紧急等级** —— 桶内优先级的**第一关键字**。
        ///
        /// ══════════════════════════════════════════════════════════════
        ///  [!] 为什么不能只看本地分（本轮审阅第 11 条）：
        ///      紧急桶上限 3，而有四类东西都往里挤：
        ///          必须奶满 / 复活 / 濒死 / 普通紧急治疗
        ///      纯按本地分排，"必须奶满"**可能被挤出去** ——
        ///      而 Prompt 里写着"必须奶满优先级最高"。
        ///      => 提示词和候选列表互相矛盾，AI 想遵守也没有那个选项。
        ///
        ///  [!] 分级（数字只用于比较，不显示）：
        ///        1000  必须奶满   —— 不奶就是死，无条件最高
        ///         900  复活       —— 少一个人可能就打不过
        ///         800  濒死       —— 血量极低
        ///           0  其余
        /// ══════════════════════════════════════════════════════════════
        /// </summary>
        public int 紧急等级 { get; init; }

        /// <summary>本地算分（只用于排序，**不给 AI 看**）</summary>
        public float 本地分 { get; init; }

        /// <summary>
        /// **本地 `治疗决策.打分()` 的真实分数**（H2）—— 给 AI 看，帮它理解本地的取舍。
        ///
        /// [!] 和 `本地分` 的区别：`本地分` 是候选集自己的粗排公式
        ///     （`覆盖*2 - 过量*1.5`，上面写明「不给 AI 看」）；
        ///     这个是 `选最优` **真正用的那个分**，含 AI 完全看不到的维度：
        ///     **GCD数**（缺口要几个 GCD 补满）/ 效率罚 / 盾吸收 / 过量折价 70% / 低蓝 ×2.5。
        ///
        /// [!] 在 `造()` 里算好（那里同时有技能对象和目标对象）——
        ///     候选集里**没有"按 id 找角色"的工具**，`描述()` 那边算不了。
        ///     负无穷 = 算不出来，`描述()` 就不渲染。
        /// </summary>
        public float 本地真实分 { get; init; } = float.NegativeInfinity;

        /// <summary>
        /// **减伤能少挨几个百分点**（H7）—— 只给减伤候选填，输出成 `减伤8%`。
        ///
        /// [!] 为什么不能借 `预测6秒`（原来就是这么干的）：
        ///     `预测6秒` 在图例里是「这几秒内**累计能回多少**（HoT 和直疗）」——
        ///     ==> AI 会把「少挨 8% 伤害」读成「回 8 点血」。
        /// </summary>
        public int 减伤百分点 { get; init; }

        /// <summary>
        /// **这个动作是不是「地面放置」**（罩子 / 地星 / 庇护所 / 礼仪之铃…）。
        ///
        /// ══════════════════════════════════════════════════════════════════
        ///  [!] 为什么必须有它（第三方审计 P0-2，我核实确认）：
        ///
        ///      原来减伤候选一律 `施法目标模式 = 目标模式.自己`，
        ///      而 Build 只有 `自己/队友/敌人` 三个分支 —— **没有 `地面`**
        ///      ==> 地面技能被放成 `SpellTargetType.Self`（放在**自己脚下**），
        ///          而本地是 `new Spell(团队减伤, 落点)`。
        ///      ==> **AI 选的这个动作和本地那个动作不是同一个动作。**
        ///
        ///  [!] **为什么只存是不是地面、不存落点**：
        ///      候选要经 AI 往返（≈2.6 秒）才执行，
        ///      而落点读的是**当下**的敌人位置 ——
        ///      冻结在候选里的落点**执行时已经过期**。
        ///      ==> 落点必须在 `Build()` 时**现算**，
        ///          用和本地 resolver **同一个** `敌人移动检测.地面技能位置()`。
        /// ══════════════════════════════════════════════════════════════════
        /// </summary>
        public bool 是地面技能 { get; init; }

        /// <summary>
        /// **这一条是「盾」，需要先放前置**（贤者：先 `均衡` 再 `预后`）。
        ///
        /// ══════════════════════════════════════════════════════════════════
        ///  [!] 为什么必须和 `是盾` 分开（用户指出的问题）：
        ///
        ///      贤者的盾和纯奶**共用同一个基础 id** —— 这是游戏机制，不是笔误：
        ///        `SageACR.cs:140`  治疗池：预后 = **纯治疗 300**，`是盾 = false`
        ///        `SageACR.cs:239`  技能表：`群体盾 => 预后`（靠 `均衡` 变形态）
        ///        `SageACR.cs:235`  注释：「写基础 id，靠 `SpellUtil.当前形态()`
        ///                             让游戏自己变成均衡版」
        ///
        ///      ==> **不能按 id 判断这是不是盾** —— `预后` 两个条件都成立。
        ///          按 id 判的后果：AI 建议「预后」当纯奶放时会被加上 `均衡`，
        ///          **把纯奶变成盾，方向反了**（我上一步就写成了这样）。
        ///
        ///  [!] 所以判据改为**看意图**：由候选自己携带我这一条是不是盾。
        ///      · 治疗池出来的：`false`（预后 走纯奶）
        ///      · 盾候选出来的：`true`（先均衡 -> 再预后）
        /// ══════════════════════════════════════════════════════════════════
        /// </summary>
        public bool 是盾技能 { get; init; }
    }

    /// <summary>
    /// **候选快照** —— 一次生成的结果，构造后不可变。
    /// [!] AI 请求与响应之间传递的就是它。
    /// </summary>
    public sealed class 快照
    {
        public long 快照Id;
        public long 生成时刻;
        public IReadOnlyList<候选> 候选表 = Array.Empty<候选>();

        ///
        /// [!] 为什么挂在快照上、而不是独立的静态字段（用户实测的矛盾）：
        ///      独立字段会和快照**对不上** —— `生成()` 有 300ms 缓存，
        ///      缓存命中时返回**旧快照**，但那些字段可能已被别处的
        ///      新一轮生成刷新过。调试窗于是显示出
        ///      "0 个候选 + 四个生成器都有产出" 这种自相矛盾的东西。
        ///
        ///      挂进快照之后，**结构上不可能不同步**。
        /// </summary>
        public string 生成诊断 = "";

        /// <summary>按**稳定身份**取候选</summary>
        public 候选? 按Id(string? id)
        {
            if (string.IsNullOrWhiteSpace(id)) return null;
            var 要 = id.Trim();
            foreach (var c in 候选表)
                if (string.Equals(c.候选Id, 要, StringComparison.OrdinalIgnoreCase))
                    return c;
            return null;
        }

        /// <summary>按**显示编号**取候选（C1/C2）—— 兼容 AI 直接回编号</summary>
        /// <summary>
    /// **按编号取候选（AI 可见投影）** —— 复审 ①（2026-10-03）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  [!] 问题：编号是在**完整候选表**上分配的（`编号 = "C" + (i + 1)`），
    ///      `描述()` 只是**不显示**非 治疗/减伤 的候选 ⇒ 编号有洞，
    ///      AI 若幻觉输出 `C1`，就可能命中一个**被隐藏的**候选（例如紧急治疗）✗
    ///
    ///  [!] 修法：解析侧加一道过滤 —— **只有 AI 可见类别（治疗 / 减伤）能被编号命中** ✓
    ///      被隐藏的类别一律返回 null（终审的类别白名单与 AiHardGate 还会再拦一次 ✓）
    ///
    ///  [!] 还没做的部分（复审建议的完整投影快照）：把编号本身也改成
    ///      "先过滤 → 排序 → 重新编号"，让 AI 看到连续的 C1..Cn。
    ///      那一步要同时改编号分配与解析两侧，单独一版做 ✓
    /// ══════════════════════════════════════════════════════════════════
    public 候选? 按编号(string? 编号)
    {
        try
        {
            var c = 按编号_内部(编号);
            if (c == null) return null;
            if (c.类 == 类别.治疗 || c.类 == 类别.减伤) return c;
            return null;   // ★ 被隐藏的候选不能被 AI 的编号命中
        }
        catch { return null; }
    }
    private 候选? 按编号_内部(string? 编号)
        {
            if (string.IsNullOrWhiteSpace(编号)) return null;
            var 要 = 编号.Trim();
            foreach (var c in 候选表)
                if (string.Equals(c.编号, 要, StringComparison.OrdinalIgnoreCase))
                    return c;
            return null;
        }

        /// <summary>先按稳定 Id、再按显示编号（两种都接受）</summary>
        public 候选? 解析(string? 引用) => 按Id(引用) ?? 按编号(引用);
    }

