using System.Text;
using AEAssist;
using AEAssist.Extension;
using AEAssist.Helper;
using HealerACR.Common;
using HealerACR.Timeline;

namespace BlueWhale.AutoHealerACR;

/// <summary>
/// 局面采集 —— 把"游戏里实际发生了什么"翻译成 AI 能读的文字。
///
/// **这是整个 AI 接管的地基。**
/// 喂给 AI 的信息越全，它的决策越靠谱；信息不够它就只能在幻觉里编。
///
/// 采集范围对照 HealerACR 的调试页和 同类 ACR 的 Overlay.DrawDev ——
/// 那些面板上能看到的东西，AI 也应该能看到。
/// </summary>
public static class AiSituation
{
    /// <summary>
    /// 局面描述的最大长度（字符）。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要上限 ★
    ///
    ///    这个字符串**每轮都要全量重发**（初始化 / 策略层 / 决策层），
    ///    而且现在包含：技能清单（带 CD/充能/蓝耗）+ 类别说明
    ///    + 每个队友的状态 + 敌人身上的状态 —— 内容比原来多了一大截。
    ///
    ///    太长会：① 占 token（花钱、变慢）
    ///            ② 把真正重要的**动态状态**淹在静态说明里
    ///               （模型对长提示词的中间部分注意力最差）
    ///
    ///  ★ 截断策略：**砍静态、保动态** ★
    ///
    ///    超长时优先截掉「技能类别说明」那一段 —— 它是**每轮都一样**的
    ///    静态参考，信息量最低；而血量 / 状态剩余时间 / 敌人 这些
    ///    **每轮都在变**的东西必须保住。
    ///
    ///    （如果连砍掉静态部分都还超长，就按总长硬截，
    ///      并在末尾标明"已截断"——绝不静默截断。）
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private const int 最大长度 = 6000;


    /// <summary>
    /// **AI 实际收到了什么** —— 逐段核对局面报告的内容，压成一行。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么需要它 ★
    ///
    ///  ── 光看代码会以为"AI 当然知道" ──
    ///     `采集()` 里有 `采副本` 和 `采时间轴` 两段，
    ///     光读代码会认为"副本名和时间轴都喂给它了"。
    ///     但这两段读的是**调用那一刻**的运行时状态 ——
    ///     初始化跑在开怪前，那时时间轴还没装载（`确保当前时间轴` 只在战斗中调），
    ///     于是 AI 收到的是"这个副本没有匹配到时间轴"。
    ///     日志里看不出区别，因为报告照样生成、照样发出去。
    ///
    ///  ── 所以要有"确认收到的回执" ──
    ///     这个方法**逐段检查报告里到底有没有内容**，输出一行人可读的核对结果。
    ///     它是**只读**的：只调 `采集()` 再看结果，不改变任何状态。
    ///
    ///  ⚠️ 检查项里"时间轴"和"可选技能"最关键：
    ///      · 时间轴 —— 决定 AI 能不能预判机制
    ///      · 可选技能 —— 决定 AI 能不能给出**放得出来**的技能 ID
    ///     这两个为空时 AI 仍然会回话，只是回的话没用。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    public static string 上下文核对()
    {
        try
        {
            var 全文 = 采集();

            string 有(string 标)
            {
                try
                {
                    var i = 全文.IndexOf(标, StringComparison.Ordinal);
                    if (i < 0) return "缺";

                    var j = 全文.IndexOf("\n【", i + 1, StringComparison.Ordinal);
                    var 段 = j < 0 ? 全文.Substring(i) : 全文.Substring(i, j - i);

                    // 段落里除了标题还有没有实质内容
                    var 行 = 段.Split('\n');
                    var 实 = 0;
                    foreach (var l in 行)
                    {
                        var s = l.Trim();
                        if (s.Length == 0) continue;
                        if (s.StartsWith("【")) continue;
                        if (s.StartsWith("（")) continue;   // "（没有…）"这类否定说明
                        实++;
                    }

                    return 实 > 0 ? $"{实} 行" : "空";
                }
                catch { return "?"; }
            }

            var 职业 = "";
            var 等级 = 0;
            try { 职业 = Core.Me.ClassJob.Value.Name.ToString(); } catch { }
            try { 等级 = Data.PlayerCurrentLevel; } catch { }

            var 地图 = TimelineManager.实时副本Id();
            var 副本 = 地图 == 0 ? "未知" : 地名.解析(地图, 是副本: 地名.是副本(地图));

            // ⚠️ 先把各段结果算到局部变量再拼 ——
            //    插值字符串的 `{}` 里**不能直接写双引号字符串字面量**
            //    （C# 解析器会把它当成字符串的结束），所以 `有("【副本】")`
            //    这种写法在 `$"..."` 内部是不合法的。
            var 副本段 = 有("【副本】");
            var 时间轴段 = 有("【副本与机制时间轴】");
            var 技能段 = 有("【可选技能");
            var 队伍段 = 有("【队伍】");
            var 敌人段 = 有("【敌人】");

            return $"{职业} Lv{等级} · {副本}" +
                   $" | 副本段 {副本段}" +
                   $" | 时间轴段 {时间轴段}" +
                   $" | 可选技能段 {技能段}" +
                   $" | 队伍段 {队伍段}" +
                   $" | 敌人段 {敌人段}" +
                   $" | 报告 {全文.Length} 字符";
        }
        catch (Exception e)
        {
            return "核对失败：" + e.Message;
        }
    }

    /// <summary>
    /// **一句话说清"我认出了什么"** —— 副本 / 职业 / 等级。
    ///
    /// ╔══════════════════════════════════════════════════════╗
    ///  ★ 设计意图 ★
    ///    "进本后 ai 初始化成功要输出识别到什么副本什么职业什么等级"
    ///
    ///  ── 为什么要单独给这三个 ──
    ///    它们是**识别结果**，不是"AI 说了什么"。
    ///    初始化成功只说明"请求通了"，而用户真正想知道的是
    ///    **"它认对了吗"** —— 进的是不是这个本、认的是不是这个职业、
    ///    等级读得对不对（尤其是**等级同步**时，面板等级和实际生效等级不同）。
    ///    这三个错了，后面 AI 说得再对也没用。
    ///
    ///  ⚠️ 和 `采集()` 里那段的关系：
    ///     这里**复用同一批读法**（实时副本 ID + `Resolve副本名`），
    ///     不另写一套 —— 否则会出现"面板显示的和 AI 看到的不一致"
    ///     （那种 bug 最难查：两边都"看起来对"）。
    ///     区别只是这里**不带地图 ID**（那是给 AI 看的原始数据，
    ///     用户要的是人话）。
    ///
    ///  ⚠️ 读不到时**照实说**，不要编 —— 比如不在副本里就说"不在副本"。
    /// ╚══════════════════════════════════════════════════════╝
    /// </summary>
    public static string 识别摘要()
    {
        try
        {
            var sb = new System.Text.StringBuilder();

            // ── 职业 + 等级 ──
            var 职业 = "";
            try { 职业 = Core.Me.ClassJob.Value.Name.ToString(); } catch { }

            var 等级 = 0;
            try { 等级 = Data.PlayerCurrentLevel; } catch { }

            sb.Append(string.IsNullOrWhiteSpace(职业) ? "职业未知" : 职业);
            sb.Append($" Lv{等级}");

            // ── 副本 / 所在地 ──
            //
            // ⚠️ 用 `HealerACR.Common.地名`，**不要用 `记忆库.Resolve副本名`** ——
            //    后者的键是 **ContentFinderCondition 行号**，
            //    而 `实时副本Id()` 返回的是 **TerritoryType**，两套编号不相干。
            //    现象：站在雪都房区（TerritoryType 979）时，
            //    CFC 表里恰好有个同号的"异闻阿罗阿罗岛" → 显示出**完全错误
            //    但看起来合理**的副本名。那种错最难发现。
            //    详见 `地名` 类的长注释。
            var 地图 = TimelineManager.实时副本Id();
            if (地图 != 0)
            {
                // 先判断"是不是真的在副本里"——副本和房区/野外的表不同
                var 在副本 = 地名.是副本(地图);

                sb.Append(" · ");
                sb.Append(在副本
                    ? 地名.解析(地图, 是副本: true)
                    : "在 " + 地名.解析(地图));
            }
            else
            {
                // ⚠️ 读不到区域 ID 是**正常情况**（登录中 / 过场），
                //    不是错误 —— 别让它像出问题了。
                sb.Append(" · 区域未知");
            }

            return sb.ToString();
        }
        catch (Exception e)
        {
            return "（识别失败：" + e.Message + "）";
        }
    }

    /// <summary>静态段落的起始标记（超长时从它开始砍）</summary>
    private const string 静态段标记 = "【技能类别说明";

    public static string 采集()
    {
        var sb = new StringBuilder();

        采副本(sb);
        采自己(sb);
        采资源(sb);
        采队友(sb);
        采必须奶满(sb);      // ★ 致死机制：必须放在队友之后、敌人之前 —— 它是最高优先信息
        采敌人(sb);
        采坦克压力(sb);

        // ⚠️ **技能清单必须排在「时间轴」之前**（这里调整过，别改回去）。
        //
        //    原因：`控制长度()` 超长时是**从后往前硬截**的。
        //    而技能清单是**硬性必需**的 —— 阶段 B 只能从清单里的 ID 选，
        //    清单被截掉 AI 就只能编 ID，整轮白问。
        //
        //    而「机制预告」是新增的**增强信息**（最多约 800 字符），
        //    在极端情况下被截掉只是"少了个参考"，不会让整轮失效。
        //    ⇒ 必需信息在前，增强信息在后。
        采可选技能(sb);

        采时间轴(sb);
        采记忆库(sb);        // ★ 放最后：它是"参考"，前面才是"当前事实"

        return 控制长度(sb.ToString());
    }

    // ==================== 记忆库 ====================

    /// <summary>
    /// 把「记忆库」里与当前局面相关的结论拼进提示词。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 这是用户要的最后一环 ★
    ///
    ///    "每次初始化的时候先提供正常提示词然后要提供记忆库优化ai逻辑"
    ///
    ///    所以顺序是：**先当前局面（正常提示词），后记忆库（参考）**。
    ///    这个顺序不能反 —— 当前事实永远是第一位的，
    ///    记忆只是"过去人类怎么打的"，局面不同时必须以当下为准。
    ///
    ///  ── 放在这里而不是只放初始化 ──
    ///
    ///    这个方法被三处调用：初始化 / 策略层 / 决策层。
    ///    放在这里意味着**每一轮都带记忆**，不只是初始化那一次 ——
    ///    因为策略层和决策层才是真正做判断的地方，
    ///    只在初始化给一次的话，那一次之后就"忘"了。
    ///
    ///  ⚠️ 检索和拼接的逻辑在 `记忆库.取相关记忆`，
    ///     包括"职业必须相同 / 等级±10 / 同副本类型优先"这些规则。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 采记忆库(StringBuilder sb)
    {
        try
        {
            var 职业 = "未知";
            var 等级 = 1;
            try { 职业 = Core.Me.ClassJob.Value.Name.ToString(); } catch { }
            try { 等级 = Data.PlayerCurrentLevel; } catch { }

            var 记忆 = 记忆库.取相关记忆(职业, 等级, 对局记录.当前副本类型());
            if (string.IsNullOrWhiteSpace(记忆)) return;   // 没有相关记忆 → 不占篇幅

            sb.AppendLine(记忆);
        }
        catch { }
    }

    /// <summary>按 <see cref="最大长度"/> 控制提示词体积 —— 先砍静态，再硬截</summary>
    private static string 控制长度(string 全文)
    {
        if (全文.Length <= 最大长度) return 全文;

        // ① 先砍静态段（每轮一样的说明，信息量最低）
        var 切口 = 全文.IndexOf(静态段标记, StringComparison.Ordinal);
        if (切口 > 0)
        {
            var 砍掉静态 = 全文.Substring(0, 切口)
                           + "（技能类别说明已省略：本轮提示词过长，只保留动态局面）\n";

            if (砍掉静态.Length <= 最大长度) return 砍掉静态;

            全文 = 砍掉静态;
        }

        // ② 还超长 → **按段落重要性砍**，不是简单截尾巴
        //
        //  ⚠️ 这里原来是从末尾硬截。加了「机制预告」之后那样会砍错东西：
        //     末尾是记忆库（可丢）和**机制预告**（有用），
        //     而真正该先丢的是"离当前决策最远"的段落。
        //
        //  保留优先级（数字越小越先保留）：
        //     1 副本/自己/资源/队友/必须奶满   ← 当前事实，缺一不可
        //     2 敌人/坦克压力                 ← 当前事实
        //     3 可选技能                      ← 硬性必需（AI 只能从这里选 ID）
        //     4 机制预告                      ← 增强（能预判，但缺了也能反应式治疗）
        //     5 记忆库                        ← 参考（过去人类怎么打，最可丢）
        //
        //  做法：从**最可丢**的段落开始整段删，删到装得下为止。
        var 可丢段落 = new[]
        {
            // 记忆库 —— 由 记忆库.取相关记忆 生成，标题见那边的 AppendLine
            "【记忆库 ——",
            "【副本与机制时间轴】",
            // 坦克压力（有几行推断，不如"我自己/队友/必须奶满"硬）
            "【坦克压力 / 接战强度】",
            // 敌人段（新加了"其他敌人"列表后变长；它整段是最长的，
            // 但截掉它会让 AI 失去 DoT 判断依据 —— 所以**排在最后才丢**，
            // 前面那些丢了都还能靠治疗常识兜住）
            "【敌人】",
        };

        foreach (var 标 in 可丢段落)
        {
            if (全文.Length <= 最大长度) break;

            var i = 全文.IndexOf(标, StringComparison.Ordinal);
            if (i <= 0) continue;

            // 找到该段的结尾：下一个【 开头（段落都以【 起头）
            var j = 全文.IndexOf("\n【", i + 1, StringComparison.Ordinal);
            var 段尾 = j < 0 ? 全文.Length : j + 1;

            全文 = 全文.Substring(0, i)
                   + $"（{标.TrimStart('【')} 已省略：本轮局面描述过长）\n"
                   + 全文.Substring(段尾);
        }

        if (全文.Length <= 最大长度) return 全文;

        // ③ 实在还超长才硬截，但**必须标明**（静默截断会让 AI 以为"就这些"）
        return 全文.Substring(0, 最大长度)
               + $"\n（⚠️ 局面描述超长已截断，上面只到 {最大长度} 字符；"
               + "如信息不足请输出 0|数据不足）\n";
    }

    // ==================== 必须奶满（致死机制） ====================

    /// <summary>
    /// 采集「必须奶满」类机制。
    ///
    /// ⚠️ **必须明确告诉 AI"这不是按血线判断的"** ——
    ///    否则它会按常识回"目标血量健康，不需要治疗"，
    ///    而那正是这个机制最危险的地方（血看着健康，时间一到直接死）。
    ///
    /// 没有命中时**什么都不输出**（不留空段落污染提示词）。
    /// </summary>
    private static void 采必须奶满(StringBuilder sb)
    {
        try
        {
            var 文本 = 必须奶满.状态描述();
            if (string.IsNullOrWhiteSpace(文本)) return;   // 没有就不占篇幅

            sb.Append(文本);
            sb.AppendLine();
        }
        catch (Exception e)
        {
            sb.AppendLine("（必须奶满机制读取失败：" + e.Message + "）");
            sb.AppendLine();
        }
    }

    // ==================== 副本 ====================

    /// <summary>
    /// 采集"现在在哪个副本"。
    ///
    /// ⚠️ **只给事实，不给推测。**
    ///    副本 ID 和名字是游戏数据，AI 可以据此知道"这是哪个本"，
    ///    但**绝不能让它去"回忆"这个本的机制** —— 那是幻觉的源头。
    /// </summary>
    private static void 采副本(StringBuilder sb)
    {
        try
        {
            sb.AppendLine("【副本】");

            // 地图 ID —— **用实时读取，不用 TimelineManager.当前地图Id**
            //
            // ⚠️ 那个字段**只在战斗中**才更新（赋值点在 `确保当前时间轴()`，
            //    而它由 `更新(战斗毫秒)` 调用、`战斗毫秒 <= 0` 时直接 return）。
            //    所以战斗外它恒为 0 → 副本名根本不打印。
            //    而 AI 的**初始化**恰好发生在开怪之前 —— 正是最需要名字的时候。
            var 地图 = TimelineManager.实时副本Id();
            sb.AppendLine($"地图 ID：{地图}");

            // ══════════════════════════════════════════════════════════
            //  ★ 人类可读的副本名（"要让 ai 知道进的什么副本"）★
            //
            //  名字来源 DutyNames.json（由 tools\DutyDump 从游戏
            //  ContentFinderCondition 表导出，863 条）。
            //
            //  ⚠️ 给名字是**为了上下文**，不是为了让 AI 背机制 ——
            //     提示词里有专门一条禁止它凭副本名回忆机制（那是幻觉来源）。
            //     副本类型（四人/八人）会影响群奶人数判断，所以名字有用。
            // ══════════════════════════════════════════════════════════
            if (地图 != 0)
            {
                // ⚠️ 和 `识别摘要()` 走**同一个解析器**（`地名`）——
                //    否则会出现"面板显示的和 AI 看到的不一致"。
                //    两张表：副本表 + 地点表，都以 **TerritoryType** 为键。
                var 在副本 = 地名.是副本(地图);
                var 名 = 地名.解析(地图, 是副本: 在副本);

                sb.AppendLine(在副本 ? $"副本名：{名}" : $"所在地：{名}");
            }

            // ⚠️ 这里**不重复打时间轴状态** —— 详细内容在
            //    「【副本与机制时间轴】」那一段，两边都写会浪费长度预算。
            if (TimelineManager.时间轴在跑())
                sb.AppendLine($"时间轴：已加载 {TimelineManager.时间轴文件}");

            if (地图 == 0)
            {
                sb.AppendLine("（不在副本里 / 地图信息读不到）");
            }

            sb.AppendLine();
        }
        catch (Exception e)
        {
            sb.AppendLine("（副本信息读取失败：" + e.Message + "）");
