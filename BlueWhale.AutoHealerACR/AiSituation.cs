    // ==================== 队友 ====================

    private static void 采队友(StringBuilder sb)
    {
        try
        {
            sb.AppendLine("【队伍】");

            var 队友 = PartyHelper.CastableAlliesWithin30;
            if (队友 == null || 队友.Count == 0)
            {
                sb.AppendLine("（没有可施法的队友 —— 可能单人在打木桩）");
                sb.AppendLine();
                return;
            }

            // ⚠️ 这份列表**包含自己** —— 必须在表头说清楚，
            //    并且逐行标出来（见循环里的 [自己]）。
            //
            //    不标的话 AI 会凭空多数出一个人：
            //    实测回复"只有两名治疗（我学者 + 月時計）"，
            //    而"月時計"就是玩家自己 —— 报告里
            //    `月時計 [治疗]：100%` 看起来就像另一个治疗。
            //
            //    比"人数算错"更糟的是：AI 会据此判断"还有一个治疗能兜底"，
            //    于是倾向于少交技能 —— 这是会影响实际治疗的错。
            var 我 = Core.Me;
            var 表头自己数 = 队友.Count(r => r != null && r.GameObjectId == 我.GameObjectId);
            sb.AppendLine($"（共 {队友.Count} 行，**包含你自己**{(表头自己数 > 0 ? "，标了 [自己]" : "")}）");

            var 低血 = 0;
            var 危急 = 0;

            foreach (var r in 队友)
            {
                if (r == null) continue;

                var 比例 = r.MaxHp > 0 ? r.CurrentHp * 100f / r.MaxHp : 100f;

                // ⚠️ **先判自己** —— 自己是治疗的话，
                //    光看 `[治疗]` 标记 AI 会以为是"另一个治疗"。
                var 是自己 = false;
                try { 是自己 = r.GameObjectId == 我.GameObjectId; } catch { }

                var 标记 = "";
                try
                {
                    if (r.IsTank()) 标记 = "[坦克]";
                    else if (r.IsHealer()) 标记 = "[治疗]";
                }
                catch { }

                if (是自己) 标记 = "[自己]" + 标记;

                // ══════════════════════════════════════════════════════
                //  ★★ 无敌 / 假死标记 —— **不标会害 AI 犯错** ★★
                //
                //  ⚠️ 坦克开 `死斗` / `行尸走肉` / `超火流星` 时，
                //     **血量会被打到 1% 左右**（那是机制设计如此，
                //     因为那几秒它本来就不会死）。
                //
                //     不给标记的话，AI 看到「坦克 1%」**必然会建议急救** ——
                //     而本地层 `可以治()` 是**拒绝**治的，
                //     于是一轮 AI 建议被终审拦掉（白问一轮），
                //     还正是我们刚修过的"刷屏"来源。
                //
                //  ⇒ 标出来，AI 才知道"这个 1% 是正常的、别管他"。
                //
                //  ⚠️ `死而不僵`（811）是**例外**：那一段是**要奶**的，
                //     所以单独标成"该治"，不能和别的无敌混在一起
                //     （AuraIds.假死不治 的注释专门警告过这一点）。
                // ══════════════════════════════════════════════════════
                var 无敌标记 = "";
                try
                {
                    if (AuraIds.死而不僵 != 0 && r.HasAura(AuraIds.死而不僵))
                    {
                        无敌标记 = "  ⚠️**死而不僵（要奶这一段）**";
                    }
                    else if (r.处于假死状态())
                    {
                        无敌标记 = "  无敌中，**别治他也别给减伤**";
                    }
                }
                catch { }

                // ── 这个队友身上的状态（带剩余时间）──
                //   价值最高的是**盾**和**HoT**：
                //     · 盾还剩几秒 → 决定"要不要现在补"（快没了才补，满的别浪费）
                //     · HoT 还剩几秒 → 决定"他会自己回上来还是要我出手"
                //   这直接支撑"该不该再投一个治疗"的判断。
                var 状态 = CharacterExt.所有状态剩余(r)
                    .Where(x => x.剩余秒 >= 1f)
                    .OrderBy(x => x.剩余秒)
                    .Take(6)
                    .Select(x => $"{x.名} {x.剩余秒:F0}s")
                    .ToList();

                var 状态文本 = 状态.Count > 0 ? "  状态：" + string.Join("、", 状态) : "";

                sb.AppendLine($"  {r.Name}{标记}：{比例:F0}%{无敌标记}{状态文本}");

                // ⚠️ **不把自己算进人数** ——
                //    这两个数是给 AI 判断"压力多大"用的，
                //    把自己算进去会显得队伍更危险（凭空多一个低血的人），
                //    而自己的血量在【我】那一段里已经单独给过了。
                if (!是自己)
                {
                    if (比例 <= 70f) 低血++;
                    if (比例 <= 35f) 危急++;
                }
            }

            sb.AppendLine();
            sb.AppendLine($"低于 70%：{低血} 人（不含自己）");
            sb.AppendLine($"低于 35%：{危急} 人（不含自己）");

            // 坦克单独列 —— 治疗最关心它
            var 坦克 = HealTargetHelper.血量最低的坦克();
            if (坦克 != null)
            {
                sb.AppendLine($"最危险的坦克：{坦克.Name}（{坦克.血量比例() * 100f:F0}%）");
            }

            // 待复活 / 待驱散
            var 待复活 = HealTargetHelper.待复活队友();
            if (待复活 != null) sb.AppendLine($" 有队友倒地待复活：{待复活.Name}");

            var 待驱散 = HealTargetHelper.需要驱散队友();
            if (待驱散 != null) sb.AppendLine($" 有队友需要驱散：{待驱散.Name}");

            sb.AppendLine();
        }
        catch (Exception e)
        {
            sb.AppendLine("（队伍读取失败：" + e.Message + "）");
        }
    }

