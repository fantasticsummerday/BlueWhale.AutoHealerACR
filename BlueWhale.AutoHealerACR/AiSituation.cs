            //  没有它，AI 只能看着"我有个 DoT 技能、CD 也好了"就建议补 ——
            //  而那正是"不断补 DoT"（每 4.9 秒一次）的来源。
            //
            //  现在它会看到「天辉 22s」这种事实，自然就知道不用补。
            //  （本地层也有 Dot补判 兜底，两道保险。）
            // ══════════════════════════════════════════════════════════
            var 目标状态 = CharacterExt.所有状态剩余(目标)
                .Where(x => x.剩余秒 >= 1f)
                .OrderBy(x => x.剩余秒)
                .Take(8)
                .Select(x => $"{x.名} {x.剩余秒:F0}s")
                .ToList();

            if (目标状态.Count > 0)
            {
                sb.AppendLine($"  我挂在它身上的状态：{string.Join("、", 目标状态)}");
                sb.AppendLine("    （DoT 类：剩余时间还多就别补，补了纯浪费一个 GCD）");
            }
            else
            {
                sb.AppendLine("  我挂在它身上的状态：无（DoT 还没上，或者已掉光）");
            }

            sb.AppendLine($"周围敌人数量（5 米内）：{HealTargetHelper.周围敌人数量()}");

            // ══════════════════════════════════════════════════════════
            //  ★ AOE 判断要用**本的职业真实值**，不能写死（审计发现）★
            //
            //  ── 原来写死"8 米内 ≥3 个"的两个方向的错 ──
            //    · 本地 `AOE最少敌人数` 是 **2**（四个职业都没覆写）——
            //      所以 2 只怪时**本地会放 AOE**，而这里告诉 AI"否"
            //      （那正是阈值从 3 降到 2 特意覆盖的日随场景）。
            //    · 半径默认 **5 米**，只有白魔是 8 米 ——
            //      学者/占星/贤者被按 8 米数人 → 数多了 → 告诉 AI"是"。
            //
            //  ⇒ 直接读表，口径和本地**完全一致**。
            //     提示词和实现不一致，AI 给的理由再对也没用（这次已经栽过一次）。
            // ══════════════════════════════════════════════════════════
            try
            {
                var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                if (表 != null && 表.群体输出 != 0 && SpellUtil.已解锁(表.群体输出))
                {
                    var 需要几个 = Math.Max(1, 表.AOE最少敌人数);
                    var 半径 = Math.Max(1, 表.AOE伤害范围);
                    var 够数 = HealTargetHelper.周围敌人数量(半径);

                    sb.AppendLine($"适合放 AOE：{(够数 >= 需要几个 ? "是" : "否")}" +
                                  $"（{半径} 米内 {够数} 个，需要 ≥{需要几个}）");
                }
                else
                {
                    sb.AppendLine("适合放 AOE：当前等级还没有群体输出技能");
                }
            }
            catch
            {
                sb.AppendLine("（AOE 判断读取失败）");
            }

            // ══════════════════════════════════════════════════════════
            //  ★ 非当前目标的敌人 ★
            //
            //    "非当前目标的敌人状态也得知道这样才能更好判断"
            //
            //  ── 补的是哪两个盲区 ──
            //
            //    ① **DoT 覆盖判断**
            //       原来只看到当前目标有没有 DoT，看不到全局。
            //       5 个怪里 3 个已经有我的 DoT，AI 也以为"只有当前这个有"。
            //       → 没法判断"再补 DoT 是不是全在重复"。
            //
            //    ② **AOE / 群奶时机**
            //       原来只知道"5 米内有几个"，不知道血量分布。
            //       一堆残血小怪即将清完时交群奶/爆发是浪费 ——
            //       本地有 `敌人波次要结束` 在管，但 AI 看不到依据。
            //
            //  ⚠️ 必须**排除当前目标**（它在上面已经单独详细列过了），
            //     否则同一个怪出现两遍，浪费长度预算还容易让 AI 混淆。
            // ══════════════════════════════════════════════════════════
            try
            {
                var 总数 = HealTargetHelper.附近敌人总数();

                // 用当前职业真正的 DoT buff 表去查（各职业不同，且**有多档**）
                uint[] DotBuffs = Array.Empty<uint>();
                var 有Dot技能 = false;
                try
                {
                    var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
                    if (表 != null && 表.Dot技能 != 0)
                    {
                        有Dot技能 = true;
                        DotBuffs = 表.所有DotBuff ?? Array.Empty<uint>();
                    }
                }
                catch { }

                var 其他 = HealTargetHelper.其他敌人(DotBuffs)
                    .Where(x => !x.是当前目标)
                    .ToList();

                if (其他.Count > 0)
                {
                    sb.AppendLine($"其他敌人（共 {总数} 个在附近，下面是除当前目标外最需要关注的）：");

                    foreach (var x in 其他)
                    {
                        var 标记 = new List<string>();
                        if (x.是Boss) 标记.Add("Boss");
                        if (有Dot技能)
                            标记.Add(x.有我的Dot ? "**已有我的DoT**" : "**没有我的DoT**");
                        if (x.血量比例 <= 0.25f) 标记.Add("残血");
                        if (x.距离 <= 8f) 标记.Add($"近({x.距离:F0}m)");

                        var 后缀 = 标记.Count > 0 ? "  [" + string.Join("/", 标记) + "]" : "";
                        sb.AppendLine($"  {x.名字}：{x.血量比例 * 100f:F0}%（{x.距离:F0}m）{后缀}");
                    }

                    // 汇总一句，方便 AI 一眼看出该不该补 DoT
                    if (有Dot技能 && DotBuffs.Length > 0)
                    {
                        bool 当前也有 = false;
                        try
                        {
                            foreach (var b in DotBuffs)
                                if (b != 0 && 目标.HasAura(b)) { 当前也有 = true; break; }
                        }
                        catch { }

                        var 覆盖数 = 其他.Count(x => x.有我的Dot) + (当前也有 ? 1 : 0);

                        sb.AppendLine($"  → 附近 {总数} 个敌人里，**{覆盖数} 个身上有我的 DoT** " +
                                      "（判断\"要不要补 DoT\"看这个，别只看当前目标）");

                        // ★ 明确列出"被拉到了、但没我的 DoT"的 ★
                        //
                        //   ⚠️ 加这一行的原因：
                        //      "在小怪阶段没有别的技能可打的情况下
                        //       没有给 T 拉到仇恨的其他小怪上 dot"
                        //
                        //   原来只有一句覆盖率汇总，AI 得自己从列表里反推
                        //   "哪个还没上"。明确列出来，它才知道**可以切过去补**。
                        //
                        //   ⚠️ 这里列的一定是**有仇恨的**（`其他敌人()` 已过滤）——
                        //      所以"切过去补 DoT"不会 ADD。
                        var 该补 = 其他.Where(x => !x.有我的Dot).ToList();
                        if (该补.Count > 0)
                        {
                            var 名单 = string.Join("、", 该补.Take(4).Select(x => x.名字));
                            sb.AppendLine($"  → **被拉到但没我 DoT 的：{名单}**" +
                                          "（没别的技能可打时可以切过去补 DoT，" +
                                          "这些都是**已经有仇恨**的，不会 ADD）");
                        }
                    }

                    var 残血数 = 其他.Count(x => x.血量比例 <= 0.25f);
                    if (残血数 >= 2)
                    {
                        sb.AppendLine($"  → 有 {残血数} 个残血小怪，**这一波快清完了** —— " +
                                      "别再交群奶/爆发，省下来给下一波");
                    }
                }
                else if (总数 > 1)
                {
                    sb.AppendLine($"其他敌人：附近共 {总数} 个，但没有需要额外关注的");
                }
            }
            catch { }

            sb.AppendLine();
        }
        catch (Exception e)
        {
            sb.AppendLine("（敌人读取失败：" + e.Message + "）");
        }
    }

    // ==================== 时间轴 ====================

    private static void 采时间轴(StringBuilder sb)
    {
        try
        {
            sb.AppendLine("【副本与机制时间轴】");

            if (!HealSettings.Instance.启用时间轴)
            {
                sb.AppendLine("（时间轴功能未启用 —— 下面没有机制预告，请只按眼前数据判断）");
                sb.AppendLine();
                return;
            }

            if (!TimelineManager.时间轴在跑())
            {
                // ⚠️ 明确说"没有时间轴"，而不是留空 ——
                //    留空的话 AI 会以为"没机制"，而实际是"我们不知道"。
                //    这两种情况该给的建议完全不同。
                sb.AppendLine("（这个副本**没有匹配到时间轴** —— 后续机制未知。「机制预告」为空");
                sb.AppendLine("  不代表没有机制，只代表我们查不到。请保守一点，别假设安全。）");
                sb.AppendLine();
                return;
            }

            sb.AppendLine($"共记录 {TimelineManager.机制总数()} 条机制");

            // ── 正在发生的机制 ──
            //
            //   语义："出现机制时…也要告诉 ai"
            //
            //   为什么要单列"正在发生"：
            //     刚结算的那一下往往就是掉血的原因。AI 看到"现在正在放 XXX"
            //     就能把"为什么突然掉了 40% 血"和具体机制对上，
            //     而不是笼统地说"有人掉血了要群奶"。
            var 当前 = TimelineManager.当前机制();
            if (当前.Count > 0)
            {
                var 描述 = string.Join("、", 当前.Select(x => x.名称 + (x.需减伤 ? "（大伤害）" : "")));
                sb.AppendLine($"⚠️ 正在发生：{描述}");
            }

            // ── 后续机制预告 ──
            //
            //   语义："时间轴内告知后续有机制时也要告诉 ai"
            //
            //   窗口取 20 秒 —— 依据：
            //     · 一次 GCD 2.5 秒 → 20 秒约 8 个 GCD，是能提前安排的尺度
            //     · 大技能 CD（神速 120s / 以太超流 60s）里最短的也有 30 秒以上，
            //       再往远看对"这一轮怎么打"没有指导意义
            var 预告 = TimelineManager.未来机制(20.0);
            if (预告.Count > 0)
            {
                sb.AppendLine("后续机制（还有几秒 → 名字）：");
                foreach (var (还有几秒, 名称, 需减伤) in 预告)
                {
                    var 时点 = 还有几秒 <= 0.6 ? "刚刚" : $"{还有几秒:F1}s 后";
                    var 标注 = 需减伤 ? "  ← 大伤害，考虑预铺" : "";
                    sb.AppendLine($"  {时点,-10} {名称}{标注}");
                }
            }
            else
            {
                sb.AppendLine("后续 20 秒内没有记录到的机制。");
            }

            // ── 再远一点的下一步（给"要不要现在花资源"用）──
            var 下一条 = TimelineManager.下一条机制();
            if (下一条 != null && 下一条.Value.还有几秒 > 20.0)
            {
                sb.AppendLine($"再往后：{下一条.Value.还有几秒:F0}s 后 —— {下一条.Value.名称}" +
                              (下一条.Value.需减伤 ? "（大伤害）" : ""));
            }

            sb.AppendLine();
        }
        catch (Exception e)
        {
            sb.AppendLine("（时间轴读取失败：" + e.Message + "）");
            sb.AppendLine();
        }
    }

    // ==================== 可选技能清单 ====================

    /// <summary>
    /// 采集**当前职业实际会用的技能清单**（ID + 中文名 + 用途分类）。
    ///
    /// **这是防幻觉的最后一道闸。**
    /// 阶段 B 让 AI 输出技能 ID —— 不给清单它就凭记忆编，
    /// 编错的后果是一次无效施放，甚至放出不该放的技能。
    ///
    /// 有了清单，提示词里就能写"只能从这里选"，
    /// 而且返回后还能做白名单校验（见 AiDecisionLayer.解析）。
    /// </summary>
    private static void 采可选技能(StringBuilder sb)
    {
        try
        {
            sb.AppendLine("【可选技能（阶段 B 只能从这些 ID 里选）】");

            // ⚠️ 必须取"当前实际职业"的表，不能用静态的 当前技能表 ——
        //    那个会被最后加载的职业覆盖（现象：玩学者却收到幻术师的技能清单）
        var 表 = HealerACR.Common.HealRotationEventHandler.取当前职业技能表();
            if (表 == null)
            {
                sb.AppendLine("（拿不到技能表 —— 阶段 B 请输出 0|数据不足）");
                sb.AppendLine();
                return;
            }

            var 计数 = 0;

            // ══════════════════════════════════════════════════════════
            //  ★★ 按等级过滤 —— 治"建议了 852 次不能用技能" ★★
            //
            //  ── 现象 ──
            //    "刚刚法令有问题的本是 50 本，ai 是不是没有知道等级和副本名字呢"
            //
            //    日志实证：`建议 3571 未解锁，放弃（改用原逻辑）` **852 条**。
            //    法令是**白魔 56 级**技能，而他在 **50 级本**（等级同步到 50）。
            //
            //  ── 为什么会这样 ──
            //    技能表里配的是"**满级那一个**"（`取已解锁` 链的终点），
            //    而**清单从来不按等级过滤** ——
            //    于是 50 级时清单里照样写着"3571 = 法令"，
            //    AI 看到就建议，终审又用 `IsUnlock()` 档回来。
            //    **一轮 AI 请求白花，还刷 852 条日志。**
            //
            //  ── 为什么用 `SpellUtil.已解锁()` 过滤 ──
            //    它就是终审用的那个判断 —— **清单口径和终审口径必须一致**，
            //    否则一定会出现"清单里有、终审拒掉"的错配。
            //    （我之前加过"技能表里有就放行"的兜底，那个是错的方向，已删。）
            //
            //  ⚠️ 过滤只影响**告诉 AI 什么**，不影响 AI 可以建议什么 ——
            //     终审仍然独立校验一次。
            // ══════════════════════════════════════════════════════════
            var 被等级挡掉 = new List<string>();

            void 加(string 类别, uint id)
            {
                if (id == 0) return;

                // ★ 等级/职业任务没到 → 不列进清单
                if (!SpellUtil.已解锁(id))
                {
                    被等级挡掉.Add($"{id}={SpellIds.反查(id)}");
                    return;
                }

                var 名 = SpellIds.反查(id);
                var 附加 = new StringBuilder();

                // ══════════════════════════════════════════════════════
                //  ★ 每个技能都带上**当前运行时状态** ★
                //
                //  只给"ID = 名字（类别）"是不够的 —— AI 不知道
                //  这个技能现在**转好没有**，于是会建议一个 CD 中的技能，
                //  然后在终审被"技能不可用"挡掉（白问一轮，命中率被拉低）。
                //
                // 加上：剩余 CD / 充能层数 / 施法时间 / 蓝耗 / 射程。
                // 这些都是**游戏里读出来的实时值**，不是让 AI 去背知识。
                //
                // ⚠️ 读不到的项**不写**（不要写 "CD=?"）——
                //     宁可少一项，也不要给 AI 一个它只能瞎猜的占位符。
                // ══════════════════════════════════════════════════════════

                // 充能技：显示"还剩几层/上限"（比 CD 更直观）
                //
                // ⚠️ 压缩：`充能2/3` → `2/3`。
                //    只有充能技才有 `x/y` 这个形状，不会和别的字段混淆，
                //    所以"充能"两个字是纯冗余（25 个技能能省 75 字符）。
                var 上限 = CharacterExt.最大充能数(id);
                if (上限 > 1)
                {
                    var 当前 = CharacterExt.充能数(id);
                    if (当前 >= 0) 附加.Append($" {当前}/{上限}");
                }
                else
                {
                    // ⚠️ 压缩：**就绪时不写任何字**。
                    //    `CD` 前缀已经表示"这是冷却时间"——
                    //    没有 `CD` 前缀就说明可用，不需要再写"就绪"。
                    //    反过来说，写"就绪"是在用 2 个字符表达"没信息"。
                    var cd = CharacterExt.冷却剩余秒(id);
                    if (cd > 0.05f) 附加.Append($" CD{cd:F1}");
                }

                // ★ 明确标出「瞬发」★ —— 这是移动中唯一能用的那一类。
                //   （原来瞬发的什么都不写，AI 分不清"瞬发"和"读不到施法时间"。）
                var 施法 = CharacterExt.施法时间秒(id);
                if (施法 > 0.05f) 附加.Append($" 读条{施法:F1}");
                else if (施法 >= 0f) 附加.Append(" 瞬发");

                // 蓝耗只在 >0 时给；射程只在**明显偏短**（≤15m）时给
                //   —— 25/30 米是常态没有信息量，够不着才值得提醒
                var 蓝 = CharacterExt.蓝耗(id);
                if (蓝 > 0) 附加.Append($" 蓝{蓝}");

                var 距离 = CharacterExt.射程(id);
                if (距离 > 0.5f && 距离 <= 15f) 附加.Append($" 射程{距离:F0}m");

                sb.AppendLine($"  {id} = {名}（{类别}）{附加}");
                计数++;
            }

            void 加数组(string 类别, uint[] ids)
            {
                if (ids == null) return;
                foreach (var id in ids) 加(类别, id);
            }

            加("基础输出", 表.基础输出);
            加("群体输出", 表.群体输出);
            加("DoT", 表.Dot技能);
            加("移动填充", 表.移动填充技);
            加("单体治疗", 表.单体治疗GCD);
            加("群体治疗", 表.群体治疗GCD);
            加("紧急单奶", 表.紧急单奶);
            加("群体治疗能力技", 表.群体治疗能力技);
            // ★ 三个“瞬发”栏位 —— 移动中唯一能用的治疗 ★
            //   ⚠️ 它们原来**没列进清单**（我加栏位时漏了同步）——
            //      于是 AI 移动中一直说“无瞬发技能可用，等站定”，
            //      而再生就是瞬发的。这正是问题所在。
            加("单体HoT", 表.单体HoT);
            加("预铺单奶", 表.预铺单奶能力技);
            加("瞬发单奶", 表.瞬发单奶能力技);
            加("单体盾", 表.单体盾);
            加("群体盾", 表.群体盾);
            加("团队减伤", 表.团队减伤);

            // ★ 个人减伤（神祝祷 7432 / 擢升 25873）★
            //   ⚠️ 这个栏位原来**没列**，但它**是真的会被放出去**的技能 ——
            //      `Res_SelfMitigation` 在**五个职业的队列里都注册了**。
            //      AI 看不到它就等于少了一类可用的自保手段。
            //
            //   ⚠️ 不列 `护盾前置`（贤者均衡 24290）：它是**形态切换**，
            //      本身不是"用出去的治疗/减伤"，列了会误导 ——
            //      本仓库 `SGE_Dot` 的注释专门写过"同一帧里按完均衡
            //      就立刻放均衡注药是放不出来的"。
            //
            //   ⚠️ 不列 `DotBuff`：那是 **buff id**，不是技能 id。
            加("个人减伤", 表.个人减伤);

            // ★ 药尾声补刀技（爆发药快过期时用即刻打的瞬发填充）★
            //   和 `基础输出` 通常是同一个技能，但**时机完全不同** ——
            //   列出来 AI 才知道"药快没了可以交即刻补一发"。
            加("药尾声填充", 表.药尾声填充技);
            加("复活", 表.复活);
            加("驱散", 表.驱散);
            加("醒梦", 表.醒梦);

            加数组("输出能力技", 表.输出能力技);
            加数组("脱战准备", 表.脱战准备技能);

            sb.AppendLine($"（共 {计数} 个）");

            // ★ 明确告诉 AI "哪些技能因为等级没到被滤掉了" ★
            //
            //  为什么要说：不然 AI 可能会去建议一个它"记得这个职业有"的技能
            //  （比如白魔的法令），然后被终审拒掉、白问一轮。
            //  说清楚"现在几级、哪些还没有"，它就不会往那边想。
            //
            //  ⚠️ 只报**数量 + 前 3 个名字**，不列全 ——
            //     提示词预算实测已经到 90%，这里多列一个就多占一份。
            //     目的只是让 AI 知道"有东西被滤掉了、别建议它们"，
            //     不需要它知道每一个是什么。
            if (被等级挡掉.Count > 0)
            {
                var 显示 = string.Join("、", 被等级挡掉.Take(3));
                var 更多 = 被等级挡掉.Count > 3 ? " 等" : "";
                sb.AppendLine($"（另有 {被等级挡掉.Count} 个技能因**等级/职业任务没到**未列出：" +
                              $"{显示}{更多} —— **不要建议它们**）");
            }

            sb.AppendLine();

            // ── 静态参考：每个类别"是什么用的" ──
            //   ⚠️ 这块是**静态**的（每轮都一样），所以它是超长时
            //      第一个该被砍掉的部分 —— 见 采集() 里的截断逻辑。
            采技能效果说明(sb);
        }
        catch (Exception e)
        {
            sb.AppendLine("（技能清单读取失败：" + e.Message + "）");
            sb.AppendLine();
        }
    }

    /// <summary>
    /// **技能效果说明** —— 静态参考，每轮都给。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么给这个（"告知 ai 所有技能和效果"）★
    ///
    ///    上面那张表只说"ID = 名字（类别）"，类别名是我们自己起的简写
    ///    （"紧急单奶"/"群体盾"…）。AI 未必能从这个词推断出
    ///    "什么时候该用、用了会怎样"，于是容易给出语境不对的建议
    ///    （实测例子：它建议在这时候补 DoT，而正确做法是留 GCD 给治疗）。
    ///
    ///    这里给每个**类别**一段固定说明，讲清楚：
    ///      · 这个类别的技能是干什么的
    ///      · 什么时机用它才对
    ///      · 用它有什么代价
    ///
    ///  ⚠️ **只讲类别，不讲具体副本机制** ——
    ///    这是防幻觉原则的边界：类别说明是"我们系统自己的定义"（可信），
    ///    而"某个副本该怎么打"是模型的知识盲区（不可信，必编）。
    ///    所以这里绝不出现任何副本名、Boss 名、机制名。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    /// <summary>
    /// 技能类别说明 —— **压缩版**。
    ///
    /// ══════════════════════════════════════════════════════════════════
    ///  ★ 为什么压缩（用户提出："提示词还能压缩吗 以免后续记忆增多超额"）★
    ///
    ///    这一段**每轮都发**，而它**每轮完全一样** —— 是纯静态参考。
    ///    原来的写法（一条一行、每条带完整解释）实测 **588 字符**，
    ///    占 6000 预算的近 10%。
    ///
    ///    而 `tools/PromptBudget.py` 量出来最坏情况已经到 **99%** ——
    ///    再增加任何动态内容都会触发截断。所以静态段是**首选压缩对象**：
    ///    压缩它的信息损失最小（AI 本来就知道"治疗是什么"）。
    ///
    ///  ── 压缩原则 ──
    ///    · **保留"反直觉"的部分** —— 那些 AI 自己猜不到、猜错会出事的
    ///      （DoT 看剩余时间不看 CD / 盾要提前铺 / 急救别随手交 /
    ///        移动填充是瞬发 / 群疗优先度）
    ///    · **删掉常识部分** —— "治疗是什么""复活是什么"不用教
    ///    · 一条一行，去掉对齐用的大量空格
    ///
    ///  ⚠️ 压缩时**不要动**那些"防幻觉"的约束（比如 DoT 的补判标准）——
    ///     它们是这段里唯一真正有价值的内容。
    /// ══════════════════════════════════════════════════════════════════
    /// </summary>
    private static void 采技能效果说明(StringBuilder sb)
    {
        // ⚠️ 只留"猜不到、猜错会出事"的；常识（治疗是什么、复活是什么）一律删。
        //    这一段**每轮一字不变**，是纯静态参考 —— 属于首选压缩对象。
        //    ⚠️ 但**别删 DoT 补判标准** —— 那是这段里唯一防幻觉的核心。
        sb.AppendLine("【技能类别说明】只列反直觉的点，其余按常识：");
        sb.AppendLine("  DoT：**不按 CD 补**，看目标身上 DoT 的剩余时间（见敌人段）。剩得多就别补。");
        sb.AppendLine("  盾/减伤：**伤害落地前**铺才有用；已落地再铺等于浪费。");
        sb.AppendLine("  紧急单奶：CD 很长，**别随手交**，留给救命时刻。");
        sb.AppendLine("  能力技（群体治疗/输出类）：不占 GCD，比 GCD 技能舍得用。");
        sb.AppendLine("  移动填充：走位时用来填 GCD 的瞬发技能。");
        sb.AppendLine("  醒梦：蓝低回蓝。驱散：解队友有害状态。复活：优先度很高。");
        sb.AppendLine();
    }
