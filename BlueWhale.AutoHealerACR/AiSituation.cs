            //  ★ 目标站得稳不稳（让 AI 知道小怪是否稳定在固定位置）★
            //
            //  为什么要给这个：
            //    · **地面技能**（罩子 / 地星 / 庇护所）放下去敌人一走就废了 ——
            //      AI 建议这类技能前，得知道"扔这儿会不会白扔"
            //    · **AOE** 也一样：怪在跑动时，以它为中心的范围大概率打不满
            //
            //  ⚠️ 判据不是"现在没动"，而是**"已经稳定了足够久"** ——
            //     小怪刚出现时往往站着不动（待机 / 没被拉 / 在远处），
            //     那种"没动"是假象，马上就会冲进来。
            //     详情见 敌人移动检测.cs 的说明。
            // ══════════════════════════════════════════════════════════
